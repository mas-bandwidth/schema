// Package testreg is the test registry: the one data structure that names
// every test the repository runs, the languages that answer them and the
// adapters that run them (docs/TEST-REGISTRY.md).
//
// The registry is data, test/registry/registry.jsonl: one JSON object per
// line, each carrying "rec" (lang, tier, type, test, unrepresentable or group).
// There is no owed record: a test a language fails is an ordinary red row
// (Glenn, 2026-11-25: no skips and no exemption list of any kind). The
// per-language instances are never written down: they are every test times
// every language row, generated by Instances. The number of languages is
// never written anywhere either; it is len(Registry.Langs).
//
// Load refuses a registry that is not one, naming the file and the line:
// a malformed line, an unknown record kind or field, a duplicate language,
// tier, type or test key, a test whose type or tier is not declared, a key
// that is not type.family.case, and an unrepresentable declaration for a
// test or a language that does not exist.
package testreg

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"maps"
	"math"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

// DefaultPath is where the registry lives, from the repository root.
const DefaultPath = "test/registry/registry.jsonl"

// Lang is one supported language: its name (the --lang spelling), its write
// rule and the adapter that runs its instances ("" while none has landed).
type Lang struct {
	Name    string `json:"name"`
	Write   string `json:"write"`
	Adapter string `json:"adapter"`
	Line    int    `json:"-"`
}

// Ready reports whether the language has an adapter: a language without one
// still has every instance, and each is MISSING.
func (l Lang) Ready() bool { return l.Adapter != "" }

// Tier is unit, functional or nightly; Type is one kind of check. Both are
// declared in the registry so a test can only name one that exists.
type Tier struct {
	Name string `json:"name"`
	What string `json:"what"`
	Line int    `json:"-"`
}

// Type is one kind of check a test makes (roundtrip, load-refusal, ...).
// Contract is what an adapter must do to answer a test of the type; the spec
// addenda write it out, and refuse a type without one (addenda.go).
type Type struct {
	Name     string `json:"name"`
	What     string `json:"what"`
	Contract string `json:"contract"`
	Line     int    `json:"-"`
}

// Test is one language-free test. Its key is type.family.case; Inputs and
// Expect are what the adapter is handed and what it must establish.
type Test struct {
	Key    string          `json:"key"`
	Type   string          `json:"type"`
	Family string          `json:"family"`
	Case   string          `json:"case"`
	Tier   string          `json:"tier"`
	Checks string          `json:"checks"`
	Inputs json.RawMessage `json:"inputs"`
	Expect string          `json:"expect"`
	Source string          `json:"source"`
	// Scope is "" for a test every language answers (one instance per
	// language row), or "none" for a language-free test (one instance,
	// none.<tier>.<key>), which names the Adapter that runs it.
	Scope   string `json:"scope,omitempty"`
	Adapter string `json:"adapter,omitempty"`
	// Seconds is the test's measured run time on a fleet runner: what Shard
	// weighs it by, so each part of a stored query fits its job. A test with
	// none weighs DefaultSeconds.
	Seconds float64 `json:"seconds,omitempty"`
	// Intrinsic, on a per-language row, says its subject exists in one
	// language only (that language's own generated source or runtime): the
	// row has that language's instance and no other, and every other
	// language is unrepresentable with the reason. It is declared data, as
	// an unrepresentable line is, never a runtime result
	// (docs/TEST-REGISTRY.md, "Language-intrinsic tests").
	Intrinsic *Intrinsic `json:"intrinsic,omitempty"`
	// Needs are the machine properties the test needs from the bench that
	// runs it (casefold: a volume that folds names by case, which captain,
	// WSL2 with no ext4 casefold, cannot have). The fleet's benches declare
	// what they provide, and the full run (tools/fullrun) never sends a row
	// to a bench that lacks one; a need no bench of a run provides is red by
	// name there, never skipped. It is a fact of the test, like its tier.
	Needs []string `json:"needs,omitempty"`
	Line  int      `json:"-"`
}

// fillerWords say nothing about a test's subject. An intrinsic reason is
// boilerplate when it is under four words, or when fewer than three distinct
// words of it (hyphenated parts counted apart) are not filler:
// "language-specific", "it is language-specific code", "this is really just
// lua", "lua lua lua lua", "TODO fill this reason later" and "a unique
// Lua-only feature" are each refused, "a Lua string escape" is not. A count
// of words cannot judge a reason's truth: the cold reader of the split does.
var fillerWords = map[string]bool{}

func init() {
	for _, w := range strings.Fields(`a an the it its it's is are was be been this that these those
		just really only so very quite simply code test tests testing tested language languages
		specific intrinsic intrinsically other others another no not none nothing in on of to for
		and or but has have had exists exist existing counterpart counterparts behaviour behavior
		format here there one own thing things stuff something which with by as at from n/a na
		tbd todo fixme xxx placeholder reason reasons later fill filled write written writing
		unique uniquely feature features semantics detail details etc same different elsewhere
		nowhere else every any all applies apply does do lacks lack`) {
		fillerWords[w] = true
	}
}

func boilerplate(reason string) bool {
	if len(strings.Fields(reason)) < 4 {
		return true
	}
	content := map[string]bool{}
	for _, w := range strings.FieldsFunc(strings.ToLower(reason), func(r rune) bool {
		return r == '-' || r == '/' || unicode.IsSpace(r)
	}) {
		w = strings.Trim(w, ".,:;!?()[]\"'`")
		if w != "" && !fillerWords[w] {
			content[w] = true
		}
	}
	return len(content) < 3
}

// Intrinsic names the one language a test's subject exists in, and why no
// other language has it.
type Intrinsic struct {
	Lang   string `json:"lang"`
	Reason string `json:"reason"`
}

// LangFree is the scope, and the language part of the full name, of a test
// no language answers: a Go tooling test, a TLA model check, a roadmap check.
const LangFree = "none"

// LangPlaceholder stands for the language in a per-language row's inputs:
// one row serves every language, and its adapter puts the language in its
// place (tools/namebuild's TestNameBuildability_{lang}).
const LangPlaceholder = "{lang}"

// PerLang reports whether every language answers the test.
func (t Test) PerLang() bool { return t.Scope == "" }

// Unrep declares that a language cannot express a test, with the reason. It
// is a declared result, never an absence.
type Unrep struct {
	Test   string `json:"test"`
	Lang   string `json:"lang"`
	Reason string `json:"reason"`
	Line   int    `json:"-"`
}

// Group is a stored query: a name a workflow runs (--group), so which tests
// a job runs is data here, never a list in the workflow.
type Group struct {
	Name   string     `json:"name"`
	What   string     `json:"what"`
	Stored GroupQuery `json:"query"`
	Line   int        `json:"-"`
}

// GroupQuery is a Query as the registry spells it.
type GroupQuery struct {
	Names    []string `json:"names,omitempty"`
	Langs    []string `json:"langs,omitempty"`
	Tiers    []string `json:"tiers,omitempty"`
	Types    []string `json:"types,omitempty"`
	Families []string `json:"families,omitempty"`
	Ready    bool     `json:"ready,omitempty"`
}

// Query is the stored query.
func (g Group) Query() Query {
	return Query(g.Stored)
}

// Registry is the loaded file, in file order.
type Registry struct {
	Path   string
	Langs  []Lang
	Tiers  []Tier
	Types  []Type
	Tests  []Test
	Unreps []Unrep
	Groups []Group

	lang  map[string]int
	test  map[string]int
	unrep map[[2]string]int
}

// WriteRules are the two write rules a language may have (SPEC.md §5.1):
// "assert" (debug-build asserts only) and "refuse" (refused in every build).
var WriteRules = []string{"assert", "refuse"}

var (
	nameRE = regexp.MustCompile(`^[a-z][a-z0-9]*(-[a-z0-9]+)*$`)
	caseRE = regexp.MustCompile(`^[a-z0-9]+(-[a-z0-9]+)*$`)
	// needRE is a machine property a test needs (Test.Needs).
	needRE = nameRE
)

// Load reads and validates the registry at path.
func Load(path string) (*Registry, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("test registry: %w", err)
	}
	return Parse(path, bytes.NewReader(data))
}

// Parse reads and validates a registry; name is the file every refusal names.
func Parse(name string, r io.Reader) (*Registry, error) {
	reg := &Registry{Path: name, lang: map[string]int{}, test: map[string]int{}, unrep: map[[2]string]int{}}
	tiers := map[string]int{}
	types := map[string]int{}
	var pending []Test
	var pendingGroups []Group
	var errs []string
	fail := func(line int, format string, args ...any) {
		errs = append(errs, fmt.Sprintf("%s:%d: %s", name, line, fmt.Sprintf(format, args...)))
	}
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 0, 64*1024), 16*1024*1024)
	n := 0
	for sc.Scan() {
		n++
		text := strings.TrimSpace(sc.Text())
		if text == "" {
			continue
		}
		var head struct {
			Rec string `json:"rec"`
		}
		if err := json.Unmarshal([]byte(text), &head); err != nil {
			fail(n, "not a JSON object: %v", err)
			continue
		}
		dec := func(v any) bool {
			d := json.NewDecoder(bytes.NewReader([]byte(text)))
			d.DisallowUnknownFields()
			if err := d.Decode(v); err != nil {
				fail(n, "%s record: %v", head.Rec, err)
				return false
			}
			return true
		}
		switch head.Rec {
		case "lang":
			var v struct {
				Rec string `json:"rec"`
				Lang
			}
			if !dec(&v) {
				continue
			}
			l := v.Lang
			l.Line = n
			switch {
			case !nameRE.MatchString(l.Name):
				fail(n, "language name %q is not a lowercase name", l.Name)
			case l.Name == LangFree:
				fail(n, "%q is the scope of language-free tests, not a language", LangFree)
			case !contains(WriteRules, l.Write):
				fail(n, "language %s: write rule %q is not one of %s", l.Name, l.Write, strings.Join(WriteRules, ", "))
			case reg.lang[l.Name] != 0:
				fail(n, "language %s is already declared on line %d", l.Name, reg.Langs[reg.lang[l.Name]-1].Line)
			default:
				reg.Langs = append(reg.Langs, l)
				reg.lang[l.Name] = len(reg.Langs)
			}
		case "tier", "type":
			var v struct {
				Rec      string `json:"rec"`
				Name     string `json:"name"`
				What     string `json:"what"`
				Contract string `json:"contract"`
			}
			if !dec(&v) {
				continue
			}
			seen := tiers
			if head.Rec == "type" {
				seen = types
			}
			switch {
			case head.Rec == "tier" && v.Contract != "":
				fail(n, "tier %s: a tier has no \"contract\"; a type does", v.Name)
			case !nameRE.MatchString(v.Name):
				fail(n, "%s name %q is not a lowercase name", head.Rec, v.Name)
			case strings.TrimSpace(v.What) == "":
				fail(n, "%s %s says nothing in \"what\"", head.Rec, v.Name)
			case seen[v.Name] != 0:
				fail(n, "%s %s is already declared on line %d", head.Rec, v.Name, seen[v.Name])
			case head.Rec == "tier":
				seen[v.Name] = n
				reg.Tiers = append(reg.Tiers, Tier{v.Name, v.What, n})
			default:
				seen[v.Name] = n
				reg.Types = append(reg.Types, Type{v.Name, v.What, v.Contract, n})
			}
		case "test":
			var v struct {
				Rec string `json:"rec"`
				Test
			}
			if !dec(&v) {
				continue
			}
			t := v.Test
			t.Line = n
			pending = append(pending, t)
		case "group":
			var v struct {
				Rec string `json:"rec"`
				Group
			}
			if !dec(&v) {
				continue
			}
			g := v.Group
			g.Line = n
			pendingGroups = append(pendingGroups, g)
		case "unrepresentable":
			var v struct {
				Rec string `json:"rec"`
				Unrep
			}
			if !dec(&v) {
				continue
			}
			u := v.Unrep
			u.Line = n
			reg.Unreps = append(reg.Unreps, u)
		case "owed":
			fail(n, "an owed record is an exemption list, and there is none (Glenn, 2026-11-25: no skips and no exemptions): a test a language fails is an ordinary red row; delete the line")
		default:
			fail(n, "record kind %q is not one of lang, tier, type, test, unrepresentable, group", head.Rec)
		}
	}
	if err := sc.Err(); err != nil {
		errs = append(errs, fmt.Sprintf("%s:%d: %v", name, n+1, err))
	}
	// Tests and unrepresentable declarations are checked once every tier,
	// type, test and language is known, so the order of the file's lines
	// does not matter.
	for _, t := range pending {
		if msg := checkTest(t, tiers, types); msg != "" {
			fail(t.Line, "test %s: %s", t.Key, msg)
			continue
		}
		if prev := reg.test[t.Key]; prev != 0 {
			fail(t.Line, "test %s is already declared on line %d", t.Key, reg.Tests[prev-1].Line)
			continue
		}
		reg.Tests = append(reg.Tests, t)
		reg.test[t.Key] = len(reg.Tests)
	}
	// a union row's Go tests: a per-language row, naming only languages the
	// registry lists, and no Go test twice
	unionTest := map[string]string{}
	for _, t := range reg.Tests {
		tests, ok, err := GoTestsOf(t)
		switch {
		case !ok:
			continue
		case err != nil:
			fail(t.Line, "%v", err)
			continue
		case !t.PerLang():
			fail(t.Line, "test %s names per-language Go tests but is scoped %q", t.Key, t.Scope)
			continue
		case t.Seconds != 0:
			// each language's test takes its own time: one number for the
			// row would weigh every language by the slowest
			fail(t.Line, "test %s is a union row with seconds %v: a union row's seconds are each language's, in inputs.tests.<lang>.seconds", t.Key, t.Seconds)
		}
		// a language's own tier moves one test that measured past a shard's
		// budget on its own to the night, with the seconds that put it
		// there; it is never a way for a test that fits to leave the pull
		// request, nor for a shard of several to get under the budget
		for _, lang := range slices.Sorted(maps.Keys(tests)) {
			g := tests[lang]
			switch {
			case g.Tier == "":
			case g.Tier != NightlyTier || t.Tier == NightlyTier:
				fail(t.Line, "test %s gives %s the tier %q: a language's own tier is %s, for a row of a per-PR tier", t.Key, lang, g.Tier, NightlyTier)
			case tiers[NightlyTier] == 0:
				fail(t.Line, "test %s gives %s the tier %q, which the registry does not declare", t.Key, lang, g.Tier)
			case g.Seconds <= ShardBudget:
				fail(t.Line, "test %s moves %s to %s at %v s measured: only a test past one shard's %.0f s budget on its own goes to the night; one that fits stays per pull request", t.Key, lang, NightlyTier, g.Seconds, ShardBudget)
			}
		}
		for _, lang := range slices.Sorted(maps.Keys(tests)) {
			g := tests[lang]
			if reg.lang[lang] == 0 || lang == LangFree {
				fail(t.Line, "test %s names a Go test for %q, which is not a language of the registry", t.Key, lang)
				continue
			}
			id := g.Package + " " + g.Test
			if prev, dup := unionTest[id]; dup {
				fail(t.Line, "test %s names %s %s, which %s already names", t.Key, g.Package, g.Test, prev)
				continue
			}
			unionTest[id] = t.Key
		}
	}
	intrinsicCase := map[string]Test{}
	for _, t := range reg.Tests {
		if t.Intrinsic == nil {
			continue
		}
		if reg.lang[t.Intrinsic.Lang] == 0 || t.Intrinsic.Lang == LangFree {
			fail(t.Line, "test %s is intrinsic to %q, which is not a language of the registry", t.Key, t.Intrinsic.Lang)
		}
		// an intrinsic family is one language's, and an intrinsic case has
		// no counterpart: a case split into one intrinsic row per language
		// that answers it is a union case with its reds dropped
		if !strings.HasPrefix(t.Family, t.Intrinsic.Lang+"-") {
			fail(t.Line, "test %s is intrinsic to %s, so its family is named %s-<subject>, not %q", t.Key, t.Intrinsic.Lang, t.Intrinsic.Lang, t.Family)
		}
		if prev, dup := intrinsicCase[t.Case]; dup && prev.Intrinsic.Lang != t.Intrinsic.Lang {
			fail(t.Line, "test %s is intrinsic to %s, but %s, the same case, is intrinsic to %s: a case two languages answer is one union row", t.Key, t.Intrinsic.Lang, prev.Key, prev.Intrinsic.Lang)
		} else if !dup {
			intrinsicCase[t.Case] = t
		}
		// intrinsic is a union row of one language's own Go test, never a
		// way for another kind of row to drop languages
		tests, ok, err := GoTestsOf(t)
		if !ok {
			fail(t.Line, "test %s is intrinsic to %s but is not a union row: only a row naming that language's own Go test (inputs.tests) can be intrinsic", t.Key, t.Intrinsic.Lang)
			continue
		}
		if err != nil {
			continue // refused above
		}
		if _, named := tests[t.Intrinsic.Lang]; !named {
			fail(t.Line, "test %s is intrinsic to %s but names no Go test for %s", t.Key, t.Intrinsic.Lang, t.Intrinsic.Lang)
		}
		for lang := range tests {
			if lang != t.Intrinsic.Lang {
				fail(t.Line, "test %s is intrinsic to %s but names a Go test for %s", t.Key, t.Intrinsic.Lang, lang)
			}
		}
	}
	for _, u := range reg.Unreps {
		k := [2]string{u.Test, u.Lang}
		if i := reg.test[u.Test]; i != 0 && reg.Tests[i-1].Intrinsic != nil {
			fail(u.Line, "unrepresentable %s for %s: the test is intrinsic to %s, which already declares every other language", u.Test, u.Lang, reg.Tests[i-1].Intrinsic.Lang)
			continue
		}
		if i := reg.test[u.Test]; i != 0 {
			if _, union, _ := GoTestsOf(reg.Tests[i-1]); union {
				fail(u.Line, "unrepresentable %s for %s: the test is a union row, where a language with no Go test for the case is red, never left out", u.Test, u.Lang)
				continue
			}
		}
		switch {
		case reg.test[u.Test] == 0:
			fail(u.Line, "unrepresentable: test %q does not exist", u.Test)
		case reg.lang[u.Lang] == 0:
			fail(u.Line, "unrepresentable: language %q does not exist", u.Lang)
		case strings.TrimSpace(u.Reason) == "":
			fail(u.Line, "unrepresentable %s for %s gives no reason", u.Test, u.Lang)
		case reg.unrep[k] != 0:
			fail(u.Line, "unrepresentable %s for %s is already declared on line %d", u.Test, u.Lang, reg.unrep[k])
		default:
			reg.unrep[k] = u.Line
		}
	}
	groups := map[string]int{}
	for _, g := range pendingGroups {
		if !nameRE.MatchString(g.Name) {
			fail(g.Line, "group name %q is not a lowercase name", g.Name)
			continue
		}
		if prev := groups[g.Name]; prev != 0 {
			fail(g.Line, "group %s is already declared on line %d", g.Name, prev)
			continue
		}
		if strings.TrimSpace(g.What) == "" {
			fail(g.Line, "group %s says nothing in \"what\"", g.Name)
			continue
		}
		groups[g.Name] = g.Line
		reg.Groups = append(reg.Groups, g)
	}
	if len(errs) == 0 {
		// a stored query that names what the registry does not have, or
		// matches nothing, is refused where it is written
		for _, g := range reg.Groups {
			if _, err := reg.Select(g.Query()); err != nil {
				fail(g.Line, "group %s: %v", g.Name, err)
			}
		}
	}
	if len(errs) == 0 {
		for _, c := range []struct {
			what  string
			empty bool
		}{{"language", len(reg.Langs) == 0}, {"tier", len(reg.Tiers) == 0}, {"type", len(reg.Types) == 0}, {"test", len(reg.Tests) == 0}} {
			if c.empty {
				errs = append(errs, fmt.Sprintf("%s: declares no %s", name, c.what))
			}
		}
	}
	if len(errs) > 0 {
		return nil, fmt.Errorf("test registry refused:\n  %s", strings.Join(errs, "\n  "))
	}
	return reg, nil
}

func checkTest(t Test, tiers, types map[string]int) string {
	switch {
	case !nameRE.MatchString(t.Type) || !nameRE.MatchString(t.Family) || !caseRE.MatchString(t.Case):
		return fmt.Sprintf("type %q, family %q and case %q must be lowercase names", t.Type, t.Family, t.Case)
	case t.Key != t.Type+"."+t.Family+"."+t.Case:
		return fmt.Sprintf("key is not type.family.case (%s.%s.%s)", t.Type, t.Family, t.Case)
	case types[t.Type] == 0:
		return fmt.Sprintf("type %q is not declared", t.Type)
	case tiers[t.Tier] == 0:
		return fmt.Sprintf("tier %q is not declared", t.Tier)
	case strings.TrimSpace(t.Checks) == "":
		return "says nothing in \"checks\""
	case strings.TrimSpace(t.Expect) == "":
		return "has no \"expect\""
	case len(t.Inputs) == 0 || string(t.Inputs) == "null":
		return "has no \"inputs\""
	case t.Scope != "" && t.Scope != LangFree:
		return fmt.Sprintf("scope %q is not \"\" (every language) or %q", t.Scope, LangFree)
	case t.Scope == LangFree && t.Adapter == "":
		return "is language-free and names no adapter"
	case t.Scope == "" && t.Adapter != "":
		return "names an adapter, but a per-language test runs through each language's adapter"
	case t.Intrinsic != nil && t.Scope != "":
		return "is intrinsic to one language, so it is a per-language row, not scoped " + strconv.Quote(t.Scope)
	case t.Intrinsic != nil && strings.TrimSpace(t.Intrinsic.Reason) == "":
		return "is intrinsic to " + t.Intrinsic.Lang + " but gives no reason"
	case t.Intrinsic != nil && boilerplate(t.Intrinsic.Reason):
		return fmt.Sprintf("is intrinsic to %s with the boilerplate reason %q: say what the subject is and why no other language has it", t.Intrinsic.Lang, t.Intrinsic.Reason)
	case t.Seconds < 0:
		return fmt.Sprintf("seconds %v is negative: it is a measured run time", t.Seconds)
	}
	for i, n := range t.Needs {
		if !needRE.MatchString(n) || slices.Contains(t.Needs[:i], n) {
			return fmt.Sprintf("needs %q: each need is a lowercase machine property, named once", t.Needs)
		}
	}
	return ""
}

func contains(list []string, s string) bool {
	return slices.Contains(list, s)
}

// Lang returns the language row with the name, if there is one.
func (r *Registry) Lang(name string) (Lang, bool) {
	i := r.lang[name]
	if i == 0 {
		return Lang{}, false
	}
	return r.Langs[i-1], true
}

// Test returns the test with the key, if there is one.
func (r *Registry) Test(key string) (Test, bool) {
	i := r.test[key]
	if i == 0 {
		return Test{}, false
	}
	return r.Tests[i-1], true
}

// Declared is every unrepresentable pair: the unrepresentable lines, and
// for each intrinsic test every language but its own, with the reason.
func (r *Registry) Declared() []Unrep {
	out := slices.Clone(r.Unreps)
	for _, t := range r.Tests {
		if t.Intrinsic == nil {
			continue
		}
		for _, l := range r.Langs {
			if l.Name != t.Intrinsic.Lang {
				reason, _ := r.Unrepresentable(t.Key, l.Name)
				out = append(out, Unrep{Test: t.Key, Lang: l.Name, Reason: reason, Line: t.Line})
			}
		}
	}
	return out
}

// Unrepresentable returns the declared reason a language cannot express a
// test, if it declared one.
func (r *Registry) Unrepresentable(key, lang string) (string, bool) {
	if i := r.test[key]; i != 0 {
		if in := r.Tests[i-1].Intrinsic; in != nil && in.Lang != lang {
			return "intrinsic to " + in.Lang + ": " + in.Reason, true
		}
	}
	line := r.unrep[[2]string{key, lang}]
	if line == 0 {
		return "", false
	}
	for _, u := range r.Unreps {
		if u.Line == line {
			return u.Reason, true
		}
	}
	return "", false
}

// LangNames is the language list, in registry order.
func (r *Registry) LangNames() []string {
	out := make([]string, len(r.Langs))
	for i, l := range r.Langs {
		out[i] = l.Name
	}
	return out
}

// Group returns the stored query with the name, if there is one.
func (r *Registry) Group(name string) (Group, bool) {
	for _, g := range r.Groups {
		if g.Name == name {
			return g, true
		}
	}
	return Group{}, false
}

// HasTier and HasType report whether a tier or type is declared.
func (r *Registry) HasTier(name string) bool {
	for _, t := range r.Tiers {
		if t.Name == name {
			return true
		}
	}
	return false
}

// HasType reports whether a type is declared.
func (r *Registry) HasType(name string) bool {
	for _, t := range r.Types {
		if t.Name == name {
			return true
		}
	}
	return false
}

// secondsField is a test line's measured seconds, as WriteSeconds writes it.
// It is the line's last field, so a "seconds" key inside a row's inputs is
// never taken for it.
var secondsField = regexp.MustCompile(`,"seconds":[0-9.e+-]+\}$`)

// WriteSeconds records measured run times in the registry file at path: for
// each test key in seconds, its line's "seconds" is set to the value,
// rounded up to the hundredth; for each union row's key in langSeconds, each
// named language's Go test gets its own "seconds" in the row's inputs.tests,
// the same way. Every other byte of the file is kept. A key that is no test
// line of the file, a union row in seconds, or a language langSeconds gives
// that its union row names no Go test for is an error, and nothing is
// written.
func WriteSeconds(path string, seconds map[string]float64, langSeconds map[string]map[string]float64) (int, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return 0, err
	}
	lines := strings.SplitAfter(string(data), "\n")
	done := map[string]bool{}
	for i, line := range lines {
		var head struct {
			Rec, Key string
			Inputs   json.RawMessage
		}
		if json.Unmarshal([]byte(line), &head) != nil || head.Rec != "test" {
			continue
		}
		tests, union, _ := GoTestsOf(Test{Key: head.Key, Inputs: head.Inputs})
		if ls, ok := langSeconds[head.Key]; ok {
			if !union || tests == nil {
				return 0, fmt.Errorf("%s:%d: %s is not a union row: its seconds are the row's", path, i+1, head.Key)
			}
			for _, lang := range slices.Sorted(maps.Keys(ls)) {
				g, named := tests[lang]
				if !named {
					return 0, fmt.Errorf("%s:%d: %s names no Go test for %s, so %s has no seconds of it", path, i+1, head.Key, lang, lang)
				}
				g.Seconds = roundSeconds(ls[lang])
				tests[lang] = g
			}
			in, err := json.Marshal(struct {
				Tests map[string]GoTest `json:"tests"`
			}{tests})
			if err != nil {
				return 0, err
			}
			raw := `"inputs":` + string(head.Inputs)
			if strings.Count(line, raw) != 1 {
				return 0, fmt.Errorf("%s:%d: %s: the inputs are not written once, compact, as %s", path, i+1, head.Key, raw)
			}
			lines[i] = strings.Replace(line, raw, `"inputs":`+string(in), 1)
			done[head.Key] = true
			continue
		}
		s, ok := seconds[head.Key]
		if !ok {
			continue
		}
		if union {
			return 0, fmt.Errorf("%s:%d: %s is a union row: its seconds are each language's", path, i+1, head.Key)
		}
		v := fmt.Sprintf(`,"seconds":%s`, strconv.FormatFloat(roundSeconds(s), 'f', -1, 64))
		body, nl := strings.TrimSuffix(line, "\n"), line[len(strings.TrimSuffix(line, "\n")):]
		body = secondsField.ReplaceAllString(body, "}")
		if !strings.HasSuffix(body, "}") {
			return 0, fmt.Errorf("%s:%d: a test line ends in }", path, i+1)
		}
		lines[i] = body[:len(body)-1] + v + "}" + nl
		done[head.Key] = true
	}
	var missing []string
	for k := range seconds {
		if !done[k] {
			missing = append(missing, k)
		}
	}
	for k := range langSeconds {
		if !done[k] {
			missing = append(missing, k)
		}
	}
	if len(missing) > 0 {
		slices.Sort(missing)
		return 0, fmt.Errorf("%s has no test line for %s", path, strings.Join(missing, ", "))
	}
	return len(done), os.WriteFile(path, []byte(strings.Join(lines, "")), 0o644)
}

// roundSeconds is a measured run time as the registry records it: at least
// minSeconds, rounded up to the hundredth.
func roundSeconds(s float64) float64 {
	return math.Ceil(max(s, minSeconds)*100) / 100
}

// SplitSeconds sorts the measured seconds of passing instances (by full
// name) into what WriteSeconds takes: a union row's by its key and language,
// every other row's by its key; a row with several instances keeps the
// longest. A measured name with no instance, or seconds that are not a
// positive time, is an error naming it: a measurement is never dropped
// without a word.
func SplitSeconds(instances map[string]Instance, measured map[string]float64) (map[string]float64, map[string]map[string]float64, error) {
	rows, langs := map[string]float64{}, map[string]map[string]float64{}
	for _, full := range slices.Sorted(maps.Keys(measured)) {
		s := measured[full]
		inst, ok := instances[full]
		switch {
		case !ok:
			return nil, nil, fmt.Errorf("%s was measured, and is no instance of the run: its seconds belong to no row", full)
		case !(s > 0):
			return nil, nil, fmt.Errorf("%s was measured at %v s: a run time is a positive number of seconds", full, s)
		}
		if _, union, _ := GoTestsOf(inst.Test); union {
			if langs[inst.Test.Key] == nil {
				langs[inst.Test.Key] = map[string]float64{}
			}
			langs[inst.Test.Key][inst.Lang] = max(langs[inst.Test.Key][inst.Lang], s)
			continue
		}
		rows[inst.Test.Key] = max(rows[inst.Test.Key], s)
	}
	return rows, langs, nil
}
