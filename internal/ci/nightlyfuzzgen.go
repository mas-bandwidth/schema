//go:build ignore

// nightlyfuzzgen writes the nightly table-reader fuzz harness for the Go port.
//
// It reads the corpus list the make target passes, scans the generated packages
// the target emitted (one directory per corpus entry), and writes one test file
// at the module root. There is ONE fuzz entry point per reader kind — load,
// strict read, text/JSON parse — and each dispatches over every table the
// generated packages expose, selected by the first input byte. The table set is
// discovered from the generated output (a type that has <T>ReadStrict), so a
// new table or corpus directory joins with no second list to edit.
//
// Usage: go run internal/ci/nightlyfuzzgen.go <corpus-list> <module-dir>
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	readStrictRe = regexp.MustCompile(`^func ([A-Za-z_][A-Za-z0-9_]*)ReadStrict\(wire \[\]byte\) \(\*([A-Za-z_][A-Za-z0-9_]*), error\)`)
	loadRe       = regexp.MustCompile(`^func ([A-Za-z_][A-Za-z0-9_]*)Load\(`)
	packageRe    = regexp.MustCompile(`^package ([A-Za-z_][A-Za-z0-9_]*)`)
)

type table struct {
	name   string
	row    string
	region bool
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: nightlyfuzzgen <corpus-list> <module-dir>")
		os.Exit(2)
	}
	list, out := os.Args[1], os.Args[2]
	dirs, err := corpusDirs(list)
	if err != nil {
		fatal(err)
	}
	var imports []string
	for i, dir := range dirs {
		pkgDir := filepath.Join(out, safeName(dir))
		files, err := filepath.Glob(filepath.Join(pkgDir, "*.go"))
		if err != nil {
			fatal(err)
		}
		if len(files) == 0 {
			fatalf("%s: no generated Go files in %s", dir, pkgDir)
		}
		pkgName, loads, err := scanPackage(files)
		if err != nil {
			fatal(err)
		}
		if len(loads) == 0 {
			fatalf("%s: no table entry points in %s", dir, pkgDir)
		}
		alias := fmt.Sprintf("p%d", i)
		imports = append(imports, fmt.Sprintf("\t%s \"nightlyfuzz/%s\"", alias, safeName(dir)))
		names := make([]string, 0, len(loads))
		for name := range loads {
			names = append(names, name)
		}
		sort.Strings(names)
		_ = pkgName
	}
	var b strings.Builder
	b.WriteString("// Code generated by internal/ci/nightlyfuzzgen.go. DO NOT EDIT.\n\n")
	b.WriteString("package nightlyfuzz\n\nimport (\n")
	b.WriteString("\t\"bytes\"\n\t\"fmt\"\n\t\"os\"\n\t\"path/filepath\"\n\t\"strconv\"\n\t\"strings\"\n\t\"testing\"\n\n")
	b.WriteString(strings.Join(imports, "\n"))
	b.WriteString("\n)\n\ntype tableFuzz struct {\n")
	b.WriteString("\tname     string\n\tload     func([]byte)\n\tread     func([]byte) error\n\ttext     func([]byte) error\n")
	b.WriteString("\twireSeed func() []byte\n\ttextSeed func() []byte\n}\n\n")
	b.WriteString("var tables = []tableFuzz{\n")
	idx := 0
	for _, dir := range dirs {
		files, _ := filepath.Glob(filepath.Join(out, safeName(dir), "*.go"))
		_, loads, _ := scanPackage(files)
		names := make([]string, 0, len(loads))
		for name := range loads {
			names = append(names, name)
		}
		sort.Strings(names)
		alias := fmt.Sprintf("p%d", dirIndex(dirs, dir))
		for _, name := range names {
			writeTable(&b, alias, loads[name])
			idx++
		}
	}
	b.WriteString("}\n\n")
	writeFuzz(&b)
	writeReplay(&b)
	if err := os.WriteFile(filepath.Join(out, "nightly_test.go"), []byte(b.String()), 0o644); err != nil {
		fatal(err)
	}
	fmt.Printf("nightly fuzz harness: %d tables over %d corpus directories\n", idx, len(dirs))
}

func writeTable(b *strings.Builder, alias string, t table) {
	name, row := t.name, t.row
	if row == "" {
		row = name
	}
	fmt.Fprintf(b, "\t{\n\t\tname: %q,\n", name)
	if t.region {
		fmt.Fprintf(b, "\t\tload: func(data []byte) { %s.%sLoad(nil, data, &%s.TableReport{}) },\n", alias, name, alias)
	} else {
		fmt.Fprintf(b, "\t\tload: func(data []byte) { var v %s.%s; %s.%sReset(&v); %s.%sLoad(&v, data, &%s.TableReport{}) },\n", alias, row, alias, name, alias, name, alias)
	}
	fmt.Fprintf(b, "\t\tread: func(data []byte) error {\n")
	fmt.Fprintf(b, "\t\t\tv, err := %s.%sReadStrict(data)\n", alias, name)
	fmt.Fprintf(b, "\t\t\tif err != nil && v != nil { return fmt.Errorf(%q) }\n", name+": strict read refused with a value")
	fmt.Fprintf(b, "\t\t\tif err == nil && v == nil { return fmt.Errorf(%q) }\n", name+": strict read accepted with a nil value")
	b.WriteString("\t\t\treturn err\n\t\t},\n")
	fmt.Fprintf(b, "\t\ttext: func(data []byte) error {\n")
	fmt.Fprintf(b, "\t\t\tv, err := %s.%sLoadText(string(data), &%s.TableReport{})\n", alias, name, alias)
	fmt.Fprintf(b, "\t\t\tif err != nil && v != nil { return fmt.Errorf(%q) }\n", name+": text parse refused with a value")
	fmt.Fprintf(b, "\t\t\tif err == nil && v == nil { return fmt.Errorf(%q) }\n", name+": text parse accepted with a nil value")
	b.WriteString("\t\t\treturn err\n\t\t},\n")
	fmt.Fprintf(b, "\t\twireSeed: func() []byte { var v %s.%s; %s.%sReset(&v); n := %s.%sMeasure(&v); if n < 0 { return nil }; out := make([]byte, n); if %s.%sSave(&v, out) != n { return nil }; return out },\n", alias, row, alias, name, alias, name, alias, name)
	fmt.Fprintf(b, "\t\ttextSeed: func() []byte { var v %s.%s; %s.%sReset(&v); n := %s.%sToJsonMeasure(&v); if n < 0 { return nil }; out := make([]byte, n); if %s.%sToJson(&v, out) != n { return nil }; return out },\n", alias, row, alias, name, alias, name, alias, name)
	b.WriteString("\t},\n")
}

func writeFuzz(b *strings.Builder) {
	b.WriteString(`func FuzzLoad(f *testing.F) {
	seed(f, "Load")
	f.Fuzz(func(t *testing.T, data []byte) {
		if len(data) == 0 {
			return
		}
		tables[int(data[0])%len(tables)].load(data[1:])
	})
}

func FuzzReadStrict(f *testing.F) {
	seed(f, "ReadStrict")
	f.Fuzz(func(t *testing.T, data []byte) {
		if len(data) == 0 {
			return
		}
		if err := tables[int(data[0])%len(tables)].read(data[1:]); err != nil {
			t.Logf("typed refusal: %v", err)
		}
	})
}

func FuzzTextJson(f *testing.F) {
	seed(f, "TextJson")
	f.Fuzz(func(t *testing.T, data []byte) {
		if len(data) == 0 {
			return
		}
		if err := tables[int(data[0])%len(tables)].text(data[1:]); err != nil {
			t.Logf("typed refusal: %v", err)
		}
	})
}

func seed(f *testing.F, kind string) {
	f.Helper()
	f.Add([]byte{})
	for i, target := range tables {
		wire := target.wireSeed()
		if len(wire) > 0 {
			f.Add(append([]byte{byte(i)}, wire...))
		}
		text := target.textSeed()
		if len(text) > 0 && kind == "TextJson" {
			f.Add(append([]byte{byte(i)}, text...))
		}
	}
	for _, dir := range splitEnv("SCHEMA_GO_FUZZ_SEEDS") {
		_ = filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return nil
			}
			data, err := os.ReadFile(path)
			if err == nil && len(data) > 0 {
				f.Add(data)
			}
			return nil
		})
	}
}

func splitEnv(name string) []string {
	raw := os.Getenv(name)
	if raw == "" {
		return nil
	}
	var out []string
	for _, part := range strings.Split(raw, string(os.PathListSeparator)) {
		if part != "" {
			out = append(out, part)
		}
	}
	return out
}

`)
}

func writeReplay(b *strings.Builder) {
	b.WriteString(`// TestSavedInputsReplay replays every committed regression input. It never
// fuzzes: the clock is not consulted, and a saved input that panicked is a red
// on every push.
func TestSavedInputsReplay(t *testing.T) {
	t.Parallel()
	for _, dir := range splitEnv("SCHEMA_GO_FUZZ_REGRESSIONS") {
		for kind, apply := range map[string]func([]byte){
			"Load":       func(data []byte) { tables[int(data[0])%len(tables)].load(data[1:]) },
			"ReadStrict": func(data []byte) { _ = tables[int(data[0])%len(tables)].read(data[1:]) },
			"TextJson":   func(data []byte) { _ = tables[int(data[0])%len(tables)].text(data[1:]) },
		} {
			entries, err := os.ReadDir(filepath.Join(dir, kind))
			if err != nil {
				continue
			}
			for _, entry := range entries {
				if entry.IsDir() {
					continue
				}
				data, err := os.ReadFile(filepath.Join(dir, kind, entry.Name()))
				if err != nil {
					t.Fatalf("%s: %v", entry.Name(), err)
				}
				data = decodeSaved(data)
				if len(data) == 0 {
					continue
				}
				apply(data)
			}
		}
	}
}

// TestSeedsRun drives every seed through every reader kind without a fuzzer or
// a clock. It is the per-push half of the campaign: the emitters' zero-value
// images and the external seed corpus are inputs a reader must survive now, not
// only on the nightly.
func TestSeedsRun(t *testing.T) {
	t.Parallel()
	drive := func(selector byte, wire []byte) {
		apply := []func([]byte){
			func(data []byte) { tables[int(selector)%len(tables)].load(data) },
			func(data []byte) { _ = tables[int(selector)%len(tables)].read(data) },
			func(data []byte) { _ = tables[int(selector)%len(tables)].text(data) },
		}
		for _, f := range apply {
			f(wire)
		}
	}
	for i, target := range tables {
		if wire := target.wireSeed(); len(wire) > 0 {
			drive(byte(i), wire)
		}
		if text := target.textSeed(); len(text) > 0 {
			_ = tables[i].text(text)
		}
	}
	for _, dir := range splitEnv("SCHEMA_GO_FUZZ_SEEDS") {
		_ = filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() {
				return nil
			}
			data, err := os.ReadFile(path)
			if err == nil && len(data) > 0 {
				drive(data[0], data[1:])
			}
			return nil
		})
	}
}

// decodeSaved accepts the raw selector+input form, and the Go fuzz corpus form
// the fuzzer writes (go test fuzz v1 / []byte("...")), so a minimized crasher
// can be committed without a second conversion step.
func decodeSaved(data []byte) []byte {
	if !bytes.HasPrefix(data, []byte("go test fuzz v1\n")) {
		return data
	}
	lines := strings.Split(strings.TrimSpace(string(data)), "\n")
	if len(lines) < 2 {
		return nil
	}
	quoted := strings.TrimSuffix(strings.TrimPrefix(lines[len(lines)-1], "[]byte("), ")")
	decoded, err := strconv.Unquote(quoted)
	if err != nil {
		return nil
	}
	return []byte(decoded)
}
`)
}

func corpusDirs(list string) ([]string, error) {
	data, err := os.ReadFile(list)
	if err != nil {
		return nil, err
	}
	var dirs []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		info, err := os.Stat(line)
		if err != nil {
			return nil, fmt.Errorf("%s: corpus directory does not exist: %w", line, err)
		}
		if !info.IsDir() {
			return nil, fmt.Errorf("%s: corpus entry is not a directory", line)
		}
		dirs = append(dirs, line)
	}
	if len(dirs) == 0 {
		return nil, fmt.Errorf("%s: the corpus set is empty", list)
	}
	return dirs, nil
}

func scanPackage(files []string) (string, map[string]table, error) {
	pkg := ""
	loads := map[string]table{}
	regions := map[string]bool{}
	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			return "", nil, err
		}
		for _, line := range strings.Split(string(data), "\n") {
			if pkg == "" {
				if m := packageRe.FindStringSubmatch(line); m != nil {
					pkg = m[1]
				}
			}
			if m := readStrictRe.FindStringSubmatch(line); m != nil {
				loads[m[1]] = table{name: m[1], row: m[2]}
			}
			if m := loadRe.FindStringSubmatch(line); m != nil {
				regions[m[1]] = strings.Contains(line, "(region, wire")
			}
		}
	}
	for name, t := range loads {
		t.region = regions[name]
		loads[name] = t
	}
	return pkg, loads, nil
}

func safeName(dir string) string {
	base := filepath.Base(filepath.Clean(dir))
	var b strings.Builder
	for _, r := range base {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteByte('_')
		}
	}
	return b.String()
}

func dirIndex(dirs []string, dir string) int {
	for i, d := range dirs {
		if d == dir {
			return i
		}
	}
	return 0
}

func fatal(err error) { fatal2(err) }

func fatal2(err error) {
	fmt.Fprintln(os.Stderr, "nightlyfuzzgen:", err)
	os.Exit(1)
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "nightlyfuzzgen: "+format+"\n", args...)
	os.Exit(1)
}
