// Package jstable emits a unit's JavaScript table accelerators
// (docs/SPEC-TABLES.md): the block form (§19, built and read) and the cook
// form (§7, written and read), plus the fixed-form wire (form 3 only,
// schema#516) and the variable-form wire. One file per unit file, emitted
// only when the unit declares tables — plus the unit's ONE RUNTIME HOME per
// surface, where everything shared lands (runtimeHome, below).
//
// JavaScript has no struct layout of its own — no offsetof, no sizeof — so
// every field is placed at the offset the compiler settled, through a
// DataView with an explicit endian flag at every call. The block builder
// writes §19.1's prologue and triples, and a block is read over bytes with a
// DataView at explicit little-endian offsets. The cook writer measures before
// it writes (§7.6), the cook is read over bytes another language wrote, and
// the header words are §19.1's.
package jstable

import (
	"fmt"
	"maps"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

// table-wire kinds (docs/SPEC-TABLES.md §3) — the numbers are the wire's, not a
// backend's, and they are duplicated from cpptable deliberately: a port that
// derived them from the reference emitter's private helpers would break the
// day the two files disagree, and this way a disagreement shows up in the
// shared golden bytes instead.
const (
	tkBool   = 1
	tkI8     = 2
	tkI16    = 3
	tkI32    = 4
	tkI64    = 5
	tkU8     = 6
	tkU16    = 7
	tkU32    = 8
	tkU64    = 9
	tkF32    = 10
	tkF64    = 11
	tkString = 12
	tkTable  = 13
	tkArray  = 14
	tkUnion  = 15
)

func tableScalarKind(f *ir.Field) int {
	switch f.Type.Kind {
	case ir.TBool:
		return tkBool
	case ir.TInt:
		if f.Type.Signed {
			switch f.Type.Width {
			case 8:
				return tkI8
			case 16:
				return tkI16
			case 32:
				return tkI32
			default:
				return tkI64
			}
		}
		switch f.Type.Width {
		case 8:
			return tkU8
		case 16:
			return tkU16
		case 32:
			return tkU32
		default:
			return tkU64
		}
	case ir.TBits:
		switch {
		case f.Type.Width <= 8:
			return tkU8
		case f.Type.Width <= 16:
			return tkU16
		case f.Type.Width <= 32:
			return tkU32
		default:
			return tkU64
		}
	case ir.TFloat32:
		return tkF32
	case ir.TFloat64:
		return tkF64
	case ir.TString:
		return tkString
	case ir.TBytes:
		return tkArray
	case ir.TNamed:
		switch f.Type.Ref.(type) {
		case *ir.Enum:
			// an enum value rides as the u16 hash of its VARIANT NAME
			// (docs/SPEC-TABLES.md §5), whatever the declaration-side width
			return tkU16
		case *ir.Flags:
			return tkU64
		case *ir.Struct:
			return tkTable
		case *ir.Union:
			return tkUnion
		}
	}
	return 0
}

// runtimeHome is the basename of the module that carries a unit's shared
// JavaScript runtime — the block runtime in block.go and the cook runtime in
// cook.go, each in its own <Package><Surface>.js.
//
// IT IS THE PACKAGE, and nothing else. An ES module is file-scoped, so a shared
// runtime is DEFINED once and imported everywhere else — and the module that
// defines it wants a name that does not move.
func runtimeHome(u *ir.Unit) string {
	return ir.TableJSRuntimeHome(u)
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

// runtimeHomeMarker rides the banner of each runtime home, so "which module
// carries this unit's shared runtime" is a grep rather than a line count.
const runtimeHomeMarker = "the unit's shared runtime lives here"

// generatedFrom is the DO NOT EDIT banner's first line. A runtime home the unit
// has no file for is generated FOR THE UNIT, and says so — there is no
// <Package>.schema to name.
func generatedFrom(f *ir.File, u *ir.Unit) string {
	if f == nil {
		return fmt.Sprintf("// Code generated by the schema compiler for package %s. DO NOT EDIT.\n", u.Package)
	}
	return fmt.Sprintf("// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", f.Base)
}

// isClassRef reports a named reference whose JavaScript storage is a class
// instance: a generated struct/table class or a union.
func isClassRef(t ir.FieldType) bool {
	if t.Kind != ir.TNamed {
		return false
	}
	switch t.Ref.(type) {
	case *ir.Struct, *ir.Union:
		return true
	}
	return false
}

// refuseFileCollisions names the module basenames this backend claims beside
// each schema file, so a unit that would have two emitters writing one path is
// refused here rather than losing a file quietly.
func refuseFileCollisions(u *ir.Unit) error {
	bases := map[string]bool{}
	for _, f := range u.Files {
		bases[f.Base] = true
	}
	bases[runtimeHome(u)] = true
	// the VIEW module (docs/SPEC-TABLES.md §8.5) is the runtime home's, so a
	// schema file of that basename would be a second writer of it
	if bases[viewBase(u)] {
		return fmt.Errorf("schema file %s collides — the JS table emitter writes %s.js as the unit's view (docs/SPEC-TABLES.md §8.5); rename the file (docs/SPEC-TABLES.md §11)",
			viewBase(u), viewBase(u))
	}
	for base := range bases {
		for _, suffix := range []string{"Table", "Block", "Cook"} {
			if bases[base+suffix] {
				return fmt.Errorf("schema files %s and %s%s collide — the JS table emitter writes %s%s.js as %s's table surface; rename one file (docs/SPEC-TABLES.md §11)",
					base, base, suffix, base, suffix, base)
			}
		}
	}
	return nil
}

// Generate emits <Base>Block.js and <Base>Cook.js for every unit file when the
// unit declares tables, and nothing when it does not — a table-free unit's
// generated JavaScript is byte-identical with or without this package.
func Generate(u *ir.Unit) (map[string][]byte, error) {
	return GenerateLineage(u, nil)
}

// GenerateLineage is [Generate] with the LINEAGE the build holds for each fixed
// table: the locked layouts, OLDEST FIRST, the current one last
// (docs/FIXED-FORM-ALGORITHM.md §5.2, §5.9 #1). A nil map is a build with no
// lock — a unit that was never locked promises nothing — and every table then
// carries the one entry it can always compute: its own.
//
// THE BACKEND OPENS NO FILE: `lockfile.Open`, `lockfile.Lineage` and
// `lockfile.Floor` are the CALLER's three calls, so the disk is read in one
// place and a test can play the lock in one line.
func GenerateLineage(u *ir.Unit, lineage map[string][]FixedLineageEntry) (map[string][]byte, error) {
	if len(u.Tables) == 0 {
		return map[string][]byte{}, nil
	}
	// §15's WIDE-KIND REFUSAL IS THE FORM-1 ACCELERATORS' AND NOT THE WIRE'S
	// (ir.WideTableKinds). The rule lives in ir because a rule five ports each
	// spell for themselves is five rules — and the day this backend gained
	// §3.4's fixed form is the day the block form and the cooked form stood down
	// alone, with the unit NOT refused whole because there is a wire left to
	// emit. The refusal still names every wide field, and it is stated by name in
	// every module this unit gets.
	//
	// THE ANSWER IS THIS LEG'S OWN ROOTS, and not a hard-coded `true`: a unit
	// this leg lays no table out for, on the fixed form (jsFixedUnitRoots) or the
	// variable form (variableRoots), has no wire left to put in the
	// accelerators' place. The variable form carries the 128-bit kinds and its
	// cook writer lays them (docs/PORTING.md M19's widelist_wide), so a unit
	// whose tables are variable-only is carried, not refused.
	carried := len(jsFixedUnitRoots(u)) > 0
	for _, f := range u.Files {
		carried = carried || len(variableRoots(u, f.Tables)) > 0
	}
	scope := ir.WideTableKinds(u, "JavaScript", carried)
	if scope.Unit {
		return nil, scope.Refusal
	}
	if err := refuseFileCollisions(u); err != nil {
		return nil, err
	}
	// A HANDED ENTRY THAT IS A LOCK BUG FAILS THE BUILD, before a line is
	// emitted (§5.9 #8, #26): a layout that does not parse, or a record size
	// that is not what the entry's own layout accounts for, is never a wire
	// event and never a refusal at the first file that matches its hash.
	if err := refuseFixedLineage(u, lineage); err != nil {
		return nil, err
	}
	// THE WIDE KINDS (docs/SPEC-TABLES.md §15) ARE A REFUSAL OF THE
	// ACCELERATORS, NOT OF THE FIXED FORM. A block row and a cooked node are
	// laid out in the ID-TABLE's kind vocabulary, which has no fixed-point and
	// no 128-bit kind in this backend yet (schema#366) — but §3.4's fixed form
	// carries both by its own constant-size table, a `fixed(I, F)` riding as
	// the raw scaled integer at its storage width and an `int128`/`uint128` as
	// sixteen bytes, the low half then the high. So the refusal is SCOPED to
	// the two accelerators and stated by name in every module this unit gets,
	// rather than taken out on a form that carries the kinds fine.
	wide := ir.TableWideFields(u)
	out := map[string][]byte{}
	if len(wide) == 0 {
		blocks := ir.Blocks(u)
		var err error
		out, err = generateBlockFiles(u, blocks)
		if err != nil {
			return nil, err
		}
		cooks, err := generateCookFiles(u, blocks)
		if err != nil {
			return nil, err
		}
		maps.Copy(out, cooks)
	}
	// THE VARIABLE FORM (docs/SPEC-TABLES.md §3.1), form byte 1: tolerant
	// wire reading and canonical byte layout for card constructs.
	variable, err := generateVariableFiles(u, wide)
	if err != nil {
		return nil, err
	}
	maps.Copy(out, variable)
	// THE FIXED FORM (docs/SPEC-TABLES.md §3.4), form byte 3: this backend's
	// second table wire.
	fixed, err := generateFixedFiles(u, wide, lineage)
	if err != nil {
		return nil, err
	}
	maps.Copy(out, fixed)
	// A unit whose wide kinds cost it the accelerators AND that has no table
	// wire to put in their place has nothing to emit, so it is refused whole
	// and by name.
	if len(wide) > 0 && len(fixed) == 0 && len(variable) == 0 {
		return nil, scope.Refusal
	}
	// THE VIEW (docs/SPEC-TABLES.md §8.2, §8.3, §8.5): every table and every
	// type described, and the unit registry, in one module on the side.
	maps.Copy(out, generateViewFile(u))
	return out, nil
}

// liveImports keeps, of the symbols a module was about to import from one
// sibling, only those its body names: an import nothing reads is an unused
// binding (eslint no-unused-vars) and says nothing to a reader. The scan is
// over identifier tokens, so a name that appears only in a comment is kept
// rather than dropped: a miss here is a lint finding, never a broken module.
func liveImports(syms []string, used map[string]bool) []string {
	live := syms[:0:0]
	for _, s := range syms {
		if used[s] {
			live = append(live, s)
		}
	}
	return live
}

// jsIdentifiers is the set of identifier tokens in a module body's code, the
// lookup liveImports keeps an import by. Comments and string literals are
// skipped, so a type named only in a string (a codec's "Envelope") or a
// comment does not keep an import alive. A misread here can only drop an
// import the code names, which the lint's no-undef then names.
func jsIdentifiers(body string) map[string]bool {
	set := map[string]bool{}
	isWord := func(c byte, first bool) bool {
		return c == '_' || c == '$' || (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (!first && c >= '0' && c <= '9')
	}
	for i := 0; i < len(body); {
		c := body[i]
		switch {
		case c == '/' && i+1 < len(body) && body[i+1] == '/':
			for i < len(body) && body[i] != '\n' {
				i++
			}
		case c == '/' && i+1 < len(body) && body[i+1] == '*':
			end := strings.Index(body[i+2:], "*/")
			if end < 0 {
				return set
			}
			i += end + 4
		case c == '"' || c == '\'' || c == '`':
			i++
			for i < len(body) && body[i] != c {
				if body[i] == '\\' {
					i++
				}
				i++
			}
			i++
		case isWord(c, true):
			start := i
			for i < len(body) && isWord(body[i], false) {
				i++
			}
			set[body[start:i]] = true
		case c >= '0' && c <= '9':
			for i < len(body) && isWord(body[i], false) {
				i++
			}
		default:
			i++
		}
	}
	return set
}
