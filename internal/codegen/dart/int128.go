package dart

import (
	"fmt"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

// emitInt128Support writes Int128.dart — the emulated 128-bit pair the
// 128-bit storage widths map to, mirroring serialize.dart's Int128/UInt128
// (one pair shape across the family's GC targets, so wire behavior cannot
// diverge by platform) but emitted self-contained: generated code never
// imports a runtime package. The operation set is what generated code and
// its consumers need — construction, conversion, add/subtract, compares —
// with shifts and masks left out: the emitter folds every shift at
// generation time.
func emitInt128Support(u *ir.Unit) []byte {
	var h strings.Builder
	h.WriteString("// Code generated by the schema compiler. DO NOT EDIT.\n")
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&h, "// package %s — protocol id 0x%016x\n", u.Package, u.ProtocolId)
	h.WriteString(`//
// The emulated 128-bit pair: Dart has no native 128-bit integer, so
// int128/uint128 storage speaks these types — two's-complement math on
// (hi, lo) 64-bit halves held bit-transparently in Dart ints, the family's
// one pair shape (serialize.dart, serialize.cs).

// Unsigned 128-bit less-than on bit-transparent halves.
@pragma('vm:prefer-inline')
bool _lessThan(int aHi, int aLo, int bHi, int bLo) => aHi == bHi
    ? (aLo ^ 0x8000000000000000) < (bLo ^ 0x8000000000000000)
    : (aHi ^ 0x8000000000000000) < (bHi ^ 0x8000000000000000);

// 16 hex digits of a 64-bit pattern held in a signed int (toRadixString
// would render a sign, not the pattern).
String _hex16(int value) =>
    (value >>> 32).toRadixString(16).padLeft(8, '0') +
    (value & 0xffffffff).toRadixString(16).padLeft(8, '0');

/// Unsigned 128-bit value as (hi, lo) 64-bit halves, each held
/// bit-transparently in a signed Dart int.
final class UInt128 {
  /// The high 64 bits.
  final int hi;

  /// The low 64 bits.
  final int lo;

  /// Constructs from explicit high and low halves.
  const UInt128(this.hi, this.lo);

  /// The zero value.
  static const UInt128 zero = UInt128(0, 0);

  /// The unsigned 128-bit maximum.
  static const UInt128 maxValue = UInt128(-1, -1);

  /// Constructs from a 64-bit value, sign-extending: matching the family
  /// pair's conversion from a signed 64-bit integer. For a non-negative
  /// value this zero-extends.
  factory UInt128.fromInt(int value) => UInt128(value < 0 ? -1 : 0, value);

  /// The value reinterpreted as signed: bit-transparent.
  Int128 toSigned() => Int128(hi, lo);

  /// The low 64 bits, truncating.
  int toInt() => lo;

  UInt128 operator +(UInt128 other) {
    final low = lo + other.lo;
    final carry = (low ^ 0x8000000000000000) < (lo ^ 0x8000000000000000)
        ? 1
        : 0;
    return UInt128(hi + other.hi + carry, low);
  }

  UInt128 operator -(UInt128 other) {
    final low = lo - other.lo;
    final borrow = (lo ^ 0x8000000000000000) < (other.lo ^ 0x8000000000000000)
        ? 1
        : 0;
    return UInt128(hi - other.hi - borrow, low);
  }

  bool operator <(UInt128 other) => _lessThan(hi, lo, other.hi, other.lo);

  bool operator >(UInt128 other) => other < this;

  bool operator <=(UInt128 other) => !(other < this);

  bool operator >=(UInt128 other) => !(this < other);

  @override
  bool operator ==(Object other) =>
      other is UInt128 && hi == other.hi && lo == other.lo;

  @override
  int get hashCode => Object.hash(hi, lo);

  @override
  String toString() => '0x${_hex16(hi)}${_hex16(lo)}';
}

/// Signed 128-bit value as (hi, lo) 64-bit halves, two's complement.
final class Int128 {
  /// The high 64 bits. The sign lives in its top bit.
  final int hi;

  /// The low 64 bits, held bit-transparently.
  final int lo;

  /// Constructs from explicit high and low halves.
  const Int128(this.hi, this.lo);

  /// The zero value.
  static const Int128 zero = Int128(0, 0);

  /// The signed 128-bit minimum, -2^127.
  static const Int128 minValue = Int128(0x8000000000000000, 0);

  /// The signed 128-bit maximum, 2^127 - 1.
  static const Int128 maxValue = Int128(0x7fffffffffffffff, -1);

  /// Constructs from a 64-bit value, sign-extending.
  factory Int128.fromInt(int value) => Int128(value < 0 ? -1 : 0, value);

  /// The value reinterpreted as unsigned: bit-transparent.
  UInt128 toUnsigned() => UInt128(hi, lo);

  /// The low 64 bits, truncating.
  int toInt() => lo;

  Int128 operator +(Int128 other) =>
      (toUnsigned() + other.toUnsigned()).toSigned();

  Int128 operator -(Int128 other) =>
      (toUnsigned() - other.toUnsigned()).toSigned();

  bool operator <(Int128 other) =>
      hi == other.hi ? _lessThan(0, lo, 0, other.lo) : hi < other.hi;

  bool operator >(Int128 other) => other < this;

  bool operator <=(Int128 other) => !(other < this);

  bool operator >=(Int128 other) => !(this < other);

  @override
  bool operator ==(Object other) =>
      other is Int128 && hi == other.hi && lo == other.lo;

  @override
  int get hashCode => Object.hash(hi, lo);

  @override
  String toString() => '0x${_hex16(hi)}${_hex16(lo)}';
}
`)
	return []byte(h.String())
}
