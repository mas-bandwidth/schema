package dart

import "strings"

// runtimeBase is the basename of the unit's one packet support library,
// Schema.dart. SPEC §6.1 (the Dart bullet) has the backend spell NO private
// library-scope name: a schema identifier may begin with an underscore, so
// a generated top-level `_f32` is a collision no registry covers. The
// helpers every packet library shares therefore live as static members of
// ONE public class, `Schema`, in a library of its own that each packet
// library imports with `show Schema`. The class name is the one the
// checker already claims in every unit (the C# target's namespace-level
// home, internal/check checkClaimedNames), so a declaration can never
// shadow it; a schema FILE named Schema.schema is refused in Generate.
const runtimeBase = "Schema"

// emitRuntime writes Schema.dart. Its text is the same for every unit — no
// package, no protocol id — so two units generated into one directory agree
// on it byte for byte rather than fighting over it.
func emitRuntime() []byte {
	var h strings.Builder
	h.WriteString("// Code generated by the schema compiler. DO NOT EDIT.\n")
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	h.WriteString(runtimeSource)
	h.WriteString(strings.TrimRight(utf8Helper, "\n"))
	h.WriteString("\n")
	h.WriteString("}\n")
	return []byte(h.String())
}

const runtimeSource = `//
// The packet libraries' shared helpers, as static members of one class: the
// backend spells no private library-scope name (SPEC §6.1), and Schema is a
// name every unit already claims, so no declaration can collide with it.

import 'dart:typed_data';

abstract final class Schema {
  // One 8-byte conversion scratch under overlaid typed-data views — single
  // threaded per isolate, always consumed in the same operation that fills
  // it. Generated code converts float32 AT THE ASSIGNMENT through these
  // views (issue 404): a double crossing an out-of-line call is boxed under
  // the JIT.
  static final Float32List f32 = Float32List(2);
  static final Uint32List u32 = f32.buffer.asUint32List();
  static final Float64List f64 = f32.buffer.asFloat64List();
  static final Uint64List u64 = f32.buffer.asUint64List();

  // value rounded to the nearest float32, as a double: the float32 rounding
  // boundary the compressed-float arithmetic is pinned to (SPEC §4.3).
  @pragma('vm:prefer-inline')
  static double fround(double value) {
    f32[0] = value;
    return f32[0];
  }

  // The 64 bits of the IEEE-754 double representation of value — exactly
  // the bits of the Dart double — and the inverse.
  @pragma('vm:prefer-inline')
  static int float64BitsFromDouble(double value) {
    f64[0] = value;
    return u64[0];
  }

  @pragma('vm:prefer-inline')
  static double doubleFromFloat64Bits(int bits) {
    u64[0] = bits;
    return f64[0];
  }

  // Unsigned 64-bit less-than: flip the sign bit so the signed comparison
  // orders the unsigned domain (uint64 values ride bit-transparently in int).
  @pragma('vm:prefer-inline')
  static bool unsignedLessThan(int a, int b) =>
      (a ^ 0x8000000000000000) < (b ^ 0x8000000000000000);

  // Hex of a uint64 bit pattern held in a signed int (toRadixString would
  // render the sign, not the pattern).
  static String hex64(int value) => value < 0
      ? (value >>> 32).toRadixString(16) +
            (value & 0xffffffff).toRadixString(16).padLeft(8, '0')
      : value.toRadixString(16);

`
