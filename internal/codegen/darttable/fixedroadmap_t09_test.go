package darttable

// THE DART LEG'S FIXED-TABLE OPTIONAL AND DEFAULT ROWS (docs/roadmap.sexp node
// `fixed-tables`, rows optional-scalars, optional-arrays, scalar-defaults and
// text-bytes-flags-defaults). Each subtest is one roadmap task id and is a
// [capability] task: the leg WRITES and READS the construct with non-default
// and boundary values through its own generated save and load, in a target the
// gates run — the Dart SDK the Makefile pins, driven here from `go test`.
//
// The page sentences each assertion implements are quoted at the assertion:
// docs/SPEC-TABLES.md §2.3 ("PRESENCE decides whether the field rides … a
// present [optional array] ALWAYS rides as the array framing"), §3.4 (the
// OPTIONAL WRAPPER `?T`: "the present flag: the payload rides WHOLE either
// way"), and §3.4's template/prefill rule (a declared default is the template's
// bytes; a read is a prefill and a loop), with docs/FIXED-FORM-ALGORITHM.md §3.
//
// The probe is GENERATED by the Go side and never hand-edited: it builds
// values, saves them with the leg's own writer (`<T>FixedSave`), loads the
// bytes back into fresh values with the leg's own reader (`<T>FixedLoad`), and
// fails by name on any counter a clean round trip moves.
//
// A clause an existing test of this leg already holds is named by that test in
// the card's verdicts and is not repeated here.

import (
	"fmt"
	"maps"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/codegen/dart"
)

const t09Probe = `import 'dart:io';
import 'dart:typed_data';

import './ProbeFixed.dart' as t;

void check(bool ok, String what) {
  if (!ok) {
    stderr.writeln('FAIL: $what');
    exitCode = 1;
  }
}

void main() {
  final values = <t.@TYPE@>[for (var i = 0; i < @RECORDS@; i++) t.@TYPE@()];
  for (final v in values) {
    t.init@TYPE@(v);
  }
@BODY@
  final bytes = Uint8List(t.@LOWER@FixedMeasure(values.length));
  final wrote = t.@LOWER@FixedSave(values, values.length, bytes);
  check(wrote == bytes.length, 'the writer wrote $wrote of ${bytes.length} bytes');
  final back = <t.@TYPE@>[for (var i = 0; i < @RECORDS@; i++) t.@TYPE@()];
  final rep = t.TableFixedReport();
  final plan = t.@LOWER@FixedNewPlan();
  final n = t.@LOWER@FixedLoad(back, back.length, bytes, bytes.length, plan, rep);
  check(n == @RECORDS@, 'the load returned $n, want @RECORDS@ (refused=${rep.refused})');
  check(!rep.malformed && rep.refused == 0 && rep.clamped == 0,
      'a clean round trip moved a counter: malformed=${rep.malformed} '
      'refused=${rep.refused} clamped=${rep.clamped}');
@CHECKS@
  if (exitCode == 0) {
    stdout.writeln('ok');
  }
}
`

// t09Capability generates one inline schema with this leg's own emitter, writes
// the generated libraries beside a GENERATED probe and runs the probe with the
// leg's own toolchain (§5.9 #18). It returns the probe's combined output.
func t09Capability(t *testing.T, src, body, checks string, records int) string {
	t.Helper()
	u := unitFrom(t, src)
	st := versionRoot(t, u)
	// THE PACKET LIBRARY TOO: the fixed library imports the unit's enum and
	// flags declarations from it, the way a consumer does.
	files, err := dart.Generate(u)
	if err != nil {
		t.Fatalf("generate packet: %v", err)
	}
	tables, err := Generate(u)
	if err != nil {
		t.Fatalf("generate fixed: %v", err)
	}
	maps.Copy(files, tables)
	dir := t.TempDir()
	for name, data := range files {
		if strings.Contains(name, "/") {
			continue
		}
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	lower := lowerFirst(st.Name)
	probe := strings.NewReplacer(
		"@TYPE@", st.Name,
		"@LOWER@", lower,
		"@RECORDS@", fmt.Sprintf("%d", records),
		"@BODY@", body,
		"@CHECKS@", checks,
	).Replace(t09Probe)
	// NOT `probe.dart`: this filesystem is case-insensitive and the packet
	// library is `Probe.dart`, so the two names are one file.
	if err := os.WriteFile(filepath.Join(dir, "t09_probe.dart"), []byte(probe), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(dartBinary(t), "--enable-asserts", "t09_probe.dart")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("the capability probe did not run green: %v\n%s", err, out)
	}
	if !strings.Contains(string(out), "ok") {
		t.Fatalf("the capability probe printed no ok: %s", out)
	}
	return string(out)
}

func TestFixedRoadmapDartT09Optionals(t *testing.T) {
	t.Parallel()

	rows := []struct {
		id      string
		src     string
		records int
		body    string
		checks  string
		want    []string
	}{
		{
			// optional-scalars/dart/valid-data: "Optional scalar and enum
			// fields: valid-data write/read acceptance". §3.4's OPTIONAL
			// WRAPPER: "the present flag: the payload rides WHOLE either way"
			// — one present byte at the field's own offset, the payload whole
			// behind it present or not. The boundary is the scalar's floor and
			// the enum's LAST variant; an absent optional lands the template's
			// zero (slack is zero on write, §3.4).
			id:      "optional-scalars/dart/valid-data",
			records: 2,
			src: `package probe

enum Grade
{
    Bronze
    Silver
    Gold
}

fixed table T
{
    score ?int32
    grade ?Grade
}
`,
			body: `  values[0].scorePresent = true;
  values[0].score = -2147483648;
  values[0].gradePresent = true;
  values[0].grade = 3;
  values[1].scorePresent = false;
  values[1].score = 12345;
  values[1].gradePresent = false;
  values[1].grade = 2;
`,
			checks: `  check(back[0].scorePresent && back[0].score == -2147483648,
      'a present optional scalar at its floor landed ${back[0].score}');
  check(back[0].gradePresent && back[0].grade == 3,
      'a present optional enum at its last variant landed ${back[0].grade}');
  check(!back[1].scorePresent && back[1].score == 0,
      'an absent optional scalar landed the template zero, not the caller storage: ${back[1].score}');
  check(!back[1].gradePresent && back[1].grade == 0,
      'an absent optional enum landed None, not the caller storage: ${back[1].grade}');
`,
			want: []string{
				"value.scorePresent ? 1 : 0",
				"if (value.scorePresent) {",
				"value.gradePresent ? 1 : 0",
				"if (value.gradePresent) {",
				"if (value.grade > 3) {",
			},
		},

		{
			// optional-arrays/dart/valid-data: "Optional arrays: valid-data
			// write/read acceptance". §2.3: "PRESENCE decides whether the
			// field rides: an absent optional array is not written; a present
			// one ALWAYS rides as the array framing (§3) — a counted array
			// with its live count, ZERO included". Written and read at the
			// bound with the extremes, present-and-empty, and absent with
			// nonzero caller storage that must not reach the wire.
			id:      "optional-arrays/dart/valid-data",
			records: 4,
			src: `package probe

fixed table T
{
    lead  uint32 = 1
    xs    ?[..4]int32
    ys    ?[4]int32
    trail uint32 = 2
}
`,
			body: `  values[0].xsPresent = true;
  values[0].xsCount = 4;
  values[0].xs[0] = -2147483648;
  values[0].xs[1] = 2147483647;
  values[0].xs[2] = -1;
  values[0].xs[3] = 0;
  values[0].ysPresent = true;
  values[0].ys[0] = 7;
  values[0].ys[1] = -8;
  values[0].ys[2] = 2147483647;
  values[0].ys[3] = -2147483648;
  values[0].lead = 101;
  values[0].trail = 102;
  values[1].xsPresent = true;
  values[1].xsCount = 0;
  values[1].lead = 201;
  values[1].trail = 202;
  values[2].xsPresent = false;
  values[2].xsCount = 4;
  values[2].xs[0] = 91;
  values[2].xs[1] = 92;
  values[2].xs[2] = 93;
  values[2].xs[3] = 94;
  values[2].ysPresent = false;
  values[2].ys[0] = 55;
  values[2].ys[1] = 56;
  values[2].ys[2] = 57;
  values[2].ys[3] = 58;
  values[2].lead = 301;
  values[2].trail = 302;
  values[3].ysPresent = true;
  values[3].lead = 401;
  values[3].trail = 402;
`,
			checks: `  check(back[0].xsPresent && back[0].xsCount == 4,
      'a present counted array at the bound landed count ${back[0].xsCount}');
  check(back[0].xs[0] == -2147483648 && back[0].xs[1] == 2147483647 &&
      back[0].xs[2] == -1 && back[0].xs[3] == 0,
      'the present counted array lost an extreme: ${back[0].xs}');
  check(back[0].ysPresent && back[0].ys[0] == 7 && back[0].ys[1] == -8 &&
      back[0].ys[2] == 2147483647 && back[0].ys[3] == -2147483648,
      'the present fixed array lost a value: ${back[0].ys}');
  check(back[0].lead == 101 && back[0].trail == 102, 'r0 brackets moved');
  check(back[1].xsPresent && back[1].xsCount == 0,
      'present and empty is PRESENT with count 0: ${back[1].xsPresent} ${back[1].xsCount}');
  check(!back[2].xsPresent && back[2].xsCount == 0 && back[2].xs[0] == 0 && back[2].xs[1] == 0,
      'an absent optional array landed the caller storage: ${back[2].xs}');
  check(!back[2].ysPresent && back[2].ys[0] == 0 && back[2].ys[1] == 0,
      'an absent optional fixed array landed the caller storage: ${back[2].ys}');
  check(back[2].lead == 301 && back[2].trail == 302, 'r2 brackets moved');
  check(back[3].ysPresent && back[3].ys[0] == 0 && back[3].ys[3] == 0,
      'a present all-default fixed array still rides PRESENT: ${back[3].ysPresent}');
`,
			want: []string{
				"value.xsPresent ? 1 : 0",
				"assert(value.xsCount <= 4);",
				"for (var i = 0; i < value.xsCount; i++) {",
			},
		},

		{
			// scalar-defaults/dart/valid-data: "Scalar and enum defaults:
			// valid-data write/read acceptance" (contract "§3.4 template;
			// ALGORITHM §3"). The declared defaults are the template's bytes
			// and `initT` restores them; the round trip lands non-default and
			// boundary scalars and the non-default enum variant exact.
			id:      "scalar-defaults/dart/valid-data",
			records: 2,
			src: `package probe

enum Grade
{
    Bronze
    Silver
    Gold
}

fixed table T
{
    a int32 = 7
    b float32 = 0.0
    g Grade = Silver
}
`,
			body: `  check(values[0].a == 7, 'the fresh a = ${values[0].a}, want 7');
  check(values[0].b == 0.0, 'the fresh b = ${values[0].b}, want 0.0');
  check(values[0].g == 2, 'the fresh enum default = ${values[0].g}, want Silver (2)');
  values[1].a = -2147483648;
  values[1].b = 3.5;
  values[1].g = 3;
`,
			checks: `  check(back[0].a == 7 && back[0].b == 0.0 && back[0].g == 2,
      'the declared defaults did not round trip: ${back[0].a} ${back[0].b} ${back[0].g}');
  check(back[1].a == -2147483648, 'the int32 floor landed ${back[1].a}');
  check(back[1].b == 3.5, 'a non-default float landed ${back[1].b}');
  check(back[1].g == 3, 'the non-default variant landed ${back[1].g}');
`,
			want: []string{
				"int a = 7;",
				"int g = Grade.silver;",
				"value.a = 7;",
			},
		},

		{
			// text-bytes-flags-defaults/dart/valid-data: "String, byte-buffer
			// and flags defaults: valid-data write/read acceptance" (contract
			// "ALGORITHM §3 prefill"). The declared string, byte-buffer and
			// flags defaults ride as the template's bytes; the round trip
			// lands text at capacity, bytes at every boundary value and the
			// empty boundary exact.
			id:      "text-bytes-flags-defaults/dart/valid-data",
			records: 3,
			src: `package probe

flags Caps
{
    Jump
    Crouch
    Prone
}

fixed table T
{
    name string(16) = "untitled"
    tag  bytes(4) = "ab"
    caps Caps = { Jump, Crouch }
}
`,
			body: `  check(values[0].nameLength == 8, 'the fresh name length = ${values[0].nameLength}, want 8');
  check(values[0].tagLength == 2, 'the fresh tag length = ${values[0].tagLength}, want 2');
  check(values[0].caps == 3, 'the fresh flags mask = ${values[0].caps}, want 3');
  values[1].nameLength = 16;
  for (var i = 0; i < 16; i++) {
    values[1].name[i] = 0x41 + i;
  }
  values[1].tagLength = 4;
  values[1].tag[0] = 0x00;
  values[1].tag[1] = 0xff;
  values[1].tag[2] = 0x7f;
  values[1].tag[3] = 0x80;
  values[1].caps = 7;
  values[2].nameLength = 0;
  values[2].tagLength = 0;
  values[2].caps = 0;
`,
			checks: `  check(back[0].nameLength == 8 && back[0].name[0] == 0x75 && back[0].name[7] == 0x64,
      'the declared string default did not round trip: ${back[0].nameLength}');
  check(back[0].tagLength == 2 && back[0].tag[0] == 0x61 && back[0].tag[1] == 0x62,
      'the declared byte-buffer default did not round trip: ${back[0].tagLength}');
  check(back[0].caps == 3, 'the declared flags default did not round trip: ${back[0].caps}');
  check(back[1].nameLength == 16 && back[1].name[0] == 0x41 && back[1].name[15] == 0x50,
      'text at capacity did not round trip: ${back[1].nameLength}');
  check(back[1].tagLength == 4 && back[1].tag[1] == 0xff && back[1].tag[2] == 0x7f && back[1].tag[3] == 0x80,
      'the byte-buffer boundary values did not round trip: ${back[1].tag}');
  check(back[1].caps == 7, 'all flags did not round trip: ${back[1].caps}');
  check(back[2].nameLength == 0 && back[2].tagLength == 0 && back[2].caps == 0,
      'the empty boundary did not round trip: ${back[2].nameLength} ${back[2].tagLength} ${back[2].caps}');
`,
			want: []string{
				"int nameLength = 8;",
				"int tagLength = 2;",
				"int caps = 3;",
			},
		},
	}

	for _, row := range rows {
		t.Run(row.id, func(t *testing.T) {
			t.Parallel()
			u := unitFrom(t, row.src)
			files, err := Generate(u)
			if err != nil {
				t.Fatalf("%s: generate: %v", row.id, err)
			}
			var all strings.Builder
			for _, data := range files {
				all.Write(data)
			}
			for _, w := range row.want {
				if !strings.Contains(all.String(), w) {
					t.Fatalf("%s: the generated Dart does not carry %q", row.id, w)
				}
			}
			t09Capability(t, row.src, row.body, row.checks, row.records)
		})
	}
}
