package darttable

// EVERY DEAD BYTE IN A FIXED RECORD IS ZERO, and a non-zero one refuses the
// whole load (docs/rulings.json fixed-dead-bytes-are-zero;
// docs/FIXED-FORM-ALGORITHM.md §3.1, §4.5, §5.3 step 11; docs/SPEC-TABLES.md
// §3.4, §13.10). The dead bytes are an absent optional's payload, a counted
// array's slots past its count, a string(N)'s or bytes(N)'s bytes past its
// used length, and an inactive union arm: the bytes under tag 0 and the bytes
// past a narrower taken arm. The shared vectors carry one changed dead region
// each and their all-zero controls; the verdict is the contract and the
// refusal's name is this leg's own diagnostic, so the refusal's reason is
// never compared.

import (
	"fmt"
	"maps"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/codegen/dart"
	"github.com/mas-bandwidth/schema/v2/internal/fixedvector"
	"github.com/mas-bandwidth/schema/v2/internal/slowtest"
	"github.com/mas-bandwidth/schema/v2/ir"
)

func TestFixedDeadBytesAreZero(t *testing.T) {
	slowtest.Gate(t, "dart (it runs the generated reader over the dead-byte corpus)")
	corpus := fixedCorpus(t)
	dartBin := dartBinary(t)
	for _, vec := range fixedvector.DeadBytes {
		t.Run(vec.Name, func(t *testing.T) {
			t.Parallel()
			runDeadVectorAt(t, dartBin, corpus, vec)
		})
	}
}

// deadVectorByFile answers the shared dead-byte vector a corpus row names.
func deadVectorByFile(file string) (fixedvector.DeadVector, bool) {
	for _, vec := range fixedvector.DeadBytes {
		if vec.File == file {
			return vec, true
		}
	}
	return fixedvector.DeadVector{}, false
}

// runDeadVectorAt reads one dead-byte vector through the generated DeadRoot
// reader: a changed file refuses whole and lands nothing; a control reads and
// saves back the writer's bytes.
func runDeadVectorAt(t *testing.T, dartBin, corpus string, vec fixedvector.DeadVector) {
	t.Helper()
	file := filepath.Join(corpus, vec.File)
	var body string
	if vec.Reads {
		// THE CONTROL: every dead byte zero, so the record reads and saves
		// back the writer's own bytes.
		body = `  final data = File(FILE).readAsBytesSync();
  final n = LOAD(values, values.length, data, data.length, plan, report);
  check(n == 1, 'the control reads one record: n=$n ${why(report)}');
  check(report.refused == t.TableFixedRefusal.none,
      'the control moves no refusal: ${why(report)}');
  final back = Uint8List(t.deadRootFixedMeasure(1));
  final wrote = t.deadRootFixedSave(values, 1, back);
  check(wrote == back.length, 'the control saves $wrote of ${back.length}');
  check(back.length == data.length,
      'the control saves ${back.length} bytes, the file holds ${data.length}');
  for (var i = 0; i < back.length; i++) {
    check(back[i] == data[i], 'the control saves byte $i back: '
        '${back[i]} != ${data[i]}');
  }`
	} else {
		// A CHANGED FILE: one dead region is non-zero, and the whole load
		// refuses without landing a record.
		body = `  final data = File(FILE).readAsBytesSync();
  final n = LOAD(values, values.length, data, data.length, plan, report);
  check(n == -1, 'a non-zero dead byte refuses the whole load: '
      'n=$n ${why(report)}');
  check(fresh(values[0]), 'a refused read lands nothing: ${why(report)}');
  check(report.unknown == 0 && report.widened == 0,
      'a refusal moves no counter: ${why(report)}');`
	}
	out, err := runDeadBytesProbe(t, dartBin, file, body)
	if err != nil {
		t.Fatalf("%s: %v\n%s", vec.File, err, out)
	}
	t.Logf("%s", out)
}

// runDeadBytesProbe generates the DeadBytes unit with this leg's own emitter,
// writes one generated probe beside it, and runs it with the leg's toolchain.
// The reader is the unit's DeadRoot and its own identity layout: the corpus
// files were written by that same declaration, and every vector is one changed
// dead region of it.
func runDeadBytesProbe(t *testing.T, dartBin, file, body string) (string, error) {
	slowtest.Gate(t, "an external toolchain")

	t.Helper()
	u := versionSchema(t, "DeadBytes")
	var st *ir.Struct
	for _, root := range ir.TableFixedRoots(u) {
		if root.Name == "DeadRoot" {
			st = root
			break
		}
	}
	if st == nil {
		t.Fatal("DeadBytes.schema declares no DeadRoot")
	}
	files, err := dart.Generate(u)
	if err != nil {
		t.Fatalf("generate packet: %v", err)
	}
	tables, err := Generate(u)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	maps.Copy(files, tables)
	dir := t.TempDir()
	for name, data := range files {
		if strings.Contains(name, "/") {
			continue
		}
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	lower := lowerFirst(st.Name)
	src := strings.NewReplacer(
		"FILE", fmt.Sprintf("%q", file),
		"LOAD", "t."+lower+"FixedLoad",
	).Replace(body)
	probe := fmt.Sprintf(`// GENERATED BY internal/codegen/darttable/fixeddeadbytes_test.go — one probe per
// dead-byte vector (docs/FIXED-FORM-ALGORITHM.md §5.9 #18).
import 'dart:io';
import 'dart:typed_data';

import './%sFixed.dart' as t;

void check(bool ok, String what) {
  if (!ok) {
    stderr.writeln('FAIL: $what');
    exitCode = 1;
  }
}

String name(int refused) => t.TableFixedRefusal.name(refused);

String why(t.TableFixedReport r) =>
    'refused=${name(r.refused)} '
    'unknown=${r.unknown} widened=${r.widened} layoutHash=${r.layoutHash}';

// A FRESH VALUE's every field, compared as VALUES (§5.9 #17).
bool fresh(t.%[2]s value) {
  final want = t.%[2]s();
  t.init%[2]s(want);
  return '$value' == '$want' || _same(value, want);
}

bool _same(t.%[2]s a, t.%[2]s b) {
  final bytes = Uint8List(t.%[3]sFixedBodyBytes);
  final other = Uint8List(t.%[3]sFixedBodyBytes);
  t.%[3]sFixedWriteBody(bytes, ByteData.sublistView(bytes), 0, a);
  t.%[3]sFixedWriteBody(other, ByteData.sublistView(other), 0, b);
  for (var i = 0; i < bytes.length; i++) {
    if (bytes[i] != other[i]) {
      return false;
    }
  }
  return true;
}

void main() {
  final values = <t.%[2]s>[for (var i = 0; i < 8; i++) t.%[2]s()];
  for (final v in values) {
    t.init%[2]s(v);
  }
  final plan = t.%[3]sFixedNewPlan();
  final report = t.TableFixedReport();
%[4]s
  if (exitCode == 0) {
    stdout.writeln('ok');
  }
}
`, "DeadBytes", st.Name, lower, src)
	if home := runtimeHome(u); home != "DeadBytes" {
		probe = strings.Replace(probe, "import './DeadBytesFixed.dart' as t;",
			"import './DeadBytesFixed.dart' as t;\nimport './"+home+"Fixed.dart' as t;", 1)
	}
	if err := os.WriteFile(filepath.Join(dir, "probe.dart"), []byte(probe), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(dartBin, "--enable-asserts", "probe.dart")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	return string(out), err
}
