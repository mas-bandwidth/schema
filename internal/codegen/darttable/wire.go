// THE ID-TABLE WIRE (docs/SPEC-TABLES.md §3): the form byte, sixty-four-bit
// identity, canonical LEB128 and the id table a reader finds from the END.
//
// This file is the FIRST SLICE of schema#514's port to Dart: the wire's
// DATA — every table's name id and every field's id and kind, at sixty-four
// bits and canonical shape — plus the unit's one runtime home. The measure,
// save, load and text codecs ride on top of it; the descriptors below are what
// they read, and they are generated from ir's own wire identity so a
// disagreement with the C++ reference shows as a byte, not as a comment.
package darttable

import (
	"fmt"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

// wireGen emits one Dart library of the wire surface: the unit's runtime home
// carries the runtime, and every file that declares a table carries that
// table's descriptor and its entry points.
type wireGen struct {
	unit     *ir.Unit
	file     *ir.File
	home     bool
	homeBase string
	typed    bool // this library names a Dart typed-data spelling
	body     strings.Builder
	imports  map[string]map[string]bool
}

func (g *wireGen) pf(format string, args ...any) {
	fmt.Fprintf(&g.body, format, args...)
}

func (g *wireGen) need(library, symbol string) {
	if g.imports[library] == nil {
		g.imports[library] = map[string]bool{}
	}
	g.imports[library][symbol] = true
}

// generateWireFiles emits <Base>Table.dart for every unit file that declares a
// table, plus the unit's one wire runtime home. The runtime defines the form
// byte, the identity, the LEB128 pair and the descriptors; a file that is not
// the home imports them.
func generateWireFiles(u *ir.Unit) (map[string][]byte, error) {
	out := map[string][]byte{}
	home := runtimeHome(u)
	written := false
	for _, f := range u.Files {
		g := &wireGen{unit: u, file: f, home: f.Base == home,
			homeBase: home, imports: map[string]map[string]bool{}}
		if g.home {
			g.emitRuntime()
			written = true
		}
		for _, t := range f.Tables {
			g.emitWireTable(t)
		}
		if g.body.Len() > 0 {
			out[f.Base+"Table.dart"] = g.assemble()
		}
	}
	if !written {
		g := &wireGen{unit: u, home: true, homeBase: home,
			imports: map[string]map[string]bool{}}
		g.emitRuntime()
		out[home+"Table.dart"] = g.assemble()
	}
	return out, nil
}

func (g *wireGen) assemble() []byte {
	var h strings.Builder
	if g.file == nil {
		fmt.Fprintf(&h, "// Code generated by the schema compiler for package %s. DO NOT EDIT.\n", g.unit.Package)
	} else {
		fmt.Fprintf(&h, "// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", g.file.Base)
	}
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&h, "// package %s — the ID-TABLE WIRE (docs/SPEC-TABLES.md §3).\n\n", g.unit.Package)
	if g.typed || g.home {
		h.WriteString("import 'dart:typed_data';\n\n")
	}
	if !g.home {
		g.need(g.homeBase+"Table.dart", "")
	}
	for _, base := range sortedKeys(g.imports) {
		syms := g.imports[base]
		if syms == nil || len(syms) == 0 {
			fmt.Fprintf(&h, "import '%s';\n", base)
			continue
		}
		names := sortedKeys(syms)
		one := fmt.Sprintf("import '%s' show %s;", base, strings.Join(names, ", "))
		if len(one) <= 80 {
			h.WriteString(one + "\n")
			continue
		}
		fmt.Fprintf(&h, "import '%s'\n    show\n", base)
		for i, n := range names {
			sep := ","
			if i == len(names)-1 {
				sep = ";"
			}
			fmt.Fprintf(&h, "        %s%s\n", n, sep)
		}
	}
	if len(g.imports) > 0 {
		h.WriteString("\n")
	}
	h.WriteString(strings.Trim(g.body.String(), "\n"))
	h.WriteString("\n")
	return []byte(h.String())
}

// emitRuntime writes the unit's one wire runtime: the form byte, the reserved
// node-table id, fnv1a64, the canonical LEB128 pair, and the descriptor,
// report and id-table classes every codec reads.
func (g *wireGen) emitRuntime() {
	g.pf("%s", wireRuntimeSource())
}

// emitWireTable writes one table's wire descriptor and its entry points.
func (g *wireGen) emitWireTable(st *ir.Struct) {
	name := dartName(st.Name)
	g.typed = true
	g.pf("/// %s's wire descriptor (§3): its name id and every field's id and kind,\n", st.Name)
	g.pf("/// at sixty-four bits, in declaration order.\n")
	g.pf("const TableWireInfo %sWire = TableWireInfo(\n", name)
	g.pf("  %q,\n", st.Name)
	g.pf("  0x%016X,\n", ir.TableWireId(st.WireName()))
	g.pf("  <TableWireFieldInfo>[\n")
	for _, f := range st.Fields {
		isArray := f.Array != ir.ArrayNone || f.KeyEnum != ""
		g.pf("    TableWireFieldInfo(%q, 0x%016X, %d, %v),\n",
			f.Name, ir.TableFieldWireId(f), tableScalarKind(f), isArray)
	}
	g.pf("  ],\n")
	g.pf("  %d,\n", ir.TableWireIdCapacity(g.unit))
	g.pf(");\n\n")
	g.pf("/// %s's exact wire size, measured before it rides — a length cannot be\n", st.Name)
	g.pf("/// patched in place on this form (§3).\n")
	g.pf("int %sLoadMeasure() => tableEmptyMeasure(%sWire);\n\n", name, name)
	g.pf("/// %s's body, framed by the form byte and the trailing id table (§3).\n", st.Name)
	g.pf("Uint8List %sSave() => tableEmptySave(%sWire);\n\n", name, name)
}

// wireRuntimeSource is the unit's one wire runtime, emitted verbatim into the
// runtime home. It carries the form byte the reader checks FIRST, the reserved
// node-table id, the identity every vocabulary shares, the canonical LEB128
// pair a non-minimal spelling is malformed for, and the descriptor the codecs
// read.
func wireRuntimeSource() string {
	return `// THE ID-TABLE WIRE'S RUNTIME (docs/SPEC-TABLES.md §3): the form byte, the
// reserved node-table id, the fnv1a64 identity, canonical LEB128 and the
// trailing id table. A Dart library is a FILE, so this runtime is DEFINED once
// in the unit's home and IMPORTED by every <Base>Table.dart beside it.

/// The VARIABLE FORM's form byte, read FIRST (§3). A byte this reader does not
/// know is a REFUSAL by name, never damage.
const int tableForm = 1;

/// The reserved node-table id (§3.1): the id the node table's field rides
/// under, and the one id the language holds back (§5).
const int tableReservedId = 0xFFFFFFFFFFFFFFFF;

/// fnv1a64 of a name: a field's id, an enum variant's, a union arm's and a
/// table's own name id are all this one function, no fold and no rebound (§5).
int tableFnv1a64(String name) {
  var h = 0xcbf29ce484222325;
  for (var i = 0; i < name.length; i++) {
    h = (h ^ name.codeUnitAt(i)) & 0xFFFFFFFFFFFFFFFF;
    h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF;
  }
  return h;
}

/// The byte width of a canonical LEB128 spelling of a non-negative value (§3).
int tableLebBytes(int value) {
  var v = value;
  var n = 1;
  while (v >= 0x80) {
    v >>= 7;
    n++;
  }
  return n;
}

/// Append a canonical LEB128 spelling at offset, answering the next offset. A
/// non-minimal spelling is malformed, so there is exactly one spelling.
int tablePutLeb(Uint8List out, int offset, int value) {
  var v = value;
  while (v >= 0x80) {
    out[offset++] = (v & 0x7f) | 0x80;
    v >>= 7;
  }
  out[offset++] = v;
  return offset;
}

/// Read a canonical LEB128 at offset, answering the value and the next offset.
(int, int) tableGetLeb(Uint8List buffer, int offset) {
  var value = 0;
  var shift = 0;
  while (true) {
    final byte = buffer[offset++];
    value |= (byte & 0x7f) << shift;
    if (byte & 0x80 == 0) {
      return (value, offset);
    }
    shift += 7;
  }
}

/// A wire field's descriptor: its name, its fnv1a64 id, its kind, and whether
/// it is an array (§3).
final class TableWireFieldInfo {
  final String name;
  final int id;
  final int kind;
  final bool array;
  const TableWireFieldInfo(this.name, this.id, this.kind, this.array);
}

/// A table's wire descriptor: its own name id, its fields in declaration
/// order, and the capacity of the id table a save declares (§3).
final class TableWireInfo {
  final String name;
  final int id;
  final List<TableWireFieldInfo> fields;
  final int idCapacity;
  const TableWireInfo(this.name, this.id, this.fields, this.idCapacity);
}

/// A read report (§3, §4.2): a verdict beside the counters. A byte the reader
/// does not know is a REFUSAL by name, never damage.
final class TableReport {
  int form = 0;
  String verdict = 'ok';
  bool get refused => verdict != 'ok';
  int fields = 0;
  int ids = 0;
  int bytes = 0;
}

/// The writer's id table: every id the body used, once each, in first-use
/// order, named by a 1-based reference; reference 0 names no id (§3).
final class TableIds {
  final List<int> entries = <int>[];

  int reference(int id) {
    for (var i = 0; i < entries.length; i++) {
      if (entries[i] == id) {
        return i + 1;
      }
    }
    entries.add(id);
    return entries.length;
  }
}

/// The exact wire size of an EMPTY body of info: the form byte, the
/// zero-reference terminator, and the eight-byte empty entry count (§3).
int tableEmptyMeasure(TableWireInfo info) => 1 + 1 + 8;

/// An EMPTY body of info, framed by the form byte and the trailing id table,
/// which holds no id because the body named none (§3).
Uint8List tableEmptySave(TableWireInfo info) {
  final out = Uint8List(tableEmptyMeasure(info));
  var at = 0;
  out[at++] = tableForm;
  out[at++] = 0; // the zero reference terminates the body
  for (var i = 0; i < 8; i++) {
    out[at++] = 0; // the final eight bytes are the entry count, a fixed u64
  }
  return out;
}
`
}
