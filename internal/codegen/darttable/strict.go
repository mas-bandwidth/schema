package darttable

import (
	"fmt"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

// generateStrictFiles emits <Home>Strict.dart: THE STRICT READ of every
// variable-form root (docs/SPEC-TABLES.md §6.5), beside the tolerant
// <root>WireLoad it runs. The strict read answers the value, or the ONE typed
// reason the strict rule refuses it with, as a TableRefuseReason: the
// vocabulary the cook's and the block's openWithReason answer in, from the one
// library of the unit that declares it. The variable-form library itself stays
// standalone (it names no accelerator), so the strict read is its own library
// over the two: <Home>Wire.dart for the load and the report, and the
// accelerator home for the enum, which this library re-exports.
//
// accelerators is the unit's generated block and cook libraries; a unit with
// no variable-form root, or no library declaring the enum, has no strict read.
func generateStrictFiles(u *ir.Unit, accelerators map[string][]byte) map[string][]byte {
	if len(variableRoots(u)) == 0 {
		return map[string][]byte{}
	}
	home := runtimeHome(u)
	reasonHome := ""
	for _, name := range []string{home + "Block.dart", home + "Cook.dart"} {
		if strings.Contains(string(accelerators[name]), "\nenum TableRefuseReason {") {
			reasonHome = name
			break
		}
	}
	if reasonHome == "" {
		return map[string][]byte{}
	}
	var b strings.Builder
	pf := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	pf("// Code generated by the schema compiler for package %s. DO NOT EDIT.\n", u.Package)
	pf("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	pf("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	pf("// AGPL-3.0, its output is not.\n")
	pf("// package %s — THE STRICT READ (docs/SPEC-TABLES.md §6.5): one call per\n", u.Package)
	pf("// variable-form root that answers the value, or the one typed reason the\n")
	pf("// strict rule refuses it with. <root>WireLoad beside it is the tolerant read.\n\n")
	pf("import 'dart:typed_data';\n\n")
	pf("import '%s' show TableRefuseReason;\n", reasonHome)
	pf("import '%sWire.dart';\n\n", home)
	pf("export '%s' show TableRefuseReason;\n\n", reasonHome)
	pf("%s", dartStrictReasonSource)
	for _, st := range wireClosure(u) {
		if !st.IsTable || st.IsMapEntry() {
			continue
		}
		n := st.Name
		fn := dartName(n)
		pf("\n// %sWireReadStrict is the STRICT read of a whole %s file (§6.5): the\n", fn, n)
		pf("// value and ok, or null and the one reason TableWireReport.err() decides.\n")
		pf("// A report handed in is reset first and holds this read's report after.\n")
		pf("(%s?, TableRefuseReason) %sWireReadStrict(\n", n, fn)
		pf("  Uint8List data, [\n  TableWireReport? report,\n]) {\n")
		pf("  final r = report ?? TableWireReport();\n")
		pf("  if (report != null) r.reset();\n")
		pf("  final value = %sWireLoad(data, r);\n", fn)
		pf("  final why = r.err();\n")
		pf("  return why == null ? (value, TableRefuseReason.ok) : (null, why);\n")
		pf("}\n")
	}
	return map[string][]byte{home + "Strict.dart": []byte(b.String())}
}

// dartStrictReasonSource is THE STRICT READ'S ONE TYPED REASON
// (docs/SPEC-TABLES.md §6.5 "Strict error identity", §11), decided from the
// variable-form report in the reference precedence: a form byte the read does
// not carry is unknown_form whichever form it is; then integrity_mismatch, a
// non-finite float, any damage as wire_damaged, a builder storage refusal by
// its own name, a blob named from two slots, clamped and kind_mismatch.
// Unknown, widened, retained and duplicate alone never refuse. A missing
// required field has no member in the closed vocabulary (Go carries it as the
// typed TableMissingRequired, beside the enum): the read is refused as
// wire_damaged, as the C++ reference's strict read answers it, and
// missingFields names the fields.
const dartStrictReasonSource = `// THE STRICT READ'S ONE TYPED REASON (docs/SPEC-TABLES.md §6.5, §11): null
// when the strict rule accepts the read this report describes, else the one
// reason it refuses. A form byte the read does not carry is unknown_form; then
// integrity_mismatch, non_finite_float, any damage as wire_damaged (a missing
// required field among it, named in missingFields), count_over_extent_cap,
// blob_shared, clamped and kind_mismatch, in that order. unknown, widened,
// retained and duplicate alone never refuse.
extension TableWireStrict on TableWireReport {
  TableRefuseReason? err() {
    if (refused &&
        !countRefused &&
        missingFields.isEmpty &&
        nonFiniteFloat.isEmpty) {
      return TableRefuseReason.unknownForm;
    }
    if (integrityMismatch) return TableRefuseReason.integrityMismatch;
    if (nonFiniteFloat.isNotEmpty) return TableRefuseReason.nonFiniteFloat;
    if (malformed || missingFields.isNotEmpty) {
      return TableRefuseReason.wireDamaged;
    }
    if (countRefused) return TableRefuseReason.countOverExtentCap;
    if (blobShared > 0) return TableRefuseReason.blobShared;
    if (clamped > 0) return TableRefuseReason.clamped;
    if (kindMismatch > 0) return TableRefuseReason.kindMismatch;
    return null;
  }
}
`
