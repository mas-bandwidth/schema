// t08DartBinary is THE LEG'S OWN TOOLCHAIN, the same chain dartBinary holds,
// plus the PATH's `dart` as the last fallback so a self-contained round-trip
// runs on a bench that never unpacked dist/. A bare `go test ./...` on a tree
// with no dart anywhere still skips, which is the package's standing rule.
func t08DartBinary(t *testing.T) string {
	t.Helper()
	if env := os.Getenv("DART"); env != "" {
		return env
	}
	if dist, err := filepath.Abs("../../../dist/dart-sdk-3.13.2/bin/dart"); err == nil {
		if _, err := os.Stat(dist); err == nil {
			return dist
		}
	}
	if p, err := exec.LookPath("dart"); err == nil {
		return p
	}
	t.Skip("the Dart SDK is not unpacked in dist/ and dart is not on PATH: see make/dart.mk")
	return ""
}

// t08RoundTrip generates ONE fixed unit from an inline schema and runs a probe
// over it with the leg's own toolchain: the probe writes values, reads them
// back through the generated load, and (where the body says so) writes again
// to prove the bytes are IDENTICAL. It is generated, never hand-written, and it
// needs no corpus file: the probe's own write is the oracle the read is held
// to, which is the round-trip half of interoperability that does not ride the
// C++ reference's bytes.
func t08RoundTrip(t *testing.T, dartBin, src, body string) {
	t.Helper()
	u := unitFrom(t, src)
	files, err := Generate(u)
	if err != nil {
		t.Fatalf("generate fixed: %v", err)
	}
	pkt, err := dart.Generate(u)
	if err != nil {
		t.Fatalf("generate packet: %v", err)
	}
	for name, data := range pkt {
		files[name] = data
	}
	dir := t.TempDir()
	for name, data := range files {
		if strings.Contains(name, "/") {
			continue
		}
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	probe := `// GENERATED BY internal/codegen/darttable/fixedroadmap_t08_test.go — one probe
// per capability, a write/read round trip held to the probe's own write.
import 'dart:io';
import 'dart:typed_data';

import './ProbeFixed.dart' as t;

void check(bool ok, String what) {
  if (!ok) {
    stderr.writeln('FAIL: $what');
    exitCode = 1;
  }
}

String why(t.TableFixedReport r) =>
    'refused=${t.TableFixedRefusal.name(r.refused)} malformed=${r.malformed} '
    'unknown=${r.unknown} kind=${r.kindMismatch} clamped=${r.clamped} '
    'widened=${r.widened} duplicate=${r.duplicate}';

void main() {
` + body + `
  if (exitCode == 0) {
    stdout.writeln('ok');
  }
}
`
	if err := os.WriteFile(filepath.Join(dir, "main_probe.dart"), []byte(probe), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(dartBin, "--enable-asserts", "main_probe.dart")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("round-trip probe failed: %v\n%s", err, out)
	}
}

