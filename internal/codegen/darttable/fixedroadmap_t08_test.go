package darttable

// THE DART LEG'S CONFORMANCE ROWS FOR THE UNION WAVE (docs/roadmap.sexp node
// `fixed-tables`, rows plan-execution, interoperability, hostile-input,
// signed-integers, unsigned-integers, flags-values, union-field-arms,
// payload-free-arms, union-arrays). Each subtest is one roadmap task id and
// implements the page sentence its comment quotes.
//
// The tasks already held by an existing test are named there and add nothing
// here: dart/P1 by TestFixedFormFU1FU2OnePath (the one-path load, identity and
// compiled are one loop, no `if (identity)` door), dart/W13 by
// TestFixedLayoutMatchesReference (the layout and its fnv1a64 hash equal the
// C++ reference's constants), dart/P4 by the versioning negative control
// `make tables-dart-versioning-negative-control` (the wrong refusal name reds
// OLD-REFUSES-NEW) and `make tables-dart-fixed-form-negative-control` (one byte
// off the write template reds the byte match).
//
// dart/R27, dart/P3 and the three union capabilities (union-field-arms,
// payload-free-arms, union-arrays) are NOT asserted here, each for its own
// named reason. R27 and P3 read the C++ reference's byte oracle
// (`build/fixedform-corpus/manifest.txt`), which the build writes only from
// `test/tables/fixedform_dump.cpp` against the `../serialize` sibling runtime
// that this checkout does not carry. payload-free-arms is refused: a void arm
// has no storage the shared layout walk can name (ir/fixedform.go
// `TableFixedSupported` returns false at `v.F == nil`), so no fixed form is
// emitted for one. union-field-arms and union-arrays are EMITTED but do not
// COMPILE: the fixed form writes and decodes a scalar field arm and an array
// of a scalar-armed union through its loop, yet its storage class
// (`final Value v = Value()`, `List<Shape>`) names a union class no emitter
// declares — a table-closure union lives in `TableUnions`, which the packet
// emitter (the one that declares type-armed unions) never walks — so the probe
// fails `Type 'Value' not found`. That gap, not a named refusal, is what these
// two union rows wait on; it is named in the verdicts, not decided here.

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/codegen/dart"
)

// t08DartBinary is THE LEG'S OWN TOOLCHAIN, the same chain dartBinary holds,
// plus the PATH's `dart` as the last fallback so a self-contained round-trip
// runs on a bench that never unpacked dist/. A bare `go test ./...` on a tree
// with no dart anywhere still skips, which is the package's standing rule.
func t08DartBinary(t *testing.T) string {
	t.Helper()
	if env := os.Getenv("DART"); env != "" {
		return env
	}
	if dist, err := filepath.Abs("../../../dist/dart-sdk-3.13.2/bin/dart"); err == nil {
		if _, err := os.Stat(dist); err == nil {
			return dist
		}
	}
	if p, err := exec.LookPath("dart"); err == nil {
		return p
	}
	t.Skip("the Dart SDK is not unpacked in dist/ and dart is not on PATH: see make/dart.mk")
	return ""
}

// t08RoundTrip generates ONE fixed unit from an inline schema and runs a probe
// over it with the leg's own toolchain: the probe writes values, reads them
// back through the generated load, and (where the body says so) writes again
// to prove the bytes are IDENTICAL. It is generated, never hand-written, and it
// needs no corpus file: the probe's own write is the oracle the read is held
// to, which is the round-trip half of interoperability that does not ride the
// C++ reference's bytes.
func t08RoundTrip(t *testing.T, dartBin, src, body string) {
	t.Helper()
	u := unitFrom(t, src)
	files, err := Generate(u)
	if err != nil {
		t.Fatalf("generate fixed: %v", err)
	}
	pkt, err := dart.Generate(u)
	if err != nil {
		t.Fatalf("generate packet: %v", err)
	}
	for name, data := range pkt {
		files[name] = data
	}
	dir := t.TempDir()
	for name, data := range files {
		if strings.Contains(name, "/") {
			continue
		}
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	probe := `// GENERATED BY internal/codegen/darttable/fixedroadmap_t08_test.go — one probe
// per capability, a write/read round trip held to the probe's own write.
import 'dart:io';
import 'dart:typed_data';

import './ProbeFixed.dart' as t;

void check(bool ok, String what) {
  if (!ok) {
    stderr.writeln('FAIL: $what');
    exitCode = 1;
  }
}

String why(t.TableFixedReport r) =>
    'refused=${t.TableFixedRefusal.name(r.refused)} malformed=${r.malformed} '
    'unknown=${r.unknown} kind=${r.kindMismatch} clamped=${r.clamped} '
    'widened=${r.widened} duplicate=${r.duplicate}';

void main() {
` + body + `
  if (exitCode == 0) {
    stdout.writeln('ok');
  }
}
`
	if err := os.WriteFile(filepath.Join(dir, "main_probe.dart"), []byte(probe), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(dartBin, "--enable-asserts", "main_probe.dart")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("round-trip probe failed: %v\n%s", err, out)
	}
}

func TestFixedRoadmapDartT08ConformanceUnions(t *testing.T) {
	t.Parallel()

	// signed-integers/dart/valid-data [capability] — "Signed integers: 8, 16,
	// 32 and 64 bits: valid-data write/read acceptance" (docs/SPEC-TABLES.md
	// §3.4 record, int8..int64). The leg writes and reads each width at BOTH
	// domain boundaries, minimum and maximum, in one two-record file.
	t.Run("signed-integers/dart/valid-data", func(t *testing.T) {
		t.Parallel()
		t08RoundTrip(t, t08DartBinary(t), `package probe

fixed table Rec
{
    i8  int8
    i16 int16
    i32 int32
    i64 int64
}
`, `
  final lo = t.Rec();
  t.initRec(lo);
  lo.i8 = -128;
  lo.i16 = -32768;
  lo.i32 = -2147483648;
  lo.i64 = -9223372036854775808;
  final hi = t.Rec();
  t.initRec(hi);
  hi.i8 = 127;
  hi.i16 = 32767;
  hi.i32 = 2147483647;
  hi.i64 = 9223372036854775807;
  final bytes = Uint8List(t.recFixedMeasure(2));
  check(t.recFixedSave([lo, hi], 2, bytes) == bytes.length, 'save wrote the whole file');
  final plan = t.recFixedNewPlan();
  final report = t.TableFixedReport();
  final out = [t.Rec(), t.Rec()];
  t.initRec(out[0]);
  t.initRec(out[1]);
  final n = t.recFixedLoad(out, 2, bytes, bytes.length, plan, report);
  check(n == 2 && report.refused == 0 && !report.malformed,
      'the reader refused its own writer: n=$n ${why(report)}');
  check(out[0].i8 == -128 && out[0].i16 == -32768 && out[0].i32 == -2147483648 &&
      out[0].i64 == -9223372036854775808,
      'the int8..int64 minima did not land: ${out[0].i8} ${out[0].i16} ${out[0].i32} ${out[0].i64}');
  check(out[1].i8 == 127 && out[1].i16 == 32767 && out[1].i32 == 2147483647 &&
      out[1].i64 == 9223372036854775807,
      'the int8..int64 maxima did not land: ${out[1].i8} ${out[1].i16} ${out[1].i32} ${out[1].i64}');
`)
	})

	// unsigned-integers/dart/valid-data [capability] — "Unsigned integers: 8,
	// 16, 32 and 64 bits: valid-data write/read acceptance" (docs/SPEC-TABLES.md
	// §3.4 record, uint8..uint64). Each width lands its minimum and its maximum,
	// the 64-bit maximum as the all-ones bit pattern Dart's signed int spells
	// -1 (two's complement).
	t.Run("unsigned-integers/dart/valid-data", func(t *testing.T) {
		t.Parallel()
		t08RoundTrip(t, t08DartBinary(t), `package probe

fixed table Rec
{
    u8  uint8
    u16 uint16
    u32 uint32
    u64 uint64
}
`, `
  final lo = t.Rec();
  t.initRec(lo);
  lo.u8 = 0;
  lo.u16 = 0;
  lo.u32 = 0;
  lo.u64 = 0;
  final hi = t.Rec();
  t.initRec(hi);
  hi.u8 = 255;
  hi.u16 = 65535;
  hi.u32 = 4294967295;
  hi.u64 = -1;
  final bytes = Uint8List(t.recFixedMeasure(2));
  check(t.recFixedSave([lo, hi], 2, bytes) == bytes.length, 'save wrote the whole file');
  final plan = t.recFixedNewPlan();
  final report = t.TableFixedReport();
  final out = [t.Rec(), t.Rec()];
  t.initRec(out[0]);
  t.initRec(out[1]);
  final n = t.recFixedLoad(out, 2, bytes, bytes.length, plan, report);
  check(n == 2 && report.refused == 0 && !report.malformed,
      'the reader refused its own writer: n=$n ${why(report)}');
  check(out[0].u8 == 0 && out[0].u16 == 0 && out[0].u32 == 0 && out[0].u64 == 0,
      'the uint8..uint64 minima did not land');
  check(out[1].u8 == 255 && out[1].u16 == 65535 && out[1].u32 == 4294967295 &&
      out[1].u64 == -1,
      'the uint8..uint64 maxima did not land: ${out[1].u8} ${out[1].u16} ${out[1].u32} ${out[1].u64}');
`)
	})

	// flags-values/dart/valid-data [capability] — "Flags masks: valid-data
	// write/read acceptance" (docs/SPEC-TABLES.md §3.4 record, flags). A flags
	// field rides the fixed form as its 64-bit mask; the leg writes a NONZERO
	// mask (two bits set, not merely the first) and reads it back exactly.
	t.Run("flags-values/dart/valid-data", func(t *testing.T) {
		t.Parallel()
		t08RoundTrip(t, t08DartBinary(t), `package probe

flags Caps { Jump, Crouch, Fly }

fixed table Rec
{
    caps Caps
    seq  int32
}
`, `
  final v = t.Rec();
  t.initRec(v);
  v.caps = 5;
  v.seq = 12345;
  final bytes = Uint8List(t.recFixedMeasure(1));
  check(t.recFixedSave([v], 1, bytes) == bytes.length, 'save wrote the whole file');
  final plan = t.recFixedNewPlan();
  final report = t.TableFixedReport();
  final out = [t.Rec()];
  t.initRec(out[0]);
  final n = t.recFixedLoad(out, 1, bytes, bytes.length, plan, report);
  check(n == 1 && report.refused == 0 && !report.malformed,
      'the reader refused its own writer: n=$n ${why(report)}');
  check(out[0].caps == 5, 'the flags mask did not land: ${out[0].caps}');
  check(out[0].seq == 12345, 'the neighbour did not land: ${out[0].seq}');
`)
	})

	// dart/P2 [verify] "write-read-write byte-identical" — the write is a
	// template at constant offsets, so a read followed by a write of the same
	// value reproduces the SAME bytes, every byte (docs/SPEC-TABLES.md §3.4,
	// THE WRITE: A TEMPLATE). The probe writes, reads, writes again, and holds
	// the second write byte-identical to the first.
	t.Run("dart/P2", func(t *testing.T) {
		t.Parallel()
		t08RoundTrip(t, t08DartBinary(t), `package probe

type Alpha { m int32 }

union Pick
{
    alpha Alpha
}

fixed table Rec
{
    lead  int32
    pick  Pick
    trail int32
}
`, `
  final v = t.Rec();
  t.initRec(v);
  v.lead = 7;
  v.pick.type = 1;
  v.pick.alpha.m = 99;
  v.trail = 13;
  final b1 = Uint8List(t.recFixedMeasure(1));
  check(t.recFixedSave([v], 1, b1) == b1.length, 'save wrote the whole file');
  final plan = t.recFixedNewPlan();
  final report = t.TableFixedReport();
  final out = [t.Rec()];
  t.initRec(out[0]);
  final n = t.recFixedLoad(out, 1, b1, b1.length, plan, report);
  check(n == 1 && report.refused == 0 && !report.malformed,
      'the reader refused its own writer: n=$n ${why(report)}');
  final b2 = Uint8List(t.recFixedMeasure(1));
  check(t.recFixedSave(out, 1, b2) == b2.length, 'the rewrite wrote the whole file');
  for (var i = 0; i < b1.length; i++) {
    check(b1[i] == b2[i], 'write-read-write moved byte $i: ${b1[i]} != ${b2[i]}');
  }
`)
	})

	// dart/P4 [verify] "wrong plan goes red" — SPEC-TABLES §3.4 HELD BY TEST,
	// "THE NEGATIVE CONTROL: A READER GIVEN THE WRONG PLAN FOR A RECORD GOES
	// RED". The probe writes a Good record and runs EVIL's identity plan over
	// Good's body — the exact mistake the hash exists to prevent — and holds
	// that the wrong plan does NOT reproduce the record.
	t.Run("dart/P4", func(t *testing.T) {
		t.Parallel()
		t08RoundTrip(t, t08DartBinary(t), `package probe

fixed table Good
{
    a int32
    b int32
}

fixed table Evil
{
    b int32
    a int32
}
`, `
  final good = t.Good();
  t.initGood(good);
  good.a = 1;
  good.b = 2;
  final file = Uint8List(t.goodFixedMeasure(1));
  check(t.goodFixedSave([good], 1, file) == file.length, 'the good save wrote the whole file');
  final plan = t.evilFixedNewPlan();
  final report = t.TableFixedReport();
  final bodyAt = t.goodFixedHeaderBytes + 8;
  t.tableFixedRun(
    t.evilFixedIdentity,
    t.evilFixedIdentityCount,
    file,
    ByteData.sublistView(file),
    bodyAt,
    plan.image,
    plan.imageView,
    plan.remap,
    plan.conv,
    report,
  );
  final wrong = t.Evil();
  t.initEvil(wrong);
  t.evilFixedDecode(wrong, plan.image, plan.imageView, 0, report);
  check(!(wrong.a == 1 && wrong.b == 2),
      'NEGATIVE CONTROL: the wrong plan must NOT reproduce the record');
  check(wrong.a == 2 && wrong.b == 1,
      'the wrong plan read the reversed fields: a=${wrong.a} b=${wrong.b}');
`)
	})

	// dart/W6 [weak] "plan partition / split" — SPEC-TABLES §3.4, §5.9 #42: the
	// plan partitions its entries, every unguarded one first then every guarded
	// one, the plan states where the second half starts (the split), and
	// coalescing NEVER crosses the split, because a copy that merged a guarded
	// entry into an unguarded run would land the arm's bytes unconditionally.
	t.Run("dart/W6", func(t *testing.T) {
		t.Parallel()
		// Two unguarded, adjacent, advancing copies coalesce into one, and the
		// split is the whole plan (there is no guarded half).
		one, oneSplit := fixedCoalesce([]fixedPlanEntry{
			{op: fixedOpCopy, src: 0, dst: 0, size: 4, guard: fixedNoGuard},
			{op: fixedOpCopy, src: 4, dst: 4, size: 4, guard: fixedNoGuard},
		})
		if len(one) != 1 {
			t.Fatalf("two unguarded advancing copies did not coalesce: %d entries", len(one))
		}
		if oneSplit != len(one) {
			t.Fatalf("a plan with no guarded entry has its split at the END, not at zero (split=%d of %d)", oneSplit, len(one))
		}
		// An unguarded copy followed by a GUARDED one must NOT coalesce: that
		// merge would land the arm's bytes unconditionally. The two differ in
		// guard and nothing else, so the guard check is the only thing that
		// can keep them apart.
		two, twoSplit := fixedCoalesce([]fixedPlanEntry{
			{op: fixedOpCopy, src: 0, dst: 0, size: 4, guard: fixedNoGuard},
			{op: fixedOpCopy, src: 4, dst: 4, size: 4, guard: 0},
		})
		if len(two) != 2 {
			t.Fatal("a guarded copy coalesced across the split: an arm's bytes landed under an unguarded run")
		}
		if twoSplit != 1 {
			t.Fatalf("the split is the number of unguarded entries (split=%d, want 1)", twoSplit)
		}
		// And a real union yields a plan that is PARTITIONED (SPEC-TABLES §3.4,
		// FIXED-FORM-ALGORITHM §4.1/§4.4/§5.9 #42): every unguarded entry first,
		// then every guarded one, and the plan states where the second half
		// starts. `Rec` puts the unguarded `trail` AFTER the union, so a plan
		// pushed in declared order is [unguarded, guarded, unguarded] — the
		// exact shape the reference rejects.
		u := unitFrom(t, `package probe

type Alpha { m int32 }

union Pick
{
    alpha Alpha
}

fixed table Rec
{
    lead  int32
    pick  Pick
    trail int32
}
`)
		st := findTable(t, u, "Rec")
		plan, split := fixedIdentityPlan(st)
		if split <= 0 || split >= len(plan) {
			t.Fatalf("W6: Rec's identity plan really has a guarded half (split=%d of %d), so the case is not vacuous", split, len(plan))
		}
		for i, e := range plan {
			guarded := e.guard != fixedNoGuard
			if i < split && guarded {
				t.Fatalf("W6: entry %d is below the split and carries a GUARD", i)
			}
			if i >= split && !guarded {
				t.Fatalf("W6: entry %d is at/above the split and carries NO guard", i)
			}
		}
		// THE BOUNDARY PAIR: had the coalescer merged across the split, the
		// entry below it and the entry at it would be one. They are two.
		a, b := plan[split-1], plan[split]
		if a.op == fixedOpCopy && b.op == fixedOpCopy && a.guard == b.guard && a.arg == b.arg &&
			a.src+a.size == b.src && a.dst+a.size == b.dst {
			t.Fatal("W6: the pair at the split was coalesced across it")
		}
	})
}
