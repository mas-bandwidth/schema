package darttable

// THE SLOTS PAST A COUNT AFTER ANY LOAD, LAWFUL OR REFUSED (docs/SPEC-TABLES.md
// §3.4; docs/SPEC-CONFORMANCE.md, "Counted-array slots after a lawful fixed
// load"). A load's result never depends on what the value held before: after
// every fixed-form load, on the identity plan and on a lineage plan, every
// element slot past a counted array's live count holds what a fresh value
// holds there. Dart's slots are objects and typed lists the caller's value
// owns, so a decode that walked only the live count kept the previous load's
// elements. The fixture is the legs' one, test/tables/FixedSlack.schema, and
// its header is the recipe this test follows.

import (
	"encoding/binary"
	"fmt"
	"maps"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/codegen/dart"
	"github.com/mas-bandwidth/schema/v2/internal/slowtest"
	"github.com/mas-bandwidth/schema/v2/internal/testproc"
)

// fixedSlackOtherHash masks the lineage entry's hash: this build's own layout
// under a hash that is not this build's, so a file carrying it reads through
// the plan COMPILED from the lock's bytes, and nothing but the plan moves.
const fixedSlackOtherHash = 0x00ff00ff00ff00ff

// fixedSlackFiles generates the FixedSlack unit's packet and fixed libraries,
// with a lineage entry of the same layout under another hash.
func fixedSlackFiles(t *testing.T) (map[string][]byte, uint64) {
	t.Helper()
	u := versionSchema(t, "FixedSlack")
	self, ok := FixedLineageOf(u, "SlackRoot")
	if !ok {
		t.Fatal("no lineage entry for SlackRoot")
	}
	other := self.Wire ^ fixedSlackOtherHash
	files, err := GenerateLineage(u, map[string][]FixedLineageEntry{
		"SlackRoot": {{Wire: other, Layout: self.Layout, Record: self.Record}},
	})
	if err != nil {
		t.Fatalf("generate fixed: %v", err)
	}
	pkt, err := dart.Generate(u)
	if err != nil {
		t.Fatalf("generate packet: %v", err)
	}
	maps.Copy(files, pkt)
	return files, other
}

// TestDartFixedSlackEmitterResetsPastCount is the fast pin: no toolchain. The
// generated decode, which the identity plan and every lineage plan share,
// restores every slot past each counted array's count: a table slot in place
// through its init, a scalar slot to the element's declared default.
func TestDartFixedSlackEmitterResetsPastCount(t *testing.T) {
	t.Parallel()
	files, _ := fixedSlackFiles(t)
	var src string
	for name, data := range files {
		if strings.HasSuffix(name, "Fixed.dart") {
			src += string(data)
		}
	}
	for _, c := range []struct{ fn, want string }{
		{"slackCellFixedDecode", "  for (var i = value.subsCount; i < 2; i++) {\n    initSlackSub(value.subs[i]);\n  }\n"},
		{"slackRootFixedDecode", "  for (var i = value.cellsCount; i < 3; i++) {\n    initSlackCell(value.cells[i]);\n  }\n"},
		{"slackRootFixedDecode", "  if (value.numsCount < 4) {\n    value.nums.fillRange(value.numsCount, 4, 0);\n  }\n"},
	} {
		at := strings.Index(src, "void "+c.fn+"(")
		if at < 0 {
			t.Fatalf("no %s in the generated library", c.fn)
		}
		end := strings.Index(src[at:], "\n}\n")
		if end < 0 {
			t.Fatalf("%s has no end", c.fn)
		}
		if body := src[at : at+end+1]; !strings.Contains(body, c.want) {
			t.Errorf("%s does not reset the slots past its count (§3.4, THE SLOTS PAST A COUNT AFTER ANY LOAD): no\n%s\nin\n%s", c.fn, c.want, body)
		}
	}
}

// TestDartFixedSlackPastCountHoldsDefaults runs FixedSlack.schema's recipe
// under the leg's own dart, on the identity plan and on the compiled lineage
// plan: load A (every array at its bound, every slot 77) into a value, then B
// (every count 1) into THE SAME value, and every slot past every count equals
// a fresh value's slot after B; then a refused load holds the defaults too.
func TestDartFixedSlackPastCountHoldsDefaults(t *testing.T) {
	t.Parallel()
	slowtest.Gate(t, "the Dart SDK (it runs the generated library)")
	dartBin := dartBinary(t)
	files, other := fixedSlackFiles(t)
	dir := t.TempDir()
	for name, data := range files {
		if strings.Contains(name, "/") {
			continue
		}
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	var hash [8]byte
	binary.LittleEndian.PutUint64(hash[:], other)
	var hb []string
	for _, b := range hash {
		hb = append(hb, fmt.Sprint(b))
	}
	probe := fmt.Sprintf(`// GENERATED BY internal/codegen/darttable/fixedslack_test.go
import 'dart:io';
import 'dart:typed_data';

import './FixedSlackFixed.dart' as t;
import './TblslackFixed.dart' as t;

void check(bool ok, String what) {
  if (!ok) {
    stderr.writeln('FAIL: $what');
    exitCode = 1;
  }
}

Uint8List save(t.SlackRoot v) {
  final b = Uint8List(t.slackRootFixedMeasure(1));
  check(t.slackRootFixedSave([v], 1, b) == b.length, 'the save');
  return b;
}

// The same file under the lineage entry's hash, header and record both.
Uint8List lineage(Uint8List bytes) {
  const other = <int>[%s];
  final file = Uint8List.fromList(bytes);
  final rec = file.length - t.slackRootFixedRecordBytes;
  for (var k = 0; k < 8; k++) {
    file[8 + k] = other[k];
    file[rec + k] = other[k];
  }
  return file;
}

t.SlackRoot fresh() {
  final v = t.SlackRoot();
  t.initSlackRoot(v);
  return v;
}

int load(t.SlackRoot v, Uint8List file, t.TableFixedReport report) =>
    t.slackRootFixedLoad([v], 1, file, file.length, t.slackRootFixedNewPlan(), report);

// Every slot past every count of B: cells[1..2] whole, cells[0].subs[1],
// nums[1..3], against a fresh value's slot and the declared defaults.
void slack(String which, t.SlackRoot got, t.SlackRoot want) {
  for (var i = 1; i < 3; i++) {
    final g = got.cells[i], w = want.cells[i];
    check(g.id == w.id && g.id == 7, '$which: cells[$i].id = ${g.id}, fresh ${w.id}, declared 7');
    check(g.subsCount == w.subsCount && g.subsCount == 0,
        '$which: cells[$i].subsCount = ${g.subsCount}, fresh ${w.subsCount}');
    for (var j = 0; j < 2; j++) {
      check(g.subs[j].v == w.subs[j].v && g.subs[j].v == 3,
          '$which: cells[$i].subs[$j].v = ${g.subs[j].v}, fresh ${w.subs[j].v}, declared 3');
    }
  }
  check(got.cells[0].subs[1].v == want.cells[0].subs[1].v && got.cells[0].subs[1].v == 3,
      '$which: cells[0].subs[1].v = ${got.cells[0].subs[1].v}, fresh ${want.cells[0].subs[1].v}, declared 3');
  for (var i = 1; i < 4; i++) {
    check(got.nums[i] == want.nums[i] && got.nums[i] == 0,
        '$which: nums[$i] = ${got.nums[i]}, fresh ${want.nums[i]}, declared 0');
  }
}

void main() {
  final a = fresh();
  a.cellsCount = 3;
  for (var i = 0; i < 3; i++) {
    a.cells[i].id = 77;
    a.cells[i].subsCount = 2;
    for (var j = 0; j < 2; j++) {
      a.cells[i].subs[j].v = 77;
    }
  }
  a.numsCount = 4;
  for (var i = 0; i < 4; i++) {
    a.nums[i] = 77;
  }
  final b = fresh();
  b.cellsCount = 1;
  b.cells[0].id = 77;
  b.cells[0].subsCount = 1;
  b.cells[0].subs[0].v = 77;
  b.numsCount = 1;
  b.nums[0] = 77;
  final fileA = save(a), fileB = save(b);
  for (var path = 0; path < 2; path++) {
    final which = path == 0 ? 'identity' : 'lineage';
    final fa = path == 0 ? fileA : lineage(fileA);
    final fb = path == 0 ? fileB : lineage(fileB);
    final report = t.TableFixedReport();
    final want = fresh();
    check(load(want, fb, report) == 1, '$which: a fresh value reads B: refused=${report.refused}');
    final v = fresh();
    check(load(v, fa, report) == 1, '$which: A reads: refused=${report.refused}');
    check(v.cells[2].id == 77 && v.nums[3] == 77, '$which: A did not land its slots');
    check(load(v, fb, report) == 1, '$which: B reads: refused=${report.refused}');
    check(v.cellsCount == 1 && v.cells[0].id == 77 && v.cells[0].subsCount == 1 &&
        v.cells[0].subs[0].v == 77 && v.numsCount == 1 && v.nums[0] == 77,
        '$which: B did not land its live values');
    slack('$which A then B', v, want);
    // A REFUSED LOAD holds the declared defaults too: A lands, then B with a
    // non-zero dead byte (nums[3]'s last byte) refuses damaged.
    final r = fresh();
    check(load(r, fa, report) == 1, '$which: A reads before the refusal');
    final bad = Uint8List.fromList(fb);
    bad[bad.length - 1] = 0x55;
    check(load(r, bad, report) == -1 && report.refused == t.TableFixedRefusal.damaged,
        '$which: a non-zero dead byte refuses damaged: refused=${report.refused}');
    check(r.cellsCount == 0 && r.numsCount == 0, '$which: the refusal kept a count');
    slack('$which A then refused', r, fresh());
  }
  if (exitCode == 0) {
    stdout.writeln('PROBE OK');
  }
}
`, strings.Join(hb, ", "))
	if err := os.WriteFile(filepath.Join(dir, "slack_probe.dart"), []byte(probe), 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := testproc.Command(t, dartBin, "--enable-asserts", "slack_probe.dart")
	cmd.Dir = dir
	out, err := cmd.CombinedOutput()
	if err != nil || !strings.Contains(string(out), "PROBE OK") {
		t.Fatalf("the slots past the count after a load (§3.4) (%v):\n%s", err, out)
	}
}
