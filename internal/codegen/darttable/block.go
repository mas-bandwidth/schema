	g.pf("        size: %d,\n", size)
	g.pf("        kind: %d,\n", kind)
	g.pf("        outOfLine: %v,\n", outOfLine)
	g.pf("        offsetOfOffset: %d,\n", offsetOfOffset)
	g.pf("        countOffset: %d,\n", countOffset)
	g.pf("        strideOffset: %d,\n", strideOffset)
	g.pf("        stride: %d,\n", stride)
	g.pf("        isArray: %v,\n", isArray)
	g.pf("        counted: %v,\n", counted)
	g.pf("        optional: %v,\n", optional)
	g.pf("        arrayBound: %d,\n", arrayBound)
	g.pf("        elemSize: %d,\n", elemSize)
