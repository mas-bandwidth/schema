// blockDescriptorRecords is every record one block's descriptors reach, sorted.
func blockDescriptorRecords(b *ir.BlockUnit, bl *ir.BlockLayout) []string {
	seen := map[string]bool{}
	var out []string
	var walk func(name string)
	walk = func(name string) {
		if seen[name] {
			return
		}
		ml := b.Layout(name)
		if ml == nil {
			return
		}
		seen[name] = true
		out = append(out, name)
		for _, fl := range ml.Fields {
			if isStructRef(fl.Field.Type) {
				walk(fl.Field.Type.Name)
			}
		}
	}
	for _, a := range bl.Arrays {
		walk(a.ElemName)
	}
	for _, fl := range bl.Projection.Fields {
		if ir.BlockOutOfLine(fl.Field) {
			continue
		}
		if isStructRef(fl.Field.Type) {
			walk(fl.Field.Type.Name)
		}
	}
	sort.Strings(out)
	return out
}

// dartBlockInfoSymbol names one record's descriptor. They are MEMBERS of the
// block class, so the whole graph claims exactly one name — the block's, which
// §11's suffix set already holds.
func dartBlockInfoSymbol(owner, record string) string {
	if record == "" {
		return "type"
	}
	return "row" + record
}

// sublist writes a view getter, wrapping the way `dart format` does: the whole
// expression on one line, else broken after the arrow, else one argument per
// line.
func (g *blockGen) sublist(ind, head, args string) {
	one := fmt.Sprintf("%s%s => Uint8List.sublistView(%s);", ind, head, args)
	if len(one) <= 80 {
		g.pf("%s\n", one)
		return
	}
	broken := fmt.Sprintf("%s    Uint8List.sublistView(%s);", ind, args)
	if len(broken) <= 80 {
		g.pf("%s%s =>\n%s\n", ind, head, broken)
		return
	}
	g.pf("%s%s => Uint8List.sublistView(\n", ind, head)
	for a := range strings.SplitSeq(args, ", ") {
		g.pf("%s  %s,\n", ind, a)
	}
	g.pf("%s);\n", ind)
}

// arrow writes an expression-bodied member, breaking after the arrow the way
// `dart format` does when the one-line form runs past 80 columns.
// scalarGetter writes one scalar field's getter. A float32 widens AT THE
// READ, in the getter's own body (issue 404, PORTING M3): under the JIT a
// double crossing an out-of-line conversion call is boxed, and whether the
// call is inlined is the inliner's budget, not the codec's. A float of either
// width is TESTED ON ITS RAW BITS first (docs/SPEC-TABLES.md §3.3, ruling 2 of
// 2026-10-27): a NaN or an infinity — the all-ones exponent — is never
// returned; the getter answers 0 and latches non_finite_float on the view,
// naming the field. Every finite float32 widens exactly.
func (g *blockGen) scalarGetter(ind string, f *ir.Field, head, at string) {
	if e, ok := f.Type.Ref.(*ir.Enum); ok && f.Type.Kind == ir.TNamed {
		// an enum reads as the packet emitter's extension type over int:
		// the same bits, typed (erased at compile time, so free)
		g.need(g.unit.DeclFile[e.Name]+".dart", e.Name)
		head = e.Name + strings.TrimPrefix(head, "int")
		g.arrow(ind, head, e.Name+"("+g.readAt(f, at)+")")
		return
	}
	if f.Type.Kind != ir.TFloat32 && f.Type.Kind != ir.TFloat64 {
		g.arrow(ind, head, g.readAt(f, at))
		return
	}
	g.pf("%s%s {\n", ind, head)
	if f.Type.Kind == ir.TFloat32 {
		g.dartCall(ind+"  ", "final bits = ", "view.getUint32", at)
		g.pf("%s  if ((bits & 0x7f800000) != 0x7f800000) {\n", ind)
		g.pf("%s    _float32Words[0] = bits;\n", ind)
		g.pf("%s    return _float32Cell[0];\n", ind)
	} else {
		g.dartCall(ind+"  ", "final bits = ", "view.getUint64", at)
		g.pf("%s  if ((bits & 0x7ff0000000000000) != 0x7ff0000000000000) {\n", ind)
		g.dartCall(ind+"    ", "return ", "view.getFloat64", at)
	}
	g.pf("%s  }\n", ind)
	// a NaN or an infinity: refused, latched naming the field, never returned
	g.pf("%s  if (nonFiniteFloat.isEmpty) {\n", ind)
	g.pf("%s    nonFiniteFloat = '%s';\n", ind, dartFloatOwner(g.unit, f, nil))
	g.pf("%s  }\n", ind)
	g.pf("%s  return 0.0;\n", ind)
	g.pf("%s}\n\n", ind)
}

// dartCall writes `<lead><fn>(<at>, Endian.little);` the way dart format
// does: one line while it fits eighty columns, the tall form past it.
func (g *blockGen) dartCall(ind, lead, fn, at string) {
	one := fmt.Sprintf("%s%s%s(%s, Endian.little);", ind, lead, fn, at)
	if len(one) <= 80 {
		g.pf("%s\n", one)
		return
	}
	g.pf("%s%s%s(\n%s  %s,\n%s  Endian.little,\n%s);\n", ind, lead, fn, ind, at, ind, ind)
}

func (g *blockGen) arrow(ind, head, expr string) {
	one := fmt.Sprintf("%s%s => %s;", ind, head, expr)
	if len(one) <= 80 {
		g.pf("%s\n", one)
		return
	}
	two := fmt.Sprintf("%s    %s;", ind, expr)
	if len(two) <= 80 {
		g.pf("%s%s =>\n%s\n", ind, head, two)
		return
	}
	if fn, arg, ok := strings.Cut(strings.TrimSuffix(expr, ")"), "("); ok {
		g.pf("%s%s => %s(\n%s  %s,\n%s);\n", ind, head, fn, ind, arg, ind)
		return
	}
	g.pf("%s%s =>\n%s    %s;\n", ind, head, ind, expr)
}

// trimBlank drops a trailing blank line from the body — the emitter's
// per-member spacing meeting a closing brace or a comment block, which
// `dart format` writes with no blank between.
func (g *blockGen) trimBlank() {
	text := strings.TrimRight(g.body.String(), "\n")
	g.body.Reset()
	g.body.WriteString(text)
	g.body.WriteString("\n")
}

