// The BLOCK FORM (docs/SPEC-TABLES.md §19): the Dart READ half and, since the
// fill path landed, the WRITE half's begin (§19.1).
//
// NOTHING DECLARES THIS FORM. Every fixed table has one, and it is emitted on
// the side, in <Base>Block.dart, which a consumer imports only if it reads a
// block. The unit's <Base>Table.dart carries not one symbol of it.
//
// WHERE DART DIFFERS FROM THE REFERENCE, and why. C++ casts the base to a
// struct pointer and reads a field through the compiler's own layout; C#
// declares a blittable struct with generated padding and asserts it against the
// compiler's model. Dart has neither a struct nor a pointer: a block is a
// Uint8List and every field is read at a GENERATED OFFSET through a ByteData.
// So:
//
//   - THERE IS NO SECOND LAYOUT MODEL TO CROSS-CHECK. C#'s Verify exists
//     because two models — the emitter's and the CLR's — must agree; here the
//     generated offsets ARE the only model, and what catches a producer this
//     reader disagrees with is the prologue's BUILD VERSION, which Open
//     compares before it reads one field.
//   - THE BASE IS (buffer, offset), because that is the only base a Dart
//     consumer holds. §19.1's 64-byte alignment is checked on that offset,
//     which is the same rule said in the currency this language has — and it
//     is what the forgery battery's `pointer` column drives.
//
// Everything else is the reference's, check for check: Open's whole battery,
// the triple read out of the INSTANCE, the descriptors as constant data.
package darttable

import (
	"fmt"
	"math/bits"
	"sort"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

type blockGen struct {
	unit     *ir.Unit
	file     *ir.File
	blocks   *ir.BlockUnit
	home     bool
	homeBase string
	body     strings.Builder
	imports  map[string]map[string]bool
	needData bool // this library reads through typed data
	needHome bool // this library names the runtime's descriptors or constants
	// inCook marks a cursor emitted INTO a cook library: one record has one
	// cursor, and which accelerator's library carries it decides the import.
	inCook bool
}

func (g *blockGen) pf(format string, args ...any) {
	fmt.Fprintf(&g.body, format, args...)
}

func (g *blockGen) need(library, symbol string) {
	if g.imports[library] == nil {
		g.imports[library] = map[string]bool{}
	}
	g.imports[library][symbol] = true
}

// generateBlockFiles emits <Base>Block.dart for every unit file, plus the
// unit's one block runtime home. A table with no block form is NAMED in the
// file with the reason, never left to a reader to guess.
func generateBlockFiles(u *ir.Unit, blocks *ir.BlockUnit) (map[string][]byte, error) {
	out := map[string][]byte{}
	if len(blocks.Tables) == 0 && len(blocks.Skipped) == 0 {
		return out, nil
	}
	home := runtimeHome(u)
	written := false
	for _, f := range u.Files {
		g := &blockGen{unit: u, file: f, blocks: blocks, home: f.Base == home,
			homeBase: home, imports: map[string]map[string]bool{}}
		if g.home {
			g.emitRuntime()
			written = true
		}
		// the ROW CURSORS of the records this file DECLARES, once per unit
		// however many blocks reach them
		for _, record := range blocks.Order {
			if u.DeclFile[record] != f.Base {
				continue
			}
			if ml := blocks.Layout(record); ml != nil {
				g.emitRowCursor(record, ml)
			}
		}
		for _, t := range f.Tables {
			if bl := blocks.Block(t.Name); bl != nil {
				g.emitBlock(bl)
				continue
			}
			if why := blocks.SkippedReason(t.Name); why != "" {
				g.pf("// table %s has NO block form: %s.\n", t.Name, why)
				g.pf("// Its wire (§3) is unaffected — only this projection is absent, and it is\n")
				g.pf("// absent by construction rather than by refusal.\n\n")
			}
		}
		if g.body.Len() > 0 {
			out[f.Base+"Block.dart"] = g.assemble()
		}
	}
	if !written {
		g := &blockGen{unit: u, blocks: blocks, home: true, homeBase: home,
			imports: map[string]map[string]bool{}}
		g.emitRuntime()
		out[home+"Block.dart"] = g.assemble()
	}
	return out, nil
}

func (g *blockGen) assemble() []byte {
	var h strings.Builder
	if g.file == nil {
		fmt.Fprintf(&h, "// Code generated by the schema compiler for package %s. DO NOT EDIT.\n", g.unit.Package)
	} else {
		fmt.Fprintf(&h, "// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", g.file.Base)
	}
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&h, "// package %s — the BLOCK FORM (docs/SPEC-TABLES.md §19): the READ half and\n", g.unit.Package)
	fmt.Fprintf(&h, "// begin, the fill path's first half (§19.1).\n")
	h.WriteString("//\n")
	h.WriteString("// NOTHING DECLARES THIS FORM. Every fixed table has one, and it is emitted on\n")
	h.WriteString("// the side: import this library only if you read a block. The unit's\n")
	h.WriteString("// <Base>Table.dart carries not one symbol of it.\n")
	h.WriteString("//\n")
	h.WriteString("// A block is bytes another language wrote, and reading them without a copy is\n")
	h.WriteString("// the whole point (§12.1). Dart has no struct and no pointer, so every field\n")
	h.WriteString("// below is read at a GENERATED OFFSET through a ByteData over the caller's\n")
	h.WriteString("// bytes — the offsets are the one layout model, and the prologue's BUILD\n")
	h.WriteString("// VERSION is what refuses a producer that disagrees with them.\n")
	h.WriteString("\n")
	if g.needData || g.home {
		h.WriteString("import 'dart:typed_data';\n\n")
	}
	if !g.home && g.needHome {
		g.imports[g.homeBase+"Block.dart"] = nil
	}
	for _, base := range sortedKeys(g.imports) {
		syms := g.imports[base]
		if syms == nil {
			fmt.Fprintf(&h, "import '%s';\n", base)
			continue
		}
		names := sortedKeys(syms)
		one := fmt.Sprintf("import '%s' show %s;", base, strings.Join(names, ", "))
		if len(one) <= 80 {
			h.WriteString(one + "\n")
			continue
		}
		two := fmt.Sprintf("    show %s;", strings.Join(names, ", "))
		if len(two) <= 80 {
			fmt.Fprintf(&h, "import '%s'\n%s\n", base, two)
			continue
		}
		fmt.Fprintf(&h, "import '%s'\n    show\n", base)
		for i, n := range names {
			sep := ","
			if i == len(names)-1 {
				sep = ";"
			}
			fmt.Fprintf(&h, "        %s%s\n", n, sep)
		}
	}
	if len(g.imports) > 0 {
		h.WriteString("\n")
	}
	h.WriteString(strings.Trim(g.body.String(), "\n"))
	h.WriteString("\n")
	return []byte(h.String())
}

// emitRuntime writes the unit's shared block runtime: the magic, this build's
// byte order, the build version, and the reflection descriptor classes.
func (g *blockGen) emitRuntime() {
	g.pf("%s", blockRuntimeSource(ir.BuildVersion(g.unit)))
}

// emitBlock writes one table's block reader: the constants, Open, the
// projection's own fields, each array's triple and row accessor, and the
// descriptors.
func (g *blockGen) emitBlock(bl *ir.BlockLayout) {
	name := bl.Table.Name
	g.needData = true
	g.needHome = true
	g.pf("// %s's block: bytes, a base and a length, and then rows in place. Opening\n", name)
	g.pf("// one is ONE check and no copy; reading a row is one add (docs/SPEC-TABLES.md\n")
	g.pf("// §19.2).\n")
	g.pf("//\n")
	g.pf("// The bytes belong to the CONSUMER — a buffer it owns, or memory a producer\n")
	g.pf("// handed across. Nothing here copies them.\n")
	g.pf("final class %sBlock {\n", name)
	g.pf("  final Uint8List bytes;\n")
	g.pf("  final ByteData view;\n")
	g.pf("  // the block's first byte within bytes, and the used extent from it\n")
	g.pf("  final int base;\n")
	g.pf("  final int length;\n\n")
	// a projection with a float carries the accessors' latch (ruling 2), a
	// mutable member, so its constructor is not const
	if accessorsDecodeFloat(&bl.Projection, bl) {
		g.pf("  %sBlock(this.bytes, this.view, this.base, this.length);\n\n", name)
	} else {
		g.pf("  const %sBlock(this.bytes, this.view, this.base, this.length);\n\n", name)
	}
	g.pf("  // The storage a PRODUCER of this block allocates, sized from the declared\n")
	g.pf("  // maxima (docs/SPEC-TABLES.md §19.1). A Dart consumer does not allocate a block\n")
	g.pf("  // — the bytes are handed to it — but it caps by this.\n")
	g.pf("  static const int blockMaxBytes = %d;\n\n", bl.MaxBytes)
	g.pf("  static const int projectionSize = %d;\n\n", bl.Projection.Size)

	// the projection's own inline fields
	g.emitInlineAccessors(&bl.Projection, bl, "  ", "base")

	for _, a := range bl.Arrays {
		field := dartName(a.Field.Name)
		g.pf("\n  // %s: the constants this build asserts against. A consumer INDEXES with\n", a.Field.Name)
		g.pf("  // what it read from the INSTANCE, never with these (docs/SPEC-TABLES.md §19.2).\n")
		g.pf("  static const int %sStride = %d;\n", field, a.Stride)
		g.pf("  static const int %sMax = %d;\n", field, a.Max)
		g.pf("  static const int %sProjectionOffset = %d;\n\n", field, a.TripleOffset)
		g.pf("  // the triple, read OUT OF the instance (§2.7)\n")
		g.pf("  int get %sOffsetOf => view.getUint64(base + %d, Endian.little);\n", field, a.OffsetOfOffset)
		g.pf("  int get %sCount => view.getUint32(base + %d, Endian.little);\n", field, a.CountOffset)
		g.pf("  int get %sPitch => view.getUint32(base + %d, Endian.little);\n\n", field, a.StrideOffset)
		g.pf("  /// A cursor over %s's rows, to lend to [%sAt] and to move.\n", a.Field.Name, field)
		cursor := fmt.Sprintf("  %sRow %sCursor() => %sRow(view, base);", a.ElemName, field, a.ElemName)
		if len(cursor) <= 80 {
			g.pf("%s\n\n", cursor)
		} else {
			g.pf("  %sRow %sCursor() =>\n      %sRow(view, base);\n\n", a.ElemName, field, a.ElemName)
		}
		g.pf("  /// ONE ROW, moved onto the cursor the caller lends — at the pitch the\n")
		g.pf("  /// INSTANCE gives, never the constant above (docs/SPEC-TABLES.md §19.2).\n")
		g.pf("  ///\n")
		g.pf("  /// The cursor is required and there is no allocating twin: a per-frame\n")
		g.pf("  /// walk over thousands of rows must not have an obvious call that\n")
		g.pf("  /// allocates one object per row. [%sCursor] makes the one you lend.\n", field)
		rowSig := fmt.Sprintf("  %sRow %sAt(int index, %sRow into) {", a.ElemName, field, a.ElemName)
		if len(rowSig) <= 80 {
			g.pf("%s\n", rowSig)
		} else {
			g.pf("  %sRow %sAt(\n    int index,\n    %sRow into,\n  ) {\n",
				a.ElemName, field, a.ElemName)
		}
		g.pf("    into.at = base + %sOffsetOf + index * %sPitch;\n", field, field)
		g.pf("    return into;\n  }\n\n")
		g.pf("  /// `%s`, ITERATED (docs/SPEC-TABLES.md §19.2) — `for (final row in\n", a.Field.Name)
		g.pf("  /// block.%s)`, so a call site never spells the pitch arithmetic.\n", field)
		g.pf("  ///\n")
		g.pf("  /// THE LOOP VARIABLE IS ONE CURSOR, MOVED. That is what makes the\n")
		g.pf("  /// idiomatic loop the allocation-free one — a row object per step is\n")
		g.pf("  /// exactly what §19.2's clause exists to avoid — and it means a row\n")
		g.pf("  /// does NOT outlive its step: read what you need inside the loop, and\n")
		g.pf("  /// never collect the rows themselves.\n")
		g.pf("  Iterable<%sRow> get %s {\n", a.ElemName, field)
		g.pf("    final cursor = %sCursor();\n", field)
		g.pf("    final at = base + %sOffsetOf;\n", field)
		g.pf("    final pitch = %sPitch;\n", field)
		g.pf("    return Iterable<%sRow>.generate(%sCount, (i) {\n", a.ElemName, field)
		g.pf("      cursor.at = at + i * pitch;\n      return cursor;\n    });\n  }\n\n")
		g.pf("  /// `%s`'s own bytes, contiguously — the pitch IS the row's size\n", a.Field.Name)
		g.pf("  /// (§2.7), so they lie end to end. Dart has NO TYPED contiguous view\n")
		g.pf("  /// to give here, the way C++ has a span of the row struct and C# a\n")
		g.pf("  /// ReadOnlySpan<Row>, because Dart has no struct: what a consumer can\n")
		g.pf("  /// have is the extent as bytes, and the cursor above to read it with.\n")
		g.pf("  Uint8List %sBytes() => Uint8List.sublistView(\n", field)
		g.pf("    bytes,\n    base + %sOffsetOf,\n    base + %sOffsetOf + %sCount * %sPitch,\n  );\n",
			field, field, field, field)
		g.needRow(a.ElemName)
	}

	g.emitBlockBuild(bl)
	g.trimBlank()
	g.emitBlockOpen(bl)
	g.emitBlockDescriptors(bl)
	g.pf("}\n\n")
}

// emitBlockBuild writes the block's FILL half (docs/SPEC-TABLES.md §19.1):
// `begin`, which lays down the prologue and one triple per out-of-line array
// and NOT ONE OTHER BYTE — never a row and never the padding between arrays.
// The image is the reference's: the same three prologue words at the same
// offsets, each triple's offset_of rounded up to the array's own alignment,
// its count and its pitch, and the used extent rounded to §19.1's 64 bytes.
//
// EVERY CHECK RUNS BEFORE THE FIRST WRITE, so a refused begin leaves the
// caller's bytes exactly as they were — the clause §19.1 states for the
// producer side and the reason the count bounds are named through a
// TableBlockRefusal rather than thrown.
//
// DART HAS NO ALLOCATOR TO OWN: the reference leg's Begin takes a storage that
// allocated a maximum-sized extent, and here the caller hands the bytes it
// owns and the aligned base inside them, which is the same requirement said in
// the currency this language has — the extent from `base` must hold the
// declared maximum, exactly as the storage's allocation does.
func (g *blockGen) emitBlockBuild(bl *ir.BlockLayout) {
	name := bl.Table.Name
	g.pf("  // ---- the block fill path: begin (docs/SPEC-TABLES.md §19.1) ----\n")
	g.pf("  /// Writes the prologue and this block's triples, and NOTHING else: no row\n")
	g.pf("  /// and no padding between arrays is touched, so what a caller put in the\n")
	g.pf("  /// extent stays there. Returns the built block — its used extent in\n")
	g.pf("  /// [Block.length] — or null on a refusal, which [refusal] then names: the\n")
	g.pf("  /// array whose declared maximum a count violates, the count and the bound.\n")
	g.pf("  ///\n")
	g.pf("  /// `base` is the block's first byte within `bytes` and §19.1's 64-byte\n")
	g.pf("  /// alignment is required of it; the extent from it must hold\n")
	g.pf("  /// [blockMaxBytes], the size a producer's storage allocates.\n")
	head := fmt.Sprintf("  static %sBlock? begin(Uint8List bytes, int base, {", name)
	var params []string
	for _, a := range bl.Arrays {
		params = append(params, fmt.Sprintf("required int %sCount", dartName(a.Field.Name)))
	}
	params = append(params, "TableBlockRefusal? refusal")
	one := head + strings.Join(params, ", ") + "}) {"
	if len(one) <= 80 {
		g.pf("%s\n", one)
	} else {
		g.pf("  static %sBlock? begin(\n    Uint8List bytes,\n    int base, {\n", name)
		for _, p := range params {
			g.pf("    %s,\n", p)
		}
		g.pf("  }) {\n")
	}
	g.pf("    if (refusal != null) {\n")
	g.pf("      refusal.array = '';\n      refusal.count = 0;\n      refusal.maximum = 0;\n    }\n")
	for _, a := range bl.Arrays {
		field := dartName(a.Field.Name) + "Count"
		g.pf("    // the DECLARED MAXIMUM (§19.1): a count past it would run the array out\n")
		g.pf("    // of the extent a consumer sizes by the maximum, so it is refused here\n")
		g.pf("    // and again by [open] on the reader's side.\n")
		g.pf("    if (%s < 0 || %s > %d) {\n", field, field, a.Max)
		g.pf("      if (refusal != null) {\n")
		g.pf("        refusal.array = '%s';\n        refusal.count = %s;\n        refusal.maximum = %d;\n      }\n",
			a.Field.Name, field, a.Max)
		g.pf("      return null;\n    }\n")
	}
	g.pf("    if (base < 0 || base %% %d != 0) {\n      return null; // the base's alignment\n    }\n", ir.BlockAlign)
	g.pf("    if (bytes.length - base < blockMaxBytes) {\n")
	g.pf("      return null; // the caller's bytes cannot hold the declared maximum\n    }\n")
	g.pf("    final view = ByteData.view(\n")
	g.pf("      bytes.buffer,\n      bytes.offsetInBytes,\n      bytes.lengthInBytes,\n    );\n")
	g.pf("    // the prologue's three words (§19.1), little-endian as this build is\n")
	g.pf("    view.setUint64(base, tableBlockMagic, Endian.little);\n")
	g.pf("    view.setUint64(base + 8, tableBuildVersion, Endian.little);\n")
	g.pf("    view.setUint64(base + 16, tableBlockByteOrder, Endian.little);\n")
	g.pf("    var offset = projectionSize;\n")
	for _, a := range bl.Arrays {
		field := dartName(a.Field.Name) + "Count"
		alignment := int64(ir.BlockAlign)
		if a.ElemAlign() > alignment {
			alignment = a.ElemAlign()
		}
		g.pf("    offset = (offset + %d) & ~%d;\n", alignment-1, alignment-1)
		g.pf("    view.setUint64(base + %d, offset, Endian.little);\n", a.OffsetOfOffset)
		g.pf("    view.setUint32(base + %d, %s, Endian.little);\n", a.CountOffset, field)
		g.pf("    view.setUint32(base + %d, %d, Endian.little);\n", a.StrideOffset, a.Stride)
		g.pf("    offset += %s * %d;\n", field, a.Stride)
	}
	g.pf("    final used = (offset + %d) & ~%d;\n", ir.BlockAlign-1, ir.BlockAlign-1)
	g.pf("    return %sBlock(bytes, view, base, used);\n  }\n\n", name)
}

// needRow records the import one record's cursor needs. ONE RECORD HAS ONE
// CURSOR: the BLOCK library carries it when the block form reaches the record,
// and the COOK library otherwise — so the import follows the form, not the
// file that declared the schema type.
func (g *blockGen) needRow(record string) {
	base := cookDeclFile(g.unit, record)
	if base == "" {
		return
	}
	library := base + "Cook.dart"
	if g.blocks.Layout(record) != nil {
		library = base + "Block.dart"
	}
	own := base + "Block.dart"
	if g.inCook {
		own = base + "Cook.dart"
	}
	if g.file != nil && base == g.file.Base && library == own {
		return
	}
	g.need(library, record+"Row")
}

// emitRowCursor writes one record's row view: a ByteData and a byte offset,
// and one getter per field at its generated offset. The cursor is MUTABLE in
// its offset on purpose — a walk over a million rows moves one object rather
// than allocating one per row.
func (g *blockGen) emitRowCursor(record string, ml *ir.MemberLayout) {
	if ml == nil {
		return
	}
	g.pf("// %s as a block ROW: a view and an offset, and every field read where it\n", record)
	g.pf("// lies. `at` is settable so a walk reuses one cursor (docs/SPEC-TABLES.md §19.2).\n")
	g.needData = true
	g.pf("final class %sRow {\n", record)
	g.pf("  final ByteData view;\n")
	g.pf("  int at;\n\n")
	g.pf("  %sRow(this.view, this.at);\n\n", record)
	g.pf("  static const int rowSize = %d;\n", ml.Size)
	g.pf("  static const int rowAlign = %d;\n\n", ml.Align)
	g.emitInlineAccessors(ml, nil, "  ", "at")
	g.trimBlank()
	g.pf("}\n\n")
}

// emitInlineAccessors writes one record's field getters. `origin` is the Dart
// expression for the record's first byte.
func (g *blockGen) emitInlineAccessors(ml *ir.MemberLayout, bl *ir.BlockLayout, ind, origin string) {
	for _, fl := range ml.Fields {
		if fl.Field.Type.Kind == ir.TFloat32 && !fl.Field.Type.Pointer {
			// A class owns its scratch view; no allocation rides a field read.
			g.pf("%s", dartBlockFloat32Runtime)
			break
		}
	}
	if accessorsDecodeFloat(ml, bl) {
		g.pf("%s", dartBlockFloatLatch)
	}
	for _, fl := range ml.Fields {
		f := fl.Field
		if bl != nil && ir.BlockOutOfLine(f) {
			continue // the triple, emitted with its array
		}
		facts := ir.BlockFieldOf(g.unit, f, fl.Offset, bl != nil)
		name := accessorName(f, bl != nil)
		switch {
		case f.IsMap():
			// a MAP slot is a delta and a count, never a scalar (§2.8, §7.2):
			// only a cooked record reaches one, since a map refuses the block form
			g.emitCookMapAccessors(f, fl.Offset, ind, origin)
			continue
		case f.IsList() && bl == nil:
			// a LIST slot is a delta and a count too (§2.9, §7.2): its elements
			// are a span in the holder's node extent, read where they lie
			g.emitCookListAccessors(f, fl.Offset, ind, origin)
			continue
		case f.Type.Kind == ir.TWString && bl == nil:
			// wstring(N)'s cooked storage (§7.2): char16_t[N+1], then the used
			// length in CODE UNITS
			g.pf("%s// wstring(%d): the USED length in code units, and each unit\n", ind, f.Type.Size)
			g.pf("%sint get %sLength {\n", ind, name)
			g.pf("%s  final used = view.getInt32(%s + %d, Endian.little);\n", ind, origin, facts.CountOffset)
			g.pf("%s  return used < 0 || used > %d ? 0 : used;\n%s}\n\n", ind, f.Type.Size, ind)
			g.arrow(ind, fmt.Sprintf("int %sAt(int index)", name), fmt.Sprintf("view.getUint16(%s + %d + index * 2, Endian.little)", origin, fl.Offset))
			continue
		case f.Type.Kind == ir.TString || f.Type.Kind == ir.TBytes:
			g.pf("%s// %s: the USED length, and a view of the bytes it names\n", ind, tableFieldTypeName(f))
			g.pf("%sint get %sLength {\n", ind, name)
			g.pf("%s  final used = view.getInt32(%s + %d, Endian.little);\n", ind, origin, facts.CountOffset)
			g.pf("%s  return used < 0 || used > %d ? 0 : used;\n%s}\n\n", ind, f.Type.Size, ind)
			// a Block owns its buffer; a ROW cursor holds only a view, so the
			// caller hands the buffer the view was taken over
			head, buffer := fmt.Sprintf("Uint8List get %sBytes", name), "bytes"
			if bl == nil {
				head = fmt.Sprintf("Uint8List %sBytes(Uint8List buffer)", name)
				buffer = "buffer"
			}
			args := fmt.Sprintf("%s, %s + %d, %s + %d + %sLength",
				buffer, origin, fl.Offset, origin, fl.Offset, name)
			g.sublist(ind, head, args)
		case facts.IsArray && f.Type.Kind == ir.TNamed && isStructRef(f.Type):
			g.pf("%s// [%d]%s, inline\n", ind, facts.ArrayBound, f.Type.Name)
			g.pf("%sstatic const int %sBound = %d;\n", ind, name, facts.ArrayBound)
			one := fmt.Sprintf("%s%sRow %sAt(int index, %sRow into) {", ind, f.Type.Name, name, f.Type.Name)
			if len(one) <= 80 {
				g.pf("%s\n", one)
			} else {
				g.pf("%s%sRow %sAt(\n%s  int index,\n%s  %sRow into,\n%s) {\n",
					ind, f.Type.Name, name, ind, ind, f.Type.Name, ind)
			}
			g.pf("%s  into.at = %s + %d + index * %d;\n", ind, origin, fl.Offset, facts.ElemSize)
			g.pf("%s  return into;\n%s}\n\n", ind, ind)
			g.needRow(f.Type.Name)
		case facts.IsArray:
			g.pf("%sstatic const int %sBound = %d;\n", ind, name, facts.ArrayBound)
			g.scalarGetter(ind, f, fmt.Sprintf("%s %sAt(int index)", dartScalarType(f.Type), name),
				fmt.Sprintf("%s + %d + index * %d", origin, fl.Offset, facts.ElemSize))
		case f.Type.Kind == ir.TNamed && isStructRef(f.Type):
			g.pf("%s%sRow %s(%sRow into) {\n", ind, f.Type.Name, bareAccessor(f, bl != nil), f.Type.Name)
			g.pf("%s  into.at = %s + %d;\n%s  return into;\n%s}\n\n", ind, origin, fl.Offset, ind, ind)
			g.needRow(f.Type.Name)
		default:
			g.scalarGetter(ind, f, fmt.Sprintf("%s get %s", dartScalarType(f.Type), bareAccessor(f, bl != nil)),
				fmt.Sprintf("%s + %d", origin, fl.Offset))
		}
		if facts.Optional {
			g.pf("%sbool get %sPresent => view.getUint8(%s + %d) != 0;\n",
				ind, name, origin, facts.PresentOffset)
		}
	}
}

// rowMembers and blockMembers are the names a row cursor and a block class
// declare for themselves; a field accessor may not take one (a field named
// `at` would redeclare the cursor's offset).
var (
	rowMembers = map[string]bool{"view": true, "at": true, "rowSize": true, "rowAlign": true,
		"nonFiniteFloat": true}
	blockMembers = map[string]bool{"bytes": true, "view": true, "base": true, "length": true,
		"blockMaxBytes": true, "projectionSize": true, "nonFiniteFloat": true}
	// accessorSuffixes are every spelling a field's accessors derive from its
	// name (emitInlineAccessors, emitCookMapAccessors).
	accessorSuffixes = []string{"", "Length", "Bytes", "Bound", "At", "Present", "Count"}
)

// accessorName is the name a field's accessors in a row cursor (block false)
// or a block class (block true) derive from: the field's lowerCamel name,
// or that name followed by `$` when any accessor spelled from it would
// collide with one of the class's own members. A schema name never holds a
// `$`, so the escaped spelling collides with nothing.
func accessorName(f *ir.Field, block bool) string {
	name := dartName(f.Name)
	members := rowMembers
	if block {
		members = blockMembers
	}
	for _, suffix := range accessorSuffixes {
		if members[name+suffix] {
			return name + "$"
		}
	}
	return name
}

// bareAccessor is the accessor spelled by the field's name alone: the
// escaped name when accessorName escaped it, the reserved-word-safe member
// name (fieldMember) otherwise.
func bareAccessor(f *ir.Field, block bool) string {
	if name := accessorName(f, block); name != dartName(f.Name) {
		return name
	}
	return fieldMember(f)
}

func isStructRef(t ir.FieldType) bool {
	if t.Kind != ir.TNamed || t.Pointer {
		return false
	}
	_, ok := t.Ref.(*ir.Struct)
	return ok
}

// dartScalarType is the Dart type one block field reads as.
func dartScalarType(t ir.FieldType) string {
	switch t.Kind {
	case ir.TBool:
		return "bool"
	case ir.TFloat32, ir.TFloat64:
		return "double"
	case ir.TFixed:
		// the wide kinds hold their RAW integer as a BigInt (§3, §15)
		return "BigInt"
	case ir.TInt:
		if t.Width == 128 {
			return "BigInt"
		}
	}
	return "int"
}

// readAt renders the ByteData read one scalar field takes at a byte offset.
func (g *blockGen) readAt(f *ir.Field, at string) string {
	t := f.Type
	switch t.Kind {
	case ir.TBool:
		return fmt.Sprintf("view.getUint8(%s) != 0", at)
	case ir.TFloat32:
		panic("darttable: a float32 read is a statement body (scalarGetter), never an expression")
	case ir.TFloat64:
		return fmt.Sprintf("view.getFloat64(%s, Endian.little)", at)
	case ir.TFixed:
		return wideRead(f, at)
	case ir.TInt:
		if t.Width == 128 {
			return wideRead(f, at)
		}
	}
	signed := t.Kind == ir.TInt && t.Signed
	width := blockScalarWidth(t)
	kind := "Uint"
	if signed {
		kind = "Int"
	}
	if width == 1 {
		return fmt.Sprintf("view.get%s8(%s)", kind, at)
	}
	return fmt.Sprintf("view.get%s%d(%s, Endian.little)", kind, width*8, at)
}

// wideRead reads one wide kind at its storage width (§3, §15). The value is
// the RAW integer the wire and the cook both carry, held as a BigInt.
func wideRead(f *ir.Field, at string) string {
	kind := ir.TableScalarKind(f)
	return fmt.Sprintf("tableCookGetWide(view, %s, %d, %v)", at, ir.TableKindWidth(kind), ir.TableKindSigned(kind))
}

func blockScalarWidth(t ir.FieldType) int {
	switch t.Kind {
	case ir.TInt:
		return t.Width / 8
	case ir.TBits:
		if t.Width <= 8 {
			return 1
		}
		if t.Width <= 16 {
			return 2
		}
		if t.Width <= 32 {
			return 4
		}
		return 8
	case ir.TNamed:
		switch ref := t.Ref.(type) {
		case *ir.Enum:
			return (ref.StorageBits + 7) / 8
		case *ir.Flags:
			return 8 // a flags slot is uint64 in every target (ir/blocklayout.go)
		}
	}
	return 1
}

func (g *blockGen) emitBlockOpen(bl *ir.BlockLayout) {
	name := bl.Table.Name
	g.pf("\n  // Open checks once and points, and this is the WHOLE check\n")
	g.pf("  // (docs/SPEC-TABLES.md §19.2): the magic read bytewise, the BYTE ORDER the\n")
	g.pf("  // prologue carries against this build's own, the BUILD VERSION against this\n")
	g.pf("  // build's own, each array's pitch, its offset_of, its COUNT against the\n")
	g.pf("  // declared maximum and its extent inside the block, the used extent against\n")
	g.pf("  // the bytes the caller passed, and the base's alignment. On a match the\n")
	g.pf("  // bytes are what a build with this layout wrote, so there is nothing to\n")
	g.pf("  // validate and nothing to fix up. On any failure it returns null and points\n")
	g.pf("  // at nothing.\n")
	g.pf("  //\n")
	g.pf("  // There is ONE entry point and no tolerant twin: the block form is\n")
	g.pf("  // same-build by construction — both sides generated from one declaration at\n")
	g.pf("  // one build — so a consumer older than its producer is not a case. A\n")
	g.pf("  // mismatch is a refusal; regenerate both sides. Data that must outlive the\n")
	g.pf("  // build that wrote it takes the wire, which this same table still has.\n")
	g.pf("  //\n")
	g.pf("  // `base` is the block's first byte within `bytes`, and it is the only base a\n")
	g.pf("  // Dart consumer holds: §19.1's 64-byte alignment is checked on it.\n")
	g.pf("  //\n")
	g.pf("  // open is openWithReason without the reason: the same checks in the same\n")
	g.pf("  // order, so the verdict and the reason never disagree.\n")
	g.pf("  static %sBlock? open(Uint8List? bytes, int base, int extent) {\n", name)
	g.pf("    return openWithReason(bytes, base, extent).$1;\n  }\n\n")
	g.pf("  // openWithReason answers the block and the FIRST failing clause beside the\n")
	g.pf("  // null, as the reference leg names it (docs/SPEC-TABLES.md §19.2, the clauses\n")
	g.pf("  // in the order internal/codegen/gotable/block.go's Open checks them): no\n")
	g.pf("  // buffer is an unaligned base, a claim under the projection or past the\n")
	g.pf("  // caller's bytes is truncated, the magic is not_a_cook or, read\n")
	g.pf("  // byte-reversed, foreign_order, then the order word, the build version,\n")
	g.pf("  // every array's layout (bad_layout), the used extent's padding (truncated)\n")
	g.pf("  // and last the base's own alignment.\n")
	g.pf("  static (%sBlock?, TableRefuseReason) openWithReason(\n", name)
	g.pf("    Uint8List? bytes,\n    int base,\n    int extent,\n  ) {\n")
	g.pf("    if (bytes == null || base < 0) {\n      return (null, TableRefuseReason.unalignedBase);\n    }\n")
	g.pf("    if (extent < %d) {\n      return (null, TableRefuseReason.truncated);\n    }\n", bl.Projection.Size)
	g.pf("    if (extent > bytes.length - base) {\n")
	g.pf("      // the claim runs past the bytes the caller owns\n")
	g.pf("      return (null, TableRefuseReason.truncated);\n    }\n")
	g.pf("    final view = ByteData.view(\n")
	g.pf("      bytes.buffer,\n      bytes.offsetInBytes,\n      bytes.lengthInBytes,\n    );\n")
	g.pf("    final magic = tableBlockRead64(view, base);\n")
	g.pf("    if (magic != tableBlockMagic) {\n")
	// the magic as a block of the OTHER byte order reads back through the same
	// bytewise read: what tells foreign_order from not_a_cook (§19.2)
	g.pf("      return (\n        null,\n        magic == 0x%016x\n", bits.ReverseBytes64(ir.BlockMagic))
	g.pf("            ? TableRefuseReason.foreignOrder\n            : TableRefuseReason.notACook,\n      );\n    }\n")
	g.pf("    if (tableBlockRead64(view, base + 16) != tableBlockByteOrder) {\n      return (null, TableRefuseReason.notACook);\n    }\n")
	g.pf("    if (tableBlockRead64(view, base + 8) != tableBuildVersion) {\n      return (null, TableRefuseReason.wrongBuildVersion);\n    }\n")
	g.pf("    var used = %d;\n", bl.Projection.Size)
	for _, a := range bl.Arrays {
		field := dartName(a.Field.Name)
		alignment := int64(ir.BlockAlign)
		if a.ElemAlign() > alignment {
			alignment = a.ElemAlign()
		}
		g.pf("    {\n")
		g.pf("      // EVERY NUMBER BELOW COMES FROM THE INSTANCE. Dart's int is signed and\n")
		g.pf("      // 64 bits wide, so a forged u64 near 2^63 arrives NEGATIVE — which the\n")
		g.pf("      // first bound below refuses before any arithmetic on it, and is why\n")
		g.pf("      // each term is checked before it is added rather than after.\n")
		g.pf("      final offsetOf = view.getUint64(base + %d, Endian.little);\n", a.OffsetOfOffset)
		g.pf("      final count = view.getUint32(base + %d, Endian.little);\n", a.CountOffset)
		g.pf("      final stride = view.getUint32(base + %d, Endian.little);\n", a.StrideOffset)
		g.pf("      if (stride != %sStride) {\n        return (null, TableRefuseReason.badLayout);\n      }\n", field)
		g.pf("      // past the DECLARED MAXIMUM: Begin refuses this on the producer side\n")
		g.pf("      // and Open refuses it here, because a consumer that sizes anything by\n")
		g.pf("      // the maximum would overflow on a count the maximum does not bound\n")
		g.pf("      if (count > %sMax) {\n        return (null, TableRefuseReason.badLayout);\n      }\n", field)
		g.pf("      if (offsetOf < %d || offsetOf %% %d != 0) {\n        return (null, TableRefuseReason.badLayout);\n      }\n",
			bl.Projection.Size, alignment)
		g.pf("      if (offsetOf > extent) {\n        return (null, TableRefuseReason.badLayout);\n      }\n")
		g.pf("      final rows = count * stride; // both bounded above: this cannot carry\n")
		g.pf("      if (rows > extent - offsetOf) {\n        return (null, TableRefuseReason.badLayout);\n      }\n")
		g.pf("      final end = offsetOf + rows;\n")
		g.pf("      if (end > used) {\n        used = end;\n      }\n")
		g.pf("    }\n")
	}
	g.pf("    // the used extent, rounded to %d WITHOUT the rounding itself wrapping:\n", ir.BlockAlign)
	g.pf("    // used is already inside extent, and the padding is paid out of the slack\n")
	g.pf("    // that is left rather than added and compared after.\n")
	g.pf("    final padding = (%d - (used %% %d)) %% %d;\n", ir.BlockAlign, ir.BlockAlign, ir.BlockAlign)
	g.pf("    if (padding > extent - used) {\n      return (null, TableRefuseReason.truncated);\n    }\n")
	g.pf("    used += padding;\n")
	g.pf("    if (base %% %d != 0) {\n      return (null, TableRefuseReason.unalignedBase);\n    }\n", ir.BlockAlign)
	// one line when it fits the formatter's 80 columns, the record split
	// otherwise: the tables-dart-clean gate holds this file to `dart format`
	ret := fmt.Sprintf("    return (%sBlock(bytes, view, base, used), TableRefuseReason.ok);", name)
	if len(ret) > 80 {
		ret = fmt.Sprintf("    return (\n      %sBlock(bytes, view, base, used),\n      TableRefuseReason.ok,\n    );", name)
	}
	g.pf("%s\n  }\n", ret)
}

// emitBlockDescriptors is the REFLECTIVE half (docs/SPEC-TABLES.md §8, §19.2): the
// projection offset of every field, the offsets of the three members inside
// each triple, and the element's own descriptor beside them. A consumer holding
// these reads the facts out of an instance and points at rows, with no
// hand-written record per table and nothing to maintain when a field is added.
func (g *blockGen) emitBlockDescriptors(bl *ir.BlockLayout) {
	name := bl.Table.Name
	g.pf("\n  // this table's block descriptors: CONSTANT data, so a reflective read\n")
	g.pf("  // costs a lookup and not a parse. The row layouts hang off the element\n")
	g.pf("  // column rather than taking names of their own, so a walker reaches every\n")
	g.pf("  // record through the graph — and they are MEMBERS, so the whole graph\n")
	g.pf("  // claims one name and that name is the block's (docs/SPEC-TABLES.md §11).\n")
	records := blockDescriptorRecords(g.blocks, bl)
	for _, r := range records {
		g.emitBlockRecordDescriptor(name, r, g.blocks.Layout(r), nil)
	}
	g.emitBlockRecordDescriptor(name, "", &bl.Projection, bl)
}

func (g *blockGen) emitBlockRecordDescriptor(owner, record string, ml *ir.MemberLayout, bl *ir.BlockLayout) {
	if ml == nil {
		return
	}
	symbol := dartBlockInfoSymbol(owner, record)
	name := record
	if bl != nil {
		name = bl.Table.Name
	}
	g.pf("  static const TableBlockInfo %s = TableBlockInfo(\n", symbol)
	g.pf("    name: '%s',\n", name)
	g.pf("    buildVersion: tableBuildVersion,\n")
	g.pf("    size: %d,\n", ml.Size)
	g.pf("    align: %d,\n", ml.Align)
	g.pf("    fields: <TableBlockFieldInfo>[\n")
	for _, fl := range ml.Fields {
		f := fl.Field
		kind := tableScalarKind(f)
		if f.Type.Kind == ir.TBytes {
			// the ELEMENT kind, exactly as TableFieldInfo carries it (§8.1)
			kind = tkU8
		}
		facts := ir.BlockFieldOf(g.unit, f, fl.Offset, bl != nil)
		if bl != nil {
			if a := bl.ArrayByName(f.Name); a != nil {
				g.blockField(f.Name, fl.Offset, fl.Size, kind, true,
					a.OffsetOfOffset, a.CountOffset, a.StrideOffset, a.Stride,
					true, true, false, a.Max, 0, -1,
					dartBlockInfoSymbol(owner, a.ElemName))
				continue
			}
		}
		element := "null"
		// A field that NAMES a record carries that record's layout, whether it
		// holds one or an array of them: an INLINE array of records is part of a
		// row, and a walker descending one reaches its element through this same
		// column. Only the pointer class has no layout to name.
		if isStructRef(f.Type) {
			element = dartBlockInfoSymbol(owner, f.Type.Name)
		}
		g.blockField(f.Name, fl.Offset, fl.Size, kind, false,
			-1, facts.CountOffset, -1, 0,
			facts.IsArray, facts.Counted, facts.Optional, facts.ArrayBound, facts.ElemSize,
			facts.PresentOffset, element)
	}
	g.pf("    ],\n  );\n")
}

