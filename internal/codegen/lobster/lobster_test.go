// TestSkeletonFixture is the one fixture `schema new-leg lobster` laid down,
// kept as the smallest unit: a table-free, declaration-free unit generates a
// module that names its package and protocol id, and that module compiles
// and runs under the pinned toolchain.
func TestSkeletonFixture(t *testing.T) {
	t.Parallel()
	u := &ir.Unit{
		Package:    "hello",
		ProtocolId: 0x11,
		Files:      []*ir.File{{Base: "Hello"}},
		DeclFile:   map[string]string{},
	}
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	name := "Hello." + ext
	got, ok := files[name]
	if !ok {
		t.Fatalf("Generate omitted %s; emitted %v", name, keysOf(files))
	}
	text := string(got)
	for _, want := range []string{
		"Code generated by the schema compiler from Hello.schema",
		"package hello",
		"namespace hello",
		"let ProtocolId = 17",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("missing %q in:\n%s", want, text)
		}
	}
	dir := t.TempDir()
	writeAll(t, dir, files)
	writeFile(t, dir, "main.lobster", "import .Hello\nassert hello.ProtocolId == 17\nprint(\"ok\")\n")
	if out := string(lobsterrun.Run(t, dir, "main.lobster", nil)); out != "ok\n" {
		t.Fatalf("fixture printed %q", out)
	}
}

// TestLobsterTypesConstructAtTheirDefaults generates examples/*.schema into a
// temp dir, imports every module under the pinned toolchain, constructs
// every type and union, and checks ArmDefaults the way test/go/main.go's
// testDefaultArmInitialization checks its constructors: a fresh DefaultArm
// carries count zero and BOTH backing entries at ProbeConfig's defaults
// (retries -1, preferred Railgun), each its own object, and a fresh
// DefaultChoice is the empty union with both arms pre-allocated
// (docs/PORT-LOBSTER.md, THE TYPE MAPPING; SPEC §5, §4.8). Lobster checks a
// function's types where it is called, so constructing every type is what
// type-checks every constructor.
func TestLobsterTypesConstructAtTheirDefaults(t *testing.T) {
	t.Parallel()
	u := unitFromDir(t, filepath.Join("..", "..", "..", "examples"))
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	writeAll(t, dir, files)

	ns := u.Package
	var main strings.Builder
	for _, f := range u.Files {
		fmt.Fprintf(&main, "import .%s\n", f.Base)
	}
	main.WriteString("var n = 0\n")
	var constructed []string
	for _, f := range u.Files {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ir.Struct:
				fmt.Fprintf(&main, "%s.New%s()\nn++\n", ns, d.Name)
				constructed = append(constructed, d.Name)
			case *ir.Union:
				fmt.Fprintf(&main, "let v%d = %s.New%s()\nassert v%d.Type == %s.%s\nn++\n", len(constructed), ns, d.Name, len(constructed), ns, VariantName(d.Name+"Type", "None"))
				constructed = append(constructed, d.Name)
			}
		}
	}
	main.WriteString(strings.ReplaceAll(`
let arm = NS.NewDefaultArm()
assert arm.EntriesCount == 0
assert length(arm.Entries) == 2
for(arm.Entries) entry:
    assert entry.Retries == -1 and entry.Preferred == NS.WeaponRailgun
assert arm.Marker == 0
assert arm.Entries[0] != arm.Entries[1]
let choice = NS.NewDefaultChoice()
assert choice.Type == NS.DefaultChoiceTypeNone
assert choice.First != choice.Second
for([choice.First, choice.Second]) a:
    assert a.EntriesCount == 0 and length(a.Entries) == 2
    for(a.Entries) entry:
        assert entry.Retries == -1 and entry.Preferred == NS.WeaponRailgun
assert NS.DefaultChoiceTypeMax == 2
let bulk = NS.NewDefaultBulkChoice()
assert length(bulk.First.Data) == 2 and bulk.First.DataLength == 0
assert NS.WeaponMax == 15
print("constructed {n}")
`, "NS", ns))
	writeFile(t, dir, "main.lobster", main.String())
	out := string(lobsterrun.Run(t, dir, "main.lobster", nil))
	if want := fmt.Sprintf("constructed %d\n", len(constructed)); out != want {
		t.Fatalf("main.lobster printed %q, want %q", out, want)
	}
	if len(constructed) == 0 {
		t.Fatal("examples/ declared no types")
	}
}

// TestLobsterEveryScalarFieldIsBornAtItsIRDefault checks every scalar field
// of every examples/ type against the IR, not hand-picked values: a bool is
// its default or false, an integer of 64 bits or fewer its DefInt or 0 (a
// uint64 as its bit pattern), a float32 float32(DefFloat) bit for bit, a
// float64 DefFloat, an enum its default variant or None (SPEC §5;
// docs/PORT-LOBSTER.md, THE TYPE MAPPING). The expected values come from the
// IR here, never from the emitter.
func TestLobsterEveryScalarFieldIsBornAtItsIRDefault(t *testing.T) {
	t.Parallel()
	u := unitFromDir(t, filepath.Join("..", "..", "..", "examples"))
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	ns := u.Package
	var main strings.Builder
	for _, f := range u.Files {
		fmt.Fprintf(&main, "import .%s\n", f.Base)
	}
	main.WriteString("var checked = 0\nvar bad = 0\ndef check(what:string, ok:int):\n    checked++\n    if not ok:\n        bad++\n        print(\"BAD \" + what)\n")
	n := 0
	for _, file := range u.Files {
		for _, d := range file.Decls {
			s, ok := d.(*ir.Struct)
			if !ok {
				continue
			}
			for _, f := range s.Fields {
				if f.Array != ir.ArrayNone || f.IsMap() || f.Type.Pointer || f.Type.Optional {
					continue
				}
				want := irDefault(f)
				if want == "" {
					continue
				}
				slot := fmt.Sprintf("%s.New%s().%s", ns, s.Name, ir.GoExportName(f.Name))
				if f.Type.Kind == ir.TFloat32 || f.Type.Kind == ir.TFloat64 {
					slot = "schema_rt.f64bits(" + slot + ")"
				}
				if after, ok0 := strings.CutPrefix(want, "Variant:"); ok0 {
					want = ns + "." + VariantName(f.Type.Name, after)
				}
				fmt.Fprintf(&main, "check(\"%s.%s\", %s == %s)\n", s.Name, f.Name, slot, want)
				n++
			}
		}
	}
	main.WriteString("print(\"checked {checked} bad {bad}\")\n")
	if n == 0 {
		t.Fatal("examples/ declared no scalar fields")
	}
	dir := t.TempDir()
	writeAll(t, dir, files)
	writeFile(t, dir, "main.lobster", main.String())
	if out, want := string(lobsterrun.Run(t, dir, "main.lobster", nil)), fmt.Sprintf("checked %d bad 0\n", n); out != want {
		t.Fatalf("main.lobster printed %q, want %q", out, want)
	}
}

// irDefault is the Lobster expression a scalar field is born equal to,
// computed from the IR alone; "" for a kind this check does not cover
// (128-bit values, strings, composites). A float is its bit pattern, an enum
// "Variant:<name>".
func irDefault(f *ir.Field) string {
	t := f.Type
	switch t.Kind {
	case ir.TBool:
		return strconv.FormatBool(f.HasDefault && f.DefBool)
	case ir.TInt, ir.TBits, ir.TFixed:
		if t.Width > 64 {
			return ""
		}
		if f.HasDefault && f.DefInt != nil {
			return IntLit(f.DefInt)
		}
		return "0"
	case ir.TFloat32, ir.TFloat64:
		v := 0.0
		if f.HasDefault {
			v = f.DefFloat
		}
		if t.Kind == ir.TFloat32 {
			v = float64(float32(v))
		}
		return lit(math.Float64bits(v))
	case ir.TNamed:
		switch r := t.Ref.(type) {
		case *ir.Enum:
			if f.HasDefault {
				return "Variant:" + f.DefVariant
			}
			return "Variant:None"
		case *ir.Flags:
			if f.HasDefault && f.DefInt != nil {
				return IntLit(f.DefInt)
			}
			_ = r
			return "0"
		}
	}
	return ""
}

// TestLobsterNumberModel pins THE NUMBER MODEL of docs/PORT-LOBSTER.md on the
// pinned toolchain through the runtime's helpers, each against Go's own
// answer: the logical right shift (an arithmetic >> then the mask, the count
// guarded at 0 and 64), the guarded left shift, the unsigned order by the
// flipped sign bit, and the float32 rounding of fround and of a float32
// default — Go's float32(v), round to nearest, ties to even, a value past
// float32's range to infinity. The control is the raw operators, which do
// what the model says they do: >> copies the sign and a count of 64 is 0.
func TestLobsterNumberModel(t *testing.T) {
	t.Parallel()
	src := t.TempDir()
	writeFile(t, src, "Tuning.schema", "package tuning\n\ntype Tuning\n{\n    gain  float32 = 0.1\n    exact float64 = 0.1\n    big   uint64 = 18446744073709551615\n}\n")
	files, err := Generate(unitFromDir(t, src))
	if err != nil {
		t.Fatal(err)
	}
	words := []uint64{0, 1, 0x7fffffffffffffff, 0x8000000000000000, 0xffffffffffffffff, 0x0123456789abcdef}
	counts := []int{0, 1, 7, 63, 64, 65}
	probes := []float64{0.1, 1 + math.Ldexp(1, -24), 1 + 3*math.Ldexp(1, -24), 3.5e38, math.Inf(-1), math.Copysign(0, -1)}
	var main strings.Builder
	main.WriteString("import .Tuning\n")
	var want []string
	for _, w := range words {
		for _, c := range counts {
			fmt.Fprintf(&main, "print(schema_rt.shr(%s, %d))\nprint(schema_rt.shl(%s, %d))\n", lit(w), c, lit(w), c)
			r, l := uint64(0), uint64(0)
			if c < 64 {
				r, l = w>>c, w<<c
			}
			want = append(want, strconv.FormatInt(int64(r), 10), strconv.FormatInt(int64(l), 10))
		}
		for _, x := range words {
			fmt.Fprintf(&main, "print(int(schema_rt.ult(%s, %s)))\n", lit(w), lit(x))
			b := 0
			if w < x {
				b = 1
			}
			want = append(want, strconv.Itoa(b))
		}
	}
	for _, p := range probes {
		fmt.Fprintf(&main, "print(schema_rt.f64bits(schema_rt.fround(schema_rt.f64frombits(%s))))\n", lit(math.Float64bits(p)))
		want = append(want, strconv.FormatInt(int64(math.Float64bits(float64(float32(p)))), 10))
	}
	main.WriteString("let v = tuning.NewTuning()\nprint(schema_rt.f64bits(v.Gain))\nprint(schema_rt.f64bits(v.Exact))\nprint(v.Big)\n")
	want = append(want, strconv.FormatInt(int64(math.Float64bits(float64(float32(0.1)))), 10), strconv.FormatInt(int64(math.Float64bits(0.1)), 10), "-1")
	// the control: the raw operators
	main.WriteString("print(0x8000000000000000 >> 63)\nprint(1 << 64)\n")
	want = append(want, "-1", "1")
	dir := t.TempDir()
	writeAll(t, dir, files)
	writeFile(t, dir, "main.lobster", main.String())
	got := strings.Split(strings.TrimRight(string(lobsterrun.Run(t, dir, "main.lobster", nil)), "\n"), "\n")
	if len(got) != len(want) {
		t.Fatalf("main.lobster printed %d lines, want %d:\n%s", len(got), len(want), strings.Join(got, "\n"))
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("line %d: lobster printed %s, Go says %s", i+1, got[i], want[i])
		}
	}
	_ = binary.LittleEndian
}

// TestLobsterImportsResolveInsideTheUnitOnly is the import rule of
// docs/PORT-LOBSTER.md, THE RUNTIME LAYOUT: every import a generated module
// makes is `import .<module>` — relative to the importing file's own
// directory, never the modules directories — and names a module the unit
// emits beside it. A shadowing Wire.lobster planted in the unit's modules/
// subdirectory (which a bare import would search) does not compile, so a
// unit that ran with it present did not load it.
func TestLobsterImportsResolveInsideTheUnitOnly(t *testing.T) {
	t.Parallel()
	u := unitFromDir(t, filepath.Join("..", "..", "..", "examples"))
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	imp := regexp.MustCompile(`(?m)^import (.*)$`)
	local := regexp.MustCompile(`^\.([A-Za-z0-9_]+)$`)
	for name, data := range files {
		for _, m := range imp.FindAllStringSubmatch(string(data), -1) {
			lm := local.FindStringSubmatch(m[1])
			if lm == nil {
				t.Errorf("%s: import %s is not a .<module> import inside the unit", name, m[1])
				continue
			}
			if _, ok := files[lm[1]+".lobster"]; !ok {
				t.Errorf("%s: import %s names a module the unit does not emit", name, m[1])
			}
		}
	}
	dir := t.TempDir()
	writeAll(t, dir, files)
	if err := os.Mkdir(filepath.Join(dir, "modules"), 0o755); err != nil {
		t.Fatal(err)
	}
	writeFile(t, filepath.Join(dir, "modules"), "Wire.lobster", "this is not lobster ((\n")
	writeFile(t, dir, "main.lobster", fmt.Sprintf("import .Wire\nimport .ArmDefaults\nassert %s.WeaponRailgun == 3 and %s.NewDefaultArm().EntriesCount == 0\nprint(\"inside\")\n", u.Package, u.Package))
	if out := string(lobsterrun.Run(t, dir, "main.lobster", nil)); out != "inside\n" {
		t.Fatalf("main.lobster printed %q", out)
	}
}

// lit is a 64-bit word as a Lobster int literal, spelled by IntLit's rule
// (the hex bit pattern where decimal would overflow).
func lit(w uint64) string {
	return IntLit(new(big.Int).SetInt64(int64(w)))
}

func unitFromDir(t *testing.T, dir string) *ir.Unit {
	t.Helper()
	paths, err := filepath.Glob(filepath.Join(dir, "*.schema"))
	if err != nil || len(paths) == 0 {
		t.Fatalf("no schema files under %s: %v", dir, err)
	}
	sort.Strings(paths)
	var files []check.SourceFile
	for _, p := range paths {
		src, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		name := filepath.Base(p)
		tree, errs := parser.Parse(name, src)
		if len(errs) != 0 {
			t.Fatalf("parse %s: %v", name, errs)
		}
		files = append(files, check.SourceFile{Path: p, Name: name, Base: strings.TrimSuffix(name, ".schema"), Bytes: src, AST: tree})
	}
	u, errs := check.Unit(files)
	if len(errs) != 0 {
		t.Fatalf("check: %v", errs)
	}
	return u
}

func writeAll(t *testing.T, dir string, files map[string][]byte) {
	t.Helper()
	for name, data := range files {
		writeFile(t, dir, name, string(data))
	}
}

func writeFile(t *testing.T, dir, name, data string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
}

func keysOf(files map[string][]byte) []string {
	out := make([]string, 0, len(files))
	for k := range files {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
