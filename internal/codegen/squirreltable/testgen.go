package squirreltable

import (
	"fmt"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

// Testgen writes the Squirrel leg's generated round-trip and damage tests
// (docs/SPEC-TABLES.md §16.11): one <Base>Table_gen_test.nut per unit file
// that declares a root table, runnable under the pinned interpreter with the
// generated modules beside it. Every table's value crosses the binary wire,
// the base64 text carrier and the JSON text and comes back equal; a damaged
// wire is refused by its named reason. A table whose forms leave out wire or
// json has no sample to spell and is refused by name. The output is
// deterministic to the byte: every sample is the table's declared defaults,
// built from the declaration alone.
func Testgen(u *ir.Unit) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, f := range u.Files {
		var roots []*ir.Struct
		for _, st := range f.Tables {
			// §16.11: a ROOT TABLE is every declared table; a generated map
			// entry or text-list element record is not one
			if st.IsTable && !st.IsMapEntry() {
				roots = append(roots, st)
			}
		}
		if len(roots) == 0 {
			continue
		}
		for _, st := range roots {
			// §16.11: the sample is spelled in the JSON form and the round
			// trip crosses the wire, so a table without either is refused
			for _, form := range []string{"wire", "json"} {
				if !st.CarriesForm(form) {
					return nil, fmt.Errorf("testgen: table %s does not carry the %s form, and its generated tests spell the sample in JSON and cross the wire (docs/SPEC-TABLES.md §16.11)", st.Name, form)
				}
			}
		}
		var b strings.Builder
		fmt.Fprintf(&b, "// Code generated by the schema compiler from %s.schema (schema testgen). DO NOT EDIT.\n", f.Base)
		b.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
		b.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
		b.WriteString("// AGPL-3.0, its output is not.\n")
		b.WriteString("// The round-trip and damage tests of mas-bandwidth/schema docs/SPEC-TABLES.md §16.11.\n\n")
		b.WriteString("local schema = dofile(\"schema_module.nut\", true);\n")
		fmt.Fprintf(&b, "local T = schema.require(%q);\n", ModuleName(u))
		b.WriteString("local J = schema.require(\"schema_table_json\");\n")
		b.WriteString("local L = schema.require(\"schema_table_load\");\n")
		b.WriteString("local S = schema.require(\"schema_table_save\");\n")
		b.WriteString("local TX = schema.require(\"schema_table_text\");\n")
		b.WriteString("local R = schema.require(\"schema_table_refusal\");\n\n")
		b.WriteString("local fresh = function() { return { unknown=0, kindMismatch=0, widened=0, clamped=0, duplicate=0, malformed=false, refused=false }; };\n")
		b.WriteString("local fail = function(why) { throw \"testgen: \" + why; };\n")
		b.WriteString("local covered = 0;\n\n")
		for _, st := range roots {
			fmt.Fprintf(&b, "local %s_gen = function() {\n", st.Name)
			fmt.Fprintf(&b, "  local root = %q;\n", st.Name)
			b.WriteString("  local v = T.Descriptors[root].make();\n")
			b.WriteString("  local text = J.ToJson(T, root, v);\n")
			b.WriteString("  if (text == null) fail(root + \": ToJson refused the sample\");\n")
			b.WriteString("  local x = J.FromJson(T, root, text, fresh());\n")
			b.WriteString("  if (x == null) fail(root + \": FromJson refused the JSON text\");\n")
			b.WriteString("  if (J.ToJson(T, root, x) != text) fail(root + \": the JSON text did not read back equal\");\n")
			b.WriteString("  local wire = S.save(T, root, v);\n")
			b.WriteString("  if (wire == null) fail(root + \": save refused the sample\");\n")
			b.WriteString("  local y = L.load(T, root, wire, fresh());\n")
			b.WriteString("  if (y == null) fail(root + \": load refused the wire\");\n")
			b.WriteString("  if (J.ToJson(T, root, y) != text) fail(root + \": the wire did not read back equal\");\n")
			b.WriteString("  local b64 = TX.SaveText(T, root, v);\n")
			b.WriteString("  if (b64 == null) fail(root + \": SaveText refused the sample\");\n")
			b.WriteString("  local z = TX.LoadText(T, root, b64, fresh());\n")
			b.WriteString("  if (z == null) fail(root + \": LoadText refused the base64 text\");\n")
			b.WriteString("  if (TX.SaveText(T, root, z) != b64) fail(root + \": the base64 text did not read back equal\");\n")
			b.WriteString("  local bw = TX.LoadText(T, root, b64 + \"?\", fresh());\n")
			b.WriteString("  if (bw != null) fail(root + \": a damaged base64 text was not refused by name\");\n")
			b.WriteString("  local cut = blob(wire.len());\n")
			b.WriteString("  for (local i = 0; i < wire.len(); i++) cut[i] = wire[i];\n")
			b.WriteString("  cut.resize(wire.len() - 1);\n")
			b.WriteString("  local dr = fresh();\n")
			b.WriteString("  local gone = R.ReadStrict(T, root, cut, dr);\n")
			b.WriteString("  if (gone != null || dr.reason == null) fail(root + \": a damaged wire was not refused by name\");\n")
			b.WriteString("  local jr = fresh();\n")
			b.WriteString("  local jx = J.FromJson(T, root, \"{\", jr);\n")
			b.WriteString("  if (jx != null && !jr.malformed) fail(root + \": a damaged JSON document was not refused by name\");\n")
			b.WriteString("  covered++;\n")
			b.WriteString("};\n")
			fmt.Fprintf(&b, "%s_gen();\n", st.Name)
		}
		b.WriteString("\nprint(\"testgen tables=\" + covered + \"\\n\");\n")
		fmt.Fprintf(&b, "if (covered != %d) fail(\"covered \" + covered + \" tables, the file declares %d\");\n", len(roots), len(roots))
		out[f.Base+"Table_gen_test.nut"] = []byte(b.String())
	}
	return out, nil
}
