// Package golang emits the Go target: one .go file per schema file, all in
// package <package>, deterministic to the byte (SPEC §6.1). Emitted source is
// passed through go/format before it is returned — the stdlib formatter is an
// in-process SYNTAX refuser (unparsable generated code fails generation
// loudly; symbol-level validity — no duplicate top-level names — is the
// checker's claimed-name registry's job), and it keeps the output gofmt-clean
// without an external formatter in the build path.
//
// Storage follows the §6.1 Go column: integer families name their storage
// directly, enums are integer-backed named types with prefixed variant
// constants, flags are a uint64-backed named type with mask constants,
// string(N)/bytes(N) are [N]byte plus an int32 used length, arrays are fixed
// Go arrays with an int32 used count beside the counted form. Nothing here
// heap-allocates per message.
//
// Functions follow the §6.3 Go row: free functions against the concrete
// WriteStream/ReadStream types (no interface dispatch), sticky stream errors,
// counts error-checked before loops, `return stream.Err()`.
package golang

import (
	"fmt"
	"go/format"
	"math/big"
	"strconv"
	"strings"

	"github.com/mas-bandwidth/schema/internal/ast"
	"github.com/mas-bandwidth/schema/internal/ir"
)

// Generate returns basename.go -> file contents for every file of the unit.
// Go packages are order-free across files, so unlike C++ there is no topo
// sort and no cross-file include graph to refuse.
func Generate(u *ir.Unit) (map[string][]byte, error) {
	out := map[string][]byte{}
	home := protocolIdHome(u)
	msgOwner := ir.MessageOwner(u)
	objOwner := ir.ObjectOwner(u)
	for _, f := range u.Files {
		g := &gen{unit: u, file: f, msgOwner: msgOwner, objOwner: objOwner}
		g.emitFile(f.Base == home)
		src, err := format.Source(g.assemble())
		if err != nil {
			return nil, fmt.Errorf("generated Go for %s does not parse — a compiler bug, not a schema error: %v", f.Path, err)
		}
		out[f.Base+".go"] = src
	}
	return out, nil
}

// protocolIdHome picks the file that carries ProtocolId and ErrValidation:
// the constants aspect file if the unit has one, else the first.
func protocolIdHome(u *ir.Unit) string {
	for _, f := range u.Files {
		if f.Base == "Constants" {
			return f.Base
		}
	}
	if len(u.Files) > 0 {
		return u.Files[0].Base
	}
	return ""
}

type gen struct {
	unit     *ir.Unit
	file     *ir.File
	msgOwner string // the one file that carries the message dispatch surface
	objOwner string // the one file that carries the object tag surface

	body           strings.Builder
	needsSerialize bool // the file emits wire functions -> import the runtime
	needsMath      bool // the file emits math.Floor -> import math
	needsErrors    bool // the file declares ErrValidation -> import errors
}

func (g *gen) pf(format string, args ...any) {
	fmt.Fprintf(&g.body, format, args...)
}

func (g *gen) assemble() []byte {
	var h strings.Builder
	// the basename, not the invocation-relative path: output is deterministic
	// to the byte wherever the compiler runs (SPEC §6.1)
	fmt.Fprintf(&h, "// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", g.file.Base)
	fmt.Fprintf(&h, "// package %s — protocol id 0x%016x\n\n", g.unit.Package, g.unit.ProtocolId)
	fmt.Fprintf(&h, "package %s\n\n", g.unit.Package)
	var std, ext []string
	if g.needsErrors {
		std = append(std, `"errors"`)
	}
	if g.needsMath {
		std = append(std, `"math"`)
	}
	if g.needsSerialize {
		ext = append(ext, `"github.com/mas-bandwidth/serialize.go"`)
	}
	if len(std)+len(ext) > 0 {
		h.WriteString("import (\n")
		for _, imp := range std {
			fmt.Fprintf(&h, "\t%s\n", imp)
		}
		if len(std) > 0 && len(ext) > 0 {
			h.WriteString("\n")
		}
		for _, imp := range ext {
			fmt.Fprintf(&h, "\t%s\n", imp)
		}
		h.WriteString(")\n\n")
	}
	h.WriteString(g.body.String())
	return []byte(h.String())
}

func (g *gen) emitFile(carriesProtocolId bool) {
	if carriesProtocolId {
		g.needsErrors = true
		g.pf("// The unit's protocol id — the hash of its schema files (SPEC §3.1). Two\n")
		g.pf("// sides at the same id speak identical bits; there is no other versioning.\n")
		g.pf("const ProtocolId uint64 = 0x%016x\n\n", g.unit.ProtocolId)
		g.pf("// ErrValidation is returned when a read rejects the wire: a wrong constant,\n")
		g.pf("// nonzero reserved bits, or an interior null in a string (SPEC §4.3, §4.7).\n")
		g.pf("var ErrValidation = errors.New(\"%s: wire validation failed\")\n\n", g.unit.Package)
	}

	// MessageType / ObjectType lead their OWNER file — the unit-level surface
	// is emitted exactly once, in the topologically last carrying file, so
	// declarations spread across files never redeclare it in the package
	// (SPEC §2 keeps the aspect layout non-enforced; ir.MessageOwner picks).
	if g.file.Base == g.msgOwner && len(g.unit.Messages) > 0 {
		g.emitTagEnum("MessageType", g.unit.Messages,
			"the message set, extracted by the compiler — None = 0, then each message sorted by name (SPEC §4.8)")
	}
	if g.file.Base == g.objOwner && len(g.unit.ObjNames) > 0 {
		g.emitTagEnum("ObjectType", g.unit.ObjNames,
			"the object set, extracted by the compiler — None = 0, then each object sorted by name (SPEC §4.8)")
	}

	// declaration order — schema references are order-free and so is Go
	for _, d := range g.file.Decls {
		switch d := d.(type) {
		case *ir.Const:
			g.emitConst(d)
		case *ir.Enum:
			g.emitEnum(d)
		case *ir.Flags:
			g.emitFlags(d)
		case *ir.ContextsMarker:
			g.pf("// contexts declared for this unit: %s (SPEC §4.2).\n", strings.Join(d.Names, ", "))
			g.pf("// Contexts generate no standalone artifacts — where an object carries\n")
			g.pf("// context-scoped [local] fields, its State struct is generated once per\n")
			g.pf("// context (ClientShipState, ServerShipState, ...), each holding the `all`\n")
			g.pf("// fields plus its own context's. No build tags in this target.\n\n")
		case *ir.Struct:
			g.emitStruct(d)
			g.emitConstructor(d)
			g.emitStructFunctions(d)
		case *ir.Object:
			g.emitObject(d)
			g.emitObjectFunctions(d)
		}
	}

	if g.file.Base == g.msgOwner && len(g.unit.Messages) > 0 {
		g.emitMessageTagFunctions()
	}
	if g.file.Base == g.objOwner && len(g.unit.ObjNames) > 0 {
		g.emitObjectTagFunctions()
	}
}

func (g *gen) emitTagEnum(name string, members []string, comment string) {
	g.pf("// %s: %s\n", name, comment)
	g.pf("type %s %s\n\n", name, goUint(ir.StorageBitsFor(int64(len(members)))))
	g.pf("const (\n")
	g.pf("\t%sNone %s = 0\n", name, name)
	for i, m := range members {
		g.pf("\t%s%s %s = %d\n", name, m, name, i+1)
	}
	g.pf(")\n\n")
}

// emitConst emits a bare schema const as an UNTYPED Go constant — usable as an
// array length, a wire argument, anything — and an explicitly-typed schema
// const as a typed one (the declared type pins the exported type, SPEC §4.2).
func (g *gen) emitConst(d *ir.Const) {
	typ := ""
	if d.Explicit {
		typ = " " + d.Storage
	}
	if d.IsFloat {
		g.pf("const %s%s = %s%s\n\n", d.Name, typ, formatFloat(d.Float), g.foldComment(d.Expr))
		return
	}
	g.pf("const %s%s = %s%s\n\n", d.Name, typ, g.renderInt(d.Expr, d.Int), g.foldComment(d.Expr))
}

// foldComment returns a trailing comment carrying the schema expression when
// the rendered Go had to fold it (an E.Max reference has no Go twin).
func (g *gen) foldComment(e ast.Expr) string {
	if e != nil && containsMax(e) {
		return fmt.Sprintf(" // = %s", schemaExpr(e))
	}
	return ""
}

func (g *gen) emitEnum(d *ir.Enum) {
	g.pf("// %s — None = 0 implicit, variants dense from 1, wire range [0, %d] (SPEC §4.2)\n", d.Name, d.Max)
	g.pf("type %s %s\n\n", d.Name, goUint(d.StorageBits))
	g.pf("const (\n")
	g.pf("\t%sNone %s = 0\n", d.Name, d.Name)
	for i, v := range d.Variants {
		g.pf("\t%s%s %s = %d\n", d.Name, v, d.Name, i+1)
	}
	g.pf(")\n\n")
}

func (g *gen) emitFlags(d *ir.Flags) {
	g.pf("// %s — one bit per variant, consumed as masks; storage uint64 in every\n", d.Name)
	g.pf("// target, wire %d bits (SPEC §4.2)\n", d.WireBits)
	g.pf("type %s uint64\n\n", d.Name)
	g.pf("const (\n")
	for i, v := range d.Variants {
		g.pf("\t%s%s %s = 1 << %d\n", d.Name, v, d.Name, i)
	}
	g.pf(")\n\n")
}

func (g *gen) emitStruct(d *ir.Struct) {
	kind := "type"
	if d.IsMessage {
		kind = "message"
	}
	if len(d.Tags) > 0 {
		g.pf("// %s %s [%s] — the tag is user-chosen and inert in v1; the delta pass\n", kind, d.Name, strings.Join(d.Tags, ", "))
		g.pf("// claims tags and assigns actions (SPEC §4.2, Type tags)\n")
	} else {
		g.pf("// %s %s\n", kind, d.Name)
	}
	g.pf("type %s struct {\n", d.Name)
	g.emitFields(d.Fields, storageDeep)
	g.pf("}\n\n")
}

// emitConstructor emits NewX for a struct whose zero value is not its declared
// initial value — i.e. it (or a composed type) carries specified defaults.
// Everything else takes Go's zero value, which IS the schema's zero rule.
func (g *gen) emitConstructor(d *ir.Struct) {
	if !g.hasDefaults(d) {
		return
	}
	g.pf("// New%s returns a %s with its specified defaults applied; the plain zero\n", d.Name, d.Name)
	g.pf("// value is the all-zero form (SPEC §4.2: zero initialization unless a\n")
	g.pf("// specified default overrides it).\n")
	g.pf("func New%s() %s {\n", d.Name, d.Name)
	g.pf("\tvar value %s\n", d.Name)
	for _, f := range d.Fields {
		g.emitDefaultInit(f)
	}
	g.pf("\treturn value\n}\n\n")
}

// hasDefaults reports whether a struct transitively carries a specified default.
func (g *gen) hasDefaults(d *ir.Struct) bool {
	seen := map[string]bool{}
	var walk func(st *ir.Struct) bool
	walk = func(st *ir.Struct) bool {
		if seen[st.Name] {
			return false
		}
		seen[st.Name] = true
		for _, f := range st.Fields {
			if f.HasDefault {
				return true
			}
			if f.Type.Kind == ir.TNamed {
				if inner, ok := f.Type.Ref.(*ir.Struct); ok && walk(inner) {
					return true
				}
			}
		}
		return false
	}
	return walk(d)
}

func (g *gen) emitDefaultInit(f *ir.Field) {
	name := "value." + ir.GoExportName(f.Name)
	if f.HasDefault {
		g.pf("\t%s = %s\n", name, g.defaultValue(f))
		return
	}
	if f.Type.Kind != ir.TNamed {
		return
	}
	inner, ok := f.Type.Ref.(*ir.Struct)
	if !ok || !g.hasDefaults(inner) {
		return
	}
	if f.Array != ir.ArrayNone {
		g.pf("\tfor i := range %s {\n\t\t%s[i] = New%s()\n\t}\n", name, name, inner.Name)
		return
	}
	g.pf("\t%s = New%s()\n", name, inner.Name)
}

func (g *gen) defaultValue(f *ir.Field) string {
	switch {
	case f.Type.Kind == ir.TBool:
		return fmt.Sprintf("%v", f.DefBool)
	case f.DefVariant != "":
		return f.Type.Name + f.DefVariant
	case f.Type.Kind == ir.TFloat32 || f.Type.Kind == ir.TFloat64:
		return formatFloat(f.DefFloat)
	default:
		return g.renderInt(f.DefExpr, f.DefInt)
	}
}

// view selects which storage a field emission derives (SPEC §4.8).
type view int

const (
	storageDeep    view = iota // declared storage — State and Data_Deep
	storageShallow             // quantized wire storage
	storageInterp              // interpolate storage: projected fields wire-int, composites continuous
)

func (g *gen) emitObject(d *ir.Object) {
	g.pf("// ---- object %s — one definition, a generated family per target (SPEC §4.8) ----\n\n", d.Name)

	if hasContextFields(d) {
		for _, ctx := range g.unit.Contexts {
			var fields []*ir.Field
			for _, f := range d.Fields {
				if f.Context == "" || f.Context == ctx {
					fields = append(fields, f)
				}
			}
			g.pf("// %s%sState — the full simulation struct for the %s context: every `all`\n", capitalize(ctx), d.Name, ctx)
			g.pf("// field plus the fields scoped [local, context = %s]\n", ctx)
			g.pf("type %s%sState struct {\n", capitalize(ctx), d.Name)
			g.emitFields(fields, storageDeep)
			g.pf("}\n\n")
		}
	} else {
		g.pf("// %sState — the full simulation struct: every field\n", d.Name)
		g.pf("type %sState struct {\n", d.Name)
		g.emitFields(d.Fields, storageDeep)
		g.pf("}\n\n")
	}

	deep, interp := splitObjectFields(d)

	g.pf("// %sData_Deep — every non-[local] field, deep encodings: full state for\n", d.Name)
	g.pf("// client-side prediction\n")
	g.pf("type %sData_Deep struct {\n", d.Name)
	g.emitFields(deep, storageDeep)
	g.pf("}\n\n")

	g.pf("// %sData_Shallow — the [interpolate] fields on the quantized wire: the\n", d.Name)
	g.pf("// implementation detail on the way to interpolation on the client\n")
	g.pf("type %sData_Shallow struct {\n", d.Name)
	g.emitFields(interp, storageShallow)
	g.pf("}\n\n")

	g.pf("// %sData_Interpolate — the same fields in interpolate storage: projected\n", d.Name)
	g.pf("// fields stay in the wire integer domain and snap-interpolate; quantized\n")
	g.pf("// composites store continuous (SPEC §4.8 rule 5)\n")
	g.pf("type %sData_Interpolate struct {\n", d.Name)
	g.emitFields(interp, storageInterp)
	g.pf("}\n\n")
}

func splitObjectFields(d *ir.Object) (deep, interp []*ir.Field) {
	for _, f := range d.Fields {
		if !f.Local {
			deep = append(deep, f)
		}
		if f.Interpolate {
			interp = append(interp, f)
		}
	}
	return
}

func hasContextFields(d *ir.Object) bool {
	for _, f := range d.Fields {
		if f.Context != "" {
			return true
		}
	}
	return false
}

func (g *gen) emitFields(fields []*ir.Field, v view) {
	prevGuard := ""
	for _, f := range fields {
		if f.Guard != prevGuard {
			if f.Guard != "" {
				g.pf("\n\t// %s — wire branch; storage holds both sides, a read zeroes the\n", f.Guard)
				g.pf("\t// untaken side (SPEC §5)\n")
			} else {
				g.pf("\n") // leaving a branch group — separate so membership stays visible
			}
			prevGuard = f.Guard
		}
		g.emitField(f, v)
	}
}

func (g *gen) emitField(f *ir.Field, v view) {
	name := ir.GoExportName(f.Name)
	if v == storageShallow && f.HasQuantize {
		st := f.Type.Ref.(*ir.Struct)
		g.pf("\t// %s: %s quantized by %s, max %s — per-component int in [-%d, %d]\n",
			f.Name, f.Type.Name, schemaExpr(f.QuantScaleExpr), schemaExpr(f.QuantMaxExpr), f.QuantBound, f.QuantBound)
		typ := goInt(smallestSigned(f.QuantBound))
		for _, comp := range st.Fields {
			g.pf("\t%s%s %s\n", name, ir.GoExportName(comp.Name), typ)
		}
		return
	}
	if (v == storageShallow || v == storageInterp) && f.HasFloatRange {
		typ := goUint(ir.StorageBitsFor(f.Steps))
		note := ""
		if f.Round != "nearest" {
			note = ", round " + f.Round
		}
		tail := ""
		if v == storageInterp {
			tail = " — wire-int domain, snap-interpolated (SPEC §4.8 rule 5)"
		}
		g.pf("\t%s %s // float [%s, %s] @ resolution %s -> wire int [0, %d]%s%s\n",
			name, typ, formatFloat(f.FMin), formatFloat(f.FMax),
			formatFloat(f.Resolution), f.Steps, note, tail)
		return
	}
	g.emitStorageField(f)
}

func (g *gen) emitStorageField(f *ir.Field) {
	name := ir.GoExportName(f.Name)
	typ := g.goFieldType(f.Type)

	switch {
	case f.Type.Kind == ir.TString:
		g.pf("\t%s [%s]byte // string(%s): max length, used length beside it (SPEC §4.7)\n",
			name, g.renderInt(f.Type.SizeExpr, big.NewInt(f.Type.Size)), schemaExpr(f.Type.SizeExpr))
		g.pf("\t%sLength int32\n", name)
	case f.Type.Kind == ir.TBytes:
		g.pf("\t%s [%s]byte // bytes(%s): fixed buffer, used length beside it (SPEC §4.7)\n",
			name, g.renderInt(f.Type.SizeExpr, big.NewInt(f.Type.Size)), schemaExpr(f.Type.SizeExpr))
		g.pf("\t%sLength int32\n", name)
	case f.Array == ir.ArrayFixed:
		g.pf("\t%s [%s]%s%s\n", name, g.renderInt(f.ArrayExpr, big.NewInt(f.ArrayBound)), typ, g.fieldComment(f))
	case f.Array == ir.ArrayCounted:
		g.pf("\t%s [%s]%s // used count beside it; wire count in [%d, %s]\n",
			name, g.renderInt(f.ArrayExpr, big.NewInt(f.ArrayBound)), typ, f.ArrayMin, g.renderInt(f.ArrayExpr, big.NewInt(f.ArrayBound)))
		g.pf("\t%sCount int32\n", name)
	default:
		g.pf("\t%s %s%s\n", name, typ, g.fieldComment(f))
	}
}

func (g *gen) fieldComment(f *ir.Field) string {
	var parts []string
	if f.HasDefault {
		parts = append(parts, fmt.Sprintf("= %s in New* (zero value otherwise)", g.defaultValue(f)))
	}
	if f.HasIntRange {
		parts = append(parts, fmt.Sprintf("wire [%s, %s]", f.IntMin, f.IntMax))
	}
	if f.HasFloatRange {
		note := ""
		if f.Round != "nearest" {
			note = ", round " + f.Round
		}
		if f.Interpolate {
			parts = append(parts, fmt.Sprintf("shallow wire: [%s, %s] @ %s -> int [0, %d]%s",
				formatFloat(f.FMin), formatFloat(f.FMax), formatFloat(f.Resolution), f.Steps, note))
		} else {
			parts = append(parts, fmt.Sprintf("compressed float [%s, %s] @ %s%s",
				formatFloat(f.FMin), formatFloat(f.FMax), formatFloat(f.Resolution), note))
		}
	}
	if f.Local {
		if f.Context != "" {
			parts = append(parts, fmt.Sprintf("[local, context = %s]", f.Context))
		} else {
			parts = append(parts, "[local] — no wire")
		}
	}
	if len(parts) == 0 {
		return ""
	}
	return " // " + strings.Join(parts, "; ")
}

// goFieldType maps a field type to its Go storage (SPEC §6.1).
func (g *gen) goFieldType(t ir.FieldType) string {
	switch t.Kind {
	case ir.TInt:
		return goInt2(t.Signed, t.Width)
	case ir.TBits:
		if t.Width <= 32 {
			return "uint32"
		}
		return "uint64"
	case ir.TBool:
		return "bool"
	case ir.TFloat32:
		return "float32"
	case ir.TFloat64:
		return "float64"
	case ir.TNamed:
		return t.Name
	}
	return "/* ? */"
}

// renderInt renders an integer expression symbolically where every referenced
// constant is a BARE (untyped) schema const — safe in any Go context — and
// folds to the computed value otherwise (typed consts would force conversions;
// an E.Max reference always folds; the schema source rides in a comment).
func (g *gen) renderInt(e ast.Expr, folded *big.Int) string {
	if e == nil || containsMax(e) || !g.renderable(e) {
		return folded.String()
	}
	return renderExpr(e)
}

func (g *gen) renderable(e ast.Expr) bool {
	switch e := e.(type) {
	case *ast.IdentExpr:
		c, ok := g.unit.Consts[e.Name]
		return ok && !c.IsFloat && !c.Explicit
	case *ast.UnaryExpr:
		return g.renderable(e.X)
	case *ast.BinaryExpr:
		return g.renderable(e.X) && g.renderable(e.Y)
	case *ast.ParenExpr:
		return g.renderable(e.X)
	}
	return true
}

func renderExpr(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.IntLit:
		return e.Text
	case *ast.FloatLit:
		return e.Text
	case *ast.IdentExpr:
		return e.Name
	case *ast.UnaryExpr:
		return "-" + renderExpr(e.X)
	case *ast.BinaryExpr:
		return fmt.Sprintf("%s %s %s", renderExpr(e.X), e.Op, renderExpr(e.Y))
	case *ast.ParenExpr:
		return "(" + renderExpr(e.X) + ")"
	}
	return "?"
}

// schemaExpr renders an expression in schema source form, for comments.
func schemaExpr(e ast.Expr) string {
	switch e := e.(type) {
	case *ast.IntLit:
		return e.Text
	case *ast.FloatLit:
		return e.Text
	case *ast.IdentExpr:
		return e.Name
	case *ast.MaxExpr:
		return e.Enum + ".Max"
	case *ast.UnaryExpr:
		return "-" + schemaExpr(e.X)
	case *ast.BinaryExpr:
		return fmt.Sprintf("%s %s %s", schemaExpr(e.X), e.Op, schemaExpr(e.Y))
	case *ast.ParenExpr:
		return "(" + schemaExpr(e.X) + ")"
	}
	return "?"
}

func containsMax(e ast.Expr) bool {
	switch e := e.(type) {
	case *ast.MaxExpr:
		return true
	case *ast.UnaryExpr:
		return containsMax(e.X)
	case *ast.BinaryExpr:
		return containsMax(e.X) || containsMax(e.Y)
	case *ast.ParenExpr:
		return containsMax(e.X)
	}
	return false
}

func goInt2(signed bool, width int) string {
	if signed {
		return fmt.Sprintf("int%d", width)
	}
	return fmt.Sprintf("uint%d", width)
}

func goInt(width int) string  { return fmt.Sprintf("int%d", width) }
func goUint(width int) string { return fmt.Sprintf("uint%d", width) }

func smallestSigned(bound int64) int {
	switch {
	case bound <= 127:
		return 8
	case bound <= 32767:
		return 16
	case bound <= 2147483647:
		return 32
	default:
		return 64
	}
}

func formatFloat(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

// formatFloat32 renders a compressed-float parameter at FLOAT32 precision:
// the shortest literal that parses to exactly float32(v) in every target
// language — the same narrowing ir.CompressedFloatBits computes widths with,
// so all four targets and the advertised MaxBits agree even at f32 rounding
// ties (a 64-bit literal re-rounded per-language can land on different f32s).
func formatFloat32(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 32)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

func capitalize(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}
