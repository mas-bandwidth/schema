// Package golang emits the Go target: one .go file per schema file, all in
// package <package>, deterministic to the byte (SPEC §6.1). Emitted source is
// passed through go/format before it is returned — the stdlib formatter is an
// in-process SYNTAX refuser (unparsable generated code fails generation
// loudly; symbol-level validity — no duplicate top-level names — is the
// checker's claimed-name registry's job), and it keeps the output gofmt-clean
// without an external formatter in the build path.
//
// Storage follows the §6.1 Go column: integer families name their storage
// directly, enums are integer-backed named types with prefixed variant
// constants, flags are a uint64-backed named type with mask constants,
// string(N)/bytes(N) are [N]byte plus an int32 used length, arrays are fixed
// Go arrays with an int32 used count beside the counted form. Nothing here
// heap-allocates per value.
//
// Functions follow the §6.3 Go row: free functions against the concrete
// WriteStream/ReadStream types (no interface dispatch), sticky stream errors,
// counts error-checked before loops, `return stream.Err()`.
package golang

import (
	"fmt"
	"go/format"
	"math/big"
	"strconv"
	"strings"

	"github.com/mas-bandwidth/schema/v2/internal/ast"
	"github.com/mas-bandwidth/schema/v2/ir"
)

// Generate returns basename.go -> file contents for every file of the unit.
// Go packages are order-free across files, so unlike C++ there is no topo
// sort and no cross-file include graph to refuse.
func Generate(u *ir.Unit) (map[string][]byte, error) {
	// fixed(I, F), int128 and uint128: serialize.go carries the full surface
	// (the two-qword Int128/Uint128 pair, SerializeInt128/SerializeUint128,
	// SerializeFixed64/SerializeFixed128) — storage maps to the pair at 128
	// bits, wire calls mirror the C++ macros.
	out := map[string][]byte{}
	home := ir.ProtocolIdHome(u)
	for _, f := range u.Files {
		g := &gen{unit: u, file: f}
		g.emitFile(f.Base == home)
		src, err := format.Source(g.assemble())
		if err != nil {
			return nil, fmt.Errorf("generated Go for %s does not parse — a compiler bug, not a schema error: %w", f.Path, err)
		}
		out[f.Base+".go"] = src
	}
	return out, nil
}

type gen struct {
	unit *ir.Unit
	file *ir.File

	body           strings.Builder
	needsSerialize bool // the file emits wire functions -> import the runtime
	needsMath      bool // the file emits math.Floor -> import math
	needsErrors    bool // the file declares ErrValidation -> import errors
	needsStrconv   bool // the file emits FlagNames* -> import strconv

	// bulkBytes marks the current struct's statically byte-aligned [N]uint8
	// arrays (ir.AlignedFixedByteArrays): these serialize through the
	// runtime's bulk-bytes path instead of a per-byte loop — byte-identical
	// wire, proven by the position analysis and re-proven by the wire goldens
	bulkBytes map[*ir.Field]bool
}

func (g *gen) pf(format string, args ...any) {
	fmt.Fprintf(&g.body, format, args...)
}

func (g *gen) assemble() []byte {
	var h strings.Builder
	// the basename, not the invocation-relative path: output is deterministic
	// to the byte wherever the compiler runs (SPEC §6.1)
	fmt.Fprintf(&h, "// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", g.file.Base)
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&h, "// package %s — protocol id 0x%016x\n\n", g.unit.Package, g.unit.ProtocolId)
	fmt.Fprintf(&h, "package %s\n\n", g.unit.Package)
	var std, ext []string
	if g.needsErrors {
		std = append(std, `"errors"`)
	}
	if g.needsMath {
		std = append(std, `"math"`)
	}
	if g.needsStrconv {
		std = append(std, `"strconv"`)
	}
	if g.needsSerialize {
		ext = append(ext, `"github.com/mas-bandwidth/serialize.go"`)
	}
	if len(std)+len(ext) > 0 {
		h.WriteString("import (\n")
		for _, imp := range std {
			fmt.Fprintf(&h, "\t%s\n", imp)
		}
		if len(std) > 0 && len(ext) > 0 {
			h.WriteString("\n")
		}
		for _, imp := range ext {
			fmt.Fprintf(&h, "\t%s\n", imp)
		}
		h.WriteString(")\n\n")
	}
	h.WriteString(g.body.String())
	return []byte(h.String())
}

func (g *gen) emitFile(carriesProtocolId bool) {
	if carriesProtocolId {
		g.needsErrors = true
		g.pf("// The unit's protocol id — the hash of its wire shape (SPEC §3.1). Two\n")
		g.pf("// sides at the same id speak identical bits; there is no other versioning.\n")
		g.pf("const ProtocolId uint64 = 0x%016x\n\n", g.unit.ProtocolId)
		g.pf("// ErrValidation is returned when a read rejects the wire: a wrong constant,\n")
		g.pf("// nonzero reserved bits, or an interior null in a string (SPEC §4.3, §4.7).\n")
		g.pf("var ErrValidation = errors.New(\"%s: wire validation failed\")\n\n", g.unit.Package)
	}

	// declaration order — schema references are order-free and so is Go
	for _, d := range g.file.Decls {
		switch d := d.(type) {
		case *ir.Const:
			g.emitConst(d)
		case *ir.Enum:
			g.emitEnum(d)
		case *ir.Flags:
			g.emitFlags(d)
		case *ir.Struct:
			g.emitStruct(d)
			g.emitConstructor(d)
			g.emitStructFunctions(d)
		case *ir.Union:
			g.emitUnion(d)
			g.emitUnionFunctions(d)
		}
	}
}

// emitTagEnum emits a union's tag type. docs is each arm's doc comment
// (SPEC §4.1), parallel to members: it reaches the tag's constant as a line
// comment, the one place the arm is a declaration of its own.
func (g *gen) emitTagEnum(name string, members []string, docs []string, comment string) {
	g.pf("// %s: %s\n", name, comment)
	g.pf("type %s %s\n\n", name, goUint(ir.StorageBitsFor(int64(len(members)))))
	g.pf("const (\n")
	g.pf("\t%sNone %s = 0\n", name, name)
	for i, m := range members {
		g.pf("%s", ir.DocComment(docs[i], "\t", "//"))
		g.pf("\t%s%s %s = %d\n", name, m, name, i+1)
	}
	g.pf("\t%sCount %s = %d // the declared variant count (SPEC §4.2)\n", name, name, len(members))
	g.pf("\t%sMax %s = %d // the exported extent (SPEC §4.2)\n", name, name, len(members))
	g.pf(")\n\n")

	// the tag enum's name surface is a declared enum's, member for member: a
	// reader logging which message arrived writes EnumName<Tag>( value )
	// whichever enum it is. Nothing on the read or write path calls it. The
	// uint64 parameter (not the tag type) keeps out-of-set values exact.
	g.pf("// EnumName%s: debug/log/tooling name for any %s wire value —\n", name, name)
	g.pf("// out-of-set values (wire-legal up to the declared max) name as \"???\"\n")
	g.pf("func EnumName%s(value uint64) string {\n", name)
	g.pf("\tswitch value {\n")
	g.pf("\tcase uint64(%sNone):\n\t\treturn \"None\"\n", name)
	for _, m := range members {
		g.pf("\tcase uint64(%s%s):\n\t\treturn \"%s\"\n", name, m, m)
	}
	g.pf("\t}\n\treturn \"???\"\n}\n\n")
}

// emitConst emits a bare INTEGER schema const as an UNTYPED Go constant —
// usable as an array length, a wire argument, anything — and an
// explicitly-typed schema const as a typed one (the declared type pins the
// exported type, SPEC §4.2). A FLOAT const is always typed: a bare float
// const infers float64 (SPEC §4.2, Go's literal rule), and the export must
// be the same surface the explicit annotation spells — every other target
// already pins the type either way.
func (g *gen) emitConst(d *ir.Const) {
	typ := ""
	if d.Explicit {
		typ = " " + d.Storage
	}
	g.pf("%s", ir.DocComment(d.Doc, "", "//"))
	if d.IsFloat {
		g.pf("const %s %s = %s%s\n\n", d.Name, d.Storage, formatFloat(d.Float), g.foldComment(d.Expr))
		return
	}
	g.pf("const %s%s = %s%s\n\n", d.Name, typ, g.renderInt(d.Expr, d.Int), g.foldComment(d.Expr))
}

// foldComment returns a trailing comment carrying the schema expression when
// the rendered Go had to fold it (an E.Max reference has no Go twin).
func (g *gen) foldComment(e ast.Expr) string {
	if e != nil && ir.ExprHasEnumMax(e) {
		return fmt.Sprintf(" // = %s", ir.RenderExpr(e))
	}
	return ""
}

// emitUnion emits a first-class one-of (SPEC §4.8): the <Name>Type tag enum,
// then the interface-free storage — the tag beside one pre-allocated arm per
// variant. Nothing heap-allocates per value; the zero value IS None.
func (g *gen) emitUnion(d *ir.Union) {
	members := make([]string, len(d.Variants))
	docs := make([]string, len(d.Variants))
	for i, v := range d.Variants {
		members[i] = ir.GoExportName(v.Name)
		docs[i] = v.Doc
	}
	g.emitTagEnum(d.Name+"Type", members, docs,
		fmt.Sprintf("union %s's tag — None = 0, then each variant in declared order (SPEC §4.8)", d.Name))

	g.pf("%s", ir.DocComment(d.Doc, "", "//"))
	g.pf("// %s — at most one of the arms; Type says which. The zero value is the\n", d.Name)
	g.pf("// empty union (None). A read constructs the selected arm with its defaults before\n")
	g.pf("// decoding it (SPEC §5); unselected arms keep what they last held — the\n")
	g.pf("// reused-storage discipline. Consumers read the selected arm only.\n")
	g.pf("type %s struct {\n", d.Name)
	g.pf("\tType %sType\n", d.Name)
	for _, v := range d.Variants {
		if v.Void() {
			continue // a PAYLOAD-FREE arm has no storage (SPEC §4.8)
		}
		g.pf("\t%s %s\n", ir.GoExportName(v.Name), v.Type)
	}
	g.pf("}\n\n")
}

func (g *gen) emitEnum(d *ir.Enum) {
	g.pf("%s", ir.DocComment(d.Doc, "", "//"))
	g.pf("// %s — None = 0 implicit, variants dense from 1, wire range [0, %d] (SPEC §4.2)\n", d.Name, d.Max)
	g.pf("type %s %s\n\n", d.Name, goUint(d.StorageBits))
	g.pf("const (\n")
	g.pf("\t%sNone %s = 0\n", d.Name, d.Name)
	for i, v := range d.Variants {
		g.pf("%s", ir.DocComment(d.VariantDocs[i], "\t", "//"))
		g.pf("\t%s%s %s = %d\n", d.Name, v, d.Name, i+1)
	}
	g.pf("\t%sCount %s = %d // the declared variant count (SPEC §4.2)\n", d.Name, d.Name, len(d.Variants))
	g.pf("\t%sMax %s = %d // the exported extent (SPEC §4.2)\n", d.Name, d.Name, d.Max)
	g.pf(")\n\n")
	// the uint64 parameter (not the enum type) keeps out-of-set values exact:
	// a narrower named type would truncate 256 -> 0 -> "None" for an 8-bit enum
	g.pf("// EnumName%s: debug/log/tooling name for any %s wire value —\n", d.Name, d.Name)
	g.pf("// out-of-set values (wire-legal up to the declared max) name as \"???\"\n")
	g.pf("func EnumName%s(value uint64) string {\n", d.Name)
	g.pf("\tswitch value {\n")
	g.pf("\tcase uint64(%sNone):\n\t\treturn \"None\"\n", d.Name)
	for _, v := range d.Variants {
		g.pf("\tcase uint64(%s%s):\n\t\treturn \"%s\"\n", d.Name, v, v)
	}
	g.pf("\t}\n\treturn \"???\"\n}\n\n")
}

func (g *gen) emitFlags(d *ir.Flags) {
	g.pf("%s", ir.DocComment(d.Doc, "", "//"))
	g.pf("// %s — one bit per variant, consumed as masks; storage uint64 in every\n", d.Name)
	g.pf("// target, wire %d bits (SPEC §4.2)\n", d.WireBits)
	g.pf("type %s uint64\n\n", d.Name)
	g.pf("const (\n")
	for i, v := range d.Variants {
		g.pf("%s", ir.DocComment(d.VariantDocs[i], "\t", "//"))
		g.pf("\t%s%s %s = 1 << %d\n", d.Name, v, d.Name, i)
	}
	g.pf(")\n\n")
	g.pf("// %sCount is the declared variant count (SPEC §4.2).\n", d.Name)
	g.pf("const %sCount = %d\n\n", d.Name, len(d.Variants))

	g.pf("// FlagName%s: debug/log/tooling name for bit i of %s —\n", d.Name, d.Name)
	g.pf("// out-of-range bits name as \"???\"\n")
	g.pf("func FlagName%s(bit int) string {\n", d.Name)
	g.pf("\tswitch bit {\n")
	for i, v := range d.Variants {
		g.pf("\tcase %d:\n\t\treturn \"%s\"\n", i, v)
	}
	g.pf("\t}\n\treturn \"???\"\n}\n\n")

	g.needsStrconv = true
	g.pf("// FlagNames%s renders the set bits of value as \"A|B\" — \"0\" for the\n", d.Name)
	g.pf("// empty set, bits past the declared variants as hex\n")
	g.pf("func FlagNames%s(value uint64) string {\n", d.Name)
	g.pf("\tnames := \"\"\n")
	for i, v := range d.Variants {
		g.pf("\tif value&(1<<%d) != 0 {\n\t\tnames += \"|%s\"\n\t}\n", i, v)
	}
	if len(d.Variants) < 64 { // a 64-variant set has no room for unknown bits
		g.pf("\tif rest := value >> %d; rest != 0 {\n", len(d.Variants))
		g.pf("\t\tnames += \"|0x\" + strconv.FormatUint(rest<<%d, 16)\n\t}\n", len(d.Variants))
	}
	g.pf("\tif names == \"\" {\n\t\treturn \"0\"\n\t}\n")
	g.pf("\treturn names[1:]\n}\n\n")
}

func (g *gen) emitStruct(d *ir.Struct) {
	g.pf("%s", ir.DocComment(d.Doc, "", "//"))
	if len(d.Tags) > 0 {
		g.pf("// type %s [%s] — tags are user-chosen and inert in v1 (SPEC §4.2, Type tags)\n", d.Name, strings.Join(d.Tags, ", "))
	} else {
		g.pf("// type %s\n", d.Name)
	}
	g.pf("type %s struct {\n", d.Name)
	g.emitFields(d.Fields)
	g.pf("}\n\n")
}

// emitConstructor emits NewX for a struct whose zero value is not its declared
// initial value — i.e. it (or a composed type) carries specified defaults.
// Everything else takes Go's zero value, which IS the schema's zero rule.
func (g *gen) emitConstructor(d *ir.Struct) {
	if !g.hasDefaults(d) {
		return
	}
	g.pf("// New%s returns a %s with its specified defaults applied; the plain zero\n", d.Name, d.Name)
	g.pf("// value is the all-zero form (SPEC §4.2: zero initialization unless a\n")
	g.pf("// specified default overrides it).\n")
	g.pf("func New%s() %s {\n", d.Name, d.Name)
	g.pf("\tvar value %s\n", d.Name)
	for _, f := range d.Fields {
		g.emitDefaultInit(f)
	}
	g.pf("\treturn value\n}\n\n")
}

// hasDefaults reports whether a struct transitively carries a specified default.
func (g *gen) hasDefaults(d *ir.Struct) bool {
	seen := map[string]bool{}
	var walk func(st *ir.Struct) bool
	walk = func(st *ir.Struct) bool {
		if seen[st.Name] {
			return false
		}
		seen[st.Name] = true
		for _, f := range st.Fields {
			if f.HasDefault || f.BornCount() > 0 {
				return true
			}
			if f.Type.Kind == ir.TNamed {
				if inner, ok := f.Type.Ref.(*ir.Struct); ok && walk(inner) {
					return true
				}
			}
		}
		return false
	}
	return walk(d)
}

func (g *gen) emitDefaultInit(f *ir.Field) {
	name := "value." + ir.GoExportName(f.Name)
	if n := f.BornCount(); n > 0 {
		// a [A..B] count is born at A, the one wire-legal count a fresh value
		// can carry (SPEC §4.6). The elements below follow their own rule
		g.pf("\t%sCount = %d\n", name, n)
	}
	if f.HasDefault {
		g.pf("\t%s = %s\n", name, g.defaultValue(f))
		return
	}
	if f.Type.Kind != ir.TNamed {
		return
	}
	inner, ok := f.Type.Ref.(*ir.Struct)
	if !ok || !g.hasDefaults(inner) {
		return
	}
	if f.Array != ir.ArrayNone {
		g.pf("\tfor i := range %s {\n\t\t%s[i] = New%s()\n\t}\n", name, name, inner.Name)
		return
	}
	g.pf("\t%s = New%s()\n", name, inner.Name)
}

func (g *gen) defaultValue(f *ir.Field) string {
	switch {
	case f.Type.Kind == ir.TBool:
		return fmt.Sprintf("%v", f.DefBool)
	case f.DefVariant != "":
		return f.Type.Name + f.DefVariant
	case f.Type.Kind == ir.TFloat32 || f.Type.Kind == ir.TFloat64:
		return formatFloat(f.DefFloat)
	case f.Type.Kind == ir.TInt && f.Type.Width == 128:
		// 128-bit defaults compose through the pair — a bare decimal literal
		// past 64 bits is not a legal Go constant of any integer type
		if f.Type.Signed {
			return g.render128(f.DefExpr, f.DefInt)
		}
		return g.renderU128(f.DefExpr, f.DefInt)
	default:
		return g.renderInt(f.DefExpr, f.DefInt)
	}
}

// render128 renders a signed 128-bit constant (a bound or a default) as Go
// source. A value inside int64 rides the sign-extending From64 constructor
// (symbolically where the expression is renderable, like any other integer);
// anything wider composes its two's-complement 64-bit lanes as a pair
// literal — exact for every value, matching the C++ render128's composed
// halves.
func (g *gen) render128(e ast.Expr, folded *big.Int) string {
	i64lo := new(big.Int).Neg(new(big.Int).Lsh(big.NewInt(1), 63))
	i64hi := new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), 63), big.NewInt(1))
	if folded.Cmp(i64lo) >= 0 && folded.Cmp(i64hi) <= 0 {
		return "serialize.Int128From64(" + g.renderInt(e, folded) + ")"
	}
	u := new(big.Int).Set(folded)
	if u.Sign() < 0 {
		u.Add(u, new(big.Int).Lsh(big.NewInt(1), 128))
	}
	hi := new(big.Int).Rsh(u, 64)
	lo := new(big.Int).And(u, maxUint64)
	return fmt.Sprintf("serialize.Int128{Lo: 0x%x, Hi: 0x%x}", lo, hi)
}

// renderU128 is render128 for the unsigned domain: values inside uint64 ride
// the zero-extending From64 constructor, wider values compose the lanes.
func (g *gen) renderU128(e ast.Expr, folded *big.Int) string {
	if folded.Cmp(maxUint64) <= 0 {
		return "serialize.Uint128From64(" + g.renderInt(e, folded) + ")"
	}
	hi := new(big.Int).Rsh(folded, 64)
	lo := new(big.Int).And(folded, maxUint64)
	return fmt.Sprintf("serialize.Uint128{Lo: 0x%x, Hi: 0x%x}", lo, hi)
}

func (g *gen) emitFields(fields []*ir.Field) {
	prevGuard := ""
	for _, f := range fields {
		if f.Guard != prevGuard {
			if f.Guard != "" {
				g.pf("\n\t// %s — wire branch; storage holds both sides, a read zeroes the\n", f.Guard)
				g.pf("\t// untaken side (SPEC §5)\n")
			} else {
				g.pf("\n") // leaving a branch group — separate so membership stays visible
			}
			prevGuard = f.Guard
		}
		g.pf("%s", ir.DocComment(f.Doc, "\t", "//"))
		g.emitStorageField(f)
	}
}

func (g *gen) emitStorageField(f *ir.Field) {
	name := ir.GoExportName(f.Name)
	typ := g.goFieldType(f.Type)

	switch {
	case f.Type.Kind == ir.TString:
		g.pf("\t%s [%s]byte // string(%s): max length, used length beside it (SPEC §4.7)\n",
			name, g.renderInt(f.Type.SizeExpr, big.NewInt(f.Type.Size)), ir.RenderExpr(f.Type.SizeExpr))
		g.pf("\t%sLength int32\n", name)
	case f.Type.Kind == ir.TBytes:
		g.pf("\t%s [%s]byte // bytes(%s): fixed buffer, used length beside it (SPEC §4.7)\n",
			name, g.renderInt(f.Type.SizeExpr, big.NewInt(f.Type.Size)), ir.RenderExpr(f.Type.SizeExpr))
		g.pf("\t%sLength int32\n", name)
	case f.Array == ir.ArrayFixed:
		g.pf("\t%s [%s]%s%s\n", name, g.renderInt(f.ArrayExpr, big.NewInt(f.ArrayBound)), typ, g.fieldComment(f))
	case f.Array == ir.ArrayCounted:
		g.pf("\t%s [%s]%s // used count beside it; wire count in [%d, %s]\n",
			name, g.renderInt(f.ArrayExpr, big.NewInt(f.ArrayBound)), typ, f.ArrayMin, g.renderInt(f.ArrayExpr, big.NewInt(f.ArrayBound)))
		g.pf("\t%sCount int32\n", name)
	default:
		g.pf("\t%s %s%s\n", name, typ, g.fieldComment(f))
	}
}

func (g *gen) fieldComment(f *ir.Field) string {
	var parts []string
	if f.HasDefault {
		parts = append(parts, fmt.Sprintf("= %s in New* (zero value otherwise)", g.defaultValue(f)))
	}
	if f.HasIntRange {
		parts = append(parts, fmt.Sprintf("wire [%s, %s]", f.IntMin, f.IntMax))
	}
	if f.HasFloatRange {
		parts = append(parts, fmt.Sprintf("compressed float [%s, %s] @ %s",
			formatFloat(f.FMin), formatFloat(f.FMax), formatFloat(f.Resolution)))
	}
	if len(parts) == 0 {
		return ""
	}
	return " // " + strings.Join(parts, "; ")
}

// goFieldType maps a field type to its Go storage (SPEC §6.1).
func (g *gen) goFieldType(t ir.FieldType) string {
	switch t.Kind {
	case ir.TInt:
		if t.Width == 128 {
			// serialize.go's own two-qword pair (int128.go): Lo lane first,
			// matching the little-endian layout and the wire order
			g.needsSerialize = true
			if t.Signed {
				return "serialize.Int128"
			}
			return "serialize.Uint128"
		}
		return goInt2(t.Signed, t.Width)
	case ir.TFixed:
		// raw scaled integer in storage of exactly I+F bits, the type's own
		// signedness — serialize's fixed storage convention (STANDARD.md,
		// fixed); the wide form stores the pair. The runtime API is
		// int64/Int128-shaped and derives capacity from min < 0, so unsigned
		// storage rides the same calls through bit-exact casts.
		if t.Width == 128 {
			g.needsSerialize = true
			if t.Signed {
				return "serialize.Int128"
			}
			return "serialize.Uint128"
		}
		if t.Signed {
			return goInt(t.Width)
		}
		return goUint(t.Width)
	case ir.TBits:
		if t.Width <= 32 {
			return "uint32"
		}
		return "uint64"
	case ir.TBool:
		return "bool"
	case ir.TFloat32:
		return "float32"
	case ir.TFloat64:
		return "float64"
	case ir.TNamed:
		return t.Name
	}
	return "/* ? */"
}

// renderInt renders an integer expression symbolically where every referenced
// constant is a BARE (untyped) schema const — safe in any Go context — and
// folds to the computed value otherwise (typed consts would force conversions;
// an E.Max reference always folds; the schema source rides in a comment).
func (g *gen) renderInt(e ast.Expr, folded *big.Int) string {
	if e == nil || ir.ExprHasEnumMax(e) || !g.renderable(e) {
		return folded.String()
	}
	return renderExpr(e)
}

// renderable: every referenced constant must be a BARE (untyped) integer
// schema const — a typed const is a typed Go const, which forces conversions
// at use sites of other types.
func (g *gen) renderable(e ast.Expr) bool {
	for _, name := range ir.ExprConsts(e) {
		c, ok := g.unit.Consts[name]
		if !ok || c.IsFloat || c.Explicit {
			return false
		}
	}
	return true
}

// renderExpr renders an expression in Go form: constants keep the schema
// spelling, since the Go target emits them under their declared names.
func renderExpr(e ast.Expr) string {
	return ir.RenderExprIdent(e, nil)
}

func goInt2(signed bool, width int) string {
	if signed {
		return fmt.Sprintf("int%d", width)
	}
	return fmt.Sprintf("uint%d", width)
}

func goInt(width int) string  { return fmt.Sprintf("int%d", width) }
func goUint(width int) string { return fmt.Sprintf("uint%d", width) }

func formatFloat(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

// formatFloat32 renders a compressed-float parameter at FLOAT32 precision:
// the shortest literal that parses to exactly float32(v) in every target
// language — the same narrowing ir.CompressedFloatBits computes widths with,
// so all five targets and the advertised MaxBits agree even at f32 rounding
// ties (a 64-bit literal re-rounded per-language can land on different f32s).
func formatFloat32(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 32)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}
