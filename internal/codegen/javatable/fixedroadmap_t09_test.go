package javatable

// fixedroadmap_t09 — the java leg's optional-arrays, scalar-defaults and
// text-bytes-flags-defaults rows of docs/roadmap.sexp's node `fixed-tables`
// (ROADMAP.md "NEW Fixed Tables"), the assertions no other test of this leg
// makes. Each row is a [capability] task: the leg WRITES and READS the
// construct with non-default and boundary values through its own generated
// save and load. One subtest per task id.
//
// Law: docs/SPEC-TABLES.md §2.3 ("`?` on a bounded array — `?[..N]T` and
// `?[N]T` — is the same construct one shape up … PRESENCE decides whether the
// field rides: an absent optional array is not written; a present one ALWAYS
// rides as the array framing") and §3.4's template/record rules (a declared
// default is the template's bytes; the prefill is what answers "absent
// field"), and docs/FIXED-FORM-ALGORITHM.md §3.
//
// A clause already held by an existing test of this leg is named by that test
// in the card's verdicts and is not repeated here; this file carries the direct
// runtime witness each capability task owes. The probe is GENERATED by the Go
// side and never hand-edited: it builds values, saves them with the leg's own
// writer, loads the bytes back into fresh values with the leg's own reader, and
// dumps the report and every landed field.

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

func TestFixedRoadmapJavaT09Optionals(t *testing.T) {
	t.Parallel()
	tests := []struct {
		id  string
		run func(t *testing.T)
	}{
		{"optional-arrays/java/valid-data", t09OptionalArrays},
		{"scalar-defaults/java/valid-data", t09ScalarDefaults},
		{"text-bytes-flags-defaults/java/valid-data", t09TextBytesFlagsDefaults},
	}
	for _, tc := range tests {
		t.Run(tc.id, func(t *testing.T) {
			t.Parallel()
			tc.run(t)
		})
	}
}

// t09BuildInline generates one inline schema with the leg's own emitter, writes
// it beside the generated probe and compiles the lot with this leg's toolchain.
// It answers the classpath, the generated package and the root table's name.
func t09BuildInline(t *testing.T, dir, src, probe string) (classes, pkg, root string) {
	t.Helper()
	javac, _ := javaTools(t)
	u := unitFrom(t, src)
	pkg = javaPackageOf(u)
	if pkg == "" {
		t.Fatal("the schema declares no package")
	}
	root = rootOf(t, u).Name
	files, err := Generate(u)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	srcDir := filepath.Join(dir, "src")
	classes = filepath.Join(dir, "classes")
	if err := os.MkdirAll(classes, 0o755); err != nil {
		t.Fatal(err)
	}
	writeFixedJava(t, srcDir, pkg, files)
	if err := os.WriteFile(filepath.Join(srcDir, "Probe_capability.java"), []byte(probe), 0o644); err != nil {
		t.Fatal(err)
	}
	sources, err := filepath.Glob(filepath.Join(srcDir, "*", "*.java"))
	if err != nil {
		t.Fatal(err)
	}
	probes, err := filepath.Glob(filepath.Join(srcDir, "*.java"))
	if err != nil {
		t.Fatal(err)
	}
	args := append([]string{"--release", "17", "-nowarn", "-d", classes}, sources...)
	args = append(args, probes...)
	if out, err := exec.Command(javac, args...).CombinedOutput(); err != nil {
		t.Fatalf("javac: %v\n%s", err, out)
	}
	return classes, pkg, root
}

// t09SaveLoadProbe is the capability probe: it sets `records` values from the
// setters block (which speaks `vals[i].<field>`), saves them with the leg's own
// writer, prints the bytes, loads them back into FRESH values with the leg's
// own reader, and dumps the report and every landed record as `VALUE v<i>.<f>`.
// Each record is also dumped BEFORE the save as `FRESH f<i>.<f>`, so the
// value-surface defaults are an oracle the read is measured against.
func t09SaveLoadProbe(class, pkg, root string, records int, setters string) string {
	var b strings.Builder
	fmt.Fprintf(&b, `import java.lang.reflect.*;

// GENERATED BY internal/codegen/javatable/fixedroadmap_t09_test.go. The
// capability probe: write with the leg's own writer, read with its own reader,
// assert the round trip and the value-surface defaults.
public final class %[1]s {
    static final StringBuilder out = new StringBuilder();

    public static void main(String[] args) throws Exception {
        %[2]s.%[3]sFixed.Value[] vals = new %[2]s.%[3]sFixed.Value[%[4]d];
        for (int i = 0; i < vals.length; i++) { vals[i] = new %[2]s.%[3]sFixed.Value(); }
        for (int i = 0; i < vals.length; i++) { walk("FRESH", "f" + i, vals[i]); }
        %[5]s
        final byte[] bytes = new byte[%[2]s.%[3]sFixed.measure(vals.length)];
        %[2]s.%[3]sFixed.save(vals, vals.length, bytes);
        final StringBuilder hex = new StringBuilder();
        for (byte x : bytes) { hex.append(String.format("%%02x", x)); }
        out.append("BYTES ").append(hex).append('\n');
        %[2]s.%[3]sFixed.Value[] back = new %[2]s.%[3]sFixed.Value[%[4]d];
        for (int i = 0; i < back.length; i++) { back[i] = new %[2]s.%[3]sFixed.Value(); }
        %[2]s.TableFixed.Report report = new %[2]s.TableFixed.Report();
        final int n = %[2]s.%[3]sFixed.load(back, back.length, bytes,
                %[2]s.TableFixed.plan(1 << 14), new short[1 << 14], %[2]s.%[3]sFixed.image(), report);
        out.append("REPORT n=").append(n)
           .append(" refused=").append(report.refused)
           .append(" reason=").append(report.reason)
           .append(" malformed=").append(report.malformed)
           .append(" unknown=").append(report.unknown)
           .append(" kindMismatch=").append(report.kindMismatch)
           .append(" widened=").append(report.widened)
           .append(" clamped=").append(report.clamped)
           .append('\n');
        for (int i = 0; i < back.length; i++) { walk("VALUE", "v" + i, back[i]); }
        System.out.print(out);
    }
%[6]s
}
`, class, pkg, root, records, setters, t09Dump())
	return b.String()
}

// t09Dump is the reflection walk, unchanged from the t03 capability probe: it
// names every field, prints a byte[] as its hex and a primitive array as a
// list, so a nested value and an array are both read back field by field.
func t09Dump() string {
	return `
    static void dump(String tag, Object v) throws Exception {
        walk(tag, "", v);
    }

    static void walk(String tag, String path, Object v) throws Exception {
        if (v == null) { out.append(tag).append(' ').append(path).append("=null\n"); return; }
        Class<?> c = v.getClass();
        if (c.isArray()) {
            int n = Array.getLength(v);
            Class<?> el = c.getComponentType();
            if (el == byte.class) {
                byte[] a = (byte[]) v;
                StringBuilder h = new StringBuilder();
                for (byte x : a) { h.append(String.format("%02x", x)); }
                out.append(tag).append(' ').append(path).append("=bytes:").append(h).append('\n');
                return;
            }
            if (el.isPrimitive()) {
                StringBuilder s = new StringBuilder();
                for (int i = 0; i < n; i++) { if (i > 0) { s.append(','); } s.append(String.valueOf(Array.get(v, i))); }
                out.append(tag).append(' ').append(path).append("=list:").append(s).append('\n');
                return;
            }
            for (int i = 0; i < n; i++) { walk(tag, path + "[" + i + "]", Array.get(v, i)); }
            return;
        }
        if (v instanceof Float) {
            out.append(tag).append(' ').append(path).append('=').append(String.valueOf(v))
               .append("|0x").append(String.format("%08X", Float.floatToRawIntBits((Float) v))).append('\n');
            return;
        }
        if (v instanceof Double) {
            out.append(tag).append(' ').append(path).append('=').append(String.valueOf(v))
               .append("|0x").append(String.format("%016X", Double.doubleToRawLongBits((Double) v))).append('\n');
            return;
        }
        if (c == String.class || c.isPrimitive() || v instanceof Number || v instanceof Boolean
                || v instanceof Character || c.isEnum()) {
            out.append(tag).append(' ').append(path).append('=').append(String.valueOf(v)).append('\n');
            return;
        }
        Field[] fs = c.getFields();
        java.util.Arrays.sort(fs, (a, b) -> a.getName().compareTo(b.getName()));
        for (Field f : fs) {
            if (Modifier.isStatic(f.getModifiers())) { continue; }
            String p = path.isEmpty() ? f.getName() : path + "." + f.getName();
            walk(tag, p, f.get(v));
        }
    }
`
}

// t09Run runs one compiled capability probe and answers its output.
func t09Run(t *testing.T, classes, class string) string {
	t.Helper()
	_, javaBin := javaTools(t)
	out, err := exec.Command(javaBin, "-ea", "-cp", classes, class).CombinedOutput()
	if err != nil {
		t.Fatalf("java %s: %v\n%s", class, err, out)
	}
	return string(out)
}

// t09RequireClean fails unless the report is a clean returning read of `want`
// records with every counter at zero.
func t09RequireClean(t *testing.T, what string, r probeRun, want int) {
	t.Helper()
	if r.n != want || r.refused || r.malformed {
		t.Fatalf("%s: n=%d refused=%v reason=%s malformed=%v, want %d clean records", what, r.n, r.refused, r.reason, r.malformed, want)
	}
	if r.unknown != 0 || r.kindMismatch != 0 || r.widened != 0 || r.clamped != 0 {
		t.Errorf("%s: a clean round trip moved a counter: %+v", what, r)
	}
}

// t09Want asserts one dumped field equals its exact written value.
func t09Want(t *testing.T, what string, r probeRun, field, want string) {
	t.Helper()
	got, ok := r.value[field]
	if !ok {
		t.Errorf("%s: the probe dumped no %s", what, field)
		return
	}
	if got != want {
		t.Errorf("%s: %s landed %s, want the exact written %s", what, field, got, want)
	}
}

// t09WantFresh asserts one value-surface default equals its declared value.
func t09WantFresh(t *testing.T, what string, r probeRun, field, want string) {
	t.Helper()
	got, ok := r.fresh[field]
	if !ok {
		t.Errorf("%s: the probe dumped no fresh %s", what, field)
		return
	}
	if got != want {
		t.Errorf("%s: the fresh %s = %s, want the declared default %s", what, field, got, want)
	}
}

// t09OptionalArrays: optional-arrays/java/valid-data "Optional arrays:
// valid-data write/read acceptance" (docs/roadmap.sexp's node, contract "§2.3;
// §3.4 optional wrapper"). The construct is `?[..N]T` and `?[N]T`: §2.3's
// "PRESENCE decides whether the field rides: an absent optional array is not
// written; a present one ALWAYS rides as the array framing (§3) — a counted
// array with its live count, ZERO included". The leg writes and reads, through
// its own save/load: a present counted array AT THE BOUND with the extremes, a
// present-and-empty counted array, a present all-default fixed array, and an
// absent optional whose nonzero caller storage must not reach the wire.
func t09OptionalArrays(t *testing.T) {
	const src = `package probe

fixed table T
{
    lead  uint32 = 1
    xs    ?[..4]int32
    ys    ?[4]int32
    trail uint32 = 2
}
`
	probe := t09SaveLoadProbe("Probe_capability", "probe", "T", 4, `
        // record 0: present counted array AT THE BOUND, the extremes and 0
        vals[0].xsPresent = true;
        vals[0].xsCount = 4;
        vals[0].xs[0] = Integer.MIN_VALUE;
        vals[0].xs[1] = Integer.MAX_VALUE;
        vals[0].xs[2] = -1;
        vals[0].xs[3] = 0;
        vals[0].ysPresent = true;
        vals[0].ys[0] = 7; vals[0].ys[1] = -8;
        vals[0].ys[2] = Integer.MAX_VALUE; vals[0].ys[3] = Integer.MIN_VALUE;
        vals[0].lead = 101; vals[0].trail = 102;
        // record 1: PRESENT and EMPTY — the value no count alone can spell
        vals[1].xsPresent = true;
        vals[1].xsCount = 0;
        vals[1].lead = 201; vals[1].trail = 202;
        // record 2: ABSENT, with nonzero caller storage that must not ride
        vals[2].xsPresent = false;
        vals[2].xsCount = 4;
        vals[2].xs[0] = 91; vals[2].xs[1] = 92; vals[2].xs[2] = 93; vals[2].xs[3] = 94;
        vals[2].ysPresent = false;
        vals[2].ys[0] = 55; vals[2].ys[1] = 56; vals[2].ys[2] = 57; vals[2].ys[3] = 58;
        vals[2].lead = 301; vals[2].trail = 302;
        // record 3: PRESENT all-default fixed array — still rides
        vals[3].ysPresent = true;
        vals[3].lead = 401; vals[3].trail = 402;`)
	classes, _, _ := t09BuildInline(t, t.TempDir(), src, probe)
	r := parseProbe(t, t09Run(t, classes, "Probe_capability"))
	t09RequireClean(t, "optional-arrays", r, 4)

	// the fresh value is the absence: every optional is false, every payload
	for i := range 4 {
		if got := r.fresh[fmt.Sprintf("f%d.xsPresent", i)]; got != "false" {
			t.Errorf("optional-arrays: a fresh xsPresent = %s, want false", got)
		}
	}
	// record 0: the whole present counted array, per slot, at the bound
	t09Want(t, "optional-arrays r0", r, "v0.xsPresent", "true")
	t09Want(t, "optional-arrays r0", r, "v0.xsCount", "4")
	t09Want(t, "optional-arrays r0", r, "v0.xs", "list:-2147483648,2147483647,-1,0")
	t09Want(t, "optional-arrays r0", r, "v0.ysPresent", "true")
	t09Want(t, "optional-arrays r0", r, "v0.ys", "list:7,-8,2147483647,-2147483648")
	t09Want(t, "optional-arrays r0", r, "v0.lead", "101")
	t09Want(t, "optional-arrays r0", r, "v0.trail", "102")
	// record 1: present and empty is PRESENT with count 0, not absent
	t09Want(t, "optional-arrays r1", r, "v1.xsPresent", "true")
	t09Want(t, "optional-arrays r1", r, "v1.xsCount", "0")
	// record 2: absent skips the store; the payload lands the template's zeros
	t09Want(t, "optional-arrays r2", r, "v2.xsPresent", "false")
	t09Want(t, "optional-arrays r2", r, "v2.xsCount", "0")
	t09Want(t, "optional-arrays r2", r, "v2.xs", "list:0,0,0,0")
	t09Want(t, "optional-arrays r2", r, "v2.ysPresent", "false")
	t09Want(t, "optional-arrays r2", r, "v2.ys", "list:0,0,0,0")
	t09Want(t, "optional-arrays r2", r, "v2.lead", "301")
	// record 3: a present all-default fixed array still rides PRESENT
	t09Want(t, "optional-arrays r3", r, "v3.ysPresent", "true")
	t09Want(t, "optional-arrays r3", r, "v3.ys", "list:0,0,0,0")
}

// t09ScalarDefaults: scalar-defaults/java/valid-data "Scalar and enum
// defaults: valid-data write/read acceptance" (contract "§3.4 template;
// ALGORITHM §3"). The roadmap's remaining clause is "map an explicit
// enum-default runtime case to close the combined row", so the ENUM default is
// asserted at run time: a fresh value holds the declared variant, and the round
// trip lands non-default and boundary scalars and a non-default variant exact.
func t09ScalarDefaults(t *testing.T) {
	const src = `package probe

enum Grade
{
    Bronze
    Silver
    Gold
}

fixed table T
{
    a int32 = 7
    b float32 = 0.0
    g Grade = Silver
}
`
	probe := t09SaveLoadProbe("Probe_capability", "probe", "T", 2, `
        // record 0: the declared defaults, untouched
        // record 1: non-default and boundary values
        vals[1].a = Integer.MIN_VALUE;
        vals[1].b = -0.0f;
        vals[1].g = 3; // Gold: the non-default variant`)
	classes, _, _ := t09BuildInline(t, t.TempDir(), src, probe)
	r := parseProbe(t, t09Run(t, classes, "Probe_capability"))
	t09RequireClean(t, "scalar-defaults", r, 2)

	// THE ENUM DEFAULT, on the value surface: the declared variant Silver is
	// ordinal 2 (§3.4: "the ORDINAL is the variant's POSITION IN THE LAYOUT,
	// from 1, and 0 is None"), not the zero a missing default would leave.
	t09WantFresh(t, "scalar-defaults", r, "f0.a", "7")
	t09WantFresh(t, "scalar-defaults", r, "f0.b", "0.0|0x00000000")
	t09WantFresh(t, "scalar-defaults", r, "f0.g", "2")
	// record 0 round-trips the defaults
	t09Want(t, "scalar-defaults r0", r, "v0.a", "7")
	t09Want(t, "scalar-defaults r0", r, "v0.b", "0.0|0x00000000")
	t09Want(t, "scalar-defaults r0", r, "v0.g", "2")
	// record 1: the int32 floor, negative zero's bits, the non-default variant
	t09Want(t, "scalar-defaults r1", r, "v1.a", "-2147483648")
	t09Want(t, "scalar-defaults r1", r, "v1.b", "-0.0|0x80000000")
	t09Want(t, "scalar-defaults r1", r, "v1.g", "3")
}

// t09TextBytesFlagsDefaults: text-bytes-flags-defaults/java/valid-data
// "String, byte-buffer and flags defaults: valid-data write/read acceptance"
// (contract "ALGORITHM §3 prefill"). The roadmap's remaining clause is to "map
// runtime assertions of string bytes, byte-buffer bytes and flags defaults
// separately", so all three are asserted at run time: the value surface
// constructs the declared defaults ("untitled" behind its length, "ab" as the
// byte-buffer, Jump|Crouch), and the round trip lands non-default and boundary
// text, byte-buffer and flags values exact.
func t09TextBytesFlagsDefaults(t *testing.T) {
	const src = `package probe

flags Caps
{
    Jump
    Crouch
    Prone
}

fixed table T
{
    name string(16) = "untitled"
    tag  bytes(4) = "ab"
    caps Caps = { Jump, Crouch }
}
`
	probe := t09SaveLoadProbe("Probe_capability", "probe", "T", 3, `
        // record 0: the declared defaults, untouched
        // record 1: the text at CAPACITY, the byte-buffer at every byte value,
        // and all three flags
        vals[1].nameLength = 16;
        for (int i = 0; i < 16; i++) { vals[1].name[i] = (byte) ('A' + i); }
        vals[1].tagLength = 4;
        vals[1].tag[0] = 0; vals[1].tag[1] = (byte) 255;
        vals[1].tag[2] = 127; vals[1].tag[3] = (byte) 128;
        vals[1].caps = 7L;
        // record 2: the empty boundary
        vals[2].nameLength = 0;
        vals[2].tagLength = 0;
        vals[2].caps = 0L;`)
	classes, _, _ := t09BuildInline(t, t.TempDir(), src, probe)
	r := parseProbe(t, t09Run(t, classes, "Probe_capability"))
	t09RequireClean(t, "text-bytes-flags-defaults", r, 3)

	// THE DECLARED DEFAULTS on the value surface: the length in front of the
	// text, the text itself, the byte-buffer's bytes and the flags mask.
	t09WantFresh(t, "text-bytes-flags-defaults", r, "f0.nameLength", "8")
	t09WantFresh(t, "text-bytes-flags-defaults", r, "f0.name", "bytes:756e7469746c65640000000000000000")
	t09WantFresh(t, "text-bytes-flags-defaults", r, "f0.tagLength", "2")
	t09WantFresh(t, "text-bytes-flags-defaults", r, "f0.tag", "bytes:61620000")
	t09WantFresh(t, "text-bytes-flags-defaults", r, "f0.caps", "3")
	// record 0 round-trips the defaults
	t09Want(t, "text-bytes-flags-defaults r0", r, "v0.nameLength", "8")
	t09Want(t, "text-bytes-flags-defaults r0", r, "v0.name", "bytes:756e7469746c65640000000000000000")
	t09Want(t, "text-bytes-flags-defaults r0", r, "v0.tag", "bytes:61620000")
	t09Want(t, "text-bytes-flags-defaults r0", r, "v0.caps", "3")
	// record 1: the text at capacity, the byte-buffer's bytes, all flags
	t09Want(t, "text-bytes-flags-defaults r1", r, "v1.nameLength", "16")
	t09Want(t, "text-bytes-flags-defaults r1", r, "v1.name", "bytes:4142434445464748494a4b4c4d4e4f50")
	t09Want(t, "text-bytes-flags-defaults r1", r, "v1.tagLength", "4")
	t09Want(t, "text-bytes-flags-defaults r1", r, "v1.tag", "bytes:00ff7f80")
	t09Want(t, "text-bytes-flags-defaults r1", r, "v1.caps", "7")
	// record 2: the empty boundary — length 0, zero mask
	t09Want(t, "text-bytes-flags-defaults r2", r, "v2.nameLength", "0")
	t09Want(t, "text-bytes-flags-defaults r2", r, "v2.tagLength", "0")
	t09Want(t, "text-bytes-flags-defaults r2", r, "v2.caps", "0")
}
