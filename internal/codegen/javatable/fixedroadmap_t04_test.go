// §4.5 (the scatter's copy/count/text), §4.6 (the bounds pass), §5.1 (BASELINE),
// §5.2 (COMPILE), docs/FIXED-FORM-VERSIONING-TESTS.md ("The rows",
// `rename_without_was`, `field_append`, `field_deprecate`), docs/SPEC-TABLES.md
// §3.4, §21.
//
// A clause already held by an existing test of this leg is named by that test
// in the card's verdicts and is not repeated here; this file carries the direct
// assertion of every clause that had none, and each clause whose build is red
