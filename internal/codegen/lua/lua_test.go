// TestSkeletonFixture is the one passing fixture `schema new-leg lua` laid
// down, kept as the emitter grew: a table-free unit generates, the file names
// its source and package, and the pinned interpreter loads it (test/lua/main.lua).
func TestSkeletonFixture(t *testing.T) {
	t.Parallel()
	u := &ir.Unit{
		Package:    "hello",
		ProtocolId: 0x11,
		Files:      []*ir.File{{Base: "Hello"}},
	}
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	name := "Hello." + ext
	got, ok := files[name]
	if !ok {
		t.Fatalf("Generate omitted %s; emitted %v", name, keysOf(files))
	}
	text := string(got)
	for _, want := range []string{
		"Code generated by the schema compiler from Hello.schema",
		"package hello",
		"_M.ProtocolId = 0x0000000000000011",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("missing %q in:\n%s", want, text)
		}
	}
	dir := t.TempDir()
	luarun.WriteFiles(t, dir, files)
	harness, err := os.ReadFile(filepath.Join("..", "..", "..", "test", "lua", "main.lua"))
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "main.lua"), harness, 0o644); err != nil {
		t.Fatal(err)
	}
	out := luarun.Run(t, dir, "main.lua", map[string][]byte{"module": []byte("Hello")})
	if strings.TrimSpace(string(out)) != "ok" {
		t.Fatalf("test/lua/main.lua printed %q, want ok", out)
	}
}

func keysOf(files map[string][]byte) []string {
	out := make([]string, 0, len(files))
	for k := range files {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// TestLuaTypesConstructAtTheirDefaults generates examples/*.schema, loads
// every module under the pinned interpreter, dumps each module's data (the
// protocol id, constants, enum and union tag tables, flags masks) and every
// type and union as its constructor builds it, and compares each line with an
// expectation computed here from the IR alone (docs/PORT-LUA.md, THE TYPE
// MAPPING; SPEC §5: zero initialization unless a specified default overrides
// it). It then holds ArmDefaults the way test/go/main.go
// testDefaultArmInitialization does: a fresh DefaultArm is born with count
// zero and BOTH backing entries at their defaults, and a union's arms are
// distinct tables, so writing one never moves the other.
func TestLuaTypesConstructAtTheirDefaults(t *testing.T) {
	t.Parallel()
	u := luarun.LoadUnit(t, filepath.Join("..", "..", "..", "examples"))
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	luarun.WriteFiles(t, dir, files)
	luarun.WriteDumpProbe(t, dir)

	var probe strings.Builder
	probe.WriteString("local dump = require(\"dump\")\n")
	want := map[string]string{}
	var order []string
	expect := func(line, value string) {
		want[line] = value
		order = append(order, line)
	}
	for _, f := range u.Files {
		fmt.Fprintf(&probe, "do\n  local m = require(%q)\n", f.Base)
		fmt.Fprintf(&probe, "  print(%q .. \" \" .. dump(m))\n", "module "+f.Base)
		expect("module "+f.Base, expectModule(u, f))
		for _, d := range f.Decls {
			var name string
			switch d := d.(type) {
			case *ir.Struct:
				name = d.Name
			case *ir.Union:
				name = d.Name
			default:
				continue
			}
			fmt.Fprintf(&probe, "  print(%q .. \" \" .. dump(m.New%s()))\n", "new "+name, name)
			expect("new "+name, expectDecl(u, name))
		}
		probe.WriteString("end\n")
	}
	// ArmDefaults, as testDefaultArmInitialization holds it in Go
	probe.WriteString(armDefaultsProbe)
	if err := os.WriteFile(filepath.Join(dir, "main.lua"), []byte(probe.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	out := luarun.Run(t, dir, "main.lua", nil)

	got := map[string]string{}
	armOK := false
	for line := range strings.SplitSeq(strings.TrimRight(string(out), "\n"), "\n") {
		if line == "armdefaults ok" {
			armOK = true
			continue
		}
		kind, rest, _ := strings.Cut(line, " ")
		name, value, _ := strings.Cut(rest, " ")
		got[kind+" "+name] = value
	}
	types := 0
	for _, line := range order {
		if got[line] != want[line] {
			t.Errorf("%s:\n  lua  %s\n  want %s", line, got[line], want[line])
		}
		if strings.HasPrefix(line, "new ") {
			types++
		}
	}
	if !armOK {
		t.Errorf("the ArmDefaults probe did not finish; output:\n%s", out)
	}
	if types == 0 || len(u.Files) == 0 {
		t.Fatalf("the probe constructed nothing (%d files, %d types)", len(u.Files), types)
	}
	t.Logf("%d modules loaded, %d types and unions constructed at their defaults", len(u.Files), types)
}

const armDefaultsProbe = `
do
  local A = require("ArmDefaults")
  local W = require("Wire")
  local arm = A.NewDefaultArm()
  assert(arm.EntriesCount == 0, "DefaultArm constructor count is zero")
  assert(#arm.Entries == 2, "DefaultArm pre-builds both backing entries")
  for _, entry in ipairs(arm.Entries) do
    assert(entry.Retries == -1 and entry.Preferred == W.Weapon.Railgun,
      "DefaultArm constructor initializes both backing entries")
  end
  assert(arm.Entries[1] ~= arm.Entries[2], "the backing entries are distinct tables")
  local choice = A.NewDefaultChoice()
  assert(choice.Type == A.DefaultChoiceType.None, "a union is born None")
  assert(choice.First ~= choice.Second, "a union's arms are distinct tables")
  choice.First.Marker = 7
  choice.First.Entries[1].Retries = 123
  assert(choice.Second.Marker == 0 and choice.Second.Entries[1].Retries == -1,
    "writing one arm leaves the other at its defaults")
  assert(A.DefaultChoiceType.First == 1 and A.DefaultChoiceType.Second == 2 and A.DefaultChoiceType.Max == 2)
  assert(A.EnumNameDefaultChoiceType(1) == "First" and A.EnumNameDefaultChoiceType(9) == "???")
  print("armdefaults ok")
end
`

// expectModule is a module table's dump, computed from the IR: the protocol
// id in its home file, every constant, every enum table, every union's tag
// table, every flags mask and count.
func expectModule(u *ir.Unit, f *ir.File) string {
	named := map[string]string{}
	if f.Base == ir.ProtocolIdHome(u) {
		named["ProtocolId"] = luarun.DumpInt(u.ProtocolId)
	}
	for _, d := range f.Decls {
		switch d := d.(type) {
		case *ir.Const:
			switch {
			case d.IsFloat && d.Storage == "float32":
				named[d.Name] = luarun.DumpFloat(float64(float32(d.Float)))
			case d.IsFloat:
				named[d.Name] = luarun.DumpFloat(d.Float)
			case d.Storage == "int128" || d.Storage == "uint128" || d.Int.BitLen() > 64 || (d.Int.Sign() < 0 && d.Int.BitLen() > 63 && d.Int.Cmp(big.NewInt(math.MinInt64)) != 0):
				named[d.Name] = expectWide(d.Int)
			default:
				named[d.Name] = luarun.DumpInt(bits64(d.Int))
			}
		case *ir.Enum:
			named[d.Name] = expectTag(d.Variants, d.Max)
		case *ir.Union:
			arms := make([]string, len(d.Variants))
			for i, v := range d.Variants {
				arms[i] = ir.GoExportName(v.Name)
			}
			named[d.Name+"Type"] = expectTag(arms, int64(len(arms)))
		case *ir.Flags:
			for i, v := range d.Variants {
				named[d.Name+v] = luarun.DumpInt(uint64(1) << i)
			}
			named[d.Name+"Count"] = luarun.DumpInt(uint64(len(d.Variants)))
		}
	}
	return luarun.DumpTable(nil, named)
}

func expectTag(members []string, max int64) string {
	// an enum and a union tag export None, the variants and Max; never a Count (SPEC §4.2)
	named := map[string]string{"None": luarun.DumpInt(0), "Max": luarun.DumpInt(uint64(max))}
	for i, m := range members {
		named[m] = luarun.DumpInt(uint64(i + 1))
	}
	return luarun.DumpTable(nil, named)
}

// expectDecl is a constructed type's or union's dump.
func expectDecl(u *ir.Unit, name string) string {
	if st, ok := u.Structs[name]; ok {
		named := map[string]string{}
		for _, f := range st.Fields {
			key := ir.GoExportName(f.Name)
			if f.Array != ir.ArrayNone {
				seq := make([]string, f.ArrayBound)
				for i := range seq {
					seq[i] = expectZero(u, f.Type)
				}
				named[key] = luarun.DumpTable(seq, nil)
				if f.Array == ir.ArrayCounted {
					named[key+"Count"] = luarun.DumpInt(uint64(f.BornCount()))
				}
				continue
			}
			if f.HasDefault {
				named[key] = expectDefault(f)
				continue
			}
			named[key] = expectZero(u, f.Type)
		}
		return luarun.DumpTable(nil, named)
	}
	un, ok := u.Unions[name]
	if !ok {
		return "<no declaration " + name + ">"
	}
	named := map[string]string{"Type": luarun.DumpInt(0)}
	for _, v := range un.Variants {
		if v.Void() {
			continue
		}
		if v.Type != "" {
			named[ir.GoExportName(v.Name)] = expectDecl(u, v.Type)
			continue
		}
		named[ir.GoExportName(v.Name)] = expectZero(u, v.F.Type)
	}
	return luarun.DumpTable(nil, named)
}

func expectZero(u *ir.Unit, t ir.FieldType) string {
	switch t.Kind {
	case ir.TBool:
		return luarun.DumpBool(false)
	case ir.TFloat32, ir.TFloat64:
		return luarun.DumpFloat(0)
	case ir.TString, ir.TBytes:
		return luarun.DumpString(nil)
	case ir.TWString:
		return luarun.DumpTable(nil, nil)
	case ir.TNamed:
		switch t.Ref.(type) {
		case *ir.Struct, *ir.Union:
			return expectDecl(u, t.Name)
		}
		return luarun.DumpInt(0)
	}
	if (t.Kind == ir.TInt || t.Kind == ir.TFixed) && t.Width > 64 {
		return expectWide(big.NewInt(0))
	}
	return luarun.DumpInt(0)
}

func expectDefault(f *ir.Field) string {
	switch {
	case f.Type.Kind == ir.TBool:
		return luarun.DumpBool(f.DefBool)
	case f.DefVariant != "":
		for i, v := range f.Type.Ref.(*ir.Enum).Variants {
			if v == f.DefVariant {
				return luarun.DumpInt(uint64(i + 1))
			}
		}
		return luarun.DumpInt(0)
	case f.Type.Kind == ir.TFloat32:
		return luarun.DumpFloat(float64(float32(f.DefFloat)))
	case f.Type.Kind == ir.TFloat64:
		return luarun.DumpFloat(f.DefFloat)
	case f.Type.Kind == ir.TString || f.Type.Kind == ir.TBytes:
		return luarun.DumpString(f.DefBytes)
	case f.Type.Kind == ir.TWString:
		return luarun.DumpTable(nil, nil)
	case (f.Type.Kind == ir.TInt || f.Type.Kind == ir.TFixed) && f.Type.Width > 64:
		return expectWide(f.DefInt)
	}
	return luarun.DumpInt(bits64(f.DefInt))
}

// bits64 is the 64-bit pattern of an integer in [int64 min, uint64 max].
func bits64(v *big.Int) uint64 {
	if v == nil {
		return 0
	}
	if v.Sign() < 0 {
		return uint64(v.Int64())
	}
	return v.Uint64()
}

// expectWide is a 128-bit value's { hi, lo } dump, two's complement.
func expectWide(v *big.Int) string {
	w := new(big.Int).Set(v)
	if w.Sign() < 0 {
		w.Add(w, new(big.Int).Lsh(big.NewInt(1), 128))
	}
	lo := new(big.Int).And(w, new(big.Int).SetUint64(math.MaxUint64)).Uint64()
	hi := new(big.Int).Rsh(w, 64).Uint64()
	return luarun.DumpTable(nil, map[string]string{"lo": luarun.DumpInt(lo), "hi": luarun.DumpInt(hi)})
}
