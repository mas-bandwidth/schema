// Gen is one <Base>Table.moo module being written. A later form's [Part]
// writes into it through Pf and names what it uses through Require and K.
type Gen struct {
	Unit *ir.Unit
	File *ir.File
	// Self is the alias a module's own declarations hang from ("M"); another
	// module's require alias is "_" + its basename, and no schema name starts
	// with an underscore, so neither shadows a declaration.
	Self string
	// Suffix is the module family's basename suffix ("Table").
	Suffix string
	// Kind names the module family in its header.
	Kind string
	// Lineage is the lock's fixed-form lineage, per table, oldest first, as
	// the build handed it to GenerateLineage (docs/FIXED-FORM-ALGORITHM.md
	// §5.2); nil for a unit with no lock.
	Lineage map[string][]FixedLineageEntry

	body     strings.Builder
	requires map[string]bool
	konst    map[string]string
	konstSeq []string
}

func newGen(u *ir.Unit, f *ir.File) *Gen {
	return &Gen{Unit: u, File: f, Self: "M", Suffix: "Table", Kind: "table surface",
		requires: map[string]bool{}, konst: map[string]string{}}
}

// Pf writes into the module body.
func (g *Gen) Pf(format string, args ...any) { fmt.Fprintf(&g.body, format, args...) }

// Require records that this module requires another module (by basename,
// without .moo) and returns the local alias it is bound to.
func (g *Gen) Require(module string) string {
	if module == g.File.Base+g.Suffix {
		return g.Self
	}
	g.requires[module] = true
	return "_" + module
}

// Requires is the modules this module requires so far, sorted.
func (g *Gen) Requires() []string {
	out := make([]string, 0, len(g.requires))
	for m := range g.requires {
		out = append(out, m)
	}
	sort.Strings(out)
	return out
}

// K interns a load-time expression (a wide literal) in the module's constant
// pool and returns the local naming it: a wide value is a frozen object, built
// once at load, never per call (docs/PORT-MOO.md, THE WIRE).
func (g *Gen) K(expr string) string {
	if name, ok := g.konst[expr]; ok {
		return name
	}
	name := fmt.Sprintf("K%d", len(g.konstSeq)+1)
	g.konst[expr] = name
	g.konstSeq = append(g.konstSeq, expr)
	return name
}

// Assemble returns the module: header, requires, constant pool, body, return.
func (g *Gen) Assemble() []byte {
	body := g.body.String()
	var h strings.Builder
	h.WriteString("--!strict\n")
	fmt.Fprintf(&h, "-- Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", g.File.Base)
	h.WriteString("-- SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("-- your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("-- AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&h, "-- package %s — protocol id 0x%016x — the moo %s (docs/PORT-MOO.md)\n\n", g.Unit.Package, g.Unit.ProtocolId, g.Kind)
	used := func(name string) bool {
		return regexp.MustCompile(`\b` + regexp.QuoteMeta(name) + `\b`).MatchString(body)
	}
	if used("serialize") || len(g.konstSeq) > 0 {
		h.WriteString("local serialize = require(\"./serialize\")\n")
	}
	if used("St") {
		fmt.Fprintf(&h, "local St = require(\"./%s\")\n", RuntimeModule)
	}
	for _, m := range g.Requires() {
		fmt.Fprintf(&h, "local _%s = require(\"./%s\")\n", m, m)
	}
	if len(g.konstSeq) > 0 {
		h.WriteString("\n-- the constant pool: wide literals, built once at load\n")
		for i, e := range g.konstSeq {
			fmt.Fprintf(&h, "local K%d = %s\n", i+1, e)
		}
	}
	fmt.Fprintf(&h, "\nlocal %s = {}\n\n", g.Self)
	h.WriteString(body)
	fmt.Fprintf(&h, "return %s\n", g.Self)
	return []byte(h.String())
}

