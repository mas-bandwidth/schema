// The text form against the conformance corpus (testdata/conformance/tables):
// every instance's text, read by json.moo and written back, is the golden
// byte for byte with a silent report; every json-hostile tree reads to the
// hand-authored verdict. The goldens are the reference's (generated by the
// compiler's own engine and packed back to the wire before they land), so
// this is the text form held to internal/tabletext with the wire in between.

const repoRoot = "../../.."

type textManifest struct {
	units     map[string][]string
	instances []textInstance
	hostile   []textHostile
}

type textInstance struct{ name, unit, root, wire string }

type textHostile struct{ name, unit, root, tree, verdict string }

func readTextManifest(t *testing.T) textManifest {
	t.Helper()
	f, err := os.Open(filepath.Join(repoRoot, "testdata", "conformance", "tables", "MANIFEST.txt"))
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	m := textManifest{units: map[string][]string{}}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		fields := strings.Fields(sc.Text())
		if len(fields) == 0 || strings.HasPrefix(fields[0], "#") {
			continue
		}
		switch fields[0] {
		case "unit":
			m.units[fields[1]] = fields[2:]
		case "instance":
			noText := false
			for _, x := range fields[5:] {
				noText = noText || x == "no-text"
			}
			if !noText {
				m.instances = append(m.instances, textInstance{fields[1], fields[2], fields[3], fields[4]})
			}
		case "json-hostile":
			// moo CARRIES every rule the Go walk holds first (the zero escape,
			// the ill-formed byte at a bound): it owes the standard's verdict,
			// never a row's uncarried one (test/conformance/README.md)
			verdict := fields[5]
			m.hostile = append(m.hostile, textHostile{fields[1], fields[2], fields[3], fields[4], verdict})
		}
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	return m
}

// loadUnit compiles a unit's schema files (paths relative to the repository).
func loadUnit(t *testing.T, rel []string) *ir.Unit {
	t.Helper()
	var paths []string
	for _, p := range rel {
		full := filepath.Join(repoRoot, p)
		if st, err := os.Stat(full); err == nil && st.IsDir() {
			matches, _ := filepath.Glob(filepath.Join(full, "*.schema"))
			sort.Strings(matches)
			paths = append(paths, matches...)
			continue
		}
		paths = append(paths, full)
	}
	var files []check.SourceFile
	for _, p := range paths {
		src, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		name := filepath.Base(p)
		tree, errs := parser.Parse(name, src)
		if len(errs) != 0 {
			t.Fatalf("parse %s: %v", name, errs)
		}
		files = append(files, check.SourceFile{Path: p, Name: name, Base: strings.TrimSuffix(name, ".schema"), Bytes: src, AST: tree})
	}
	u, errs := check.Unit(files)
	if len(errs) != 0 {
		t.Fatalf("check: %v", errs)
	}
	return u
}

// generateUnitDir writes the moo packet and table surfaces of u into a fresh
// directory, with runtime overriding runtime modules by name.
func generateUnitDir(t *testing.T, u *ir.Unit, runtime map[string][]byte) string {
	t.Helper()
	files, err := moo.Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	tables, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	maps.Copy(files, tables)
	maps.Copy(files, runtime)
	dir := t.TempDir()
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func tableModule(u *ir.Unit, root string) string {
	return u.DeclFile[root] + "Table"
}

// textRun is one unit's probe: for each (root, input name) it reads the text
// with <Root>FromJson into a fresh value and prints the report, then the text
// <Root>ToJson writes of the value (or "refused"), each as a hex line.
type textCase struct{ root, input string }

func textRun(t *testing.T, u *ir.Unit, cases []textCase, inputs map[string][]byte, runtime map[string][]byte) [][2]string {
	t.Helper()
	dir := generateUnitDir(t, u, runtime)
	var b strings.Builder
	b.WriteString(probePrelude)
	mods := map[string]bool{}
	for _, c := range cases {
		mods[tableModule(u, c.root)] = true
	}
	var names []string
	for m := range mods {
		names = append(names, m)
	}
	sort.Strings(names)
	for _, m := range names {
		fmt.Fprintf(&b, "local %s: any = require(\"./%s\")\n", m, m)
	}
	b.WriteString(`local function run(mod: any, root: string, input: string)
	local value = mod["New" .. root]()
	local report: any = {}
	local ok = mod[root .. "FromJson"](value, inputs[input], report)
	hexs(string.format("%d,%d,%d,%d,%d,%s,%s,%s", report.unknown, report.kindMismatch, report.widened,
		report.clamped, report.duplicate, tostring(report.malformed), if ok then "read" else "refused", report.reason or ""))
	local size = mod[root .. "ToJsonMeasure"](value)
	if size < 0 then
		hexs("refused")
		return
	end
	local out = buffer.create(size)
	if mod[root .. "ToJson"](value, out) ~= size then
		hexs("measure and write disagree")
		return
	end
	hexs(buffer.tostring(out))
end
`)
	for _, c := range cases {
		fmt.Fprintf(&b, "run(%s, %q, %q)\n", tableModule(u, c.root), c.root, c.input)
	}
	if err := os.WriteFile(filepath.Join(dir, "main.moo"), []byte(b.String()), 0o644); err != nil {
		t.Fatal(err)
	}
	out := moorun.Run(t, dir, "main.moo", inputs)
	lines := decodeHexLines(t, out)
	if len(lines) != 2*len(cases) {
		t.Fatalf("the probe printed %d lines for %d cases:\n%s", len(lines), len(cases), strings.Join(lines, "\n"))
	}
	res := make([][2]string, len(cases))
	for i := range cases {
		res[i] = [2]string{lines[2*i], lines[2*i+1]}
	}
	return res
}

// TestMooJsonGoldensRoundTrip: every instance's golden text reads with a
// silent report and writes back byte for byte.
func TestMooJsonGoldensRoundTrip(t *testing.T) {
	slowtest.Gate(t, "moo (it runs the generated text form)")
	t.Parallel()
	bad := jsonGoldenRun(t, nil)
	for _, b := range bad {
		t.Error(b)
	}
}

func jsonGoldenRun(t *testing.T, runtime map[string][]byte) []string {
	t.Helper()
	m := readTextManifest(t)
	byUnit := map[string][]textInstance{}
	for _, in := range m.instances {
		byUnit[in.unit] = append(byUnit[in.unit], in)
	}
	var bad []string
	for _, key := range sortedKeys(byUnit) {
		u := loadUnit(t, m.units[key])
		if !unitCarriesJson(u) {
			continue
		}
		inputs := map[string][]byte{}
		var cases []textCase
		for _, in := range byUnit[key] {
			text, err := os.ReadFile(filepath.Join(repoRoot, "testdata", "conformance", "tables", "json", in.name+".json"))
			if err != nil {
				t.Fatal(err)
			}
			inputs[in.name] = text
			cases = append(cases, textCase{in.root, in.name})
		}
		res := textRun(t, u, cases, inputs, runtime)
		for i, in := range byUnit[key] {
			if res[i][0] != "0,0,0,0,0,false,read," {
				bad = append(bad, fmt.Sprintf("%s (%s %s): the golden read reported %s", in.name, key, in.root, res[i][0]))
			}
			if want := string(inputs[in.name]); res[i][1] != want {
				bad = append(bad, fmt.Sprintf("%s (%s %s): wrote\n%s\nwant\n%s", in.name, key, in.root, res[i][1], want))
			}
		}
	}
	return bad
}

// TestMooJsonHostileVerdicts: every json-hostile tree reads to its verdict.
func TestMooJsonHostileVerdicts(t *testing.T) {
	slowtest.Gate(t, "moo (it runs the generated text form)")
	t.Parallel()
	m := readTextManifest(t)
	byUnit := map[string][]textHostile{}
	for _, h := range m.hostile {
		byUnit[h.unit] = append(byUnit[h.unit], h)
	}
	for _, key := range sortedKeys(byUnit) {
		u := loadUnit(t, m.units[key])
		inputs := map[string][]byte{}
		var cases []textCase
		for _, h := range byUnit[key] {
			text, err := os.ReadFile(filepath.Join(repoRoot, h.tree, h.root+".json"))
			if err != nil {
				t.Fatal(err)
			}
			inputs[h.name] = text
			cases = append(cases, textCase{h.root, h.name})
		}
		res := textRun(t, u, cases, inputs, nil)
		for i, h := range byUnit[key] {
			got := res[i][0]
			// the verdict's columns: u,k,w,c,d,m,read — or refused alone
			at := strings.LastIndexByte(got, ',')
			verdict := got[:at]
			if strings.HasSuffix(verdict, ",refused") {
				verdict = "refused"
			}
			if verdict != h.verdict {
				t.Errorf("%s (%s %s): read %s, want %s", h.name, key, h.root, got, h.verdict)
			}
		}
	}
}

func readGolden(t *testing.T, name string) []byte {
	t.Helper()
	text, err := os.ReadFile(filepath.Join(repoRoot, "testdata", "conformance", "tables", "json", name+".json"))
	if err != nil {
		t.Fatal(err)
	}
	return text
}

// TestMooJsonOneWalk is M9's moo cell (docs/PORTING.md): the text walk is ONE
// runtime module, json.moo, byte-identical in every unit that carries the form,
// and a generated table module carries no walk of its own — only its three
// calls into it and the facts the descriptors lack.
func TestMooJsonOneWalk(t *testing.T) {
	m := readTextManifest(t)
	want := Runtime()["json.moo"]
	carried := 0
	for _, key := range sortedKeys(m.units) {
		u := loadUnit(t, m.units[key])
		files, err := Generate(u)
		if err != nil {
			t.Fatal(err)
		}
		got, ok := files["json.moo"]
		if ok != unitCarriesJson(u) {
			t.Fatalf("unit %s: json.moo emitted %v, the unit carries json %v", key, ok, unitCarriesJson(u))
		}
		if !ok {
			continue
		}
		carried++
		if string(got) != string(want) {
			t.Errorf("unit %s: json.moo differs from the runtime's", key)
		}
		for name, data := range files {
			if strings.HasSuffix(name, "Table.moo") && strings.Contains(string(data), "local function read") {
				t.Errorf("unit %s: %s carries a walk of its own", key, name)
			}
		}
	}
	if carried == 0 {
		t.Fatal("no unit of the manifest carries json: the gate proves nothing")
	}
}
