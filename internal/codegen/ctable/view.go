package ctable

// UnitView is a separately linked registry over every declared type, including
// types no table reaches. It reuses the table descriptors without adding wire
// identities or JSON codecs to those outside declarations (SPEC-TABLES section 8).
import (
	"fmt"
	"math/big"
	"sort"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

type viewGen struct {
	unit    *ir.Unit
	reached map[string]bool
	outside []*ir.Struct
}

func viewBase(pkg string) string {
	if pkg == "" {
		return "View"
	}
	return strings.ToUpper(pkg[:1]) + pkg[1:] + "View"
}
func generateViewFiles(u *ir.Unit, closure map[string]bool, variable, targets map[string]bool, anyKeyed, anyList, anyMap bool) map[string][]byte {
	v := &viewGen{unit: u, reached: ir.TableClosureVocabulary(u)}
	for _, f := range u.Files {
		for _, d := range f.Decls {
			if st, ok := d.(*ir.Struct); ok && !st.IsTable && !closure[st.Name] {
				v.outside = append(v.outside, st)
			}
		}
	}
	sort.Slice(v.outside, func(i, j int) bool { return v.outside[i].Name < v.outside[j].Name })
	base := viewBase(u.Package)
	g := &tableGen{unit: u, file: &ir.File{Base: base}, anyVariable: len(variable) > 0, anyKeyed: anyKeyed, anyList: anyList, anyMap: anyMap, anySequence: anyList || anyMap, variable: variable, targets: targets, includes: map[string]bool{}}
	banner := "/* Code generated by the schema compiler. DO NOT EDIT.\n   SPDX-License-Identifier: NONE — this generated output is yours. */\n"
	var h strings.Builder
	h.WriteString(banner)
	guard := "SCHEMA_" + strings.ToUpper(u.Package) + "_VIEW_H"
	fmt.Fprintf(&h, "#ifndef %s\n#define %s\n#include <stdint.h>\n#include <stddef.h>\n#include <string.h>\n", guard, guard)
	for _, f := range u.Files {
		fmt.Fprintf(&h, "#include \"%s.h\"\n", f.Base)
	}
	if len(u.Tables) > 0 {
		for _, f := range u.Files {
			fmt.Fprintf(&h, "#include \"%sTable.h\"\n", f.Base)
		}
	} else {
		h.WriteString(tablePrimitives(u.Package, false, false, "\n", false, false, false))
	}
	h.WriteString("\n#ifdef __cplusplus\nextern \"C\" {\n#endif\n")
	h.WriteString(viewRecords)
	g.emitTableResetDeclarations(v.outside)
	for _, st := range v.outside {
		g.emitTableReset(st)
		g.pf("extern const TableTypeInfo %s;\n", g.sym(st.Name, "info"))
		g.pf("static SCHEMA_UNUSED const TableTypeInfo * %s(void) { return &%s; }\n", g.api(st.Name, "table_type"), g.sym(st.Name, "info"))
	}
	h.WriteString(g.body.String())
	g.body.Reset()
	fmt.Fprintf(&h, "const UnitViewInfo * %s(void);\nstatic SCHEMA_UNUSED const UnitViewInfo * unit_view(void) { return %s(); }\n", g.sym("unit", "view"), g.sym("unit", "view"))
	h.WriteString("#ifdef __cplusplus\n}\n#endif\n#endif\n")
	var c strings.Builder
	c.WriteString(banner)
	fmt.Fprintf(&c, "#include \"%s.h\"\n", base)
	g.outside = true
	for _, st := range v.outside {
		g.emitTableDescriptor(st)
	}
	g.outside = false
	_, _, unions := v.vocabularies()
	for _, un := range unions {
		g.emitUnionArmDescriptors(un)
	}
	g.outside = false
	v.emitRegistry(g)
	c.WriteString(g.body.String())
	return map[string][]byte{base + ".h": []byte(h.String()), base + ".c": []byte(c.String())}
}

const viewRecords = `typedef struct ViewConstant
{
    const char * name;
    const char * file;       // the declaring schema file's basename
    const char * type_name;  // declared storage: "int64", "float64", "int32", ...
    int is_float;
    int64_t int_value;       // the folded value; float_value when is_float
    double float_value;
    const char * doc;        // the ` + "`///`" + ` block above it, verbatim (SPEC §4.1);
                             // "" when there is none, never NULL (§8.1)
    int32_t num_tags;             // the declaration's tags (SPEC §4.2), in
    const char * const * tags;    // DECLARED order; 0 and NULL when there are none
} ViewConstant;

typedef struct ViewVariant          // one enum variant, one flags bit, one union arm
{
    uint64_t value;         // an enum's value, a flags BIT INDEX, a union's tag
    const char * name;
    uint64_t id;            // the table-wire id (§5). It is 0 for a flags bit,
                            // and throughout a vocabulary no table closure
                            // reaches (§8.2)
    const char * payload_name;      // a union arm's TYPE as declared — a record's
                                    // name, or a general arm's spelling
                                    // ("int32", "string(64)", "*Chunk"); NULL on
                                    // a payload-free arm and on every other row
    const TableTypeInfo * payload;  // that payload's descriptor — never NULL for
                                    // an arm naming a ` + "`type`" + ` or a ` + "`table`" + ` (§8.2);
                                    // NULL on a general arm, on a payload-free
                                    // arm, on tag 0, and on an enum or flags row
    const TableFieldInfo * field;   // a general arm's FIELD descriptor: its kind,
                                    // width, bounds, capacity, companions and the
                                    // offsets §8.1 takes within the union's
                                    // storage. NULL on an arm naming a ` + "`type`" + ` or
                                    // a ` + "`table`" + `, on a payload-free arm, on tag 0,
                                    // and on an enum or flags row
    const char * doc;               // the ` + "`///`" + ` block above this variant, bit or
                                    // arm, verbatim; "" when there is none (§8.1)
    int32_t num_tags;               // this row's own tags, in DECLARED order;
    const char * const * tags;      // 0 and NULL when there are none. On a general
                                    // arm the ` + "`field`" + ` descriptor above carries the
                                    // same two values (§8.1)
} ViewVariant;

typedef struct ViewVocabulary       // an enum, a flags or a union declaration
{
    const char * name;
    const char * file;
    int64_t max;            // highest value / highest bit index / highest tag
    int32_t storage_bits;
    int32_t num_variants;
    const ViewVariant * variants;
    const char * doc;             // the declaration's own ` + "`///`" + ` block; "" when none
    int32_t num_tags;             // the declaration's own tags, in DECLARED order;
    const char * const * tags;    // 0 and NULL when there are none
} ViewVocabulary;

typedef struct ViewType             // one declaration: a type, or a table
{
    const char * name;
    const char * file;
    int table;                     // declared ` + "`table`" + `
    const TableTypeInfo * type;     // §8.1's descriptor: the properties, and this
                                    // declaration's own doc and tags beside them
    const char * doc;               // the ` + "`///`" + ` block above it; "" when none. The
                                    // same text ` + "`type->doc`" + ` carries (§8.1)
    int32_t num_tags;               // the declaration's tags (SPEC §4.2), in
    const char * const * tags;      // DECLARED order; the same list ` + "`type`" + ` carries
} ViewType;

typedef struct UnitViewInfo
{
    const char * package;
    uint64_t protocol_id;
    int32_t num_types;      const ViewType * types;
    int32_t num_tables;     const ViewType * tables;
    int32_t num_enums;      const ViewVocabulary * enums;
    int32_t num_flags;      const ViewVocabulary * flags;
    int32_t num_unions;     const ViewVocabulary * unions;
    int32_t num_constants;  const ViewConstant * constants;
} UnitViewInfo;

`

// emitRegistry emits UnitView() and the six sets it answers with. The data is
// a function-local static, exactly as a descriptor's is: one instance per
// process, ODR-safe, and no mutable state on the surface a caller sees.
func (v *viewGen) emitRegistry(g *tableGen) {
	u := v.unit
	g.pf("const UnitViewInfo * %s(void)\n{\n", g.sym("unit", "view"))

	enums, flags, unions := v.vocabularies()
	var enumRows, flagRows, unionRows []viewVocab
	for _, e := range enums {
		v.emitEnumVocabulary(g, e)
		enumRows = append(enumRows, enumVocab{e})
	}
	for _, f := range flags {
		v.emitFlagsVocabulary(g, f)
		flagRows = append(flagRows, flagsVocab{f})
	}
	for _, un := range unions {
		v.emitUnionVocabulary(g, un)
		unionRows = append(unionRows, unionVocab{un})
	}
	v.emitVocabularyArray(g, "enums", enumRows)
	v.emitVocabularyArray(g, "flags_decls", flagRows)
	v.emitVocabularyArray(g, "unions", unionRows)

	types, tables := v.declarations()
	v.emitTypeArray(g, "types", types)
	v.emitTypeArray(g, "tables", tables)
	v.emitConstants(g)

	g.pf("    static const UnitViewInfo info = { \"%s\", 0x%016xull,\n", u.Package, u.ProtocolId)
	g.pf("        %s,\n", countAndData(len(types), "types"))
	g.pf("        %s,\n", countAndData(len(tables), "tables"))
	g.pf("        %s,\n", countAndData(len(enums), "enums"))
	g.pf("        %s,\n", countAndData(len(flags), "flags_decls"))
	g.pf("        %s,\n", countAndData(len(unions), "unions"))
	g.pf("        %s };\n", countAndData(len(v.constants()), "constants"))
	g.pf("    return &info;\n}\n")
}

func countAndData(n int, name string) string {
	if n == 0 {
		return "0, NULL"
	}
	return fmt.Sprintf("%d, %s", n, name)
}

// ---- the vocabulary rows ----

// emitEnumVocabulary emits one enum's variant rows: row 0 is None with the
// reserved id, then the variants in DECLARED order with the wire id each
// rides under (docs/SPEC-TABLES.md §8.3).
func (v *viewGen) emitEnumVocabulary(g *tableGen, e *ir.Enum) {
	for i := range e.Variants {
		g.emitTagsStatic(variantTagsName(e.Name, i), e.VariantTags[i])
	}
	g.emitTagsStatic(declTagsName(e.Name), e.Tags)
	g.pf("    static const ViewVariant %s_view_variants[] = {\n", e.Name)
	g.pf("        { 0, \"None\", 0, NULL, NULL, NULL, %s },\n", annotationColumns("", nil, ""))
	for i, name := range e.Variants {
		id := uint64(0)
		if v.reached[e.Name] {
			id = ir.TableWireId(e.VariantWireName(i))
		}
		g.pf("        { %d, \"%s\", 0x%016xull, NULL, NULL, NULL, %s },\n",
			i+1, name, id, annotationColumns(e.VariantDocs[i], e.VariantTags[i], variantTagsName(e.Name, i)))
	}
	g.pf("    };\n")
}

// emitFlagsVocabulary emits one flags declaration's rows. A row's value is a
// BIT INDEX and its id is the reserved id, because a mask's variants ride by
// position and have no per-variant wire id (§4, §8.3).
func (v *viewGen) emitFlagsVocabulary(g *tableGen, fl *ir.Flags) {
	for i := range fl.Variants {
		g.emitTagsStatic(variantTagsName(fl.Name, i), fl.VariantTags[i])
	}
	g.emitTagsStatic(declTagsName(fl.Name), fl.Tags)
	g.pf("    static const ViewVariant %s_view_variants[] = {\n", fl.Name)
	for i, name := range fl.Variants {
		g.pf("        { %d, \"%s\", 0, NULL, NULL, NULL, %s },\n",
			i, name, annotationColumns(fl.VariantDocs[i], fl.VariantTags[i], variantTagsName(fl.Name, i)))
	}
	g.pf("    };\n")
}

// emitUnionVocabulary emits one union's rows: tag 0, the empty arm, then the
// arms in declared order (SPEC §4.8). An arm naming a record carries that
// payload's descriptor; an arm that names none carries the FIELD descriptor a
// field of that type would have, emitted through the ONE field-row emitter so
// an arm's descriptor can never drift from a field's (§8.1, §8.3).
func (v *viewGen) emitUnionVocabulary(g *tableGen, un *ir.Union) {
	was := g.outside
	g.outside = !v.reached[un.Name]
	defer func() { g.outside = was }()
	for i := range un.Variants {
		g.emitTagsStatic(variantTagsName(un.Name, i), un.Variants[i].Tags)
	}
	g.emitTagsStatic(declTagsName(un.Name), un.Tags)
	g.pf("    static const ViewVariant %s_view_variants[] = {\n", un.Name)
	g.pf("        { 0, \"None\", 0, NULL, NULL, NULL, %s },\n", annotationColumns("", nil, ""))
	for i, va := range un.Variants {
		id := uint64(0)
		if v.reached[un.Name] {
			id = ir.TableWireId(va.WireName())
		}
		payloadName, payload, field := "NULL", "NULL", "NULL"
		switch {
		case va.Void():
			// a PAYLOAD-FREE arm's name and its tag are all there is of it
		case va.Body():
			payloadName = fmt.Sprintf("%q", ir.FieldTypeSpelling(va.F))
			payload = "&" + g.sym(va.Type, "info")
		default:
			payloadName = fmt.Sprintf("%q", ir.FieldTypeSpelling(va.F))
			field = g.armDescriptorSymbol(un.Name, va.Name)
		}
		g.pf("        { %d, \"%s\", 0x%016xull, %s, %s, %s, %s },\n",
			i+1, va.Name, id, payloadName, payload, field,
			annotationColumns(va.Doc, va.Tags, variantTagsName(un.Name, i)))
	}
	g.pf("    };\n")
}

// emitVocabularyArray emits one of the three vocabulary sets, in declaration
// NAME order (docs/SPEC-TABLES.md §8.3).
func (v *viewGen) emitVocabularyArray(g *tableGen, name string, decls []viewVocab) {
	if len(decls) == 0 {
		return
	}
	g.pf("    static const ViewVocabulary %s[] = {\n", name)
	for _, d := range decls {
		g.pf("        { \"%s\", \"%s\", %d, %d, %d, %s, %s },\n",
			d.Name(), v.file(d.Name()), d.Max(), d.StorageBits(), d.NumVariants(), d.Name()+"_view_variants",
			annotationColumns(d.Doc(), d.Tags(), declTagsName(d.Name())))
	}
	g.pf("    };\n")
}

// emitTypeArray emits the `types` or the `tables` set: each entry's own doc
// and tags beside the §8.1 descriptor its properties are walked through.
func (v *viewGen) emitTypeArray(g *tableGen, name string, decls []*ir.Struct) {
	if len(decls) == 0 {
		return
	}
	for _, st := range decls {
		g.emitTagsStatic(declTagsName(st.Name), st.Tags)
	}
	g.pf("    static const ViewType %s[] = {\n", name)
	for _, st := range decls {
		g.pf("        { \"%s\", \"%s\", %s, &%s, %s },\n",
			st.Name, v.file(st.Name), boolC(st.IsTable), g.sym(st.Name, "info"),
			annotationColumns(st.Doc, st.Tags, declTagsName(st.Name)))
	}
	g.pf("    };\n")
}

// emitConstants emits the one declaration kind with no runtime surface of its
// own: its name, its declared storage and its folded value (§8.3).
func (v *viewGen) emitConstants(g *tableGen) {
	consts := v.constants()
	if len(consts) == 0 {
		return
	}
	for _, c := range consts {
		g.emitTagsStatic(declTagsName(c.Name), c.Tags)
	}
	g.pf("    static const ViewConstant constants[] = {\n")
	for _, c := range consts {
		intValue, floatValue := "0", "0.0"
		if c.IsFloat {
			floatValue = formatFloat(c.Float, false)
		} else {
			intValue = constantIntValue(c.Int)
		}
		g.pf("        { \"%s\", \"%s\", \"%s\", %s, %s, %s, %s },\n",
			c.Name, v.file(c.Name), c.Storage, boolC(c.IsFloat), intValue, floatValue,
			annotationColumns(c.Doc, c.Tags, declTagsName(c.Name)))
	}
	g.pf("    };\n")
}

// constantIntValue renders a folded integer for the int64 column. A uint64
// declaration past the signed maximum is spelled as the two's-complement
// pattern the column holds rather than truncated silently.
func constantIntValue(value *big.Int) string {
	if value == nil {
		return "0"
	}
	if value.IsInt64() {
		if value.Int64() == -1<<63 {
			return "(-INT64_C(9223372036854775807)-1)"
		}
		return "INT64_C(" + value.String() + ")"
	}
	return fmt.Sprintf("(int64_t) 0x%016xull", value.Uint64())
}

// ---- the sets, and the order they are listed in ----

// viewVocab is the one shape the three vocabulary declarations share, so the
// set emitter is written once.
type viewVocab interface {
	Name() string
	Max() int64
	StorageBits() int
	NumVariants() int
	Doc() string
	Tags() []string
}

type enumVocab struct{ e *ir.Enum }

func (d enumVocab) Name() string     { return d.e.Name }
func (d enumVocab) Max() int64       { return d.e.Max }
func (d enumVocab) StorageBits() int { return d.e.StorageBits }
func (d enumVocab) NumVariants() int { return len(d.e.Variants) + 1 } // row 0 is None
func (d enumVocab) Doc() string      { return d.e.Doc }
func (d enumVocab) Tags() []string   { return d.e.Tags }

type flagsVocab struct{ f *ir.Flags }

func (d flagsVocab) Name() string { return d.f.Name }

// Max is the highest declared BIT INDEX, the same number a flags field's
// descriptor carries in enum_max (docs/SPEC-TABLES.md §8.1).
func (d flagsVocab) Max() int64 { return int64(len(d.f.Variants) - 1) }

// StorageBits is the mask's storage width, the smallest of 8/16/32/64 that
// holds every declared bit.
func (d flagsVocab) StorageBits() int {
	for _, w := range []int{8, 16, 32, 64} {
		if d.f.WireBits <= w {
			return w
		}
	}
	return 64
}
func (d flagsVocab) NumVariants() int { return len(d.f.Variants) }
func (d flagsVocab) Doc() string      { return d.f.Doc }
func (d flagsVocab) Tags() []string   { return d.f.Tags }

type unionVocab struct{ u *ir.Union }

func (d unionVocab) Name() string     { return d.u.Name }
func (d unionVocab) Max() int64       { return d.u.Max }
func (d unionVocab) StorageBits() int { return d.u.StorageBits }
func (d unionVocab) NumVariants() int { return len(d.u.Variants) + 1 } // tag 0 is the empty arm
func (d unionVocab) Doc() string      { return d.u.Doc }
func (d unionVocab) Tags() []string   { return d.u.Tags }

// vocabularies returns the three vocabulary sets in declaration-NAME order.
func (v *viewGen) vocabularies() (enums []*ir.Enum, flags []*ir.Flags, unions []*ir.Union) {
	for _, e := range v.unit.Enums {
		enums = append(enums, e)
	}
	for _, f := range v.unit.Flags {
		flags = append(flags, f)
	}
	for _, un := range v.unit.Unions {
		unions = append(unions, un)
	}
	// a union with a table arm is a declaration like any other: it lives
	// beside Unions in the IR because it has no packet wire, and the registry
	// lists what was declared (docs/SPEC-TABLES.md §2.6)
	for _, un := range v.unit.TableUnions {
		unions = append(unions, un)
	}
	sort.Slice(enums, func(i, j int) bool { return enums[i].Name < enums[j].Name })
	sort.Slice(flags, func(i, j int) bool { return flags[i].Name < flags[j].Name })
	sort.Slice(unions, func(i, j int) bool { return unions[i].Name < unions[j].Name })
	return enums, flags, unions
}

// declarations returns the `type` set and the `table` set, each in
// declaration-NAME order. A map's GENERATED entry table is not among them: it
// is claimed rather than declared (§2.8), and a walker meets it through the
// map field's own `table` column.
func (v *viewGen) declarations() (types, tables []*ir.Struct) {
	for _, f := range v.unit.Files {
		for _, d := range f.Decls {
			if st, ok := d.(*ir.Struct); ok && !st.IsTable {
				types = append(types, st)
			}
		}
		for _, st := range f.Tables {
			if st.MapEntryOf == "" {
				tables = append(tables, st)
			}
		}
	}
	byName := func(s []*ir.Struct) { sort.Slice(s, func(i, j int) bool { return s[i].Name < s[j].Name }) }
	byName(types)
	byName(tables)
	return types, tables
}

// constants returns the unit's constants in declaration-NAME order.
func (v *viewGen) constants() []*ir.Const {
	out := make([]*ir.Const, 0, len(v.unit.Consts))
	for _, c := range v.unit.Consts {
		out = append(out, c)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}

// file names the schema file a declaration was declared in, by basename.
func (v *viewGen) file(name string) string {
	if base, ok := v.unit.DeclFile[name]; ok {
		return base + ".schema"
	}
	return ""
}

func declTagsName(name string) string { return name + "_view_tags" }

func variantTagsName(owner string, index int) string {
	return fmt.Sprintf("%s_view_variant%d_tags", owner, index)
}
