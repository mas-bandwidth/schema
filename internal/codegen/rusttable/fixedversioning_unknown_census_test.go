package rusttable

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

// §5.8 row 11, `unknown_census`, on the RUST leg: the NEW build reads
// `old_unknown_census.bin` through a HANDED-IN lineage entry (§5.1 refuses the
// removal, so no lock). The bytes are the C++ reference's own — one record,
// four `items`, `a` = 10..13 and `drop` = 900..903 — and the divergence is in
// the COUNTING, not in damaged data. `report.unknown` is asserted EXACTLY
// `== 1` because `Item.drop` is ONE field of ONE peer (§5.4), and a leg that
// censuses inside the array's element loop lands `4` and passes any `>= 1`.
func TestFixedVersioningUnknownCensus(t *testing.T) {
	corpus := versionCorpus(t)
	repo, err := filepath.Abs("../../..")
	if err != nil {
		t.Fatal(err)
	}
	serialize, err := filepath.Abs(filepath.Join(repo, "..", "serialize.rs"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(serialize); err != nil {
		t.Fatalf("the Rust runtime is not beside this tree at %s: %v", serialize, err)
	}
	root := filepath.Join(repo, "build", "rust-versioning-probes-unknown-census")
	if err := os.RemoveAll(root); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(root, 0o750); err != nil {
		t.Fatal(err)
	}

	p := versionProbe{
		name:   "probe_unknown_census_new_reads_old",
		reader: "VNEW_unknown_census",
		older:  []string{"VOLD_unknown_census"},
		src: versionProbeSource(fmt.Sprintf(`
/// unknown_census, NEW-READS-OLD: the NEW build reads the OLD writer's file
/// through a handed-in lineage entry (§5.1 refuses the removal, so no lock).
#[test]
fn v_unknown_census_new_reads_old() {
    let data = std::fs::read(%q).expect("the reference's old_unknown_census.bin");
    let mut values = vec![ROWTYPE::default(); 8];
    let mut plan = vec![TableFixedEntry::default(); 4096];
    let mut remap = vec![0u16; 4096];
    let mut report = TableFixedReport::default();
    let n = LOADFN(&mut values, &data, &mut plan, &mut remap, &mut report);
    let n = n.unwrap_or_else(|| panic!(
        "the newer reader REFUSED the older writer's file: {} {:?}", report.reason.name(), report
    ));
    assert!(n == 1, "the newer reader did not read the older writer's one record: n={n}");
    assert!(
        !report.refused && report.reason == TableFixedReason::None,
        "a clean NEW-READS-OLD is not a refusal: {:?}", report
    );
    assert!(!report.malformed, "a clean backward read is not damage: {:?}", report);
    assert!(
        report.kind_mismatch == 0 && report.widened == 0 && report.clamped == 0,
        "counters that must not move did: {:?}", report
    );
    assert!(
        report.unknown == 1,
        "unknown == {}, want 1: Item.drop is ONE field of ONE peer, not one per element", report.unknown
    );
    assert!(
        values[0].lead == 1 && values[0].trail == 2,
        "the bracketing fields moved: lead={} trail={}", values[0].lead, values[0].trail
    );
    for k in 0..4 {
        assert!(
            values[0].items[k].a == 10 + k as i32,
            "items[{k}].a == {}, want {}", values[0].items[k].a, 10 + k as i32
        );
    }
    // THE SECOND READ OWES THE SAME CENSUS. The census is the plan's own number,
    // carried onto a report once per read that returns (§5.9 #6), so a second
    // read into a fresh report reads 1 again — never 2, never 4.
    let mut values2 = vec![ROWTYPE::default(); 8];
    let mut plan2 = vec![TableFixedEntry::default(); 4096];
    let mut remap2 = vec![0u16; 4096];
    let mut report2 = TableFixedReport::default();
    let n2 = LOADFN(&mut values2, &data, &mut plan2, &mut remap2, &mut report2);
    let n2 = n2.unwrap_or_else(|| panic!(
        "the second read REFUSED the older writer's file: {} {:?}", report2.reason.name(), report2
    ));
    assert!(
        n2 == 1 && report2.unknown == 1,
        "the second read owes the same census: n={n2} {:?}", report2
    );
}
`, filepath.Join(corpus, "old_unknown_census.bin"))),
	}
	versionWriteCrate(t, root, serialize, p)

	ws := fmt.Sprintf(`# Generated by internal/codegen/rusttable/fixedversioning_unknown_census_test.go. Not tracked.
[workspace]
resolver = "3"
members = [%q]

[profile.dev]
debug = 0
`, p.name)
	if err := os.WriteFile(filepath.Join(root, "Cargo.toml"), []byte(ws), 0o600); err != nil {
		t.Fatal(err)
	}

	cmd := exec.Command("cargo", "test", "--workspace", "--no-fail-fast")
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "CARGO_TARGET_DIR="+filepath.Join(repo, "build", "rust-versioning-target-unknown-census"))
	out, _ := cmd.CombinedOutput()
	versionAssert(t, string(out), "v_unknown_census_new_reads_old")
}
