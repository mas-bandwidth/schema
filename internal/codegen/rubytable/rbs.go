var rbsReservedWords = func() map[string]bool {
	words := strings.Fields(`alias and attr_accessor attr_reader attr_writer begin bool bot break case class
		def defined? do else elsif end ensure extend false for if in include instance interface
		module next nil not or out prepend private public redo rescue retry return self singleton
		super then top true type unchecked undef unless until untyped use void when while yield`)
	m := make(map[string]bool, len(words))
	for _, w := range words {
		m[w] = true
	}
	return m
}()

func rbsMethodName(name string) string {
	base := strings.TrimSuffix(name, "=")
	if rbsReservedWords[base] {
		return "`" + name + "`"
	}
	return name
}

func rbsPacketElemType(f *ir.Field) string {
	switch f.Type.Kind {
	case ir.TBool:
		return "bool"
	case ir.TInt, ir.TBits, ir.TFixed:
		return "Integer"
	case ir.TFloat32, ir.TFloat64:
		return "Float"
	case ir.TString, ir.TBytes:
		return "String"
	case ir.TNamed:
		switch f.Type.Ref.(type) {
		case *ir.Enum, *ir.Flags:
			return "Integer"
		case *ir.Struct, *ir.Union:
			return f.Type.Name
		}
	}
	return "untyped"
}

func rbsPacketFieldType(f *ir.Field) string {
	if f.Array != ir.ArrayNone {
		return "::Array[" + rbsPacketElemType(f) + "]"
	}
	return rbsPacketElemType(f)
}

func rbsPacketUnionArms(u *ir.Union) []ir.UnionVariant {
	var arms []ir.UnionVariant
	for _, v := range u.Variants {
		if !v.Void() {
			arms = append(arms, v)
		}
	}
	return arms
}

