package rubytable

import (
	"fmt"
	"sort"
	"strings"

	"github.com/mas-bandwidth/schema/v3/internal/codegen/genheader"
	"github.com/mas-bandwidth/schema/v3/internal/tablewire"
	"github.com/mas-bandwidth/schema/v3/ir"
)

func closureUnions(u *ir.Unit) map[string]bool {
	out := map[string]bool{}
	for name := range tablewire.MessageClosure(u) {
		st := u.Tables[name]
		if st == nil {
			st = u.Structs[name]
		}
		if st == nil {
			continue
		}
		for _, f := range st.Fields {
			collectMessageUnions(u, f, out)
		}
	}
	return out
}

func collectMessageUnions(u *ir.Unit, f *ir.Field, seen map[string]bool) {
	if f == nil || f.Type.Kind != ir.TNamed {
		return
	}
	un, ok := f.Type.Ref.(*ir.Union)
	if !ok || seen[un.Name] {
		return
	}
	seen[un.Name] = true
	for _, v := range un.Variants {
		collectMessageUnions(u, v.F, seen)
	}
}

func messageRoots(u *ir.Unit) []string {
	var roots []string
	for _, st := range u.Tables {
		if st != nil && st.FixedDeclared {
			roots = append(roots, st.Name)
		}
	}
	sort.Strings(roots)
	return roots
}

func messageModule(u *ir.Unit, mod string) string {
	roots := messageRoots(u)
	if len(roots) == 0 {
		return ""
	}
	raw := tablewire.Announce(u)
	var b strings.Builder
	b.WriteString("# frozen_string_literal: true\n\n")
	fmt.Fprintf(&b, "# Code generated by the schema compiler from the unit %s. DO NOT EDIT.\n", u.Package)
	b.WriteString(genheader.Line("#") + "\n")
	b.WriteString("require_relative '_table/message'\n\n")
	fmt.Fprintf(&b, "module %s\n", mod)
	fmt.Fprintf(&b, "  ANNOUNCEMENT = %s.b.freeze\n\n", rbBytesLiteral(raw))
	b.WriteString("  class MessageVocabulary < SchemaTable::MessageVocabulary\n")
	b.WriteString("    def initialize(strict: false)\n")
	b.WriteString("      super(BUILD_VERSION, strict: strict)\n")
	b.WriteString("    end\n")
	b.WriteString("  end\n\n")
	b.WriteString("  module SchemaTable\n")
	b.WriteString("    MSG_ROOTS = SchemaTable.map_h\n")
	for _, name := range roots {
		fmt.Fprintf(&b, "    MSG_ROOTS[%s] = true\n", rbQuote(name))
	}
	b.WriteString("    MSG_ROOTS.freeze\n\n")
	b.WriteString("    MSG_CRC_ROOTS = SchemaTable.map_h\n")
	for _, name := range roots {
		if u.Tables[name].Integrity == "crc32c" {
			fmt.Fprintf(&b, "    MSG_CRC_ROOTS[%s] = true\n", rbQuote(name))
		}
	}
	b.WriteString("    MSG_CRC_ROOTS.freeze\n\n")
	b.WriteString("    MSG_FIELD_KEYS = SchemaTable.map_h\n")
	closure := tablewire.MessageClosure(u)
	names := make([]string, 0, len(closure))
	for name := range closure {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		st := u.Tables[name]
		if st == nil {
			st = u.Structs[name]
		}
		if st == nil {
			continue
		}
		for _, f := range st.Fields {
			entry := ir.TableFieldEntry(f)
			fmt.Fprintf(&b, "    MSG_FIELD_KEYS[[%s, %s].freeze] = %s.b.freeze\n",
				rbQuote(st.Name), rbQuote(f.Name), rbBytesLiteral(entry.Encode(nil)))
		}
	}
	unions := closureUnions(u)
	unionNames := make([]string, 0, len(unions))
	for name := range unions {
		unionNames = append(unionNames, name)
	}
	sort.Strings(unionNames)
	for _, name := range unionNames {
		un := u.TableUnions[name]
		if un == nil {
			un = u.Unions[name]
		}
		if un == nil {
			continue
		}
		for _, variant := range un.Variants {
			entry := ir.TableArmEntry(variant)
			fmt.Fprintf(&b, "    MSG_FIELD_KEYS[[%s, %s].freeze] = %s.b.freeze\n",
				rbQuote(un.Name), rbQuote(variant.Name), rbBytesLiteral(entry.Encode(nil)))
		}
	}
	b.WriteString("    MSG_FIELD_KEYS.freeze\n\n")
	b.WriteString("    MSG_RECORDS = SchemaTable.map_h\n")
	for _, name := range names {
		fmt.Fprintf(&b, "    if (_s_rec = SchemaTable.by_name(%s))\n      MSG_RECORDS[%s] = _s_rec\n    end\n", rbQuote(name), rbQuote(name))
	}
	b.WriteString("    MSG_RECORDS.freeze\n\n")
	b.WriteString("    MSG_LOCAL = MessageVocabulary.new\n")
	b.WriteString("    SchemaTable.announce_read_raw(MSG_LOCAL, ANNOUNCEMENT)\n")
	b.WriteString("  end\n\n")
	b.WriteString("  def self.announce_read(vocab, data, max_bytes: 65_536, max_entries: 4096)\n")
	b.WriteString("    SchemaTable.announce_read_raw(vocab, data, max_bytes: max_bytes, max_entries: max_entries)\n")
	b.WriteString("    SchemaTable.resolve_vocabulary(vocab, SchemaTable::MSG_LOCAL, SchemaTable::MSG_RECORDS)\n")
	b.WriteString("  end\n\n")
	b.WriteString("  def self.save_messages(root, values)\n")
	b.WriteString("    rname = root.respond_to?(:descriptor) ? root.descriptor.name : ''\n")
	b.WriteString("    raw = SchemaTable.save_message_batch(root, values.to_a, SchemaTable::MSG_LOCAL, SchemaTable::MSG_FIELD_KEYS, SchemaTable::MSG_ROOTS)\n")
	b.WriteString("    SchemaTable::MSG_CRC_ROOTS[rname] ? SchemaTable.seal_crc(raw) : raw\n")
	b.WriteString("  end\n\n")
	b.WriteString("  def self.measure_messages(root, values)\n")
	b.WriteString("    rname = root.respond_to?(:descriptor) ? root.descriptor.name : ''\n")
	b.WriteString("    sz = SchemaTable.measure_message_batch(root, values.to_a, SchemaTable::MSG_LOCAL, SchemaTable::MSG_FIELD_KEYS, SchemaTable::MSG_ROOTS)\n")
	b.WriteString("    sz + (SchemaTable::MSG_CRC_ROOTS[rname] ? 4 : 0)\n")
	b.WriteString("  end\n\n")
	b.WriteString("  def self.load_messages(root, vocab, data, capacity = 256, report = nil)\n")
	b.WriteString("    rname = root.respond_to?(:descriptor) ? root.descriptor.name : ''\n")
	b.WriteString("    raw = SchemaTable::MSG_CRC_ROOTS[rname] ? SchemaTable.open_crc(data, 2) : data\n")
	b.WriteString("    SchemaTable.load_message_batch(root, vocab, raw, BUILD_VERSION, SchemaTable::MSG_FIELD_KEYS, SchemaTable::MSG_ROOTS, capacity, report)\n")
	b.WriteString("  end\n")
	b.WriteString("end\n")
	return b.String()
}
