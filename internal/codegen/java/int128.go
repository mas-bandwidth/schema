package java

import (
	"fmt"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

// emitInt128Support and emitUInt128Support write Int128.java / UInt128.java —
// the emulated 128-bit pair the 128-bit storage widths map to, mirroring
// serialize.java's Int128Value/UInt128Value (one pair shape across the
// family's GC targets, so wire behavior cannot diverge by platform) but
// emitted self-contained: generated code never imports a runtime package.
// Java allows one public class per file, so the pair is two files. The
// operation set is what generated code and its consumers need —
// construction, conversion, add/subtract, compares — with shifts and masks
// left out: the emitter folds every shift at generation time. Instances are
// immutable; the 128-bit paths allocate one small object per operation, a
// Java language necessity (no user-definable value types at this language
// level) — exactly the port's stance.

func supportHeader(u *ir.Unit, base string) string {
	var h strings.Builder
	h.WriteString("// Code generated by the schema compiler. DO NOT EDIT.\n")
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&h, "// package %s — protocol id 0x%016x\n", u.Package, u.ProtocolId)
	fmt.Fprintf(&h, "//\n// The emulated 128-bit pair, %s half: Java has no native 128-bit integer,\n", base)
	h.WriteString("// so int128/uint128 storage speaks Int128/UInt128 — two's-complement math\n")
	h.WriteString("// on (hi, lo) 64-bit halves held bit-transparently in longs, the family's\n")
	h.WriteString("// one pair shape (serialize.java's Int128Value/UInt128Value).\n\n")
	fmt.Fprintf(&h, "package %s;\n\n", u.Package)
	return h.String()
}

func emitUInt128Support(u *ir.Unit) []byte {
	var h strings.Builder
	h.WriteString(supportHeader(u, "unsigned"))
	h.WriteString(`// Unsigned 128-bit value as (hi, lo) long halves, immutable.
public final class UInt128 {
    // The high 64 bits.
    public final long hi;

    // The low 64 bits, held bit-transparently.
    public final long lo;

    // The zero value.
    public static final UInt128 zero = new UInt128(0, 0);

    // The unsigned 128-bit maximum.
    public static final UInt128 maxValue = new UInt128(-1L, -1L);

    // Constructs from explicit high and low halves.
    public UInt128(long hi, long lo) {
        this.hi = hi;
        this.lo = lo;
    }

    // Constructs from a 64-bit value, sign-extending: matching the family
    // pair's conversion from a signed 64-bit integer. For a non-negative
    // value this zero-extends.
    public static UInt128 fromLong(long value) {
        return new UInt128(value < 0 ? -1L : 0, value);
    }

    // The value reinterpreted as signed: bit-transparent.
    public Int128 toSigned() {
        return new Int128(hi, lo);
    }

    // The low 64 bits, truncating.
    public long toLong() {
        return lo;
    }

    public UInt128 add(UInt128 other) {
        final long low = lo + other.lo;
        final long carry = Long.compareUnsigned(low, lo) < 0 ? 1 : 0;
        return new UInt128(hi + other.hi + carry, low);
    }

    public UInt128 subtract(UInt128 other) {
        final long low = lo - other.lo;
        final long borrow = Long.compareUnsigned(lo, other.lo) < 0 ? 1 : 0;
        return new UInt128(hi - other.hi - borrow, low);
    }

    // Unsigned ordering: the high lanes compare unsigned, the low lanes
    // break ties.
    public int compareUnsigned(UInt128 other) {
        final int c = Long.compareUnsigned(hi, other.hi);
        return c != 0 ? c : Long.compareUnsigned(lo, other.lo);
    }

    @Override
    public boolean equals(Object obj) {
        if (!(obj instanceof UInt128)) {
            return false;
        }
        final UInt128 other = (UInt128) obj;
        return lo == other.lo && hi == other.hi;
    }

    @Override
    public int hashCode() {
        return Long.hashCode(lo) * 31 + Long.hashCode(hi);
    }

    // Hex of the 128-bit pattern (toString would render signs, not bits).
    @Override
    public String toString() {
        return String.format("0x%016x%016x", hi, lo);
    }
}
`)
	return []byte(h.String())
}

func emitInt128Support(u *ir.Unit) []byte {
	var h strings.Builder
	h.WriteString(supportHeader(u, "signed"))
	h.WriteString(`// Signed 128-bit value as (hi, lo) long halves, two's complement, immutable.
public final class Int128 {
    // The high 64 bits. The sign lives in its top bit.
    public final long hi;

    // The low 64 bits, held bit-transparently.
    public final long lo;

    // The zero value.
    public static final Int128 zero = new Int128(0, 0);

    // The signed 128-bit minimum, -2^127.
    public static final Int128 minValue = new Int128(0x8000000000000000L, 0);

    // The signed 128-bit maximum, 2^127 - 1.
    public static final Int128 maxValue = new Int128(0x7fffffffffffffffL, -1L);

    // Constructs from explicit high and low halves.
    public Int128(long hi, long lo) {
        this.hi = hi;
        this.lo = lo;
    }

    // Constructs from a 64-bit value, sign-extending.
    public static Int128 fromLong(long value) {
        return new Int128(value < 0 ? -1L : 0, value);
    }

    // The value reinterpreted as unsigned: bit-transparent.
    public UInt128 toUnsigned() {
        return new UInt128(hi, lo);
    }

    // The low 64 bits, truncating.
    public long toLong() {
        return lo;
    }

    public Int128 add(Int128 other) {
        return toUnsigned().add(other.toUnsigned()).toSigned();
    }

    public Int128 subtract(Int128 other) {
        return toUnsigned().subtract(other.toUnsigned()).toSigned();
    }

    // Signed ordering: the high lanes compare signed, the low lanes break
    // ties unsigned.
    public int compareTo(Int128 other) {
        final int c = Long.compare(hi, other.hi);
        return c != 0 ? c : Long.compareUnsigned(lo, other.lo);
    }

    @Override
    public boolean equals(Object obj) {
        if (!(obj instanceof Int128)) {
            return false;
        }
        final Int128 other = (Int128) obj;
        return lo == other.lo && hi == other.hi;
    }

    @Override
    public int hashCode() {
        return Long.hashCode(lo) * 31 + Long.hashCode(hi);
    }

    // Hex of the 128-bit pattern (toString would render signs, not bits).
    @Override
    public String toString() {
        return String.format("0x%016x%016x", hi, lo);
    }
}
`)
	return []byte(h.String())
}
