package cstable

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// §5.8 row `cfloat_res_refine`: VOLD `aim float32 | min = -1, max = 1,
// resolution = 0.1`, VNEW refines to `0.01`. A compressed float rides as the
// float32 itself (SPEC §3.4), so the resolution is a digest definition and this
// row takes NO forged file (a value off the old grid is still a float32 the
// reader lands). `back[0].Aim` is asserted EXACTLY `== 0.3f` and `clamped == 0`
// EXACTLY: the old `0.1` grid is a whole multiple of `0.01`, so a requantizing
// leg lands one ulp off, and `clamped >= 1` / an approximate value would pass
// the re-landing this row exists to catch.
func TestFixedVersioningCfloatResRefine(t *testing.T) {
	corpus := csFixedCorpus(t)
	dir := t.TempDir()

	r := csVersionRow{row: "cfloat_res_refine", check: `
            if (back[0].Aim != 0.3f)
            {
                bad += ProbeLog.Fail(@NAME@, "the old writer's value did not land exactly: aim=" + back[0].Aim);
            }
            if (back[0].Lead != 1u || back[0].Trail != 2u)
            {
                bad += ProbeLog.Fail(@NAME@, "a neighbour moved: lead=" + back[0].Lead + " trail=" + back[0].Trail);
            }`}

	probes := []csVersionProbe{
		{name: "cfloat_res_refine/new_reads_old", reader: "VNEW_cfloat_res_refine",
			older: []string{"VOLD_cfloat_res_refine"}, file: "old_cfloat_res_refine.bin",
			body: csVersionNewReadsOld(t, corpus, r)},
		{name: "cfloat_res_refine/old_refuses_new", reader: "VOLD_cfloat_res_refine",
			file: "new_cfloat_res_refine.bin", body: csVersionOldRefusesNew(r)},
	}

	var calls []string
	for i, p := range probes {
		ns, table, files := csVersionGenerate(t, p)
		gen := filepath.Join(dir, "gen", fmt.Sprintf("u%03d", i))
		csVersionWrite(t, gen, files)
		joined := ""
		for _, data := range files {
			joined += string(data)
		}
		probeClass := fmt.Sprintf("Probe%03d", i)
		body := strings.ReplaceAll(p.body, "@JSON@", csVersionJSON(joined, table))
		body = strings.NewReplacer(
			"@NAME@", fmt.Sprintf("%q", p.name),
			"@TABLE@", table,
			"@FILE@", fmt.Sprintf("%q", p.file),
		).Replace(body)
		src := fmt.Sprintf(`// generated by internal/codegen/cstable's versioning harness: one probe per row per COLUMN
using System;

namespace %s
{
    static class %s
    {
        public static int Run(string corpus)
        {
            int bad = 0;
%s
            if (bad == 0) { Console.WriteLine("ROW " + %s + ": ok"); }
            return bad;
        }
    }
}
`, ns, probeClass, body, fmt.Sprintf("%q", p.name))
		if err := os.WriteFile(filepath.Join(dir, probeClass+".cs"), []byte(src), 0o600); err != nil {
			t.Fatal(err)
		}
		calls = append(calls, fmt.Sprintf("            bad += %s.%s.Run(corpus);", ns, probeClass))
	}

	main := fmt.Sprintf(`using System;

static class ProbeLog
{
    public static int Fail(string row, string what)
    {
        Console.WriteLine("ROW " + row + ": FAILED " + what);
        return 1;
    }
}

static class ProbeMain
{
    static int Main()
    {
        string corpus = Environment.GetEnvironmentVariable("SCHEMA_FIXEDFORM_CORPUS");
        int bad = 0;
        try
        {
%s
        }
        catch (Exception e)
        {
            Console.WriteLine("ROW harness: FAILED " + e.ToString());
            return 1;
        }
        Console.WriteLine(bad == 0 ? "cs versioning: every row green" : "cs versioning: " + bad + " FAILED");
        return bad == 0 ? 0 : 1;
    }
}
`, strings.Join(calls, "\n"))
	if err := os.WriteFile(filepath.Join(dir, "ProbeMain.cs"), []byte(main), 0o600); err != nil {
		t.Fatal(err)
	}

	runtime, err := filepath.Abs("../../../../serialize.cs")
	if err != nil {
		t.Fatal(err)
	}
	proj := fmt.Sprintf(`<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net10.0</TargetFramework>
    <ImplicitUsings>disable</ImplicitUsings>
    <Nullable>annotations</Nullable>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <AssemblyName>csversioning</AssemblyName>
    <NoWarn>CS0162;CS0168;CS0219;CS8600;CS8602;CS8604;CS8625</NoWarn>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="*.cs" />
    <Compile Include="gen/**/*.cs" />
    <Compile Include="%s/src/Serialize.cs" />
    <Compile Include="%s/src/Int128Pair.cs" />
  </ItemGroup>
</Project>
`, runtime, runtime)
	if err := os.WriteFile(filepath.Join(dir, "csversioning.csproj"), []byte(proj), 0o600); err != nil {
		t.Fatal(err)
	}

	dotnet := os.Getenv("DOTNET")
	if dotnet == "" {
		dotnet = "dotnet"
	}
	cmd := exec.Command(dotnet, "run", "--project", dir, "-v", "q", "--nologo")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "SCHEMA_FIXEDFORM_CORPUS="+corpus, "DOTNET_NOLOGO=1")
	out, runErr := cmd.CombinedOutput()

	csVersionAssert(t, out, runErr, "cfloat_res_refine/new_reads_old")
	csVersionAssert(t, out, runErr, "cfloat_res_refine/old_refuses_new")
}
