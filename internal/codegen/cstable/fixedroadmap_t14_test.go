package cstable

// TestFixedRoadmapCSharpT14CompressedFloats is cs/R30. A compressed float
// rides as the float on this leg, and the dequantize the emitter writes is a
// separate multiply then add (docs/SPEC.md Floating-point discipline,
// docs/FIXED-FORM-ALGORITHM.md §5.1):
//
//	float normalized = (float)index / (float)count;
//	float scaled = normalized * delta;
//	return TableFloatToBits(scaled + qmin);
//
// The fixture where math.FMA differs is index 2 under min=-1, max=2,
// resolution=0.1 (count=30, delta=3): unfused 0xbf4ccccc, fused 0xbf4ccccd.
// This test compiles the generated C# and runs the probe on the .NET SDK, so
// the bytes are the leg's own.

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/slowtest"
)

const t14CsOld = `package cfold

fixed table Reading
{
    lead uint32 = 1
    aim float32 | min = -1, max = 2, resolution = 0.1
    trail uint32 = 2
}
`

func TestFixedRoadmapCSharpT14CompressedFloats(t *testing.T) {
	t.Parallel()
	t.Run("cs/R30", func(t *testing.T) {
		t.Parallel()
		slowtest.Gate(t, "the .NET SDK (it compiles and runs the generated unit)")
		b, err := os.ReadFile("../../lockfile/cfloatrange_test.go")
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(b), "func TestLockCFloatResolutionCoarsenedRefuses") || !strings.Contains(string(b), "resolution coarsened") {
			t.Fatal("the lockfile citation is gone")
		}
		u := unitFrom(t, t14CsOld)
		files, err := Generate(u)
		if err != nil {
			t.Fatal(err)
		}
		var src string
		for name, data := range files {
			if strings.HasSuffix(name, ".cs") {
				src += string(data)
			}
		}
		if !strings.Contains(src, "float scaled = normalized * shape.Delta;") || !strings.Contains(src, "TableFloatToBits(scaled + shape.QMin)") {
			t.Fatal("the emitted dequantize does not round the product before the add")
		}
		if !strings.Contains(src, "public static uint TableDequantizeBits(int index, float qmin, float delta, int count)") {
			t.Fatal("the leg emits no fused-free dequantize spelling to probe")
		}
		if strings.Contains(src, "FusedMultiplyAdd(") {
			t.Fatal("the emitted dequantize contracts the multiply-add")
		}

		dir := t.TempDir()
		var sources []string
		for name, data := range files {
			if !strings.HasSuffix(name, ".cs") {
				continue
			}
			path := filepath.Join(dir, name)
			if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, data, 0o600); err != nil {
				t.Fatal(err)
			}
			sources = append(sources, path)
		}
		// The probe rides the emitter's own quantize: index 2 under min=-1,
		// max=2, resolution=0.1 (count=30, delta=3) must give the unfused
		// 0xbf4ccccc, and the fixture must separate it from FMA's 0xbf4ccccd.
		probe := `// generated by internal/codegen/cstable's t14 harness
using System;

static class T14Probe
{
    static int Main()
    {
        uint bits = Cfold.Schema.TableDequantizeBits(2, -1f, 3f, 30);
        if (bits != 0xbf4ccccc) { Console.WriteLine("FAIL cs/R30 dequantize " + bits.ToString("x8")); return 1; }
        float normalized = 2f / 30f;
        uint fused = Cfold.Schema.TableFloatToBits(MathF.FusedMultiplyAdd(normalized, 3f, -1f));
        if (fused == bits) { Console.WriteLine("FAIL cs/R30 fixture does not separate fma"); return 1; }
        Console.WriteLine("PASS cs/R30");
        return 0;
    }
}
`
		probePath := filepath.Join(dir, "T14Probe.cs")
		if err := os.WriteFile(probePath, []byte(probe), 0o600); err != nil {
			t.Fatal(err)
		}
		sources = append(sources, probePath)
		sort.Strings(sources)

		// The Roslyn compiler is invoked through the host directly — the SDK's
		// own compiler without the CLI's first-run configuration or NuGet's
		// restore, neither of which a project referencing no package needs.
		csc, refs, runtime := csDotnetToolchain(t)
		dotnet := csDotnet()
		app := filepath.Join(dir, "cst14.dll")
		args := []string{"exec", csc, "-nologo", "-noconfig", "-target:exe", "-unsafe",
			"-nullable:annotations", "-langversion:latest", "-nostdlib+", "-out:" + app}
		for _, ref := range refs {
			args = append(args, "-r:"+ref)
		}
		args = append(args, sources...)
		compile := exec.Command(dotnet, args...)
		compile.Env, compile.Dir = csDotnetEnv(dir, dir), dir
		compileOut, compileErr := compile.CombinedOutput()
		if compileErr != nil {
			t.Fatalf("cs/R30 compile failed: %v\n%s", compileErr, compileOut)
		}
		cfg := fmt.Sprintf("{\"runtimeOptions\":{\"tfm\":\"net10.0\",\"framework\":{\"name\":\"Microsoft.NETCore.App\",\"version\":%q}}}\n", runtime)
		if err := os.WriteFile(filepath.Join(dir, "cst14.runtimeconfig.json"), []byte(cfg), 0o600); err != nil {
			t.Fatal(err)
		}
		run := exec.Command(dotnet, "exec", app)
		run.Env, run.Dir = csDotnetEnv(dir, dir), dir
		out, runErr := run.CombinedOutput()
		if !strings.Contains(string(out), "PASS cs/R30") {
			t.Fatalf("cs/R30 DID NOT PASS: %v\n%s", runErr, out)
		}
	})
}
