// csTextDifferentialSchema is the Go leg's float-only unit, byte for byte: a
// float32, a float64, a nested type, a bounded float32 array and a bounded
// float64 array under a fixed table.
const csTextDifferentialSchema = `package probe
type Sample {
 s float32
 d float64
}
fixed table Root {
 a float32
 b float64
 pair Sample
 many [..8]float32
 deep [..8]float64
}
`

// csTextDifferentialProbe is the C# probe program. It takes the directory, the
// seed and the count as arguments, so the outer test owns them, and writes
// inst-<i>.wire and inst-<i>.json for each instance. The splitmix64 and the
// draw order are the Go leg's.
const csTextDifferentialProbe = `// generated by internal/codegen/cstable's text differential (I13)
using System;
using System.IO;

static class SplitMix64
{
    public static ulong State;

    public static ulong Next()
    {
        unchecked
        {
            State += 0x9E3779B97F4A7C15UL;
            ulong z = State;
            z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9UL;
            z = (z ^ (z >> 27)) * 0x94D049BB133111EBUL;
            return z ^ (z >> 31);
        }
    }

    public static float NextFloat32()
    {
        for (;;)
        {
            float f = BitConverter.UInt32BitsToSingle(unchecked((uint)Next()));
            if (float.IsFinite(f)) { return f; }
        }
    }

    public static double NextFloat64()
    {
        for (;;)
        {
            double f = BitConverter.UInt64BitsToDouble(Next());
            if (double.IsFinite(f)) { return f; }
        }
    }
}

static class ProbeMain
{
    static int Main(string[] args)
    {
        if (args.Length != 3)
        {
            Console.WriteLine("PROBE FAILED: usage: app <dir> <seed> <n>");
            return 2;
        }
        string dir = args[0];
        SplitMix64.State = ulong.Parse(args[1], System.Globalization.CultureInfo.InvariantCulture);
        int n = int.Parse(args[2], System.Globalization.CultureInfo.InvariantCulture);
        for (int i = 0; i < n; i++)
        {
            var v = new Probe.Root();
            Probe.Schema.TableReset(v);
            if (i != 0)
            {
                v.A = SplitMix64.NextFloat32();
                v.B = SplitMix64.NextFloat64();
                v.Pair.S = SplitMix64.NextFloat32();
                v.Pair.D = SplitMix64.NextFloat64();
                v.ManyCount = 8;
                for (int j = 0; j < 8; j++) { v.Many[j] = SplitMix64.NextFloat32(); }
                v.DeepCount = 8;
                for (int j = 0; j < 8; j++) { v.Deep[j] = SplitMix64.NextFloat64(); }
            }
            long size = Probe.Schema.RootMeasure(v);
            if (size < 0)
            {
                Console.WriteLine("PROBE FAILED: instance " + i + ": RootMeasure refused (" + size + ")");
                return 1;
            }
            byte[] wire = new byte[size];
            if (Probe.Schema.RootSave(v, wire) != wire.Length)
            {
                Console.WriteLine("PROBE FAILED: instance " + i + ": RootSave wrote short");
                return 1;
            }
            File.WriteAllBytes(Path.Combine(dir, "inst-" + i + ".wire"), wire);
            long textSize = Probe.Schema.RootToJsonMeasure(v);
            if (textSize < 0)
            {
                Console.WriteLine("PROBE FAILED: instance " + i + ": RootToJsonMeasure refused (" + textSize + ")");
                return 1;
            }
            byte[] text = new byte[textSize];
            if (Probe.Schema.RootToJson(v, text) != text.Length)
            {
                Console.WriteLine("PROBE FAILED: instance " + i + ": RootToJson wrote short");
                return 1;
            }
            File.WriteAllBytes(Path.Combine(dir, "inst-" + i + ".json"), text);
        }
        Console.WriteLine("PROBE wrote " + n + " instances");
        return 0;
    }
}
`

const (
	csTextDifferentialSeed = 24845619678
	csTextDifferentialN    = 200

	// csTextDifferentialAnchor is the emitted walker's float32 precision
	// ceiling (json.go's WriteFloat). The negative control caps it at six.
	csTextDifferentialAnchor   = "int high = single ? 9 : 17;"
	csTextDifferentialSabotage = "int high = single ? 6 : 17; /* SABOTAGED */"
)

// csTextDiffToolchain is the SDK the probe builds with: dotnet, Roslyn's
// csc.dll and the net10.0 ref pack. Discovery is local and returns values, so
// a parallel caller never races on package state (the T13/T18 lesson).
type csTextDiffToolchain struct {
	dotnet, csc, refDir, refVersion string
	runtime                         []string // the sibling serialize.cs sources
}

func csTextDiffDiscover(t *testing.T) csTextDiffToolchain {
	t.Helper()
	require := os.Getenv("SCHEMA_REQUIRE_CORPUS") != ""
	miss := func(format string, args ...any) {
		t.Helper()
		if require {
			t.Fatalf("SCHEMA_REQUIRE_CORPUS is set and "+format, args...)
		}
		t.Skipf(format, args...)
	}
	var tc csTextDiffToolchain
	tc.dotnet = os.Getenv("DOTNET")
	if tc.dotnet == "" {
		tc.dotnet = "dotnet"
	}
	resolved, err := exec.LookPath(tc.dotnet)
	if err != nil {
		miss("no dotnet on PATH (set DOTNET): %v", err)
	}
	real, err := filepath.EvalSymlinks(resolved)
	if err != nil {
		real = resolved
	}
	root := filepath.Dir(real)
	cscs, _ := filepath.Glob(filepath.Join(root, "sdk", "*", "Roslyn", "bincore", "csc.dll"))
	if len(cscs) == 0 {
		miss("no Roslyn csc.dll under %s", root)
	}
	tc.csc = cscs[0]
	refs, _ := filepath.Glob(filepath.Join(root, "packs", "Microsoft.NETCore.App.Ref", "*", "ref", "net10.0"))
	if len(refs) == 0 {
		miss("no .NET ref pack (net10.0) under %s", root)
	}
	tc.refDir = refs[0]
	tc.refVersion = filepath.Base(filepath.Dir(filepath.Dir(refs[0])))
	// the unit's nested type is a plain `type`, which the csharp backend emits
	// into the packet-form file, and that file needs the serialize.cs runtime:
	// the sibling checkout beside the repository, where the fixed-form
	// versioning harnesses name it
	runtime, err := filepath.Abs("../../../../serialize.cs")
	if err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"Serialize.cs", "Int128Pair.cs"} {
		path := filepath.Join(runtime, "src", name)
		if _, err := os.Stat(path); err != nil {
			miss("no sibling serialize.cs runtime: %v", err)
		}
		tc.runtime = append(tc.runtime, path)
	}
	return tc
}

// runCsTextDifferential generates the unit, applies an optional in-memory
// edit to the emitted files, builds and runs the probe once, and then runs the
// engine comparison. It returns the divergence messages and a non-nil error
// when any instance differs, so the negative control asserts on the same
// output the row itself produces.
func runCsTextDifferential(t *testing.T, tc csTextDiffToolchain, edit func(map[string][]byte)) ([]byte, error) {
	t.Helper()
	dir := t.TempDir()
	u := unitFrom(t, csTextDifferentialSchema)
	pk, err := csharp.Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	tb, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	files := map[string][]byte{}
	for name, data := range pk {
		files[name] = data
	}
	for name, data := range tb {
		files[name] = data
	}
	if edit != nil {
		edit(files)
	}
	gen := filepath.Join(dir, "gen")
	out := filepath.Join(dir, "out")
	for _, d := range []string{gen, out} {
		if err := os.MkdirAll(d, 0o700); err != nil {
			t.Fatal(err)
		}
	}
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(gen, name), data, 0o600); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, "ProbeMain.cs"), []byte(csTextDifferentialProbe), 0o600); err != nil {
		t.Fatal(err)
	}

	genFiles, _ := filepath.Glob(filepath.Join(gen, "*.cs"))
	refs, _ := filepath.Glob(filepath.Join(tc.refDir, "*.dll"))
	args := []string{"exec", tc.csc, "-nologo", "-langversion:latest", "-unsafe", "-out:" + filepath.Join(dir, "app.dll")}
	for _, r := range refs {
		args = append(args, "-r:"+r)
	}
	args = append(args, filepath.Join(dir, "ProbeMain.cs"))
	args = append(args, genFiles...)
	args = append(args, tc.runtime...)
	env := append(os.Environ(), "DOTNET_NOLOGO=1", "DOTNET_CLI_TELEMETRY_OPTOUT=1")
	build := exec.Command(tc.dotnet, args...)
	build.Dir = dir
	build.Env = env
	if b, err := build.CombinedOutput(); err != nil {
		return b, fmt.Errorf("csc: %w", err)
	}
	rtc := fmt.Sprintf(`{
  "runtimeOptions": {
    "tfm": "net10.0",
    "framework": { "name": "Microsoft.NETCore.App", "version": %q }
  }
}
`, tc.refVersion)
	if err := os.WriteFile(filepath.Join(dir, "app.runtimeconfig.json"), []byte(rtc), 0o600); err != nil {
		t.Fatal(err)
	}
	run := exec.Command(tc.dotnet, "exec", filepath.Join(dir, "app.dll"), out,
		strconv.FormatUint(csTextDifferentialSeed, 10), strconv.Itoa(csTextDifferentialN))
	run.Dir = dir
	run.Env = env
	if b, err := run.CombinedOutput(); err != nil {
		return b, fmt.Errorf("probe: %w", err)
	}

	m := tabletext.NewModel(u)
	msgs, err := compareCsTextDifferential(m, out, csTextDifferentialN)
	if err != nil {
		return nil, err
	}
	if len(msgs) > 0 {
		return []byte(strings.Join(msgs, "\n\n")), fmt.Errorf("%d of %d instance(s) differ", len(msgs), csTextDifferentialN)
	}
	return nil, nil
}

// TestCsTextDifferential is the row: the emitted C# float writer and the
// engine's float writer agree, byte for byte, over 200 random float-only
// instances, in both directions.
func TestCsTextDifferential(t *testing.T) {
	t.Parallel()
	slowtest.Gate(t, "dotnet (it compiles and runs a C# probe over the generated unit)")
	tc := csTextDiffDiscover(t)
	out, err := runCsTextDifferential(t, tc, nil)
	if err != nil {
		t.Fatalf("cs text differential: %v\n%s", err, out)
	}
	t.Logf("cs text differential: %d random instances, leg text == engine text and engine wire == leg wire, both directions", csTextDifferentialN)
}

// TestCsTextDifferentialNegativeControl caps the emitted walker's float32 text
// at SIX significant digits, so a float32 that needs seven, eight or nine
// renders short and only the cross-implementation comparison sees it. The gate
// must go red on the text comparison, not on a compile error or a probe
// failure.
func TestCsTextDifferentialNegativeControl(t *testing.T) {
	t.Parallel()
	slowtest.Gate(t, "dotnet (it compiles and runs a C# probe over the generated unit)")
	tc := csTextDiffDiscover(t)
	out, err := runCsTextDifferential(t, tc, func(files map[string][]byte) {
		total := 0
		for _, data := range files {
			total += strings.Count(string(data), csTextDifferentialAnchor)
		}
		if total != 1 {
			t.Fatalf("NEGATIVE CONTROL FAILED: the sabotage anchor %q appeared %d times across the emitted files, want 1", csTextDifferentialAnchor, total)
		}
		for name, data := range files {
			if bytes.Contains(data, []byte(csTextDifferentialAnchor)) {
				files[name] = bytes.Replace(data, []byte(csTextDifferentialAnchor), []byte(csTextDifferentialSabotage), 1)
			}
		}
	})
	if err == nil {
		t.Fatalf("NEGATIVE CONTROL FAILED: a float32 writer capped at six significant digits left the gate GREEN\n%s", out)
	}
	if !bytes.Contains(out, []byte("leg text and engine text differ")) {
		t.Fatalf("NEGATIVE CONTROL FAILED: the gate went red, but not on the text comparison: %v\n%s", err, out)
	}
	first, _, _ := strings.Cut(string(out), "\n\n")
	t.Logf("cs text differential negative control: red on the text comparison as required (%v); first divergence:\n%s", err, first)
}

// compareCsTextDifferential runs both directions of the engine comparison for
// every instance the probe wrote. Direction one: the engine reads the wire and
// writes its text, byte-compared against the leg's text. Direction two: the
// engine packs the leg's text back to wire, byte-compared against the leg's
// wire. Divergences are collected as messages, never failures, so the negative
// control can assert on them.
func compareCsTextDifferential(m *tabletext.Model, dir string, n int) ([]string, error) {
	var msgs []string
	for i := range n {
		wire, err := os.ReadFile(filepath.Join(dir, fmt.Sprintf("inst-%d.wire", i)))
		if err != nil {
			return msgs, fmt.Errorf("read inst-%d.wire: %w", i, err)
		}
		legJSON, err := os.ReadFile(filepath.Join(dir, fmt.Sprintf("inst-%d.json", i)))
		if err != nil {
			return msgs, fmt.Errorf("read inst-%d.json: %w", i, err)
		}

		d1, err := os.MkdirTemp(dir, "d1-")
		if err != nil {
			return msgs, err
		}
		report, err := tablepack.UnpackOneFile(m, "Root", wire, d1)
		if err != nil {
			os.RemoveAll(d1)
			return msgs, fmt.Errorf("instance %d: UnpackOneFile: %w", i, err)
		}
		if report != (tabletext.Report{}) {
			os.RemoveAll(d1)
			return msgs, fmt.Errorf("instance %d: UnpackOneFile report not clean: %+v", i, report)
		}
		engineJSON, err := os.ReadFile(filepath.Join(d1, "Root.json"))
		os.RemoveAll(d1)
		if err != nil {
			return msgs, fmt.Errorf("instance %d: read engine Root.json: %w", i, err)
		}
		if !bytes.Equal(engineJSON, legJSON) {
			off, win := csTextWindow(legJSON, engineJSON)
			msgs = append(msgs, fmt.Sprintf("instance %d: leg text and engine text differ at byte %d\n%s\nfloats: %s", i, off, win, csFloatBitsOf(m, wire)))
			continue
		}

		d2, err := os.MkdirTemp(dir, "d2-")
		if err != nil {
			return msgs, err
		}
		if err := os.WriteFile(filepath.Join(d2, "Root.json"), legJSON, 0o600); err != nil {
			os.RemoveAll(d2)
			return msgs, err
		}
		wireBack, _, report2, err := tablepack.Pack(m, "Root", d2)
		os.RemoveAll(d2)
		if err != nil {
			return msgs, fmt.Errorf("instance %d: Pack: %w", i, err)
		}
		if report2 != (tabletext.Report{}) {
			return msgs, fmt.Errorf("instance %d: Pack report not clean: %+v", i, report2)
		}
		if !bytes.Equal(wireBack, wire) {
			msgs = append(msgs, fmt.Sprintf("instance %d: engine wire packed from leg text differs from leg wire: engine=%x leg=%x", i, wireBack, wire))
		}
	}
	return msgs, nil
}

// csFloatBitsOf decodes one wire with the engine and spells every float
// field's bits, so a divergence replays from the bits alone.
func csFloatBitsOf(m *tabletext.Model, wire []byte) string {
	inst := m.New(m.Lookup("Root"))
	var report tabletext.Report
	if _, err := tablewire.Decode(m, inst, wire, &report); err != nil {
		return fmt.Sprintf("<decode error: %v>", err)
	}
	var b strings.Builder
	var walk func(fields []tabletext.Field, prefix string)
	walk = func(fields []tabletext.Field, prefix string) {
		for i := range fields {
			f := &fields[i]
			name := prefix + f.Def.Name
			emit := func(c tabletext.Cell, slot string) {
				switch f.Def.Type.Kind {
				case ir.TFloat32:
					fmt.Fprintf(&b, "%s=0x%08x(f32) ", slot, math.Float32bits(float32(c.F)))
				case ir.TFloat64:
					fmt.Fprintf(&b, "%s=0x%016x(f64) ", slot, math.Float64bits(c.F))
				}
			}
			if len(f.Elems) > 0 {
				for j := 0; j < f.Count && j < len(f.Elems); j++ {
					c := f.Elems[j]
					if c.Tab != nil {
						walk(c.Tab.Fields, fmt.Sprintf("%s[%d].", name, j))
					} else {
						emit(c, fmt.Sprintf("%s[%d]", name, j))
					}
				}
				continue
			}
			if f.Cell.Tab != nil {
				walk(f.Cell.Tab.Fields, name+".")
				continue
			}
			emit(f.Cell, name)
		}
	}
	walk(inst.Fields, "")
	return strings.TrimSpace(b.String())
}

// csTextWindow returns the first byte offset where two texts differ and a
// window of each around it.
func csTextWindow(a, b []byte) (int, string) {
	n := min(len(b), len(a))
	i := 0
	for i < n && a[i] == b[i] {
		i++
	}
	lo := max(i-32, 0)
	hiA := min(i+32, len(a))
	hiB := min(i+32, len(b))
	return i, fmt.Sprintf("leg[%d:%d]=%q engine[%d:%d]=%q", lo, hiA, a[lo:hiA], lo, hiB, b[lo:hiB])
}
