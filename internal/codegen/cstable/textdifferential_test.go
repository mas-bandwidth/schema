package cstable

// I13 (docs/PORTING.md) is the text differential against a third
// implementation: the leg emits random instances as (wire, text), the
// compiler's own engine (schema unpack, internal/tabletext, written from the
// spec and from neither backend) reads the same wire and writes its text, the
// two are byte-compared, then the other direction. This is the C# leg's cell,
// shaped like the Go leg's (internal/codegen/gotable/textdifferential_test.go)
// with the probe in C#.
//
// The engine's float loop is internal/tabletext/write.go's writeFloat/formatG
// (C's %.*g spelled out over Go's exact strconv), while the leg's is the
// emitted walker's WriteFloat/FormatG (json.go's tableJsonWalkSource, C's %.*g
// spelled out over .NET's custom numeric format strings). Two implementations
// in two languages that share no code, and a pinned corpus never reaches a
// float tie, so the random source is built here: a splitmix64 written into the
// probe fills N instances, redrawing any non-finite pattern (non-finite floats
// have no JSON spelling and both writers REFUSE them). Instance 0 is the
// fixture proof: RootReset alone.
//
// The probe is compiled the way the t10 harness compiles its probes: the SDK's
// Roslyn csc and dotnet exec, one build, one run, no csproj, no NuGet; the
// nested plain type lives in the packet-form file, so the sibling serialize.cs
// runtime sources compile in beside it. It is a functional test (a foreign toolchain), so it
// sits behind internal/slowtest.Gate, skips by name without dotnet, and fails
// by name under SCHEMA_REQUIRE_CORPUS=1. The make targets are
// tables-cs-json-differential and tables-cs-json-differential-negative-control
// (make/cs.mk).

