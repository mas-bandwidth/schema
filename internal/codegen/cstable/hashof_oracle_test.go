// hashOracleFile is the C# fixture this test writes and then holds: one row
// per fixed root the cs-tables program compiles, carrying the Go oracle's
// hash and the definitions digest the C# side cannot derive from layout bytes.
const hashOracleFile = "../../../test/cs-tables/src/FixedHashOracle.cs"

// TestCSharpHashOfPinsTheGoOracle pins test/cs-tables's HashOf — the
// cs-tables program's own fnv1a64 over a layout, which replaced the
// TableFixedWire.HashOf that cs/R7 retired from the emitted runtime — against
// the Go oracle, ir.TableFixedLayoutHash, for EVERY fixed root the program
// compiles.
//
// The chain has two halves and this test is the Go one. Here: every fixed root
// of every schema test/cs-tables/schematables.csproj compiles (resolved through
// make/cs.mk's tables_generate_cs, the one list of what generates where) is
// generated through the CLI's own path, its emitted <Root>FixedHash is held to
// ir.TableFixedLayoutHash over its emitted <Root>FixedLayout, and the row
// (layout reference, digest, oracle hash, emitted constant) is written into
// FixedHashOracle.cs — which must match byte for byte, so a root added,
// dropped or rehashed without the fixture following is red here. There:
// TestFixedHashOracleCase in FixedFormChecks.cs runs HashOf(layout ‖ digest)
// on each row and holds it to the oracle and the compiled constant.
//
// SCHEMA_UPDATE_HASH_ORACLE=1 rewrites the fixture; nothing else may.
func TestCSharpHashOfPinsTheGoOracle(t *testing.T) {
	t.Parallel()

	dirs := csTablesProgramDirs(t)
	sources := csTablesGenerateSources(t)

	type row struct {
		ns, class, root string
		digest          []byte
		oracle, emitted uint64
	}
	var rows []row
	for _, dir := range dirs {
		src, ok := sources[dir]
		if !ok {
			t.Fatalf("schematables.csproj compiles build/tables-generated-cs/%s, and make/cs.mk's tables_generate_cs names no source for it", dir)
		}
		paths, err := compiler.GatherPaths([]string{filepath.Join("..", "..", "..", src)})
		if err != nil {
			t.Fatalf("%s: %v", src, err)
		}
		c := compiler.New()
		u, err := c.Load(paths)
		if err != nil {
			t.Fatalf("load %s: %v", src, err)
		}
		files, err := c.Generate(u, "cs", compiler.Options{})
		if err != nil {
			t.Fatalf("generate cs %s: %v", src, err)
		}
		emitted := map[string]csEmittedRoot{}
		for name, text := range files {
			for k, v := range csEmittedRoots(t, name, string(text)) {
				if _, dup := emitted[k]; dup {
					t.Fatalf("%s: root %s is emitted twice", src, k)
				}
				emitted[k] = v
			}
		}
		// THE EMITTED SET IS THE SET: a fixed table the C# leg does not lay a
		// fixed form down for (g.fixedRoots) has no constant to pin, and every
		// constant it does lay down must be a fixed root of the unit.
		known := map[string]*ir.Struct{}
		for _, st := range ir.TableFixedRoots(u) {
			known[st.Name] = st
		}
		names := make([]string, 0, len(emitted))
		for k := range emitted {
			names = append(names, k)
		}
		sort.Strings(names)
		for _, name := range names {
			e := emitted[name]
			st, ok := known[name]
			if !ok {
				t.Fatalf("%s: %s.%sFixedHash is emitted for a type that is no fixed root of the unit", src, e.ns, name)
			}
			oracle := ir.TableFixedLayoutHash(e.layout, st)
			if oracle != e.hash {
				t.Errorf("%s: %s.%sFixedHash = 0x%016x, the Go oracle over its emitted layout says 0x%016x", src, e.ns, st.Name, e.hash, oracle)
			}
			digest := ir.TableFixedDefinitionsDigest(st)
			if got := fnv1a64(e.layout, digest); got != oracle {
				t.Errorf("%s: %s: fnv1a64(layout ‖ digest) = 0x%016x, oracle 0x%016x: the digest is not the one the oracle folds", src, st.Name, got, oracle)
			}
			rows = append(rows, row{ns: e.ns, class: e.class, root: st.Name, digest: digest, oracle: oracle, emitted: e.hash})
		}
	}
	if len(rows) == 0 {
		t.Fatal("the cs-tables program compiles no fixed root: the walk, not the property, broke")
	}
	sort.Slice(rows, func(i, j int) bool {
		if rows[i].ns != rows[j].ns {
			return rows[i].ns < rows[j].ns
		}
		return rows[i].root < rows[j].root
	})

	var b bytes.Buffer
	b.WriteString("// FixedHashOracle.cs — GENERATED by TestCSharpHashOfPinsTheGoOracle\n")
	b.WriteString("// (internal/codegen/cstable/hashof_oracle_test.go) from the Go oracle,\n")
	b.WriteString("// ir.TableFixedLayoutHash. Never hand-edited: SCHEMA_UPDATE_HASH_ORACLE=1 go test\n")
	b.WriteString("// -run TestCSharpHashOfPinsTheGoOracle ./internal/codegen/cstable/ rewrites it.\n")
	b.WriteString("//\n")
	b.WriteString("// One row per fixed root this program compiles: the emitted layout, the\n")
	b.WriteString("// definitions digest the oracle folds after it (bill §13; it never rides the\n")
	b.WriteString("// wire, so it is carried here), the oracle's hash, and the compiled constant.\n")
	b.WriteString("// TestFixedHashOracleCase holds HashOf(layout ‖ digest) to both.\n\n")
	b.WriteString("static partial class Program\n{\n")
	b.WriteString("    static readonly (string Root, byte[] Layout, byte[] Digest, ulong Oracle, ulong Emitted)[] FixedHashOracleRoots =\n    {\n")
	for _, r := range rows {
		q := r.ns + "." + r.class + "." + r.root
		fmt.Fprintf(&b, "        (%q, %sFixedLayout, %s, 0x%016xul, %sFixedHash),\n", r.ns+"."+r.root, q, csByteArray(r.digest), r.oracle, q)
	}
	b.WriteString("    };\n}\n")

	if os.Getenv("SCHEMA_UPDATE_HASH_ORACLE") == "1" {
		if err := os.WriteFile(hashOracleFile, b.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(hashOracleFile)
	if err != nil {
		t.Fatalf("%v: SCHEMA_UPDATE_HASH_ORACLE=1 writes it", err)
	}
	if !bytes.Equal(have, b.Bytes()) {
		t.Errorf("%s is not what the Go oracle says for the %d fixed roots the cs-tables program compiles: SCHEMA_UPDATE_HASH_ORACLE=1 rewrites it", hashOracleFile, len(rows))
	}
}

type csEmittedRoot struct {
	ns, class string
	layout    []byte
	hash      uint64
}

var (
	csNamespaceRe = regexp.MustCompile(`(?m)^namespace (\S+)`)
	// The namespace's OWN class, four spaces in: a nested static class (the
	// runtime's TableWire) holds no root's constants.
	csClassRe   = regexp.MustCompile(`(?m)^    public static partial class (\w+)`)
	csHashRe    = regexp.MustCompile(`public const ulong (\w+)FixedHash = 0x([0-9a-f]{16})ul;`)
	csLayoutRe  = regexp.MustCompile(`(?s)public static readonly byte\[\] (\w+)FixedLayout = new byte\[\] \{(.*?)\};`)
	csHexByteRe = regexp.MustCompile(`0x([0-9a-f]{2})`)
)

// csEmittedRoots reads one emitted file's fixed roots: each <Root>FixedHash
// constant, the <Root>FixedLayout beside it, and the namespace and class both
// live in.
func csEmittedRoots(t *testing.T, name, text string) map[string]csEmittedRoot {
	t.Helper()
	out := map[string]csEmittedRoot{}
	hashes := csHashRe.FindAllStringSubmatchIndex(text, -1)
	if len(hashes) == 0 {
		return out
	}
	nsm := csNamespaceRe.FindAllStringSubmatch(text, -1)
	if len(nsm) != 1 {
		t.Fatalf("%s: %d namespaces, want one", name, len(nsm))
	}
	layouts := map[string][]byte{}
	for _, m := range csLayoutRe.FindAllStringSubmatch(text, -1) {
		var lb []byte
		for _, h := range csHexByteRe.FindAllStringSubmatch(m[2], -1) {
			v, _ := strconv.ParseUint(h[1], 16, 8)
			lb = append(lb, byte(v))
		}
		layouts[m[1]] = lb
	}
	classes := csClassRe.FindAllStringSubmatchIndex(text, -1)
	for _, m := range hashes {
		root := text[m[2]:m[3]]
		h, err := strconv.ParseUint(text[m[4]:m[5]], 16, 64)
		if err != nil {
			t.Fatal(err)
		}
		class := ""
		for _, c := range classes {
			if c[0] < m[0] {
				class = text[c[2]:c[3]]
			}
		}
		if class == "" {
			t.Fatalf("%s: %sFixedHash sits in no static partial class", name, root)
		}
		lb, ok := layouts[root]
		if !ok {
			t.Fatalf("%s: %sFixedHash has no %sFixedLayout", name, root, root)
		}
		out[root] = csEmittedRoot{ns: nsm[0][1], class: class, layout: lb, hash: h}
	}
	return out
}

// csTablesProgramDirs is every build/tables-generated-cs/<dir> the cs-tables
// program compiles, read from its own project file. The project names the
// directory through $(TablesGeneratedDir), which defaults to
// build/tables-generated-cs and which the leg's negative controls point at a
// sabotaged copy; either spelling of an include counts.
func csTablesProgramDirs(t *testing.T) []string {
	t.Helper()
	data, err := os.ReadFile("../../../test/cs-tables/schematables.csproj")
	if err != nil {
		t.Fatal(err)
	}
	re := regexp.MustCompile(`(?:build/tables-generated-cs|\$\(TablesGeneratedDir\))/(\w+)/\*\.cs`)
	seen := map[string]bool{}
	var dirs []string
	for _, m := range re.FindAllStringSubmatch(string(data), -1) {
		if !seen[m[1]] {
			seen[m[1]] = true
			dirs = append(dirs, m[1])
		}
	}
	sort.Strings(dirs)
	if len(dirs) == 0 {
		t.Fatal("schematables.csproj compiles no generated table directory")
	}
	return dirs
}

// csTablesGenerateSources maps each generated directory to its schema source,
// from make/cs.mk's tables_generate_cs.
func csTablesGenerateSources(t *testing.T) map[string]string {
	t.Helper()
	data, err := os.ReadFile("../../../make/cs.mk")
	if err != nil {
		t.Fatal(err)
	}
	text := string(data)
	start := strings.Index(text, "define tables_generate_cs\n")
	if start < 0 {
		t.Fatal("make/cs.mk defines no tables_generate_cs")
	}
	end := strings.Index(text[start:], "\nendef")
	if end < 0 {
		t.Fatal("make/cs.mk's tables_generate_cs does not end")
	}
	re := regexp.MustCompile(`--out \$\(2\)/(\w+) (\S+)`)
	out := map[string]string{}
	for _, m := range re.FindAllStringSubmatch(text[start:start+end], -1) {
		out[m[1]] = m[2]
	}
	return out
}

func fnv1a64(runs ...[]byte) uint64 {
	h := uint64(0xcbf29ce484222325)
	for _, run := range runs {
		for _, c := range run {
			h ^= uint64(c)
			h *= 0x100000001b3
		}
	}
	return h
}

func csByteArray(b []byte) string {
	if len(b) == 0 {
		return "new byte[0]"
	}
	parts := make([]string, len(b))
	for i, c := range b {
		parts[i] = fmt.Sprintf("0x%02x", c)
	}
	return "new byte[] { " + strings.Join(parts, ", ") + " }"
}
