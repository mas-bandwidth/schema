package cstable

// The text read's report carries the read's answer, on every outcome: a
// refused or damaged text returns false with a public Verdict other than Ok,
// and a text that reads returns true with Verdict.Ok. The report is the
// caller's ledger whether it is fresh or was last written by an Ok wire load.
// The reason is each language's own diagnostic and is never compared.

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/slowtest"
)

type csTextVerdictCase struct {
	Name string
	Text string
	Want bool
}

var csTextVerdictCases = []csTextVerdictCase{
	{"good", "{\"value\":7,\"count\":3}\n", true},
	{"repeated-key", "{\"value\":1,\"value\":2}\n", false},
	{"trailing-rubbish", "{\"value\":1} x\n", false},
	{"empty-text", "", false},
	{"leading-zero", "{\"value\":01}\n", false},
	{"out-of-range", "{\"value\":101}\n", false},
}

const csTextVerdictSchema = `package probe

table Root {
    value int32 = 1 | min = 0, max = 100
    count int32 = 2
}
`

type csTextVerdictLine struct {
	Name    string
	Phase   string
	OK      bool
	Verdict int
}

func csTextVerdictGenerate(t *testing.T) map[string][]byte {
	t.Helper()
	u := unitFrom(t, csTextVerdictSchema)
	files, err := Generate(u)
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	return files
}

func csTextVerdictDriver() string {
	var b strings.Builder
	b.WriteString(`// generated by internal/codegen/cstable's text-read report probe
using System;

public static class TextVerdictProbe
{
    sealed class C
    {
        public string Name;
        public byte[] Text;
    }

    public static int Main()
    {
        C[] cases = new C[]
        {`)
	for _, c := range csTextVerdictCases {
		fmt.Fprintf(&b, "\n            new C { Name = %q, Text = System.Text.Encoding.UTF8.GetBytes(%q) },", c.Name, c.Text)
	}
	b.WriteString(`
        };

        var seed = new Probe.Root();
        long measure = Probe.Schema.RootMeasure(seed);
        if (measure <= 0) { throw new Exception("the priming value did not measure"); }
        byte[] wire = new byte[(int)measure];
        if (Probe.Schema.RootSave(seed, wire) != measure) { throw new Exception("the priming wire did not save"); }

        foreach (C c in cases)
        {
            Check(c, "fresh", new Probe.TableReport());
            Check(c, "reused", ReusedReport(wire));
        }
        return 0;
    }

    static Probe.TableReport ReusedReport(byte[] wire)
    {
        var report = new Probe.TableReport();
        var value = new Probe.Root();
        if (!Probe.Schema.RootLoad(value, wire, report) || report.Verdict != Probe.Schema.TableWire.Verdict.Ok)
        {
            throw new Exception("the report could not be primed with an Ok wire load");
        }
        return report;
    }

    static void Check(C c, string phase, Probe.TableReport report)
    {
        var value = new Probe.Root();
        bool ok = Probe.Schema.RootFromJson(value, c.Text, report);
        Console.WriteLine(c.Name + "|" + phase + "|" + (ok ? "true" : "false") + "|" + ((int)report.Verdict));
    }
}
`)
	return b.String()
}

func csTextVerdictRun(t *testing.T, files map[string][]byte) []csTextVerdictLine {
	t.Helper()
	dir := t.TempDir()
	var sources []string
	for name, data := range files {
		if !strings.HasSuffix(name, ".cs") {
			continue
		}
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, data, 0o600); err != nil {
			t.Fatal(err)
		}
		sources = append(sources, p)
	}
	driver := filepath.Join(dir, "TextVerdictProbe.cs")
	if err := os.WriteFile(driver, []byte(csTextVerdictDriver()), 0o600); err != nil {
		t.Fatal(err)
	}
	sources = append(sources, driver)

	csc, refs, runtime := csDotnetToolchain(t)
	args := []string{"exec", csc, "-nologo", "-unsafe", "-nowarn:CS8500", "-out:" + filepath.Join(dir, "probe.dll")}
	args = append(args, sources...)
	for _, r := range refs {
		args = append(args, "-r:"+r)
	}
	compile := exec.Command(csDotnet(), args...)
	compile.Env = csDotnetEnv(dir, dir)
	if out, err := compile.CombinedOutput(); err != nil {
		t.Fatalf("csc failed:\n%s", out)
	}
	rc := fmt.Sprintf(`{ "runtimeOptions": { "tfm": "net10.0", "framework": { "name": "Microsoft.NETCore.App", "version": %q } } }`, runtime)
	if err := os.WriteFile(filepath.Join(dir, "probe.runtimeconfig.json"), []byte(rc), 0o600); err != nil {
		t.Fatal(err)
	}
	run := exec.Command(csDotnet(), "exec", filepath.Join(dir, "probe.dll"))
	run.Env = csDotnetEnv(dir, dir)
	out, err := run.CombinedOutput()
	if err != nil {
		t.Fatalf("TextVerdictProbe failed: %v\n%s", err, out)
	}
	var lines []csTextVerdictLine
	for _, raw := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		if raw == "" {
			continue
		}
		parts := strings.Split(raw, "|")
		if len(parts) != 4 {
			t.Fatalf("probe line %q is not name|phase|ok|verdict", raw)
		}
		verdict, err := strconv.Atoi(parts[3])
		if err != nil {
			t.Fatalf("probe line %q has no verdict: %v", raw, err)
		}
		lines = append(lines, csTextVerdictLine{Name: parts[0], Phase: parts[1], OK: parts[2] == "true", Verdict: verdict})
	}
	return lines
}

func csTextVerdictFailures(lines []csTextVerdictLine) []string {
	got := make(map[string]csTextVerdictLine, len(lines))
	for _, line := range lines {
		got[line.Name+"|"+line.Phase] = line
	}
	var fails []string
	for _, c := range csTextVerdictCases {
		for _, phase := range []string{"fresh", "reused"} {
			key := c.Name + "|" + phase
			line, ok := got[key]
			if !ok {
				fails = append(fails, key+": the probe printed no result")
				continue
			}
			if line.OK != c.Want {
				fails = append(fails, fmt.Sprintf("%s: FromJson returned %t, want %t", key, line.OK, c.Want))
			}
			if c.Want && line.Verdict != 0 {
				fails = append(fails, fmt.Sprintf("%s: FromJson returned true with Verdict %d, want Ok (0)", key, line.Verdict))
			}
			if !c.Want && line.Verdict == 0 {
				fails = append(fails, key+": FromJson returned false with Verdict Ok")
			}
		}
	}
	return fails
}

func TestCSharpTextReadReportVerdict(t *testing.T) {
	t.Parallel()
	slowtest.Gate(t, "the .NET SDK (it compiles and runs the generated C#)")
	files := csTextVerdictGenerate(t)
	lines := csTextVerdictRun(t, files)
	if fails := csTextVerdictFailures(lines); len(fails) != 0 {
		t.Fatalf("the text read's report disagrees with its answer:\n%s", strings.Join(fails, "\n"))
	}
}

func TestCSharpTextReadReportVerdictNegativeControl(t *testing.T) {
	t.Parallel()
	slowtest.Gate(t, "the .NET SDK (it compiles and runs the generated C#)")
	files := csTextVerdictGenerate(t)

	const write = "input.Report.Verdict = verdict;"
	removed := false
	without := make(map[string][]byte, len(files))
	for name, data := range files {
		text := string(data)
		if strings.Contains(text, write) {
			text = strings.ReplaceAll(text, write, "/* the verdict write is removed */")
			removed = true
		}
		without[name] = []byte(text)
	}
	if !removed {
		t.Fatalf("the generated artifact carries no verdict write to remove")
	}

	lines := csTextVerdictRun(t, without)
	fails := csTextVerdictFailures(lines)
	for _, c := range csTextVerdictCases {
		if c.Want {
			continue
		}
		found := false
		for _, fail := range fails {
			if strings.HasPrefix(fail, c.Name+"|") {
				found = true
				break
			}
		}
		if !found {
			t.Fatalf("the negative control did not go red by name for %q:\n%s", c.Name, strings.Join(fails, "\n"))
		}
	}
}
