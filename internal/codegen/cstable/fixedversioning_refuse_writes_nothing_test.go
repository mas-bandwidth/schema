package cstable

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// §5.8 row 9, refuse_writes_nothing: the NEW reader reads old_nested_append.bin
// through its lineage, so a compiled plan with a NONEMPTY fill list is in hand
// (the appended nested Vec.w = 88 is the one nonzero prefill) when record 0's
// per-record hash word — its first eight bytes, bitwise inverted — fails the
// hash check; the header's hash stays untouched, so the OLD lineage entry is
// still selected. Verdict: n == -1, no_layout by name, malformed false, every
// counter zero, and a destination poisoned to 0x5A stays 0x5A in every field.
func TestFixedVersioningRefuseWritesNothing(t *testing.T) {
	corpus := csFixedCorpus(t)
	dir := t.TempDir()

	probe := csVersionProbe{
		name:   "refuse_writes_nothing",
		reader: "VNEW_nested_append",
		older:  []string{"VOLD_nested_append"},
		file:   "old_nested_append.bin",
		body: `            byte[] data = System.IO.File.ReadAllBytes(System.IO.Path.Combine(corpus, @FILE@));
            // THE FORGE: record 0's per-record hash word, inverted. The header's
            // hash at HashAt is left untouched, so the reader still selects the
            // OLD lineage entry and has a compiled plan with a nonempty fill
            // list (the appended Vec.w = 88) in hand when step 11 compares the
            // record's own hash and finds it wrong.
            int rec0 = Schema.TableFixedWire.HeaderBytes + 4 + (int)System.Buffers.Binary.BinaryPrimitives.ReadUInt32LittleEndian(data.AsSpan(Schema.TableFixedWire.HeaderBytes));
            if (rec0 + 8 > data.Length)
            {
                bad += ProbeLog.Fail(@NAME@, "record 0 does not fit the corpus file");
                return bad;
            }
            for (int i = 0; i < 8; ++i) { data[rec0 + i] ^= 0xFF; }
            @TABLE@[] back = new @TABLE@[8];
            for (int i = 0; i < back.Length; ++i) { back[i] = new @TABLE@(); }
            // THE POISON: every field of back[0] and its nested Vec — V.X, V.Y,
            // V.Z, V.W and Seq, which is the whole field list the type declares —
            // set to 0x5A5A5A5A, a value that is neither the prefill's default
            // (Vec.W = 88) nor anything the file carries (v.x=1, v.y=2, v.z=3,
            // seq=24) nor the int zero.
            back[0].V.X = 0x5A5A5A5A;
            back[0].V.Y = 0x5A5A5A5A;
            back[0].V.Z = 0x5A5A5A5A;
            back[0].V.W = 0x5A5A5A5A;
            back[0].Seq = 0x5A5A5A5A;
            TableReport r = new TableReport();
            TableFixedEntry[] plan = new TableFixedEntry[8192];
            long n = Schema.@TABLE@FixedLoad(back, data, plan, r);
            if (n != -1)
            {
                bad += ProbeLog.Fail(@NAME@, "a record whose hash names no held layout must refuse: n=" + n + " reason=" + r.Reason);
            }
            if (!r.Refused || r.Reason != "no_layout")
            {
                bad += ProbeLog.Fail(@NAME@, "the refusal is no_layout by name: reason=" + r.Reason + " refused=" + r.Refused);
            }
            if (r.Malformed)
            {
                bad += ProbeLog.Fail(@NAME@, "a refusal by name never sets malformed too (§5.3): malformed=" + r.Malformed);
            }
            if (r.LayoutHash != 0)
            {
                bad += ProbeLog.Fail(@NAME@, "no_layout publishes no hash: 0x" + r.LayoutHash.ToString("x16"));
            }
            if (r.Unknown != 0 || r.KindMismatch != 0 || r.Clamped != 0 || r.Widened != 0 || r.Duplicate != 0 || r.Retained != 0 || r.RetainLost != 0)
            {
                bad += ProbeLog.Fail(@NAME@, "REFUSE is total: no counter moves: unknown=" + r.Unknown + " kind=" + r.KindMismatch + " clamped=" + r.Clamped + " widened=" + r.Widened + " duplicate=" + r.Duplicate + " retained=" + r.Retained + " lost=" + r.RetainLost);
            }
            if (back[0].V.X != 0x5A5A5A5A || back[0].V.Y != 0x5A5A5A5A || back[0].V.Z != 0x5A5A5A5A || back[0].V.W != 0x5A5A5A5A || back[0].Seq != 0x5A5A5A5A)
            {
                bad += ProbeLog.Fail(@NAME@, "the refusal wrote the poisoned destination: v.x=" + back[0].V.X + " v.y=" + back[0].V.Y + " v.z=" + back[0].V.Z + " v.w=" + back[0].V.W + " seq=" + back[0].Seq);
            }`,
	}

	ns, table, files := csVersionGenerate(t, probe)
	gen := filepath.Join(dir, "gen", "u000")
	csVersionWrite(t, gen, files)
	joined := ""
	for _, data := range files {
		joined += string(data)
	}
	body := strings.ReplaceAll(probe.body, "@JSON@", csVersionJSON(joined, table))
	body = strings.NewReplacer(
		"@NAME@", fmt.Sprintf("%q", probe.name),
		"@TABLE@", table,
		"@FILE@", fmt.Sprintf("%q", probe.file),
	).Replace(body)
	src := fmt.Sprintf(`// generated by internal/codegen/cstable's versioning harness: one probe per row per COLUMN
using System;

namespace %s
{
    static class Probe000
    {
        public static int Run(string corpus)
        {
            int bad = 0;
%s
            if (bad == 0) { Console.WriteLine("ROW " + %s + ": ok"); }
            return bad;
        }
    }
}
`, ns, body, fmt.Sprintf("%q", probe.name))
	if err := os.WriteFile(filepath.Join(dir, "Probe000.cs"), []byte(src), 0o600); err != nil {
		t.Fatal(err)
	}

	main := fmt.Sprintf(`using System;

static class ProbeLog
{
    public static int Fail(string row, string what)
    {
        Console.WriteLine("ROW " + row + ": FAILED " + what);
        return 1;
    }
}

static class ProbeMain
{
    static int Main()
    {
        string corpus = Environment.GetEnvironmentVariable("SCHEMA_FIXEDFORM_CORPUS");
        int bad = 0;
        try
        {
            bad += %s.Probe000.Run(corpus);
        }
        catch (Exception e)
        {
            Console.WriteLine("ROW harness: FAILED " + e.ToString());
            return 1;
        }
        Console.WriteLine(bad == 0 ? "cs versioning: every row green" : "cs versioning: " + bad + " FAILED");
        return bad == 0 ? 0 : 1;
    }
}
`, ns)
	if err := os.WriteFile(filepath.Join(dir, "ProbeMain.cs"), []byte(main), 0o600); err != nil {
		t.Fatal(err)
	}

	runtime, err := filepath.Abs("../../../../serialize.cs")
	if err != nil {
		t.Fatal(err)
	}
	proj := fmt.Sprintf(`<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net10.0</TargetFramework>
    <ImplicitUsings>disable</ImplicitUsings>
    <Nullable>annotations</Nullable>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
    <AssemblyName>csversioning</AssemblyName>
    <NoWarn>CS0162;CS0168;CS0219;CS8600;CS8602;CS8604;CS8625</NoWarn>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="*.cs" />
    <Compile Include="gen/**/*.cs" />
    <Compile Include="%s/src/Serialize.cs" />
    <Compile Include="%s/src/Int128Pair.cs" />
  </ItemGroup>
</Project>
`, runtime, runtime)
	if err := os.WriteFile(filepath.Join(dir, "csversioning.csproj"), []byte(proj), 0o600); err != nil {
		t.Fatal(err)
	}

	dotnet := os.Getenv("DOTNET")
	if dotnet == "" {
		dotnet = "dotnet"
	}
	cmd := exec.Command(dotnet, "run", "--project", dir, "-v", "q", "--nologo")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "SCHEMA_FIXEDFORM_CORPUS="+corpus, "DOTNET_NOLOGO=1")
	out, runErr := cmd.CombinedOutput()

	csVersionAssert(t, out, runErr, "refuse_writes_nothing")
}
