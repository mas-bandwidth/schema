// Generate returns basename.cs -> file contents for every file of the unit.
// C# compilations are order-free across files, so there is no topo sort and
// no include graph.
func Generate(u *ir.Unit) (map[string][]byte, error) {
	if err := refuseCollisions(u); err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	home := ir.ProtocolIdHome(u)
	for _, f := range u.Files {
		g := &gen{unit: u, file: f, home: f.Base == home}
		if g.home {
			g.emitBuffers()
		}
		g.emitFile()
		if g.home && usesText(u) {
			g.emitUtf8()
		}
		out[f.Base+".cs"] = g.assemble()
	}
	return out, nil
}

// buffersClass is the static class carrying the buffers' AsSpan extensions.
const buffersClass = "Buffers"

// refuseCollisions refuses a declaration whose name is one of the unit-level
// types this generator adds to the namespace: the Buffer<N> structs and the
// Buffers extension class. The checker's registry claims every per-declaration
// name; these two are this target's own.
func refuseCollisions(u *ir.Unit) error {
	if u.Consts[utf8Helper] != nil {
		return fmt.Errorf("unity: constant %s collides with the generated Schema member of that name; rename it", utf8Helper)
	}
	taken := func(name string) bool {
		return u.Structs[name] != nil || u.Unions[name] != nil || u.Enums[name] != nil || u.Flags[name] != nil || u.Tables[name] != nil
	}
	names := []string{buffersClass}
	for _, n := range bufferLengths(u) {
		names = append(names, bufferName(n))
	}
	for _, name := range names {
		if taken(name) {
			return fmt.Errorf("unity: declaration %s collides with the generated type of that name; rename it", name)
		}
	}
	return nil
}

type gen struct {
	unit *ir.Unit
	file *ir.File
	home bool // this file carries ProtocolId and the unit's buffer types

	types  strings.Builder // namespace-level declarations
	schema strings.Builder // members of the partial static Schema class

	needsSerialize bool // wire functions -> using Serialize;
	needsDiag      bool // Debug.Assert -> using System.Diagnostics;
	needsInterop   bool // MemoryMarshal, StructLayout -> using System.Runtime.InteropServices;
}

func (g *gen) tf(format string, args ...any) { fmt.Fprintf(&g.types, format, args...) }
func (g *gen) sf(format string, args ...any) { fmt.Fprintf(&g.schema, format, args...) }

func (g *gen) assemble() []byte {
	var h strings.Builder
	fmt.Fprintf(&h, "// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", g.file.Base)
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&h, "// package %s — protocol id 0x%016x\n", g.unit.Package, g.unit.ProtocolId)
	if g.home {
		h.WriteString("//\n")
		h.WriteString("// Unity C# (--lang unity, docs/UNITY.md): C# 9 over netstandard2.1, no `unsafe`\n")
		h.WriteString("// code, no reflection, no runtime code generation — IL2CPP and Burst safe.\n")
		h.WriteString("// Every type is an unmanaged [Serializable] struct; default(T) is the zero\n")
		h.WriteString("// form (SPEC §5), Schema.New<T>() the construction form where a type\n")
		h.WriteString("// declares defaults.\n")
		h.WriteString("//\n")
		h.WriteString("// Wire functions return bool. A READ-side schema validation failure returns\n")
		h.WriteString("// false WITHOUT latching; stream failures latch on stream.Error. WRITE-side\n")
		h.WriteString("// contracts (ranges, counts, lengths, mask widths) are caller error and ride\n")
		h.WriteString("// on Debug.Assert, gone from a release build like serialize.cs's own.\n")
	}
	h.WriteString("\n")
	h.WriteString("using System;\n")
	if g.needsDiag {
		h.WriteString("using System.Diagnostics;\n")
	}
	if g.needsInterop {
		h.WriteString("using System.Runtime.InteropServices;\n")
	}
	if g.needsSerialize {
		h.WriteString("using Serialize;\n")
	}
	h.WriteString("\n")
	// a block namespace: file-scoped namespaces are C# 10
	fmt.Fprintf(&h, "namespace %s\n{\n", namespaceOf(g.unit.Package))
	var body strings.Builder
	body.WriteString(g.types.String())
	if g.schema.Len() > 0 {
		body.WriteString("// Schema carries the unit's generated functions and constants — C# has no\n")
		body.WriteString("// namespace-level members (SPEC §6.1 naming); partial, one slice per file.\n")
		body.WriteString("public static partial class Schema\n{\n")
		body.WriteString(indent(g.schema.String()))
		body.WriteString("}\n")
	}
	h.WriteString(indent(body.String()))
	h.WriteString("}\n")
	return []byte(h.String())
}

// indent indents every nonempty line by one level.
func indent(s string) string {
	s = strings.TrimRight(s, "\n")
	var b strings.Builder
	for _, line := range strings.Split(s, "\n") {
		if line != "" {
			b.WriteString("    ")
			b.WriteString(line)
		}
		b.WriteString("\n")
	}
	return b.String()
}

func namespaceOf(pkg string) string {
	if pkg == "" {
		return pkg
	}
	return strings.ToUpper(pkg[:1]) + pkg[1:]
}

func (g *gen) emitFile() {
	if g.home {
		g.sf("// The unit's protocol id — the hash of its wire shape (SPEC §3.1). Two\n")
		g.sf("// sides at the same id speak identical bits; there is no other versioning.\n")
		g.sf("public const ulong ProtocolId = 0x%016x;\n\n", g.unit.ProtocolId)
	}
	for _, d := range g.file.Decls {
		switch d := d.(type) {
		case *ir.Const:
			g.emitConst(d)
		case *ir.Enum:
			g.emitEnum(d)
		case *ir.Flags:
			g.emitFlags(d)
		case *ir.Struct:
			g.emitStruct(d)
			g.emitStructFunctions(d)
		case *ir.Union:
			g.emitUnion(d)
			g.emitUnionFunctions(d)
		}
	}
}

// ---- buffers ----

func bufferName(n int64) string { return fmt.Sprintf("Buffer%d", n) }

// fieldBufferLength is the element count of a field's inline buffer, 0 for a
// field without one.
func fieldBufferLength(f *ir.Field) int64 {
	switch {
	case f.Type.Kind == ir.TString || f.Type.Kind == ir.TWString || f.Type.Kind == ir.TBytes:
		return f.Type.Size
	case f.Array != ir.ArrayNone:
		return f.ArrayBound
	}
	return 0
}

// bufferLengths is every buffer length the unit's types use, ascending.
func bufferLengths(u *ir.Unit) []int64 {
	seen := map[int64]bool{}
	var out []int64
	for _, st := range u.Structs {
		for _, f := range st.Fields {
			if n := fieldBufferLength(f); n > 0 && !seen[n] {
				seen[n] = true
				out = append(out, n)
			}
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out
}

// emitBuffers declares the unit's inline buffer types (home file only): one
// generic struct per length, N sequential fields of T. The layout is what
// makes the Span view legal — every field is the same unmanaged T, declared
// in index order, under LayoutKind.Sequential, so element i sits at i *
// sizeof(T) from E0 (docs/UNITY.md, "Buffers"); test/unity asserts it.
func (g *gen) emitBuffers() {
	lengths := bufferLengths(g.unit)
	if len(lengths) == 0 {
		return
	}
	g.needsInterop = true
	g.tf("// Inline fixed-capacity buffers: a type's arrays, strings and bytes live\n")
	g.tf("// inside it, so every generated struct is unmanaged and allocation-free.\n")
	g.tf("// Index with buffer[i] (bounds-checked, by value) or AsSpan() for refs.\n")
	for _, n := range lengths {
		name := bufferName(n)
		g.tf("[Serializable]\n[StructLayout(LayoutKind.Sequential)]\n")
		g.tf("public struct %s<T> where T : unmanaged\n{\n", name)
		g.tf("    public const int Capacity = %d;\n\n", n)
		for i := int64(0); i < n; i += 16 {
			end := i + 16
			if end > n {
				end = n
			}
			var parts []string
			for j := i; j < end; j++ {
				parts = append(parts, fmt.Sprintf("E%d", j))
			}
			g.tf("    public T %s;\n", strings.Join(parts, ", "))
		}
		g.tf("\n    public T this[int index]\n    {\n")
		g.tf("        get { return MemoryMarshal.CreateReadOnlySpan(ref E0, Capacity)[index]; }\n")
		g.tf("        set { MemoryMarshal.CreateSpan(ref E0, Capacity)[index] = value; }\n")
		g.tf("    }\n}\n\n")
	}
	g.tf("// %s carries the buffers' Span views. An extension on `ref this` is how\n", buffersClass)
	g.tf("// C# 9 returns a view into a struct's own storage.\n")
	g.tf("public static class %s\n{\n", buffersClass)
	for i, n := range lengths {
		if i > 0 {
			g.tf("\n")
		}
		name := bufferName(n)
		g.tf("    public static Span<T> AsSpan<T>(ref this %s<T> buffer) where T : unmanaged\n    {\n", name)
		g.tf("        return MemoryMarshal.CreateSpan(ref buffer.E0, %s<T>.Capacity);\n    }\n", name)
	}
	g.tf("}\n\n")
}

// ---- the UTF-8 content check ----

// utf8Helper is the Schema member a string(N) read calls.
const utf8Helper = "ValidUtf8Text"

// usesText reports whether any packet type of the unit holds a string(N).
func usesText(u *ir.Unit) bool {
	for _, st := range u.Structs {
		for _, f := range st.Fields {
			if f.Type.Kind == ir.TString {
				return true
			}
		}
	}
	return false
}

// emitUtf8 emits the content rule of a string(N) read (SPEC §4.7) once per
// unit: well-formed UTF-8 by Unicode Table 3-7 — no overlong form, no
// surrogate, nothing past U+10FFFF — and no zero byte. In place, no decoder,
// no allocation.
func (g *gen) emitUtf8() {
	g.sf("// %s: well-formed UTF-8 (Unicode Table 3-7) with no zero byte —\n", utf8Helper)
	g.sf("// the content a string(N) read accepts (SPEC §4.7).\n")
	g.sf("internal static bool %s(ReadOnlySpan<byte> text)\n{\n", utf8Helper)
	g.sf(`    for (int i = 0; i < text.Length;)
    {
        int lead = text[i++];
        if (lead < 0x80)
        {
            if (lead == 0)
            {
                return false;
            }
            continue;
        }
        int remaining, point;
        if ((lead & 0xE0) == 0xC0)
        {
            remaining = 1;
            point = lead & 0x1F;
        }
        else if ((lead & 0xF0) == 0xE0)
        {
            remaining = 2;
            point = lead & 0x0F;
        }
        else if ((lead & 0xF8) == 0xF0)
        {
            remaining = 3;
            point = lead & 0x07;
        }
        else
        {
            return false;
        }
        if (remaining > text.Length - i)
        {
            return false;
        }
        for (int part = 0; part < remaining; part++)
        {
            int next = text[i++];
            if ((next & 0xC0) != 0x80)
            {
                return false;
            }
            point = (point << 6) | (next & 0x3F);
        }
        if ((remaining == 1 && point < 0x80)
            || (remaining == 2 && (point < 0x800 || (point >= 0xD800 && point <= 0xDFFF)))
            || (remaining == 3 && (point < 0x10000 || point > 0x10FFFF)))
        {
            return false;
        }
    }
    return true;
}

`)
}

// ---- declarations ----

func (g *gen) emitConst(d *ir.Const) {
	g.sf("%s", ir.DocComment(d.Doc, "", "//"))
	comment := ""
	if d.Expr != nil {
		if s := ir.RenderExpr(d.Expr); s != d.Int.String() && !d.IsFloat {
			comment = " // = " + s
		}
	}
	if d.IsFloat {
		if d.Storage == "float32" {
			g.sf("public const float %s = %s;\n\n", d.Name, formatFloat32(d.Float))
			return
		}
		g.sf("public const double %s = %s;\n\n", d.Name, formatFloat(d.Float))
		return
	}
	g.sf("public const %s %s = %s;%s\n\n", storageName(d.Storage), d.Name, d.Int.String(), comment)
}

func (g *gen) emitEnum(d *ir.Enum) {
	g.tf("%s", ir.DocComment(d.Doc, "", "//"))
	g.tf("// %s — None = 0, variants dense from 1, wire range [0, %d] (SPEC §4.2); C# enums\n", d.Name, d.Max)
	g.tf("// are open over their backing type, so | max headroom values are representable.\n")
	g.tf("public enum %s : %s\n{\n    None = 0,\n", d.Name, csUint(d.StorageBits))
	for i, v := range d.Variants {
		g.tf("%s", ir.DocComment(d.VariantDocs[i], "    ", "//"))
		g.tf("    %s = %d,\n", v, i+1)
	}
	g.tf("}\n\n")
	g.emitEnumSurface(d.Name, d.Variants, d.Max)
}

// emitEnumSurface is the Max constant and the debug name function of an enum
// or a union tag.
func (g *gen) emitEnumSurface(name string, variants []string, max int64) {
	g.sf("public const %s %sMax = (%s)%d; // the exported extent (SPEC §4.2)\n\n", name, name, name, max)
	g.sf("// EnumName%s: the debug/log name of any %s value; \"???\" outside the set.\n", name, name)
	g.sf("public static string EnumName%s(%s value)\n{\n    switch (value)\n    {\n", name, name)
	g.sf("        case %s.None:\n            return \"None\";\n", name)
	for _, v := range variants {
		g.sf("        case %s.%s:\n            return %q;\n", name, v, v)
	}
	g.sf("        default:\n            return \"???\";\n    }\n}\n\n")
}

func (g *gen) emitFlags(d *ir.Flags) {
	g.tf("%s", ir.DocComment(d.Doc, "", "//"))
	g.tf("// %s — one bit per variant; wire %d bits (SPEC §4.2). ulong-backed, the full\n", d.Name, d.WireBits)
	g.tf("// width §4.2 requires, so bits a newer build appended survive a round trip.\n")
	g.tf("[Flags]\npublic enum %s : ulong\n{\n", d.Name)
	for i, v := range d.Variants {
		g.tf("%s", ir.DocComment(d.VariantDocs[i], "    ", "//"))
		g.tf("    %s = 1ul << %d,\n", v, i)
	}
	g.tf("}\n\n")
	g.sf("public const long %sCount = %d; // the declared variant count (SPEC §4.2)\n\n", d.Name, len(d.Variants))
	g.sf("// FlagName%s: the debug/log name of bit i; \"???\" past the declared bits.\n", d.Name)
	g.sf("public static string FlagName%s(int bit)\n{\n    switch (bit)\n    {\n", d.Name)
	for i, v := range d.Variants {
		g.sf("        case %d:\n            return %q;\n", i, v)
	}
	g.sf("        default:\n            return \"???\";\n    }\n}\n\n")
	g.sf("// FlagNames%s renders the set bits as \"A|B\": \"0\" for the empty set, bits\n", d.Name)
	g.sf("// past the declared variants as hex.\n")
	g.sf("public static string FlagNames%s(%s value)\n{\n    string names = \"\";\n", d.Name, d.Name)
	for _, v := range d.Variants {
		g.sf("    if ((value & %s.%s) != 0)\n    {\n        names += \"|%s\";\n    }\n", d.Name, v, v)
	}
	if len(d.Variants) < 64 {
		g.sf("    ulong unknown = (ulong)value >> %d;\n", len(d.Variants))
		g.sf("    if (unknown != 0)\n    {\n        names += \"|0x\" + (unknown << %d).ToString(\"x\", System.Globalization.CultureInfo.InvariantCulture);\n    }\n", len(d.Variants))
	}
	g.sf("    return names.Length == 0 ? \"0\" : names.Substring(1);\n}\n\n")
}

func (g *gen) emitUnion(d *ir.Union) {
	g.tf("// %sType: union %s's tag — None = 0, then each arm in declared order (SPEC §4.8)\n", d.Name, d.Name)
	g.tf("public enum %sType : %s\n{\n    None = 0,\n", d.Name, csUint(ir.StorageBitsFor(int64(len(d.Variants)))))
	arms := make([]string, len(d.Variants))
	for i, v := range d.Variants {
		arms[i] = ir.GoExportName(v.Name)
		g.tf("%s", ir.DocComment(v.Doc, "    ", "//"))
		g.tf("    %s = %d,\n", arms[i], i+1)
	}
	g.tf("}\n\n")
	g.emitEnumSurface(d.Name+"Type", arms, int64(len(d.Variants)))

	g.tf("%s", ir.DocComment(d.Doc, "", "//"))
	g.tf("// union %s — Type says which arm holds the value. default is the empty union\n", d.Name)
	g.tf("// (None). A read initializes the selected arm from its construction form;\n")
	g.tf("// the other arms are unspecified (SPEC §4.8). Consumers read the selected arm.\n")
	g.tf("[Serializable]\npublic struct %s\n{\n    public %sType Type;\n", d.Name, d.Name)
	for _, v := range d.Variants {
		if v.Void() {
			continue // a payload-free arm has no storage (SPEC §4.8)
		}
		g.tf("    public %s %s;\n", v.Type, ir.GoExportName(v.Name))
	}
	g.tf("}\n\n")
}

func (g *gen) emitStruct(d *ir.Struct) {
	g.tf("%s", ir.DocComment(d.Doc, "", "//"))
	g.tf("// type %s", d.Name)
	if hasDefaults(d) {
		g.tf(" — declares defaults: Schema.New%s() constructs it, default is the zero form", d.Name)
	}
	g.tf("\n[Serializable]\npublic struct %s\n{\n", d.Name)
	prevGuard := ""
	for _, f := range d.Fields {
		if f.Guard != prevGuard {
			if f.Guard != "" {
				g.tf("\n    // %s — wire branch; a read zeroes the untaken side (SPEC §5)\n", f.Guard)
			} else {
				g.tf("\n")
			}
			prevGuard = f.Guard
		}
		g.tf("%s", ir.DocComment(f.Doc, "    ", "//"))
		g.emitField(f)
	}
	g.tf("}\n\n")
}

func (g *gen) emitField(f *ir.Field) {
	name := member(f)
	n := fieldBufferLength(f)
	switch {
	case f.Type.Kind == ir.TWString:
		g.tf("    public %s<char> %s; // wstring(%s): UTF-16 code units (SPEC §4.12)\n", bufferName(n), name, sizeSpelling(f))
		g.tf("    public int %sLength;\n", name)
	case f.Type.Kind == ir.TString:
		g.tf("    public %s<byte> %s; // string(%s): UTF-8 bytes (SPEC §4.7)\n", bufferName(n), name, sizeSpelling(f))
		g.tf("    public int %sLength;\n", name)
	case f.Type.Kind == ir.TBytes:
		g.tf("    public %s<byte> %s; // bytes(%s) (SPEC §4.7)\n", bufferName(n), name, sizeSpelling(f))
		g.tf("    public int %sLength;\n", name)
	case f.Array == ir.ArrayFixed:
		g.tf("    public %s<%s> %s;%s\n", bufferName(n), g.storage(f.Type), name, fieldComment(f))
	case f.Array == ir.ArrayCounted:
		g.tf("    public %s<%s> %s; // count in [%d, %s]%s\n", bufferName(n), g.storage(f.Type), name, f.ArrayMin, arraySpelling(f), commentTail(f))
		g.tf("    public int %sCount;\n", name)
	default:
		g.tf("    public %s %s;%s\n", g.storage(f.Type), name, fieldComment(f))
	}
}

func sizeSpelling(f *ir.Field) string {
	if f.Type.SizeExpr != nil {
		return ir.RenderExpr(f.Type.SizeExpr)
	}
	return strconv.FormatInt(f.Type.Size, 10)
}

func arraySpelling(f *ir.Field) string {
	if f.ArrayExpr != nil {
		return ir.RenderExpr(f.ArrayExpr)
	}
	return strconv.FormatInt(f.ArrayBound, 10)
}

func member(f *ir.Field) string { return ir.GoExportName(f.Name) }

func fieldComment(f *ir.Field) string {
	parts := commentParts(f)
	if len(parts) == 0 {
		return ""
	}
	return " // " + strings.Join(parts, "; ")
}

func commentTail(f *ir.Field) string {
	parts := commentParts(f)
	if len(parts) == 0 {
		return ""
	}
	return "; " + strings.Join(parts, "; ")
}

func commentParts(f *ir.Field) []string {
	var parts []string
	if f.HasDefault {
		parts = append(parts, "default "+defaultSpelling(f))
	}
	if f.HasIntRange {
		parts = append(parts, fmt.Sprintf("wire [%s, %s]", f.IntMin, f.IntMax))
	}
	if f.HasFloatRange {
		parts = append(parts, fmt.Sprintf("compressed [%s, %s] @ %s", formatFloat(f.FMin), formatFloat(f.FMax), formatFloat(f.Resolution)))
	}
	if f.Type.Kind == ir.TFixed {
		sign := "fixed"
		if !f.Type.Signed {
			sign = "ufixed"
		}
		parts = append(parts, fmt.Sprintf("%s(%d, %d), raw scaled value", sign, f.Type.IntBits, f.Type.FracBits))
	}
	return parts
}

// defaultSpelling is a field's specified default as the comment shows it.
func defaultSpelling(f *ir.Field) string {
	switch {
	case f.Type.Kind == ir.TString || f.Type.Kind == ir.TBytes:
		return strconv.Quote(string(f.DefBytes))
	case f.DefExpr != nil:
		return ir.RenderExpr(f.DefExpr)
	}
	return "set"
}

// storage maps a field type to its C# storage (SPEC §6.1 C# column).
func (g *gen) storage(t ir.FieldType) string {
	switch t.Kind {
	case ir.TInt, ir.TFixed:
		if t.Width == 128 {
			if t.Signed {
				return "Int128Value"
			}
			return "UInt128Value"
		}
		if t.Signed {
			return csInt(t.Width)
		}
		return csUint(t.Width)
	case ir.TBits:
		if t.Width <= 32 {
			return "uint"
		}
		return "ulong"
	case ir.TBool:
		return "bool"
	case ir.TFloat32:
		return "float"
	case ir.TFloat64:
		return "double"
	case ir.TNamed:
		return t.Name
	}
	panic(fmt.Sprintf("unity: no storage for field kind %d", t.Kind))
}

// ---- literals ----

func storageName(s string) string {
	switch s {
	case "int8":
		return "sbyte"
	case "int16":
		return "short"
	case "int32":
		return "int"
	case "int64":
		return "long"
	case "uint8":
		return "byte"
	case "uint16":
		return "ushort"
	case "uint32":
		return "uint"
	case "uint64":
		return "ulong"
	}
	panic("unity: unknown const storage " + s)
}

func csInt(width int) string {
	switch width {
	case 8:
		return "sbyte"
	case 16:
		return "short"
	case 32:
		return "int"
	}
	return "long"
}

func csUint(width int) string {
	switch width {
	case 8:
		return "byte"
	case 16:
		return "ushort"
	case 32:
		return "uint"
	}
	return "ulong"
}

func formatFloat(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eEN") {
		s += ".0"
	}
	return s
}

func formatFloat32(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 32)
	if !strings.ContainsAny(s, ".eEN") {
		s += ".0"
	}
	return s + "f"
}

var (
	maxUint64 = new(big.Int).SetUint64(math.MaxUint64)
	minInt64  = big.NewInt(math.MinInt64)
	maxInt64  = big.NewInt(math.MaxInt64)
)

// lit128 renders a 128-bit value: inside long (or ulong, unsigned) it rides
// the pair's implicit conversion, wider values compose the two 64-bit lanes.
func lit128(v *big.Int, signed bool) string {
	if signed && v.Cmp(minInt64) >= 0 && v.Cmp(maxInt64) <= 0 {
		return v.String() + "L"
	}
	if !signed && v.Sign() >= 0 && v.Cmp(maxUint64) <= 0 {
		return v.String() + "UL"
	}
	u := new(big.Int).Set(v)
	if u.Sign() < 0 {
		u.Add(u, new(big.Int).Lsh(big.NewInt(1), 128))
	}
	hi := new(big.Int).Rsh(u, 64)
	lo := new(big.Int).And(u, maxUint64)
	typ := "UInt128Value"
	if signed {
		typ = "Int128Value"
	}
	return fmt.Sprintf("new %s(0x%xUL, 0x%xUL)", typ, hi, lo)
}

// flagsLiteral spells a mask as its named bits joined with |; an empty mask
// is 0, which converts to any enum.
func flagsLiteral(d *ir.Flags, mask *big.Int) string {
	if mask == nil || mask.Sign() == 0 {
		return "0"
	}
	rest := new(big.Int).Set(mask)
	var parts []string
	for i, v := range d.Variants {
		if rest.Bit(i) != 0 {
			parts = append(parts, d.Name+"."+v)
			rest.SetBit(rest, i, 0)
		}
	}
	if rest.Sign() != 0 {
		parts = append(parts, fmt.Sprintf("(%s)0x%sUL", d.Name, rest.Text(16)))
	}
	return strings.Join(parts, " | ")
}

// defaultValue renders a scalar field's specified default in its storage.
func (g *gen) defaultValue(f *ir.Field) string {
	switch {
	case f.Type.Kind == ir.TBool:
		return strconv.FormatBool(f.DefBool)
	case f.DefVariant != "":
		return f.Type.Name + "." + f.DefVariant
	case f.Type.Kind == ir.TNamed:
		if fl, ok := f.Type.Ref.(*ir.Flags); ok {
			return flagsLiteral(fl, f.DefInt)
		}
	case f.Type.Kind == ir.TFloat32:
		return formatFloat32(f.DefFloat)
	case f.Type.Kind == ir.TFloat64:
		return formatFloat(f.DefFloat)
	case f.Type.Width == 128:
		return lit128(f.DefInt, f.Type.Signed)
	}
	// a plain decimal: C# types the literal int, uint, long or ulong by value,
	// and the constant converts implicitly into storage the value fits
	return f.DefInt.String()
}

// hasDefaults reports whether a type's construction form differs from its
// zero form: a specified default or a born count anywhere in its by-value
// closure (unions are constructed at None either way).
func hasDefaults(d *ir.Struct) bool {
	seen := map[*ir.Struct]bool{}
	var walk func(st *ir.Struct) bool
	walk = func(st *ir.Struct) bool {
		if seen[st] {
			return false
		}
		seen[st] = true
		for _, f := range st.Fields {
			if f.HasDefault || f.BornCount() > 0 {
				return true
			}
			if inner, ok := f.Type.Ref.(*ir.Struct); ok && f.Type.Kind == ir.TNamed && walk(inner) {
				return true
			}
		}
		return false
	}
	return walk(d)
}
