// pyModule is one schema file's module while it is being emitted. The
// declaration walk records the names it needs; assemble writes the header,
// the imports and the body once, so the output is deterministic.
type pyModule struct {
	u *ir.Unit
	f *ir.File

	body strings.Builder

	imports map[string]bool   // typing names
	schema  map[string]bool   // names imported from ._schema
	serial  map[string]bool   // names imported from ._schema.serialize
	sibling map[string]string // file base -> local alias

	surfaceOnly bool // a class-surface-only unit (tests of every field kind)
}

func (m *pyModule) need(name string)                  { m.imports[name] = true }
func (m *pyModule) needSchema(name string)            { m.schema[name] = true }
func (m *pyModule) needSerialize(name string)         { m.serial[name] = true }
func (m *pyModule) printf(format string, args ...any) { fmt.Fprintf(&m.body, format, args...) }
func (m *pyModule) line(format string, args ...any)   { m.printf(format+"\n", args...) }
func (m *pyModule) addSibling(base string) string {
	if alias, ok := m.sibling[base]; ok {
		return alias
	}
	alias := HelperPrefix + base
	m.sibling[base] = alias
	return alias
}

// typeRef names a declaration from this module: bare in its own file, and
// through its module alias elsewhere.
func (m *pyModule) typeRef(name string) string {
	base, ok := m.u.DeclFile[name]
	if !ok || base == m.f.Base {
		return name
	}
	return m.addSibling(base) + "." + name
}

func (m *pyModule) assemble() string {
	var h strings.Builder
	fmt.Fprintf(&h, "# Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", m.f.Base)
	fmt.Fprintf(&h, "\"\"\"%s.schema.\"\"\"\n\n", m.f.Base)

	if len(m.imports) > 0 {
		h.WriteString("from typing import ")
		h.WriteString(strings.Join(sortedKeys(m.imports), ", "))
		h.WriteString("\n\n")
	}
	if len(m.sibling) > 0 {
		bases := make([]string, 0, len(m.sibling))
		for b := range m.sibling {
			bases = append(bases, b)
		}
		sort.Strings(bases)
		for _, b := range bases {
			fmt.Fprintf(&h, "from . import %s as %s\n", b, m.sibling[b])
		}
		h.WriteString("\n")
	}
	if len(m.schema) > 0 {
		h.WriteString("from ._schema import ")
		h.WriteString(strings.Join(sortedKeys(m.schema), ", "))
		h.WriteString("\n")
	}
	if len(m.serial) > 0 {
		h.WriteString("from ._schema.serialize import ")
		h.WriteString(strings.Join(sortedKeys(m.serial), ", "))
		h.WriteString("\n")
	}
	if len(m.schema) > 0 || len(m.serial) > 0 {
		h.WriteString("\n")
	}
	h.WriteString(m.body.String())
	return h.String()
}

func sortedKeys(set map[string]bool) []string {
	out := make([]string, 0, len(set))
	for k := range set {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

func intLiteral(v *big.Int) string {
	if v == nil {
		return "0"
	}
	return v.String()
}

func floatLiteral(v float64) string {
	switch {
	case math.IsNaN(v):
		return "float(\"nan\")"
	case math.IsInf(v, 1):
		return "float(\"inf\")"
	case math.IsInf(v, -1):
		return "-float(\"inf\")"
	case v == 0 && math.Signbit(v):
		return "-0.0"
	}
	s := strconv.FormatFloat(v, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

func float32Value(v float64) float64 { return float64(float32(v)) }

func stringLiteral(s string) string { return strconv.Quote(s) }

func bytesLiteral(b []byte) string {
	var out strings.Builder
	out.WriteString("b\"")
	for _, c := range b {
		switch {
		case c == '\\' || c == '"':
			out.WriteByte('\\')
			out.WriteByte(c)
		case c >= 0x20 && c < 0x7f:
			out.WriteByte(c)
		default:
			fmt.Fprintf(&out, "\\x%02x", c)
		}
	}
	out.WriteByte('"')
	return out.String()
}

// zeroExpr is the SPEC §5 ZERO form of a field's storage: all-zero, never a
// declared default.
func (m *pyModule) zeroExpr(f *ir.Field) string {
	if f.Array != ir.ArrayNone {
		return "[]"
	}
	switch f.Type.Kind {
	case ir.TBool:
		return "False"
	case ir.TFloat32, ir.TFloat64:
		return "0.0"
	case ir.TString:
		return "\"\""
	case ir.TBytes:
		return "b\"\""
	case ir.TNamed:
		switch f.Type.Ref.(type) {
		case *ir.Struct:
			return m.typeRef(f.Type.Name) + "()"
		case *ir.Union:
			return m.typeRef(f.Type.Name) + "()"
		}
		return "0"
	}
	return "0"
}

// defaultExpr is a field's declared default, or its zero form (SPEC §5).
func (m *pyModule) defaultExpr(f *ir.Field) string {
	if !f.HasDefault {
		return m.zeroExpr(f)
	}
	switch {
	case f.Type.Kind == ir.TBool:
		if f.DefBool {
			return "True"
		}
		return "False"
	case f.DefVariant != "":
		return m.typeRef(f.Type.Name) + "." + f.DefVariant
	case f.Type.Kind == ir.TFloat32:
		return floatLiteral(float32Value(f.DefFloat))
	case f.Type.Kind == ir.TFloat64:
		return floatLiteral(f.DefFloat)
	case f.Type.Kind == ir.TString:
		return stringLiteral(string(f.DefBytes))
	case f.Type.Kind == ir.TBytes:
		return bytesLiteral(f.DefBytes)
	case f.DefInt != nil:
		return intLiteral(f.DefInt)
	}
	return m.zeroExpr(f)
}
