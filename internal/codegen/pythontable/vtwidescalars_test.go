// wideVtSchema is the wide-scalars construct the Lua leg proves
// (internal/codegen/luatable/vtcells_test.go, "wide_ints"): every storage width
// of the fixed-point family, both signednesses, the 128-bit integers at their
// extremes and a bits field beside them.
const wideVtSchema = `package wide
table W
{
    a int64
    b uint64
    c int128 | min = -170141183460469231731687303715884105728, max = 170141183460469231731687303715884105727
    d uint128
    e fixed(48, 16) | min = -100000, max = 100000
    f ufixed(8, 8) | min = 0, max = 200
    g fixed(60, 4) | min = -1000000000000, max = 1000000000000
    h bits(40)
}
`

// wideVtDefaults exercises the raw value a wide field is born at: a fixed
// default in whole units is held raw, an int128 default keeps its sign, and a
// uint128 default may exceed 64 bits.
const wideVtDefaults = `package wide
table Defaults
{
    a fixed(16, 16) = 0.5 | min = -8, max = 8
    b fixed(16, 16) = 1.0 | min = -8, max = 8
    c ufixed(8, 8) = 10 | min = 0, max = 200
    d int128 = -250 | min = -5000000000, max = 5000000000
    e uint128 = 18446744073709551616
}
`

// wideVtCases are the raw scaled values (units × 2^F) and the 128-bit extremes.
var wideVtCases = []struct {
	name string
	text string
}{
	{"zero", `{"a":0,"b":0,"c":0,"d":0,"e":0,"f":0,"g":0,"h":0}`},
	{"extremes", `{"a":-9007199254740993,"b":18446744073709551615,"c":-170141183460469231731687303715884105728,"d":340282366920938463463374607431768211455,"e":-12345.5,"f":3.25,"g":-1.5,"h":1099511627775}`},
	{"ones", `{"a":1,"b":1,"c":1,"d":1,"e":0.00390625,"f":0.00390625,"g":0.0625,"h":1}`},
}

// wideVtGoWire is the Go engine's form-1 wire of the JSON text at root.
func wideVtGoWire(t *testing.T, u *ir.Unit, root, text string) []byte {
	t.Helper()
	model := tabletext.NewModel(u)
	st := u.Tables[root]
	if st == nil {
		t.Fatalf("no table %s", root)
	}
	inst := model.New(st)
	var report tabletext.Report
	if !model.Read(inst, []byte(text), &report) || report.Refused || report.Unknown > 0 {
		t.Fatalf("the Go engine does not read the JSON cleanly: %+v", report)
	}
	wire, err := tablewire.Encode(model, inst)
	if err != nil {
		t.Fatalf("the Go engine does not write it: %v", err)
	}
	return wire
}

// wideVtProbe reads the wire input and answers "<len>:<same|diff>:<measure>",
// or "refused <reason>". It never catches a value it did not read whole.
const wideVtProbe = `import wide
data = open("wire", "rb").read()
try:
    value = wide.W.load(data)
except Exception as err:
    print("refused", getattr(err, "reason", type(err).__name__))
else:
    saved = value.save()
    print("%d:%s:%d" % (len(saved), "same" if saved == data else "diff", value.measure()))
`

// wideVtDefaultsProbe checks a default value against the Go engine's default
// wire: the Python object is born at the same raw value and saves elided.
const wideVtDefaultsProbe = `import wide
data = open("wire", "rb").read()
value = wide.Defaults()
saved = value.save()
print("defaults", value.a, value.b, value.c, value.d, value.e)
print("wire", "same" if saved == data else "diff")
print("roundtrip", wide.Defaults.load(saved) == value)
`

// wideVtExec runs the probe under one pinned interpreter and hands back both
// streams; a control reads the failure rather than the test helper turning it
// into a fatal.
func wideVtExec(t *testing.T, floor bool, dir, main string, inputs map[string][]byte) (string, string, error) {
	t.Helper()
	python := pyrun.Interpreter(t)
	if floor {
		python = pyrun.Floor(t)
	}
	return pyrun.Try(t, python, dir, main, inputs)
}

// wideVtRun generates u (its files edited by mutate when set), runs the probe
// over wire at root under both pins and answers its line. The two pins must
// agree.
func wideVtRun(t *testing.T, u *ir.Unit, root string, wire []byte, probe string, mutate func(*testing.T, map[string][]byte)) string {
	t.Helper()
	files, err := Generate(u)
	if err != nil {
		t.Fatalf("the table frame refuses the unit: %v", err)
	}
	if mutate != nil {
		mutate(t, files)
	}
	dir := t.TempDir()
	writeTree(t, dir, files)
	inputs := map[string][]byte{"main.py": []byte(pyrun.ImportPrelude + probe), "wire": wire}
	current, stderr, err := wideVtExec(t, false, dir, "main.py", inputs)
	if err != nil {
		t.Fatalf("under the current pin: %v\nstderr:\n%s\nstdout:\n%s", err, stderr, current)
	}
	floor, stderr, err := wideVtExec(t, true, dir, "main.py", inputs)
	if err != nil {
		t.Fatalf("under the floor pin: %v\nstderr:\n%s\nstdout:\n%s", err, stderr, floor)
	}
	if current != floor {
		t.Fatalf("the two pinned interpreters disagree:\ncurrent:\n%s\nfloor:\n%s", current, floor)
	}
	return strings.TrimSpace(current)
}

// wideVtManifest is the manifest's units, its instance and report rows, and
// reports.txt's verdicts.
func wideVtManifest(t *testing.T) (map[string][]string, map[string][]string, map[string]string) {
	t.Helper()
	repo := filepath.Join("..", "..", "..")
	manifest := filepath.Join(repo, "testdata", "conformance", "tables", "MANIFEST.txt")
	data, err := os.ReadFile(manifest)
	if err != nil {
		t.Fatal(err)
	}
	units := map[string][]string{}
	rows := map[string][]string{}
	for _, raw := range strings.Split(string(data), "\n") {
		line := strings.TrimSpace(raw)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		switch fields[0] {
		case "unit":
			units[fields[1]] = fields[2:]
		case "instance", "report":
			rows[fields[1]] = fields
		}
	}
	reports := map[string]string{}
	reportFile, err := os.ReadFile(filepath.Join(repo, "testdata", "conformance", "tables", "reports.txt"))
	if err != nil {
		t.Fatal(err)
	}
	for _, raw := range strings.Split(string(reportFile), "\n") {
		fields := strings.Fields(raw)
		if len(fields) >= 2 && !strings.HasPrefix(strings.TrimSpace(raw), "#") {
			reports[fields[0]] = fields[1]
		}
	}
	return units, rows, reports
}

// wideVtLoadUnit loads a manifest unit's schema paths.
func wideVtLoadUnit(t *testing.T, repo string, paths []string) *ir.Unit {
	t.Helper()
	var sources []check.SourceFile
	seen := map[string]bool{}
	for _, path := range paths {
		full := filepath.Join(repo, path)
		info, err := os.Stat(full)
		if err != nil {
			t.Fatal(err)
		}
		var files []string
		if info.IsDir() {
			files, err = filepath.Glob(filepath.Join(full, "*.schema"))
			if err != nil {
				t.Fatal(err)
			}
			sort.Strings(files)
		} else {
			files = []string{full}
		}
		for _, file := range files {
			name := filepath.Base(file)
			if seen[name] {
				t.Fatalf("the unit names %s twice", name)
			}
			seen[name] = true
			data, err := os.ReadFile(file)
			if err != nil {
				t.Fatal(err)
			}
			ast, perrs := parser.Parse(file, data)
			if len(perrs) > 0 {
				t.Fatalf("parse %s: %v", file, perrs[0])
			}
			sources = append(sources, check.SourceFile{
				Path: full, Name: name, Base: strings.TrimSuffix(name, ".schema"),
				Bytes: data, AST: ast,
			})
		}
	}
	u, cerrs := check.Unit(sources)
	if len(cerrs) > 0 {
		t.Fatalf("check: %v", cerrs[0])
	}
	return u
}

// wideVtCells are the manifest rows whose unit declares a wide kind, the same
