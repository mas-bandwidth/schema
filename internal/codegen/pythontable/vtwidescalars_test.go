// THE WIDE-SCALARS CELL of the Python table leg (ROADMAP.md, Variable tables;
// docs/SPEC-TABLES.md §3 kinds 18-29; docs/PORT-PYTHON.md, THE TABLE FRAME):
// fixed(I, F), ufixed(I, F), int128 and uint128 read from a canonical wire and
// written back byte for byte, under both pinned interpreters, with a negative
// control planted in a copy of the generated runtime.
//
// The manifest's wide units also carry constructs outside this cut — the
// scalars unit reaches a packet `type` by value, Scalars2 does too, and
// widelist is an unbounded array — so the table frame refuses those units or
// reads by name until their cards land. This file holds those rows to the
// refusal the frame owes them, and proves the wide scalars themselves over a
// construct the frame carries whole, generated by the same emitter.

