// luaVTCells "wide-scalars").
var wideVtCells = []string{
	"scalars_full",
	"scalars_default",
	"scalars_edges",
	"scalars_full_as_2",
	"scalars_edges_as_2",
	"field_scalar_widen",
}

// TestPythonVtWide holds the wide-scalars construct to the one read on
// read-then-write under both pinned interpreters, its ordinary module, and
// every manifest row of the wide row.
func TestPythonVtWide(t *testing.T) {
	t.Parallel()
	t.Run("construct", func(t *testing.T) {
		t.Parallel()
		u := loadUnit(t, wideVtSchema)
		for _, tc := range wideVtCases {
			t.Run(tc.name, func(t *testing.T) {
				t.Parallel()
				wire := wideVtGoWire(t, u, "W", tc.text)
				got := wideVtRun(t, u, "W", wire, wideVtProbe, nil)
				want := fmt.Sprintf("%d:same:%d", len(wire), len(wire))
				if got != want {
					t.Fatalf("the Python save is not the Go wire: got %q, want %q (wire %x)", got, want, wire)
				}
			})
		}
	})

	t.Run("defaults", func(t *testing.T) {
		t.Parallel()
		u := loadUnit(t, wideVtDefaults)
		model := tabletext.NewModel(u)
		st := u.Tables["Defaults"]
		inst := model.New(st)
		wire, err := tablewire.Encode(model, inst)
		if err != nil {
			t.Fatalf("the Go engine does not write the defaults: %v", err)
		}
		got := wideVtRun(t, u, "Defaults", wire, wideVtDefaultsProbe, nil)
		want := "defaults 32768 65536 2560 -250 18446744073709551616\nwire same\nroundtrip True"
		if got != want {
			t.Fatalf("the wide defaults differ:\ngot:\n%s\nwant:\n%s", got, want)
		}
	})

	t.Run("module", func(t *testing.T) {
		t.Parallel()
		u := loadUnit(t, wideVtSchema)
		files, err := Generate(u)
		if err != nil {
			t.Fatal(err)
		}
		if _, ok := files["wide/_schema/kind_wide.py"]; !ok {
			t.Fatalf("the generated runtime has no _schema/kind_wide.py: the wide scalars are their own module")
		}
		module := string(files["wide/Core.py"])
		if !strings.Contains(module, `codec="wide"`) {
			t.Fatalf("the wide fields do not ride the wide dispatch entry:\n%s", module)
		}
		probe := pyrun.ImportPrelude + `import wide
from wide._schema import kinds
fields = {field.name: field.codec for field in wide.W.descriptor.fields}
print("codecs", fields["c"], fields["d"], fields["e"], fields["f"], fields["g"], fields["a"], fields["h"])
print("registered", "wide" in kinds._REGISTRY)
`
		dir := t.TempDir()
		writeTree(t, dir, files)
		lines := strings.TrimSpace(wideVtRun(t, u, "W", nil, probe, nil))
		for _, want := range []string{"codecs wide wide wide wide wide int int", "registered True"} {
			if !strings.Contains(lines, want) {
				t.Errorf("the module probe lacks %q:\n%s", want, lines)
			}
		}
		if out, err := pyrun.Analyze(t, dir, "wide"); err != nil {
			t.Fatalf("mypy --strict over the wide package:\n%s", out)
		}
		if out, err := pyrun.Analyze(t, dir, "wide/_schema"); err != nil {
			t.Fatalf("mypy --strict over the runtime:\n%s", out)
		}
	})

	t.Run("manifest", func(t *testing.T) {
		t.Parallel()
		repo := filepath.Join("..", "..", "..")
		units, rows, reports := wideVtManifest(t)
		for _, name := range wideVtCells {
			row, ok := rows[name]
			if !ok {
				t.Fatalf("%s is not a manifest instance or report row", name)
			}
			kind, unit, root, wirePath := row[0], row[2], row[3], row[4]
			t.Run(name, func(t *testing.T) {
				t.Parallel()
				u := wideVtLoadUnit(t, repo, units[unit])
				if _, err := Generate(u); err != nil {
					// The wide unit also carries a construct outside this cut.
					// The frame must refuse it by name, never emit a second wire.
					if !strings.Contains(err.Error(), "python") && !strings.Contains(err.Error(), "does not carry") {
						t.Fatalf("%s is refused without a named reason: %v", unit, err)
					}
					t.Logf("%s: the frame refuses the unit by name: %v", name, err)
					return
				}
				wire, err := os.ReadFile(filepath.Join(repo, wirePath))
				if err != nil {
					t.Fatal(err)
				}
				got := wideVtRun(t, u, root, wire, wideVtProbe, nil)
				if kind == "report" {
					want := "read"
					if got == "refused" || strings.HasPrefix(got, "refused ") {
						want = "refused"
					}
					if want != reports[name] {
						t.Fatalf("%s: Python %s, the engine %s", name, want, reports[name])
					}
					return
				}
				if strings.HasPrefix(got, "refused") {
					return
				}
				parts := strings.SplitN(got, ":", 3)
				if len(parts) != 3 || parts[1] != "same" || parts[0] != parts[2] {
					t.Fatalf("%s: the save is not the wire and is not a refusal: %s", name, got)
				}
				t.Logf("%s: round-trips %s", name, got)
			})
		}
	})
}

// TestPythonVtWideNegativeControl plants a defect in a COPY of the generated
// wide module and requires the wide construct to go red: a gate is only
// watching the codec if a broken codec fails it.
func TestPythonVtWideNegativeControl(t *testing.T) {
	t.Parallel()
	u := loadUnit(t, wideVtSchema)
	wire := wideVtGoWire(t, u, "W", wideVtCases[1].text)
	want := fmt.Sprintf("%d:same:%d", len(wire), len(wire))
	plant := func(from, to string) func(*testing.T, map[string][]byte) {
		return func(t *testing.T, files map[string][]byte) {
			t.Helper()
			const path = "wide/_schema/kind_wide.py"
			src := string(files[path])
			if strings.Count(src, from) != 1 {
				t.Fatalf("%s carries %q %d times, want 1: the control would be vacuous", path, from, strings.Count(src, from))
			}
			files[path] = []byte(strings.Replace(src, from, to, 1))
		}
	}
	for _, ctl := range []struct {
		name   string
		mutate func(*testing.T, map[string][]byte)
	}{
		{"read-signedness", plant("return fd.lo < 0", "return False")},
		{"write-byte-order", plant(`w.raw(int(value).to_bytes(width, "little", signed=neg))`, `w.raw(int(value).to_bytes(width, "little", signed=neg)[::-1])`)},
	} {
		t.Run(ctl.name, func(t *testing.T) {
			t.Parallel()
			files, err := Generate(u)
			if err != nil {
				t.Fatal(err)
			}
			ctl.mutate(t, files)
			dir := t.TempDir()
			writeTree(t, dir, files)
			inputs := map[string][]byte{"main.py": []byte(pyrun.ImportPrelude + wideVtProbe), "wire": wire}
			for _, floor := range []bool{false, true} {
				out, stderr, err := wideVtExec(t, floor, dir, "main.py", inputs)
				if err == nil && strings.TrimSpace(out) == want {
					t.Fatalf("NEGATIVE CONTROL FAILED: %s left the wide construct green at %q", ctl.name, want)
				}
				t.Logf("%s went red: stdout=%q stderr=%q err=%v", ctl.name, strings.TrimSpace(out), strings.TrimSpace(stderr), err)
			}
		})
	}
}
