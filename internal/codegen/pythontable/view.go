func reflectionElemSize(u *ir.Unit, f *ir.Field) int64 {
	switch {
	case f.IsMap():
		return ir.RecordLayout(u, f.MapEntry).Size
	case f.Array != ir.ArrayNone:
		size, _ := ir.ListElementLayout(u, f)
		return size
	case f.Type.Pointer:
		return 8
	case f.Type.Kind == ir.TBytes || f.Type.Kind == ir.TString:
		return 1
	default:
		size, _ := ir.ListElementLayout(u, f)
		return size
	}
}

// viewSource emits the optional unit view beside the table runtime. It owns no
// codecs; all declaration data comes from the checked unit.
func viewSource(u *ir.Unit) string {
	var b strings.Builder
	b.WriteString(`# Code generated by the schema compiler. DO NOT EDIT.
from __future__ import annotations
from .descriptor import ArmDesc, FieldDesc, TableDesc, UnionDesc, by_name, _union_by_name
from .view import UnitViewInfo, ViewConstant, ViewType, ViewVariant, ViewVocabulary

def _arm_field(name: str, index: int, fallback: FieldDesc) -> FieldDesc:
    cls = _union_by_name(name)
    if cls is None:
        return fallback
    field: FieldDesc | None = cls.descriptor.arms[index].field
    return fallback if field is None else field

`)
	types, tables := viewSortedStructs(u)
	reached := ir.TableClosure(u)
	vocabulary := ir.TableClosureVocabulary(u)
	variable := ir.VariableTables(u)
	b.WriteString("_descriptors: dict[str, TableDesc] = {}\n")
	records := append(slices.Clone(types), tables...)
	for _, name := range slices.Sorted(maps.Keys(u.Tables)) {
		st := u.Tables[name]
		if st.IsMapEntry() {
			records = append(records, st)
		}
	}
	for _, st := range records {
		wire := st.IsTable || reached[st.Name]
		typeID := uint64(0)
		if wire {
			typeID = ir.TableWireId(st.WireName())
		}
		layout := ir.RecordLayout(u, st)
		fmt.Fprintf(&b, "_descriptors[%q] = TableDesc(name=%q, type_id=%d, variable=%s, doc=%s, tags=%s, table=%s, size=%d, align=%d, region_align=%d, %s, fields=(\n", st.Name, st.Name, typeID, pyBool(variable[st.Name]), viewQuote(st.Doc), pythonTags(st.Tags), pyBool(st.IsTable), layout.Size, layout.Align, ir.TableRegionAlign(u), cookTableColumns(u, st, layout))
		for i, f := range st.Fields {
			key := "None"
			fieldID := uint64(0)
			if wire {
				key = viewQuote(ir.TableFieldJsonKey(f))
				fieldID = ir.TableFieldWireId(f)
			}
			offset := int64(0)
			if fl := layout.FieldByName(f.Name); fl != nil {
				offset = fl.Offset
			}
			lo, hi := intRange(f)
			fmt.Fprintf(&b, "    FieldDesc(name=%q, field_id=%d, kind=%d, codec=%q, ordinal=%d, lo=%s, hi=%s, target=%q, map_entry=%q, pointer=%s, optional=%s, array=%s, bound=%d, size=%d, key_enum=%q, array_kind=%d, array_min=%d, elem_kind=%d, elem_codec=%q, doc=%s, tags=%s, json_key=%s, type_name=%q, at=%d, pieces=%s, elem_size=%d, elem_align=%d, variant_ids=%s, deprecated=%s, keys=%s, default=%s, inner=%q, %s, f32=%s, fmin=%s, fmax=%s, float_range=%s, %s),\n", f.Name, fieldID, ir.TableWireFieldKind(f), codecOf(f), i, lo, hi, targetName(f), reflectionMapEntry(f), pyBool(f.Type.Pointer), pyBool(f.Type.Optional), pyBool(f.Array != ir.ArrayNone), f.ArrayBound, fieldSize(f), f.KeyEnum, f.Array, f.ArrayMin, ir.TableWireElemKind(f), arrayElemCodec(f), viewQuote(f.Doc), pythonTags(f.Tags), key, ir.TableTypeSpelling(f), offset, reflectionPieces(u, f, offset), reflectionElemSize(u, f), reflectionElemAlign(u, f), viewVariantIds(f, viewVocabularyReached(f, vocabulary)), viewDeprecated(f), viewKeys(f, vocabulary[f.KeyEnum]), defaultFor(f, codecOf(f)), innerCodecOf(f), reflectionVocabularyColumns(f), pyBool(f.Type.Kind == ir.TFloat32), floatBound(f, f.FMin), floatBound(f, f.FMax), pyBool(compressedFloat(f)), reflectionColumns(u, f, offset))
		}
		b.WriteString("))\n")
		if wire {
			fmt.Fprintf(&b, "_cls = by_name(%q)\nif _cls is not None:\n    _descriptors[%q] = _cls.descriptor\n", st.Name, st.Name)
		}
	}
	b.WriteString("for _descriptor in _descriptors.values():\n    for _field in _descriptor.fields:\n        _field.target_desc = _descriptors.get(_field.map_entry or _field.target)\n        if _field.element is not None:\n            _field.element.target_desc = _field.target_desc\n        if _field.elem is not None:\n            _field.elem.target_desc = _field.target_desc\n")
	emitRows := func(name string, rows []*ir.Struct) {
		fmt.Fprintf(&b, "_%s: tuple[ViewType, ...] = (\n", name)
		for _, st := range rows {
			fmt.Fprintf(&b, "    ViewType(%q, %q, %s, _descriptors[%q], %s, %s),\n", st.Name, viewFileName(u, st.Name), pyBool(st.IsTable), st.Name, viewQuote(st.Doc), pythonTags(st.Tags))
		}
		b.WriteString(")\n")
	}
	emitRows("types", types)
	emitRows("tables", tables)
	b.WriteString("_constants: tuple[ViewConstant, ...] = (\n")
	for _, name := range slices.Sorted(maps.Keys(u.Consts)) {
		c := u.Consts[name]
		v := int64(0)
		if c.Int != nil {
			if c.Int.IsInt64() {
				v = c.Int.Int64()
			} else {
				v = int64(c.Int.Uint64())
			}
		}
		fv := "0.0"
		if c.IsFloat {
			fv = strconv.FormatFloat(c.Float, 'g', -1, 64)
			if !strings.ContainsAny(fv, ".eE") {
				fv += ".0"
			}
		}
		fmt.Fprintf(&b, "    ViewConstant(%q, %q, %q, %s, %d, %s, %s, %s),\n", c.Name, viewFileName(u, name), c.Storage, pyBool(c.IsFloat), v, fv, viewQuote(c.Doc), pythonTags(c.Tags))
	}
	b.WriteString(")\n_enums: tuple[ViewVocabulary, ...] = (\n")
	for _, name := range slices.Sorted(maps.Keys(u.Enums)) {
		e := u.Enums[name]
		fmt.Fprintf(&b, "    ViewVocabulary(%q, %q, %d, %d, 0, (\n", name, viewFileName(u, name), e.Max, e.StorageBits)
		b.WriteString("        ViewVariant(0, \"None\", 0, None, None, None, \"\", ()),\n")
		for i, v := range e.Variants {
			id := uint64(0)
			if vocabulary[name] {
				id = ir.TableWireId(e.VariantWireName(i))
			}
			fmt.Fprintf(&b, "        ViewVariant(%d, %q, %d, None, None, None, %s, %s),\n", i+1, v, id, viewQuote(e.VariantDocs[i]), pythonTags(e.VariantTags[i]))
		}
		fmt.Fprintf(&b, "    ), %s, %s),\n", viewQuote(e.Doc), pythonTags(e.Tags))
	}
	b.WriteString(")\n_flags: tuple[ViewVocabulary, ...] = (\n")
	for _, name := range slices.Sorted(maps.Keys(u.Flags)) {
		f := u.Flags[name]
		bits := 64
		for _, width := range []int{8, 16, 32, 64} {
			if f.WireBits <= width {
				bits = width
				break
			}
		}
		fmt.Fprintf(&b, "    ViewVocabulary(%q, %q, %d, %d, 0, (\n", name, viewFileName(u, name), len(f.Variants)-1, bits)
		for i, v := range f.Variants {
			fmt.Fprintf(&b, "        ViewVariant(%d, %q, 0, None, None, None, %s, %s),\n", i, v, viewQuote(f.VariantDocs[i]), pythonTags(f.VariantTags[i]))
		}
		fmt.Fprintf(&b, "    ), %s, %s),\n", viewQuote(f.Doc), pythonTags(f.Tags))
	}
	b.WriteString(")\n_unions: tuple[ViewVocabulary, ...] = (\n")
	unions := map[string]*ir.Union{}
	maps.Copy(unions, u.Unions)
	maps.Copy(unions, u.TableUnions)
	for _, name := range slices.Sorted(maps.Keys(unions)) {
		un := unions[name]
		offset := int64(0)
		if _, ok := u.TableUnions[name]; ok {
			_, _, _, offset = ir.UnionLayout(u, un)
		}
		fmt.Fprintf(&b, "    ViewVocabulary(%q, %q, %d, %d, %d, (\n", name, viewFileName(u, name), un.Max, un.StorageBits, offset)
		b.WriteString("        ViewVariant(0, \"None\", 0, None, None, None, \"\", ()),\n")
		for i, arm := range un.Variants {
			id := uint64(0)
			if vocabulary[name] {
				id = ir.TableWireId(arm.WireName())
			}
			payloadName, payload, field := "None", "None", "None"
			if !arm.Void() {
				payloadName = viewQuote(ir.FieldTypeSpelling(arm.F))
				if arm.Body() {
					payload = "_descriptors[" + viewQuote(arm.Type) + "]"
				} else {
					field = fmt.Sprintf("_arm_field(%q, %d, %s)", name, i, viewArmField(u, un, arm, i+1, vocabulary[name], vocabulary))
				}
			}
			fmt.Fprintf(&b, "        ViewVariant(%d, %q, %d, %s, %s, %s, %s, %s),\n", i+1, arm.Name, id, payloadName, payload, field, viewQuote(arm.Doc), pythonTags(arm.Tags))
		}
		fmt.Fprintf(&b, "    ), %s, %s),\n", viewQuote(un.Doc), pythonTags(un.Tags))
	}
	b.WriteString(")\n_unions_by_name = {v.name: v for v in _unions}\n_union_descriptors: dict[str, UnionDesc] = {}\n")
	for _, name := range slices.Sorted(maps.Keys(unions)) {
		un := unions[name]
		size, _, tagSize, armOffset := ir.UnionLayout(u, un)
		fmt.Fprintf(&b, "_v = _unions_by_name[%q]\n_cls = _union_by_name(%q)\nif _cls is None:\n    _union_descriptors[%q] = UnionDesc(name=%q, size=%d, tag_size=%d, arm_offset=%d, doc=%s, tags=%s, arms=(\n", name, name, name, name, size, tagSize, armOffset, viewQuote(un.Doc), pythonTags(un.Tags))
		for i, arm := range un.Variants {
			id := uint64(0)
			if vocabulary[name] {
				id = ir.TableWireId(arm.WireName())
			}
			kind := ir.TableKindNoPayload
			target := ""
			pointer := false
			if arm.F != nil {
				kind = ir.TableWireFieldKind(arm.F)
				target = targetName(arm.F)
				pointer = arm.F.Type.Pointer
			}
			armSize, _ := ir.ArmLayout(u, arm)
			fmt.Fprintf(&b, "        ArmDesc(name=%q, tag=%d, arm_id=%d, kind=%d, target=%q, pointer=%s, field=_v.variants[%d].field, size=%d, doc=%s, tags=%s),\n", arm.Name, i+1, id, kind, target, pyBool(pointer), i+1, armSize, viewQuote(arm.Doc), pythonTags(arm.Tags))
		}
		fmt.Fprintf(&b, "    ))\nelse:\n    _union_descriptors[%q] = _cls.descriptor\n", name)
	}
	b.WriteString("for _union in _union_descriptors.values():\n    for _arm in _union.arms:\n        _arm.target_desc = _descriptors.get(_arm.target)\n        if _arm.field is not None:\n            _arm.field.target_desc = _descriptors.get(_arm.field.map_entry or _arm.field.target)\n            _arm.field.union_desc = _union_descriptors.get(_arm.field.target)\nfor _descriptor in _descriptors.values():\n    for _field in _descriptor.fields:\n        _field.union_desc = _union_descriptors.get(_field.target)\n        if _field.element is not None:\n            _field.element.union_desc = _field.union_desc\n        if _field.elem is not None:\n            _field.elem.union_desc = _field.union_desc\n")
	fmt.Fprintf(&b, "_unit = UnitViewInfo(%q, %d, _types, _tables, _constants, _enums, _flags, _unions)\n\ndef UnitView() -> UnitViewInfo:\n    return _unit\n", u.Package, u.ProtocolId)
	return b.String()
}

func viewFileName(u *ir.Unit, name string) string {
	if base, ok := u.DeclFile[name]; ok {
		return base + ".schema"
	}
	return ""
}

func viewQuote(s string) string { return strconv.Quote(s) }

func viewSortedStructs(u *ir.Unit) ([]*ir.Struct, []*ir.Struct) {
	var types, tables []*ir.Struct
	for _, f := range u.Files {
		for _, d := range f.Decls {
			if st, ok := d.(*ir.Struct); ok && !st.IsTable {
				types = append(types, st)
			}
		}
		for _, st := range f.Tables {
			if st.MapEntryOf == "" {
				tables = append(tables, st)
			}
		}
	}
	slices.SortFunc(types, func(a, b *ir.Struct) int { return strings.Compare(a.Name, b.Name) })
	slices.SortFunc(tables, func(a, b *ir.Struct) int { return strings.Compare(a.Name, b.Name) })
	return types, tables
}

// AddView places the unit registry beside the generated runtime and exports its
// entry point from the package. A schema declaration cannot replace that entry.
func AddView(u *ir.Unit, out map[string][]byte) error {
	if _, exists := u.DeclFile["UnitView"]; exists {
		return fmt.Errorf("python: declaration UnitView conflicts with the unit registry entry point")
	}
	for _, f := range u.Files {
		if f.Base == "UnitView" {
			return fmt.Errorf("python: schema file UnitView conflicts with the unit registry entry point")
		}
	}
	runtime, err := Runtime()
	if err != nil {
		return err
	}
	for _, name := range []string{"descriptor.py", "view.py"} {
		dest := path.Join(u.Package, RuntimeDir, name)
		if _, ok := out[dest]; !ok {
			out[dest] = runtime[path.Join(RuntimeDir, name)]
		}
	}
	out[path.Join(u.Package, RuntimeDir, "unit_view.py")] = []byte(viewSource(u))
	initFile := path.Join(u.Package, "__init__.py")
	out[initFile] = append(out[initFile], []byte("\nfrom ._schema.view import UnitViewInfo as _s_UnitViewInfo\n\ndef UnitView() -> \"_s_UnitViewInfo\":\n    from ._schema.unit_view import UnitView as _s_unit_view\n    return _s_unit_view()\n\n__all__.append(\"UnitView\")\n")...)
	return nil
}

func viewArmField(u *ir.Unit, un *ir.Union, arm ir.UnionVariant, ordinal int, wire bool, vocabulary map[string]bool) string {
	f := arm.F
	kind := ir.TableWireFieldKind(f)
	bound := f.ArrayBound
	id := uint64(0)
	key := "None"
	if wire {
		id = ir.TableWireId(arm.WireName())
		key = viewQuote(ir.TableFieldJsonKey(f))
	}
	offset := int64(0)
	lo, hi := intRange(f)
	return fmt.Sprintf("FieldDesc(name=%q, field_id=%d, kind=%d, codec=%q, ordinal=%d, bound=%d, lo=%s, hi=%s, target=%q, map_entry=%q, pointer=%s, optional=%s, array=%s, size=%d, key_enum=%q, array_kind=%d, array_min=%d, elem_kind=%d, elem_codec=%q, variant_ids=%s, deprecated=%s, keys=%s, doc=%s, tags=%s, json_key=%s, type_name=%q, at=%d, pieces=%s, elem_size=%d, elem_align=%d, %s, f32=%s, fmin=%s, fmax=%s, float_range=%s, %s)", arm.Name, id, kind, codecOf(f), ordinal, bound, lo, hi, targetName(f), reflectionMapEntry(f), pyBool(f.Type.Pointer), pyBool(f.Type.Optional), pyBool(f.Array != ir.ArrayNone), fieldSize(f), f.KeyEnum, f.Array, f.ArrayMin, ir.TableWireElemKind(f), arrayElemCodec(f), viewVariantIds(f, viewVocabularyReached(f, vocabulary)), viewDeprecated(f), viewKeys(f, vocabulary[f.KeyEnum]), viewQuote(arm.Doc), pythonTags(arm.Tags), key, ir.FieldTypeSpelling(f), offset, reflectionPieces(u, f, offset), reflectionElemSize(u, f), reflectionElemAlign(u, f), reflectionVocabularyColumns(f), pyBool(f.Type.Kind == ir.TFloat32), floatBound(f, f.FMin), floatBound(f, f.FMax), pyBool(compressedFloat(f)), reflectionColumns(u, f, offset))
}

func reflectionMapEntry(f *ir.Field) string {
	if f.MapEntry != nil {
		return f.MapEntry.Name
	}
	return ""
}

func reflectionColumns(u *ir.Unit, f *ir.Field, offset int64) string {
	counted := f.IsList() || f.IsMap() || f.Array == ir.ArrayCounted || (!f.Type.Pointer && !f.Type.TextUnbounded() && (f.Type.Kind == ir.TBytes || f.Type.Kind == ir.TString))
	bound := int64(0)
	switch {
	case f.IsList() || f.IsMap():
	case f.KeyEnumRef != nil:
		bound = f.KeyEnumRef.Max
	case f.Array != ir.ArrayNone:
		bound = f.ArrayBound
	case f.Type.Kind == ir.TBytes || f.Type.Kind == ir.TString:
		bound = f.Type.Size
	}
	countOffset, presentOffset := int64(-1), int64(-1)
	pieces := ir.FieldPieces(u, f, offset)
	if counted {
		if f.IsList() || f.IsMap() {
			countOffset = offset + 8
		} else if len(pieces) > 1 {
			countOffset = pieces[1].Offset
		}
	}
	if f.Type.Optional && len(pieces) > 1 {
		presentOffset = pieces[len(pieces)-1].Offset
	}
	wide := reflectionWide(f)
	return fmt.Sprintf("counted=%s, count_offset=%d, present_offset=%d, unbounded_container=%s, unbounded=%s, array_bound=%d, frac_bits=%d, wide=%s, guard=%q, required=%s, field_deprecated=%s", pyBool(counted), countOffset, presentOffset, pyBool(f.IsList() || f.IsMap()), pyBool(f.Type.TextUnbounded()), bound, f.Type.FracBits, wide, f.Guard, pyBool(f.Required), pyBool(f.Deprecated))
}

func viewVariantIds(f *ir.Field, wire bool) string {
	if _, ok := f.Type.Ref.(*ir.Enum); ok && wire {
		return variantIds(f)
	}
	var names []string
	switch v := f.Type.Ref.(type) {
	case *ir.Enum:
		for i := range v.Variants {
			names = append(names, v.VariantWireName(i))
		}
	case *ir.Union:
		for _, arm := range v.Variants {
			names = append(names, arm.WireName())
		}
	}
	var b strings.Builder
	b.WriteString("(")
	for _, name := range names {
		id := uint64(0)
		if wire {
			id = ir.TableWireId(name)
		}
		fmt.Fprintf(&b, "%d, ", id)
	}
	b.WriteString(")")
	return b.String()
}

func viewDeprecated(f *ir.Field) string {
	if s := deprecatedOrdinals(f); s != "" {
		return s
	}
	return "()"
}
func viewKeys(f *ir.Field, wire bool) string {
	if f.KeyEnumRef == nil {
		return "()"
	}
	var b strings.Builder
	b.WriteString("(")
	for i := int64(0); i < f.ArrayBound; i++ {
		id := uint64(0)
		if wire && int(i) < len(f.KeyEnumRef.Variants) {
			id = ir.TableWireId(f.KeyEnumRef.VariantWireName(int(i)))
		}
		fmt.Fprintf(&b, "%d, ", id)
	}
	b.WriteString(")")
	return b.String()
}

func viewVocabularyReached(f *ir.Field, reached map[string]bool) bool {
	switch v := f.Type.Ref.(type) {
	case *ir.Enum:
		return reached[v.Name]
	case *ir.Union:
		return reached[v.Name]
	}
	return false
}

func reflectionVocabularyColumns(f *ir.Field) string {
	var names []string
	kind := ""
	max := int64(0)
	switch v := f.Type.Ref.(type) {
	case *ir.Enum:
		kind = "enum"
		max = v.Max
		names = v.Variants
	case *ir.Flags:
		kind = "flags"
		max = int64(len(v.Variants) - 1)
		names = v.Variants
	case *ir.Union:
		kind = "union"
		max = v.Max
		for _, arm := range v.Variants {
			names = append(names, arm.Name)
		}
	}
	var keys []string
	if f.KeyEnumRef != nil {
		for i := int64(0); i < f.ArrayBound; i++ {
			name := ""
			if int(i) < len(f.KeyEnumRef.Variants) {
				name = f.KeyEnumRef.Variants[i]
			}
			keys = append(keys, name)
		}
	}
	return fmt.Sprintf("variant_names=%s, key_names=%s, vocabulary_kind=%q, enum_max=%d", pythonTags(names), pythonTags(keys), kind, max)
}

func reflectionPieces(u *ir.Unit, f *ir.Field, offset int64) string {
	var b strings.Builder
	b.WriteString("(")
	for _, p := range ir.FieldPieces(u, f, offset) {
		fmt.Fprintf(&b, "(%d, %d), ", p.Offset, p.Size)
	}
	b.WriteString(")")
	return b.String()
}
func reflectionElemAlign(u *ir.Unit, f *ir.Field) int64 {
	if f.IsMap() {
		return ir.RecordLayout(u, f.MapEntry).Align
	}
	if f.Type.Pointer && f.Array == ir.ArrayNone {
		return 8
	}
	if f.Type.Kind == ir.TString || f.Type.Kind == ir.TBytes {
		return 1
	}
	_, align := ir.ListElementLayout(u, f)
	return align
}
func cookTableColumns(u *ir.Unit, st *ir.Struct, layout *ir.MemberLayout) string {
	var padding strings.Builder
	padding.WriteString("(")
	end := int64(0)
	for _, field := range layout.Fields {
		if field.Offset > end {
			fmt.Fprintf(&padding, "(%d, %d), ", end, field.Offset)
		}
		end = field.Offset + field.Size
	}
	if end < layout.Size {
		fmt.Fprintf(&padding, "(%d, %d), ", end, layout.Size)
	}
	padding.WriteString(")")
	return fmt.Sprintf("cook_align=%d, extent_start=%d, padding=%s, build_version=%d, bytes_blob_type_id=%d, string_blob_type_id=%d", ir.CookNodeAlign(u, st), ir.CookExtentStart(u, st), padding.String(), ir.BuildVersion(u), ir.BytesTypeId, ir.StringTypeId)
}

func reflectionWide(f *ir.Field) string {
	if ir.TableKindWide(ir.TableWireScalarKind(f)) {
		if lo, hi, ok := ir.TableRawRange(f); ok {
			return "(" + lo.String() + ", " + hi.String() + ")"
		}
	}
	return "None"
}
func reflectionElementColumns(f *ir.Field) string {
	elem := *f
	elem.KeyEnum = ""
	elem.KeyEnumRef = nil
	return fmt.Sprintf("size=%d, frac_bits=%d, wide=%s, variant_ids=%s, %s", fieldSize(f), f.Type.FracBits, reflectionWide(f), viewVariantIds(f, true), reflectionVocabularyColumns(&elem))
}
