// t10Root is the named fixed root of a unit, so a probe can name its surface.
func t10Root(t *testing.T, u *ir.Unit, name string) *ir.Struct {
	t.Helper()
	for _, st := range fixedRoots(u) {
		if st.Name == name {
			return st
		}
	}
	t.Fatalf("the unit declares no fixed root %s", name)
	return nil
}

// t10Probe generates this leg's Elixir for an inline schema — the packet
// surface the type values lower to and the fixed surface this leg emits — then
// writes ONE generated probe beside it and runs it with the leg's own toolchain
// (§5.9 #18). body asserts the values the leg wrote and read back; a FAIL line
// or a non-zero exit fails the test.
func t10Probe(t *testing.T, src, root, body string) {
	t.Helper()
	bin := elixirBinary(t)
	u := unitFrom(t, src)
	files, err := elixir.Generate(u)
	if err != nil {
		t.Fatalf("generate packet: %v", err)
	}
	tables, err := Generate(u)
	if err != nil {
		t.Fatalf("generate fixed: %v", err)
	}
	maps.Copy(files, tables)
	dir := t.TempDir()
	var names []string
	for name, data := range files {
		if strings.Contains(name, "/") || !strings.HasSuffix(name, ".ex") {
			continue
		}
		if err := os.WriteFile(filepath.Join(dir, name), data, 0o600); err != nil {
			t.Fatal(err)
		}
		names = append(names, name)
	}
	st := t10Root(t, u, root)
	snake := ir.RustSnake(st.Name)
	mod := ir.GoExportName(u.Package) + "." + ir.GoExportName(fileOf(t, u, st.Name)) + FixedModuleSuffix
	probe := fmt.Sprintf(`# GENERATED BY internal/codegen/elixirtable/fixedroadmap_t10_test.go.
defmodule T10Probe do
  alias %[1]s, as: T

  def load(data), do: T.%[2]s_fixed_load(data)
  def save(values), do: T.%[2]s_fixed_save(values)
  def measure(n), do: T.%[2]s_fixed_measure(n)
  def body_bytes, do: T.%[2]s_fixed_body_bytes()
  def record_bytes, do: T.%[2]s_fixed_record_bytes()

  def check(true, _what), do: :ok

  def check(false, what) do
    IO.puts(:stderr, "FAIL: " <> what)
    Process.put(:failed, true)
  end

  def run do
%[3]s
    if Process.get(:failed), do: System.halt(1), else: IO.puts("ok")
  end
end

T10Probe.run()
`, mod, snake, indentBody(body))
	if err := os.WriteFile(filepath.Join(dir, "probe.exs"), []byte(probe), 0o600); err != nil {
		t.Fatal(err)
	}
	args := []string{}
	for _, n := range sortedRuntimeFirst(names) {
		args = append(args, "-r", n)
	}
	args = append(args, "probe.exs")
	cmd := exec.Command(bin, args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "PATH="+otpBin(t)+string(os.PathListSeparator)+os.Getenv("PATH"))
	out, err := cmd.CombinedOutput()
	if err != nil || !strings.Contains(string(out), "ok") {
		t.Fatalf("the probe failed: %v\n%s", err, out)
	}
}

// ---- optional-scalars -------------------------------------------------------

// t10OptionalScalars holds optional-scalars/elixir/valid-data to SPEC-TABLES
// §2.3: an optional scalar and an optional enum carry a presence bool beside a
// payload that RIDES WHOLE; the WRITE puts a non-default and both int32
// boundaries on the wire, the READ lands the flag and the value, and an absent
// field reads back absent at its declared default.
func t10OptionalScalars(t *testing.T) {
	t10Probe(t, `package probe

enum Grade { Bronze, Silver, Gold }

fixed table Opt
{
    lead  uint32 = 1
    tier  ?int32
    grade ?Grade
    trail uint32 = 2
}
`, "Opt", `  v = %Probe.Opt{lead: 7, tier_present: true, tier: -2147483648, grade_present: true, grade: 3, trail: 9}
  {:ok, [r], _} = load(save([v]))
  check(r.tier_present == true and r.tier == -2147483648, "present boundary scalar did not land: #{inspect({r.tier_present, r.tier})}")
  check(r.grade_present == true and r.grade == 3, "present enum ordinal did not land: #{inspect({r.grade_present, r.grade})}")
  check(r.lead == 7 and r.trail == 9, "the brackets either side of the optionals moved: #{inspect({r.lead, r.trail})}")
  h = %Probe.Opt{lead: 7, tier_present: true, tier: 2147483647, grade_present: true, grade: 1, trail: 9}
  {:ok, [rh], _} = load(save([h]))
  check(rh.tier == 2147483647 and rh.grade == 1, "the other boundary did not land: #{inspect({rh.tier, rh.grade})}")
  a = %Probe.Opt{lead: 7, tier_present: false, grade_present: false, trail: 9}
  {:ok, [ra], _} = load(save([a]))
  check(ra.tier_present == false and ra.grade_present == false, "an absent optional came back present: #{inspect({ra.tier_present, ra.grade_present})}")
  check(ra.tier == 0 and ra.grade == 0, "an absent optional did not read its declared default: #{inspect({ra.tier, ra.grade})}")
  check(ra.lead == 7 and ra.trail == 9, "an absent optional moved its neighbours: #{inspect({ra.lead, ra.trail})}")`)
}

// ---- optional-arrays --------------------------------------------------------

// t10OptionalArrays holds optional-arrays/elixir/valid-data to SPEC-TABLES
// §2.3's "`?` on a bounded array — `?[..N]T` and `?[N]T` — is the same construct
// one shape up": presence decides whether the array rides; a present counted
// array carries its live count (zero included); a present all-default fixed
// array rides whole; an absent one reads back absent.
func t10OptionalArrays(t *testing.T) {
	t10Probe(t, `package probe

fixed table Opt
{
    lead  uint32 = 1
    vals  ?[..4]int32
    fx    ?[3]uint16
    trail uint32 = 2
}
`, "Opt", `  v = %Probe.Opt{lead: 5, vals_present: true, vals: [10, 20, 30, 40], fx_present: true, fx: [1, 2, 65535], trail: 6}
  {:ok, [r], _} = load(save([v]))
  check(r.vals_present == true and r.vals == [10, 20, 30, 40], "the present counted array did not land: #{inspect({r.vals_present, r.vals})}")
  check(r.fx_present == true and r.fx == [1, 2, 65535], "the present fixed array did not land: #{inspect({r.fx_present, r.fx})}")
  check(r.lead == 5 and r.trail == 6, "the brackets either side of the optionals moved: #{inspect({r.lead, r.trail})}")
  e = %Probe.Opt{lead: 5, vals_present: true, vals: [], fx_present: true, fx: [0, 0, 0], trail: 6}
  {:ok, [re], _} = load(save([e]))
  check(re.vals_present == true and re.vals == [], "present-and-empty counted array is not absent: #{inspect({re.vals_present, re.vals})}")
  check(re.fx_present == true and re.fx == [0, 0, 0], "a present all-default fixed array did not ride whole: #{inspect({re.fx_present, re.fx})}")
  a = %Probe.Opt{lead: 5, vals_present: false, fx_present: false, trail: 6}
  {:ok, [ra], _} = load(save([a]))
  check(ra.vals_present == false and ra.fx_present == false, "an absent optional array came back present: #{inspect({ra.vals_present, ra.fx_present})}")`)
}

// ---- scalar-defaults --------------------------------------------------------

// t10ScalarDefaults holds scalar-defaults/elixir/valid-data to
// docs/FIXED-FORM-ALGORITHM.md §3: a declared scalar, enum and ranged default
// is what a field with no value on the wire reads as. The default is CONSTRUCTED
// and read back, and non-default boundary values round-trip beside it.
func t10ScalarDefaults(t *testing.T) {
	t10Probe(t, `package probe

enum Grade { Bronze, Silver, Gold }

fixed table Cfg
{
    count  int32 = 7
    grade  Grade = Silver
    ranged int32 = 3 | min = 0, max = 10
}
`, "Cfg", `  d = %Probe.Cfg{}
  {:ok, [rd], _} = load(save([d]))
  check(rd.count == 7, "the declared scalar default did not read back: #{inspect(rd.count)}")
  check(rd.grade == 2, "the declared enum default did not read back: #{inspect(rd.grade)}")
  check(rd.ranged == 3, "the declared ranged default did not read back: #{inspect(rd.ranged)}")
  lo = %Probe.Cfg{count: -2147483648, grade: 3, ranged: 0}
  {:ok, [rlo], _} = load(save([lo]))
  check(rlo.count == -2147483648 and rlo.grade == 3 and rlo.ranged == 0, "the lower boundary did not land: #{inspect(rlo)}")
  hi = %Probe.Cfg{count: 2147483647, grade: 1, ranged: 10}
  {:ok, [rhi], _} = load(save([hi]))
  check(rhi.count == 2147483647 and rhi.grade == 1 and rhi.ranged == 10, "the upper boundary did not land: #{inspect(rhi)}")`)
}

// ---- text-bytes-flags-defaults ---------------------------------------------

// t10TextBytesFlagsDefaults holds text-bytes-flags-defaults/elixir/valid-data
// to docs/FIXED-FORM-ALGORITHM.md §3's prefill: a string, a byte buffer and a
// flags mask each carry a declared default. The default is CONSTRUCTED and read
// back; full-width text/bytes and a non-default mask round-trip at the bounds.
func t10TextBytesFlagsDefaults(t *testing.T) {
	t10Probe(t, `package probe

flags Caps { Jump, Crouch }

fixed table Ship
{
    name string(8) = "hi"
    tag  bytes(4) = "ab"
    caps Caps = { Jump, Crouch }
}
`, "Ship", `  d = %Probe.Ship{}
  {:ok, [rd], _} = load(save([d]))
  check(rd.name == "hi", "the declared string default did not read back: #{inspect(rd.name)}")
  check(rd.tag == "ab", "the declared bytes default did not read back: #{inspect(rd.tag)}")
  check(rd.caps == 3, "the declared flags default did not read back: #{inspect(rd.caps)}")
  v = %Probe.Ship{name: "abcdefgh", tag: "wxyz", caps: 1}
  {:ok, [rv], _} = load(save([v]))
  check(rv.name == "abcdefgh" and rv.tag == "wxyz" and rv.caps == 1, "the boundary-width values did not land: #{inspect(rv)}")
  e = %Probe.Ship{name: "", tag: "", caps: 0}
  {:ok, [re], _} = load(save([e]))
  check(re.name == "" and re.tag == "" and re.caps == 0, "empty text, empty bytes and a zero mask did not land: #{inspect(re)}")`)
}

// ---- record-measurement -----------------------------------------------------

// t10RecordMeasurement holds record-measurement/elixir/valid-data to
// docs/SPEC-TABLES.md §3.4's `C(f)`, `C(T)` and record size: the emitted
// `<root>_fixed_measure/1` is the FILE size of that many records, the record is
// the body plus the eight-byte hash, and no value is read to measure.
func t10RecordMeasurement(t *testing.T) {
	t10Probe(t, `package probe

fixed table Rec
{
    a uint32
    b bytes(6)
    c string(8)
}
`, "Rec", `  v = %Probe.Rec{a: 5, b: "abcdef", c: "hi"}
  one = save([v])
  check(byte_size(one) == measure(1), "measure(1) is not the saved size: #{byte_size(one)} vs #{measure(1)}")
  check(byte_size(save([])) == measure(0), "measure(0) is not an empty file's size: #{measure(0)}")
  check(byte_size(save([v, v, v])) == measure(3), "measure(3) is not three records: #{measure(3)}")
  check(record_bytes() == body_bytes() + 8, "the record is not the body plus the hash: #{record_bytes()} vs #{body_bytes()}")
  check(measure(10) - measure(0) == 10 * record_bytes(), "measure is not linear in the record count")
  check(measure(1) - measure(0) == record_bytes(), "one record is exactly the record size")`)
}

// ---- the card's test --------------------------------------------------------

func TestFixedRoadmapElixirT10Optionals(t *testing.T) {
	t.Parallel()
	tasks := []struct {
		id    string
		check func(t *testing.T)
	}{
		{id: "optional-scalars/elixir/valid-data", check: t10OptionalScalars},
		{id: "optional-arrays/elixir/valid-data", check: t10OptionalArrays},
		{id: "scalar-defaults/elixir/valid-data", check: t10ScalarDefaults},
		{id: "text-bytes-flags-defaults/elixir/valid-data", check: t10TextBytesFlagsDefaults},
		{id: "record-measurement/elixir/valid-data", check: t10RecordMeasurement},
	}
	for _, task := range tasks {
		t.Run(task.id, func(t *testing.T) {
			t.Parallel()
			task.check(t)
		})
	}
}
