package elixirtable

// A ZERO-WIDTH RUN IN A MESSAGE BATCH IS HELD TO THE BITS LEFT IN THE BATCH
// (docs/SPEC-TABLES.md §3.3). An array's shape is the peer's announcement, not
// a count this side declared, so a run whose elements ride no bits is backed by
// the batch's remaining bits for every announced maximum. The list path builds
// what the bits can back and refuses the rest before any cell is allocated;
// internal/tablewire's walked-element rule is the oracle for the same bytes.

import (
	"encoding/binary"
	"fmt"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/slowtest"
	"github.com/mas-bandwidth/schema/v2/internal/tabletext"
	"github.com/mas-bandwidth/schema/v2/internal/tablewire"
	"github.com/mas-bandwidth/schema/v2/ir"
)

// zeroWidthArray is one array entry's shape: min, max, element kind, and the
// element's own announced shape. A zero-width element is kind 0, kind 32, or a
// ranged scalar whose min equals its max.
func zeroWidthArray(min, max uint64, elem byte, elemShape []byte) []byte {
	out := binary.AppendUvarint(nil, min)
	out = binary.AppendUvarint(out, max)
	out = append(out, elem)
	return append(out, elemShape...)
}

// zeroWidthEntry is one announced vocabulary entry: the id, the kind, the shape.
func zeroWidthEntry(id uint64, kind byte, shape []byte) []byte {
	out := binary.LittleEndian.AppendUint64(nil, id)
	out = append(out, kind)
	return append(out, shape...)
}

// zeroWidthAnnouncement wraps entries in the announcement's file form, the same
// bytes the generated announce_read reads: a build version, the vocabulary
// field over byte element kind 6, then the form's trailer.
func zeroWidthAnnouncement(entries ...[]byte) []byte {
	words := []byte{}
	for _, e := range entries {
		words = append(words, e...)
	}
	vocabSub := []byte{6}
	vocabSub = binary.AppendUvarint(vocabSub, uint64(len(words)))
	vocabSub = append(vocabSub, words...)

	version := []byte{1, 9, 0, 0, 0, 0, 0, 0, 0, 0}
	vocab := []byte{2, 14}
	vocab = binary.AppendUvarint(vocab, uint64(len(vocabSub)))
	vocab = append(vocab, vocabSub...)

	body := append(version, vocab...)
	body = append(body, 0)

	out := []byte{1}
	out = append(out, body...)
	out = append(out, 0xFE, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF)
	out = append(out, 0xFD, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF)
	return append(out, 2, 0, 0, 0, 0, 0, 0, 0)
}

func TestElixirMessageZeroWidthRunIsBounded(t *testing.T) {
	t.Parallel()
	slowtest.Gate(t, "an external toolchain")

	const far = 30_000_000

	flat := zeroWidthAnnouncement(
		zeroWidthEntry(0x1000, 14, zeroWidthArray(far, far, 0, nil)),
	)
	ranged := zeroWidthAnnouncement(
		zeroWidthEntry(0x1000, 14, zeroWidthArray(far, far, 2, []byte{1, 0, 14})),
	)
	nested := zeroWidthAnnouncement(
		zeroWidthEntry(0x1000, 14, zeroWidthArray(far, far, 14, zeroWidthArray(far, far, 0, nil))),
	)
	small := zeroWidthAnnouncement(
		zeroWidthEntry(0x1000, 14, zeroWidthArray(2, 2, 0, nil)),
	)

	u := unitFrom(t, `package probe

fixed table Probe
{
    x uint8
}
`)
	tables, err := Generate(u)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	module, ok := tables[TableMessageModule+".ex"]
	if !ok {
		t.Fatalf("the unit grows no %s.ex", TableMessageModule)
	}

	probe := fmt.Sprintf(`# GENERATED BY internal/codegen/elixirtable/messageform_zero_width_run_test.go.
defmodule Probe do
  alias %[1]s.TableMessage, as: M

  def check(true, _what), do: :ok

  def check(false, what) do
    IO.puts(:stderr, "FAIL: " <> what)
    Process.put(:failed, true)
  end

  def refuse(label, announcement, batch) do
    Process.flag(:max_heap_size, %%{size: 1_000_000, kill: true, error_logger: false})

    vocab =
      case M.announce_read(Base.decode16!(announcement, case: :lower)) do
        {:ok, v} -> v
        other -> raise "announce_read refused the announcement: #{inspect(other)}"
      end

    case M.load_messages(vocab, batch) do
      {:malformed, 0, []} -> :ok
      other -> check(false, label <> " accepted " <> inspect(other))
    end
  end

  def control(label, announcement, batch) do
    vocab =
      case M.announce_read(Base.decode16!(announcement, case: :lower)) do
        {:ok, v} -> v
        other -> raise "announce_read refused the announcement: #{inspect(other)}"
      end

    case M.load_messages(vocab, batch) do
      {:ok, [[{1, names}]]} ->
        check(names == List.duplicate(:name, %[2]d), label <> " decoded " <> inspect(names))

      other ->
        check(false, label <> " refused " <> inspect(other))
    end
  end

  def run do
    refuse("flat zero-width run", "%[3]s", <<2, 0, 1>>)
    refuse("ranged zero-width run", "%[4]s", <<2, 0, 1>>)
    refuse("nested zero-width run", "%[5]s", <<2, 0, 1>>)
    control("backed zero-width run", "%[6]s", <<2, 0, 1>>)

    if Process.get(:failed), do: System.halt(1), else: IO.puts("ok")
  end
end

Probe.run()
`, ir.GoExportName(u.Package), 2, hexOf(flat), hexOf(ranged), hexOf(nested), hexOf(small))
	out, err := runElixirModuleProbe(t, module, probe)
	if err != nil {
		t.Fatalf("%v\n%s", err, out)
	}

	// THE ENGINE READS THE SAME BYTES: the nested run is a walked element that
	// consumes no bits, and a remaining count the bits cannot back is damage.
	m := tabletext.NewModel(u)
	v := &tablewire.Vocabulary{}
	var announced tabletext.Report
	if err := v.AnnounceRead(nested, &announced); err != nil {
		t.Fatalf("the announcement did not read: %v %+v", err, announced)
	}
	var report tabletext.Report
	got, err := tablewire.DecodeMessage(m, m.New(m.Lookup("Probe")), []byte{2, 0, 1}, v, &report)
	if got || err == nil {
		t.Fatalf("the engine accepted a zero-width run the batch's bits cannot back: ok=%v err=%v report=%+v", got, err, report)
	}
}

// hexOf spells the bytes the probe passes to Base.decode16!.
func hexOf(b []byte) string {
	var s strings.Builder
	for _, v := range b {
		fmt.Fprintf(&s, "%02x", v)
	}
	return s.String()
}
