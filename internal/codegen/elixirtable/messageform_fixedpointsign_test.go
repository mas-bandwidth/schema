package elixirtable

// THE MESSAGE FORM's SIGNED FIXED-POINT KINDS (docs/SPEC-TABLES.md §3.3): a
// raw kind 20–24 rides at its storage width, two's complement, so -16 is the
// same value at every width. The engine writes the canonical batch; the
// generated reader must land its value and the generated writer must spell
// its bytes. The probe takes each row from the unit's own announcement, never
// a copied vocabulary.

import (
	"encoding/hex"
	"fmt"
	"math/big"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/tabletext"
	"github.com/mas-bandwidth/schema/v2/internal/tablewire"
	"github.com/mas-bandwidth/schema/v2/ir"
)

// fixedPointUnrangedKind is one raw signed fixed-point kind under test.
type fixedPointUnrangedKind struct {
	kind int
	decl string
	lo   string
	hi   string
}

// The bounds are the declaration's; clearing them announces packing RAW, which
// is the row under test. Full-width bounds keep the declaration honest at the
// narrow kinds; the wider kinds use the same span the engine's own raw-kind
// rows declare.
var fixedPointUnrangedKinds = []fixedPointUnrangedKind{
	{ir.TableKindFixed8, "fixed(8, 0)", "-128", "127"},
	{ir.TableKindFixed16, "fixed(16, 0)", "-32768", "32767"},
	{ir.TableKindFixed32, "fixed(32, 0)", "-1000", "1000"},
	{ir.TableKindFixed64, "fixed(64, 0)", "-1000", "1000"},
	{ir.TableKindFixed128, "fixed(128, 0)", "-1000", "1000"},
}

// fixedPointUnrangedUnit builds a one-field probe whose field announces the
// kind raw, and returns the engine's batch for -16 through it.
func fixedPointUnrangedUnit(t *testing.T, tc fixedPointUnrangedKind) (*ir.Unit, []byte) {
	t.Helper()
	u := unitFrom(t, fmt.Sprintf(`package rawfixed

fixed table Probe
{
    v %s | min = %s, max = %s
}
`, tc.decl, tc.lo, tc.hi))
	st := findTable(t, u, "Probe")
	f := st.Fields[0]
	f.HasIntRange = false
	f.IntMin = nil
	f.IntMax = nil

	vocab := tablewire.MessageVocabulary(u)
	if len(vocab) != 1 || int(vocab[0].Kind) != tc.kind || vocab[0].Shape.Packing != ir.TableMessageRaw {
		t.Fatalf("kind %d: the probe announces %d entries and kind %d packing %d",
			tc.kind, len(vocab), vocab[0].Kind, vocab[0].Shape.Packing)
	}

	m := tabletext.NewModel(u)
	inst := m.New(m.Lookup("Probe"))
	inst.Fields[0].Cell.Wide = big.NewInt(-16)
	wire, err := tablewire.EncodeMessage(m, inst)
	if err != nil {
		t.Fatalf("kind %d: engine save -16: %v", tc.kind, err)
	}
	return u, wire
}

// fixedPointUnrangedProbe is the generated-module probe: load the engine bytes
// and save the value, each against the other.
func fixedPointUnrangedProbe(ns string, kind int, wire []byte) string {
	return fmt.Sprintf(`# GENERATED BY internal/codegen/elixirtable/messageform_fixedpointsign_test.go.
defmodule Probe do
  import Bitwise
  alias %[1]s.TableMessage, as: M

  def check(true, _what), do: :ok

  def check(false, what) do
    IO.puts(:stderr, "FAIL: " <> what)
    Process.put(:failed, true)
  end

  def run do
    vocab =
      case M.announce_read(M.announce()) do
        {:ok, v} -> v
        other -> raise "announce_read refused the unit's own announcement: #{inspect(other)}"
      end

    wire = Base.decode16!(%[2]q, case: :lower)
    value = -16
    ref = 1

    check(
      M.load_messages(vocab, wire) == {:ok, [[{ref, value}]]},
      "kind %[3]d signed fixed-point load"
    )

    check(
      M.save_messages(vocab, [[{ref, value}]]) == {:ok, wire},
      "kind %[3]d signed fixed-point save"
    )

    if Process.get(:failed), do: System.halt(1), else: IO.puts("ok")
  end
end

Probe.run()
`, ns, hex.EncodeToString(wire), kind)
}

func TestElixirMessageSignedFixedPointUnranged(t *testing.T) {
	t.Parallel()
	for _, tc := range fixedPointUnrangedKinds {
		t.Run(fmt.Sprintf("kind-%d", tc.kind), func(t *testing.T) {
			t.Parallel()
			u, wire := fixedPointUnrangedUnit(t, tc)
			tables, err := Generate(u)
			if err != nil {
				t.Fatalf("kind %d: generate: %v", tc.kind, err)
			}
			module, ok := tables[TableMessageModule+".ex"]
			if !ok {
				t.Fatalf("kind %d: the unit grows no %s.ex", tc.kind, TableMessageModule)
			}
			probe := fixedPointUnrangedProbe(ir.GoExportName(u.Package), tc.kind, wire)
			if out, err := runElixirModuleProbe(t, module, probe); err != nil {
				t.Fatalf("kind %d: %v\n%s", tc.kind, err, out)
			}
		})
	}
}

// TestElixirMessageSignedFixedPointUnrangedNegativeControl removes the raw
// sign extension from a COPY of the emitted reader and requires the probe to
// go red by the row it owns.
func TestElixirMessageSignedFixedPointUnrangedNegativeControl(t *testing.T) {
	t.Parallel()
	const anchor = `  defp scalar_value(kind, _shape, raw) when kind in [2, 3, 4, 5, 18, 20, 21, 22, 23, 24, 36],
    do: sign_extend(raw, kind_bits(kind))`
	const removed = `  defp scalar_value(kind, _shape, raw) when kind in [2, 3, 4, 5, 18, 20, 21, 22, 23, 24, 36],
    do: raw`

	for _, tc := range fixedPointUnrangedKinds {
		t.Run(fmt.Sprintf("kind-%d", tc.kind), func(t *testing.T) {
			t.Parallel()
			u, wire := fixedPointUnrangedUnit(t, tc)
			tables, err := Generate(u)
			if err != nil {
				t.Fatalf("kind %d: generate: %v", tc.kind, err)
			}
			module := tables[TableMessageModule+".ex"]
			if n := strings.Count(string(module), anchor); n != 1 {
				t.Fatalf("NEGATIVE CONTROL FAILED: the sign-extension anchor appears %d times, want 1:\n%s", n, anchor)
			}
			broken := []byte(strings.Replace(string(module), anchor, removed, 1))
			probe := fixedPointUnrangedProbe(ir.GoExportName(u.Package), tc.kind, wire)
			out, err := runElixirModuleProbe(t, broken, probe)
			if err == nil {
				t.Fatalf("NEGATIVE CONTROL FAILED: removing the raw sign extension left kind %d green\n%s", tc.kind, out)
			}
			want := fmt.Sprintf("FAIL: kind %d signed fixed-point load", tc.kind)
			if !strings.Contains(out, want) {
				t.Fatalf("NEGATIVE CONTROL FAILED: removing the raw sign extension did not red %q:\n%s", want, out)
			}
		})
	}
}
