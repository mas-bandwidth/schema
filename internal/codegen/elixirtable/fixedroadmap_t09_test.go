// t09UTF16 holds utf16-values to §3.4: a `wstring(N)` field is its UTF-16 code
// units, and the write/read pair reproduces a non-default string and a string
// filling the declared capacity exactly.
func t09UTF16(t *testing.T) {
	u := unitFrom(t, `package probe

fixed table T
{
    w wstring(8)
}
`)
	t09Probe(t, u, "T", `  ab = <<0x41, 0x00, 0x42, 0x00>>
  {:ok, [r], rep} = @@LOAD@@(@@SAVE@@([%Probe.T{w: ab}]))
  check(r.w == ab, "a non-default UTF-16 string does not round-trip: #{inspect(r.w)}")
  check(rep.malformed == false, "a well-formed UTF-16 string is malformed: #{inspect(rep)}")
  full = :binary.copy(<<0x41, 0x00>>, 8)
  {:ok, [rf], repf} = @@LOAD@@(@@SAVE@@([%Probe.T{w: full}]))
  check(rf.w == full, "a string at the declared capacity does not round-trip: #{inspect(rf.w)}")
  check(repf.malformed == false, "a full-capacity string is malformed: #{inspect(repf)}")`)
}

// t09UnionValues holds union-values to §3.4: a tagged union is a tag ordinal
// and the widest arm's storage, and the write/read pair reproduces a value in
// each arm and the implicit None.
func t09UnionValues(t *testing.T) {
	u := unitFrom(t, `package probe

type Dot { x int32 = 7 }
type Box
{
    w int32 = 1
    h int32 = 2
}

union Shape
{
    dot Dot
    box Box
}

fixed table T { s Shape }
`)
	t09Probe(t, u, "T", `  d = %Probe.Shape{type: 1, dot: %Probe.Dot{x: -7}}
  {:ok, [rd], _} = @@LOAD@@(@@SAVE@@([%Probe.T{s: d}]))
  check(rd.s.type == 1 and rd.s.dot.x == -7, "the Dot arm does not round-trip: #{inspect(rd.s)}")
  b = %Probe.Shape{type: 2, box: %Probe.Box{w: 34, h: 55}}
  {:ok, [rb], _} = @@LOAD@@(@@SAVE@@([%Probe.T{s: b}]))
  check(rb.s.type == 2 and rb.s.box.w == 34 and rb.s.box.h == 55, "the Box arm does not round-trip: #{inspect(rb.s)}")
  none = %Probe.Shape{}
  {:ok, [rn], _} = @@LOAD@@(@@SAVE@@([%Probe.T{s: none}]))
  check(rn.s.type == 0, "None (tag 0) does not round-trip: #{inspect(rn.s)}")`)
}

// t09PayloadFree holds payload-free-arms to §3.4: a union arm whose type has no
// fields occupies zero bytes and is selected by its tag alone, so the
