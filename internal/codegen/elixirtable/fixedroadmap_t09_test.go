  check(b64(r.a) == 0x3FF8000000000000, "a = 1.5 is not its eight little-endian bytes: #{b64(r.a)}")
  check(b64(r.b) == 0xC002000000000000, "b = -2.25 is not its eight little-endian bytes: #{b64(r.b)}")
