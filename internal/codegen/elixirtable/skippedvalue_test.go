package elixirtable

// THE SKIPPED-VALUE RULE ON THE ELIXIR LEG (docs/SPEC-TABLES.md §3.3, §4,
// §16.2, §16.3; docs/rulings.json skipped-value-is-validated). A value the
// reader SKIPS is held to what a read of it would hold, in every form, and
// damage inside it refuses the whole read. The shared vectors under
// testdata/wire/skipped-value/ carry one row per condition, each with its
// verdict in the manifest; a reader of test/skipped-value/reader declares only
// `known` and skips the writer's six extra fields.
//
// The verdict is the contract, never a refusal's name (docs/rulings.json
// refusal-verdict-only), so this test compares read against refused and
// nothing else.

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/mas-bandwidth/schema/v2/ir"
)

type skippedValueRow struct {
	name    string
	form    string
	verdict string
}

func skippedValueRows(t *testing.T, path string) []skippedValueRow {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var rows []skippedValueRow
	for line := range strings.SplitSeq(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) != 3 {
			t.Fatalf("MANIFEST.tsv: a row is <file> TAB <form> TAB <verdict>, got %q", line)
		}
		rows = append(rows, skippedValueRow{name: fields[0], form: fields[1], verdict: fields[2]})
	}
	if len(rows) == 0 {
		t.Fatal("the skipped-value manifest carries no rows")
	}
	return rows
}

func TestElixirSkippedValueIsValidated(t *testing.T) {
	t.Parallel()
	root, err := filepath.Abs("../../..")
	if err != nil {
		t.Fatal(err)
	}
	u := loadUnit(t, filepath.Join(root, "test", "skipped-value", "reader", "Reader.schema"))
	dir := filepath.Join(root, "testdata", "wire", "skipped-value")
	rows := skippedValueRows(t, filepath.Join(dir, "MANIFEST.tsv"))

	ns := ir.GoExportName(u.Package)
	announcement := filepath.Join(dir, "announcement.bin")

	var body strings.Builder
	fmt.Fprintf(&body, "    alias %s.Table, as: T\n", ns)
	fmt.Fprintf(&body, "    alias %s.TableMessage, as: M\n", ns)
	needsVocab := false
	for _, row := range rows {
		if row.form == "message" && row.name != "announcement.bin" {
			needsVocab = true
		}
	}
	if needsVocab {
		fmt.Fprintf(&body, "    vocab =\n      case M.announce_read(File.read!(%s)) do\n        {:ok, v} -> v\n        other -> raise \"announce_read refused the reference's announcement: #{inspect(other)}\"\n      end\n", elixirString(announcement))
	}

	for _, row := range rows {
		path := elixirString(filepath.Join(dir, row.name))
		want := elixirString(row.verdict)
		switch {
		case row.form == "json":
			fmt.Fprintf(&body, `
    got = case T.from_json("Root", File.read!(%[1]s)) do
      {:ok, _, _} -> "read"
      _ -> "refused"
    end
    check(got == %[2]s, "%[3]s: from_json gave #{inspect(got)}")
`, path, want, row.name)
		case row.name == "announcement.bin":
			fmt.Fprintf(&body, `
    got = case M.announce_read(File.read!(%[1]s)) do
      {:ok, _} -> "read"
      _ -> "refused"
    end
    check(got == %[2]s, "%[3]s: announce_read gave #{inspect(got)}")
`, path, want, row.name)
		default:
			fmt.Fprintf(&body, `
    got = case M.load_messages(vocab, File.read!(%[1]s)) do
      {:ok, _} -> "read"
      _ -> "refused"
    end
    check(got == %[2]s, "%[3]s: load_messages gave #{inspect(got)}")
`, path, want, row.name)
		}
	}

	probe := fmt.Sprintf(`# GENERATED BY internal/codegen/elixirtable/skippedvalue_test.go.
defmodule Probe do
  def check(true, _what), do: :ok

  def check(false, what) do
    IO.puts(:stderr, "FAIL: " <> what)
    Process.put(:failed, true)
  end

  def run do
%[1]s
    if Process.get(:failed), do: System.halt(1), else: IO.puts("ok")
  end
end

Probe.run()
`, body.String())

	out, err := runArmProbe(t, elixirBinary(t), generateElixir(t, u), probe)
	if err != nil {
		t.Fatalf("the skipped-value probe failed: %v\n%s", err, out)
	}
	if !strings.Contains(out, "ok") {
		t.Fatalf("the skipped-value probe did not finish:\n%s", out)
	}
}
