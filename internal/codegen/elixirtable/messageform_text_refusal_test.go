package elixirtable

// A TEXT IN THE MESSAGE FORM WRITES ONLY WHAT ITS ENTRY ANNOUNCES
// (docs/SPEC.md §5.1 rows 4 and 8, every build on the Elixir leg;
// docs/SPEC-TABLES.md §3.3). save_messages refuses, writing nothing, a string
// that is not well-formed UTF-8, holds a zero byte, or is longer than its
// entry's announced max, whether the text is a field of the body or rides
// inside an array element. A text of exactly max bytes of well-formed
// multi-byte UTF-8 still writes and reads back equal.
//
// The rows run against the unit's own vocabulary (tables/messages, resolved
// from its own announcement): the InsertText text entry for the field, and
// the Origin union's text arm inside the `origins` array for the element.
// Verdicts and values are asserted, never reason names.

import (
	"fmt"
	"path/filepath"
	"testing"

	"github.com/mas-bandwidth/schema/v2/internal/slowtest"
	"github.com/mas-bandwidth/schema/v2/ir"
)

func TestElixirSaveMessagesRefusesTextOffShape(t *testing.T) {
	t.Parallel()
	slowtest.Gate(t, "Elixir save_messages refuses text off its announced shape")

	root, err := filepath.Abs("../../..")
	if err != nil {
		t.Fatal(err)
	}
	units, _ := messageManifest(t, filepath.Join(root, "testdata", "conformance", "tables", "MANIFEST.txt"))
	paths, ok := units["messagedemo"]
	if !ok {
		t.Fatalf("the manifest carries no unit line for messagedemo")
	}
	u := messageLoadUnit(t, root, paths)
	tables, err := Generate(u)
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	module, ok := tables[TableMessageModule+".ex"]
	if !ok {
		t.Fatalf("the unit grows no %s.ex", TableMessageModule)
	}
	out, err := runElixirModuleProbe(t, module, textShapeProbe(ir.GoExportName(u.Package)))
	if err != nil {
		t.Fatalf("%v\n%s", err, out)
	}
}

func textShapeProbe(ns string) string {
	return fmt.Sprintf(`# GENERATED BY internal/codegen/elixirtable/messageform_text_refusal_test.go.
defmodule Probe do
  alias %s.TableMessage, as: M

  def check(true, _what), do: :ok

  def check(false, what) do
    IO.puts(:stderr, "FAIL: " <> what)
    Process.put(:failed, true)
  end

  # The one entry of the vocabulary that matches, by its 1-based reference.
  defp only(vocab, what, pred) do
    case all(vocab, what, pred) do
      [hit] -> hit
      hits -> raise "#{what}: #{length(hits)} entries match"
    end
  end

  # Every entry that matches, at least one.
  defp all(vocab, what, pred) do
    case for({e, ref} <- Enum.with_index(vocab.entries, 1), pred.(e), do: {ref, e}) do
      [] -> raise "#{what}: no entry matches"
      hits -> hits
    end
  end

  # Exactly max bytes of well-formed UTF-8, two-byte characters where they fit.
  defp full_text(max), do: String.duplicate(<<0xC3, 0xA9>>, div(max, 2)) <> String.duplicate("a", rem(max, 2))

  defp off_shape(max) do
    [
      {"max + 1 bytes", String.duplicate("a", max + 1)},
      {"a zero byte", "a" <> <<0>> <> "b"},
      {"a lone 0xFF", <<0xFF>>},
      {"an encoded surrogate", <<0xED, 0xA0, 0x80>>}
    ]
  end

  defp refused(vocab, what, body) do
    case M.save_messages(vocab, [body]) do
      {:error, _} -> :ok
      other -> check(false, "save_messages wrote #{what}: #{inspect(other)}")
    end

    case M.measure_messages(vocab, [body]) do
      {:error, _} -> :ok
      other -> check(false, "measure_messages measured #{what}: #{inspect(other)}")
    end
  end

  defp round_trip(vocab, what, body) do
    case M.save_messages(vocab, [body]) do
      {:ok, batch} ->
        case M.load_messages(vocab, batch) do
          {:ok, [^body]} -> :ok
          other -> check(false, "#{what} read back #{inspect(other)}")
        end

      other ->
        check(false, "#{what} did not write: #{inspect(other)}")
    end
  end

  def run do
    vocab =
      case M.announce_read(M.announce()) do
        {:ok, v} -> v
        other -> raise "announce_read refused the unit's own announcement: #{inspect(other)}"
      end

    # The field: InsertText's text, string(32).
    {text, te} = only(vocab, "text entry", fn e -> e.kind == 12 and e.shape.max == 32 end)
    check(te.shape.max == 32, "text entry max #{te.shape.max}")

    for {what, value} <- off_shape(te.shape.max) do
      refused(vocab, "a field holding #{what}", [{text, value}])
    end

    round_trip(vocab, "a field of exactly max bytes", [{text, full_text(te.shape.max)}])

    # The array element: a [..2]Origin array (InsertText origins), whose
    # element is the Origin union; its text arm is note, string(24).
    [{origins, _} | _] =
      all(vocab, "origins entry", fn e ->
        e.kind == 14 and Map.get(e, :element, %%{})[:kind] == 15 and e.shape.min == 0 and e.shape.max == 2
      end)

    {note, ne} = only(vocab, "note arm", fn e -> e.kind == 12 and e.shape.max == 24 end)

    for {what, value} <- off_shape(ne.shape.max) do
      refused(vocab, "an array element holding #{what}", [{origins, [{note, full_text(ne.shape.max)}, {note, value}]}])
    end

    round_trip(vocab, "an array element of exactly max bytes", [
      {origins, [{note, full_text(ne.shape.max)}, {note, <<>>}]}
    ])

    if Process.get(:failed), do: System.halt(1), else: IO.puts("ok")
  end
end

Probe.run()
`, ns)
}
