// Package rust emits the Rust target: one module per schema file —
// Constants.schema -> constants.rs — plus a generated lib.rs declaring and
// glob re-exporting every module, all deterministic to the byte (SPEC §6.1).
// There is no in-process rustfmt: the emitter writes formatter-clean source
// directly (goldens pin it; no external formatter in the build path), and the
// refuser is `cargo build` in the test chain.
//
// Storage follows the §6.1 Rust column: integer families name their storage
// directly (i8..u64), enums are #[repr(transparent)] newtypes with associated
// variant constants (headroom makes non-variant values wire-legal, which a
// native Rust enum cannot hold), flags are a u64 alias with flat mask
// constants, string(N)/bytes(N) are [u8; N] plus an i32 used length, arrays
// are fixed Rust arrays with an i32 used count beside the counted form.
// Nothing here heap-allocates per value.
//
// Functions follow the §6.3 Rust row: free functions against the concrete
// WriteStream/ReadStream types (the Stream trait in scope for its methods),
// `?` propagation of serialize::Error through the generated Error wrapper on
// EVERY call — this runtime has no sticky errors.
package rust

import (
	"fmt"
	"math/big"
	"sort"
	"strconv"
	"strings"

	"github.com/mas-bandwidth/schema/v2/internal/ast"
	"github.com/mas-bandwidth/schema/v2/ir"
)

// Generate returns module filename -> file contents for every file of the
// unit, plus the lib.rs that stitches the crate together. Modules glob
// re-export into the crate root, so schema references stay order-free across
// files exactly as in Go.
func Generate(u *ir.Unit) (map[string][]byte, error) {
	// fixed(I, F), int128 and uint128: serialize.rs carries the full surface
	// (serialize_int128/serialize_u128 over native i128/u128, serialize_fixed
	// over FixedPointStorage) — storage is native, wire calls mirror the C++
	// macros.
	out := map[string][]byte{}
	home := ir.ProtocolIdHome(u)
	deps := ir.FileDeps(u)

	// module names lowercase the basename; two bases that collapse to the
	// same module cannot coexist in one crate (the other targets keep the
	// basename's case and never collide this way)
	modules := map[string]string{}
	for _, f := range u.Files {
		mod := strings.ToLower(f.Base)
		if prev, dup := modules[mod]; dup {
			return nil, fmt.Errorf("schema files %s and %s both lower to Rust module %q — rename one (module files are the lowercased basename)", prev, f.Base, mod)
		}
		if mod == "lib" {
			// lib.rs is the generated crate root; a schema file lowering to it
			// would silently vanish under the assembled index
			return nil, fmt.Errorf("schema file %s lowers to Rust module \"lib\", which is the generated crate root — rename the file", f.Base)
		}
		modules[mod] = f.Base
	}

	for _, f := range u.Files {
		g := &gen{unit: u, file: f, home: home}
		g.emitFile(f.Base == home)
		g.needsCrate = g.needsCrate || len(deps[f.Base]) > 0 || (g.needsStreams && f.Base != home)
		out[strings.ToLower(f.Base)+".rs"] = g.assemble()
	}

	out["lib.rs"] = assembleLib(u, modules, nil)
	return out, nil
}

// Lib re-assembles the crate root with EXTRA modules declared beside the
// per-file ones — the table surface's modules (internal/codegen/rusttable),
// which are generated by a second backend and must reach the same crate root.
// The Rust target is the one target whose files are stitched together by a
// generated index, so the index is a door rather than a private detail.
func Lib(u *ir.Unit, extra []string) ([]byte, error) {
	modules := map[string]string{}
	for _, f := range u.Files {
		mod := strings.ToLower(f.Base)
		modules[mod] = f.Base
	}
	for _, mod := range extra {
		if prev, dup := modules[mod]; dup {
			return nil, fmt.Errorf("schema file %s lowers to Rust module %q, which the generated table surface claims — rename the file (docs/SPEC-TABLES.md §11)", prev, mod)
		}
	}
	return assembleLib(u, modules, extra), nil
}

func assembleLib(u *ir.Unit, modules map[string]string, extra []string) []byte {
	// a module re-exports into the crate root only if it declares anything: a
	// glob over an item-less module (a comments-only file) is an unused
	// import
	exports := map[string]bool{}
	home := ir.ProtocolIdHome(u)
	for _, f := range u.Files {
		has := f.Base == home
		for _, d := range f.Decls {
			switch d.(type) {
			case *ir.Const, *ir.Enum, *ir.Flags, *ir.Struct:
				has = true
			}
		}
		exports[strings.ToLower(f.Base)] = has
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by the schema compiler for the %s unit. DO NOT EDIT.\n", u.Package)
	b.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	b.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	b.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&b, "// package %s — protocol id 0x%016x\n\n", u.Package, u.ProtocolId)
	b.WriteString("// Two clippy classes are silenced deliberately, crate-wide:\n")
	b.WriteString("// - derivable_impls / field_reassign_with_default: Default impls are\n")
	b.WriteString("//   hand-emitted as the explicit ZERO form (SPEC §5) and new() reassigns\n")
	b.WriteString("//   only the specified defaults — certainty over derive, in every target\n")
	b.WriteString("//   the same way, is the point.\n")
	b.WriteString("#![allow(clippy::derivable_impls, clippy::field_reassign_with_default)]\n\n")
	names := make([]string, 0, len(modules))
	for mod := range modules {
		names = append(names, mod)
	}
	sort.Strings(names)
	for _, mod := range names {
		if exports[mod] {
			fmt.Fprintf(&b, "mod %s;\npub use %s::*;\n", mod, mod)
		} else {
			fmt.Fprintf(&b, "mod %s; // no items — documentation only\n", mod)
		}
	}
	if len(extra) > 0 {
		b.WriteString("\n// the TABLE surface (docs/SPEC-TABLES.md): emitted only for a unit that\n")
		b.WriteString("// declares tables, and glob re-exported like every other module.\n")
		b.WriteString("//\n")
		b.WriteString("// THE TWO ACCELERATORS ARE CARGO FEATURES, both ON by default, because\n")
		b.WriteString("// §19's rule for the block form is that it costs nothing unless you reach\n")
		b.WriteString("// for it — in C++ by not including the header, and here by not enabling\n")
		b.WriteString("// the feature. A consumer that wants only the tolerant wire builds with\n")
		b.WriteString("// default-features = false and compiles no block and no cook module at\n")
		b.WriteString("// all; a consumer that says nothing gets everything, so the default is\n")
		b.WriteString("// the whole surface and the saving is opt-in.\n")
		sorted := append([]string(nil), extra...)
		sort.Strings(sorted)
		for _, mod := range sorted {
			switch {
			case strings.HasSuffix(mod, "_block") || mod == "block_runtime":
				fmt.Fprintf(&b, "#[cfg(feature = \"block\")]\nmod %s;\n#[cfg(feature = \"block\")]\npub use %s::*;\n", mod, mod)
			case strings.HasSuffix(mod, "_cook") || mod == "cook_runtime":
				fmt.Fprintf(&b, "#[cfg(feature = \"cook\")]\nmod %s;\n#[cfg(feature = \"cook\")]\npub use %s::*;\n", mod, mod)
			default:
				fmt.Fprintf(&b, "mod %s;\npub use %s::*;\n", mod, mod)
			}
		}
	}
	return []byte(b.String())
}

type gen struct {
	unit *ir.Unit
	file *ir.File
	home string // the file that carries PROTOCOL_ID and Error/Result

	body             strings.Builder
	bulkBytes        map[*ir.Field]bool // fixed [N]u8 arrays at statically byte-aligned positions (ir.AlignedFixedByteArrays)
	needsStreams     bool               // the file emits wire functions -> import the stream types
	needsStreamTrait bool               // the file calls stream.serialize_* -> the trait must be in scope
	needsCrate       bool               // the file references sibling modules -> use crate::*
}

func (g *gen) pf(format string, args ...any) {
	fmt.Fprintf(&g.body, format, args...)
}

func (g *gen) assemble() []byte {
	var h strings.Builder
	// the basename, not the invocation-relative path: output is deterministic
	// to the byte wherever the compiler runs (SPEC §6.1)
	fmt.Fprintf(&h, "// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", g.file.Base)
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(&h, "// package %s — protocol id 0x%016x\n\n", g.unit.Package, g.unit.ProtocolId)
	hasUse := false
	if g.needsCrate {
		h.WriteString("use crate::*;\n")
		hasUse = true
	}
	if g.needsStreams {
		if g.needsStreamTrait {
			h.WriteString("use serialize::{ReadStream, Stream, WriteStream};\n")
		} else {
			h.WriteString("use serialize::{ReadStream, WriteStream};\n")
		}
		hasUse = true
	}
	if hasUse {
		h.WriteString("\n")
	}
	h.WriteString(g.body.String())
	return []byte(h.String())
}

func (g *gen) emitFile(carriesProtocolId bool) {
	if carriesProtocolId {
		g.pf("// The unit's protocol id — the hash of its wire shape (SPEC §3.1). Two\n")
		g.pf("// sides at the same id speak identical bits; there is no other versioning.\n")
		g.pf("pub const PROTOCOL_ID: u64 = 0x%016x;\n\n", g.unit.ProtocolId)
		g.pf("/// The generated crate's error: the runtime's own errors pass through;\n")
		g.pf("/// Validation is a read rejecting the wire (SPEC §4.3, §4.7).\n")
		g.pf("#[derive(Clone, Copy, PartialEq, Eq, Debug)]\n")
		g.pf("pub enum Error {\n    Stream(serialize::Error),\n    Validation,\n}\n\n")
		g.pf("impl From<serialize::Error> for Error {\n")
		g.pf("    fn from(e: serialize::Error) -> Error {\n        Error::Stream(e)\n    }\n}\n\n")
		g.pf("// serialize.rs 2.0.0 writes are infallible: their Result carries an\n")
		g.pf("// uninhabited error, and `?` on one needs this vacuous conversion.\n")
		g.pf("impl From<core::convert::Infallible> for Error {\n")
		g.pf("    fn from(e: core::convert::Infallible) -> Error {\n        match e {}\n    }\n}\n\n")
		g.pf("pub type Result<T = ()> = core::result::Result<T, Error>;\n\n")
	}

	// declaration order — schema references are order-free and so is the crate
	for _, d := range g.file.Decls {
		switch d := d.(type) {
		case *ir.Const:
			g.emitConst(d)
		case *ir.Enum:
			g.emitEnum(d)
		case *ir.Flags:
			g.emitFlags(d)
		case *ir.Struct:
			g.emitStruct(d)
			g.emitDefaultImpl(d.Name, d.Fields)
			g.emitConstructor(d)
			g.emitStructFunctions(d)
		case *ir.Union:
			g.emitUnion(d)
			g.emitUnionFunctions(d)
		}
	}
}

// emitTagEnum emits a tag newtype: variants live as associated constants so
// the flat crate namespace stays clean, and headroom values remain
// representable (SPEC §6.1 — the enum row's rationale).
func (g *gen) emitTagEnum(name string, members []string, comment string) {
	storage := rustUint(ir.StorageBitsFor(int64(len(members))))
	g.pf("// %s: %s\n", name, comment)
	g.pf("#[repr(transparent)]\n#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]\n")
	g.pf("pub struct %s(pub %s);\n\n", name, storage)
	g.pf("impl %s {\n", name)
	g.pf("    pub const NONE: %s = %s(0);\n", name, name)
	for i, m := range members {
		g.pf("    pub const %s: %s = %s(%d);\n", ir.RustConstName(m), name, name, i+1)
	}
	g.pf("    pub const COUNT: %s = %s(%d); // the declared variant count (SPEC §4.2)\n", name, name, len(members))
	g.pf("    pub const MAX: %s = %s(%d); // the exported extent (SPEC §4.2)\n", name, name, len(members))
	g.pf("}\n\n")

	// the tag enum's name surface is a declared enum's, member for member: a
	// reader logging which message arrived writes enum_name_<tag>(value)
	// whichever enum it is. Nothing on the read or write path calls it.
	snake := ir.RustSnake(name)
	g.pf("/// Debug/log name for any `%s` value, out-of-set included.\n", name)
	g.pf("pub fn enum_name_%s(value: %s) -> &'static str {\n", snake, name)
	g.pf("    match value.0 {\n")
	g.pf("        0 => \"None\",\n")
	for i, m := range members {
		g.pf("        %d => %q,\n", i+1, m)
	}
	g.pf("        _ => \"???\",\n")
	g.pf("    }\n}\n\n")
}

// emitConst emits a schema const: bare integers are i64, bare floats f64, and
// an explicitly-typed schema const carries its declared Rust type (the
// declared type pins the exported type, SPEC §4.2). Consumers cast at the use
// site — Rust has no untyped constants.
func (g *gen) emitConst(d *ir.Const) {
	typ := "i64"
	if d.IsFloat {
		typ = "f64"
	}
	if d.Explicit {
		typ = rustStorage(d.Storage)
	}
	name := ir.RustConstName(d.Name)
	if d.IsFloat {
		g.pf("pub const %s: %s = %s;%s\n\n", name, typ, formatFloat(d.Float), g.foldComment(d.Expr))
		return
	}
	g.pf("pub const %s: %s = %s;%s\n\n", name, typ, g.renderArg(d.Expr, d.Int, typ), g.foldComment(d.Expr))
}

// foldComment returns a trailing comment carrying the schema expression when
// the rendered Rust had to fold it (an E.Max reference has no Rust twin).
func (g *gen) foldComment(e ast.Expr) string {
	if e != nil && ir.ExprHasEnumMax(e) {
		return fmt.Sprintf(" // = %s", ir.RenderExpr(e))
	}
	return ""
}

// allowNonCamel emits the one narrow lint allow the generated code needs:
// generated names are fixed across targets and a declared name can carry an
// underscore Rust's camel-case lint rejects. Emitted only when the name
// actually violates the lint.
func (g *gen) allowNonCamel(name string) {
	if strings.Contains(name, "_") {
		g.pf("#[allow(non_camel_case_types)] // the name is fixed across targets (SPEC §4.8)\n")
	}
}

// emitUnion emits a first-class one-of (SPEC §4.8): the <Name>Type tag
// newtype (the uniform tag surface across targets), then the value as a
// REAL Rust enum — None the default, one tuple variant per arm. Out-of-set
// tags are unrepresentable by construction, so the write side needs no
// guard.
func (g *gen) emitUnion(d *ir.Union) {
	members := make([]string, len(d.Variants))
	for i, v := range d.Variants {
		members[i] = ir.GoExportName(v.Name)
	}
	g.emitTagEnum(d.Name+"Type", members,
		fmt.Sprintf("union %s's tag — None = 0, then each variant in declared order (SPEC §4.8)", d.Name))

	g.pf("// %s — at most one of the arms. The default is None (the empty union);\n", d.Name)
	g.pf("// a read replaces the whole value, so stale-arm semantics cannot arise here.\n")
	g.pf("#[derive(Clone, Copy, PartialEq, Debug, Default)]\n")
	g.pf("pub enum %s {\n", d.Name)
	g.pf("    #[default]\n    None,\n")
	for _, v := range d.Variants {
		if v.Void() {
			// a PAYLOAD-FREE arm is a UNIT variant: no payload to hold (SPEC §4.8)
			g.pf("    %s,\n", ir.GoExportName(v.Name))
			continue
		}
		g.pf("    %s(%s),\n", ir.GoExportName(v.Name), v.Type)
	}
	g.pf("}\n\n")
}

func (g *gen) emitEnum(d *ir.Enum) {
	g.pf("// %s — None = 0 implicit, variants dense from 1, wire range [0, %d] (SPEC §4.2);\n", d.Name, d.Max)
	g.pf("// a newtype because | max = ... headroom makes non-variant values wire-legal\n")
	g.allowNonCamel(d.Name)
	g.pf("#[repr(transparent)]\n#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]\n")
	g.pf("pub struct %s(pub %s);\n\n", d.Name, rustUint(d.StorageBits))
	g.pf("impl %s {\n", d.Name)
	g.pf("    pub const NONE: %s = %s(0);\n", d.Name, d.Name)
	for i, v := range d.Variants {
		g.pf("    pub const %s: %s = %s(%d);\n", ir.RustConstName(v), d.Name, d.Name, i+1)
	}
	g.pf("    pub const COUNT: %s = %s(%d); // the declared variant count (SPEC §4.2)\n", d.Name, d.Name, len(d.Variants))
	g.pf("    pub const MAX: %s = %s(%d); // the exported extent (SPEC §4.2)\n", d.Name, d.Name, d.Max)
	g.pf("}\n\n")

	// Debug/log name for any value, out-of-set included — the counterpart of
	// C++'s and Go's EnumName.
	snake := ir.RustSnake(d.Name)
	g.pf("/// Debug/log name for any `%s` value, out-of-set included.\n", d.Name)
	g.pf("pub fn enum_name_%s(value: %s) -> &'static str {\n", snake, d.Name)
	g.pf("    match value.0 {\n")
	g.pf("        0 => \"None\",\n")
	for i, v := range d.Variants {
		g.pf("        %d => %q,\n", i+1, v)
	}
	g.pf("        _ => \"???\",\n")
	g.pf("    }\n}\n\n")
}

func (g *gen) emitFlags(d *ir.Flags) {
	g.pf("// %s — one bit per variant, consumed as masks; storage u64 in every\n", d.Name)
	g.pf("// target, wire %d bits (SPEC §4.2)\n", d.WireBits)
	g.allowNonCamel(d.Name)
	g.pf("pub type %s = u64;\n\n", d.Name)
	for i, v := range d.Variants {
		g.pf("pub const %s_%s: %s = 1 << %d;\n", ir.RustConstName(d.Name), ir.RustConstName(v), d.Name, i)
	}
	g.pf("pub const %s: i64 = %d; // the declared variant count (SPEC §4.2)\n", ir.RustConstName(d.Name+"Count"), len(d.Variants))
	g.pf("\n")

	snake := ir.RustSnake(d.Name)
	g.pf("/// Debug/log name for bit `i` of `%s` — out-of-range bits name as `\"???\"`.\n", d.Name)
	g.pf("pub fn flag_name_%s(bit: u32) -> &'static str {\n", snake)
	g.pf("    match bit {\n")
	for i, v := range d.Variants {
		g.pf("        %d => %q,\n", i, v)
	}
	g.pf("        _ => \"???\",\n    }\n}\n\n")

	g.pf("/// Renders the set bits of `value` as `\"A|B\"` — `\"0\"` for the empty set,\n")
	g.pf("/// bits past the declared variants as hex.\n")
	g.pf("pub fn flag_names_%s(value: %s) -> String {\n", snake, d.Name)
	g.pf("    let mut names = String::new();\n")
	for i := range d.Variants {
		g.pf("    if value & (1 << %d) != 0 {\n", i)
		g.pf("        if !names.is_empty() {\n            names.push('|');\n        }\n")
		g.pf("        names.push_str(flag_name_%s(%d));\n    }\n", snake, i)
	}
	if len(d.Variants) < 64 { // a 64-variant set has no room for unknown bits
		g.pf("    if value >> %d != 0 {\n", len(d.Variants))
		g.pf("        if !names.is_empty() {\n            names.push('|');\n        }\n")
		g.pf("        names.push_str(&format!(\"{:#x}\", (value >> %d) << %d));\n    }\n", len(d.Variants), len(d.Variants))
	}
	g.pf("    if names.is_empty() {\n        names.push('0');\n    }\n")
	g.pf("    names\n}\n\n")
}

func (g *gen) emitStruct(d *ir.Struct) {
	if len(d.Tags) > 0 {
		g.pf("// type %s [%s] — tags are user-chosen and inert in v1 (SPEC §4.2, Type tags)\n", d.Name, strings.Join(d.Tags, ", "))
	} else {
		g.pf("// type %s\n", d.Name)
	}
	g.allowNonCamel(d.Name)
	// #[repr(C)] is what makes the relocatable-storage promise true here.
	// Copy alone only says the bytes can be duplicated within one build;
	// Rust's default representation may reorder fields and is not stable
	// across builds, so memcpy to a file, an mmap or another process — the
	// things docs/USAGE.md's "The wire" promises of generated storage — would be
	// honoured by accident until the day they were not. It also makes the layout match
	// the C++ struct field for field, which is what "the same data type in
	// five languages" ought to mean.
	g.pf("#[repr(C)]\n")
	g.pf("#[derive(Clone, Copy, PartialEq, Debug)]\n")
	if len(d.Fields) == 0 {
		g.pf("pub struct %s {}\n\n", d.Name)
		return
	}
	g.pf("pub struct %s {\n", d.Name)
	g.emitFields(d.Fields)
	g.pf("}\n\n")
}

// emitDefaultImpl hand-emits the zero form for a struct. It is ALWAYS the
// all-zero value — §5's untaken-branch value and the base new() starts from;
// specified defaults live only in new(), never here (derive(Default) is not
// used: hand emission is uniform across array sizes and nested types).
func (g *gen) emitDefaultImpl(name string, fields []*ir.Field) {
	g.pf("// The zero form (SPEC §5): specified defaults live only in new(), never here.\n")
	g.pf("impl Default for %s {\n", name)
	g.pf("    fn default() -> Self {\n")
	if len(fields) == 0 {
		g.pf("        %s {}\n", name)
	} else {
		g.pf("        %s {\n", name)
		for _, f := range fields {
			g.emitZeroInit(f, "            ")
		}
		g.pf("        }\n")
	}
	g.pf("    }\n}\n\n")
}

// emitZeroInit writes one field's zero-form struct-literal entries.
func (g *gen) emitZeroInit(f *ir.Field, ind string) {
	switch {
	case f.Type.Kind == ir.TString || f.Type.Kind == ir.TBytes:
		g.pf("%s%s: [0; %s],\n", ind, f.Name, g.renderArg(f.Type.SizeExpr, big.NewInt(f.Type.Size), "usize"))
		g.pf("%s%s_length: 0,\n", ind, f.Name)
	case f.Array != ir.ArrayNone:
		g.pf("%s%s: [%s; %s],\n", ind, f.Name, g.zeroScalar(f), g.renderArg(f.ArrayExpr, big.NewInt(f.ArrayBound), "usize"))
		if f.Array == ir.ArrayCounted {
			g.pf("%s%s_count: 0,\n", ind, f.Name)
		}
	default:
		g.pf("%s%s: %s,\n", ind, f.Name, g.zeroScalar(f))
	}
}

// zeroScalar is a field's scalar zero value — the §5 memset twin.
func (g *gen) zeroScalar(f *ir.Field) string {
	switch f.Type.Kind {
	case ir.TBool:
		return "false"
	case ir.TFloat32, ir.TFloat64:
		return "0.0"
	case ir.TNamed:
		switch f.Type.Ref.(type) {
		case *ir.Enum:
			return f.Type.Name + "::NONE"
		case *ir.Flags:
			return "0"
		case *ir.Struct:
			// Default IS the zero form; specified defaults live only in new()
			return f.Type.Name + "::default()"
		case *ir.Union:
			return f.Type.Name + "::None" // zero IS the empty union (SPEC §4.8)
		}
	}
	return "0"
}

// emitConstructor emits X::new() for a struct whose zero value is not its
// declared initial value — i.e. it (or a composed type) carries specified
// defaults. Everything else takes Default::default(), which IS the schema's
// zero rule.
func (g *gen) emitConstructor(d *ir.Struct) {
	if !g.hasDefaults(d) {
		return
	}
	g.pf("impl %s {\n", d.Name)
	g.pf("    // new returns a %s with its specified defaults applied; the plain\n", d.Name)
	g.pf("    // Default::default() is the all-zero form (SPEC §4.2: zero initialization\n")
	g.pf("    // unless a specified default overrides it).\n")
	g.pf("    pub fn new() -> Self {\n")
	g.pf("        let mut value = %s::default();\n", d.Name)
	for _, f := range d.Fields {
		g.emitDefaultInit(f)
	}
	g.pf("        value\n    }\n}\n\n")
}

// hasDefaults reports whether a struct transitively carries a specified default.
func (g *gen) hasDefaults(d *ir.Struct) bool {
	seen := map[string]bool{}
	var walk func(st *ir.Struct) bool
	walk = func(st *ir.Struct) bool {
		if seen[st.Name] {
			return false
		}
		seen[st.Name] = true
		for _, f := range st.Fields {
			if f.HasDefault || f.BornCount() > 0 {
				return true
			}
			if f.Type.Kind == ir.TNamed {
				if inner, ok := f.Type.Ref.(*ir.Struct); ok && walk(inner) {
					return true
				}
			}
		}
		return false
	}
	return walk(d)
}

func (g *gen) emitDefaultInit(f *ir.Field) {
	name := "value." + f.Name
	if n := f.BornCount(); n > 0 {
		// a [A..B] count is born at A, the one wire-legal count a fresh value
		// can carry (SPEC §4.6); the elements below follow their own rule
		g.pf("        %s_count = %d;\n", name, n)
	}
	if f.HasDefault {
		g.pf("        %s = %s;\n", name, g.defaultValue(f))
		return
	}
	if f.Type.Kind != ir.TNamed {
		return
	}
	inner, ok := f.Type.Ref.(*ir.Struct)
	if !ok || !g.hasDefaults(inner) {
		return
	}
	if f.Array != ir.ArrayNone {
		g.pf("        for element in %s.iter_mut() {\n            *element = %s::new();\n        }\n", name, inner.Name)
		return
	}
	g.pf("        %s = %s::new();\n", name, inner.Name)
}

func (g *gen) defaultValue(f *ir.Field) string {
	switch {
	case f.Type.Kind == ir.TBool:
		return fmt.Sprintf("%v", f.DefBool)
	case f.DefVariant != "":
		return f.Type.Name + "::" + ir.RustConstName(f.DefVariant)
	case f.Type.Kind == ir.TFloat32 || f.Type.Kind == ir.TFloat64:
		return formatFloat(f.DefFloat)
	default:
		// the assignment target is the field's own storage type, so a
		// symbolic i64 const must cast down to it
		return g.renderArg(f.DefExpr, f.DefInt, g.rustFieldType(f.Type))
	}
}

func (g *gen) emitFields(fields []*ir.Field) {
	prevGuard := ""
	for _, f := range fields {
		if f.Guard != prevGuard {
			if f.Guard != "" {
				g.pf("\n    // %s — wire branch; storage holds both sides, a read zeroes the\n", f.Guard)
				g.pf("    // untaken side (SPEC §5)\n")
			} else {
				g.pf("\n") // leaving a branch group — separate so membership stays visible
			}
			prevGuard = f.Guard
		}
		g.emitStorageField(f)
	}
}

func (g *gen) emitStorageField(f *ir.Field) {
	typ := g.rustFieldType(f.Type)

	switch {
	case f.Type.Kind == ir.TString:
		g.pf("    pub %s: [u8; %s], // string(%s): max length, used length beside it (SPEC §4.7)\n",
			f.Name, g.renderArg(f.Type.SizeExpr, big.NewInt(f.Type.Size), "usize"), ir.RenderExpr(f.Type.SizeExpr))
		g.pf("    pub %s_length: i32,\n", f.Name)
	case f.Type.Kind == ir.TBytes:
		g.pf("    pub %s: [u8; %s], // bytes(%s): fixed buffer, used length beside it (SPEC §4.7)\n",
			f.Name, g.renderArg(f.Type.SizeExpr, big.NewInt(f.Type.Size), "usize"), ir.RenderExpr(f.Type.SizeExpr))
		g.pf("    pub %s_length: i32,\n", f.Name)
	case f.Array == ir.ArrayFixed:
		g.pf("    pub %s: [%s; %s],%s\n", f.Name, typ, g.renderArg(f.ArrayExpr, big.NewInt(f.ArrayBound), "usize"), g.fieldComment(f))
	case f.Array == ir.ArrayCounted:
		g.pf("    pub %s: [%s; %s], // used count beside it; wire count in [%d, %s]\n",
			f.Name, typ, g.renderArg(f.ArrayExpr, big.NewInt(f.ArrayBound), "usize"), f.ArrayMin, ir.RenderExpr(f.ArrayExpr))
		g.pf("    pub %s_count: i32,\n", f.Name)
	default:
		g.pf("    pub %s: %s,%s\n", f.Name, typ, g.fieldComment(f))
	}
}

func (g *gen) fieldComment(f *ir.Field) string {
	var parts []string
	if f.HasDefault {
		parts = append(parts, fmt.Sprintf("= %s in new() (zero value otherwise)", g.defaultValue(f)))
	}
	if f.HasIntRange {
		parts = append(parts, fmt.Sprintf("wire [%s, %s]", f.IntMin, f.IntMax))
	}
	if f.HasFloatRange {
		parts = append(parts, fmt.Sprintf("compressed float [%s, %s] @ %s",
			formatFloat(f.FMin), formatFloat(f.FMax), formatFloat(f.Resolution)))
	}
	if len(parts) == 0 {
		return ""
	}
	return " // " + strings.Join(parts, "; ")
}

// rustFieldType maps a field type to its Rust storage (SPEC §6.1).
func (g *gen) rustFieldType(t ir.FieldType) string {
	switch t.Kind {
	case ir.TInt:
		// the 128-bit family is native here (i128/u128) — the same arm as
		// every narrower width
		if t.Signed {
			return fmt.Sprintf("i%d", t.Width)
		}
		return fmt.Sprintf("u%d", t.Width)
	case ir.TFixed:
		// raw scaled integer in storage of exactly I+F bits, the type's own
		// signedness — serialize's fixed storage convention (serialize_fixed
		// asserts integer_bits + fraction_bits == T::BITS, and
		// FixedPointStorage is implemented for the unsigned primitives too)
		if t.Signed {
			return rustInt(t.Width)
		}
		return rustUint(t.Width)
	case ir.TBits:
		if t.Width <= 32 {
			return "u32"
		}
		return "u64"
	case ir.TBool:
		return "bool"
	case ir.TFloat32:
		return "f32"
	case ir.TFloat64:
		return "f64"
	case ir.TNamed:
		return t.Name
	}
	return "/* ? */"
}

// rustStorage maps a schema storage name (explicit const types) to Rust.
func rustStorage(s string) string {
	switch s {
	case "int8", "int16", "int32", "int64":
		return "i" + s[len("int"):]
	case "uint8", "uint16", "uint32", "uint64":
		return "u" + s[len("uint"):]
	case "float32":
		return "f32"
	case "float64":
		return "f64"
	}
	return "/* ? */"
}

// renderArg renders an integer expression for a context requiring the Rust
// type `typ`. Folded values and literal-only expressions are emitted as bare
// literals (they infer from context); a symbolic form referencing BARE
// (untyped-in-schema, i64-in-Rust) constants casts to the required type — the
// same renderability rule as the Go target, so both fold identically.
func (g *gen) renderArg(e ast.Expr, folded *big.Int, typ string) string {
	if e == nil || ir.ExprHasEnumMax(e) || !g.renderable(e) || !g.overflowSafe(e) {
		return folded.String()
	}
	if !containsIdent(e) {
		return renderExpr(e)
	}
	s := renderExpr(e)
	if typ == "i64" {
		return s // bare consts are i64 already
	}
	if _, ok := e.(*ast.IdentExpr); ok {
		return s + " as " + typ
	}
	return "(" + s + ") as " + typ
}

// overflowSafe reports whether e can render symbolically without the
// TARGET's arithmetic overflowing on the way to the folded value. Schema
// folding is arbitrary-precision; Rust is not, and rustc DENIES the overflow
// (`arithmetic_overflow` is deny by default), so a doubled unary minus over
// an INT64_MIN constant renders symbolically as -(-FLOOR_LIMIT) — an
// intermediate one past i64::MAX that is a build break even though the outer
// minus brings the value home (the C and C# backends' carrierEval
// already folds this shape). A symbolic rendering evaluates in i64: every
// renderable constant is a bare schema const — i64 in Rust — and the
// literals beside one infer i64 through the operations, so the carrier is
// uniform where C's is split. Anything unprovable folds — folding is always
// correct, symbolic rendering is the luxury; for the shapes this gate
// newly folds, the folded text is the spelling generated Rust already
// compiles for the same values.
func (g *gen) overflowSafe(e ast.Expr) bool {
	_, ok := g.i64Eval(e)
	return ok
}

// i64Eval returns e's folded value and whether every subexpression's value
// fits the i64 arithmetic a symbolic Rust rendering evaluates in. A bare
// IntLit past i64::MAX also reports unsafe: it renders no better than its
// fold (the text is identical), and admitting it would let an enclosing
// operation evaluate a too-wide operand.
func (g *gen) i64Eval(e ast.Expr) (*big.Int, bool) {
	switch e := e.(type) {
	case *ast.IntLit:
		return e.Value, e.Value.IsInt64()
	case *ast.IdentExpr:
		c, ok := g.unit.Consts[e.Name]
		if !ok || c.IsFloat || c.Int == nil || !c.Int.IsInt64() {
			return nil, false
		}
		return c.Int, true
	case *ast.ParenExpr:
		return g.i64Eval(e.X)
	case *ast.UnaryExpr:
		v, ok := g.i64Eval(e.X)
		if !ok {
			return nil, false
		}
		nv := new(big.Int).Neg(v)
		return nv, nv.IsInt64()
	case *ast.BinaryExpr:
		x, ok := g.i64Eval(e.X)
		if !ok {
			return nil, false
		}
		y, ok := g.i64Eval(e.Y)
		if !ok {
			return nil, false
		}
		v := new(big.Int)
		switch e.Op {
		case "+":
			v.Add(x, y)
		case "-":
			v.Sub(x, y)
		case "*":
			v.Mul(x, y)
		case "/":
			if y.Sign() == 0 {
				return nil, false
			}
			v.Quo(x, y) // truncation toward zero, as Rust divides
		case "%":
			if y.Sign() == 0 {
				return nil, false
			}
			v.Rem(x, y)
		default:
			return nil, false
		}
		return v, v.IsInt64()
	}
	return nil, false
}

// renderable: every referenced constant must be a BARE (untyped) integer
// schema const — a typed const is a typed Rust const, which forces `as`
// casts at use sites of other types.
func (g *gen) renderable(e ast.Expr) bool {
	for _, name := range ir.ExprConsts(e) {
		c, ok := g.unit.Consts[name]
		if !ok || c.IsFloat || c.Explicit {
			return false
		}
	}
	return true
}

// renderExpr renders an expression in Rust form: constants are spelled
// SCREAMING_SNAKE, the way the Rust target declares them.
func renderExpr(e ast.Expr) string {
	return ir.RenderExprIdent(e, ir.RustConstName)
}

// containsIdent reports whether e references any named constant — a literal
// expression renders no better than its folded value.
func containsIdent(e ast.Expr) bool {
	return len(ir.ExprConsts(e)) > 0
}

func rustInt(width int) string  { return fmt.Sprintf("i%d", width) }
func rustUint(width int) string { return fmt.Sprintf("u%d", width) }

// signedStorageBounds is the | min, max domain of an iN storage type.
func signedStorageBounds(width int) (lo, hi *big.Int) {
	lo = new(big.Int).Neg(new(big.Int).Lsh(big.NewInt(1), uint(width-1)))
	hi = new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), uint(width-1)), big.NewInt(1))
	return
}

// rustIntLit renders a signed literal with its width suffix; the two's
// complement minimum has no direct literal form in Rust (the unary minus
// applies after an overflowing parse), so it renders as the type's MIN.
func rustIntLit(v *big.Int, width int) string {
	min, _ := signedStorageBounds(width)
	if v.Cmp(min) == 0 {
		return fmt.Sprintf("i%d::MIN", width)
	}
	return fmt.Sprintf("%s_i%d", v, width)
}

func formatFloat(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s
}

// formatFloat32 renders a float literal for an f32 argument position with the
// explicit suffix, so the type never rests on inference — at FLOAT32
// precision: the shortest literal that parses to exactly float32(v) in every
// target language, the same narrowing ir.CompressedFloatBits computes widths
// with, so all five targets and the advertised MaxBits agree even at f32
// rounding ties.
func formatFloat32(v float64) string {
	s := strconv.FormatFloat(v, 'g', -1, 32)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	}
	return s + "_f32"
}
