// The TYPE DECLARATIONS: Base.d.ts beside Base.js and BaseFlat.d.ts beside
// BaseFlat.js, so a TypeScript project, or a JavaScript one checked with
// `tsc --checkJs`, types every generated name without a hand-written shim.
// The declarations are emitted from the same IR walk as the modules and state
// exactly what the modules export: the classes with their storage members,
// the constants, the enum and tag objects, and every function's parameters.
//
// Numbers and BigInts follow the module's value-domain seam (Number at 32 bits
// or fewer, BigInt past it and for flags). An enum field is typed by its
// enum's value union, so assigning an undeclared ordinal is a type error. The
// stream parameter is typed structurally (SerializeStream): the runtime
// tier calls only serialize.js methods on it, and the generated modules
// import nothing from the runtime.
package js

import (
	"fmt"
	"sort"
	"strings"

	"github.com/mas-bandwidth/schema/v2/ir"
)

// dgen emits one declaration file.
type dgen struct {
	unit    *ir.Unit
	file    *ir.File
	body    strings.Builder
	imports map[string]map[string]bool // base -> type names
	stream  bool                       // the SerializeStream interface is named
}

func (g *dgen) pf(format string, args ...any) { fmt.Fprintf(&g.body, format, args...) }

// typeRef names a declaration's TYPE, importing it when it lives in another
// file. A table's classes live in the table modules, which carry no
// declarations, so a table reference is the structural `object`.
func (g *dgen) typeRef(name string) string {
	if g.unit.Tables[name] != nil {
		return "object"
	}
	base, ok := g.unit.DeclFile[name]
	if !ok {
		return "object"
	}
	if base != g.file.Base {
		g.need(base, name)
	}
	return name
}

func (g *dgen) need(base, name string) {
	set := g.imports[base]
	if set == nil {
		set = map[string]bool{}
		g.imports[base] = set
	}
	set[name] = true
}

func (g *dgen) header(h *strings.Builder, base string) {
	fmt.Fprintf(h, "// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", g.file.Base)
	h.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
	h.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
	h.WriteString("// AGPL-3.0, its output is not.\n")
	fmt.Fprintf(h, "// package %s — protocol id 0x%016x\n", g.unit.Package, g.unit.ProtocolId)
	fmt.Fprintf(h, "//\n// The TypeScript declarations of %s.js (SPEC §6.3).\n\n", base)
	bases := make([]string, 0, len(g.imports))
	for b := range g.imports {
		bases = append(bases, b)
	}
	sort.Strings(bases)
	for _, b := range bases {
		names := make([]string, 0, len(g.imports[b]))
		for n := range g.imports[b] {
			names = append(names, n)
		}
		sort.Strings(names)
		fmt.Fprintf(h, "import type { %s } from \"./%s.js\";\n", strings.Join(names, ", "), b)
	}
	if len(bases) > 0 {
		h.WriteString("\n")
	}
	if g.stream {
		h.WriteString("// The serialize.js stream the runtime-tier functions take: WriteStream,\n")
		h.WriteString("// ReadStream or MeasureStream, typed by the methods the generated code calls.\n")
		h.WriteString("interface SerializeStream {\n")
		for _, m := range []string{
			"serializeBits(ref: { value: number }, bits: number): boolean;",
			"serializeBits64(ref: { value: bigint }, bits: number): boolean;",
			"serializeInt(ref: { value: number }, min: number, max: number): boolean;",
			"serializeInt64(ref: { value: bigint }, min: bigint, max: bigint): boolean;",
			"serializeInt128(ref: { value: bigint }, min: bigint, max: bigint): boolean;",
			"serializeUint128(ref: { value: bigint }): boolean;",
			"serializeFixed(ref: { value: number | bigint }, integerBits: number, fractionBits: number, min: number | bigint, max: number | bigint): boolean;",
			"serializeBool(ref: { value: boolean }): boolean;",
			"serializeFloat(ref: { value: number }): boolean;",
			"serializeDouble(ref: { value: number }): boolean;",
			"serializeCompressedFloat(ref: { value: number }, min: number, max: number, resolution: number): boolean;",
			"serializeBytes(data: Uint8Array): boolean;",
			"serializeAlign(): boolean;",
		} {
			fmt.Fprintf(h, "  %s\n", m)
		}
		h.WriteString("}\n\n")
	}
}

// generateDecls returns Base.d.ts and, where the file has a flat surface,
// BaseFlat.d.ts.
func generateDecls(u *ir.Unit) map[string][]byte {
	out := map[string][]byte{}
	home := ir.ProtocolIdHome(u)
	for _, f := range u.Files {
		g := &dgen{unit: u, file: f, imports: map[string]map[string]bool{}}
		g.emitFile(f.Base == home)
		var h strings.Builder
		g.header(&h, f.Base)
		h.WriteString(g.body.String())
		out[f.Base+".d.ts"] = []byte(h.String())
		if flatFileHasSurface(f) {
			fg := &dgen{unit: u, file: f, imports: map[string]map[string]bool{}}
			fg.emitFlat()
			var fh strings.Builder
			fg.header(&fh, f.Base+"Flat")
			fh.WriteString(fg.body.String())
			out[f.Base+"Flat.d.ts"] = []byte(fh.String())
		}
	}
	return out
}

func (g *dgen) emitFile(home bool) {
	if home {
		g.pf("export declare const ProtocolId: bigint;\n\n")
	}
	for _, d := range ir.EmissionOrder(g.file) {
		switch d := d.(type) {
		case *ir.Const:
			g.emitConst(d)
		case *ir.Enum:
			g.emitEnumObject(d.Name, d.Variants)
			g.pf("export declare const %sMax: %d;\n", d.Name, d.Max)
			g.pf("export declare function EnumName%s(value: number): string;\n\n", d.Name)
		case *ir.Flags:
			for _, v := range d.Variants {
				g.pf("export declare const %s%s: bigint;\n", d.Name, v)
			}
			g.pf("export declare const %sCount: %d;\n", d.Name, len(d.Variants))
			g.pf("export declare function FlagName%s(bit: number): string;\n", d.Name)
			g.pf("export declare function FlagNames%s(value: bigint): string;\n\n", d.Name)
		case *ir.Struct:
			g.emitStruct(d)
		case *ir.Union:
			g.emitUnion(d, true)
		}
	}
	for _, un := range g.file.TableUnions {
		g.emitUnion(un, false)
	}
}

func (g *dgen) emitConst(d *ir.Const) {
	switch {
	case d.IsFloat:
		g.pf("export declare const %s: number;\n\n", d.Name)
	case constIsBig(d):
		g.pf("export declare const %s: bigint;\n\n", d.Name)
	default:
		g.pf("export declare const %s: number;\n\n", d.Name)
	}
}

// emitEnumObject declares a frozen variant object and, under the same name,
// the type of its values: `Team` is both the object and the union 0 | 1 | 2.
func (g *dgen) emitEnumObject(name string, variants []string) {
	g.pf("export declare const %s: Readonly<{\n  None: 0;\n", name)
	for i, v := range variants {
		g.pf("  %s: %d;\n", v, i+1)
	}
	g.pf("}>;\n")
	g.pf("export type %s = (typeof %s)[keyof typeof %s];\n", name, name, name)
}

// scalarType is a scalar field's storage type.
func (g *dgen) scalarType(t ir.FieldType) string {
	switch t.Kind {
	case ir.TBool:
		return "boolean"
	case ir.TNamed:
		switch t.Ref.(type) {
		case *ir.Enum:
			return g.typeRef(t.Name)
		case *ir.Flags:
			return "bigint"
		case *ir.Struct, *ir.Union:
			return g.typeRef(t.Name)
		}
		return "object"
	}
	if isBigStorage(t) {
		return "bigint"
	}
	return "number"
}

// emitMembers declares a field's storage, member for member, exactly as the
// constructor lays it down (emitStorageField).
func (g *dgen) emitMembers(f *ir.Field, ind string) {
	name := MemberName(f.Name)
	switch {
	case f.Type.Kind == ir.TWString:
		g.pf("%s%s: Uint16Array;\n%s%sLength: number;\n", ind, name, ind, name)
	case f.Type.Kind == ir.TString || f.Type.Kind == ir.TBytes:
		g.pf("%s%s: Uint8Array;\n%s%sLength: number;\n", ind, name, ind, name)
	case f.Array != ir.ArrayNone:
		switch {
		case f.Type.Kind == ir.TNamed && isClassRef(f.Type.Ref):
			g.pf("%s%s: %s[];\n", ind, name, g.typeRef(f.Type.Name))
		case isByteElem(f.Type):
			g.pf("%s%s: Uint8Array;\n", ind, name)
		default:
			g.pf("%s%s: %s[];\n", ind, name, g.scalarType(f.Type))
		}
		if f.Array == ir.ArrayCounted {
			g.pf("%s%sCount: number;\n", ind, name)
		}
	default:
		g.pf("%s%s: %s;\n", ind, name, g.scalarType(f.Type))
	}
}

func (g *dgen) emitStruct(st *ir.Struct) {
	g.pf("%s", ir.DocComment(st.Doc, "", "//"))
	g.pf("export declare class %s {\n", st.Name)
	for _, f := range st.Fields {
		g.pf("%s", ir.DocComment(f.Doc, "  ", "//"))
		g.emitMembers(f, "  ")
	}
	g.pf("}\n")
	g.pf("export declare const %sMaxBits: number;\n", st.Name)
	g.pf("export declare const %sMaxBytes: number;\n", st.Name)
	// a parameter the empty type's functions ignore is optional, so a caller
	// may pass it or not
	param := "value: " + st.Name
	stream := "stream: SerializeStream, "
	if len(st.Fields) == 0 {
		param = "value?: " + st.Name
	}
	g.pf("export declare function Init%s(%s): void;\n", st.Name, param)
	g.pf("export declare function Zero%s(%s): void;\n", st.Name, param)
	if len(st.Items) == 0 {
		stream, param = "stream?: SerializeStream, ", "value?: "+st.Name
	}
	g.stream = true
	g.pf("export declare function Write%s(%s%s): boolean;\n", st.Name, stream, param)
	g.pf("export declare function Read%s(%s%s): boolean;\n\n", st.Name, stream, param)
}

// emitUnion declares the tag object and the storage class; a packet union
// adds its bounds and functions, a table-closure union has none.
func (g *dgen) emitUnion(un *ir.Union, packet bool) {
	members := make([]string, len(un.Variants))
	for i, v := range un.Variants {
		members[i] = ir.GoExportName(v.Name)
	}
	g.emitEnumObject(un.Name+"Type", members)
	g.pf("export declare const %sTypeMax: %d;\n", un.Name, len(members))
	g.pf("export declare function EnumName%sType(value: number): string;\n", un.Name)
	g.pf("%s", ir.DocComment(un.Doc, "", "//"))
	g.pf("export declare class %s {\n  type: %sType;\n", un.Name, un.Name)
	for _, v := range un.Variants {
		switch {
		case v.Void():
		case v.Ref == nil:
			g.emitMembers(v.F, "  ")
		default:
			g.pf("  %s: %s;\n", MemberName(v.Name), g.typeRef(v.Type))
		}
	}
	g.pf("}\n")
	if !packet {
		g.pf("\n")
		return
	}
	g.stream = true
	g.pf("export declare const %sMaxBits: number;\n", un.Name)
	g.pf("export declare const %sMaxBytes: number;\n", un.Name)
	g.pf("export declare function Zero%s(value: %s): void;\n", un.Name, un.Name)
	g.pf("export declare function Write%s(stream: SerializeStream, value: %s): boolean;\n", un.Name, un.Name)
	g.pf("export declare function Read%s(stream: SerializeStream, value: %s): boolean;\n\n", un.Name, un.Name)
}

// emitFlat declares BaseFlat.js: the read slack and one codec pair per type
// and union, over the classes the runtime-tier module declares.
func (g *dgen) emitFlat() {
	g.pf("export declare const FlatReadSlack: 8;\n\n")
	for _, d := range ir.EmissionOrder(g.file) {
		var name string
		switch d := d.(type) {
		case *ir.Struct:
			name = d.Name
		case *ir.Union:
			name = d.Name
		default:
			continue
		}
		g.need(g.file.Base, name)
		g.pf("export declare function Write%sFlat(view: DataView, value: %s): number;\n", name, name)
		g.pf("export declare function Read%sFlat(view: DataView, numBits: number, value: %s): boolean;\n\n", name, name)
	}
}
