// TestSkeletonFixture is the one fixture `schema new-leg goose` laid down,
// kept as the smallest unit: a declaration-free unit generates a module that
// names its package and protocol id, and that module compiles and runs under
// the pinned compiler.
func TestSkeletonFixture(t *testing.T) {
	t.Parallel()
	u := &ir.Unit{
		Package:    "hello",
		ProtocolId: 0x11,
		Files:      []*ir.File{{Base: "Hello"}},
		DeclFile:   map[string]string{},
	}
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	name := "Hello." + ext
	got, ok := files[name]
	if !ok {
		t.Fatalf("Generate omitted %s; emitted %v", name, keysOf(files))
	}
	text := string(got)
	for _, want := range []string{
		"Code generated by the schema compiler from Hello.schema",
		"package hello",
		"namespace hello;",
		"let ProtocolId: u64 = 0x0000000000000011;",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("missing %q in:\n%s", want, text)
		}
	}
	dir := t.TempDir()
	writeAll(t, dir, files)
	writeFile(t, dir, "main.goose", "import .Hello;\nfn main() {\n    assert(hello::ProtocolId == 17);\n    print(\"ok\");\n}\n")
	if out := string(gooserun.Run(t, dir, "main.goose", nil)); out != "ok\n" {
		t.Fatalf("fixture printed %q", out)
	}
}

// TestGooseTypesConstructAtTheirDefaults generates examples/*.schema into a
// temp dir, compiles every module under the pinned compiler, constructs
// every type and union, and checks ArmDefaults the way test/go/main.go's
// testDefaultArmInitialization checks its constructors: a fresh DefaultArm
// carries count zero and BOTH backing entries at ProbeConfig's defaults
// (retries -1, preferred Railgun), and a fresh DefaultChoice is the empty
// union with both arms pre-allocated at their defaults (docs/PORT-GOOSE.md,
// THE TYPE MAPPING; SPEC §5, §4.8). The enum and tag constants carry Max
// and no Count (SPEC §4.2: Max is an enum's only exported number).
func TestGooseTypesConstructAtTheirDefaults(t *testing.T) {
	t.Parallel()
	u := unitFromDir(t, filepath.Join("..", "..", "..", "examples"))
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	writeAll(t, dir, files)
	ns := Namespace(u)

	var main strings.Builder
	for _, f := range u.Files {
		fmt.Fprintf(&main, "import .%s;\n", f.Base)
	}
	main.WriteString("\nvar bad: i64 = 0;\nfn check(ok: bool, what: const u8[:]) { if !ok { print(\"BAD \", what); bad += 1; } }\n\nfn main() {\n    var n = 0;\n")
	var constructed []string
	for _, f := range u.Files {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ir.Struct:
				fmt.Fprintf(&main, "    { let v = %s::New%s(); n += 1; }\n", ns, d.Name)
				constructed = append(constructed, d.Name)
			case *ir.Union:
				fmt.Fprintf(&main, "    { let v = %s::New%s(); check(v.Type == %s::%sTypeNone, %q); n += 1; }\n", ns, d.Name, ns, d.Name, d.Name+" is born None")
				constructed = append(constructed, d.Name)
			}
		}
	}
	main.WriteString(strings.ReplaceAll(`
    let arm = NS::NewDefaultArm();
    check(arm.EntriesCount == 0, "DefaultArm constructor count is zero");
    check(arm.Entries.len == 2, "DefaultArm pre-allocates both backing entries");
    for entry in arm.Entries {
        check(entry.Retries == -1 && entry.Preferred == NS::WeaponRailgun, "DefaultArm constructor initializes both backing entries");
    }
    check(arm.Marker == 0, "marker is born zero");
    let choice = NS::NewDefaultChoice();
    check(choice.Type == NS::DefaultChoiceTypeNone, "the empty union");
    for a in [choice.First, choice.Second] {
        check(a.EntriesCount == 0 && a.Entries.len == 2, "each arm is a fresh DefaultArm");
        for entry in a.Entries {
            check(entry.Retries == -1 && entry.Preferred == NS::WeaponRailgun, "each arm's entries are at their defaults");
        }
    }
    check(NS::DefaultChoiceTypeMax == 2, "tag Max");
    let bulk = NS::NewDefaultBulkChoice();
    check(bulk.First.Data.len == 2 && bulk.First.DataLength == 0, "bytes(2) is a 2-byte array, used length zero");
    check(NS::WeaponMax == 15, "enum Max is the widened extent");
    check(NS::EnumNameWeapon(NS::WeaponRailgun) == "Railgun" && NS::EnumNameWeapon(14) == "???", "EnumName names a variant, ??? past them");
    print("constructed ", n, " bad ", bad);
}
`, "NS::", ns+"::"))
	writeFile(t, dir, "main.goose", main.String())
	out := string(gooserun.Run(t, dir, "main.goose", nil))
	if want := fmt.Sprintf("constructed %d bad 0\n", len(constructed)); out != want {
		t.Fatalf("main.goose printed %q, want %q", out, want)
	}
	if len(constructed) == 0 {
		t.Fatal("examples/ declared no types")
	}
}

// TestGooseEveryScalarFieldIsBornAtItsIRDefault checks every scalar field of
// every examples/ type against the IR, not hand-picked values: a bool is its
// default or false, an integer of 64 bits or fewer its DefInt or 0, a float32
// float32(DefFloat), a float64 DefFloat, an enum its default variant or None
// (SPEC §5; docs/PORT-GOOSE.md, THE TYPE MAPPING). The expected literals come
// from the IR here, never from the emitter; the program runs under --debug.
func TestGooseEveryScalarFieldIsBornAtItsIRDefault(t *testing.T) {
	t.Parallel()
	u := unitFromDir(t, filepath.Join("..", "..", "..", "examples"))
	files, err := Generate(u)
	if err != nil {
		t.Fatal(err)
	}
	ns := Namespace(u)
	var main strings.Builder
	for _, f := range u.Files {
		fmt.Fprintf(&main, "import .%s;\n", f.Base)
	}
	main.WriteString("\nvar bad: i64 = 0;\nvar checked: i64 = 0;\nfn check(ok: bool, what: const u8[:]) { checked += 1; if !ok { print(\"BAD \", what); bad += 1; } }\n\nfn main() {\n")
	n := 0
	for _, file := range u.Files {
		for _, d := range file.Decls {
			s, ok := d.(*ir.Struct)
			if !ok {
				continue
			}
			for _, f := range s.Fields {
				if f.Array != ir.ArrayNone || f.IsMap() || f.Type.Pointer || f.Type.Optional {
					continue
				}
				want := irDefault(ns, f)
				if want == "" {
					continue
				}
				slot := ir.GoExportName(f.Name)
				fmt.Fprintf(&main, "    check(%s::New%s().%s == %s, %q);\n", ns, s.Name, slot, want, s.Name+"."+slot+" == "+want)
				n++
			}
		}
	}
	main.WriteString("    print(\"checked \", checked, \" bad \", bad);\n}\n")
	if n == 0 {
		t.Fatal("examples/ declared no scalar fields")
	}
	dir := t.TempDir()
	writeAll(t, dir, files)
	writeFile(t, dir, "main.goose", main.String())
	if out, want := string(gooserun.RunDebug(t, dir, "main.goose", nil)), fmt.Sprintf("checked %d bad 0\n", n); out != want {
		t.Fatalf("main.goose printed %q, want %q", out, want)
	}
}

// irDefault is the Goose literal a scalar field is born at, computed from the
// IR alone; "" for a kind this check does not cover (128-bit integers,
// flags, strings, composites, non-finite floats).
func irDefault(ns string, f *ir.Field) string {
	t := f.Type
	switch t.Kind {
	case ir.TBool:
		return strconv.FormatBool(f.HasDefault && f.DefBool)
	case ir.TInt, ir.TBits, ir.TFixed:
		if t.Width > 64 {
			return ""
		}
		if f.HasDefault && f.DefInt != nil {
			if f.DefInt.Cmp(big.NewInt(math.MinInt64)) == 0 {
				return ""
			}
			return "(" + f.DefInt.String() + ")"
		}
		return "0"
	case ir.TFloat32, ir.TFloat64:
		v := 0.0
		if f.HasDefault {
			v = f.DefFloat
		}
		if t.Kind == ir.TFloat32 {
			v = float64(float32(v))
		}
		if math.IsInf(v, 0) || math.IsNaN(v) {
			return ""
		}
		return "(" + strconv.FormatFloat(v, 'f', -1, 64) + ")"
	case ir.TNamed:
		e, ok := t.Ref.(*ir.Enum)
		if !ok {
			return ""
		}
		if !f.HasDefault {
			return ns + "::" + e.Name + "None"
		}
		return ns + "::" + e.Name + f.DefVariant
	}
	return ""
}

// TestGooseRefusesByName holds the unit refusals of docs/PORT-GOOSE.md, THE
// RUNTIME LAYOUT: a package that is a Goose scalar type name (the namespace
// every module declares into) and a name declared twice in that namespace (an
// enum's EnumName<E> beside a type spelled the same, which the checker's
// collision table leaves to the port) are refused by name. A
// package that is a Goose keyword never reaches the port: the checker's one
// reserved-word table refuses it first (SPEC §4.6), so the port's own refusal
// is held on the names that table leaves to it, the scalar types, std and main.
func TestGooseRefusesByName(t *testing.T) {
	t.Parallel()
	for _, c := range []struct{ src, want string }{
		{"package u8\n\ntype T\n{\n    x uint8\n}\n", `package "u8" is reserved in Goose`},
		{"package p\n\nenum E\n{\n    Alpha\n}\n\ntype EnumNameE\n{\n    x uint8\n}\n", "declares EnumNameE in namespace p, which"},
	} {
		dir := t.TempDir()
		writeFile(t, dir, "E.schema", c.src)
		_, err := Generate(unitFromDir(t, dir))
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("Generate(%q) = %v, want a refusal naming %q", c.src, err, c.want)
		}
	}
}

func unitFromDir(t *testing.T, dir string) *ir.Unit {
	t.Helper()
	paths, err := filepath.Glob(filepath.Join(dir, "*.schema"))
	if err != nil || len(paths) == 0 {
		t.Fatalf("no schema files under %s: %v", dir, err)
	}
	sort.Strings(paths)
	var files []check.SourceFile
	for _, p := range paths {
		src, err := os.ReadFile(p)
		if err != nil {
			t.Fatal(err)
		}
		name := filepath.Base(p)
		tree, errs := parser.Parse(name, src)
		if len(errs) != 0 {
			t.Fatalf("parse %s: %v", name, errs)
		}
		files = append(files, check.SourceFile{Path: p, Name: name, Base: strings.TrimSuffix(name, ".schema"), Bytes: src, AST: tree})
	}
	u, errs := check.Unit(files)
	if len(errs) != 0 {
		t.Fatalf("check: %v", errs)
	}
	return u
}

func writeAll(t *testing.T, dir string, files map[string][]byte) {
	t.Helper()
	for name, data := range files {
		writeFile(t, dir, name, string(data))
	}
}

func writeFile(t *testing.T, dir, name, data string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(data), 0o644); err != nil {
		t.Fatal(err)
	}
}

func keysOf(files map[string][]byte) []string {
	out := make([]string, 0, len(files))
	for k := range files {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
