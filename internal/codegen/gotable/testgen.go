// The bounded seed corpus of §16.11: no seed over tgSeedCeiling bytes (a longer
// sample is trimmed to its first and last half of it), at most tgSeedMutations
// mutation seeds per target, and tgSeedEnds bytes at each end of a sample
// mutated before the stride between.
const (
	tgSeedCeiling   = 4096
	tgSeedMutations = 256
	tgSeedEnds      = 16
)

// testgenFuzzHelpers writes the file's shared fuzz helpers, named for the unit
// file so two generated test files of one package never collide (SPEC-TABLES
// §16.11, the fuzz targets): the named-reason test, the input's spelling in a
// failure, and the bounded seed corpus.
func testgenFuzzHelpers(b *strings.Builder, base string) {
	fmt.Fprintf(b, "\n// fuzz%sNamed reports whether a refusal names its reason (SPEC-TABLES §16.11):\n// a typed reason other than ok, a missing required field or a build version\n// mismatch. A bare failure is a defect of the reader.\n", base)
	fmt.Fprintf(b, "func fuzz%sNamed(err error) bool {\n", base)
	b.WriteString("\tvar reason TableRefuseReason\n\tif errors.As(err, &reason) {\n\t\treturn reason != TableRefuseOk && reason.Error() != \"invalid refusal reason\"\n\t}\n")
	b.WriteString("\tvar missing TableMissingRequired\n\tvar build TableBuildVersionMismatch\n\treturn errors.As(err, &missing) || errors.As(err, &build)\n}\n")
	fmt.Fprintf(b, "\n// fuzz%sSilent reports whether a tolerant read's report is silent (SPEC-TABLES\n// §4.1): the whole report at its zero value, as a sample's read must be.\n", base)
	fmt.Fprintf(b, "func fuzz%sSilent(r *TableReport) bool {\n", base)
	b.WriteString("\treturn *r == (TableReport{})\n}\n")
	fmt.Fprintf(b, "\n// fuzz%sInput spells a failing input: its length, its flip position when it is\n// a flip, and its first 256 bytes in hex.\n", base)
	fmt.Fprintf(b, "func fuzz%sInput(data []byte, at int) string {\n", base)
	b.WriteString("\ts := strconv.Itoa(len(data)) + \" bytes\"\n\tif at >= 0 {\n\t\ts += \", flipped at byte \" + strconv.Itoa(at)\n\t}\n")
	b.WriteString("\tif len(data) > 256 {\n\t\treturn s + \", \" + hex.EncodeToString(data[:256]) + \"...\"\n\t}\n\treturn s + \", \" + hex.EncodeToString(data)\n}\n")
	fmt.Fprintf(b, `
// fuzz%[1]sBound turns a target's sample encodings into its bounded, deterministic
// seed corpus (SPEC-TABLES §16.11). A sample over %[2]d bytes is trimmed, for
// seeding only, to a representative %[2]d: its first %[3]d bytes and its last %[3]d
// (the round-trip tests keep the full sample). Every trimmed sample is a seed.
// Then at most %[4]d mutations: %[5]d byte positions are shared out round robin
// across the samples, no sample taking more positions than it has bytes, and
// each position takes each of the values 0x00, 0x01 and 0xff. Within a sample
// the positions are its first %[6]d and last %[6]d bytes, then an even fixed
// stride over the bytes between them, stopping at the sample's share.
func fuzz%[1]sBound(samples [][]byte) (seeds [][]byte, mutations int) {
	trimmed := make([][]byte, len(samples))
	for i, s := range samples {
		trimmed[i] = s
		if len(s) > %[2]d {
			trimmed[i] = append(append([]byte{}, s[:%[3]d]...), s[len(s)-%[3]d:]...)
		}
	}
	seeds = append(seeds, trimmed...)
	share := make([]int, len(trimmed))
	for left := %[5]d; left > 0; {
		gave := false
		for i, s := range trimmed {
			if left > 0 && share[i] < len(s) {
				share[i]++
				left--
				gave = true
			}
		}
		if !gave {
			break
		}
	}
	for i, s := range trimmed {
		var at []int
		if p, l := share[i], len(s); p >= l {
			for k := 0; k < l; k++ {
				at = append(at, k)
			}
		} else {
			head := min(%[6]d, (p+1)/2)
			tail := min(%[6]d, p-head)
			for k := 0; k < head; k++ {
				at = append(at, k)
			}
			for k := 0; k < tail; k++ {
				at = append(at, l-1-k)
			}
			if m := p - head - tail; m > 0 {
				stride := (l - %[7]d) / (m + 1)
				for k := 1; k <= m; k++ {
					at = append(at, %[6]d+stride*k)
				}
			}
		}
		for _, a := range at {
			for _, c := range []byte{0x00, 0x01, 0xff} {
				m := bytes.Clone(s)
				m[a] = c
				seeds = append(seeds, m)
				mutations++
			}
		}
	}
	return seeds, mutations
}

// fuzz%[1]sSeed adds a target's bounded seed corpus, fuzz%[1]sBound of its sample
// encodings, to its corpus (SPEC-TABLES §16.11). The bound is the seeds' only:
// at fuzz time the fuzzer explores past them.
func fuzz%[1]sSeed(f *testing.F, samples [][]byte) {
	f.Helper()
	seeds, _ := fuzz%[1]sBound(samples)
	for _, seed := range seeds {
		f.Add(seed)
	}
}
`, base, tgSeedCeiling, tgSeedCeiling/2, tgSeedMutations, tgSeedMutations/3, tgSeedEnds, 2*tgSeedEnds)
}

// testgenFuzz writes the table's seeds and its three fuzz targets,
// Fuzz<Name>Wire, Fuzz<Name>Text and Fuzz<Name>Json (SPEC-TABLES §16.11, the
// fuzz targets): every input never panics, and is refused by a named reason,
// re-encodes to exactly itself, or reads with a report that is not silent.
func testgenFuzz(b *strings.Builder, base string, st *ir.Struct, variable bool, samples []tgSample) {
	n := st.Name
	fmt.Fprintf(b, "\n// fuzz%sSeeds builds %s's seeds (SPEC-TABLES §16.11): every sample's wire,\n// base64 text and JSON text, as the writers spell them.\n", n, n)
	fmt.Fprintf(b, "func fuzz%sSeeds(tb testing.TB) (wire, text, json [][]byte) {\n\ttb.Helper()\n\tfor _, sample := range []string{\n", n)
	for _, s := range samples {
		fmt.Fprintf(b, "\t\t%s, // %s\n", s.expr, s.name)
	}
	b.WriteString("\t} {\n\t\tvar r TableReport\n")
	if variable {
		fmt.Fprintf(b, "\t\tvar sb %sBuilder\n\t\tif !sb.Init() {\n\t\t\ttb.Fatal(\"builder init\")\n\t\t}\n", n)
		fmt.Fprintf(b, "\t\tif !%sFromJson(&sb, []byte(sample), &r) || r != (TableReport{}) || !sb.Lock() {\n\t\t\ttb.Fatalf(\"FromJson of a sample: report %%+v\", r)\n\t\t}\n\t\tv := sb.AsConst()\n", n)
	} else {
		fmt.Fprintf(b, "\t\tv := new(%s)\n\t\tif !%sFromJson(v, []byte(sample), &r) || r != (TableReport{}) {\n\t\t\ttb.Fatalf(\"FromJson of a sample: report %%+v\", r)\n\t\t}\n", n, n)
	}
	fmt.Fprintf(b, "\t\tw := make([]byte, max(%sMeasure(v), 0))\n\t\tif %sSave(v, w) != int64(len(w)) || len(w) == 0 {\n\t\t\ttb.Fatal(\"Save of a sample\")\n\t\t}\n", n, n)
	fmt.Fprintf(b, "\t\tx, err := %sSaveText(v)\n\t\tif err != nil {\n\t\t\ttb.Fatalf(\"SaveText of a sample: %%v\", err)\n\t\t}\n", n)
	fmt.Fprintf(b, "\t\tj := make([]byte, max(%sToJsonMeasure(v), 0))\n\t\tif %sToJson(v, j) != int64(len(j)) || len(j) == 0 {\n\t\t\ttb.Fatal(\"ToJson of a sample\")\n\t\t}\n", n, n)
	b.WriteString("\t\twire, text, json = append(wire, w), append(text, []byte(x)), append(json, j)\n")
	if variable {
		b.WriteString("\t\tsb.Shutdown()\n")
	}
	b.WriteString("\t}\n\treturn wire, text, json\n}\n")

	// the tolerant read of a wire named buf into the report r
	tolerant := func(in, buf string) string {
		if variable {
			return fmt.Sprintf("%svar lb %sBuilder\n%sif lb.Init() {\n%s\t%sLoadBuilder(&lb, %s, &r)\n%s\tlb.Shutdown()\n%s}\n", in, n, in, in, n, buf, in, in)
		}
		return in + n + "Load(new(" + n + "), " + buf + ", &r)\n"
	}

	// §16.11 item 3: a shorter re-encoding is a respelling the wire allows
	// when it reads back silently to a value that re-encodes to it again
	fmt.Fprintf(b, "\n// fuzz%sRespelled reports whether a shorter re-encoding is one the wire allows\n// (SPEC-TABLES §16.11, item 3): it reads back with a silent report to a value\n// that re-encodes to it again.\n", n)
	fmt.Fprintf(b, "func fuzz%sRespelled(wire []byte) bool {\n\tback, err := %sReadStrict(wire)\n\tif err != nil || back == nil {\n\t\treturn false\n\t}\n", n, n)
	fmt.Fprintf(b, "\tagain := make([]byte, max(%sMeasure(back), 0))\n\tif %sSave(back, again) != int64(len(again)) || !bytes.Equal(again, wire) {\n\t\treturn false\n\t}\n", n, n)
	b.WriteString("\tvar r TableReport\n" + tolerant("\t", "wire"))
	fmt.Fprintf(b, "\treturn fuzz%sSilent(&r)\n}\n", base)

	// Wire.
	fmt.Fprintf(b, "\n// Fuzz%sWire reads %s's wire seeds, their bounded mutations and every input\n// the fuzzer makes through %sReadStrict (SPEC-TABLES §16.11).\n", n, n, n)
	fmt.Fprintf(b, "func Fuzz%sWire(f *testing.F) {\n\twire, _, _ := fuzz%sSeeds(f)\n\tcheck := func(t testing.TB, data []byte, at int) {\n\t\tt.Helper()\n", n, n)
	fmt.Fprintf(b, "\t\tgot, err := %sReadStrict(data)\n\t\tif err != nil {\n\t\t\tif got != nil || !fuzz%sNamed(err) {\n\t\t\t\tt.Fatalf(\"wire %%s: refused without a named reason: %%v\", fuzz%sInput(data, at), err)\n\t\t\t}\n\t\t\treturn\n\t\t}\n", n, base, base)
	fmt.Fprintf(b, "\t\tif got == nil {\n\t\t\tt.Fatalf(\"wire %%s: accepted with no value\", fuzz%sInput(data, at))\n\t\t}\n", base)
	fmt.Fprintf(b, "\t\tagain := make([]byte, max(%sMeasure(got), 0))\n\t\tsaved := %sSave(got, again) == int64(len(again))\n", n, n)
	fmt.Fprintf(b, "\t\tif !saved {\n\t\t\tt.Fatalf(\"wire %%s: accepted a value Save refuses\", fuzz%sInput(data, at))\n\t\t}\n", base)
	b.WriteString("\t\tif bytes.Equal(again, data) {\n\t\t\treturn\n\t\t}\n")
	fmt.Fprintf(b, "\t\tif len(again) < len(data) && fuzz%sRespelled(again) {\n\t\t\treturn\n\t\t}\n", n)
	b.WriteString("\t\tvar r TableReport\n" + tolerant("\t\t", "data"))
	fmt.Fprintf(b, "\t\tif fuzz%sSilent(&r) {\n\t\t\tt.Fatalf(\"wire %%s: accepted silently, and re-encodes to %%d other bytes, %%s\", fuzz%sInput(data, at), len(again), fuzz%sInput(again, -1))\n\t\t}\n\t}\n", base, base, base)
	fmt.Fprintf(b, "\tfuzz%sSeed(f, wire)\n\tf.Fuzz(func(t *testing.T, data []byte) { check(t, data, -1) })\n}\n", base)

	// Text.
	fmt.Fprintf(b, "\n// Fuzz%sText reads %s's base64 seeds, their bounded mutations and every input\n// the fuzzer makes through %sLoadText (SPEC-TABLES §16.11).\n", n, n, n)
	fmt.Fprintf(b, "func Fuzz%sText(f *testing.F) {\n\t_, text, _ := fuzz%sSeeds(f)\n\tcheck := func(t testing.TB, data []byte, at int) {\n\t\tt.Helper()\n\t\tvar r TableReport\n", n, n)
	fmt.Fprintf(b, "\t\tgot, err := %sLoadText(string(data), &r)\n\t\tif err != nil {\n\t\t\tif got != nil || !fuzz%sNamed(err) {\n\t\t\t\tt.Fatalf(\"text %%s: refused without a named reason: %%v\", fuzz%sInput(data, at), err)\n\t\t\t}\n\t\t\treturn\n\t\t}\n", n, base, base)
	fmt.Fprintf(b, "\t\tif got == nil {\n\t\t\tt.Fatalf(\"text %%s: accepted with no value\", fuzz%sInput(data, at))\n\t\t}\n", base)
	fmt.Fprintf(b, "\t\tagain, err := %sSaveText(got)\n\t\tif err != nil {\n\t\t\tt.Fatalf(\"text %%s: accepted a value SaveText refuses: %%v\", fuzz%sInput(data, at), err)\n\t\t}\n\t\tif again == string(data) {\n\t\t\treturn\n\t\t}\n", n, base)
	// §16.11 item 3 holds on the wire the text carries, never on the base64:
	// the input's own base64 must be the standard spelling of its bytes
	b.WriteString("\t\tif len(again) < len(data) {\n")
	b.WriteString("\t\t\tin, inErr := base64.StdEncoding.DecodeString(string(data))\n\t\t\tout, outErr := base64.StdEncoding.DecodeString(again)\n")
	fmt.Fprintf(b, "\t\t\tif inErr == nil && outErr == nil && base64.StdEncoding.EncodeToString(in) == string(data) && len(out) < len(in) && fuzz%sRespelled(out) {\n\t\t\t\treturn\n\t\t\t}\n\t\t}\n", n)
	fmt.Fprintf(b, "\t\tif fuzz%sSilent(&r) {\n\t\t\tt.Fatalf(\"text %%s: accepted silently, and re-encodes to other text\", fuzz%sInput(data, at))\n\t\t}\n\t}\n", base, base)
	fmt.Fprintf(b, "\tfuzz%sSeed(f, text)\n\tf.Fuzz(func(t *testing.T, data []byte) { check(t, data, -1) })\n}\n", base)

	// Json.
	fmt.Fprintf(b, "\n// Fuzz%sJson reads %s's JSON seeds, their bounded mutations and every input\n// the fuzzer makes through %sFromJson (SPEC-TABLES §16.11).\n", n, n, n)
	fmt.Fprintf(b, "func Fuzz%sJson(f *testing.F) {\n\t_, _, json := fuzz%sSeeds(f)\n\tcheck := func(t testing.TB, data []byte, at int) {\n\t\tt.Helper()\n\t\tvar r TableReport\n", n, n)
	if variable {
		fmt.Fprintf(b, "\t\tvar jb %sBuilder\n\t\tif !jb.Init() {\n\t\t\tt.Fatal(\"builder init\")\n\t\t}\n\t\tdefer jb.Shutdown()\n", n)
		fmt.Fprintf(b, "\t\tok := %sFromJson(&jb, data, &r)\n\t\tif ok && r.Err() == nil && !jb.Lock() {\n\t\t\tt.Fatalf(\"json %%s: accepted, and the builder does not lock\", fuzz%sInput(data, at))\n\t\t}\n", n, base)
	} else {
		fmt.Fprintf(b, "\t\tv := new(%s)\n\t\tok := %sFromJson(v, data, &r)\n", n, n)
	}
	fmt.Fprintf(b, "\t\tif !ok || r.Err() != nil {\n\t\t\tif !fuzz%sNamed(r.Err()) {\n\t\t\t\tt.Fatalf(\"json %%s: refused without a named reason: report %%+v\", fuzz%sInput(data, at), r)\n\t\t\t}\n\t\t\treturn\n\t\t}\n", base, base)
	if variable {
		b.WriteString("\t\tv := jb.AsConst()\n")
	}
	fmt.Fprintf(b, "\t\tagain := make([]byte, max(%sToJsonMeasure(v), 0))\n\t\tif %sToJson(v, again) != int64(len(again)) || len(again) == 0 {\n\t\t\tt.Fatalf(\"json %%s: accepted a value ToJson refuses\", fuzz%sInput(data, at))\n\t\t}\n\t\tif bytes.Equal(again, data) {\n\t\t\treturn\n\t\t}\n", n, n, base)
	fmt.Fprintf(b, "\t\tif fuzz%sSilent(&r) {\n\t\t\tt.Fatalf(\"json %%s: accepted silently, and re-encodes to %%d other bytes\", fuzz%sInput(data, at), len(again))\n\t\t}\n\t}\n", base, base)
	fmt.Fprintf(b, "\tfuzz%sSeed(f, json)\n\tf.Fuzz(func(t *testing.T, data []byte) { check(t, data, -1) })\n}\n", base)
}
