// Testgen writes the generated round-trip and damage tests of a unit
// (docs/SPEC-TABLES.md §16.11): one <Base>Table_gen_test.go per unit file that
// declares a root table, in the generated package, calling the generated API
// and the standard library only. It writes nothing; the caller places the
// files beside what Generate wrote. The output is deterministic to the byte:
// every sample is built from the declaration alone.
func Testgen(u *ir.Unit) (map[string][]byte, error) {
	variable := ir.VariableTables(u)
	out := map[string][]byte{}
	for _, f := range u.Files {
		var roots []*ir.Struct
		for _, st := range f.Tables {
			// §16.11: a ROOT TABLE is every declared table; a generated map
			// entry or text-list element record is not one
			if st.IsTable && !st.IsMapEntry() {
				roots = append(roots, st)
			}
		}
		if len(roots) == 0 {
			continue
		}
		var body strings.Builder
		for _, st := range roots {
			// §16.11: the sample is spelled in the JSON form and the round
			// trip crosses the wire, so a table without either is refused
			for _, form := range []string{"wire", "json"} {
				if !st.CarriesForm(form) {
					return nil, fmt.Errorf("testgen: table %s does not carry the %s form, and its generated tests spell the sample in JSON and cross the wire (docs/SPEC-TABLES.md §16.11)", st.Name, form)
				}
			}
			samples, err := testgenSamples(st)
			if err != nil {
				return nil, err
			}
			testgenRoundTrip(&body, st, variable[st.Name], samples)
			testgenDamage(&body, st, variable[st.Name], samples)
		}
		var src strings.Builder
		fmt.Fprintf(&src, "// Code generated by the schema compiler from %s.schema (schema testgen). DO NOT EDIT.\n", f.Base)
		src.WriteString("// SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
		src.WriteString("// your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
		src.WriteString("// AGPL-3.0, its output is not.\n")
		src.WriteString("// The round-trip and damage tests of mas-bandwidth/schema docs/SPEC-TABLES.md §16.11.\n\n")
		fmt.Fprintf(&src, "package %s\n\nimport (\n\t\"bytes\"\n\t\"encoding/base64\"\n\t\"errors\"\n", u.Package)
		if strings.Contains(body.String(), "strings.") {
			src.WriteString("\t\"strings\"\n")
		}
		src.WriteString("\t\"testing\"\n)\n")
		src.WriteString(body.String())
		out[f.Base+"Table_gen_test.go"] = []byte(src.String())
	}
	return out, nil
}

// The sample modes of §16.11.
const (
	tgDefaults = iota
	tgLow
	tgHigh
	tgInside
	tgArm
)

type tgSample struct {
	name string
	expr string // a Go expression whose value is the sample's JSON text
}

// testgenSamples builds a root table's samples (§16.11): defaults, low, high,
// inside, and arm_<k> for every arm past the first of the widest union.
func testgenSamples(st *ir.Struct) ([]tgSample, error) {
	arms := testgenMaxArms(st, map[*ir.Struct]bool{}, map[*ir.Union]bool{})
	var out []tgSample
	modes := []struct {
		name string
		mode int
		arm  int
	}{{"defaults", tgDefaults, 0}, {"low", tgLow, 0}, {"high", tgHigh, 0}, {"inside", tgInside, 0}}
	for k := 1; k < arms; k++ {
		modes = append(modes, struct {
			name string
			mode int
			arm  int
		}{"arm_" + strconv.Itoa(k), tgArm, k})
	}
	for _, m := range modes {
		g := &tgGen{mode: m.mode, arm: m.arm, path: map[string]bool{}}
		var j tgJSON
		if err := g.table(&j, st); err != nil {
			return nil, err
		}
		out = append(out, tgSample{m.name, j.expr()})
	}
	return out, nil
}

// testgenMaxArms is the largest arm count of any union the table reaches.
func testgenMaxArms(st *ir.Struct, seen map[*ir.Struct]bool, useen map[*ir.Union]bool) int {
	if st == nil || seen[st] {
		return 0
	}
	seen[st] = true
	n := 0
	var field func(f *ir.Field)
	field = func(f *ir.Field) {
		if f == nil {
			return
		}
		if f.IsMap() {
			field(ir.MapValueField(f))
			return
		}
		switch ref := f.Type.Ref.(type) {
		case *ir.Struct:
			n = max(n, testgenMaxArms(ref, seen, useen))
		case *ir.Union:
			if useen[ref] {
				return
			}
			useen[ref] = true
			n = max(n, len(ref.Variants))
			for _, v := range ref.Variants {
				field(v.F)
			}
		}
	}
	for _, f := range st.Fields {
		field(f)
	}
	return n
}

// tgJSON accumulates a Go expression that concatenates literal JSON with
// computed runs (a long string, a long array), so a sample at a 70000 bound
// is a short line of source.
type tgJSON struct {
	parts []string
	lit   strings.Builder
}

func (j *tgJSON) raw(s string) { j.lit.WriteString(s) }

func (j *tgJSON) code(e string) {
	j.flush()
	j.parts = append(j.parts, e)
}

func (j *tgJSON) flush() {
	if j.lit.Len() > 0 {
		j.parts = append(j.parts, strconv.Quote(j.lit.String()))
		j.lit.Reset()
	}
}

func (j *tgJSON) expr() string {
	j.flush()
	if len(j.parts) == 0 {
		return `""`
	}
	return strings.Join(j.parts, " + ")
}

// tgGen spells one sample. path holds the tables on the current pointer path,
// so a recursive declaration ends in null (§16.11).
type tgGen struct {
	mode int
	arm  int
	path map[string]bool
}

// table writes a table or type body as its JSON object, or as its one field's
// array for a `json = "array"` table (§16.10).
func (g *tgGen) table(j *tgJSON, st *ir.Struct) error {
	if st.JsonArray {
		if len(st.Fields) != 1 {
			return fmt.Errorf("testgen: %s is json = \"array\" with %d fields", st.Name, len(st.Fields))
		}
		return g.value(j, st.Fields[0], true)
	}
	if g.mode == tgDefaults {
		// §16.11 defaults: `{}`, with a required field at its low value
		j.raw("{")
		first := true
		for _, f := range st.Fields {
			if !f.Required || f.Deprecated {
				continue
			}
			if !first {
				j.raw(",")
			}
			first = false
			j.raw(strconv.Quote(ir.TableFieldJsonKey(f)) + ":")
			low := &tgGen{mode: tgLow, path: g.path}
			if err := low.value(j, f, true); err != nil {
				return err
			}
		}
		j.raw("}")
		return nil
	}
	j.raw("{")
	first := true
	for _, f := range st.Fields {
		if f.Deprecated {
			continue
		}
		if !first {
			j.raw(",")
		}
		first = false
		j.raw(strconv.Quote(ir.TableFieldJsonKey(f)) + ":")
		if err := g.value(j, f, true); err != nil {
			return err
		}
	}
	j.raw("}")
	return nil
}

// value writes one field line's JSON value by its §16.2 row. whole is false
// when writing an ELEMENT of the field's array.
func (g *tgGen) value(j *tgJSON, f *ir.Field, whole bool) error {
	if whole && f.IsMap() {
		return g.mapValue(j, f)
	}
	if whole && f.Array != ir.ArrayNone {
		return g.array(j, f)
	}
	t := f.Type
	if t.Pointer {
		return g.pointer(j, f)
	}
	switch t.Kind {
	case ir.TBool:
		j.raw(strconv.FormatBool(g.mode == tgHigh || g.mode == tgInside || g.mode == tgArm))
	case ir.TInt, ir.TBits:
		if t.Kind == ir.TInt && t.Timestamp {
			if g.mode == tgLow {
				j.raw(`"1970-01-01T00:00:00Z"`)
			} else {
				j.raw(`"2026-10-15T12:34:05.123456789Z"`)
			}
			return nil
		}
		lo, hi := testgenIntRange(f)
		j.raw(g.pick(lo, hi).String())
	case ir.TFixed:
		lo, hi := testgenIntRange(f)
		raw := g.pick(lo, hi)
		j.raw(testgenFixedDecimal(raw, t.FracBits))
	case ir.TFloat32, ir.TFloat64:
		j.raw(g.float(f))
	case ir.TString, ir.TWString:
		n := g.length(t.Size)
		g.text(j, n)
	case ir.TBytes:
		g.bytesValue(j, g.length(t.Size))
	case ir.TNamed:
		switch ref := t.Ref.(type) {
		case *ir.Struct:
			if ref.IsTextListElem() {
				return g.value(j, ref.Fields[0], true)
			}
			return g.table(j, ref)
		case *ir.Enum:
			j.raw(strconv.Quote(g.variant(ref.Variants)))
		case *ir.Flags:
			j.raw("[")
			var names []string
			switch g.mode {
			case tgHigh:
				names = ref.Variants
			case tgLow:
			default:
				names = ref.Variants[:min(1, len(ref.Variants))]
			}
			for i, n := range names {
				if i > 0 {
					j.raw(",")
				}
				j.raw(strconv.Quote(n))
			}
			j.raw("]")
		case *ir.Union:
			return g.union(j, ref)
		default:
			return fmt.Errorf("testgen: field %s names %s, a declaration testgen does not spell (docs/SPEC-TABLES.md §16.11)", f.Name, t.Name)
		}
	default:
		return fmt.Errorf("testgen: field %s is %s, a kind testgen does not spell (docs/SPEC-TABLES.md §16.11)", f.Name, ir.FieldTypeSpelling(f))
	}
	return nil
}

// pick chooses a bounded integer by the sample's mode (§16.11).
func (g *tgGen) pick(lo, hi *big.Int) *big.Int {
	switch g.mode {
	case tgLow:
		return lo
	case tgHigh:
		return hi
	}
	span := new(big.Int).Sub(hi, lo)
	if span.Cmp(big.NewInt(2)) >= 0 {
		return new(big.Int).Add(lo, big.NewInt(1))
	}
	return lo
}

// length chooses a bounded extent: empty, the bound, or one inside it.
func (g *tgGen) length(bound int64) int64 {
	switch g.mode {
	case tgLow:
		return 0
	case tgHigh:
		return bound
	}
	return min(1, bound)
}

func (g *tgGen) variant(vs []string) string {
	switch g.mode {
	case tgLow:
		return vs[0]
	case tgHigh:
		return vs[len(vs)-1]
	}
	return vs[len(vs)/2]
}

// float spells a float: a compressed float's own range, else values every
// width holds exactly.
func (g *tgGen) float(f *ir.Field) string {
	if f.HasFloatRange {
		v := f.FMin
		switch g.mode {
		case tgHigh:
			v = f.FMin + float64(f.Steps)*f.Resolution
			if v > f.FMax {
				v = f.FMin + float64(f.Steps-1)*f.Resolution
			}
		case tgInside, tgArm:
			if f.Steps >= 2 {
				v = f.FMin + f.Resolution
			}
		}
		bits := 64
		if f.Type.Kind == ir.TFloat32 {
			bits = 32
		}
		return strconv.FormatFloat(v, 'g', -1, bits)
	}
	switch g.mode {
	case tgLow:
		return "-1.5"
	case tgHigh:
		return "1.5"
	}
	return "0.25"
}

// text writes a JSON string of n ASCII bytes.
func (g *tgGen) text(j *tgJSON, n int64) {
	if n <= 64 {
		j.raw(strconv.Quote(strings.Repeat("a", int(n))))
		return
	}
	j.raw(`"`)
	j.code(fmt.Sprintf("strings.Repeat(%q, %d)", "a", n))
	j.raw(`"`)
}

// bytesValue writes n bytes as padded standard base64 (§16.2).
func (g *tgGen) bytesValue(j *tgJSON, n int64) {
	if n <= 48 {
		j.raw(strconv.Quote(base64.StdEncoding.EncodeToString(bytes.Repeat([]byte{0x5a}, int(n)))))
		return
	}
	j.raw(`"`)
	j.code(fmt.Sprintf("base64.StdEncoding.EncodeToString(bytes.Repeat([]byte{0x5a}, %d))", n))
	j.raw(`"`)
}

// pointer writes `*T` as the pointee's object, or null when T is on the path;
// `*bytes`, `*string` and `*wstring` as their blob (§2.5, §16.2).
func (g *tgGen) pointer(j *tgJSON, f *ir.Field) error {
	t := f.Type
	switch t.Kind {
	case ir.TBytes:
		g.bytesValue(j, g.unbounded())
		return nil
	case ir.TString, ir.TWString:
		g.text(j, g.unbounded())
		return nil
	}
	st, ok := t.Ref.(*ir.Struct)
	if !ok {
		return fmt.Errorf("testgen: pointer field %s names no table (docs/SPEC-TABLES.md §16.11)", f.Name)
	}
	if g.path[st.Name] {
		j.raw("null")
		return nil
	}
	g.path[st.Name] = true
	defer delete(g.path, st.Name)
	return g.table(j, st)
}

// unbounded is an unbounded collection's extent: empty, two, or one (§16.11).
func (g *tgGen) unbounded() int64 {
	switch g.mode {
	case tgLow:
		return 0
	case tgHigh:
		return 2
	}
	return 1
}

// union writes the one-key object of the arm the mode selects (§16.2).
func (g *tgGen) union(j *tgJSON, un *ir.Union) error {
	if len(un.Variants) == 0 {
		j.raw("{}")
		return nil
	}
	v := un.Variants[g.arm%len(un.Variants)]
	key := v.Name
	j.raw("{" + strconv.Quote(key) + ":")
	if v.Void() {
		j.raw("null")
	} else if err := g.value(j, v.F, true); err != nil {
		return err
	}
	j.raw("}")
	return nil
}

// array writes `[N]T`, `[..N]T`, `[E]T` and `[]T` by their rows (§16.2).
func (g *tgGen) array(j *tgJSON, f *ir.Field) error {
	if f.KeyEnumRef != nil {
		j.raw("{")
		for i, name := range f.KeyEnumRef.Variants {
			if i > 0 {
				j.raw(",")
			}
			j.raw(strconv.Quote(name) + ":")
			if err := g.value(j, f, false); err != nil {
				return err
			}
		}
		j.raw("}")
		return nil
	}
	var n int64
	switch f.Array {
	case ir.ArrayFixed:
		n = f.ArrayBound
	case ir.ArrayCounted:
		switch g.mode {
		case tgLow:
			n = f.ArrayMin
		case tgHigh:
			n = f.ArrayBound
		default:
			n = min(f.ArrayMin+1, f.ArrayBound)
		}
	case ir.ArrayList:
		n = g.unbounded()
	}
	// a `?string(M)` text-list element is written absent once, in high (§16.11)
	absentFirst := false
	if elem := f.TextListElem(); elem != nil && g.mode == tgHigh && n > 0 && elem.Fields[0].Type.Optional {
		absentFirst = true
	}
	one := func(i int64) (string, error) {
		if i == 0 && absentFirst {
			return `"null"`, nil
		}
		var e tgJSON
		if err := g.value(&e, f, false); err != nil {
			return "", err
		}
		return e.expr(), nil
	}
	j.raw("[")
	if n <= 4 {
		for i := int64(0); i < n; i++ {
			if i > 0 {
				j.raw(",")
			}
			e, err := one(i)
			if err != nil {
				return err
			}
			j.code(e)
		}
	} else {
		first, err := one(0)
		if err != nil {
			return err
		}
		rest, err := one(1)
		if err != nil {
			return err
		}
		j.code(first)
		j.code(fmt.Sprintf("strings.Repeat(\",\"+%s, %d)", rest, n-1))
	}
	j.raw("]")
	return nil
}

// mapValue writes `map[K]V` as an object keyed in ascending order (§2.8,
// §16.2): empty, two entries or one.
func (g *tgGen) mapValue(j *tgJSON, f *ir.Field) error {
	key, val := ir.MapKeyField(f), ir.MapValueField(f)
	n := g.unbounded()
	var keys []string
	if key.Type.Kind == ir.TString || key.Type.Kind == ir.TWString {
		for i := int64(0); i < n; i++ {
			keys = append(keys, string(rune('a'+i)))
		}
	} else {
		lo, hi := testgenIntRange(key)
		for i := int64(0); i < n; i++ {
			k := new(big.Int).Add(lo, big.NewInt(i))
			if k.Cmp(hi) > 0 {
				break
			}
			keys = append(keys, k.String())
		}
	}
	j.raw("{")
	for i, k := range keys {
		if i > 0 {
			j.raw(",")
		}
		j.raw(strconv.Quote(k) + ":")
		if err := g.value(j, val, true); err != nil {
			return err
		}
	}
	j.raw("}")
	return nil
}

// testgenIntRange is an integer-like field's range on the scale its JSON
// token carries: declared, else implied by its storage.
func testgenIntRange(f *ir.Field) (lo, hi *big.Int) {
	if lo, hi, ok := ir.TableRawRange(f); ok {
		return lo, hi
	}
	width := f.Type.Width
	signed := f.Type.Signed && f.Type.Kind != ir.TBits
	if signed {
		hi = new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), uint(width-1)), big.NewInt(1))
		lo = new(big.Int).Neg(new(big.Int).Lsh(big.NewInt(1), uint(width-1)))
		return lo, hi
	}
	return big.NewInt(0), new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), uint(width)), big.NewInt(1))
}

// testgenFixedDecimal spells a fixed-point raw value in whole units, exactly
// (§16.2's fixed row).
func testgenFixedDecimal(raw *big.Int, frac int) string {
	r := new(big.Rat).SetFrac(raw, new(big.Int).Lsh(big.NewInt(1), uint(frac)))
	return r.FloatString(max(frac, 1))
}

// testgenRoundTrip writes Test<Name>GenRoundTrip: every sample read equal
// through the binary wire, base64 text and JSON text (§16.11).
func testgenRoundTrip(b *strings.Builder, st *ir.Struct, variable bool, samples []tgSample) {
	n := st.Name
	fmt.Fprintf(b, "\n// Test%sGenRoundTrip reads every sample of %s back through the binary wire,\n// base64 text and JSON text, each equal to what was written (SPEC-TABLES §16.11).\n", n, n)
	fmt.Fprintf(b, "func Test%sGenRoundTrip(t *testing.T) {\n\tt.Parallel()\n\tsamples := []struct{ name, text string }{\n", n)
	for _, s := range samples {
		fmt.Fprintf(b, "\t\t{%q, %s},\n", s.name, s.expr)
	}
	b.WriteString("\t}\n\tfor _, s := range samples {\n\t\tt.Run(s.name, func(t *testing.T) {\n\t\t\tt.Parallel()\n")
	testgenSave(b, n)
	testgenSample(b, n, variable, "s.text")
	b.WriteString("\t\t\twire, jsonText := save(\"sample\", v)\n")
	b.WriteString("\t\t\tsame := func(leg string, got *" + n + ") {\n\t\t\t\tt.Helper()\n\t\t\t\tgotWire, gotJson := save(leg, got)\n")
	b.WriteString("\t\t\t\tif !bytes.Equal(gotWire, wire) {\n\t\t\t\t\tt.Fatalf(\"%s: the value read saves to %x, the sample saved to %x\", leg, gotWire, wire)\n\t\t\t\t}\n")
	b.WriteString("\t\t\t\tif !bytes.Equal(gotJson, jsonText) {\n\t\t\t\t\tt.Fatalf(\"%s: the value read writes %s, the sample wrote %s\", leg, gotJson, jsonText)\n\t\t\t\t}\n\t\t\t}\n")
	fmt.Fprintf(b, "\t\t\tgot, err := %sReadStrict(wire)\n\t\t\tif err != nil || got == nil {\n\t\t\t\tt.Fatalf(\"binary: ReadStrict: %%v\", err)\n\t\t\t}\n\t\t\tsame(\"binary\", got)\n", n)
	fmt.Fprintf(b, "\t\t\ttext, err := %sSaveText(v)\n\t\t\tif err != nil || text != base64.StdEncoding.EncodeToString(wire) {\n\t\t\t\tt.Fatalf(\"base64: SaveText is not the base64 of the wire: %%v\", err)\n\t\t\t}\n", n)
	fmt.Fprintf(b, "\t\t\tgot, err = %sLoadText(text, nil)\n\t\t\tif err != nil || got == nil {\n\t\t\t\tt.Fatalf(\"base64: LoadText: %%v\", err)\n\t\t\t}\n\t\t\tsame(\"base64\", got)\n", n)
	testgenFromJson(b, n, variable, "jsonText", "j", "jr")
	b.WriteString("\t\t\tif !ok || jr != (TableReport{}) {\n\t\t\t\tt.Fatalf(\"json: FromJson of ToJson's text: report %+v\", jr)\n\t\t\t}\n\t\t\tsame(\"json\", j)\n")
	b.WriteString("\t\t})\n\t}\n}\n")
}

// testgenDamage writes Test<Name>GenDamage: the high sample's wire and texts,
// damaged, each refused by its named reason (§16.11).
func testgenDamage(b *strings.Builder, st *ir.Struct, variable bool, samples []tgSample) {
	n := st.Name
	high := samples[0].expr
	for _, s := range samples {
		if s.name == "high" {
			high = s.expr
		}
	}
	fmt.Fprintf(b, "\n// Test%sGenDamage damages %s's high sample and requires each damage refused by\n// its named reason through the strict read (SPEC-TABLES §16.11).\n", n, n)
	fmt.Fprintf(b, "func Test%sGenDamage(t *testing.T) {\n\tt.Parallel()\n", n)
	b.WriteString("\tvar r TableReport\n")
	testgenSampleAt(b, "\t", n, variable, high)
	fmt.Fprintf(b, "\twire := make([]byte, %sMeasure(v))\n\tif len(wire) < 2 || %sSave(v, wire) != int64(len(wire)) {\n\t\tt.Fatal(\"save of the high sample\")\n\t}\n", n, n)
	b.WriteString("\tfor _, cut := range [][]byte{wire[:1], wire[:len(wire)-1]} {\n")
	fmt.Fprintf(b, "\t\tif got, err := %sReadStrict(cut); got != nil || !(errors.Is(err, TableRefuseWireDamaged) || errors.Is(err, TableRefuseTruncated)) {\n", n)
	b.WriteString("\t\t\tt.Fatalf(\"truncated wire of %d bytes: %v, want wire_damaged or truncated\", len(cut), err)\n\t\t}\n\t}\n")
	b.WriteString("\tfor _, form := range []byte{2, 9, 255} {\n\t\tflipped := bytes.Clone(wire)\n\t\tflipped[0] = form\n")
	fmt.Fprintf(b, "\t\tif got, err := %sReadStrict(flipped); got != nil || !errors.Is(err, TableRefuseUnknownForm) {\n", n)
	b.WriteString("\t\t\tt.Fatalf(\"form byte %d: %v, want unknown_form\", form, err)\n\t\t}\n\t}\n")
	fmt.Fprintf(b, "\ttext, err := %sSaveText(v)\n\tif err != nil {\n\t\tt.Fatal(err)\n\t}\n", n)
	b.WriteString("\tfor _, bad := range []string{\"!\" + text[1:], text[:len(text)-1]} {\n")
	fmt.Fprintf(b, "\t\tif got, err := %sLoadText(bad, nil); got != nil || err == nil || err.Error() != \"base64_damaged\" {\n", n)
	b.WriteString("\t\t\tt.Fatalf(\"base64 damage: %v, want base64_damaged\", err)\n\t\t}\n\t}\n")
	fmt.Fprintf(b, "\tjsonText := make([]byte, %sToJsonMeasure(v))\n\tif %sToJson(v, jsonText) != int64(len(jsonText)) {\n\t\tt.Fatal(\"ToJson of the high sample\")\n\t}\n", n, n)
	testgenFromJsonAt(b, "\t", n, variable, "jsonText[:len(jsonText)-2]", "", "jr")
	b.WriteString("\tif ok || !jr.Malformed || !errors.Is(jr.Err(), TableRefuseMalformed) {\n\t\tt.Fatalf(\"a JSON document cut off inside its value: report %+v, want malformed\", jr)\n\t}\n}\n")
}

// testgenSave writes the subtest's save closure: a value's wire and JSON text.
func testgenSave(b *strings.Builder, n string) {
	b.WriteString("\t\t\tsave := func(leg string, value *" + n + ") ([]byte, []byte) {\n\t\t\t\tt.Helper()\n")
	fmt.Fprintf(b, "\t\t\t\twire := make([]byte, max(%sMeasure(value), 0))\n\t\t\t\tif %sSave(value, wire) != int64(len(wire)) || len(wire) == 0 {\n\t\t\t\t\tt.Fatalf(\"%%s: Save refused\", leg)\n\t\t\t\t}\n", n, n)
	fmt.Fprintf(b, "\t\t\t\tjsonText := make([]byte, max(%sToJsonMeasure(value), 0))\n\t\t\t\tif %sToJson(value, jsonText) != int64(len(jsonText)) || len(jsonText) == 0 {\n\t\t\t\t\tt.Fatalf(\"%%s: ToJson refused\", leg)\n\t\t\t\t}\n", n, n)
	b.WriteString("\t\t\t\treturn wire, jsonText\n\t\t\t}\n")
}

// testgenSample writes the sample's read into v, with a silent report.
func testgenSample(b *strings.Builder, n string, variable bool, text string) {
	b.WriteString("\t\t\tvar r TableReport\n")
	testgenSampleAt(b, "\t\t\t", n, variable, text)
}

func testgenSampleAt(b *strings.Builder, in, n string, variable bool, text string) {
	if variable {
		fmt.Fprintf(b, "%svar sb %sBuilder\n%sif !sb.Init() {\n%s\tt.Fatal(\"builder init\")\n%s}\n%sdefer sb.Shutdown()\n", in, n, in, in, in, in)
		fmt.Fprintf(b, "%sif !%sFromJson(&sb, []byte(%s), &r) || r != (TableReport{}) || !sb.Lock() {\n", in, n, text)
		fmt.Fprintf(b, "%s\tt.Fatalf(\"FromJson of the sample: report %%+v\", r)\n%s}\n%sv := sb.AsConst()\n", in, in, in)
		return
	}
	fmt.Fprintf(b, "%sv := new(%s)\n%sif !%sFromJson(v, []byte(%s), &r) || r != (TableReport{}) {\n", in, n, in, n, text)
	fmt.Fprintf(b, "%s\tt.Fatalf(\"FromJson of the sample: report %%+v\", r)\n%s}\n", in, in)
}

// testgenFromJson writes a JSON read of text into a fresh value named v,
// leaving ok and the report jr.
func testgenFromJson(b *strings.Builder, n string, variable bool, text, v, jr string) {
	testgenFromJsonAt(b, "\t\t\t", n, variable, text, v, jr)
}

func testgenFromJsonAt(b *strings.Builder, in, n string, variable bool, text, v, jr string) {
	fmt.Fprintf(b, "%svar %s TableReport\n", in, jr)
	if variable {
		fmt.Fprintf(b, "%svar jb %sBuilder\n%sif !jb.Init() {\n%s\tt.Fatal(\"builder init\")\n%s}\n%sdefer jb.Shutdown()\n", in, n, in, in, in, in)
		fmt.Fprintf(b, "%sok := %sFromJson(&jb, %s, &%s) && jb.Lock()\n", in, n, text, jr)
		if v != "" {
			fmt.Fprintf(b, "%s%s := jb.AsConst()\n", in, v)
		}
		return
	}
	target := v
	if target == "" {
		target = "new(" + n + ")"
	} else {
		fmt.Fprintf(b, "%s%s := new(%s)\n", in, v, n)
	}
	fmt.Fprintf(b, "%sok := %sFromJson(%s, %s, &%s)\n", in, n, target, text, jr)
}
