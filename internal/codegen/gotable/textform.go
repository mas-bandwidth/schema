// tableTextFormRead reads one document strictly and answers it with the
// canonical JSON of its value.
func tableTextFormRead(text []byte, info *TableTypeInfo, limits TableTextFormLimits) (*TableTextFormDocument, []byte, error) {
	limits = limits.resolved()
	src := append([]byte(nil), text...)
	root, outside, perr := tableTextFormParse(src, limits)
	if perr != nil {
		return nil, nil, perr
	}
	r := tableTextFormResolver{paths: map[string]*tableTextFormNode{}, labels: map[string]*tableTextFormLabel{}}
	r.mark(root, "")
	if !r.record(root, info, "", 0, "") {
		return nil, nil, r.err
	}
	doc := &TableTextFormDocument{text: src, info: info, limits: limits, paths: r.paths}
	for _, c := range outside {
		doc.comments = append(doc.comments, TableTextFormComment{Offset: c.start, Text: string(src[c.start:c.end]), Path: ""})
	}
	tableTextFormAttach(src, root, &doc.comments)
	sort.SliceStable(doc.comments, func(i, j int) bool { return doc.comments[i].Offset < doc.comments[j].Offset })
	return doc, r.out, nil
}

// tableTextFormReportError refuses a JSON walk that counted anything: the
// strict resolve refuses every event the walk can count, so a count here is a
// disagreement between the two and is never accepted silently.
func tableTextFormReportError(report TableReport) error {
	name := TableTextFormKindMismatch
	switch {
	case report.Clamped > 0:
		name = TableTextFormBound
	case report.Unknown > 0:
		name = TableTextFormUnknownKey
	case report.Duplicate > 0:
		name = TableTextFormDuplicateKey
	case report.Malformed:
		name = TableTextFormSyntax
	}
	return &TableTextFormError{Name: name}
}

func tableTextFormSave(doc *TableTextFormDocument, info *TableTypeInfo) ([]byte, error) {
	if doc == nil || doc.info != info {
		return nil, &TableTextFormError{Name: TableTextFormEditConflict}
	}
	return doc.Bytes(), nil
}

type tableTextFormSplice struct {
	start, end int
	text       string
	path       string
	canon      string
}

func tableTextFormApply(src []byte, splices []tableTextFormSplice) []byte {
	out := make([]byte, 0, len(src))
	at := 0
	for _, s := range splices {
		out = append(out, src[at:s.start]...)
		out = append(out, s.text...)
		at = s.end
	}
	return append(out, src[at:]...)
}

// tableTextFormEdit answers the source of the edited document, every span
// taken from the original, after reading it back under the same limits.
func tableTextFormEdit(doc *TableTextFormDocument, info *TableTypeInfo, edits []TableTextFormEdit) ([]byte, error) {
	if doc == nil || doc.info != info {
		return nil, &TableTextFormError{Name: TableTextFormEditConflict}
	}
	splices := make([]tableTextFormSplice, 0, len(edits))
	for _, e := range edits {
		n := doc.paths[e.Path]
		if n == nil || n.kind == '(' {
			// an absent value is an insert, a compound is edited through its
			// children: both are structural, not a leaf edit
			return nil, &TableTextFormError{Name: TableTextFormEditConflict, Path: e.Path}
		}
		p := tableTextFormParser{src: []byte(e.Text), limits: doc.limits}
		value := p.value(0)
		if value == nil {
			p.err.Offset += n.start
			p.err.Path = e.Path
			return nil, p.err
		}
		if value.kind == '(' || p.pos != len(e.Text) {
			return nil, &TableTextFormError{Name: TableTextFormEditConflict, Offset: n.start, Path: e.Path}
		}
		splices = append(splices, tableTextFormSplice{start: n.start, end: n.end, text: e.Text, path: e.Path, canon: n.canon})
	}
	sort.Slice(splices, func(i, j int) bool { return splices[i].start < splices[j].start })
	for i := 1; i < len(splices); i++ {
		if splices[i].start < splices[i-1].end {
			return nil, &TableTextFormError{Name: TableTextFormEditConflict, Offset: splices[i].start, Path: splices[i].path}
		}
	}
	for {
		text := tableTextFormApply(doc.text, splices)
		edited, _, err := tableTextFormRead(text, info, doc.limits)
		if err != nil {
			return nil, err
		}
		// a semantic no-op keeps the old spelling (§16.9.3)
		kept := splices[:0]
		for _, s := range splices {
			if n := edited.paths[s.path]; n == nil || n.canon != s.canon {
				kept = append(kept, s)
			}
		}
		if len(kept) == len(splices) {
			return text, nil
		}
		splices = kept
	}
}

