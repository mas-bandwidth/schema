func tableTextFormLineBreak(src []byte, from, to int) bool {
	for i := from; i < to; i++ {
		if src[i] == '\n' {
			return true
		}
	}
	return false
}

// tableTextFormOwner is the path a comment directly inside list n attaches to.
func tableTextFormOwner(src []byte, n *tableTextFormNode, c tableTextFormSpan) string {
	type child struct {
		start, end int // the child's first and last byte (key through value)
		value      *tableTextFormNode
		path       string
	}
	var children []child
	if n.pairs {
		for i := 0; i+1 < len(n.items); i += 2 {
			k, v := n.items[i], n.items[i+1]
			p := k.path
			if !k.pathed {
				p = n.path
			}
			// between a key and its value: that field
			if k.end <= c.start && c.start < v.start {
				return p
			}
			children = append(children, child{k.start, v.end, v, p})
		}
	} else {
		for _, item := range n.items {
			p := item.path
			if !item.pathed {
				p = n.path
			}
			children = append(children, child{item.start, item.end, item, p})
		}
	}
	// after a complete value on the same physical line: that value
	for i := len(children) - 1; i >= 0; i-- {
		if children[i].end <= c.start {
			if !tableTextFormLineBreak(src, children[i].end, c.start) {
				return children[i].path
			}
			break
		}
	}
	// otherwise standalone: the next sibling, else the container
	for _, ch := range children {
		if ch.start > c.start {
			return ch.path
		}
	}
	return n.path
}

func tableTextFormAttach(src []byte, n *tableTextFormNode, out *[]TableTextFormComment) {
	for _, c := range n.comments {
		*out = append(*out, TableTextFormComment{Offset: c.start, Text: string(src[c.start:c.end]), Path: tableTextFormOwner(src, n, c)})
	}
	for _, item := range n.items {
		if item.kind == '(' {
			tableTextFormAttach(src, item, out)
		}
	}
}

