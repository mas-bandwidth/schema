func tableJsonWriteBase64(out *tableJsonOut, data []byte) {
	out.put('"')
	var quad [4]byte
	i := 0
	for ; len(data)-i >= 3; i += 3 {
		triple := uint32(data[i])<<16 | uint32(data[i+1])<<8 | uint32(data[i+2])
		quad[0] = tableJsonBase64Alphabet[(triple>>18)&0x3f]
		quad[1] = tableJsonBase64Alphabet[(triple>>12)&0x3f]
		quad[2] = tableJsonBase64Alphabet[(triple>>6)&0x3f]
		quad[3] = tableJsonBase64Alphabet[triple&0x3f]
		out.raw(quad[:])
	}
	if i < len(data) {
		left := len(data) - i
		triple := uint32(data[i]) << 16
		if left == 2 {
			triple |= uint32(data[i+1]) << 8
		}
		quad[0] = tableJsonBase64Alphabet[(triple>>18)&0x3f]
		quad[1] = tableJsonBase64Alphabet[(triple>>12)&0x3f]
		quad[2] = '='
		quad[3] = '='
		if left == 2 {
			quad[2] = tableJsonBase64Alphabet[(triple>>6)&0x3f]
		}
		out.raw(quad[:])
	}
	out.put('"')
}

// tableJsonUtf8 is one UTF-8 sequence at the head of s, or -1 when the bytes
// there are not one. It rejects the lot: a stray continuation, an overlong
// form, a surrogate half, and anything past U+10FFFF.
func tableJsonUtf8(s []byte) (code int32, width int32) {
	lead := s[0]
	var want int32
	switch {
	case lead < 0x80:
		return int32(lead), 1
	case lead >= 0xc2 && lead <= 0xdf:
		want, code = 2, int32(lead&0x1f)
	case lead >= 0xe0 && lead <= 0xef:
		want, code = 3, int32(lead&0x0f)
	case lead >= 0xf0 && lead <= 0xf4:
		want, code = 4, int32(lead&0x07)
	default:
		return -1, 0
	}
	if int32(len(s)) < want {
		return -1, 0
	}
	for i := int32(1); i < want; i++ {
		next := s[i]
		if next&0xc0 != 0x80 {
			return -1, 0
		}
		code = code<<6 | int32(next&0x3f)
	}
	if want == 3 && code < 0x800 {
		return -1, 0 // overlong
	}
	if want == 4 && code < 0x10000 {
		return -1, 0 // overlong
	}
	if code >= 0xd800 && code <= 0xdfff {
		return -1, 0 // a surrogate half
	}
	if code > 0x10ffff {
		return -1, 0
	}
	return code, want
}

// A JSON text MUST be valid UTF-8 (RFC 8259 §8.1). The read path is
// byte-transparent — the wire imposes no encoding (§3) and a string may hold
// anything — so the WRITER is where that obligation is met: a byte that is not
// part of a well-formed sequence is written as U+FFFD, one per bad byte, and
// never raw. A text this walk writes is therefore readable by any conforming
// parser, which a raw byte would not be. The cost is stated plainly: for a
// string holding invalid UTF-8, the round trip is NOT byte-identical, because
// the alternative is emitting a text that is not JSON.
func tableJsonWriteString(out *tableJsonOut, s []byte) { out.put('"');tableJsonWriteStringBody(out,s);out.put('"') }

func tableJsonWriteStringBody(out *tableJsonOut, s []byte) {
	const hex = "0123456789abcdef"
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '"':
			out.text("\\\"")
		case '\\':
			out.text("\\\\")
		case '\b':
			out.text("\\b")
		case '\f':
			out.text("\\f")
		case '\n':
			out.text("\\n")
		case '\r':
			out.text("\\r")
		case '\t':
			out.text("\\t")
		default:
			switch {
			case c < 0x20:
				var escape [6]byte
				escape[0], escape[1], escape[2], escape[3] = '\\', 'u', '0', '0'
				escape[4], escape[5] = hex[c>>4], hex[c&0xf]
				out.raw(escape[:])
			case c < 0x80:
				out.put(c)
			default:
				_, width := tableJsonUtf8(s[i:])
				if width == 0 {
					out.text("�") // one per bad byte
				} else {
					out.raw(s[i : i+int(width)])
					i += int(width) - 1
				}
			}
		}
	}
}

func tableJsonWriteUnsigned(out *tableJsonOut, value uint64) {
	var digits [24]byte
	n := len(digits)
	for {
		n--
		digits[n] = byte('0' + value%10)
		value /= 10
		if value == 0 {
			break
		}
	}
	out.raw(digits[n:])
}

func tableJsonWriteSigned(out *tableJsonOut, value int64) {
	if value < 0 {
		out.put('-')
		tableJsonWriteUnsigned(out, -uint64(value))
		return
	}
	tableJsonWriteUnsigned(out, uint64(value))
}

// A float writes at the SHORTEST precision that reads back as the same value at
// the field's own width, so a round trip is exact and a text stays readable.
// Non-finite values have no JSON spelling at all, and the writer REFUSES rather
// than losing one silently — the same rule measure and save already apply to an
// enum value no variant names (§5).
func tableJsonWriteFloat(out *tableJsonOut, value float64, single bool) bool {
	if !tableJsonFinite(value) {
		return false
	}
	bits, low, high := 64, 15, 17
	if single {
		bits, low, high = 32, 6, 9
	}
	var scratch [64]byte
	for digits := low; ; digits++ {
		text := strconv.AppendFloat(scratch[:0], value, 'g', digits, bits)
		if digits >= high {
			out.raw(text)
			return true
		}
		if back, err := strconv.ParseFloat(unsafe.String(&text[0], len(text)), bits); err == nil && back == value {
			out.raw(text)
			return true
		}
	}
}

// tableJsonWriteScalar writes one scalar at one storage address: a nested
// object, a union, a vocabulary, or a number.
func tableJsonWriteScalar(out *tableJsonOut, storage unsafe.Pointer, f *TableFieldInfo, depth int32) bool {
 if f.Pointer {return tableJsonWritePointer(out,(*int64)(storage),f,depth)}
 if f.Kind>=18 && f.Kind<=29 {tableJsonWriteWide(out,storage,f);return true}
 if f.Kind==36 {return tableJsonWriteTimestamp(out,storage)}
	if f.Arms != nil {
		// a union is an object with ONE key, the arm's name; None is {}
		arms := f.Arms()
		tag := tableJsonGetRaw(unsafe.Add(storage, uintptr(arms.TagOffset)), arms.TagSize)
		if tag == 0 {
			out.text("{}")
			return true
		}
		if int64(tag) > f.EnumMax {
			return false // a tag no arm names, exactly as measure refuses it
		}
		arm := f.EnumName(tag)
		// and refuse on the NAME, not merely on the bound: §16.2 says a value
		// no variant NAMES is refused, so the check is the name. Writing
		// whatever came back would emit "???", a spelling the reader counts as
		// unknown — a silent round-trip loss in place of a refusal.
		if !tableJsonNamed(arm) {
			return false
		}
		out.put('{')
		out.line(depth + 1)
		tableJsonWriteString(out, tableJsonText(arm))
		out.text(": ")
		if arms.Arms[tag].Void { out.text("null") } else if !tableJsonWriteField(out, storage, &arms.Arms[tag].Field, depth+1) {
			return false
		}
		out.line(depth)
		out.put('}')
		return true
	}
	if f.Kind == 13 {
		return tableJsonWriteValue(out, storage, f.Table(), depth)
	}
	if tableJsonIsEnum(f) {
		value := tableJsonGetRaw(storage, f.ElemSize)
		// a value no variant names has no text spelling, exactly as it has no
		// wire identity: the writer REFUSES rather than writing None over it,
		// the rule measure and save already apply (§5)
		if int64(value) > f.EnumMax {
			return false
		}
		name := f.EnumName(value)
		if !tableJsonNamed(name) {
			return false
		}
		tableJsonWriteString(out, tableJsonText(name))
		return true
	}
	if tableJsonIsFlags(f) {
		bits := tableJsonGetRaw(storage, f.ElemSize)
		if bits == 0 {
			out.text("[]")
			return true
		}
		out.put('[')
		first := true
		for bit := int64(0); bit < 64; bit++ {
			if bits&(uint64(1)<<bit) == 0 {
				continue
			}
			if bit > f.EnumMax {
				return false // a bit no variant names has no text spelling
			}
			name := f.EnumName(uint64(bit))
			if !tableJsonNamed(name) {
				return false
			}
			if !first {
				out.put(',')
			}
			first = false
			out.line(depth + 1)
			tableJsonWriteString(out, tableJsonText(name))
		}
		out.line(depth)
		out.put(']')
		return true
	}
	switch f.Kind {
	case 1:
		if tableJsonGetRaw(storage, f.ElemSize) != 0 {
			out.text("true")
		} else {
			out.text("false")
		}
		return true
	case 10:
		return tableJsonWriteFloat(out, float64(*(*float32)(storage)), true)
	case 11:
		return tableJsonWriteFloat(out, *(*float64)(storage), false)
	case 2, 3, 4, 5:
		tableJsonWriteSigned(out, tableJsonGetSigned(storage, f.ElemSize))
		return true
	}
	tableJsonWriteUnsigned(out, tableJsonGetRaw(storage, f.ElemSize))
	return true
}

func tableJsonWriteField(out *tableJsonOut, base unsafe.Pointer, f *TableFieldInfo, depth int32) bool {
	storage := unsafe.Add(base, uintptr(f.Offset))
 if f.Map {return tableJsonWriteMap(out,storage,f,depth)}
 if f.List {return tableJsonWriteList(out,storage,f,depth)}
 if f.Kind==33 {tableJsonWriteWString(out,unsafe.Slice((*uint16)(storage),tableJsonCount(base,f)));return true}
	if f.Kind == 12 {
		tableJsonWriteString(out, tableJsonBytes(storage, tableJsonCount(base, f)))
		return true
	}
	if tableJsonIsBytes(f) {
		tableJsonWriteBase64(out, tableJsonBytes(storage, tableJsonCount(base, f)))
		return true
	}
	if tableJsonIsKeyed(f) {
		// one entry per SLOT, keyed by the variant that owns it, so inserting a
		// variant next season moves nothing in the text either. Slot i holds
		// the key i + 1: nothing is stored for None, so nothing is written for
		// it.
		out.put('{')
		first := true
		for slot := int32(0); slot < f.ArrayBound; slot++ {
			if !tableJsonKeyedSlotValid(f, slot) {
				continue
			}
			if !first {
				out.put(',')
			}
			first = false
			out.line(depth + 1)
			tableJsonWriteString(out, tableJsonText(f.KeyName(tableJsonKeyedSlotKey(slot))))
			out.text(": ")
			if !tableJsonWriteScalar(out, unsafe.Add(storage, uintptr(slot)*uintptr(f.ElemSize)), f, depth+1) {
				return false
			}
		}
		if first {
			out.put('}')
			return true
		}
		out.line(depth)
		out.put('}')
		return true
	}
	if f.IsArray {
		count := tableJsonCount(base, f)
		if count == 0 {
			out.text("[]")
			return true
		}
		out.put('[')
		for i := int32(0); i < count; i++ {
			if i > 0 {
				out.put(',')
			}
			out.line(depth + 1)
			if !tableJsonWriteScalar(out, unsafe.Add(storage, uintptr(i)*uintptr(f.ElemSize)), f, depth+1) {
				return false
			}
		}
		out.line(depth)
		out.put(']')
		return true
	}
	return tableJsonWriteScalar(out, storage, f, depth)
}

// tableJsonWriteValue writes one instance, every field, in DECLARATION ORDER,
// defaults included — a text is for people and tools, and a text that elides is
// a text a reader has to know the schema to complete.
func tableJsonWriteValue(out *tableJsonOut, base unsafe.Pointer, info *TableTypeInfo, depth int32) bool {
 return tableJsonWriteLabeledValue(out,base,info,depth,0)
}
func tableJsonWriteLabeledValue(out *tableJsonOut, base unsafe.Pointer, info *TableTypeInfo, depth int32,label uint64) bool {
 if depth>tableJsonMaxDepth{return false}
 any := label!=0
 if any {out.put('{');out.line(depth+1);out.text("\"&node\": ");tableJsonWriteUnsigned(out,label)}
 wrote:=false
	for i := range info.Fields {
		f := &info.Fields[i]
		if f.Guard != "" && !tableJsonGuardHolds(base, info, f.Guard) {
			continue
		}
		// an ABSENT optional writes no key: presence of the key IS the presence
		// (§16.2), so an absent field is an absent key and nothing else would
		// read back as absent
		if f.Optional && tableJsonGetRaw(unsafe.Add(base, uintptr(f.PresentOffset)), 1) == 0 {
			continue
		}
		if !any {
			out.put('{')
		} else {
			out.put(',')
		}
		any = true
 wrote=true
		out.line(depth + 1)
		tableJsonWriteString(out, tableJsonText(f.Json))
		out.text(": ")
		if !tableJsonWriteField(out, base, f, depth+1) {
			return false
		}
	}
	if label!=0 && !wrote {return false}
	if !any {
		out.text("{}")
		return true
	}
	out.line(depth)
	out.put('}')
	return true
}

// ---- reading ----

type tableJsonIn struct {
 graph *tableJsonGraph
	text   []byte
	pos    int
	report *TableReport
	bad    bool // the text is not JSON: the walk stops and keeps what it placed
}

func (in *tableJsonIn) space() {
	for in.pos < len(in.text) {
		c := in.text[in.pos]
		if c == ' ' || c == '\t' || c == '\n' || c == '\r' {
			in.pos++
			continue
		}
        if c == '/' && in.pos+1 < len(in.text) {
            switch in.text[in.pos+1] {
            case '/':
                in.pos += 2
                for in.pos < len(in.text) && in.text[in.pos] != '\n' { in.pos++ }
                continue
            case '*':
                in.pos += 2
                for in.pos+1 < len(in.text) && !(in.text[in.pos] == '*' && in.text[in.pos+1] == '/') { in.pos++ }
                if in.pos+1 >= len(in.text) { in.bad = true; return }
                in.pos += 2
                continue
            }
        }
		return
	}
}

func (in *tableJsonIn) peek() byte {
	in.space()
	if in.pos < len(in.text) {
		return in.text[in.pos]
	}
	return 0
}

// the shape of the value sitting at the cursor, without consuming it
func (in *tableJsonIn) valueShape() byte {
	switch in.peek() {
	case '{':
		return 'o'
	case '[':
		return 'a'
	case '"':
		return 's'
	case 't', 'f':
		return 'b'
	case 'n':
		return 'z'
	case 0:
		return 0
	}
	return 'n'
}

func (in *tableJsonIn) literal(word string) bool {
	if in.pos+len(word) > len(in.text) || string(in.text[in.pos:in.pos+len(word)]) != word {
		in.bad = true
		return false
	}
	in.pos += len(word)
	return true
}

// one \uXXXX escape body; -1 when the four hex digits are not there
func (in *tableJsonIn) hex4() int32 {
	if in.pos+4 > len(in.text) {
		return -1
	}
	value := int32(0)
	for i := 0; i < 4; i++ {
		c := in.text[in.pos+i]
		var digit int32
		switch {
		case c >= '0' && c <= '9':
			digit = int32(c - '0')
		case c >= 'a' && c <= 'f':
			digit = int32(c-'a') + 10
		case c >= 'A' && c <= 'F':
			digit = int32(c-'A') + 10
		default:
			return -1
		}
		value = value<<4 | digit
	}
	in.pos += 4
	return value
}

func tableJsonEncodeUtf8(code uint32, unit []byte) int32 {
	switch {
	case code < 0x80:
		unit[0] = byte(code)
		return 1
	case code < 0x800:
		unit[0] = byte(0xc0 | code>>6)
		unit[1] = byte(0x80 | code&0x3f)
		return 2
	case code < 0x10000:
		unit[0] = byte(0xe0 | code>>12)
		unit[1] = byte(0x80 | (code>>6)&0x3f)
		unit[2] = byte(0x80 | code&0x3f)
		return 3
	}
	unit[0] = byte(0xf0 | code>>18)
	unit[1] = byte(0x80 | (code>>12)&0x3f)
	unit[2] = byte(0x80 | (code>>6)&0x3f)
	unit[3] = byte(0x80 | code&0x3f)
	return 4
}

// scanString scans one JSON string into a caller buffer. Bytes are appended ONE
// CODE POINT AT A TIME — an escape's encoding, or a UTF-8 sequence read whole —
// so a string longer than the field is clamped AT A CODE POINT BOUNDARY and
// never cut through a multi-byte character. Clamping is counted, never fatal,
// exactly as it is on the wire (§4). A nil destination scans past a string
// without keeping it.
func (in *tableJsonIn) scanString(out []byte) (int32, bool) {return in.scanText(out,nil)}

func (in *tableJsonIn) scanText(out []byte, wide []uint16) (int32, bool) {
	if in.peek() != '"' {
		in.bad = true
		return 0, false
	}
	in.pos++
	placed := int32(0)
	clamped := false
	var unit [4]byte
	for {
		if in.pos >= len(in.text) {
			in.bad = true
			return 0, false
		}
		c := in.text[in.pos]
		if c == '"' {
			in.pos++
			break
		}
		unitLength := int32(0)
		switch {
		case c == '\\':
			in.pos++
			if in.pos >= len(in.text) {
				in.bad = true
				return 0, false
			}
			escape := in.text[in.pos]
			in.pos++
			switch escape {
			case '"':
				unit[0], unitLength = '"', 1
			case '\\':
				unit[0], unitLength = '\\', 1
			case '/':
				unit[0], unitLength = '/', 1
			case 'b':
				unit[0], unitLength = '\b', 1
			case 'f':
				unit[0], unitLength = '\f', 1
			case 'n':
				unit[0], unitLength = '\n', 1
			case 'r':
				unit[0], unitLength = '\r', 1
			case 't':
				unit[0], unitLength = '\t', 1
			case 'u':
				high := in.hex4()
				if high < 0 {
					in.bad = true
					return 0, false
				}
				code := uint32(high)
				if high >= 0xd800 && high <= 0xdbff && in.pos+2 <= len(in.text) &&
					in.text[in.pos] == '\\' && in.text[in.pos+1] == 'u' {
					mark := in.pos
					in.pos += 2
					low := in.hex4()
					if low >= 0xdc00 && low <= 0xdfff {
						code = 0x10000 + (uint32(high)-0xd800)<<10 + (uint32(low) - 0xdc00)
					} else {
						in.pos = mark // a lone lead surrogate rides as itself
					}
				}
				// a surrogate half that never found its partner has no UTF-8
				// encoding: encoding it anyway would manufacture CESU-8 —
				// invalid UTF-8 — out of input that was valid JSON, so it reads
				// as the replacement character
				if code >= 0xd800 && code <= 0xdfff {
					code = 0xfffd
				}
				unitLength = tableJsonEncodeUtf8(code, unit[:])
			default:
				in.bad = true
				return 0, false
			}
		case c < 0x20:
			in.bad = true // a raw control character is not a JSON string body
			return 0, false
		default:
            code, n := utf8.DecodeRune(in.text[in.pos:])
            if code == utf8.RuneError && n == 1 {
                unitLength = tableJsonEncodeUtf8(0xfffd, unit[:])
            } else {
                unitLength = int32(n)
                copy(unit[:], in.text[in.pos:in.pos+n])
            }
            in.pos += n
		}
        if out==nil && wide==nil { placed+=unitLength;continue }
 if wide != nil {
            code,_:=utf8.DecodeRune(unit[:unitLength]);n:=int32(1);if code>=0x10000 {n=2}
            if !clamped && placed+n<=int32(len(wide)) {
                if n==1 {wide[placed]=uint16(code)}else{code-=0x10000;wide[placed]=0xd800+uint16(code>>10);wide[placed+1]=0xdc00+uint16(code&0x3ff)}
                placed+=n
            }else{clamped=true}
        } else if out != nil {
			if !clamped && placed+unitLength <= int32(len(out)) {
				copy(out[placed:], unit[:unitLength])
				placed += unitLength
			} else {
				clamped = true
			}
		}
	}
	if clamped {
		in.report.Clamped++
	}
	return placed, true
}

// walkNumber scans one number, to JSON's OWN grammar (RFC 8259 §6) and not to a
// run of number-ish characters:
//
//	number = [ "-" ] int [ frac ] [ exp ]
//	int    = "0" / ( digit1-9 *digit )
//	frac   = "." 1*digit
//	exp    = ( "e" / "E" ) [ "-" / "+" ] 1*digit
//
// Scanning the production is what makes a typo in an authoring file a
// DIAGNOSTIC rather than a value: "1-2" scans as 1 and leaves "-2" where the
// object expects a comma, so the text is malformed — which is what §16.2
// already promises. A permissive scan would hand "1-2" to a digit loop and
// report a clamp, and a config pipeline would never hear about it. Leading "+",
// leading zeros, ".5" and "3." are not JSON either.
func (in *tableJsonIn) walkNumber() (integral bool, ok bool) {
	in.space()
	whole := true
	if in.pos < len(in.text) && in.text[in.pos] == '-' {
		in.pos++
	}
	// int: a lone zero, or a non-zero digit and any digits after it
	if in.pos >= len(in.text) {
		return false, false
	}
	switch {
	case in.text[in.pos] == '0':
		in.pos++
	case in.text[in.pos] >= '1' && in.text[in.pos] <= '9':
		for in.pos < len(in.text) && in.text[in.pos] >= '0' && in.text[in.pos] <= '9' {
			in.pos++
		}
	default:
		return false, false
	}
	// frac
	if in.pos < len(in.text) && in.text[in.pos] == '.' {
		in.pos++
		if in.pos >= len(in.text) || in.text[in.pos] < '0' || in.text[in.pos] > '9' {
			return false, false
		}
		for in.pos < len(in.text) && in.text[in.pos] >= '0' && in.text[in.pos] <= '9' {
			in.pos++
		}
		whole = false
	}
	// exp
	if in.pos < len(in.text) && (in.text[in.pos] == 'e' || in.text[in.pos] == 'E') {
		in.pos++
		if in.pos < len(in.text) && (in.text[in.pos] == '-' || in.text[in.pos] == '+') {
			in.pos++
		}
		if in.pos >= len(in.text) || in.text[in.pos] < '0' || in.text[in.pos] > '9' {
			return false, false
		}
		for in.pos < len(in.text) && in.text[in.pos] >= '0' && in.text[in.pos] <= '9' {
			in.pos++
		}
		whole = false
	}
	return whole, true
}

// the same production, with the token kept for conversion
func (in *tableJsonIn) scanNumber(token []byte) (n int32, integral bool, ok bool) {
	in.space()
	start := in.pos
	integral, ok = in.walkNumber()
	if !ok {
		return 0, false, false
	}
	count := in.pos - start
	if count <= 0 || count >= len(token) {
		return 0, false, false
	}
	copy(token, in.text[start:in.pos])
	return int32(count), integral, true
}

// the token's exact double. Go's strconv is locale-free, so unlike the C++
// walk's strtod there is no decimal point to cross on the way in.
func tableJsonTokenDouble(token []byte, single bool) float64 {
	bits := 64
	if single {
		bits = 32
	}
	// an out-of-range token is the only failure a scanned production can
	// produce, and ParseFloat still hands back the infinity the caller checks
	value, _ := strconv.ParseFloat(unsafe.String(&token[0], len(token)), bits)
	return value
}

// tableJsonTokenInteger is the token's exact integer, parsed digit by digit so
// no width and no locale can move it. Saturation is reported as a clamp, the
// wire's rule for a value outside what the reader can hold (§4).
func tableJsonTokenInteger(token []byte, isSigned bool) (value int64, saturated bool) {
	i := 0
	negative := false
	if i < len(token) && (token[i] == '-' || token[i] == '+') {
		negative = token[i] == '-'
		i++
	}
	magnitude := uint64(0)
	over := false
	for ; i < len(token); i++ {
		digit := uint64(token[i] - '0')
		if magnitude > (^uint64(0)-digit)/10 {
			over = true
			break
		}
		magnitude = magnitude*10 + digit
	}
	if !isSigned {
		// -0 IS zero, and clamping it would report an event that did not
		// happen; only a real negative magnitude is out of range here
		if negative {
			return 0, magnitude != 0
		}
		if over {
			// the whole unsigned range, carried in the int64 the walk works
			// in: the same bit pattern the C++ cast of UINT64_MAX produces
			return ^int64(0), true
		}
		return int64(magnitude), false
	}
	if negative {
		if over || magnitude > uint64(1)<<63 {
			return math.MinInt64, true
		}
		if magnitude == uint64(1)<<63 {
			return math.MinInt64, false
		}
		return -int64(magnitude), false
	}
	if over || magnitude > uint64(math.MaxInt64) {
		return math.MaxInt64, true
	}
	return int64(magnitude), false
}

func (in *tableJsonIn) skipContainer(closing byte, depth int32) bool {
	if depth > tableJsonMaxDepth {
		in.bad = true
		return false
	}
	in.pos++ // the opening bracket
	for {
		c := in.peek()
		if c == closing {
			in.pos++
			return true
		}
		if c == 0 {
			in.bad = true
			return false
		}
		if closing == '}' {
			if _, ok := in.scanString(nil); !ok {
				return false
			}
			if in.peek() != ':' {
				in.bad = true
				return false
			}
			in.pos++
		}
		if !in.skipValue(depth + 1) {
			return false
		}
		c = in.peek()
		if c == ',' {
			in.pos++ // a trailing comma is accepted
			continue
		}
		if c == closing {
			in.pos++
			return true
		}
		in.bad = true
		return false
	}
}

func (in *tableJsonIn) skipValue(depth int32) bool {
 tableJsonDropLabel(in)
	switch in.peek() {
	case '{':
		return in.skipContainer('}', depth)
	case '[':
		return in.skipContainer(']', depth)
	case '"':
		_, ok := in.scanString(nil)
		return ok
	case 't':
		return in.literal("true")
	case 'f':
		return in.literal("false")
	case 'n':
		return in.literal("null")
	case 0:
		in.bad = true
		return false
	}
	// consumed, never converted: skipping needs no buffer, and this is the one
	// walk a hostile text drives to the depth cap. It is the SAME production
	// the value path scans, so an unknown key cannot smuggle past a number a
	// named key would refuse.
	if _, ok := in.walkNumber(); !ok {
		in.bad = true
		return false
	}
	return true
}

// tableJsonNameIs compares a descriptor's name against a scanned key without
// turning the key into a string, so a read allocates nothing for a comparison.
func tableJsonNameIs(name string, key []byte) bool {
	if len(name) != len(key) {
		return false
	}
	for i := 0; i < len(key); i++ {
		if name[i] != key[i] {
			return false
		}
	}
	return true
}

// tableJsonReadScalar places one scalar at one storage address.
func tableJsonReadScalar(in *tableJsonIn, storage unsafe.Pointer, f *TableFieldInfo, depth int32) bool {
 if f.Pointer {return tableJsonReadPointer(in,(*int64)(storage),f,depth+1)}
	if f.Arms != nil {
		// a union is an object with ONE key, the arm's name; {} is None, and
		// two keys is a text this walk will not guess at
		arms := f.Arms()
		if in.peek() != '{' {
			in.bad = true
			return false
		}
		in.pos++
		tableJsonSetRaw(unsafe.Add(storage, uintptr(arms.TagOffset)), arms.TagSize, 0)
		if in.peek() == '}' {
			in.pos++
			return true
		}
		var key [tableJsonMaxKey]byte
		keyLength, ok := in.scanString(key[:tableJsonMaxKey-1])
		if !ok {
			return false
		}
		if in.peek() != ':' {
			in.bad = true
			return false
		}
		in.pos++
		tag := int64(0)
		for t := int64(1); t <= f.EnumMax; t++ {
			if tableJsonNameIs(f.EnumName(uint64(t)), key[:keyLength]) {
				tag = t
				break
			}
		}
		if tag == 0 {
			in.report.Unknown++
			if !in.skipValue(depth + 1) {
				return false
			}
		} else {
			arm := &arms.Arms[tag]
            want := byte('z'); if !arm.Void { want = tableJsonShape(&arm.Field) }
            if in.valueShape() != want && !(arm.Field.Pointer && !arm.Field.IsArray && in.valueShape()=='z') {
                in.report.KindMismatch++
                if !in.skipValue(depth+1) { return false }
            } else {
                if arm.Void { if !in.literal("null") { return false } } else {
                    arm.Reset(storage)
                    if !tableJsonReadField(in, storage, &arm.Field, depth+1) { return false }
                }
                tableJsonSetRaw(unsafe.Add(storage, uintptr(arms.TagOffset)), arms.TagSize, uint64(tag))
            }
		}
		c := in.peek()
		if c == ',' {
			in.pos++
			c = in.peek()
		}
		if c == '}' {
			in.pos++
			return true
		}
		in.bad = true // a second key: a one-of with two arms is not a value
		return false
	}
	if f.Kind == 13 {
		nested := f.Table()
		nested.Reset(storage)
		return tableJsonReadTable(in, storage, nested, depth+1)
	}
	if tableJsonIsEnum(f) {
		var name [tableJsonMaxKey]byte
		nameLength, ok := in.scanString(name[:tableJsonMaxKey-1])
		if !ok {
			return false
		}
		for v := int64(0); v <= f.EnumMax; v++ {
			if tableJsonNameIs(f.EnumName(uint64(v)), name[:nameLength]) {
				tableJsonSetRaw(storage, f.ElemSize, uint64(v))
				return true
			}
		}
		// a name this build cannot name reads as None and counts as unknown,
		// exactly as an unknown variant id does on the wire (§4)
		tableJsonSetRaw(storage, f.ElemSize, 0)
		in.report.Unknown++
		return true
	}
	if tableJsonIsFlags(f) {
		if in.peek() != '[' {
			in.bad = true
			return false
		}
		in.pos++
		bits := uint64(0)
		for {
			c := in.peek()
			if c == ']' {
				in.pos++
				break
			}
			if c == 0 {
				in.bad = true
				return false
			}
			if c != '"' {
				in.report.KindMismatch++
				if !in.skipValue(depth + 1) {
					return false
				}
			} else {
				var name [tableJsonMaxKey]byte
				nameLength, ok := in.scanString(name[:tableJsonMaxKey-1])
				if !ok {
					return false
				}
				found := false
				for bit := int64(0); bit <= f.EnumMax; bit++ {
					if tableJsonNameIs(f.EnumName(uint64(bit)), name[:nameLength]) {
						bits |= uint64(1) << bit
						found = true
						break
					}
				}
				if !found {
					in.report.Unknown++
				}
			}
			c = in.peek()
			if c == ',' {
				in.pos++
				continue
			}
			if c == ']' {
				in.pos++
				break
			}
			in.bad = true
			return false
		}
		tableJsonSetRaw(storage, f.ElemSize, bits)
		return true
	}
	if f.Kind == 36 {
		return tableJsonReadTimestamp(in, storage, f)
	}
	if f.Kind == 1 {
		if in.peek() == 't' {
			if !in.literal("true") {
				return false
			}
			tableJsonSetRaw(storage, f.ElemSize, 1)
			return true
		}
		if !in.literal("false") {
			return false
		}
		tableJsonSetRaw(storage, f.ElemSize, 0)
		return true
	}
	var scratch [tableJsonMaxNumber]byte
	length, integral, ok := in.scanNumber(scratch[:])
	if !ok {
		in.bad = true
		return false
	}
	token := scratch[:length]
 if f.Kind>=18 && f.Kind<=29 {return tableJsonReadWide(in,token,storage,f)}
	if f.Kind == 10 || f.Kind == 11 {
		single := f.Kind == 10
		value := tableJsonTokenDouble(token, single)
		// A magnitude the field's format cannot hold is the WRONG SHAPE for the
		// kind, and it never reaches storage: 1e400 is not a float64 and 1e300
		// is not a float32. Storing the infinity the conversion produced would
		// leave an instance this walk called CLEAN that ToJsonMeasure then
		// refuses forever (a non-finite float has no JSON spelling), and
		// §16.1's one invariant is that a text which reads clean writes back.
		if !tableJsonFinite(value) {
			in.report.KindMismatch++
			return true
		}
		if f.HasRange {
			// A COMPRESSED FLOAT'S -0 LANDS AS +0 (§3.3, the special values):
			// it is inside the range, so it does not count, and the sign bit
			// is a spelling the declaration cannot name. A NaN or an infinity
			// never reaches this line: the text has no spelling for either
			// and the walk above refused it as kind_mismatch.
			if value < f.RangeMin {
				value = f.RangeMin
				in.report.Clamped++
			} else if value > f.RangeMax {
				value = f.RangeMax
				in.report.Clamped++
			} else if value == 0 {
				value = 0
			}
		}
		if single {
			narrow := float32(value)
			if !tableJsonFinite(float64(narrow)) {
				in.report.KindMismatch++
				return true
			}
			*(*float32)(storage) = narrow
		} else {
			*(*float64)(storage) = value
		}
		return true
	}
	// JSON HAS ONE NUMBER TYPE. 2.0 IS the integer 2 and 1e3 IS 1000, and a
	// library that round-trips numbers through a double emits them that way —
	// this walker's own float writer emits 1e+21. So an integer field takes any
	// number whose VALUE is integral, however it was spelled; only a genuinely
	// fractional value is the wrong shape for it.
	isSigned := f.Kind >= 2 && f.Kind <= 5
	saturated := false
	value := int64(0)
	if integral {
		value, saturated = tableJsonTokenInteger(token, isSigned)
	} else {
		d := tableJsonTokenDouble(token, false)
		if !tableJsonFinite(d) {
			in.report.KindMismatch++
			return true
		}
		if isSigned {
			switch {
			case d >= 9223372036854775808.0:
				value, saturated = math.MaxInt64, true
			case d < -9223372036854775808.0:
				value, saturated = math.MinInt64, true
			case d != float64(int64(d)):
				in.report.KindMismatch++
				return true
			default:
				value = int64(d)
			}
		} else {
			switch {
			case d < 0.0:
				// a negative for an unsigned field clamps to zero, as the exact
				// digit path already does
				if d != float64(int64(d)) {
					in.report.KindMismatch++
					return true
				}
				value, saturated = 0, true
			case d >= 18446744073709551616.0:
				value, saturated = ^int64(0), true
			case d != float64(uint64(d)):
				in.report.KindMismatch++
				return true
			default:
				value = int64(uint64(d))
			}
		}
	}
	if saturated {
		in.report.Clamped++
	}
	if f.HasRange {
		// an integer field clamps against its EXACT range (docs/SPEC-TABLES.md
		// §8.1) so a bound past 2^53 is not degraded through a float64; float
		// and fixed-point ranges keep the float64 pair
		if isSigned {
			if value < f.RangeIntMin {
				value = f.RangeIntMin
				in.report.Clamped++
			} else if value > f.RangeIntMax {
				value = f.RangeIntMax
				in.report.Clamped++
			}
		} else {
			uv := uint64(value)
			if uv < f.RangeUintMin {
				value = int64(f.RangeUintMin)
				in.report.Clamped++
			} else if uv > f.RangeUintMax {
				value = int64(f.RangeUintMax)
				in.report.Clamped++
			}
		}
	}
	// the field's own storage width is the last bound: a value past it clamps
	// rather than wrapping, which is what the wire does too
	if f.ElemSize < 8 {
		if isSigned {
			high := int64(1)<<(f.ElemSize*8-1) - 1
			low := -high - 1
			if value > high {
				value = high
				in.report.Clamped++
			} else if value < low {
				value = low
				in.report.Clamped++
			}
		} else {
			high := uint64(1)<<(f.ElemSize*8) - 1
			if value < 0 {
				value = 0
				in.report.Clamped++
			} else if uint64(value) > high {
				value = int64(high)
				in.report.Clamped++
			}
		}
	}
	// at eight bytes the storage IS the parser's width, and an unsigned value
	// past MaxInt64 rides here as a negative int64 by design — the token parser
	// already turned a NEGATIVE token for an unsigned field into a clamped
	// zero, so there is nothing left to bound.
	tableJsonSetRaw(storage, f.ElemSize, uint64(value))
	return true
}

func tableJsonReadField(in *tableJsonIn, base unsafe.Pointer, f *TableFieldInfo, depth int32) bool {
	storage := unsafe.Add(base, uintptr(f.Offset))
 if f.Map {return tableJsonReadMap(in,storage,f,depth)}
 if f.List {return tableJsonReadList(in,storage,f,depth)}
 if f.Kind==33 {units:=unsafe.Slice((*uint16)(storage),f.ArrayBound);clear(units);n,ok:=in.scanText(nil,units);if !ok{return false};tableJsonSetCount(base,f,n);return true}
	if f.Kind == 12 {
		length, ok := in.scanString(tableJsonBytes(storage, f.ArrayBound))
		if !ok {
			return false
		}
		tableJsonSetCount(base, f, length)
		return true
	}
	if tableJsonIsBytes(f) {
		// A base64 body carries no escapes, so a backslash in one is simply
		// not an alphabet character. Validate the stream and its padding before
		// touching storage, so a malformed body leaves the declared default.
		if in.peek() != '"' {
			in.bad = true
			return false
		}
		in.pos++
		mark := in.pos
		symbols := 0
		pad := 0
		malformed := false
		for {
			if in.pos >= len(in.text) {
				in.bad = true
				return false
			}
			c := in.text[in.pos]
			in.pos++
			if c == '"' {
				break
			}
			if malformed {
				continue
			}
			if c == '=' {
				pad++
				continue
			}
			if pad > 0 {
				malformed = true
				continue
			}
			at := tableJsonBase64Decode[c]
			if at < 0 {
				malformed = true
				continue
			}
			symbols++
		}
		if !malformed {
			if pad > 0 {
				if pad > 2 || (symbols+pad)%4 != 0 || symbols%4 < 2 {
					malformed = true
				}
			} else if symbols%4 == 1 {
				malformed = true
			}
		}
		if malformed {
			// a body that is not base64 is the wrong shape for the kind: the
			// field keeps its default and the event is counted
			in.report.KindMismatch++
			return true
		}
		buffer := tableJsonBytes(storage, f.ArrayBound)
		clear(buffer)
		tableJsonSetCount(base, f, 0)
		placed := int32(0)
		accumulator := uint32(0)
		held := int32(0)
		clamped := false
		for at := mark; ; at++ {
			c := in.text[at]
			if c == '"' || c == '=' {
				break
			}
			symbol := tableJsonBase64Decode[c]
			accumulator = accumulator<<6 | uint32(symbol)
			held += 6
			if held >= 8 {
				held -= 8
				if placed < f.ArrayBound {
					buffer[placed] = byte(accumulator >> held)
					placed++
				} else {
					clamped = true
				}
			}
		}
		if clamped {
			in.report.Clamped++
		}
		tableJsonSetCount(base, f, placed)
		return true
	}
	if tableJsonIsKeyed(f) {
		if in.peek() != '{' {
			in.bad = true
			return false
		}
		in.pos++
		// every slot back to its declared defaults first, so a key the text
		// omits keeps them and a repeated field key cannot leave an earlier
		// occurrence's slots standing
		for i := int32(0); i < f.ArrayBound; i++ {
			slot := unsafe.Add(storage, uintptr(i)*uintptr(f.ElemSize))
			if f.Kind == 13 {
				f.Table().Reset(slot)
			} else {
				clear(unsafe.Slice((*byte)(slot), f.ElemSize))
			}
		}
		shape := tableJsonElementShape(f)
		// A KEYED OBJECT'S KEYS ARE KEYS: a variant named twice is a duplicate
		// key like any other, last-wins and counted (§16.2). Tracked the way a
		// table's own field keys are — a bounded, allocation-free bitmask; a
		// vocabulary wider than this still reads, its repeats simply stop being
		// counted.
		var seen [8]uint64
		for {
			c := in.peek()
			if c == '}' {
				in.pos++
				break
			}
			if c == 0 {
				in.bad = true
				return false
			}
			var key [tableJsonMaxKey]byte
			keyLength, ok := in.scanString(key[:tableJsonMaxKey-1])
			if !ok {
				return false
			}
			if in.peek() != ':' {
				in.bad = true
				return false
			}
			in.pos++
			slot := int32(-1)
			for v := int32(0); v < f.ArrayBound; v++ {
				// nothing is stored for None, so "None" finds no slot and is an
				// unknown key like any other name this reader cannot place
				if !tableJsonKeyedSlotValid(f, v) {
					continue
				}
				if tableJsonNameIs(f.KeyName(tableJsonKeyedSlotKey(v)), key[:keyLength]) {
					slot = v
					break
				}
			}
			if slot >= 0 && slot < 512 {
				bit := uint64(1) << (slot & 63)
				if seen[slot>>6]&bit != 0 {
					in.report.Duplicate++
				}
				seen[slot>>6] |= bit
			}
			switch {
			case slot < 0:
				in.report.Unknown++
				if !in.skipValue(depth + 1) {
					return false
				}
			case in.valueShape() != shape && !(f.Pointer && in.valueShape()=='z'):
				in.report.KindMismatch++
				if !in.skipValue(depth + 1) {
					return false
				}
			default:
				if !tableJsonReadScalar(in, unsafe.Add(storage, uintptr(slot)*uintptr(f.ElemSize)), f, depth+1) {
					return false
				}
			}
			c = in.peek()
			if c == ',' {
				in.pos++ // a trailing comma is accepted
				continue
			}
			if c == '}' {
				in.pos++
				break
			}
			in.bad = true
			return false
		}
		return true
	}
	if f.IsArray {
		if in.peek() != '[' {
			in.bad = true
			return false
		}
		in.pos++
		// LAST WINS has to be true of a repeated ARRAY key too, and it is
		// wire-visible: a fixed array writes every slot, so a second, shorter
		// occurrence overlaying a prefix would leave the first occurrence's
		// tail standing. The field goes back to its declared defaults before
		// this occurrence's elements are placed — the re-establishment a nested
		// table and a union arm already get. A table element's defaults are its
		// own (the reset hook); every other element kind's storage default is
		// zero, which is what the generated array declares.
		if f.Kind == 13 {
			for i := int32(0); i < f.ArrayBound; i++ {
				f.Table().Reset(unsafe.Add(storage, uintptr(i)*uintptr(f.ElemSize)))
			}
		} else {
			clear(unsafe.Slice((*byte)(storage), int64(f.ArrayBound)*int64(f.ElemSize)))
		}
		tableJsonSetCount(base, f, 0)
		placed := int32(0)
		shape := tableJsonElementShape(f)
		for {
			c := in.peek()
			if c == ']' {
				in.pos++
				break
			}
			if c == 0 {
				in.bad = true
				return false
			}
			switch {
			case placed >= f.ArrayBound:
				// more elements than the reader's bound: the bounded prefix is
				// kept and the excess counts, the wire's rule (§4)
				in.report.Clamped++
				if !in.skipValue(depth + 1) {
					return false
				}
			case in.valueShape() != shape && !(f.Pointer && in.valueShape()=='z'):
				in.report.KindMismatch++
				if !in.skipValue(depth + 1) {
					return false
				}
				placed++
			default:
				if !tableJsonReadScalar(in, unsafe.Add(storage, uintptr(placed)*uintptr(f.ElemSize)), f, depth+1) {
					return false
				}
				placed++
			}
			c = in.peek()
			if c == ',' {
				in.pos++
				continue
			}
			if c == ']' {
				in.pos++
				break
			}
			in.bad = true
			return false
		}
		// a fixed array's tail keeps the defaults the prefill left there,
		// exactly as a short wire count does
		tableJsonSetCount(base, f, placed)
		return true
	}
	return tableJsonReadScalar(in, storage, f, depth)
}

// tableJsonReadTable reads ONE table object: keys are field keys, unknown ones
// are skipped and counted, a repeated key is last-wins and counted. The
// instance is already at its declared defaults when this is entered, so a key
// the text never mentions keeps the default an absent field takes on the wire
// (§4).
func tableJsonReadTable(in *tableJsonIn, base unsafe.Pointer, info *TableTypeInfo, depth int32) bool {
	if depth > tableJsonMaxDepth {
		in.bad = true
		return false
	}
	if in.peek() != '{' {
		in.bad = true
		return false
	}
	in.pos++
 return tableJsonReadTableFields(in,base,info,depth,true)
}
func tableJsonReadTableFields(in *tableJsonIn,base unsafe.Pointer,info *TableTypeInfo,depth int32,emptyAllowed bool) bool {
	// duplicate tracking, bounded and allocation-free: a table with more fields
	// than this still reads, its repeats simply stop being counted
	var seen [8]uint64
	for {
		c := in.peek()
		if c == '}' {
			in.pos++
			return true
		}
		if c == 0 {
			in.bad = true
			return false
		}
		var key [tableJsonMaxKey]byte
		keyLength, ok := in.scanString(key[:tableJsonMaxKey-1])
		if !ok {
			return false
		}
		if in.peek() != ':' {
			in.bad = true
			return false
		}
		in.pos++
		index := -1
		for i := range info.Fields {
			if tableJsonNameIs(info.Fields[i].Json, key[:keyLength]) {
				index = i
				break
			}
		}
		if keyLength > 0 && key[0] == '&' {
			// THE AMPERSAND PREFIX IS RESERVED TO THE FORM (docs/SPEC-TABLES.md
			// 16.7): never a field this build lacks, always a construct it
			// cannot honor. MALFORMED and refused, never counted as unknown.
			in.report.Malformed = true
			in.bad = true
			return false
		}
		if index < 0 {
			in.report.Unknown++
			if !in.skipValue(depth + 1) {
				return false
			}
		} else {
			f := &info.Fields[index]
			if index < 512 {
				bit := uint64(1) << (index & 63)
				if seen[index>>6]&bit != 0 {
					in.report.Duplicate++
				}
				seen[index>>6] |= bit
			}
			// PRESENCE OF THE KEY IS THE PRESENCE (§16.2): reaching this line
			// is the key being present, so an optional is set present whatever
			// its value — with one exception the page names: a JSON null, which
			// reads as ABSENT rather than as a value.
			got := in.valueShape()
			if f.Optional && got == 'z' {
				if !in.literal("null") {
					return false
				}
				// absent, and back at its defaults: a repeated key whose last
				// occurrence is null must not leave an earlier value standing
				if f.Table != nil {
					f.Table().Reset(unsafe.Add(base, uintptr(f.Offset)))
				} else {
					clear(unsafe.Slice((*byte)(unsafe.Add(base, uintptr(f.Offset))), f.ElemSize))
				}
				tableJsonSetRaw(unsafe.Add(base, uintptr(f.PresentOffset)), 1, 0)
			} else {
				if got != tableJsonShape(f) && !(f.Pointer && !f.IsArray && got=='z') {
					// the wrong JSON type for the kind: skipped, never coerced
					in.report.KindMismatch++
					if !in.skipValue(depth + 1) {
						return false
					}
				} else if !tableJsonReadField(in, base, f, depth) {
					return false
				}
				if f.Optional {
					tableJsonSetRaw(unsafe.Add(base, uintptr(f.PresentOffset)), 1, 1)
				}
			}
		}
		c = in.peek()
		if c == ',' {
			in.pos++ // a trailing comma is accepted
			continue
		}
		if c == '}' {
			in.pos++
			return true
		}
		in.bad = true
		return false
	}
}

