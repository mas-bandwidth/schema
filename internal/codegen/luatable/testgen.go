// Testgen writes the generated round-trip and damage tests of a unit
// (docs/SPEC-TABLES.md §16.11): one <Base>Table_gen_test.lua per unit file
// that declares a root table, beside the module Generate writes, using the
// generated API and the pinned Lua 5.4 interpreter alone. It writes nothing;
// the caller places the files beside what Generate wrote. The output is
// deterministic to the byte: every sample is built from the declaration alone.
func Testgen(u *ir.Unit) (map[string][]byte, error) {
	module := ModuleName(u)
	variable := ir.VariableTables(u)
	out := map[string][]byte{}
	for _, f := range u.Files {
		var roots []*ir.Struct
		for _, st := range f.Tables {
			// §16.11: a ROOT TABLE is every declared table; a generated map
			// entry or text-list element record is not one
			if st.IsTable && !st.IsMapEntry() {
				roots = append(roots, st)
			}
		}
		if len(roots) == 0 {
			continue
		}
		var body strings.Builder
		var cases []string
		for _, st := range roots {
			// §16.11: the sample is spelled in the JSON form and the round
			// trip crosses the wire, so a table without either is refused
			for _, form := range []string{"wire", "json"} {
				if !st.CarriesForm(form) {
					return nil, fmt.Errorf("testgen: table %s does not carry the %s form, and its generated tests spell the sample in JSON and cross the wire (docs/SPEC-TABLES.md §16.11)", st.Name, form)
				}
			}
			if field := ltgUnreadableUint64(st, map[*ir.Struct]bool{}); field != "" {
				// THE JSON READER'S BOUND (§16.2): an unsigned 64-bit bound
				// above 2^63-1 is a Lua integer with the same bits, and the
				// tolerating read reads it as a negative bound, so no sample
				// can be silent. The gap is written down, not skipped in
				// silence.
				fmt.Fprintf(&body, "\n-- not generated: %s — field %s has an unsigned 64-bit bound above 2^63-1,\n-- which the Lua JSON reader cannot read (docs/PORT-LUA.md)\n", st.Name, field)
				continue
			}
			samples, err := ltgSamples(st)
			if err != nil {
				return nil, err
			}
			ltgRoundTrip(&body, st, variable[st.Name], samples)
			ltgDamage(&body, st, variable[st.Name], samples)
			cases = append(cases, `{"Test`+st.Name+`GenRoundTrip", Test`+st.Name+`GenRoundTrip}`)
			cases = append(cases, `{"Test`+st.Name+`GenDamage", Test`+st.Name+`GenDamage}`)
		}
		var src strings.Builder
		fmt.Fprintf(&src, "-- Code generated by the schema compiler from %s.schema (schema testgen). DO NOT EDIT.\n", f.Base)
		src.WriteString("-- SPDX-License-Identifier: NONE — this generated output is yours, under terms of\n")
		src.WriteString("-- your choice. See the LICENSE exception in the schema compiler; the compiler is\n")
		src.WriteString("-- AGPL-3.0, its output is not.\n")
		src.WriteString("-- The round-trip and damage tests of mas-bandwidth/schema docs/SPEC-TABLES.md §16.11.\n\n")
		src.WriteString(ltgHarness(module))
		src.WriteString(body.String())
		src.WriteString("\n-- THE RUNNER: every test in its own protected call, so one failure still runs the\n")
		src.WriteString("-- rest; the process exits 1 when any test failed.\n")
		src.WriteString("local cases = {\n")
		for _, c := range cases {
			src.WriteString("\t" + c + ",\n")
		}
		src.WriteString("}\nlocal failed = 0\nfor _, c in ipairs(cases) do\n")
		src.WriteString("\tlocal ok, err = pcall(c[2])\n")
		src.WriteString("\tif ok then print(\"PASS \" .. c[1]) else\n")
		src.WriteString("\t\tfailed = failed + 1\n\t\tio.stderr:write(\"FAIL \" .. c[1] .. \": \" .. tostring(err) .. \"\\n\")\n")
		src.WriteString("\tend\nend\n")
		src.WriteString("if failed > 0 then os.exit(1) end\n")
		fmt.Fprintf(&src, "print(\"PASS %s\")\n", f.Base+"Table_gen_test.lua")
		out[f.Base+"Table_gen_test.lua"] = []byte(src.String())
	}
	return out, nil
}

// ltgHarness is the shared preamble of one generated file: the module, the
// carriers, and the checks every test uses (§16.11).
func ltgHarness(module string) string {
	return `local T = require("` + module + `")
local load = require("load")
local save = require("save")
local json = require("json")
local text = require("text")
local refusal = require("refusal")

-- §4: a read of a sample the generator built is SILENT.
local function report()
  return { malformed = false, refused = 0, unknown = 0, kindMismatch = 0,
    clamped = 0, widened = 0, duplicate = 0 }
end

local function silent(r)
  return not r.malformed and r.refused == 0 and r.unknown == 0 and
    r.kindMismatch == 0 and r.clamped == 0 and r.widened == 0 and r.duplicate == 0
end

local function check(cond, msg)
  if not cond then error(msg, 0) end
end

-- THE REFUSAL'S NAME is the word before the first colon (§6.5, §11).
local function errname(err)
  local s = tostring(err)
  return s:match("^([%a_]+):") or s
end

local function refused(ok, err, names)
  if ok then return false end
  local name = errname(err)
  for _, want in ipairs(names) do
    if name == want then return true end
  end
  return false
end

-- §16.8: the standard padded base64 alphabet, so SaveText's text can be
-- checked against the wire it claims to carry.
local alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local function b64(s)
  local out = {}
  local i, n = 1, #s
  while i + 2 <= n do
    local a, b, c = s:byte(i, i + 2)
    local v = (a << 16) | (b << 8) | c
    out[#out + 1] = alphabet:sub(((v >> 18) & 63) + 1, ((v >> 18) & 63) + 1)
    out[#out + 1] = alphabet:sub(((v >> 12) & 63) + 1, ((v >> 12) & 63) + 1)
    out[#out + 1] = alphabet:sub(((v >> 6) & 63) + 1, ((v >> 6) & 63) + 1)
    out[#out + 1] = alphabet:sub((v & 63) + 1, (v & 63) + 1)
    i = i + 3
  end
  local rem = n - i + 1
  if rem == 1 then
    local v = s:byte(i) << 16
    out[#out + 1] = alphabet:sub(((v >> 18) & 63) + 1, ((v >> 18) & 63) + 1)
    out[#out + 1] = alphabet:sub(((v >> 12) & 63) + 1, ((v >> 12) & 63) + 1)
    out[#out + 1] = "="
    out[#out + 1] = "="
  elseif rem == 2 then
    local a, b = s:byte(i, i + 1)
    local v = (a << 16) | (b << 8)
    out[#out + 1] = alphabet:sub(((v >> 18) & 63) + 1, ((v >> 18) & 63) + 1)
    out[#out + 1] = alphabet:sub(((v >> 12) & 63) + 1, ((v >> 12) & 63) + 1)
    out[#out + 1] = alphabet:sub(((v >> 6) & 63) + 1, ((v >> 6) & 63) + 1)
    out[#out + 1] = "="
  end
  return table.concat(out)
end

-- same_equal: the value read saves to exactly the wire and writes exactly the
-- JSON text the sample did (§16.11).
local function same_equal(name, leg, wantWire, wantJson, got)
  check(got ~= nil, name .. ": " .. leg .. ": nothing read")
  local wire = save.Save(T, name, got)
  check(wire == wantWire, name .. ": " .. leg .. ": the value read saves to a different wire")
  local wrote = json.ToJson(T, name, got)
  check(wrote ~= nil and wrote == wantJson, name .. ": " .. leg .. ": the value read writes different JSON")
end

`
}

// The sample modes of §16.11.
const (
	ltgDefaults = iota
	ltgLow
	ltgHigh
	ltgInside
	ltgArm
)

type ltgSample struct {
	name string
	expr string // a Lua expression whose value is the sample's JSON text
}

// ltgSamples builds a root table's samples (§16.11): defaults, low, high,
// inside, and arm_<k> for every arm past the first of the widest union.
func ltgSamples(st *ir.Struct) ([]ltgSample, error) {
	arms := ltgMaxArms(st, map[*ir.Struct]bool{}, map[*ir.Union]bool{})
	var out []ltgSample
	modes := []struct {
		name string
		mode int
		arm  int
	}{{"defaults", ltgDefaults, 0}, {"low", ltgLow, 0}, {"high", ltgHigh, 0}, {"inside", ltgInside, 0}}
	for k := 1; k < arms; k++ {
		modes = append(modes, struct {
			name string
			mode int
			arm  int
		}{"arm_" + strconv.Itoa(k), ltgArm, k})
	}
	for _, m := range modes {
		g := &ltgGen{mode: m.mode, arm: m.arm, path: map[string]bool{}}
		var j ltgJSON
		if err := g.table(&j, st); err != nil {
			return nil, err
		}
		out = append(out, ltgSample{m.name, j.expr()})
	}
	return out, nil
}

// ltgUnreadableUint64 names a declared unsigned 64-bit bound above 2^63-1 in
// st's closure. The Lua reader keeps that bound as a negative Lua integer and
// reads every value against it as past the bound (§16.2), so no sample of the
// table can be silent.
func ltgUnreadableUint64(st *ir.Struct, seen map[*ir.Struct]bool) string {
	if st == nil || seen[st] {
		return ""
	}
	seen[st] = true
	maxInt64 := new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), 63), big.NewInt(1))
	var field func(f *ir.Field) string
	field = func(f *ir.Field) string {
		if f == nil {
			return ""
		}
		t := f.Type
		if t.Kind == ir.TInt && t.Width == 64 && !t.Signed {
			if _, hi, ok := ir.TableRawRange(f); ok && hi.Cmp(maxInt64) > 0 {
				return f.Name
			}
		}
		if f.IsMap() {
			if name := field(ir.MapValueField(f)); name != "" {
				return name
			}
		}
		if t.Kind == ir.TNamed {
			switch ref := t.Ref.(type) {
			case *ir.Struct:
				for _, inner := range ref.Fields {
					if name := field(inner); name != "" {
						return name
					}
				}
			case *ir.Union:
				for _, v := range ref.Variants {
					if name := field(v.F); name != "" {
						return name
					}
				}
			}
		}
		return ""
	}
	for _, f := range st.Fields {
		if name := field(f); name != "" {
			return name
		}
	}
	return ""
}

// ltgMaxArms is the largest arm count of any union the table reaches.
func ltgMaxArms(st *ir.Struct, seen map[*ir.Struct]bool, useen map[*ir.Union]bool) int {
	if st == nil || seen[st] {
		return 0
	}
	seen[st] = true
	n := 0
	var field func(f *ir.Field)
	field = func(f *ir.Field) {
		if f == nil {
			return
		}
		if f.IsMap() {
			field(ir.MapValueField(f))
			return
		}
		switch ref := f.Type.Ref.(type) {
		case *ir.Struct:
			n = max(n, ltgMaxArms(ref, seen, useen))
		case *ir.Union:
			if useen[ref] {
				return
			}
			useen[ref] = true
			n = max(n, len(ref.Variants))
			for _, v := range ref.Variants {
				field(v.F)
			}
		}
	}
	for _, f := range st.Fields {
		field(f)
	}
	return n
}

// ltgJSON accumulates a Lua expression that concatenates literal JSON with
// computed runs (a long string, a long array), so a sample at a 70000 bound is
// a short line of source.
type ltgJSON struct {
	parts []string
	lit   strings.Builder
}

func (j *ltgJSON) raw(s string) { j.lit.WriteString(s) }

func (j *ltgJSON) code(e string) {
	j.flush()
	j.parts = append(j.parts, e)
}

func (j *ltgJSON) flush() {
	if j.lit.Len() > 0 {
		j.parts = append(j.parts, ltgQuote(j.lit.String()))
		j.lit.Reset()
	}
}

func (j *ltgJSON) expr() string {
	j.flush()
	if len(j.parts) == 0 {
		return `""`
	}
	return strings.Join(j.parts, " .. ")
}

// ltgQuote renders s as a Lua string literal. The samples are ASCII JSON, and
// Lua 5.4 takes the \ddd decimal escapes for the bytes outside it.
func ltgQuote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteByte(c)
		case '\n':
			b.WriteString("\\n")
		case '\r':
			b.WriteString("\\r")
		case '\t':
			b.WriteString("\\t")
		default:
			if c < 0x20 || c >= 0x7f {
				fmt.Fprintf(&b, "\\%03d", c)
			} else {
				b.WriteByte(c)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// ltgGen spells one sample. path holds the tables on the current pointer path,
// so a recursive declaration ends in null (§16.11).
type ltgGen struct {
	mode int
	arm  int
	path map[string]bool
}

// table writes a table or type body as its JSON object, or as its one field's
// array for a `json = "array"` table (§16.10).
func (g *ltgGen) table(j *ltgJSON, st *ir.Struct) error {
	if st.JsonArray {
		if len(st.Fields) != 1 {
			return fmt.Errorf("testgen: %s is json = \"array\" with %d fields", st.Name, len(st.Fields))
		}
		return g.value(j, st.Fields[0], true)
	}
	if g.mode == ltgDefaults {
		// §16.11 defaults: `{}`, with a required field at its low value
		j.raw("{")
		first := true
		for _, f := range st.Fields {
			if !f.Required || f.Deprecated {
				continue
			}
			if !first {
				j.raw(",")
			}
			first = false
			j.raw(ltgQuote(ir.TableFieldJsonKey(f)) + ":")
			low := &ltgGen{mode: ltgLow, path: g.path}
			if err := low.value(j, f, true); err != nil {
				return err
			}
		}
		j.raw("}")
		return nil
	}
	j.raw("{")
	first := true
	for _, f := range st.Fields {
		if f.Deprecated {
			continue
		}
		if !first {
			j.raw(",")
		}
		first = false
		j.raw(ltgQuote(ir.TableFieldJsonKey(f)) + ":")
		if err := g.value(j, f, true); err != nil {
			return err
		}
	}
	j.raw("}")
	return nil
}

// value writes one field line's JSON value by its §16.2 row. whole is false
// when writing an ELEMENT of the field's array.
func (g *ltgGen) value(j *ltgJSON, f *ir.Field, whole bool) error {
	if whole && f.IsMap() {
		return g.mapValue(j, f)
	}
	if whole && f.Array != ir.ArrayNone {
		return g.array(j, f)
	}
	t := f.Type
	if t.Pointer {
		return g.pointer(j, f)
	}
	switch t.Kind {
	case ir.TBool:
		j.raw(strconv.FormatBool(g.mode == ltgHigh || g.mode == ltgInside || g.mode == ltgArm))
	case ir.TInt, ir.TBits:
		if t.Kind == ir.TInt && t.Timestamp {
			if g.mode == ltgLow {
				j.raw(`"1970-01-01T00:00:00Z"`)
			} else {
				j.raw(`"2026-10-15T12:34:05.123456789Z"`)
			}
			return nil
		}
		lo, hi := ltgIntRange(f)
		j.raw(g.pick(lo, hi).String())
	case ir.TFixed:
		lo, hi := ltgIntRange(f)
		raw := g.pick(lo, hi)
		j.raw(ltgFixedDecimal(raw, t.FracBits))
	case ir.TFloat32, ir.TFloat64:
		j.raw(g.float(f))
	case ir.TString, ir.TWString:
		n := g.length(t.Size)
		g.text(j, n)
	case ir.TBytes:
		g.bytesValue(j, g.length(t.Size))
	case ir.TNamed:
		switch ref := t.Ref.(type) {
		case *ir.Struct:
			if ref.IsTextListElem() {
				return g.value(j, ref.Fields[0], true)
			}
			return g.table(j, ref)
		case *ir.Enum:
			j.raw(ltgQuote(g.variant(ref.Variants)))
		case *ir.Flags:
			j.raw("[")
			var names []string
			switch g.mode {
			case ltgHigh:
				names = ref.Variants
			case ltgLow:
			default:
				names = ref.Variants[:min(1, len(ref.Variants))]
			}
			for i, n := range names {
				if i > 0 {
					j.raw(",")
				}
				j.raw(ltgQuote(n))
			}
			j.raw("]")
		case *ir.Union:
			return g.union(j, ref)
		default:
			return fmt.Errorf("testgen: field %s names %s, a declaration testgen does not spell (docs/SPEC-TABLES.md §16.11)", f.Name, t.Name)
		}
	default:
		return fmt.Errorf("testgen: field %s is %s, a kind testgen does not spell (docs/SPEC-TABLES.md §16.11)", f.Name, ir.FieldTypeSpelling(f))
	}
	return nil
}

// pick chooses a bounded integer by the sample's mode (§16.11).
func (g *ltgGen) pick(lo, hi *big.Int) *big.Int {
	switch g.mode {
	case ltgLow:
		return lo
	case ltgHigh:
		return hi
	}
	// §16.11's inside value is strictly inside where the range leaves room.
	// A range that crosses zero takes 0: the Lua reader's negative bounds are
	// read by magnitude (§16.2), and only the bound itself reads exactly.
	if lo.Sign() < 0 && hi.Sign() > 0 {
		return big.NewInt(0)
	}
	span := new(big.Int).Sub(hi, lo)
	if span.Cmp(big.NewInt(2)) >= 0 {
		return new(big.Int).Add(lo, big.NewInt(1))
	}
	return lo
}

// length chooses a bounded extent: empty, the bound, or one inside it.
func (g *ltgGen) length(bound int64) int64 {
	switch g.mode {
	case ltgLow:
		return 0
	case ltgHigh:
		return bound
	}
	return min(1, bound)
}

func (g *ltgGen) variant(vs []string) string {
	switch g.mode {
	case ltgLow:
		return vs[0]
	case ltgHigh:
		return vs[len(vs)-1]
	}
	return vs[len(vs)/2]
}

// float spells a float: a compressed float's own range, else values every
// width holds exactly.
func (g *ltgGen) float(f *ir.Field) string {
	if f.HasFloatRange {
		v := f.FMin
		switch g.mode {
		case ltgHigh:
			v = f.FMin + float64(f.Steps)*f.Resolution
			if v > f.FMax {
				v = f.FMin + float64(f.Steps-1)*f.Resolution
			}
		case ltgInside, ltgArm:
			if f.Steps >= 2 {
				v = f.FMin + f.Resolution
			}
		}
		bits := 64
		if f.Type.Kind == ir.TFloat32 {
			bits = 32
		}
		return strconv.FormatFloat(v, 'g', -1, bits)
	}
	switch g.mode {
	case ltgLow:
		return "-1.5"
	case ltgHigh:
		return "1.5"
	}
	return "0.25"
}

// text writes a JSON string of n ASCII bytes.
func (g *ltgGen) text(j *ltgJSON, n int64) {
	if n <= 64 {
		j.raw(ltgQuote(strings.Repeat("a", int(n))))
		return
	}
	j.raw(`"`)
	j.code(fmt.Sprintf("string.rep(%q, %d)", "a", n))
	j.raw(`"`)
}

// bytesValue writes n bytes as padded standard base64 (§16.2).
func (g *ltgGen) bytesValue(j *ltgJSON, n int64) {
	j.raw(ltgQuote(base64.StdEncoding.EncodeToString(bytes.Repeat([]byte{0x5a}, int(n)))))
}

// pointer writes `*T` as the pointee's object, or null when T is on the path;
// `*bytes`, `*string` and `*wstring` as their blob (§2.5, §16.2).
func (g *ltgGen) pointer(j *ltgJSON, f *ir.Field) error {
	t := f.Type
	switch t.Kind {
	case ir.TBytes:
		g.bytesValue(j, g.unbounded())
		return nil
	case ir.TString, ir.TWString:
		g.text(j, g.unbounded())
		return nil
	}
	st, ok := t.Ref.(*ir.Struct)
	if !ok {
		return fmt.Errorf("testgen: pointer field %s names no table (docs/SPEC-TABLES.md §16.11)", f.Name)
	}
	if g.path[st.Name] {
		j.raw("null")
		return nil
	}
	g.path[st.Name] = true
	defer delete(g.path, st.Name)
	return g.table(j, st)
}

// unbounded is an unbounded collection's extent: empty, two, or one (§16.11).
func (g *ltgGen) unbounded() int64 {
	switch g.mode {
	case ltgLow:
		return 0
	case ltgHigh:
		return 2
	}
	return 1
}

// union writes the one-key object of the arm the mode selects (§16.2).
func (g *ltgGen) union(j *ltgJSON, un *ir.Union) error {
	if len(un.Variants) == 0 {
		j.raw("{}")
		return nil
	}
	v := un.Variants[g.arm%len(un.Variants)]
	key := v.Name
	j.raw("{" + ltgQuote(key) + ":")
	if v.Void() {
		j.raw("null")
	} else if err := g.value(j, v.F, true); err != nil {
		return err
	}
	j.raw("}")
	return nil
}

// array writes `[N]T`, `[..N]T`, `[E]T` and `[]T` by their rows (§16.2).
func (g *ltgGen) array(j *ltgJSON, f *ir.Field) error {
	if f.KeyEnumRef != nil {
		j.raw("{")
		for i, name := range f.KeyEnumRef.Variants {
			if i > 0 {
				j.raw(",")
			}
			j.raw(ltgQuote(name) + ":")
			if err := g.value(j, f, false); err != nil {
				return err
			}
		}
		j.raw("}")
		return nil
	}
	var n int64
	switch f.Array {
	case ir.ArrayFixed:
		n = f.ArrayBound
	case ir.ArrayCounted:
		switch g.mode {
		case ltgLow:
			n = f.ArrayMin
		case ltgHigh:
			n = f.ArrayBound
		default:
			n = min(f.ArrayMin+1, f.ArrayBound)
		}
	case ir.ArrayList:
		n = g.unbounded()
	}
	// a `?string(M)` text-list element is written absent once, in high (§16.11)
	absentFirst := false
	if elem := f.TextListElem(); elem != nil && g.mode == ltgHigh && n > 0 && elem.Fields[0].Type.Optional {
		absentFirst = true
	}
	one := func(i int64) (string, error) {
		if i == 0 && absentFirst {
			return ltgQuote("null"), nil
		}
		var e ltgJSON
		if err := g.value(&e, f, false); err != nil {
			return "", err
		}
		return e.expr(), nil
	}
	j.raw("[")
	if n <= 4 {
		for i := int64(0); i < n; i++ {
			if i > 0 {
				j.raw(",")
			}
			e, err := one(i)
			if err != nil {
				return err
			}
			j.code(e)
		}
	} else {
		first, err := one(0)
		if err != nil {
			return err
		}
		rest, err := one(1)
		if err != nil {
			return err
		}
		j.code(first)
		j.code(fmt.Sprintf("string.rep(\",\" .. (%s), %d)", rest, n-1))
	}
	j.raw("]")
	return nil
}

// mapValue writes `map[K]V` as an object keyed in ascending order (§2.8,
// §16.2): empty, two entries or one.
func (g *ltgGen) mapValue(j *ltgJSON, f *ir.Field) error {
	key, val := ir.MapKeyField(f), ir.MapValueField(f)
	n := g.unbounded()
	var keys []string
	if key.Type.Kind == ir.TString || key.Type.Kind == ir.TWString {
		for i := range n {
			keys = append(keys, string(rune('a'+i)))
		}
	} else {
		lo, hi := ltgIntRange(key)
		for i := range n {
			k := new(big.Int).Add(lo, big.NewInt(i))
			if k.Cmp(hi) > 0 {
				break
			}
			keys = append(keys, k.String())
		}
	}
	j.raw("{")
	for i, k := range keys {
		if i > 0 {
			j.raw(",")
		}
		j.raw(ltgQuote(k) + ":")
		if err := g.value(j, val, true); err != nil {
			return err
		}
	}
	j.raw("}")
	return nil
}

// ltgIntRange is an integer-like field's range on the scale its JSON token
// carries: declared, else implied by its storage.
func ltgIntRange(f *ir.Field) (lo, hi *big.Int) {
	if lo, hi, ok := ir.TableRawRange(f); ok {
		return lo, hi
	}
	width := f.Type.Width
	signed := f.Type.Signed && f.Type.Kind != ir.TBits
	if signed {
		hi = new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), uint(width-1)), big.NewInt(1))
		lo = new(big.Int).Neg(new(big.Int).Lsh(big.NewInt(1), uint(width-1)))
		return lo, hi
	}
	return big.NewInt(0), new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), uint(width)), big.NewInt(1))
}

// ltgFixedDecimal spells a fixed-point raw value in whole units, exactly
// (§16.2's fixed row).
func ltgFixedDecimal(raw *big.Int, frac int) string {
	r := new(big.Rat).SetFrac(raw, new(big.Int).Lsh(big.NewInt(1), uint(frac)))
	return r.FloatString(max(frac, 1))
}

// ltgRoundTrip writes Test<Name>GenRoundTrip: every sample read equal through
// the binary wire, base64 text and JSON text (§16.11).
func ltgRoundTrip(b *strings.Builder, st *ir.Struct, variable bool, samples []ltgSample) {
	n := st.Name
	fmt.Fprintf(b, "\n-- Test%sGenRoundTrip reads every sample of %s back through the binary wire,\n-- base64 text and JSON text, each equal to what was written (§16.11).\n", n, n)
	fmt.Fprintf(b, "local samples_%s = {\n", n)
	for _, s := range samples {
		fmt.Fprintf(b, "\t{ name = %s, text = %s },\n", ltgQuote(s.name), s.expr)
	}
	fmt.Fprintf(b, "}\n\nlocal function Test%sGenRoundTrip()\n", n)
	fmt.Fprintf(b, "\tfor _, s in ipairs(samples_%s) do\n", n)
	b.WriteString("\t\tlocal ok, err = pcall(function()\n")
	fmt.Fprintf(b, "\t\t\tlocal r = report()\n\t\t\tlocal v = json.FromJson(T, %q, s.text, r)\n", n)
	fmt.Fprintf(b, "\t\t\tcheck(v ~= nil, %q .. s.name .. %q)\n", n+": ", ": FromJson of the sample returned nothing")
	b.WriteString("\t\t\tcheck(silent(r), " + strconv.Quote(n+": ") + " .. s.name .. \": FromJson of the sample is not silent\")\n")
	fmt.Fprintf(b, "\t\t\tlocal wire = save.Save(T, %q, v)\n\t\t\tcheck(wire ~= nil, %q .. s.name .. %q)\n", n, n+": ", ": Save refused the sample")
	fmt.Fprintf(b, "\t\t\tlocal jsonText = json.ToJson(T, %q, v)\n\t\t\tcheck(jsonText ~= nil, %q .. s.name .. %q)\n", n, n+": ", ": ToJson refused the sample")
	b.WriteString("\t\t\t-- 1. the binary wire, through the strict read (§6.5)\n")
	fmt.Fprintf(b, "\t\t\tlocal rok, got = pcall(refusal.ReadStrict, T, %q, wire)\n", n)
	fmt.Fprintf(b, "\t\t\tcheck(rok and got ~= nil, %q .. s.name .. %q .. tostring(got))\n", n+": ", ": binary: ReadStrict: ")
	fmt.Fprintf(b, "\t\t\tif rok and got ~= nil then same_equal(%q, \"binary\", wire, jsonText, got) end\n", n)
	b.WriteString("\t\t\t-- 2. base64 text, through SaveText then LoadText (§16.8)\n")
	fmt.Fprintf(b, "\t\t\tlocal b64text = text.SaveText(T, %q, v)\n", n)
	fmt.Fprintf(b, "\t\t\tcheck(b64text ~= nil and b64text == b64(wire), %q .. s.name .. %q)\n", n+": ", ": base64: SaveText is not the standard base64 of the wire")
	b.WriteString("\t\t\tlocal tr = report()\n")
	fmt.Fprintf(b, "\t\t\tlocal tok, tgot = pcall(text.LoadText, T, %q, b64text, tr)\n", n)
	fmt.Fprintf(b, "\t\t\tcheck(tok and tgot ~= nil and silent(tr), %q .. s.name .. %q .. tostring(tgot))\n", n+": ", ": base64: LoadText: ")
	fmt.Fprintf(b, "\t\t\tif tok and tgot ~= nil then same_equal(%q, \"base64\", wire, jsonText, tgot) end\n", n)
	b.WriteString("\t\t\t-- 3. JSON text, through ToJson then FromJson (§16.1)\n")
	b.WriteString("\t\t\tlocal jr = report()\n")
	fmt.Fprintf(b, "\t\t\tlocal jgot = json.FromJson(T, %q, jsonText, jr)\n", n)
	fmt.Fprintf(b, "\t\t\tcheck(jgot ~= nil and silent(jr), %q .. s.name .. %q)\n", n+": ", ": json: FromJson of ToJson's text is not silent")
	fmt.Fprintf(b, "\t\t\tif jgot ~= nil then same_equal(%q, \"json\", wire, jsonText, jgot) end\n", n)
	b.WriteString("\t\tend)\n\t\tif not ok then error(s.name .. \": \" .. tostring(err), 0) end\n")
	b.WriteString("\tend\nend\n")
}

// ltgDamage writes Test<Name>GenDamage: the high sample's wire and texts,
// damaged, each refused by its named reason (§16.11).
func ltgDamage(b *strings.Builder, st *ir.Struct, variable bool, samples []ltgSample) {
	n := st.Name
	high := samples[0].expr
	for _, s := range samples {
		if s.name == "high" {
			high = s.expr
		}
	}
	fmt.Fprintf(b, "\n-- Test%sGenDamage damages %s's high sample and requires each damage refused by\n-- its named reason (§16.11).\n", n, n)
	fmt.Fprintf(b, "local function Test%sGenDamage()\n", n)
	fmt.Fprintf(b, "\tlocal r = report()\n\tlocal v = json.FromJson(T, %q, %s, r)\n", n, high)
	fmt.Fprintf(b, "\tcheck(v ~= nil and silent(r), %q)\n", n+": the high sample is not silent")
	fmt.Fprintf(b, "\tlocal wire = save.Save(T, %q, v)\n\tcheck(wire ~= nil and #wire >= 2, %q)\n", n, n+": save of the high sample")
	b.WriteString("\t-- a TRUNCATED wire: the framing check refuses it by name (§3)\n")
	fmt.Fprintf(b, "\tfor _, cut in ipairs({ wire:sub(1, 1), wire:sub(1, #wire - 1) }) do\n")
	fmt.Fprintf(b, "\t\tlocal ok, err = pcall(refusal.ReadStrict, T, %q, cut)\n", n)
	b.WriteString("\t\tcheck(refused(ok, err, { \"malformed\", \"wire_damaged\", \"truncated\", \"integrity_mismatch\" }), " + strconv.Quote(n+": truncated wire: ") + " .. errname(err))\n")
	b.WriteString("\tend\n")
	b.WriteString("\t-- a FLIPPED FORM BYTE: the first byte is the form (§3)\n")
	b.WriteString("\tfor _, form in ipairs({ 2, 9, 255 }) do\n")
	fmt.Fprintf(b, "\t\tlocal flipped = string.char(form) .. wire:sub(2)\n\t\tlocal ok, err = pcall(refusal.ReadStrict, T, %q, flipped)\n", n)
	b.WriteString("\t\tcheck(refused(ok, err, { \"unknown_form\", \"message_form_as_file\" }), " + strconv.Quote(n+": form byte ") + " .. form .. " + strconv.Quote(": ") + " .. errname(err))\n")
	b.WriteString("\tend\n")
	b.WriteString("\t-- BASE64 DAMAGE: a character outside the alphabet, and a short text (§16.8)\n")
	fmt.Fprintf(b, "\tlocal b64text = text.SaveText(T, %q, v)\n", n)
	b.WriteString("\tfor _, damaged in ipairs({ \"!\" .. b64text:sub(2), b64text:sub(1, #b64text - 1) }) do\n")
	fmt.Fprintf(b, "\t\tlocal ok, err = pcall(text.LoadText, T, %q, damaged, report())\n", n)
	b.WriteString("\t\tcheck(refused(ok, err, { \"base64_damaged\" }), " + strconv.Quote(n+": base64 damage: ") + " .. errname(err))\n")
	b.WriteString("\tend\n")
	b.WriteString("\t-- JSON OF THE WRONG SHAPE: cut off inside the object (§16.2)\n")
	fmt.Fprintf(b, "\tlocal jsonText = json.ToJson(T, %q, v)\n", n)
	b.WriteString("\tlocal jr = report()\n")
	fmt.Fprintf(b, "\tlocal jgot = json.FromJson(T, %q, jsonText:sub(1, #jsonText - 2), jr)\n", n)
	fmt.Fprintf(b, "\tcheck(jgot ~= nil and jr.malformed, %q)\n", n+": a JSON document cut off inside its value is not malformed")
	b.WriteString("end\n")
}
