var rbsReservedWords = func() map[string]bool {
	m := wordSet(`alias attr_accessor attr_reader attr_writer bool bot class def end extend false
		in include instance interface module nil out prepend private public self singleton top
		true type unchecked untyped use void`)
	for k := range rubyKeywords {
		m[k] = true
	}
	return m
}()

func rbsMethodName(name string) string {
	base := strings.TrimSuffix(name, "=")
	if rbsReservedWords[base] {
		return "`" + name + "`"
	}
	return name
}

func (m *rbModule) rbsFieldType(f *ir.Field) string {
	if f.Array != ir.ArrayNone {
		return "::Array[" + m.rbsFieldType(arrayElem(f)) + "]"
	}
	switch f.Type.Kind {
	case ir.TBool:
		return "bool"
	case ir.TInt, ir.TBits, ir.TFixed:
		return "Integer"
	case ir.TFloat32, ir.TFloat64:
		return "Float"
	case ir.TString, ir.TBytes:
		return "String"
	case ir.TNamed:
		switch f.Type.Ref.(type) {
		case *ir.Enum, *ir.Flags:
			return "Integer"
		case *ir.Struct, *ir.Union:
			return f.Type.Name
		}
	}
	return "untyped"
}

func emitRBS(u *ir.Unit, mod string) string {
	var b strings.Builder
	b.WriteString("# frozen_string_literal: true\n\n")
	fmt.Fprintf(&b, "# Code generated by the schema compiler from the unit %s. DO NOT EDIT.\n", u.Package)
	b.WriteString(genheader.Line("#") + "\n")
	fmt.Fprintf(&b, "module %s\n", mod)
	b.WriteString(`  PROTOCOL_ID: Integer

  class Refused < ::StandardError
    attr_reader reason: String
    def initialize: ((String | Symbol) reason, ?String? detail) -> void
  end

  class InvalidValue < ::StandardError
    attr_reader path: String
    attr_reader rule: String
    def initialize: (String path, String rule) -> void
  end

  class LoadReport
    attr_accessor unknown: Integer
    attr_accessor widened: Integer
    attr_accessor retained: Integer
    attr_accessor retain_lost: Integer
    def initialize: () -> void
  end

  module Serialize
    def self.float32_round: (Float value) -> Float
    class WriteMisuse < ::StandardError
    end

    class Ref[T]
      attr_accessor value: T
      def initialize: (T value) -> void
    end

    class Stream
      def is_writing: () -> bool
      def is_reading: () -> bool
      def is_measuring: () -> bool
      def bits_processed: () -> Integer
      def bytes_processed: () -> Integer
      def align_bits: () -> Integer
    end

    class WriteStream < Stream
      def initialize: (Integer bytes) -> void
      def flush: () -> void
      def data: () -> String
      def serialize_uint8: (Ref[Integer] ref) -> bool
      def serialize_uint16: (Ref[Integer] ref) -> bool
      def serialize_uint32: (Ref[Integer] ref) -> bool
      def serialize_uint64: (Ref[Integer] ref) -> bool
      def serialize_bits: (Ref[Integer] ref, Integer bits) -> bool
      def serialize_bool: (Ref[bool] ref) -> bool
      def serialize_int: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_int64: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_int128: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_uint128: (Ref[Integer] ref) -> bool
      def serialize_fixed: (Ref[Integer] ref, Integer integer_bits, Integer fraction_bits, Integer min, Integer max) -> bool
      def serialize_float: (Ref[Float] ref) -> bool
      def serialize_double: (Ref[Float] ref) -> bool
      def serialize_compressed_float: (Ref[Float] ref, Float min, Float max, Float res) -> bool
      def serialize_compressed_float_precomputed: (Ref[Float] ref, Integer max_integer_value, Integer bits, Float delta, Float min) -> bool
      def serialize_bytes: (Ref[String] ref, Integer count) -> bool
      def serialize_string: (Ref[String] ref, Integer buffer_size) -> bool
      def serialize_align: () -> bool
      def serialize_end: () -> bool
    end

    class ReadStream < Stream
      def initialize: (String buffer) -> void
      def refusal: () -> (String | Symbol)?
      def serialize_uint8: (Ref[Integer] ref) -> bool
      def serialize_uint16: (Ref[Integer] ref) -> bool
      def serialize_uint32: (Ref[Integer] ref) -> bool
      def serialize_uint64: (Ref[Integer] ref) -> bool
      def serialize_bits: (Ref[Integer] ref, Integer bits) -> bool
      def serialize_bool: (Ref[bool] ref) -> bool
      def serialize_int: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_int64: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_int128: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_uint128: (Ref[Integer] ref) -> bool
      def serialize_fixed: (Ref[Integer] ref, Integer integer_bits, Integer fraction_bits, Integer min, Integer max) -> bool
      def serialize_float: (Ref[Float] ref) -> bool
      def serialize_double: (Ref[Float] ref) -> bool
      def serialize_compressed_float: (Ref[Float] ref, Float min, Float max, Float res) -> bool
      def serialize_compressed_float_precomputed: (Ref[Float] ref, Integer max_integer_value, Integer bits, Float delta, Float min) -> bool
      def serialize_bytes: (Ref[String] ref, Integer count) -> bool
      def serialize_string: (Ref[String] ref, Integer buffer_size) -> bool
      def serialize_align: () -> bool
      def serialize_end: () -> bool
    end

    class MeasureStream < Stream
      def initialize: () -> void
      def serialize_uint8: (Ref[Integer] ref) -> bool
      def serialize_uint16: (Ref[Integer] ref) -> bool
      def serialize_uint32: (Ref[Integer] ref) -> bool
      def serialize_uint64: (Ref[Integer] ref) -> bool
      def serialize_bits: (Ref[Integer] ref, Integer bits) -> bool
      def serialize_bool: (Ref[bool] ref) -> bool
      def serialize_int: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_int64: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_int128: (Ref[Integer] ref, Integer min, Integer max) -> bool
      def serialize_uint128: (Ref[Integer] ref) -> bool
      def serialize_fixed: (Ref[Integer] ref, Integer integer_bits, Integer fraction_bits, Integer min, Integer max) -> bool
      def serialize_float: (Ref[Float] ref) -> bool
      def serialize_double: (Ref[Float] ref) -> bool
      def serialize_compressed_float: (Ref[Float] ref, Float min, Float max, Float res) -> bool
      def serialize_compressed_float_precomputed: (Ref[Float] ref, Integer max_integer_value, Integer bits, Float delta, Float min) -> bool
      def serialize_bytes: (Ref[String] ref, Integer count) -> bool
      def serialize_string: (Ref[String] ref, Integer buffer_size) -> bool
      def serialize_align: () -> bool
      def serialize_end: () -> bool
    end
  end

  Stream: singleton(Serialize::Stream)
  WriteStream: singleton(Serialize::WriteStream)
  ReadStream: singleton(Serialize::ReadStream)
  MeasureStream: singleton(Serialize::MeasureStream)

  def self._s_validate_int: (untyped value, String path, Integer min, Integer max) -> void
  def self._s_validate_bool: (untyped value, String path) -> void
  def self._s_validate_array: (untyped value, String path, Integer min, Integer max) -> void
  def self._s_validate_string: (untyped value, String path, Integer size) -> void
  def self._s_validate_bytes: (untyped value, String path, Integer size) -> void
  def self._s_finite_float32: (untyped value, String path) -> Float
  def self._s_validate_float32: (untyped value, String path) -> void
  def self._s_validate_float64: (untyped value, String path) -> void
  def self._s_validate_compressed_float: (untyped value, String path, Float min, Float max) -> void
  def self._s_float32_bits_eq: (untyped a, untyped b) -> bool
  def self._s_float64_bits_eq: (untyped a, untyped b) -> bool
  def self._s_copy_bytes: (String data) -> String
  def self._s_open_read_stream: (untyped data, untyped bit_offset) -> [Serialize::ReadStream, Integer]
`)

	files := slices.Clone(u.Files)
	slices.SortFunc(files, func(a, b *ir.File) int {
		return strings.Compare(a.Base, b.Base)
	})
	m := &rbModule{u: u, mod: mod}
	for _, f := range files {
		m.f = f
		for _, d := range ir.EmissionOrder(f) {
			switch d := d.(type) {
			case *ir.Const:
				typ := "Integer"
				if d.IsFloat {
					typ = "Float"
				}
				fmt.Fprintf(&b, "\n  %s: %s\n", d.Name, typ)
			case *ir.Enum:
				fmt.Fprintf(&b, "\n  module %s\n", d.Name)
				b.WriteString("    None: Integer\n")
				for _, v := range d.Variants {
					fmt.Fprintf(&b, "    %s: Integer\n", VariantConstant(v))
				}
				b.WriteString("    Max: Integer\n")
				b.WriteString("    NAMES: ::Hash[Integer, String]\n")
				b.WriteString("  end\n")
			case *ir.Flags:
				fmt.Fprintf(&b, "\n  module %s\n", d.Name)
				for _, v := range d.Variants {
					fmt.Fprintf(&b, "    %s: Integer\n", VariantConstant(v))
				}
				b.WriteString("    Count: Integer\n")
				b.WriteString("    NAMES: ::Hash[Integer, String]\n")
				b.WriteString("  end\n")
			case *ir.Struct:
				fmt.Fprintf(&b, "\n  class %s\n", d.Name)
				for _, fld := range d.Fields {
					ft := m.rbsFieldType(fld)
					fmt.Fprintf(&b, "    @%s: %s\n", fld.Name, ft)
					fmt.Fprintf(&b, "    def %s: () -> %s\n", rbsMethodName(fld.Name), ft)
					fmt.Fprintf(&b, "    def %s: (%s) -> %s\n", rbsMethodName(fld.Name+"="), ft, ft)
				}
				fmt.Fprintf(&b, "    def initialize: () -> void\n")
				fmt.Fprintf(&b, "    def %scopy_from: (%s other) -> %s\n", HelperPrefix, d.Name, d.Name)
				fmt.Fprintf(&b, "    def to_h: () -> ::Hash[Symbol, untyped]\n")
				fmt.Fprintf(&b, "    def ==: (untyped other) -> bool\n")
				fmt.Fprintf(&b, "    def inspect: () -> String\n")
				fmt.Fprintf(&b, "    def self.read_bits: (untyped data, ?bit_offset: untyped) -> [%s, Integer]\n", d.Name)
				fmt.Fprintf(&b, "    def self.read: (untyped data) -> %s\n", d.Name)
				fmt.Fprintf(&b, "    def write: () -> String\n")
				fmt.Fprintf(&b, "    def _s_read: (Serialize::ReadStream stream) -> bool\n")
				fmt.Fprintf(&b, "    def _s_write: (Serialize::WriteStream stream) -> void\n")
				fmt.Fprintf(&b, "    def _s_validate: (String path) -> void\n")
				fmt.Fprintf(&b, "    def _s_zero: () -> void\n")
				b.WriteString("  end\n")
			case *ir.Union:
				fmt.Fprintf(&b, "\n  module %sType\n", d.Name)
				b.WriteString("    None: Integer\n")
				for _, v := range d.Variants {
					fmt.Fprintf(&b, "    %s: Integer\n", ir.GoExportName(v.Name))
				}
				b.WriteString("    Max: Integer\n")
				b.WriteString("    NAMES: ::Hash[Integer, String]\n")
				b.WriteString("  end\n")

				arms := unionArms(d)
				fmt.Fprintf(&b, "\n  class %s\n", d.Name)
				b.WriteString("    @type: Integer\n")
				b.WriteString("    def `type`: () -> Integer\n")
				b.WriteString("    def `type=`: (Integer) -> Integer\n")
				for _, v := range arms {
					ft := m.rbsFieldType(v.F)
					fmt.Fprintf(&b, "    @%s: %s\n", v.Name, ft)
					fmt.Fprintf(&b, "    def %s: () -> %s\n", rbsMethodName(v.Name), ft)
					fmt.Fprintf(&b, "    def %s: (%s) -> %s\n", rbsMethodName(v.Name+"="), ft, ft)
				}
				fmt.Fprintf(&b, "    def initialize: () -> void\n")
				fmt.Fprintf(&b, "    def %scopy_from: (%s other) -> %s\n", HelperPrefix, d.Name, d.Name)
				fmt.Fprintf(&b, "    def ==: (untyped other) -> bool\n")
				fmt.Fprintf(&b, "    def inspect: () -> String\n")
				fmt.Fprintf(&b, "    def self.read_bits: (untyped data, ?bit_offset: untyped) -> [%s, Integer]\n", d.Name)
				fmt.Fprintf(&b, "    def self.read: (untyped data) -> %s\n", d.Name)
				fmt.Fprintf(&b, "    def write: () -> String\n")
				fmt.Fprintf(&b, "    def _s_read: (Serialize::ReadStream stream) -> bool\n")
				fmt.Fprintf(&b, "    def _s_write: (Serialize::WriteStream stream) -> void\n")
				fmt.Fprintf(&b, "    def _s_validate: (String path) -> void\n")
				fmt.Fprintf(&b, "    def _s_zero: () -> void\n")
				b.WriteString("  end\n")
			}
		}
	}
	b.WriteString("end\n")
	return b.String()
}
