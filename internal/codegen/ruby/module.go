package ruby

import (
	"fmt"
	"math"
	"math/big"
	"strconv"
	"strings"

	"github.com/mas-bandwidth/schema/v3/internal/codegen/genheader"
	"github.com/mas-bandwidth/schema/v3/ir"
)

// rbModule is one schema file's module while it is being emitted.
type rbModule struct {
	u   *ir.Unit
	f   *ir.File
	mod string

	body strings.Builder

	surfaceOnly bool
	hosted      bool
}

func emitModule(u *ir.Unit, f *ir.File, mod string) string {
	return emitModuleMode(u, f, mod, false)
}

func emitModuleMode(u *ir.Unit, f *ir.File, mod string, surfaceOnly bool) string {
	m := &rbModule{
		u:           u,
		f:           f,
		mod:         mod,
		surfaceOnly: surfaceOnly,
	}
	for _, d := range ir.EmissionOrder(f) {
		switch d := d.(type) {
		case *ir.Const:
			m.emitConst(d)
		case *ir.Enum:
			m.emitEnum(d)
		case *ir.Flags:
			m.emitFlags(d)
		case *ir.Struct:
			m.emitStruct(d)
		case *ir.Union:
			m.emitUnion(d)
		}
	}
	return m.assemble()
}

func (m *rbModule) printf(format string, args ...any) { fmt.Fprintf(&m.body, format, args...) }
func (m *rbModule) line(format string, args ...any)   { m.printf(format+"\n", args...) }

// typeRef names a declaration inside the unit module. Because every schema
// file in the unit reopens the same module <Mod>, declarations name each other
// unqualified inside <Mod>.
func (m *rbModule) typeRef(name string) string { return name }

func (m *rbModule) assemble() string {
	var h strings.Builder
	h.WriteString("# frozen_string_literal: true\n\n")
	fmt.Fprintf(&h, "# Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n", m.f.Base)
	h.WriteString(genheader.Line("#") + "\n")
	fmt.Fprintf(&h, "module %s\n", m.mod)
	body := strings.TrimRight(m.body.String(), "\n")
	if body != "" {
		h.WriteString(body)
		h.WriteString("\n")
	}
	h.WriteString("end\n")
	return h.String()
}

func intLiteral(v *big.Int) string {
	if v == nil {
		return "0"
	}
	return v.String()
}

func floatLiteral(v float64) string {
	switch {
	case math.IsNaN(v):
		return "Float::NAN"
	case math.IsInf(v, 1):
		return "Float::INFINITY"
	case math.IsInf(v, -1):
		return "-Float::INFINITY"
	case v == 0 && math.Signbit(v):
		return "-0.0"
	}
	s := strconv.FormatFloat(v, 'g', -1, 64)
	if !strings.ContainsAny(s, ".eE") {
		s += ".0"
	} else if idx := strings.IndexAny(s, "eE"); idx > 0 && !strings.Contains(s[:idx], ".") {
		// In Ruby, 1e39 is valid, and 1.0e39 is also valid; keep canonical Float literal.
		s = s[:idx] + ".0" + s[idx:]
	}
	return s
}

func float32Value(v float64) float64 { return float64(float32(v)) }

// rubyStringLiteral quotes s as a double-quoted Ruby UTF-8 string literal with
// `#` escaped so `#{...}` interpolation can never trigger.
func rubyStringLiteral(s string) string {
	var out strings.Builder
	out.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '\\' || r == '"' || r == '#':
			out.WriteByte('\\')
			out.WriteRune(r)
		case r == '\n':
			out.WriteString("\\n")
		case r == '\r':
			out.WriteString("\\r")
		case r == '\t':
			out.WriteString("\\t")
		case r >= 0x20 && r < 0x7f:
			out.WriteRune(r)
		default:
			fmt.Fprintf(&out, "\\u{%x}", r)
		}
	}
	out.WriteByte('"')
	return out.String()
}

// rubyBytesLiteral quotes b as a frozen ASCII-8BIT Ruby String (`"...".b.freeze`).
// Note: under `# frozen_string_literal: true`, `"..."` is frozen, but `"...".b`
// returns a mutable ASCII-8BIT String unless `.freeze` is called.
func rubyBytesLiteral(b []byte) string {
	var out strings.Builder
	out.WriteByte('"')
	for _, c := range b {
		switch {
		case c == '\\' || c == '"' || c == '#':
			out.WriteByte('\\')
			out.WriteByte(c)
		case c >= 0x20 && c < 0x7f:
			out.WriteByte(c)
		default:
			fmt.Fprintf(&out, "\\x%02x", c)
		}
	}
	out.WriteString("\".b.freeze")
	return out.String()
}

// zeroExpr is the SPEC §5 ZERO form of a field's storage: all-zero, never a
// declared default.
func (m *rbModule) zeroExpr(f *ir.Field) string {
	if f.Array != ir.ArrayNone {
		elem := arrayElem(f)
		return fmt.Sprintf("[] #: ::Array[%s]", m.rbsFieldType(elem))
	}
	switch f.Type.Kind {
	case ir.TBool:
		return "false"
	case ir.TFloat32, ir.TFloat64:
		return "0.0"
	case ir.TString:
		return "\"\""
	case ir.TBytes:
		return "\"\".b.freeze"
	case ir.TNamed:
		switch f.Type.Ref.(type) {
		case *ir.Struct, *ir.Union:
			return m.typeRef(f.Type.Name) + ".new"
		}
		return "0"
	}
	return "0"
}

// defaultExpr is a field's declared default, or its zero form (SPEC §5).
func (m *rbModule) defaultExpr(f *ir.Field) string {
	if !f.HasDefault {
		return m.zeroExpr(f)
	}
	switch {
	case f.Type.Kind == ir.TBool:
		if f.DefBool {
			return "true"
		}
		return "false"
	case f.DefVariant != "":
		return m.typeRef(f.Type.Name) + "::" + f.DefVariant
	case f.Type.Kind == ir.TFloat32:
		return floatLiteral(float32Value(f.DefFloat))
	case f.Type.Kind == ir.TFloat64:
		return floatLiteral(f.DefFloat)
	case f.Type.Kind == ir.TString:
		return rubyStringLiteral(string(f.DefBytes))
	case f.Type.Kind == ir.TBytes:
		return rubyBytesLiteral(f.DefBytes)
	case f.DefInt != nil:
		return intLiteral(f.DefInt)
	}
	return m.zeroExpr(f)
}

func isImmutableExpr(f *ir.Field) bool {
	if f.Array != ir.ArrayNone {
		return false
	}
	if f.Type.Kind == ir.TNamed {
		switch f.Type.Ref.(type) {
		case *ir.Struct, *ir.Union:
			return false
		}
	}
	return true
}
