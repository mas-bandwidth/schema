// gen_targets.mjs — emit one Jazzer.js entry point per READER KIND over the
// generated JavaScript the compiler wrote for the fuzz corpus.
//
// The card asks for three kinds, and each mirrors the API a caller actually
// gets from the port's emitter:
//
//   load    <Root>Load(bytes, report)                 variable wire, tolerant load
//   strict  <Root>FixedLoad(values, cap, bytes, ...)  fixed form, no strict flag
//   text    <Root>FromJson(text, report)              text/JSON parse
//
// Nothing here is handwritten reader logic: the functions are imported from
// the generated modules, and the generator only enumerates their exports. A
// unit the emitter refuses (a pointered fixed surface, say) simply contributes
// no candidate of that kind.
//
// Usage: node gen_targets.mjs <generated-dir> <out-dir>
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const [generatedDir, outDir] = process.argv.slice(2);
if (!generatedDir || !outDir) {
  console.error("usage: gen_targets.mjs <generated-dir> <out-dir>");
  process.exit(2);
}

const load = [];
const strict = [];
const text = [];
const exported = (src) =>
  [...src.matchAll(/^export function ([A-Za-z_$][\w$]*)\s*\(/gm)].map((m) => m[1]);

function units(dir) {
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => path.join(dir, e.name))
    .sort();
}

for (const unitDir of units(generatedDir)) {
  const files = fs
    .readdirSync(unitDir)
    .filter((f) => f.endsWith(".js"))
    .sort();
  const variables = files.filter((f) => f.endsWith("Variable.js"));
  const tables = files.filter((f) => f.endsWith("Table.js"));
  const variableNames = [];
  variables.forEach((f, i) => {
    const src = fs.readFileSync(path.join(unitDir, f), "utf8");
    const module = `var${i}`;
    variableNames.push({ module, src, file: path.join(unitDir, f) });
    for (const fn of exported(src)) {
      if (fn.endsWith("FixedLoad")) continue;
      if (fn.endsWith("Load")) {
        load.push({
          moduleFile: path.join(unitDir, f),
          fn,
          report: "TableVariableReport",
          sortKey: `${f}:${fn}`,
        });
      } else if (fn.endsWith("FromJson")) {
        text.push({
          moduleFile: path.join(unitDir, f),
          fn,
          report: "TableVariableReport",
          sortKey: `${f}:${fn}`,
        });
      }
    }
  });
  tables.forEach((f, i) => {
    const src = fs.readFileSync(path.join(unitDir, f), "utf8");
    const module = `tab${i}`;
    for (const fn of exported(src)) {
      if (!fn.endsWith("FixedLoad")) continue;
      const root = fn.slice(0, -"FixedLoad".length);
      // The VALUE the fixed reader writes through is the variable module's
      // own class for the same root; every *Table.js unit has its *Variable.js
      // sibling beside it (make/js.mk generates the whole unit).
      const holder = variableNames.find((v) =>
        new RegExp(`^export class ${root}\\s*\\{`, "m").test(v.src),
      );
      if (!holder) continue;
      const plan = `${root}FixedNewPlan`;
      if (!new RegExp(`^export function ${plan}\\s*\\(`, "m").test(src)) continue;
      strict.push({
        module,
        moduleFile: path.join(unitDir, f),
        fn,
        root,
        valueModule: holder.module,
        valueModuleFile: holder.file,
        plan,
        sortKey: `${f}:${fn}`,
      });
    }
  });
}

function writeTarget(name, candidates, call) {
  const imports = new Map();
  const importFor = (file) => {
    if (!imports.has(file)) {
      imports.set(file, `mod${imports.size}`);
    }
    return imports.get(file);
  };
  const entries = candidates
    .sort((a, b) => a.sortKey.localeCompare(b.sortKey))
    .map((c) => call(c, importFor));
  const header = [...imports.entries()]
    .map(([file, module]) => `import * as ${module} from ${JSON.stringify(pathToFileURL(file).href)};`)
    .join("\n");
  const body = `// Generated by test/js-nightly-fuzz/gen_targets.mjs. DO NOT EDIT.
${header}

const candidates = [
${entries.join("\n")}
];

export function fuzz(data) {
  if (data.length < 1 || candidates.length === 0) return;
  const c = candidates[data[0] % candidates.length];
  c.run(data.subarray(1));
}
`;
  fs.writeFileSync(path.join(outDir, `${name}.mjs`), body);
  return candidates.length;
}

fs.mkdirSync(outDir, { recursive: true });

const loadCount = writeTarget("load", load, (c, importFor) => {
  const module = importFor(c.moduleFile);
  return `  { name: ${JSON.stringify(c.fn)}, run: (b) => ${module}.${c.fn}(b, new ${module}.${c.report}()) },`;
});
const strictCount = writeTarget("strict", strict, (c, importFor) => {
  const table = importFor(c.moduleFile);
  const values = importFor(c.valueModuleFile);
  return `  { name: ${JSON.stringify(c.fn)}, run: (b) => { const v = Array.from({ length: 8 }, () => new ${values}.${c.root}()); return ${table}.${c.fn}(v, 8, b, b.length, ${table}.${c.plan}(4096, 4096), {}); } },`;
});
const textCount = writeTarget("text", text, (c, importFor) => {
  const module = importFor(c.moduleFile);
  return `  { name: ${JSON.stringify(c.fn)}, run: (b) => ${module}.${c.fn}(new TextDecoder("utf-8", { fatal: false }).decode(b), new ${module}.${c.report}()) },`;
});

console.log(
  `js nightly fuzz targets: load=${loadCount} strict=${strictCount} text=${textCount}`,
);
