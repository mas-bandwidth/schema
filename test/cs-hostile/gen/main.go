// Command gen writes the C# hostile-corpus runner's dispatch
// (schema-cs-runs-hostile-corpus, make/schema-cs-runs-hostile-corpus.mk).
//
//	go run ./test/cs-hostile/gen -schema ./bin/schema -corpus <dir> -out <dir>
//
// It reads the corpus manifest, generates the C# unit every distinct schema
// names (one directory per unit under -out), reads each unit's generated
// surface, and writes Dispatch.cs: one entry per (schema, table, carrier) the
// manifest uses, calling the port's public reader for that carrier by name.
// C# cannot pass a span through reflection, so the dispatch is source; a
// carrier the port has no reader for is written as a SKIP with its reason.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"

	"github.com/mas-bandwidth/schema/v2/internal/ci/hostilecorpus"
)

type row struct {
	carrier, schema, table string
}

type unit struct {
	schema    string // the manifest's name
	dir       string // directory under -out
	namespace string
	source    string // every generated .cs of the unit, concatenated
}

func main() {
	schemaBin := flag.String("schema", "./bin/schema", "the schema compiler")
	corpus := flag.String("corpus", "internal/ci/hostilecorpus/corpus", "corpus directory")
	out := flag.String("out", "build/cs-hostile/generated", "output directory")
	flag.Parse()
	if err := run(*schemaBin, *corpus, *out); err != nil {
		fmt.Fprintln(os.Stderr, "cs-hostile gen:", err)
		os.Exit(1)
	}
}

func run(schemaBin, corpus, out string) error {
	data, err := os.ReadFile(filepath.Join(corpus, hostilecorpus.ManifestName))
	if err != nil {
		return err
	}
	var rows []row
	seen := map[row]bool{}
	var schemas []string
	seenSchema := map[string]bool{}
	for i, line := range strings.Split(string(data), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 9 {
			return fmt.Errorf("manifest line %d: %d fields, want 9", i+1, len(f))
		}
		r := row{carrier: f[1], schema: f[2], table: f[3]}
		if !seen[r] {
			seen[r] = true
			rows = append(rows, r)
		}
		if !seenSchema[r.schema] {
			seenSchema[r.schema] = true
			schemas = append(schemas, r.schema)
		}
	}
	sort.Strings(schemas)

	if err := os.RemoveAll(out); err != nil {
		return err
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	units := make([]*unit, len(schemas))
	for i, s := range schemas {
		units[i] = &unit{schema: s, dir: fmt.Sprintf("u%02d_%s", i, sanitize(s))}
	}

	// Each unit generates independently, so they generate concurrently.
	var wg sync.WaitGroup
	errs := make([]error, len(units))
	limit := make(chan struct{}, 4)
	for i, u := range units {
		wg.Add(1)
		go func(i int, u *unit) {
			defer wg.Done()
			limit <- struct{}{}
			defer func() { <-limit }()
			errs[i] = generate(schemaBin, out, u)
		}(i, u)
	}
	wg.Wait()
	for _, e := range errs {
		if e != nil {
			return e
		}
	}
	byNamespace := map[string]string{}
	bySchema := map[string]*unit{}
	for _, u := range units {
		if prev, ok := byNamespace[u.namespace]; ok {
			return fmt.Errorf("units %s and %s share the C# namespace %s; one assembly cannot hold both", prev, u.schema, u.namespace)
		}
		byNamespace[u.namespace] = u.schema
		bySchema[u.schema] = u
	}

	var b bytes.Buffer
	b.WriteString(header)
	var cases, bodies bytes.Buffer
	emitted := map[string]bool{}
	for _, r := range rows {
		u := bySchema[r.schema]
		key := r.schema + "\\t" + r.table + "\\t" + r.carrier
		expr := dispatch(u, r, &bodies, emitted)
		fmt.Fprintf(&cases, "            case \"%s\": return %s;\n", key, expr)
	}
	b.WriteString("    internal static string Run(string carrier, string schema, string table, byte[] d)\n    {\n")
	b.WriteString("        switch (schema + \"\\t\" + table + \"\\t\" + carrier)\n        {\n")
	b.Write(cases.Bytes())
	b.WriteString("            default: return \"error: no dispatch for \" + schema + \" \" + table + \" \" + carrier + \" (regenerate the runner)\";\n")
	b.WriteString("        }\n    }\n")
	b.Write(bodies.Bytes())
	b.WriteString("}\n")
	return os.WriteFile(filepath.Join(out, "Dispatch.cs"), b.Bytes(), 0o644)
}

const header = `// Code generated by test/cs-hostile/gen from the hostile corpus manifest. DO NOT EDIT.
// One entry per (schema, table, carrier) the manifest uses; each calls the
// port's public reader for that carrier and answers a verdict string
// ("accept <digest>", "refuse <reason>", "skip: <why>", or an error text).
using System;
using System.Runtime.InteropServices;

#pragma warning disable CS0162

static unsafe class Dispatch
{
`

func sanitize(s string) string {
	return strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' {
			return r
		}
		return '_'
	}, s)
}

var namespaceLine = regexp.MustCompile(`(?m)^namespace ([A-Za-z_][A-Za-z0-9_.]*)`)

func generate(schemaBin, out string, u *unit) error {
	src := filepath.FromSlash(u.schema)
	dir := filepath.Join(out, u.dir)
	if u.schema == hostilecorpus.ProbeSchemaPath {
		if err := os.MkdirAll(filepath.Join(out, "schemas"), 0o755); err != nil {
			return err
		}
		src = filepath.Join(out, "schemas", "probe.schema")
		if err := os.WriteFile(src, []byte(hostilecorpus.ProbeSchema), 0o644); err != nil {
			return err
		}
	}
	cmd := exec.Command(schemaBin, "generate", "--lang", "cs", "--out", dir, src)
	var log bytes.Buffer
	cmd.Stdout, cmd.Stderr = &log, &log
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("generate %s: %v\n%s", u.schema, err, log.String())
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.cs"))
	if err != nil {
		return err
	}
	var all strings.Builder
	for _, f := range files {
		t, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		all.Write(t)
		all.WriteByte('\n')
	}
	u.source = all.String()
	m := namespaceLine.FindStringSubmatch(u.source)
	if m == nil {
		return fmt.Errorf("generate %s: no namespace in the generated C#", u.schema)
	}
	u.namespace = m[1]
	return nil
}

// has reports whether the unit carries a public, callable declaration whose
// line contains want (an [Obsolete] stub is a compile error to call, so it
// does not count).
func (u *unit) has(want string) bool {
	for _, line := range strings.Split(u.source, "\n") {
		if strings.Contains(line, want) && !strings.Contains(line, "Obsolete") {
			return true
		}
	}
	return false
}

type surface struct {
	managed, fromJSON, toJSON, measure          bool
	region, loadMeasure, builder, regionSave    bool
	retain, retainSave                          bool
	messages, announce, packetRead, packetWrite bool
}

func surfaceOf(u *unit, t string) surface {
	return surface{
		managed:     u.has("public static bool " + t + "Load(" + t + " value, ReadOnlySpan<byte> bytes, TableReport report)"),
		fromJSON:    u.has("public static bool " + t + "FromJson(" + t + " value, ReadOnlySpan<byte> text, TableReport report)"),
		toJSON:      u.has("public static long "+t+"ToJsonMeasure("+t+" value)") && u.has("public static long "+t+"ToJson("+t+" value, Span<byte> buffer)"),
		measure:     u.has("public static long "+t+"Measure("+t+" value)") && u.has("public static long "+t+"Save("+t+" value, Span<byte> buffer)"),
		region:      u.has(t + "Row* " + t + "Load(System.IntPtr region, long capacity, System.ReadOnlySpan<byte> bytes, TableReport report)"),
		loadMeasure: u.has("public static long " + t + "LoadMeasure(System.ReadOnlySpan<byte> bytes, out long dataBytes, out long attributionBytes,"),
		builder:     u.has("public static " + t + " " + t + "LoadBuilder(System.IntPtr region)"),
		regionSave:  u.has("public static long "+t+"Measure(System.IntPtr region)") && u.has("public static long "+t+"Save(System.IntPtr region, Span<byte> bytes)"),
		retain:      u.has(t + "Row* " + t + "LoadRetain(IntPtr region, long capacity, ReadOnlySpan<byte> bytes, ref TableRetain retain, TableReport report)"),
		retainSave:  u.has("public static long "+t+"MeasureRetain(IntPtr region, ref TableRetain retain)") && u.has("public static long "+t+"SaveRetain(IntPtr region, ref TableRetain retain, Span<byte> bytes, TableReport report)"),
		messages:    u.has("public static TableWire.Verdict " + t + "LoadMessages(" + t + "[] values, ReadOnlySpan<byte> bytes, TableVocabulary vocabulary, TableReport report, out int count)"),
		announce:    u.has("public static TableWire.Verdict AnnounceRead(TableVocabulary vocabulary, ReadOnlySpan<byte> bytes, TableReport report)"),
		packetRead:  u.has("public static bool Read" + t + "(ReadStream stream, ref " + t + " value)"),
		packetWrite: u.has("public static bool Write" + t + "(WriteStream stream, ref " + t + " value)"),
	}
}

func skip(why string) string { return fmt.Sprintf("%q", "skip: "+why) }

// dispatch returns the C# expression for one manifest (schema, table, carrier)
// and emits the bodies it calls, once each.
func dispatch(u *unit, r row, bodies *bytes.Buffer, emitted map[string]bool) string {
	t := r.table
	s := surfaceOf(u, t)
	f := u.dir + "_" + t
	emit := func(name, text string) {
		if emitted[name] {
			return
		}
		emitted[name] = true
		bodies.WriteString(strings.NewReplacer("{N}", u.namespace, "{T}", t, "{F}", f, "{U}", u.dir).Replace(text))
	}
	accept := func() bool {
		if !s.toJSON || !s.measure {
			return false
		}
		emit(f+"_accept", acceptBody)
		return true
	}
	switch r.carrier {
	case "wire":
		if !s.managed || !accept() {
			return skip(t + " has no managed load, Measure/Save and ToJson in the C# port")
		}
		emit(f+"_wire", wireBody)
		if s.region && s.loadMeasure && s.builder {
			emit(f+"_region", regionBody(s.regionSave))
			return "H.Both(\"managed load\", " + f + "_wire(d), \"native region load\", " + f + "_region(d))"
		}
		return f + "_wire(d)"
	case "wire_retain":
		if !s.retain || !s.loadMeasure || !s.builder || !accept() {
			return skip(t + " is a fixed-class root (or has no builder copy); the C# port carries no retaining load for it (docs/SPEC-TABLES.md §6.6)")
		}
		emit(f+"_retain", retainBody(s.retainSave))
		return f + "_retain(d)"
	case "text":
		if !s.fromJSON || !accept() {
			return skip(t + " has no FromJson in the C# port")
		}
		emit(f+"_text", textBody)
		return f + "_text(d)"
	case "message", "message_novocab":
		if !s.messages || !s.announce || !accept() {
			return skip(t + " has no LoadMessages in the C# port")
		}
		emit(f+"_message", messageBody)
		return fmt.Sprintf("%s_message(d, %v)", f, r.carrier == "message")
	case "announce", "announce_second", "announce_bytes", "announce_entries":
		if !s.announce {
			return skip(u.schema + " has no AnnounceRead in the C# port")
		}
		emit(u.dir+"_announce", announceBody)
		mode := map[string]int{"announce": 0, "announce_bytes": 1, "announce_entries": 2, "announce_second": 3}[r.carrier]
		return fmt.Sprintf("%s_announce(d, %d)", u.dir, mode)
	case "packet":
		if !s.packetRead || !s.packetWrite {
			return skip(t + " has no Read" + t + "/Write" + t + " packet pair in the C# port")
		}
		emit(f+"_packet", packetBody)
		return f + "_packet(d)"
	default:
		return fmt.Sprintf("%q", "error: carrier "+r.carrier+" is not in the runner contract")
	}
}

// acceptBody is rule 4 of the runner contract for an accepted value: Measure
// and Save run (a negative measure is a clean refusal), and the digest is the
// text writer's output.
const acceptBody = `
    static string {F}_accept({N}.{T} v)
    {
        long m = {N}.Schema.{T}Measure(v);
        if (m >= 0)
        {
            byte[] file = new byte[m];
            long w = {N}.Schema.{T}Save(v, file);
            if (w != m) { return "error: Save wrote " + w + " of " + m + " measured bytes"; }
        }
        long n = {N}.Schema.{T}ToJsonMeasure(v);
        if (n < 0) { return "error: ToJsonMeasure refused the decoded value (" + n + ")"; }
        byte[] text = new byte[n];
        long t = {N}.Schema.{T}ToJson(v, text);
        if (t != n) { return "error: ToJson wrote " + t + " of " + n + " measured bytes"; }
        return H.Accept(H.Digest(text));
    }
`

const wireBody = `
    static string {F}_wire(byte[] d)
    {
        var v = new {N}.{T}();
        var r = new {N}.TableReport();
        bool ok = {N}.Schema.{T}Load(v, d, r);
        return H.Read(ok, r.Refused, r.Reason, r.Malformed) ?? {F}_accept(v);
    }
`

const textBody = `
    static string {F}_text(byte[] d)
    {
        var v = new {N}.{T}();
        var r = new {N}.TableReport();
        bool ok = {N}.Schema.{T}FromJson(v, d, r);
        return H.Read(ok, r.Refused, r.Reason, r.Malformed) ?? {F}_accept(v);
    }
`

func regionSaveText(on bool) string {
	if !on {
		return ""
	}
	return `
            long m = {N}.Schema.{T}Measure((IntPtr)region);
            if (m >= 0)
            {
                byte[] file = new byte[m];
                long w = {N}.Schema.{T}Save((IntPtr)region, file);
                if (w != m) { return "error: region Save wrote " + w + " of " + m + " measured bytes"; }
            }`
}

func regionBody(save bool) string {
	return `
    static string {F}_region(byte[] d)
    {
        long total = {N}.Schema.{T}LoadMeasure(d, out _, out _, out _);
        string big = H.Oversized(total, d.Length);
        if (big != null) { return big; }
        long capacity = Math.Max(total, 64);
        byte* region = (byte*)NativeMemory.AlignedAlloc((nuint)capacity, 64);
        try
        {
            var r = new {N}.TableReport();
            IntPtr root = (IntPtr){N}.Schema.{T}Load((IntPtr)region, capacity, d, r);
            string refused = H.Read(root != IntPtr.Zero, r.Refused, r.Reason, r.Malformed);
            if (refused != null) { return refused; }` + regionSaveText(save) + `
            return {F}_accept({N}.Schema.{T}LoadBuilder((IntPtr)region));
        }
        finally { NativeMemory.AlignedFree(region); }
    }
`
}

func retainBody(save bool) string {
	saveText := ""
	if save {
		saveText = `
            long m = {N}.Schema.{T}MeasureRetain((IntPtr)region, ref store);
            if (m >= 0)
            {
                byte[] file = new byte[m];
                long w = {N}.Schema.{T}SaveRetain((IntPtr)region, ref store, file, new {N}.TableReport());
                if (w != m) { return "error: SaveRetain wrote " + w + " of " + m + " measured bytes"; }
            }`
	}
	return `
    static string {F}_retain(byte[] d)
    {
        long total = {N}.Schema.{T}LoadMeasure(d, out _, out _, out _);
        string big = H.Oversized(total, d.Length);
        if (big != null) { return big; }
        long capacity = Math.Max(total, 64);
        const int idCapacity = 4096 + 64;
        long storeCapacity = d.Length + 4096L;
        byte* region = (byte*)NativeMemory.AlignedAlloc((nuint)capacity, 64);
        byte* bytes = (byte*)NativeMemory.Alloc((nuint)storeCapacity);
        {N}.TableRetain.Id* ids = ({N}.TableRetain.Id*)NativeMemory.Alloc((nuint)(idCapacity * sizeof({N}.TableRetain.Id)));
        try
        {
            var store = new {N}.TableRetain { Bytes = bytes, Capacity = storeCapacity, Ids = ids, IdCapacity = idCapacity };
            var r = new {N}.TableReport();
            IntPtr root = (IntPtr){N}.Schema.{T}LoadRetain((IntPtr)region, capacity, d, ref store, r);
            string refused = H.Read(root != IntPtr.Zero, r.Refused, r.Reason, r.Malformed);
            if (refused != null) { return refused; }` + saveText + `
            return {F}_accept({N}.Schema.{T}LoadBuilder((IntPtr)region));
        }
        finally { NativeMemory.AlignedFree(region); NativeMemory.Free(bytes); NativeMemory.Free(ids); }
    }
`
}

const messageBody = `
    static string {F}_message(byte[] d, bool announced)
    {
        {N}.TableVocabulary vocabulary = null;
        if (announced)
        {
            vocabulary = new {N}.TableVocabulary();
            if ({N}.Schema.AnnounceRead(vocabulary, {N}.Schema.Announce(), new {N}.TableReport()) != {N}.Schema.TableWire.Verdict.Ok)
            {
                return "error: the unit's own announcement was refused";
            }
        }
        var values = new {N}.{T}[] { new {N}.{T}() };
        var r = new {N}.TableReport();
        var verdict = {N}.Schema.{T}LoadMessages(values, d, vocabulary, r, out int count);
        string refused = H.Read(verdict == {N}.Schema.TableWire.Verdict.Ok, r.Refused, r.Reason, r.Malformed);
        if (refused != null) { return refused; }
        if (count != 1) { return "error: an accepted batch delivered " + count + " bodies into a capacity of 1"; }
        return {F}_accept(values[0]);
    }
`

const announceBody = `
    static string {U}_announce(byte[] d, int mode)
    {
        var vocabulary = new {N}.TableVocabulary();
        if (mode == 1) { vocabulary.MaxBytes = 8; }
        if (mode == 2) { vocabulary.MaxEntries = 1; }
        if (mode == 3 && {N}.Schema.AnnounceRead(vocabulary, d, new {N}.TableReport()) != {N}.Schema.TableWire.Verdict.Ok)
        {
            return "error: the first announcement was refused";
        }
        var r = new {N}.TableReport();
        var verdict = {N}.Schema.AnnounceRead(vocabulary, d, r);
        return H.Read(verdict == {N}.Schema.TableWire.Verdict.Ok, r.Refused, r.Reason, r.Malformed) ?? H.Accept("-");
    }
`

// packetBody reads from bit 0 with numBits = 8*len and, on accept, digests the
// bytes the port's own writer emits for the decoded value.
const packetBody = `
    static string {F}_packet(byte[] d)
    {
        var v = new {N}.{T}();
        var rs = new Serialize.ReadStream(d, d.Length);
        if (!{N}.Schema.Read{T}(rs, ref v)) { return H.Refuse("packet_refused"); }
        var ws = new Serialize.WriteStream(new byte[Math.Max(1 << 16, d.Length * 8)]);
        if (!{N}.Schema.Write{T}(ws, ref v)) { return "error: the writer refused the decoded value"; }
        ws.Flush();
        return H.Accept(H.Sha(ws.Data));
    }
`
