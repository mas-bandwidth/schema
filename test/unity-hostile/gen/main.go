// Command gen writes the Unity C# hostile-corpus runner's dispatch
// (schema-unity-runs-hostile-corpus, make/schema-unity-runs-hostile-corpus.mk).
//
//	go run ./test/unity-hostile/gen -schema ./bin/schema -corpus <dir> -out <dir>
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"sync"

	"github.com/mas-bandwidth/schema/v2/internal/ci/hostilecorpus"
)

type row struct {
	name                   string
	carrier, schema, table string
}

type unit struct {
	schema    string
	dir       string
	namespace string
	source    string
}

func main() {
	schemaBin := flag.String("schema", "./bin/schema", "the schema compiler")
	corpus := flag.String("corpus", "internal/ci/hostilecorpus/corpus", "corpus directory")
	out := flag.String("out", "build/unity-hostile/generated", "output directory")
	flag.Parse()
	if err := run(*schemaBin, *corpus, *out); err != nil {
		fmt.Fprintln(os.Stderr, "unity-hostile gen:", err)
		os.Exit(1)
	}
}

func run(schemaBin, corpus, out string) error {
	data, err := os.ReadFile(filepath.Join(corpus, hostilecorpus.ManifestName))
	if err != nil {
		return err
	}
	var rows []row
	seen := map[row]bool{}
	var schemas []string
	seenSchema := map[string]bool{}
	for i, line := range strings.Split(string(data), "\n") {
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) != 9 {
			return fmt.Errorf("manifest line %d: %d fields, want 9", i+1, len(f))
		}
		r := row{carrier: f[1], schema: f[2], table: f[3]}
		if !seen[r] {
			seen[r] = true
			r.name = f[0]
			rows = append(rows, r)
		}
		if !seenSchema[r.schema] {
			seenSchema[r.schema] = true
			schemas = append(schemas, r.schema)
		}
	}
	sort.Strings(schemas)
	if err := os.RemoveAll(out); err != nil {
		return err
	}
	if err := os.MkdirAll(out, 0o755); err != nil {
		return err
	}
	units := make([]*unit, len(schemas))
	for i, s := range schemas {
		units[i] = &unit{schema: s, dir: fmt.Sprintf("u%02d_%s", i, sanitize(s))}
	}

	inSet := map[string]bool{}
	for _, s := range schemas {
		inSet[s] = true
	}
	alias := map[string]string{}
	for _, s := range schemas {
		if strings.HasSuffix(s, ".schema") {
			if dir := filepath.ToSlash(filepath.Dir(filepath.FromSlash(s))); inSet[dir] {
				alias[s] = dir
			}
		}
	}

	var wg sync.WaitGroup
	errs := make([]error, len(units))
	limit := make(chan struct{}, 4)
	for i, u := range units {
		if _, rides := alias[u.schema]; rides {
			continue
		}
		wg.Add(1)
		go func(i int, u *unit) {
			defer wg.Done()
			limit <- struct{}{}
			defer func() { <-limit }()
			errs[i] = generate(schemaBin, out, u)
		}(i, u)
	}
	wg.Wait()
	for _, e := range errs {
		if e != nil {
			return e
		}
	}
	{
		byDir := map[string]*unit{}
		for _, u := range units {
			byDir[u.schema] = u
		}
		for _, u := range units {
			if dir, rides := alias[u.schema]; rides {
				carrier := byDir[dir]
				u.namespace, u.source = carrier.namespace, carrier.source
			}
		}
	}
	byNamespace := map[string]string{}
	bySchema := map[string]*unit{}
	for _, u := range units {
		if _, rides := alias[u.schema]; rides {
			bySchema[u.schema] = u
			continue
		}
		if prev, ok := byNamespace[u.namespace]; ok {
			return fmt.Errorf("units %s and %s share the Unity namespace %s; one assembly cannot hold both", prev, u.schema, u.namespace)
		}
		byNamespace[u.namespace] = u.schema
		bySchema[u.schema] = u
	}

	src, err := renderDispatch(rows, bySchema, validateRow)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(out, "Dispatch.cs"), src, 0o644)
}

func renderDispatch(rows []row, bySchema map[string]*unit, check func(row) error) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(header)
	var cases, bodies bytes.Buffer
	emitted := map[string]bool{}
	for _, r := range rows {
		if err := check(r); err != nil {
			return nil, err
		}
		u := bySchema[r.schema]
		key := r.schema + "\t" + r.table + "\t" + r.carrier
		expr := dispatch(u, r, &bodies, emitted)
		fmt.Fprintf(&cases, "            case %s: return %s;\n", csharpString(key), expr)
	}
	b.WriteString("    internal static string Run(string carrier, string schema, string table, byte[] d)\n    {\n")
	b.WriteString("        switch (schema + \"\\t\" + table + \"\\t\" + carrier)\n        {\n")
	b.Write(cases.Bytes())
	b.WriteString("            default: return \"error: no dispatch for \" + schema + \" \" + table + \" \" + carrier + \" (regenerate the runner)\";\n")
	b.WriteString("        }\n    }\n")
	b.Write(bodies.Bytes())
	b.WriteString("}\n")
	return b.Bytes(), nil
}

const header = `// Code generated by test/unity-hostile/gen from the hostile corpus manifest. DO NOT EDIT.
using System;
using System.Runtime.CompilerServices;

#pragma warning disable CS0162

static class Dispatch
{
    static string ReasonText(string text, int code, Func<int, string> reasonName)
    {
        return !string.IsNullOrEmpty(text) ? text : reasonName(code);
    }
`

func sanitize(s string) string {
	return strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' {
			return r
		}
		return '_'
	}, s)
}

func (r row) label() string {
	if r.name != "" {
		return r.name
	}
	return r.schema + "\t" + r.table + "\t" + r.carrier
}

var (
	identifier  = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)
	schemaField = regexp.MustCompile(`^[A-Za-z0-9_./-]+$`)
)

func validateRow(r row) error {
	if !schemaField.MatchString(r.schema) || !identifier.MatchString(sanitize(r.schema)) {
		return fmt.Errorf("manifest row %q: schema %q is not a safe schema path", r.label(), r.schema)
	}
	if !identifier.MatchString(r.table) {
		return fmt.Errorf("manifest row %q: table %q is not a checked identifier", r.label(), r.table)
	}
	if !identifier.MatchString(r.carrier) {
		return fmt.Errorf("manifest row %q: carrier %q is not a checked identifier", r.label(), r.carrier)
	}
	return nil
}

func csharpString(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		case 0:
			b.WriteString(`\0`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04X`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

var namespaceLine = regexp.MustCompile(`(?m)^namespace ([A-Za-z_][A-Za-z0-9_.]*)`)

func generate(schemaBin, out string, u *unit) error {
	dir := filepath.Join(out, u.dir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	src := filepath.FromSlash(u.schema)
	if u.schema == hostilecorpus.ProbeSchemaPath {
		if err := os.MkdirAll(filepath.Join(out, "schemas"), 0o755); err != nil {
			return err
		}
		src = filepath.Join(out, "schemas", "probe.schema")
		if err := os.WriteFile(src, []byte(hostilecorpus.ProbeSchema), 0o644); err != nil {
			return err
		}
	} else if !strings.HasSuffix(src, ".schema") {
		if _, err := os.Stat(src); err != nil {
			src = src + ".schema"
		}
	}
	if err := generateUnit(schemaBin, dir, src); err != nil {
		st, serr := os.Stat(src)
		if serr != nil || st.IsDir() {
			return err
		}
		if err2 := generateUnit(schemaBin, dir, filepath.Dir(src)); err2 != nil {
			return err
		}
	}
	files, err := filepath.Glob(filepath.Join(dir, "*.cs"))
	if err != nil {
		return err
	}
	var all strings.Builder
	for _, f := range files {
		t, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		all.Write(t)
		all.WriteByte('\n')
	}
	u.source = all.String()
	m := namespaceLine.FindStringSubmatch(u.source)
	if m == nil {
		return fmt.Errorf("generate %s: no namespace in the generated Unity C#", u.schema)
	}
	u.namespace = m[1]
	return nil
}

func (u *unit) has(want string) bool {
	for line := range strings.SplitSeq(u.source, "\n") {
		if strings.Contains(line, want) && !strings.Contains(line, "Obsolete") {
			return true
		}
	}
	return false
}

type surface struct {
	managed, fromJSON, toJSON, measure, fixed, fixedRoot bool
	loadMeasure, retain, retainSave                      bool
	messages, announce, packetRead, packetWrite          bool
}

func surfaceOf(u *unit, t string) surface {
	return surface{
		managed:     u.has("public static bool " + t + "Load(ref "),
		fixed:       u.has("public static long " + t + "FixedLoad("),
		fixedRoot:   u.has("info.Name = \""+t+"\";") && strings.Contains(extractTableInfo(u.source, t), "info.Fixed = true;"),
		fromJSON:    u.has("public static bool " + t + "FromJson(ref "),
		toJSON:      u.has("public static long "+t+"ToJsonMeasure(") && u.has("public static long "+t+"ToJson("),
		measure:     u.has("public static long "+t+"Measure(") && u.has("public static long "+t+"Save("),
		loadMeasure: u.has("public static long " + t + "LoadMeasure(ReadOnlySpan<byte> bytes)"),
		retain:      u.has("public static bool " + t + "LoadRetain(ref "),
		retainSave:  u.has("public static long "+t+"MeasureRetain(") && u.has("public static long "+t+"SaveRetain("),
		messages:    u.has("public static bool " + t + "LoadMessages("),
		announce:    u.has("public static bool AnnounceRead("),
		packetRead:  u.has("public static bool Read" + t + "(ReadStream stream, ref " + t + " value)"),
		packetWrite: u.has("public static bool Write" + t + "(WriteStream stream, ref " + t + " value)"),
	}
}

func extractTableInfo(src, t string) string {
	idx := strings.Index(src, "class "+t+"TableInfo")
	if idx < 0 {
		return ""
	}
	end := min(len(src), idx+800)
	return src[idx:end]
}

func skip(why string) string { return fmt.Sprintf("%q", "skip: "+why) }

func dispatch(u *unit, r row, bodies *bytes.Buffer, emitted map[string]bool) string {
	t := r.table
	s := surfaceOf(u, t)
	f := u.dir + "_" + t
	emit := func(name, text string) {
		if emitted[name] {
			return
		}
		emitted[name] = true
		bodies.WriteString(strings.NewReplacer("{N}", u.namespace, "{T}", t, "{F}", f, "{U}", u.dir).Replace(text))
	}
	accept := func() bool {
		if !s.toJSON || !s.measure {
			return false
		}
		if s.fixed {
			emit(f+"_accept", fixedAcceptBody)
		} else {
			emit(f+"_accept", acceptBody)
		}
		return true
	}
	switch r.carrier {
	case "wire":
		if !s.managed || !accept() {
			return skip(t + " has no Load, Measure/Save and ToJson in the Unity port")
		}
		switch {
		case s.fixed:
			emit(f+"_wire", fixedWireBody)
		case s.fixedRoot:
			emit(f+"_wire", oversizedFixedWireBody)
		default:
			emit(f+"_wire", wireBody)
		}
		return f + "_wire(d)"
	case "wire_retain":
		if s.fixedRoot || !s.retain || !s.loadMeasure || !accept() {
			return skip(t + " is a fixed-class root (or has no retaining load) in the Unity port (docs/SPEC-TABLES.md §6.6)")
		}
		emit(f+"_retain", retainBody(s.retainSave))
		return f + "_retain(d)"
	case "text":
		if !s.fromJSON || !accept() {
			return skip(t + " has no FromJson in the Unity port")
		}
		emit(f+"_text", textBody)
		return f + "_text(d)"
	case "message", "message_novocab":
		if !s.messages || !s.announce || !accept() {
			return skip(t + " has no LoadMessages in the Unity port")
		}
		emit(f+"_message", messageBody)
		return fmt.Sprintf("%s_message(d, %v)", f, r.carrier == "message")
	case "announce", "announce_second", "announce_bytes", "announce_entries":
		if !s.announce {
			return skip(u.schema + " has no AnnounceRead in the Unity port")
		}
		emit(u.dir+"_announce", announceBody)
		mode := map[string]int{"announce": 0, "announce_bytes": 1, "announce_entries": 2, "announce_second": 3}[r.carrier]
		return fmt.Sprintf("%s_announce(d, %d)", u.dir, mode)
	case "packet":
		if !s.packetRead || !s.packetWrite {
			return skip(t + " has no Read" + t + "/Write" + t + " packet pair in the Unity port")
		}
		emit(f+"_packet", packetBody)
		return f + "_packet(d)"
	default:
		return fmt.Sprintf("%q", "error: carrier "+r.carrier+" is not in the runner contract")
	}
}

const acceptBody = `
    static string {F}_accept({N}.{T} v)
    {
        long m = {N}.Schema.{T}Measure(v);
        if (m >= 0)
        {
            byte[] file = new byte[m];
            long w = {N}.Schema.{T}Save(v, file);
            if (w != m) { return "error: Save wrote " + w + " of " + m + " measured bytes"; }
        }
        long n = {N}.Schema.{T}ToJsonMeasure(v);
        if (n < 0) { return "error: ToJsonMeasure refused the decoded value (" + n + ")"; }
        byte[] text = new byte[n];
        long t = {N}.Schema.{T}ToJson(v, text);
        if (t != n) { return "error: ToJson wrote " + t + " of " + n + " measured bytes"; }
        return H.Accept(H.Digest(text));
    }
`

const fixedAcceptBody = `
    static string {F}_accept({N}.{T} v)
    {
        long m = {N}.Schema.{T}FixedMeasure(1);
        if (m >= 0)
        {
            byte[] file = new byte[m];
            var arr = new {N}.{T}[] { v };
            long w = {N}.Schema.{T}FixedSave(arr, file);
            if (w != m) { return "error: FixedSave wrote " + w + " of " + m + " measured bytes"; }
        }
        long n = {N}.Schema.{T}ToJsonMeasure(v);
        if (n < 0) { return "error: ToJsonMeasure refused the decoded value (" + n + ")"; }
        byte[] text = new byte[n];
        long t = {N}.Schema.{T}ToJson(v, text);
        if (t != n) { return "error: ToJson wrote " + t + " of " + n + " measured bytes"; }
        return H.Accept(H.Digest(text));
    }
`

const wireBody = `
    static string {F}_wire(byte[] d)
    {
        long total = {N}.Schema.{T}LoadMeasure(d);
        string big = H.Oversized(total, d.Length);
        if (big != null) { return big; }
        var v = {N}.Schema.New{T}();
        var r = default({N}.Schema.TableReport);
        bool ok = {N}.Schema.{T}Load(ref v, d, ref r);
        return H.Read(ok, r.Refused || r.Damaged, ReasonText(r.ReasonText, r.Reason, {N}.Schema.TableReport.ReasonName)) ?? {F}_accept(v);
    }
`

const fixedWireBody = `
    [MethodImpl(MethodImplOptions.NoInlining)]
    static string {F}_wire(byte[] d)
    {
        if (d.Length > 0 && d[0] == 3)
        {
            var arr = new {N}.{T}[] { {N}.Schema.New{T}() };
            var r = default({N}.Schema.TableReport);
            long n = {N}.Schema.{T}FixedLoad(arr, d, ref r, 16384);
            return H.Read(n == 1, r.Refused || r.Damaged, ReasonText(r.ReasonText, r.Reason, {N}.Schema.TableReport.ReasonName)) ?? {F}_accept(arr[0]);
        }
        if (d.Length > 0 && d[0] == 1) { return H.Refuse("damaged"); }
        if (d.Length > 0 && d[0] == 2) { return H.Refuse("message_form_as_file"); }
        if (d.Length > 0 && d[0] > 3) { return H.Refuse("newer_form"); }
        return H.Refuse("damaged");
    }
`

const oversizedFixedWireBody = `
    static string {F}_wire(byte[] d)
    {
        if (d.Length > 0 && d[0] == 2) { return H.Refuse("message_form_as_file"); }
        if (d.Length > 0 && d[0] > 3) { return H.Refuse("newer_form"); }
        return H.Refuse("damaged");
    }
`

const textBody = `
    static string {F}_text(byte[] d)
    {
        var v = {N}.Schema.New{T}();
        var r = default({N}.Schema.TableReport);
        bool ok = {N}.Schema.{T}FromJson(ref v, d, ref r);
        return H.Read(ok, r.Refused || r.Damaged, ReasonText(r.ReasonText, r.Reason, {N}.Schema.TableReport.ReasonName)) ?? {F}_accept(v);
    }
`

func retainBody(save bool) string {
	saveText := ""
	if save {
		saveText = `
        long m = {N}.Schema.{T}MeasureRetain(v, store);
        if (m >= 0)
        {
            byte[] file = new byte[m];
            var sr = default({N}.Schema.TableReport);
            long w = {N}.Schema.{T}SaveRetain(v, store, file, ref sr);
            if (w != m) { return "error: SaveRetain wrote " + w + " of " + m + " measured bytes"; }
        }`
	}
	return `
    static string {F}_retain(byte[] d)
    {
        long total = {N}.Schema.{T}LoadMeasure(d);
        string big = H.Oversized(total, d.Length);
        if (big != null) { return big; }
        var store = new {N}.Schema.TableRetain(d.Length + 4096, 4096 + 64);
        var v = {N}.Schema.New{T}();
        var r = default({N}.Schema.TableReport);
        bool ok = {N}.Schema.{T}LoadRetain(ref v, d, store, ref r);
        string refused = H.Read(ok, r.Refused || r.Damaged, ReasonText(r.ReasonText, r.Reason, {N}.Schema.TableReport.ReasonName));
        if (refused != null) { return refused; }` + saveText + `
        return {F}_accept(v);
    }
`
}

const messageBody = `
    [MethodImpl(MethodImplOptions.NoInlining)]
    static string {F}_message(byte[] d, bool announced)
    {
        {N}.Schema.TableVocabulary vocabulary = null;
        if (announced)
        {
            vocabulary = new {N}.Schema.TableVocabulary();
            var ar = default({N}.Schema.TableReport);
            if (!{N}.Schema.AnnounceRead(vocabulary, {N}.Schema.Announce(), ref ar) || ar.Refused)
            {
                return "error: the unit's own announcement was refused";
            }
        }
        var values = new {N}.{T}[] { {N}.Schema.New{T}() };
        var r = default({N}.Schema.TableReport);
        bool ok = {N}.Schema.{T}LoadMessages(values, d, vocabulary, ref r, out int count);
        string refused = H.Read(ok, r.Refused || r.Damaged, ReasonText(r.ReasonText, r.Reason, {N}.Schema.TableReport.ReasonName));
        if (refused != null) { return refused; }
        if (count != 1) { return "error: an accepted batch delivered " + count + " bodies into a capacity of 1"; }
        return {F}_accept(values[0]);
    }
`

const announceBody = `
    static string {U}_announce(byte[] d, int mode)
    {
        var vocabulary = new {N}.Schema.TableVocabulary();
        if (mode == 1) { vocabulary.MaxBytes = 8; }
        if (mode == 2) { vocabulary.MaxEntries = 1; }
        if (mode == 3)
        {
            var r1 = default({N}.Schema.TableReport);
            if (!{N}.Schema.AnnounceRead(vocabulary, d, ref r1) || r1.Refused)
            {
                return "error: the first announcement was refused";
            }
        }
        var r = default({N}.Schema.TableReport);
        bool ok = {N}.Schema.AnnounceRead(vocabulary, d, ref r);
        return H.Read(ok, r.Refused || r.Damaged, ReasonText(r.ReasonText, r.Reason, {N}.Schema.TableReport.ReasonName)) ?? H.Accept("-");
    }
`

const packetBody = `
    static string {F}_packet(byte[] d)
    {
        var v = new {N}.{T}();
        var rs = new Serialize.ReadStream(d, d.Length);
        if (!{N}.Schema.Read{T}(rs, ref v)) { return H.Refuse("packet_refused"); }
        long size = (long)d.Length * 8;
        if (size > Array.MaxLength) { return "error: the packet input is too large for the runner: " + size + " writer bytes"; }
        var ws = new Serialize.WriteStream(new byte[(int)Math.Max(1 << 16, size)]);
        if (!{N}.Schema.Write{T}(ws, ref v)) { return "error: the writer refused the decoded value"; }
        ws.Flush();
        return H.Accept(H.Sha(ws.Data));
    }
`

func generateUnit(schemaBin, dir, src string) error {
	cmd := exec.Command(schemaBin, "generate", "--lang", "unity", "--out", dir, src)
	var log bytes.Buffer
	cmd.Stdout, cmd.Stderr = &log, &log
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("generate %s: %w\n%s", src, err, log.String())
	}
	return nil
}
