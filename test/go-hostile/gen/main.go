// Command gen builds dispatch to generated Go readers for the shared corpus.
// It uses the manifest only for input/schema selection, never for verdicts.
package main

import (
	"flag"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"github.com/mas-bandwidth/schema/v2/internal/ci/hostilecorpus"
)

func main() {
	compiler := flag.String("schema", "./bin/schema", "schema compiler")
	corpus := flag.String("corpus", "internal/ci/hostilecorpus/corpus", "fixed corpus directory")
	runtime := flag.String("serialize", "../serialize.go", "pinned serialize.go checkout")
	out := flag.String("out", "build/go-hostile", "private build directory")
	flag.Parse()
	if err := generate(*compiler, *corpus, *out, *runtime); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(compiler, corpus, out, runtime string) error {
	_, cases, err := hostilecorpus.LoadManifest(corpus)
	if err != nil {
		return err
	}
	root, err := os.Getwd()
	if err != nil {
		return err
	}
	runtime, err = filepath.Abs(runtime)
	if err != nil {
		return err
	}
	if _, err := os.Stat(filepath.Join(runtime, "go.mod")); err != nil {
		return fmt.Errorf("serialize.go runtime: %w", err)
	}
	abs, err := filepath.Abs(out)
	if err != nil {
		return err
	}
	if !strings.HasPrefix(abs, filepath.Join(root, "build")+string(os.PathSeparator)) {
		return fmt.Errorf("output must be below repository build/")
	}
	if err := os.MkdirAll(abs, 0755); err != nil {
		return err
	}
	schemas := map[string]bool{}
	for _, c := range cases {
		schemas[c.Schema] = true
	}
	names := make([]string, 0, len(schemas))
	for name := range schemas {
		names = append(names, name)
	}
	sort.Strings(names)
	aliases, sources := map[string]string{}, map[string]string{}
	var imports strings.Builder
	for i, name := range names {
		alias := fmt.Sprintf("u%02d", i)
		aliases[name] = alias
		dir := filepath.Join(abs, "generated", alias)
		if err := os.RemoveAll(dir); err != nil {
			return err
		}
		src := name
		if name == hostilecorpus.ProbeSchemaPath {
			src = filepath.Join(abs, "probe.schema")
			if err := os.WriteFile(src, []byte(hostilecorpus.ProbeSchema), 0644); err != nil {
				return err
			}
		}
		cmd := exec.Command(compiler, "generate", "--lang", "go", "--out", dir, src)
		if b, err := cmd.CombinedOutput(); err != nil {
			return fmt.Errorf("generate %s: %w\n%s", name, err, b)
		}
		paths, err := filepath.Glob(filepath.Join(dir, "*.go"))
		if err != nil {
			return err
		}
		var source strings.Builder
		for _, p := range paths {
			b, err := os.ReadFile(p)
			if err != nil {
				return err
			}
			source.Write(b)
		}
		sources[name] = source.String()
		fmt.Fprintf(&imports, "%s %q\n", alias, "example.com/schema-go-hostile/generated/"+alias)
	}
	var dispatch strings.Builder
	dispatch.WriteString("// Code generated by test/go-hostile/gen. DO NOT EDIT.\npackage main\nimport (\n")
	dispatch.WriteString(imports.String())
	dispatch.WriteString("\"fmt\"\n\"unsafe\"\n\"github.com/mas-bandwidth/schema/v2/tables/goruntime\"\n)\n")
	dispatch.WriteString("func dispatch(carrier, schema, table string, data []byte) string {\nswitch schema+\"\\t\"+table+\"\\t\"+carrier {\n")
	seen := map[string]bool{}
	for _, c := range cases {
		key := c.Schema + "\t" + c.Table + "\t" + c.Carrier
		if seen[key] {
			continue
		}
		seen[key] = true
		a, t := aliases[c.Schema], c.Table
		fmt.Fprintf(&dispatch, "case %q: {\nvar r goruntime.TableReport\n", key)
		variable := strings.Contains(sources[c.Schema], "type "+t+"Builder struct")
		switch c.Carrier {
		case "text":
			if variable {
				fmt.Fprintf(&dispatch, "var b %s.%sBuilder\nif !b.Init(){return \"error: builder init\"};defer b.Shutdown()\nok:=%s.%sFromJSON(&b,data,&r)\nif reason:=wireRefusal(ok,&r);reason!=\"\"{return reason}\nif !b.Lock(){return \"error: builder lock\"};v:=b.AsConst()\n", a, t, a, t)
			} else {
				fmt.Fprintf(&dispatch, "v:=new(%s.%s)\nok:=%s.%sFromJSON(v,data,&r)\nif reason:=wireRefusal(ok,&r);reason!=\"\"{return reason}\n", a, t, a, t)
			}
			emitDigest(&dispatch, a, t)
		case "wire":
			if variable {
				fmt.Fprintf(&dispatch, "n,err:=%s.%sLoadMeasureReason(data);if err!=nil{return measureRefusal(err)}\nif n<=0{return \"error: invalid region extent\"}\nraw:=make([]byte,n+63);off:=(-uintptr(unsafe.Pointer(&raw[0])))&63\nv:=%s.%sLoad(raw[off:off+uintptr(n)],data,&r)\nif reason:=wireRefusal(v!=nil,&r);reason!=\"\"{return reason}\n", a, t, a, t)
			} else {
				fmt.Fprintf(&dispatch, "v:=new(%s.%s)\nok:=%s.%sLoad(v,data,&r)\nif reason:=wireRefusal(ok,&r);reason!=\"\"{return reason}\n", a, t, a, t)
			}
			emitDigest(&dispatch, a, t)
		case "announce", "announce_second", "announce_bytes", "announce_entries":
			n := 4096
			if c.Carrier == "announce_entries" {
				n = 1
			}
			fmt.Fprintf(&dispatch, "v:=%s.TableVocabulary{Entries:make([]%s.TableMessageEntry,%d)}\n", a, a, n)
			if c.Carrier == "announce_bytes" {
				dispatch.WriteString("v.MaxBytes=8\n")
			}
			fmt.Fprintf(&dispatch, "ok:=%s.AnnounceRead(&v,data,&r)\n", a)
			if c.Carrier == "announce_second" {
				fmt.Fprintf(&dispatch, "if !ok{return \"error: first announcement refused\"};ok=%s.AnnounceRead(&v,data,&r)\n", a)
			}
			dispatch.WriteString("if reason:=wireRefusal(ok,&r);reason!=\"\"{return reason};return \"accept -\"\n")
		case "message", "message_novocab":
			fmt.Fprintf(&dispatch, "var vocabulary *%s.TableVocabulary\n", a)
			if c.Carrier == "message" {
				fmt.Fprintf(&dispatch, "vocabulary=&%s.TableVocabulary{Entries:make([]%s.TableMessageEntry,4096)}\nannouncement:=make([]byte,%s.AnnounceMeasure());%s.Announce(announcement)\nif !%s.AnnounceRead(vocabulary,announcement,&r){return \"error: own announcement refused\"}\n", a, a, a, a, a)
			}
			fmt.Fprintf(&dispatch, "values:=make([]%s.%s,1)\nn,ok:=%s.%sLoadMessages(values,vocabulary,data,&r)\nif reason:=wireRefusal(ok,&r);reason!=\"\"{return reason}\nif n!=1{return \"refuse damaged\"};v:=&values[0]\n", a, t, a, t)
			emitDigest(&dispatch, a, t)
		default:
			return fmt.Errorf("unsupported carrier %q", c.Carrier)
		}
		dispatch.WriteString("}\n")
	}
	dispatch.WriteString("default:return fmt.Sprintf(\"error: missing dispatch %s/%s/%s\",schema,table,carrier)\n}\n}\n")
	code, err := format.Source([]byte(dispatch.String()))
	if err != nil {
		return fmt.Errorf("format dispatch: %w\n%s", err, dispatch.String())
	}
	if err := os.WriteFile(filepath.Join(abs, "dispatch.go"), code, 0644); err != nil {
		return err
	}
	harness, err := os.ReadFile("test/go-hostile/runner.go.txt")
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(abs, "main.go"), harness, 0644); err != nil {
		return err
	}
	mod := fmt.Sprintf("module example.com/schema-go-hostile\n\ngo 1.26.0\n\nrequire (\n github.com/mas-bandwidth/schema/v2 v2.0.0\n github.com/mas-bandwidth/serialize.go/v2 v2.0.0\n)\nreplace github.com/mas-bandwidth/schema/v2 => %q\nreplace github.com/mas-bandwidth/serialize.go/v2 => %q\n", filepath.ToSlash(root), filepath.ToSlash(runtime))
	return os.WriteFile(filepath.Join(abs, "go.mod"), []byte(mod), 0644)
}

func emitDigest(b *strings.Builder, a, t string) {
	fmt.Fprintf(b, "return jsonDigest(func()int64{return %s.%sToJSONMeasure(v)},func(out []byte)int64{return %s.%sToJSON(v,out)})\n", a, t, a, t)
}
