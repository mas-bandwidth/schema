//go:build unix

// wirefuzzhost is THE LOBSTER WIRE-FUZZ LEG's host (test/conformance/README.md,
// "The wire-fuzz driver"; docs/PORT-LOBSTER.md, THE HARNESS, "The wire-fuzz
// pipe").
//
// The harness speaks a binary stream on one pipe and holds the oracle; a leg
// only reads. The pinned Lobster console build cannot be that leg alone: it
// reads stdin a line at a time and its print is block-buffered on a pipe with
// no flush, so a reply could never be flushed before the next mutant. This
// host is the fallback the port's design names: it speaks the stream, and the
// DECODING is Lobster's — test/conformance/lobster/wirefuzz.lobster, run once
// per generated unit (Lobster resolves imports when it compiles a program, so
// one program reaches one unit). The host hands each mutant over as a file
// and a command line, and the program answers the harness's reply record,
// byte for byte, through a named pipe. The host holds the pipe open for
// reading and writing for the whole run, so the program's open never waits
// and no open races a signal; the record is self-delimiting (47 bytes, then
// the saved bytes the record counts), so the host reads exactly one reply
// before it sends the next command. Every reply is therefore flushed before
// the next mutant, and a crash is attributed to the mutant that caused it. The host
// decides nothing about what a mutant means and never rewrites a reply.
//
//	wirefuzzhost [--builder] [--units build/conformance-lobster]
//
// With --builder the leg answers the harness's --builder arm (the
// variable-class file roots, against tablewire.Decode); without it, the
// ordinary run over the fixed-class file roots. The working directory is the
// repository root, as for every driver.
package main

import (
	"bufio"
	"bytes"
	"encoding/binary"
	"errors"
	"flag"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"sync"
	"syscall"
)

const program = "test/conformance/lobster/wirefuzz.lobster"

// unitLeg is one generated unit's running program.
type unitLeg struct {
	unit   string
	dir    string
	cmd    *exec.Cmd
	stdin  io.WriteCloser
	output bytes.Buffer // the program's stdout and stderr: a compiler warning lands here
	fifo   string
	reply  *os.File // the fifo, held open read-write for the whole run
	mutant string
	dead   chan struct{}
	err    error
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "wirefuzzhost: "+format+"\n", args...)
	os.Exit(1)
}

// lobsterBinary is the pinned toolchain: $LOBSTER, else the repo-local unpack.
func lobsterBinary() string {
	if p := os.Getenv("LOBSTER"); p != "" {
		return p
	}
	return "dist/lobster-v2026.8/bin/lobster"
}

// stage writes the program into the unit's directory as wirefuzz_main.lobster,
// after one `import .<Base>Table` per table module there (a module of imports
// alone does not compile), as the conformance driver stages main.lobster.
func stage(dir string) (string, error) {
	src, err := os.ReadFile(program)
	if err != nil {
		return "", err
	}
	tables, err := filepath.Glob(filepath.Join(dir, "*Table.lobster"))
	if err != nil {
		return "", err
	}
	sort.Strings(tables)
	var b strings.Builder
	b.WriteString("// GENERATED by test/conformance/lobster/wirefuzzhost from wirefuzz.lobster: the unit's table modules, then the program\n")
	for _, t := range tables {
		fmt.Fprintf(&b, "import .%s\n", strings.TrimSuffix(filepath.Base(t), ".lobster"))
	}
	b.Write(src)
	// written beside and renamed into place, so two hosts over one units
	// directory never compile a half-written program: every host stages the
	// same bytes, and a rename is atomic
	path := filepath.Join(dir, "wirefuzz_main.lobster")
	tmp, err := os.CreateTemp(dir, ".wirefuzz_main-*")
	if err != nil {
		return "", err
	}
	if _, err := tmp.WriteString(b.String()); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return "", err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmp.Name())
		return "", err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		os.Remove(tmp.Name())
		return "", err
	}
	return path, os.Rename(tmp.Name(), path)
}

func startUnit(unitsDir, unit, scratch, arm string) (*unitLeg, error) {
	dir := filepath.Join(unitsDir, unit)
	main, err := stage(dir)
	if err != nil {
		return nil, err
	}
	work := filepath.Join(scratch, unit)
	if err := os.MkdirAll(work, 0o755); err != nil {
		return nil, err
	}
	l := &unitLeg{unit: unit, dir: dir, fifo: filepath.Join(work, "reply"), mutant: filepath.Join(work, "mutant.bin"), dead: make(chan struct{})}
	if err := syscall.Mkfifo(l.fifo, 0o600); err != nil {
		return nil, fmt.Errorf("mkfifo %s: %w", l.fifo, err)
	}
	// O_RDWR on a fifo never blocks and keeps a writer present, so the
	// program's write_file open finds a reader at once on every reply
	if l.reply, err = os.OpenFile(l.fifo, os.O_RDWR, 0); err != nil {
		return nil, err
	}
	if err := os.WriteFile(l.mutant, nil, 0o644); err != nil {
		return nil, err
	}
	bin, err := filepath.Abs(lobsterBinary())
	if err != nil {
		return nil, err
	}
	if main, err = filepath.Abs(main); err != nil {
		return nil, err
	}
	l.cmd = exec.Command(bin, main, "--", l.fifo, l.mutant, arm)
	// the program runs in its scratch directory, so a leak report it writes
	// at exit (memory_leaks.txt) never lands in the checkout
	l.cmd.Dir = work
	l.cmd.Stdout = &l.output
	l.cmd.Stderr = &l.output
	if l.stdin, err = l.cmd.StdinPipe(); err != nil {
		return nil, err
	}
	if err := l.cmd.Start(); err != nil {
		return nil, fmt.Errorf("starting lobster for %s: %w", unit, err)
	}
	go func() {
		l.err = l.cmd.Wait()
		close(l.dead)
	}()
	return l, nil
}

// ask sends one command line and reads exactly one reply of the length
// measure says from the fifo. A program that exits instead is a failure
// naming the unit.
func (l *unitLeg) ask(command string, measure func(io.Reader) ([]byte, error)) ([]byte, error) {
	if _, err := io.WriteString(l.stdin, command+"\n"); err != nil {
		return nil, fmt.Errorf("unit %s closed its input on %q: %w\n%s", l.unit, command, err, l.output.String())
	}
	type result struct {
		b   []byte
		err error
	}
	ch := make(chan result, 1)
	go func() {
		b, err := measure(l.reply)
		ch <- result{b, err}
	}()
	select {
	case r := <-ch:
		return r.b, r.err
	case <-l.dead:
		return nil, fmt.Errorf("unit %s exited on %q (%w)\n%s", l.unit, command, l.err, l.output.String())
	}
}

// oneByte is a roster answer.
func oneByte(r io.Reader) ([]byte, error) {
	b := make([]byte, 1)
	_, err := io.ReadFull(r, b)
	return b, err
}

// replyHead is the reply record before the saved bytes
// (test/conformance/README.md): u8 loaded, five i32 counters, u8 malformed,
// u8 refused, i64 measure, i32 retained, i32 retain_lost, i64 saved.
const replyHead = 1 + 5*4 + 1 + 1 + 8 + 4 + 4 + 8

// oneRecord is a mutant's reply: the head, then the saved bytes when the
// saved length is positive.
func oneRecord(r io.Reader) ([]byte, error) {
	head := make([]byte, replyHead)
	if _, err := io.ReadFull(r, head); err != nil {
		return nil, err
	}
	saved := int64(binary.LittleEndian.Uint64(head[replyHead-8:]))
	if saved <= 0 {
		return head, nil
	}
	if saved > 1<<30 {
		return nil, fmt.Errorf("the reply record claims %d saved bytes", saved)
	}
	body := make([]byte, saved)
	if _, err := io.ReadFull(r, body); err != nil {
		return nil, err
	}
	return append(head, body...), nil
}

// leakReport is the line the pinned VM prints at exit when objects are still
// alive: reference counting never frees a cycle, so a loaded graph whose
// pointers close a cycle outlives the program.
const leakReport = "LEAKS FOUND"

// compiled checks the program's output once it has answered the roster, which
// is after it compiled: anything printed by then is a compiler warning, and
// generated Lobster compiles with no warning.
func (l *unitLeg) compiled() error {
	if out := l.output.String(); out != "" {
		return fmt.Errorf("unit %s printed while compiling (a warning fails the leg):\n%s", l.unit, out)
	}
	return nil
}

// close ends the unit's stream and answers whether the VM reported leaks at
// exit. Any other output fails.
func (l *unitLeg) close() (leaked bool, err error) {
	_, _ = io.WriteString(l.stdin, "\n")
	_ = l.stdin.Close()
	<-l.dead
	_ = l.reply.Close()
	out := l.output.String()
	if l.err != nil {
		return false, fmt.Errorf("unit %s exited with %w\n%s", l.unit, l.err, out)
	}
	if out == "" {
		return false, nil
	}
	if strings.Contains(out, leakReport) {
		return true, nil
	}
	return false, fmt.Errorf("unit %s printed:\n%s", l.unit, out)
}

// readKnownLeaks reads the KNOWN FINDINGS: one `<unit> <arm>` per line, `#`
// comments. A unit that leaks and is not listed fails, and a listed unit
// that no longer leaks fails too, so the list cannot rot into silence.
func readKnownLeaks(path, arm string) (map[string]bool, error) {
	known := map[string]bool{}
	if path == "" {
		return known, nil
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	for line := range strings.SplitSeq(string(data), "\n") {
		f := strings.Fields(line)
		if len(f) == 0 || strings.HasPrefix(f[0], "#") {
			continue
		}
		if len(f) < 2 {
			return nil, fmt.Errorf("%s: %q is not `<unit> <arm> ...`", path, line)
		}
		if f[1] == arm {
			known[f[0]] = true
		}
	}
	return known, nil
}

type entry struct {
	unit, root   string
	form, retain byte
}

// entryCommand is one command line naming a roster entry: the root, its
// FORM byte and its RETAIN byte.
func entryCommand(verb string, e entry) string {
	return fmt.Sprintf("%s %s %d %d", verb, e.root, e.form, e.retain)
}

func readString(r io.Reader) (string, error) {
	var n uint16
	if err := binary.Read(r, binary.LittleEndian, &n); err != nil {
		return "", err
	}
	b := make([]byte, n)
	_, err := io.ReadFull(r, b)
	return string(b), err
}

func main() {
	builder := flag.Bool("builder", false, "answer the --builder arm (variable-class file roots)")
	unitsDir := flag.String("units", "build/conformance-lobster", "the generated units, one directory each")
	knownPath := flag.String("known-leaks", "", "the units whose loaded cyclic graphs the VM reports leaked at exit, one `<unit> <arm>` a line")
	flag.Parse()
	arm := "file"
	if *builder {
		arm = "builder"
	}
	knownLeaks, err := readKnownLeaks(*knownPath, arm)
	if err != nil {
		fatalf("%v", err)
	}

	in := bufio.NewReaderSize(os.Stdin, 1<<20)
	out := bufio.NewWriterSize(os.Stdout, 1<<20)

	// THE ROSTER
	var count uint32
	if err := binary.Read(in, binary.LittleEndian, &count); err != nil {
		fatalf("reading the roster: %v", err)
	}
	roster := make([]entry, count)
	for i := range roster {
		var e entry
		var err error
		if e.unit, err = readString(in); err != nil {
			fatalf("reading the roster: %v", err)
		}
		if e.root, err = readString(in); err != nil {
			fatalf("reading the roster: %v", err)
		}
		var fr [2]byte
		if _, err := io.ReadFull(in, fr[:]); err != nil {
			fatalf("reading the roster: %v", err)
		}
		e.form, e.retain = fr[0], fr[1]
		roster[i] = e
	}

	scratch, err := os.MkdirTemp("", "lobster-wirefuzz-")
	if err != nil {
		fatalf("%v", err)
	}
	defer func() { _ = os.RemoveAll(scratch) }()

	// one program per unit the roster names and the target generated (a unit
	// it refused has no directory: its roots are 0), started in parallel
	// because each compiles its unit
	units := map[string]*unitLeg{}
	for _, e := range roster {
		if _, seen := units[e.unit]; seen {
			continue
		}
		units[e.unit] = nil
		if _, err := os.Stat(filepath.Join(*unitsDir, e.unit, "schema_tables.lobster")); err == nil {
			l, err := startUnit(*unitsDir, e.unit, scratch, arm)
			if err != nil {
				fatalf("%v", err)
			}
			units[e.unit] = l
		}
	}
	known := make([]byte, len(roster))
	var wg sync.WaitGroup
	var mu sync.Mutex
	var firstErr error
	byUnit := map[string][]int{}
	for i, e := range roster {
		byUnit[e.unit] = append(byUnit[e.unit], i)
	}
	for unit, idx := range byUnit {
		l := units[unit]
		if l == nil {
			continue
		}
		wg.Go(func() {
			for _, i := range idx {
				b, err := l.ask(entryCommand("root", roster[i]), oneByte)
				if err == nil && b[0] > 1 {
					err = fmt.Errorf("unit %s answered %d for root %s", unit, b[0], roster[i].root)
				}
				if err != nil {
					mu.Lock()
					firstErr = cmpErr(firstErr, err)
					mu.Unlock()
					return
				}
				known[i] = b[0]
			}
		})
	}
	wg.Wait()
	if firstErr != nil {
		fatalf("%v", firstErr)
	}
	for _, l := range units {
		if l == nil {
			continue
		}
		if err := l.compiled(); err != nil {
			fatalf("%v", err)
		}
	}
	if _, err := out.Write(known); err != nil {
		fatalf("%v", err)
	}
	if err := out.Flush(); err != nil {
		fatalf("%v", err)
	}

	// THE MUTANTS, one reply each, flushed before the next is read
	for {
		var head [8]byte
		if _, err := io.ReadFull(in, head[:]); err != nil {
			if errors.Is(err, io.EOF) {
				break
			}
			fatalf("reading a mutant: %v", err)
		}
		index := binary.LittleEndian.Uint32(head[0:])
		size := binary.LittleEndian.Uint32(head[4:])
		data := make([]byte, size)
		if _, err := io.ReadFull(in, data); err != nil {
			fatalf("reading a mutant: %v", err)
		}
		if int(index) >= len(roster) || known[index] == 0 {
			fatalf("the harness sent a mutant for roster entry %d, which this leg answered 0", index)
		}
		e := roster[index]
		l := units[e.unit]
		if err := os.WriteFile(l.mutant, data, 0o644); err != nil {
			fatalf("%v", err)
		}
		reply, err := l.ask(entryCommand("load", e), oneRecord)
		if err != nil {
			fatalf("%v", err)
		}
		if _, err := out.Write(reply); err != nil {
			fatalf("%v", err)
		}
		if err := out.Flush(); err != nil {
			fatalf("%v", err)
		}
	}
	names := make([]string, 0, len(units))
	for unit, l := range units {
		if l != nil {
			names = append(names, unit)
		}
	}
	sort.Strings(names)
	var failures []string
	for _, unit := range names {
		leaked, err := units[unit].close()
		if err != nil {
			fatalf("%v", err)
		}
		switch {
		case leaked && knownLeaks[unit]:
			fmt.Fprintf(os.Stderr, "wirefuzzhost: KNOWN FINDING %s (%s arm): the VM reports leaked records at exit (a loaded cyclic graph)\n", unit, arm)
		case leaked:
			failures = append(failures, fmt.Sprintf("unit %s leaked records at exit and no known finding names it", unit))
		case knownLeaks[unit]:
			failures = append(failures, fmt.Sprintf("unit %s is a known leak finding for the %s arm but leaked nothing: delete its line", unit, arm))
		}
	}
	if len(failures) > 0 {
		fatalf("%s", strings.Join(failures, "\n"))
	}
}

func cmpErr(first, err error) error {
	if first != nil {
		return first
	}
	return err
}
