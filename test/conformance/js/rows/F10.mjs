// F10 — no_layout: per-record hash names no layout the reader holds (docs/FIXED-FORM-ALGORITHM.md:148).
//
// SPEC: "per record: if `LE(8, at) != h`, `REFUSE no_layout`; then §4.4"
//
// A FIXED-TABLE RECORD OPENS WITH AN EIGHT-BYTE HASH OF THE WRITER'S LAYOUT.
// When a reader loads a record whose first eight bytes are not the hash of the
// layout the file's header named, the reader must REFUSE under the name
// `no_layout` — not `malformed`, not a counter, nothing decoded, nothing
// written to the caller's storage, the prefill included.
//
// This is the law of §5.3's step 7: the hash check runs BEFORE any byte is
// landed, and a record whose hash names no layout this build knows about
// refuses by name.
//
// run: node test/conformance/js/rows/F10.mjs
// exit: 0 = all assertions passed, 1 = one or more failed
// depends on: build/js-fixed/fx1/* (generated by make build/js-fixed/.stamp)

import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

// §3's header layout, spelled out here rather than imported — a driver that
// read the offsets out of the code under test would agree with whatever header
// that code happened to write, which is the one thing this file exists to refuse.
const HEADER_BYTES = 16;
const LAYOUT_AT = 20;

const generated = process.env.SCHEMA_JS_GENERATED ?? "build/js-fixed";
const load = (p) => import(pathToFileURL(resolve(generated, p)).href);

let pass = 0;
let fail = 0;

function check(ok, msg) {
  if (ok) {
    console.log("PASS " + msg);
    pass++;
  } else {
    console.log("FAIL " + msg);
    fail++;
  }
}

async function main() {
  const fx1 = await load("fx1/FX1Table.js");
  const fx1home = await load("fx1/Tblfx1Table.js");
  const R = fx1home.TableFixedRefusal;

  // --- build a valid form-3 file of this leg's own FX1 ---
  const one = new fx1home.FxRoot();
  one.Keep = 4242;
  one.Narrow = 40000;
  one.Renamed = 321;
  one.Gone = 654;
  one.Nested.A = 111;
  one.Nested.B = 222;

  const w1 = new Uint8Array(fx1.FxRootFixedMeasure(1));
  check(
    fx1.FxRootFixedSave([one], 1, w1) === w1.length,
    "valid form-3 fixture saves its own length"
  );

  // --- forge the record's hash: the header still names this build's own layout,
  //     but record 0 now names none this reader holds — no_layout ---
  const bad = Uint8Array.from(w1);
  bad[LAYOUT_AT + fx1.FxRootFixedLayoutBytes] ^= 0xff;

  // --- THE DESTINATION IS POISONED, NOT RESET ---
  // A read that wrote a default would look exactly like a read that wrote
  // nothing if the destination started at its construction values, so every byte
  // of the caller's image takes a sentinel a lawful read never lands (0x5A).
  const plan = fx1.FxRootFixedNewPlan();
  plan.image.fill(0x5A);

  const values = [new fx1home.FxRoot()];
  const v = values[0];
  v.Keep = 0x5A5A5A5A;
  v.Narrow = 0x5A5A;
  v.Renamed = 0x5A5A;
  v.Gone = 0x5A5A;
  v.Nested.A = 0x5A5A;
  v.Nested.B = 0x5A5A;
  v.Label.fill(0x5A);
  v.LabelLength = 0x5A;
  v.Marks.fill(0x5A);
  v.MarksCount = 0x5A;
  v.Blob.fill(0x5A);
  v.BlobLength = 0x5A;

  // --- the actual load ---
  const r = new fx1home.TableFixedReport();
  const n = fx1.FxRootFixedLoad(values, 1, bad, bad.length, plan, r);

  // --- ASSERTION 1: the refusal is named no_layout, malformed is FALSE ---
  // §5.3 step 7: the per-record hash check fires before any decode, so the
  // record is refused under its own name and the malformed flag never moves.
  check(
    n === -1 && r.refused === R.NoLayout && !r.malformed,
    "REFUSE by name: a record whose hash names no held layout refuses no_layout, and malformed is FALSE"
  );

  // --- ASSERTION 2: no counter moves ---
  // REFUSE is total — when a record is refused, not one counter advances.
  check(
    r.unknown === 0 && r.kindMismatch === 0 && r.clamped === 0 && r.widened === 0 && r.duplicate === 0,
    "REFUSE is total: no counter moves"
  );

  // --- ASSERTION 3: not one destination byte is written, the prefill included ---
  // The hash check runs BEFORE the prefill; a refused read leaves the caller's
  // image exactly as it was handed in.
  check(
    plan.image.every((b) => b === 0x5A),
    "REFUSE writes nothing: not one destination byte is written, the prefill included"
  );

  // --- ASSERTION 4: nothing is decoded ---
  // Every decoded value field remains at its poisoned sentinel.
  check(
    v.Keep === 0x5A5A5A5A && v.Narrow === 0x5A5A && v.Renamed === 0x5A5A && v.Gone === 0x5A5A &&
      v.Nested.A === 0x5A5A && v.Nested.B === 0x5A5A &&
      v.Label.every((b) => b === 0x5A) && v.LabelLength === 0x5A &&
      v.Marks.every((b) => b === 0x5A) && v.MarksCount === 0x5A &&
      v.Blob.every((b) => b === 0x5A) && v.BlobLength === 0x5A,
    "REFUSE is total: nothing is decoded"
  );

  if (fail > 0) {
    console.log("\nFAILED: " + fail + " of " + (pass + fail) + " assertions");
    process.exit(1);
  } else {
    console.log("\nPASSED: " + pass + " assertions");
    process.exit(0);
  }
}

main();
