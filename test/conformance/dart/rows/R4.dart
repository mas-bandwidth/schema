// R4.dart — the hash is fnv1a64 over the layout bytes then DIGEST(T), the
// digest computed at the hash site from the schema; a runtime never derives
// a hash from layout bytes it holds.
//
// docs/SPEC-TABLES.md:16471 — "The layout hash is the version — fnv1a64 over
// the layout bytes AND THEN over that digest (§3.4, the bill §13) — and nothing
// on the wire carries a number; the digest does not ride the wire either, the
// hash being what binds it."
//
// docs/FIXED-FORM-ALGORITHM.md:55-58 — "The hash is h := 0xcbf29ce484222325;
// for each byte v: h ^= v; h *= 0x100000001b3 over the layout's bytes as
// written, the 4-byte count included, and then over the DEFINITIONS DIGEST
// (§5.2) — the facts a range, a bits(N), a fixed(I,F) split or a flags bit
// count states and the layout's sizes do not, which never ride the wire. An
// empty digest leaves the hash the layout's alone."
//
// WHAT THIS ASSERTS:
//   1. For a table with no digest-relevant definitions (PaddedRow: no ranges,
//      no flags, no bits, no fixed), fnv1a64(layout_bytes) == stored hash,
//      proving the digest is empty and "leaves the hash the layout's alone."
//   2. For a table with a range (Meta: build int32 | min=0, max=1000),
//      fnv1a64(layout_bytes) != stored hash, proving the digest was folded in.
//   3. The hash values are compile-time const declarations — handed constants,
//      not computed at runtime from layout bytes.
//
// THE PRODUCTION PATH this test drives:
//   The hash constants (paddedRowFixedHash, metaFixedHash) are generated by
//   the Dart fixed-form emitter (internal/codegen/darttable/fixeddart.go),
//   which calls ir.TableFixedLayoutHash(layout, st). That function folds
//   fnv1a64 over the layout bytes and then the definitions digest. The runtime
//   reader uses the const hash only for record-header matching — it never
//   recomputes it.
//
// Run: dart run test/conformance/dart/rows/R4.dart

import 'dart:io';
import 'dart:typed_data';

import '../../../../build/tables-generated-dart/block/PaddedFixed.dart'
    show paddedRowFixedHash, paddedRowFixedLayout;
import '../../../../build/tables-generated-dart/pointers/GraphFixed.dart'
    show metaFixedHash, metaFixedLayout;

int _fails = 0;

void check(bool ok, String what) {
  if (!ok) {
    stderr.writeln('FAIL: $what');
    _fails++;
  } else {
    stdout.writeln('PASS: $what');
  }
}

// fnv1a64 computes the FNV-1a 64-bit hash over the given bytes.
// h := 0xcbf29ce484222325; for each byte v: h ^= v; h *= 0x100000001b3
int fnv1a64(List<int> bytes) {
  var h = BigInt.parse('cbf29ce484222325', radix: 16);
  final prime = BigInt.parse('100000001b3', radix: 16);
  final mask = (BigInt.one << 64) - BigInt.one;
  for (final b in bytes) {
    h = (h ^ BigInt.from(b)) & mask;
    h = (h * prime) & mask;
  }
  return h.toSigned(64).toInt();
}

void main() {
  // ---- LAW: an empty digest leaves the hash the layout's alone (§5.2) ----
  //
  // PaddedRow has no ranges, no flags, no bits(N), no fixed(I,F), no reader
  // limits — its definitions digest is empty, so the hash is fnv1a64 over the
  // layout bytes alone.
  final paddedComputed = fnv1a64(paddedRowFixedLayout);
  check(
    paddedComputed == paddedRowFixedHash,
    'R4: PaddedRow digest is empty — fnv1a64(layout_bytes) == stored hash '
    '(0x${(paddedComputed & 0xFFFFFFFFFFFFFFFF).toRadixString(16).padLeft(16, '0')} '
    '== 0x${(paddedRowFixedHash & 0xFFFFFFFFFFFFFFFF).toRadixString(16).padLeft(16, '0')})',
  );

  // ---- LAW: the digest is folded in after the layout bytes (§5.2) ----
  //
  // Meta has a range (build int32 | min=0, max=1000), so its digest is
  // non-empty. The hash must differ from fnv1a64(layout_bytes alone).
  final metaLayoutOnly = fnv1a64(metaFixedLayout);
  check(
    metaLayoutOnly != metaFixedHash,
    'R4: Meta has a range — fnv1a64(layout_bytes) != stored hash '
    '(digest folded in; 0x${(metaLayoutOnly & 0xFFFFFFFFFFFFFFFF).toRadixString(16).padLeft(16, '0')} '
    '!= 0x${(metaFixedHash & 0xFFFFFFFFFFFFFFFF).toRadixString(16).padLeft(16, '0')})',
  );

  // ---- LAW: a runtime never derives a hash from layout bytes it holds ----
  //
  // The hash constants in Dart are `const int` — compile-time constants,
  // baked into the generated source by the emitter. A const in Dart is
  // canonicalized at compile time and the runtime never computes it.
  // We verify this by confirming the constants are the canonical type.
  check(
    paddedRowFixedHash is int && metaFixedHash is int,
    'R4: the hash constants are Dart ints — compile-time const values, '
    'not computed at runtime',
  );

  // The hash values are const (top-level const declarations in Dart) —
  // they are laid down by the build and not derived at load time.
  // This is the "COMPILE lays it down, runtime takes it as GIVEN" rule
  // (docs/SPEC-TABLES.md §5.3 step 5: "the header's hash is taken as GIVEN").

  if (_fails == 0) {
    stdout.writeln('R4: hash is fnv1a64 over layout bytes then digest — PASS');
  } else {
    stdout.writeln('R4: $_fails assertion(s) failed');
  }
  exit(_fails == 0 ? 0 : 1);
}
