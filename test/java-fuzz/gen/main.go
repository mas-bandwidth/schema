// Command gen writes the Jazzer entry points for the Java port's generated
// table readers. It reads the tree make/java.mk generates (never a second
// corpus), finds every <Table>Variable / <Table>Fixed reader, and emits one
// fuzzerTestOneInput per reader kind: variable load, fixed strict load and
// variable text/JSON parse. The manifest it writes lists the fully qualified
// class of every target so the Makefile can run each inside the time budget.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var packageRE = regexp.MustCompile(`(?m)^package\s+([A-Za-z_][A-Za-z0-9_]*)\s*;`)

type target struct{ pkg, class, unit, table, kind string }

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen: "+format+"\n", args...)
	os.Exit(1)
}

func main() {
	generated := flag.String("generated", "build/tables-generated-java", "generated Java tree")
	out := flag.String("out", "build/java-fuzz", "harness output root")
	flag.Parse()

	if _, err := os.Stat(*generated); err != nil {
		fail("generated tree %s is missing (run make build/tables-generated-java/.stamp): %v", *generated, err)
	}
	targets, err := discover(*generated)
	if err != nil {
		fail("%v", err)
	}
	if len(targets) == 0 {
		fail("no generated readers found under %s -- the glob, not the property, is what broke", *generated)
	}
	src := filepath.Join(*out, "src")
	cl := filepath.Join(*out, "classes")
	if err := os.RemoveAll(*out); err != nil {
		fail("%v", err)
	}
	if err := os.MkdirAll(src, 0o755); err != nil {
		fail("%v", err)
	}
	if err := os.MkdirAll(cl, 0o755); err != nil {
		fail("%v", err)
	}
	for _, t := range targets {
		dir := filepath.Join(src, t.pkg)
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fail("%v", err)
		}
		if err := os.WriteFile(filepath.Join(dir, t.class+".java"), []byte(targetSource(t)), 0o644); err != nil {
			fail("%v", err)
		}
	}
	if err := os.WriteFile(filepath.Join(src, "NightlyReplay.java"), []byte(replaySource), 0o644); err != nil {
		fail("%v", err)
	}
	var b strings.Builder
	for _, t := range targets {
		fmt.Fprintf(&b, "%s.%s %s %s %s\n", t.pkg, t.class, t.unit, t.table, t.kind)
	}
	if err := os.WriteFile(filepath.Join(*out, "manifest.txt"), []byte(b.String()), 0o644); err != nil {
		fail("%v", err)
	}
	fmt.Printf("generated %d Jazzer targets from %s\n", len(targets), *generated)
}

func discover(root string) ([]target, error) {
	var out []target
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(path, ".java") {
			return err
		}
		base := strings.TrimSuffix(filepath.Base(path), ".java")
		kind := ""
		switch {
		case strings.HasSuffix(base, "Variable"):
			kind = "variable"
		case strings.HasSuffix(base, "Fixed"):
			kind = "fixed"
		default:
			return nil
		}
		body, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		text := string(body)
		m := packageRE.FindStringSubmatch(text)
		if m == nil {
			return fmt.Errorf("%s has no package clause", path)
		}
		unit := filepath.Base(filepath.Dir(path))
		table := strings.TrimSuffix(base, map[string]string{"variable": "Variable", "fixed": "Fixed"}[kind])
		switch kind {
		case "variable":
			if strings.Contains(text, "public static Value load(byte[] data, TableVariable.Report report)") {
				out = append(out, target{m[1], "Nightly" + table + "LoadFuzz", unit, table, "load"})
			}
			if strings.Contains(text, "public static Value fromJson(byte[] text, TableVariable.Report report)") {
				out = append(out, target{m[1], "Nightly" + table + "JsonFuzz", unit, table, "json"})
			}
		case "fixed":
			if strings.Contains(text, "public static int load(") {
				out = append(out, target{m[1], "Nightly" + table + "StrictFuzz", unit, table, "strict"})
			}
		}
		return nil
	})
	sort.Slice(out, func(i, j int) bool {
		if out[i].pkg != out[j].pkg {
			return out[i].pkg < out[j].pkg
		}
		return out[i].class < out[j].class
	})
	return out, err
}

func targetSource(t target) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by test/java-fuzz/gen. DO NOT EDIT.\npackage %s;\n\n", t.pkg)
	fmt.Fprintf(&b, "public final class %s {\n    private %s() {}\n\n", t.class, t.class)
	b.WriteString("    public static void fuzzerTestOneInput(byte[] data) {\n")
	switch t.kind {
	case "load":
		fmt.Fprintf(&b, "        TableVariable.Report report = new TableVariable.Report();\n        %sVariable.load(data, report);\n", t.table)
	case "json":
		fmt.Fprintf(&b, "        TableVariable.Report report = new TableVariable.Report();\n        %sVariable.fromJson(data, report);\n", t.table)
	case "strict":
		fmt.Fprintf(&b, "        TableFixed.Report report = new TableFixed.Report();\n")
		b.WriteString("        int n = Math.min(data.length, 256);\n")
		fmt.Fprintf(&b, "        %sFixed.Value[] values = new %sFixed.Value[n];\n", t.table, t.table)
		b.WriteString("        for (int i = 0; i < n; i++) { values[i] = new " + t.table + "Fixed.Value(); }\n")
		fmt.Fprintf(&b, "        %sFixed.load(values, n, data, null, null, new byte[Math.max(1, data.length)], report);\n", t.table)
	}
	b.WriteString("    }\n}\n")
	return b.String()
}

const replaySource = `// Code generated by test/java-fuzz/gen. DO NOT EDIT.
import java.lang.reflect.InvocationTargetException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.List;

// Replays every saved regression input against the target it names, with no
// clock: the fuzzer's finding is an input file, and the replay is the proof it
// still fires. A saved name is <simple-class>__<anything>.bin.
public final class NightlyReplay {
    private NightlyReplay() {}

    public static void main(String[] args) throws Exception {
        Path manifest = Paths.get(args[0]);
        Path corpus = Paths.get(args[1]);
        List<String> lines = Files.readAllLines(manifest);
        int replayed = 0;
        boolean failed = false;
        for (String line : lines) {
            if (line.isBlank()) continue;
            String fqcn = line.trim().split("\\s+")[0];
            String simple = fqcn.substring(fqcn.lastIndexOf('.') + 1);
            Class<?> target = Class.forName(fqcn);
            for (Path p : Files.newDirectoryStream(corpus)) {
                String name = p.getFileName().toString();
                if (!name.startsWith(simple + "__")) continue;
                try {
                    target.getMethod("fuzzerTestOneInput", byte[].class)
                          .invoke(null, (Object) Files.readAllBytes(p));
                } catch (InvocationTargetException e) {
                    failed = true;
                    System.err.println("REPLAY FAILED: " + name + " -> " + fqcn + ": " + e.getCause());
                }
                replayed++;
            }
        }
        System.out.println("replayed " + replayed + " saved input(s)");
        if (replayed == 0) {
            System.out.println("replay: no saved inputs yet (the fuzzer has found nothing to save)");
        }
        if (failed) System.exit(1);
    }
}
`
