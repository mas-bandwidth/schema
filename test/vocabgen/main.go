// vocabgen writes the WIDE-VOCABULARY units the message form's reference width
// is held by (docs/SPEC-TABLES.md §3.3): tables of thirteen fields each, enough
// of them that the unit's vocabulary passes a power of two and its references
// take one more bit. vocabdemo's passes 128, so a reference is 8 bits, and
// vocab9demo's passes 256, so a reference is 9 bits, which is the pair the
// page names.
//
// A generator wrote them rather than a person, on test/cookgen's precedent: a
// hundred and thirty distinct field names typed by hand is a file nobody would
// review and a bound nobody would trust. What is COMMITTED is the schema and
// every wire it produces — a golden a generator has to re-derive is not a
// golden — and this program is how the files are regenerated deliberately.
//
//	go run ./test/vocabgen --out tables/vocab/Vocab.schema
//	go run ./test/vocabgen --package vocab9demo --tables 20 --out tables/vocab9/Vocab9.schema
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// fields is the shape of every table: thirteen fields, so ten tables put the
// last field past slot 127 and twenty put it past 255.
const fields = 13

func main() {
	out := flag.String("out", "tables/vocab/Vocab.schema", "the schema file to write")
	pkg := flag.String("package", "vocabdemo", "the unit's package name")
	tables := flag.Int("tables", 10, "how many tables of thirteen fields to declare")
	flag.Parse()

	var b strings.Builder
	fmt.Fprintf(&b, `// %s — GENERATED by test/vocabgen. Do not edit by hand; regenerate
// with: go run ./test/vocabgen --package %s --tables %d --out %s
//
// A WIDE-VOCABULARY unit of the message form's corpus (docs/SPEC-TABLES.md
// §3.3). %d tables of thirteen fields each name %d distinct ids, so the
// unit's vocabulary passes %d before its tail begins and a reference on this
// unit's bodies is %d bits wide: a message over the LAST table names entries
// at the far end of that range and a message over the FIRST names them at the
// near end, which is the row a leg that fixes the reference width goes red on.
package %s

`, filepath.Base(*out), *pkg, *tables, *out, *tables, *tables*fields, boundary(*tables*fields), refBits(*tables*fields), *pkg)
	for t := range *tables {
		fmt.Fprintf(&b, "table Wide%02d\n{\n", t)
		for f := range fields {
			fmt.Fprintf(&b, "    field_%02d_%02d uint32 = 0\n", t, f)
		}
		b.WriteString("}\n")
		if t != *tables-1 {
			b.WriteString("\n")
		}
	}

	if dir := filepath.Dir(*out); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fatal(err)
		}
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fatal(err)
	}
}

// boundary is the power of two the field count passes.
func boundary(n int) int {
	p := 1
	for p*2 <= n {
		p *= 2
	}
	return p
}

// refBits is bits_required(0, E) for a vocabulary of at least n entries.
func refBits(n int) int {
	bits := 0
	for v := n; v > 0; v >>= 1 {
		bits++
	}
	return bits
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "vocabgen:", err)
	os.Exit(1)
}
