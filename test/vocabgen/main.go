// vocabgen writes the WIDE-VOCABULARY unit the message form's slot encoding is
// held by (docs/SPEC-TABLES.md §3.3): ten tables of thirteen fields each, so
// the unit's vocabulary passes 127 ids well before the tail and its
// announcement carries slots on BOTH SIDES of the one-byte boundary.
//
// A generator wrote it rather than a person, on test/cookgen's precedent: a
// hundred and thirty distinct field names typed by hand is a file nobody would
// review and a bound nobody would trust. What is COMMITTED is the schema and
// every wire it produces — a golden a generator has to re-derive is not a
// golden — and this program is how the file is regenerated deliberately.
//
//	go run ./test/vocabgen --out tables/vocab/Vocab.schema
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// tables and fields are the shape: 10 x 13 = 130 distinct field names, which
// puts the last of them past slot 127 with the reserved build-version id at
// slot 1 and before the tail has been reached at all.
const (
	tables = 10
	fields = 13
)

func main() {
	out := flag.String("out", "tables/vocab/Vocab.schema", "the schema file to write")
	flag.Parse()

	var b strings.Builder
	b.WriteString(`// Vocab.schema — GENERATED by test/vocabgen. Do not edit by hand; regenerate
// with: go run ./test/vocabgen --out tables/vocab/Vocab.schema
//
// The WIDE-VOCABULARY unit of the message form's corpus (docs/SPEC-TABLES.md
// §3.3). Ten tables of thirteen fields each name 130 distinct ids, so the
// unit's vocabulary passes 127 before its tail begins: a message over the
// LAST table names ids in TWO-BYTE slots and a message over the FIRST names
// them in one-byte slots, which is the row the reference encoding goes red on.
//
// A unit past 127 ids spends two bytes on the references beyond there rather
// than one, which the compiler cannot help, because it cannot know which ids
// are hot. That is a cost of the unit's size, and this unit is what pins the
// encoding paying it correctly and MINIMALLY.
package vocabdemo

`)
	for t := 0; t < tables; t++ {
		fmt.Fprintf(&b, "table Wide%02d\n{\n", t)
		for f := 0; f < fields; f++ {
			fmt.Fprintf(&b, "    field_%02d_%02d uint32 = 0\n", t, f)
		}
		b.WriteString("}\n")
		if t != tables-1 {
			b.WriteString("\n")
		}
	}

	if dir := filepath.Dir(*out); dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			fatal(err)
		}
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fatal(err)
	}
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "vocabgen:", err)
	os.Exit(1)
}
