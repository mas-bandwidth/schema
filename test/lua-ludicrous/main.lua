-- The Lua cross-language wire test for the fixed-point and 128-bit unit
-- (examples128/), the twin of test/luau-ludicrous/main.luau,
-- test/js-ludicrous/main.mjs and test/ludicrous_main.cpp block for block: the
-- generated module writes the SAME pinned instances and byte-compares against
-- the C++-pinned testdata/wire goldens, reads them back, zeroes an untaken
-- 128-bit field, installs the specified 128-bit defaults, and rejects (never
-- clamps) hostile offsets and truncation. Prints OK, or the failures and an
-- error.
--
-- usage: lua test/lua-ludicrous/main.lua <generated examples128 dir> <testdata/wire dir>
local generated, wireDir = arg[1], arg[2]
if generated == nil or wireDir == nil then
  error("usage: lua test/lua-ludicrous/main.lua <generated dir> <wire dir>")
end
package.path = generated .. "/?.lua;" .. package.path

local serialize = require("serialize")
local lud = require("Ludicrous")

local failed = false
local function check(ok, what)
  if not ok then
    print("FAILED: " .. what)
    failed = true
  end
end

local function hex(s)
  return (s:gsub(".", function(c)
    return string.format("%02x", c:byte())
  end))
end

local function readGolden(name)
  local file = io.open(wireDir .. "/" .. name .. ".bin", "rb")
  if file == nil then
    return nil
  end
  local bytes = file:read("a")
  file:close()
  return bytes
end

local function i128(lo, hi)
  return { lo = lo, hi = hi }
end

local function eq128(a, b)
  return a.lo == b.lo and a.hi == b.hi
end

-- deepEqual compares two values field by field.
local function deepEqual(a, b)
  if type(a) ~= type(b) then
    return false
  end
  if type(a) ~= "table" then
    return a == b
  end
  for k, x in pairs(a) do
    if not deepEqual(x, b[k]) then
      return false
    end
  end
  for k in pairs(b) do
    if a[k] == nil then
      return false
    end
  end
  return true
end

-- goldenWire byte-compares written wire against the C++-pinned golden.
local function goldenWire(name, data)
  local golden = readGolden(name)
  check(golden ~= nil, "the golden " .. name .. " is readable")
  check(golden ~= nil and data == golden,
    "wire golden " .. name .. ": Lua bytes " .. hex(data) .. " must equal the C++-pinned bytes " .. hex(golden or ""))
end

-- setBits forces bits [pos, pos + n) of a wire image to 1: the hostile
-- reader's tool, smuggling an offset into a range's bit headroom, which a
-- read must REJECT, never clamp (STANDARD.md).
local function setBits(data, pos, n)
  local bytes = { data:byte(1, -1) }
  for i = pos, pos + n - 1 do
    local index = i // 8 + 1
    bytes[index] = bytes[index] | (1 << (i % 8))
  end
  return string.char(table.unpack(bytes))
end

local function write(fn, v, what)
  local ws = serialize.WriteStream.new(256)
  check(fn(ws, v), "write " .. what)
  ws:flush()
  return ws:data()
end

local function read(fn, data, out)
  return fn(serialize.ReadStream.new(data), out)
end

-- makeState is test/ludicrous_main.cpp's make_state: the values stay mirrored.
local function makeState()
  local inp = lud.NewLudicrousState()
  inp.Mode = lud.DriveMode.Ludicrous
  inp.Probe.Angle = 2981888 -- +45.5 * 2^16
  inp.Probe.Position = -809119744 -- -12346.1875 * 2^16
  inp.Probe.Reach = i128(65535999999, 0) -- raw_max - 1
  inp.Probe.Ticks = 777777
  inp.Probe.Samples[1] = -524288 -- raw_min
  inp.Probe.Samples[2] = 524288 -- raw_max
  inp.Wide.EntityId = i128(0xfedcba9876543210, 0x0123456789abcdef)
  inp.Wide.Energy = i128(4999999999, 0)
  inp.Wide.Flux = i128(7, 0x0000000800000000) -- 2^99 + 7
  -- Wide.Bias and Wide.Seed stay at their SPECIFIED DEFAULTS (-250 and 2^65)
  inp.KeysCount = 2
  inp.Keys[1] = i128(1, 0)
  inp.Keys[2] = i128(0, 0x8000000000000000) -- 2^127
  inp.HasTarget = true
  inp.TargetId = i128(42, 0)
  return inp
end

check(lud.ProtocolId == 0xd2ded2cc8a482aa1, "the unit's protocol id is the C++ reference's")

-- construction installs the specified defaults (SPEC §4.2), one of which no
-- 64-bit literal can spell; Zero is the §5 zero form
do
  local zero = lud.NewLudicrousState()
  check(zero.Mode == lud.DriveMode.None, "a fresh state starts at DriveMode None")
  check(eq128(zero.Probe.Reach, i128(0, 0)), "reach starts zero")
  check(eq128(zero.Wide.EntityId, i128(0, 0)), "entity_id starts zero")
  check(eq128(zero.Wide.Bias, i128(-250, -1)), "bias defaults -250")
  check(eq128(zero.Wide.Seed, i128(0, 2)), "seed defaults 2^65")
  check(zero.KeysCount == 0, "keys start empty")
  check(eq128(zero.TargetId, i128(0, 0)), "target_id starts zero")
  lud.ZeroLudicrousState(zero)
  check(eq128(zero.Wide.Bias, i128(0, 0)), "the §5 zero form stays zero")
end

-- the taken-branch wire: generated bytes == the C++-pinned golden
local takenWire
do
  local inp = makeState()
  takenWire = write(lud.WriteLudicrousState, inp, "LudicrousState")
  goldenWire("ludicrous_state", takenWire)
  local out = lud.NewLudicrousState()
  check(read(lud.ReadLudicrousState, takenWire, out), "read LudicrousState")
  check(out.Mode == lud.DriveMode.Ludicrous, "mode round-trips")
  check(deepEqual(out.Probe, inp.Probe), "the fixed probe round-trips")
  check(deepEqual(out.Wide, inp.Wide), "the wide probe round-trips, the defaults riding the wire")
  check(out.KeysCount == 2 and eq128(out.Keys[1], inp.Keys[1]) and eq128(out.Keys[2], inp.Keys[2]), "keys round-trip")
  check(out.HasTarget and eq128(out.TargetId, i128(42, 0)), "the taken branch round-trips")
end

-- the untaken branch: the 128-bit field under it reads back ZERO into a
-- dirty object (SPEC §5)
do
  local inp = makeState()
  inp.HasTarget = false
  local data = write(lud.WriteLudicrousState, inp, "LudicrousState untargeted")
  goldenWire("ludicrous_state_untargeted", data)
  local out = lud.NewLudicrousState()
  out.TargetId = i128(0xdead, 0)
  check(read(lud.ReadLudicrousState, data, out), "read LudicrousState untargeted")
  check(not out.HasTarget, "has_target reads false")
  check(eq128(out.TargetId, i128(0, 0)), "the untaken 128-bit field reads as zero (SPEC §5)")
end

-- hostile reads REJECT, never clamp (STANDARD.md, SPEC §5)
do
  -- fixed: angle's 25 offset bits start at bit 2; all ones is above the raw range
  local hostile = setBits(takenWire, 2, 25)
  check(not read(lud.ReadLudicrousState, hostile, lud.NewLudicrousState()), "a smuggled fixed offset is REJECTED")
  -- int128: energy's 34 offset bits start at bit 286; all ones is above 10^10
  hostile = setBits(takenWire, 286, 34)
  check(not read(lud.ReadLudicrousState, hostile, lud.NewLudicrousState()), "a smuggled int128 offset is REJECTED")
  -- truncation: running out of input mid-read is a read failure (SPEC §5)
  check(not read(lud.ReadLudicrousState, takenWire:sub(1, 4), lud.NewLudicrousState()),
    "a truncated stream is a read failure")
end

-- DegenerateProbe: min == max costs ZERO bits (SPEC §4.6); the whole wire
-- is the tail byte
do
  local inp = lud.NewDegenerateProbe()
  inp.LockedFixed = -196608 -- -3 * 2^16, the ONE legal raw
  inp.LockedInt = 7
  inp.LockedWide = i128(-12345678901234, -1)
  inp.Tail = 0xa5
  local data = write(lud.WriteDegenerateProbe, inp, "DegenerateProbe")
  goldenWire("degenerate_probe", data)
  check(#data == 1, "three degenerate fields cost zero bits: the wire is the tail byte")
  local out = lud.NewDegenerateProbe()
  check(read(lud.ReadDegenerateProbe, data, out), "read DegenerateProbe")
  check(deepEqual(out, inp), "DegenerateProbe round-trips: every value materialized from its range")
end

-- UnsignedProbe: ufixed(I, F) (SPEC §4.3); span's raw value fills uint64's
-- HIGH HALF, carried as the integer's unsigned bit pattern
do
  local inp = lud.NewUnsignedProbe()
  inp.Angle = 2981888
  inp.Span = 0xffffffffffff0000 -- raw_max, the uint64 high half
  inp.Reach = i128(131071999999, 0) -- raw_max - 1
  inp.Ticks = 777777
  inp.Samples[1] = 0
  inp.Samples[2] = 1048576
  inp.Locked = 196608 -- 3 * 2^16, the ONE legal raw
  inp.Tail = 0xa5
  local uWire = write(lud.WriteUnsignedProbe, inp, "UnsignedProbe")
  goldenWire("unsigned_probe", uWire)
  local out = lud.NewUnsignedProbe()
  check(read(lud.ReadUnsignedProbe, uWire, out), "read UnsignedProbe")
  check(deepEqual(out, inp), "UnsignedProbe round-trips, the uint64 high half bit-exact")
  -- the write-side degenerate refusal: any raw but 3 * 2^16 is refused
  inp.Locked = 196609
  check(not lud.WriteUnsignedProbe(serialize.WriteStream.new(256), inp), "a wrong degenerate ufixed raw is REFUSED on write")
  -- hostile: span's 64 offset bits from bit 25, all ones, above the raw
  -- range in the UNSIGNED domain
  local hostile = setBits(uWire, 25, 64)
  check(not read(lud.ReadUnsignedProbe, hostile, lud.NewUnsignedProbe()), "a smuggled ufixed high-half offset is REJECTED")
end

if failed then
  error("lua ludicrous: FAILED")
end
print("OK")
