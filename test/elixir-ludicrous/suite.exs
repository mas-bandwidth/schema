# The test battery main.exs loads after the generated module — see the note
# there on why the two files are split.
defmodule SchemaTestElixirLudicrous do
  import Bitwise

  def check(ok, what) do
    unless ok do
      IO.puts("FAILED: #{what}")
      Process.put(:schema_test_failed, true)
    end
  end

  def expect_raise(fun, what) do
    fun.()
    check(false, what)
  rescue
    ArgumentError -> :ok
  end

  def golden(name), do: File.read!("../../testdata/wire/#{name}.bin")

  # set_bits forces bits [pos, pos + n) of the wire image to 1 — the hostile
  # reader's tool: smuggling an offset into the range's bit headroom, which a
  # read must REJECT, never clamp (STANDARD.md).
  def set_bits(data, _pos, 0), do: data

  def set_bits(data, pos, n) do
    byte_index = pos >>> 3
    <<head::binary-size(^byte_index), b, tail::binary>> = data
    set_bits(<<head::binary, b ||| 1 <<< (pos &&& 7), tail::binary>>, pos + 1, n - 1)
  end

  # make_state is test/ludicrous_main.cpp's make_state — the values must stay
  # mirrored on both sides.
  def make_state do
    %Ludicrous.LudicrousState{
      mode: Ludicrous.DriveMode.ludicrous(),
      probe: %Ludicrous.FixedProbe{
        # +45.5 * 2^16
        angle: 2_981_888,
        # -12346.1875 * 2^16
        position: -809_119_744,
        # raw_max - 1
        reach: 65_536_000_000 - 1,
        ticks: 777_777,
        # [raw_min, raw_max]
        samples: [-524_288, 524_288]
      },
      wide: %Ludicrous.WideProbe{
        entity_id: 0x0123456789ABCDEF_FEDCBA9876543210,
        energy: 4_999_999_999,
        # 2^99 + 7
        flux: (1 <<< 99) + 7
        # bias and seed stay at their SPECIFIED DEFAULTS (-250 and 2^65) —
        # construction installs them, and they ride the wire as written
      },
      keys: [1, 1 <<< 127],
      has_target: true,
      target_id: 42
    }
  end

  def run do
    # worst-case bounds, hand-derived (SPEC §6.1 item 4) — the same numbers
    # test/ludicrous_main.cpp static_asserts
    check(Ludicrous.Ludicrous.fixed_probe_max_bits() == 156, "FixedProbe worst case")
    check(Ludicrous.Ludicrous.wide_probe_max_bits() == 403, "WideProbe worst case")
    check(Ludicrous.Ludicrous.ludicrous_state_max_bits() == 1205, "LudicrousState worst case")
    check(Ludicrous.Ludicrous.protocol_id() != 0, "the unit has a protocol id")

    # zero initialization with specified defaults (SPEC §4.2), sentinel-zero
    # composition: construction starts at DriveMode None — the null rides
    # in-band — and the two defaulted 128-bit fields construct to their
    # declared values, one of which no 64-bit literal can spell
    zero = %Ludicrous.LudicrousState{}
    check(zero.mode == Ludicrous.DriveMode.none(), "a fresh state starts at DriveMode None")
    check(zero.probe.reach == 0, "reach starts zero")
    check(zero.wide.entity_id == 0, "entity_id starts zero")
    check(zero.wide.bias == -250, "bias defaults -250")
    check(zero.wide.seed == 1 <<< 65, "seed defaults 2^65")
    check(zero.keys == [], "keys start empty")
    check(zero.target_id == 0, "target_id starts zero")
    # zero_* is the §5 zero form; construction alone installs the defaults
    check(Ludicrous.Ludicrous.zero_ludicrous_state().wide.bias == 0, "the §5 zero form stays zero")

    # ---- the taken-branch wire: generated bytes == the C++-pinned golden ----
    inp = make_state()
    taken_wire = Ludicrous.Ludicrous.write_ludicrous_state(inp)
    g = golden("ludicrous_state")
    check(taken_wire == g, "wire golden ludicrous_state — Elixir bytes must equal the C++-pinned bytes")

    check(
      div(Ludicrous.Ludicrous.measure_ludicrous_state(inp) + 7, 8) == byte_size(taken_wire),
      "measure vs written bytes"
    )

    {:ok, out} = Ludicrous.Ludicrous.read_ludicrous_state(taken_wire, byte_size(taken_wire) * 8)
    check(out.mode == Ludicrous.DriveMode.ludicrous(), "mode round-trips")
    check(out.probe.angle == inp.probe.angle, "angle round-trips")
    check(out.probe.position == inp.probe.position, "position round-trips")
    check(out.probe.reach == inp.probe.reach, "reach round-trips")
    check(out.probe.ticks == inp.probe.ticks, "ticks round-trips")
    check(out.probe.samples == [-524_288, 524_288], "samples round-trip")
    check(out.wide.entity_id == inp.wide.entity_id, "entity_id round-trips")
    check(out.wide.energy == inp.wide.energy, "energy round-trips")
    check(out.wide.flux == inp.wide.flux, "flux round-trips")
    check(out.wide.bias == -250, "the bias default rides")
    check(out.wide.seed == 1 <<< 65, "the seed default rides")
    check(out.keys == [1, 1 <<< 127], "keys round-trip")
    check(out.has_target and out.target_id == 42, "the taken branch round-trips")

    check(
      Ludicrous.Ludicrous.write_ludicrous_state(out) == taken_wire,
      "LudicrousState round-trips to identical bytes"
    )

    # ---- the untaken branch: identical prefix, and the 128-bit field under
    # it reads back ZERO (SPEC §5) ----
    untargeted = %{inp | has_target: false}
    u_wire = Ludicrous.Ludicrous.write_ludicrous_state(untargeted)
    check(u_wire == golden("ludicrous_state_untargeted"), "wire golden ludicrous_state_untargeted")

    {:ok, out_u} = Ludicrous.Ludicrous.read_ludicrous_state(u_wire, byte_size(u_wire) * 8)
    check(not out_u.has_target, "has_target reads false")
    check(out_u.target_id == 0, "the untaken 128-bit field reads as zero (SPEC §5)")

    # ---- hostile reads REJECT, never clamp (STANDARD.md, SPEC §5) ----
    # fixed: angle's 25 offset bits start at bit 2; all-ones = 33554431,
    # above the raw range 360 * 2^16 = 23592960
    hostile = set_bits(taken_wire, 2, 25)

    check(
      Ludicrous.Ludicrous.read_ludicrous_state(hostile, byte_size(hostile) * 8) == :error,
      "a smuggled fixed offset is REJECTED"
    )

    # int128: energy's 34 offset bits start at bit 286 (2+156+128);
    # all-ones = 2^34 - 1 = 17179869183, above the range 10^10
    hostile2 = set_bits(taken_wire, 286, 34)

    check(
      Ludicrous.Ludicrous.read_ludicrous_state(hostile2, byte_size(hostile2) * 8) == :error,
      "a smuggled int128 offset is REJECTED"
    )

    # truncation: running out of input mid-read is a read failure (SPEC §5)
    t = binary_part(taken_wire, 0, 4)

    check(
      Ludicrous.Ludicrous.read_ludicrous_state(t, byte_size(t) * 8) == :error,
      "a truncated stream is a read failure"
    )

    # ---- DegenerateProbe: min == max costs ZERO bits (SPEC §4.6) ----
    # The whole wire is the tail byte; a port that emits ANY bits for a
    # degenerate range shifts it and fails the golden compare.
    check(Ludicrous.Ludicrous.degenerate_probe_max_bits() == 8, "three degenerate fields cost zero bits")

    dp = %Ludicrous.DegenerateProbe{
      # -3 * 2^16, the ONE legal raw
      locked_fixed: -196_608,
      locked_int: 7,
      locked_wide: -12_345_678_901_234,
      tail: 0xA5
    }

    dp_wire = Ludicrous.Ludicrous.write_degenerate_probe(dp)
    check(dp_wire == golden("degenerate_probe"), "wire golden degenerate_probe")
    check(Ludicrous.Ludicrous.measure_degenerate_probe(dp) == 8, "the degenerate wire is one byte")

    {:ok, out_dp} = Ludicrous.Ludicrous.read_degenerate_probe(dp_wire, byte_size(dp_wire) * 8)

    check(
      out_dp.locked_fixed == -196_608 and out_dp.locked_int == 7 and
        out_dp.locked_wide == -12_345_678_901_234 and out_dp.tail == 0xA5,
      "DegenerateProbe round-trips — every value materialized from its range"
    )

    # ---- UnsignedProbe: ufixed(I, F), the unsigned sibling (SPEC §4.3) ----
    # span's raw value fills uint64's HIGH HALF (above 2^63) — a plain BEAM
    # integer holds it exactly, and the C++-pinned golden is the gate.
    check(Ludicrous.Ludicrous.unsigned_probe_max_bits() == 196, "UnsignedProbe worst case")

    up = %Ludicrous.UnsignedProbe{
      # +45.5 * 2^16
      angle: 2_981_888,
      # raw_max — the uint64 HIGH HALF
      span: 0xFFFFFFFFFFFF0000,
      # raw_max - 1
      reach: 131_071_999_999,
      ticks: 777_777,
      # [raw_min, raw_max]
      samples: [0, 1_048_576],
      # 3 * 2^16, the ONE legal raw
      locked: 196_608,
      tail: 0xA5
    }

    u_probe_wire = Ludicrous.Ludicrous.write_unsigned_probe(up)
    check(u_probe_wire == golden("unsigned_probe"), "wire golden unsigned_probe")

    {:ok, out_up} = Ludicrous.Ludicrous.read_unsigned_probe(u_probe_wire, byte_size(u_probe_wire) * 8)

    check(
      out_up.span == 0xFFFFFFFFFFFF0000 and out_up.reach == 131_071_999_999 and
        out_up.locked == 196_608,
      "UnsignedProbe round-trips — the uint64 high half bit-exact"
    )

    # the write-side degenerate contract: any raw but 3 * 2^16 raises —
    # contracts are always on (no compile-out assert exists on the BEAM)
    expect_raise(
      fn -> Ludicrous.Ludicrous.write_unsigned_probe(%{up | locked: 196_609}) end,
      "a wrong degenerate ufixed raw must trip the writer contract"
    )

    # hostile: span's 64 offset bits (starting at bit 25) all-ones =
    # 2^64 - 1, above the raw range 0xFFFFFFFFFFFF0000 — the headroom is
    # exactly the low 16 bits, and the reject fires in plain integer
    # comparison (BEAM integers are unbounded — no signed-domain trap exists)
    hostile3 = set_bits(u_probe_wire, 25, 64)

    check(
      Ludicrous.Ludicrous.read_unsigned_probe(hostile3, byte_size(hostile3) * 8) == :error,
      "a smuggled ufixed high-half offset is REJECTED"
    )

    if Process.get(:schema_test_failed, false) do
      System.halt(1)
    end

    IO.puts("OK")
  end
end

SchemaTestElixirLudicrous.run()
