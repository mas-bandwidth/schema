// The dispatch table the Rust hostile-corpus runner reads through
// (docs/HOSTILE-CORPUS.md).
//
// Every (schema, table) pair the manifest names is bound to the generated
// functions of the unit crate built from that schema. The crate's own source is
// scanned for the function names, so a table's snake-case spelling is read off
// the compiler's output rather than re-derived here. A pair whose functions are
// absent gets no binding, and the runner reports that case as a SKIP or a FAIL
// by carrier.
//
// Inputs (set by make/schema-rust-runs-hostile-corpus.mk):
//   RUST_HOSTILE_MANIFEST  the corpus manifest.tsv
//   RUST_HOSTILE_UNITS     a tsv of crate<TAB>schema<TAB>generated src dir

use std::collections::{BTreeMap, BTreeSet};
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

struct Unit {
    krate: String,
    fns: BTreeSet<String>,
}

fn squash(s: &str) -> String {
    s.chars().filter(|c| *c != '_').flat_map(|c| c.to_lowercase()).collect()
}

// Every `pub fn <name>(` in the crate's source files.
fn scan(dir: &Path) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    let mut entries: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("{}: {e}", dir.display()))
        .map(|e| e.expect("dir entry").path())
        .filter(|p| p.extension().is_some_and(|x| x == "rs"))
        .collect();
    entries.sort();
    for path in entries {
        let text = fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        for line in text.lines() {
            let Some(rest) = line.trim_start().strip_prefix("pub fn ") else { continue };
            let name: String = rest.chars().take_while(|c| c.is_ascii_alphanumeric() || *c == '_').collect();
            if !name.is_empty() {
                out.insert(name);
            }
        }
    }
    out
}

// The snake-case stem whose `<stem><suffix>` the crate defines and whose
// squashed spelling is the table's.
fn stem(unit: &Unit, table: &str, prefix: &str, suffix: &str) -> Option<String> {
    let want = squash(table);
    unit.fns.iter().find_map(|f| {
        let s = f.strip_prefix(prefix)?.strip_suffix(suffix)?;
        (squash(s) == want).then(|| s.to_string())
    })
}

fn main() {
    let manifest = env::var("RUST_HOSTILE_MANIFEST").expect("RUST_HOSTILE_MANIFEST");
    let units_path = env::var("RUST_HOSTILE_UNITS").expect("RUST_HOSTILE_UNITS");
    println!("cargo:rerun-if-env-changed=RUST_HOSTILE_MANIFEST");
    println!("cargo:rerun-if-env-changed=RUST_HOSTILE_UNITS");
    println!("cargo:rerun-if-changed={manifest}");
    println!("cargo:rerun-if-changed={units_path}");

    let mut units: BTreeMap<String, Unit> = BTreeMap::new();
    for line in fs::read_to_string(&units_path).expect("units").lines() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let f: Vec<&str> = line.split('\t').collect();
        assert_eq!(f.len(), 3, "units line: {line}");
        println!("cargo:rerun-if-changed={}", f[2]);
        units.insert(f[1].to_string(), Unit { krate: f[0].to_string(), fns: scan(Path::new(f[2])) });
    }

    let mut tables: BTreeSet<(String, String)> = BTreeSet::new();
    let mut packets: BTreeSet<(String, String)> = BTreeSet::new();
    let mut vocabs: BTreeSet<String> = BTreeSet::new();
    for line in fs::read_to_string(&manifest).expect("manifest").lines() {
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let f: Vec<&str> = line.split('\t').collect();
        if f.len() != 9 {
            continue; // the runner reports a malformed line
        }
        let (carrier, schema, table) = (f[1], f[2].to_string(), f[3].to_string());
        match carrier {
            "packet" => {
                packets.insert((schema, table));
            }
            "announce" | "announce_second" | "announce_bytes" | "announce_entries" => {
                vocabs.insert(schema);
            }
            _ => {
                tables.insert((schema, table));
            }
        }
    }

    let mut out = String::new();
    out.push_str("// generated by test/rust-hostile/build.rs from the corpus manifest\n\n");

    out.push_str("pub fn table(schema: &str, table: &str) -> Option<TableOps> {\n    match (schema, table) {\n");
    for (schema, table) in &tables {
        let Some(unit) = units.get(schema) else { continue };
        let Some(s) = stem(unit, table, "", "_load_retain") else { continue };
        let need = ["_load", "_save_checked", "_save_retain", "_load_measure", "_to_json_checked", "_from_json_bytes"];
        if !need.iter().all(|n| unit.fns.contains(&format!("{s}{n}"))) {
            continue;
        }
        let msg = ["_load_messages", "_measure_messages", "_save_messages", "_message_default", "_fixed_write_body"]
            .iter()
            .all(|n| unit.fns.contains(&format!("{s}{n}")));
        let k = &unit.krate;
        let _ = writeln!(
            out,
            "        ({schema:?}, {table:?}) => Some(table_ops!({k}, {s}_load, {s}_load_retain, {s}_save_checked, {s}_save_retain, {s}_load_measure, {s}_to_json_checked, {s}_from_json_bytes, {msg_arm})),",
            msg_arm = if msg {
                format!("Some(message_ops!({k}, {s}_load_messages, {s}_measure_messages, {s}_save_messages, {s}_message_default, {s}_fixed_write_body, {s}_from_json_bytes, {s}_to_json_checked))")
            } else {
                "None".to_string()
            }
        );
    }
    out.push_str("        _ => None,\n    }\n}\n\n");

    out.push_str("pub fn vocabulary(schema: &str) -> Option<VocabularyOps> {\n    match schema {\n");
    for schema in &vocabs {
        let Some(unit) = units.get(schema) else { continue };
        if !unit.fns.contains("announce_read") || !unit.fns.contains("announce") {
            continue;
        }
        let _ = writeln!(out, "        {schema:?} => Some(vocabulary_ops!({})),", unit.krate);
    }
    out.push_str("        _ => None,\n    }\n}\n\n");

    out.push_str("pub fn packet(schema: &str, table: &str) -> Option<PacketOps> {\n    match (schema, table) {\n");
    for (schema, table) in &packets {
        let Some(unit) = units.get(schema) else { continue };
        let Some(s) = stem(unit, table, "read_", "") else { continue };
        if !unit.fns.contains(&format!("write_{s}")) {
            continue;
        }
        let _ = writeln!(out, "        ({schema:?}, {table:?}) => Some(packet_ops!({}, read_{s}, write_{s})),", unit.krate);
    }
    out.push_str("        _ => None,\n    }\n}\n");

    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("dispatch.rs");
    fs::write(dest, out).expect("write dispatch.rs");
}
