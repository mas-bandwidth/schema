static ludicrous::LudicrousState make_state()
{
    using namespace ludicrous;
    LudicrousState in;
    in.mode = DriveMode::Ludicrous;
    in.probe.angle = 2981888;                                   // +45.5 * 2^16
    in.probe.position = -809119744ll;                           // -12345.25 * 2^16
    in.probe.reach = serialize::int128_t( 65536000000ll - 1 );  // raw_max - 1
    in.probe.ticks = 777777;
    in.probe.samples[0] = -524288;                              // raw_min
    in.probe.samples[1] = 524288;                               // raw_max
    in.wide.entity_id = ( serialize::uint128_t( 0x0123456789ABCDEFull ) << 64 )
                      | serialize::uint128_t( 0xFEDCBA9876543210ull );
    in.wide.energy = serialize::int128_t( 4999999999ll );
    in.wide.flux = ( serialize::int128_t( 1 ) << 99 ) + serialize::int128_t( 7 );
    // wide.bias and wide.seed stay at their SPECIFIED DEFAULTS (-250 and
    // 2^65) — construction installs them, and they ride the wire as written
    in.keys_count = 2;
    in.keys[0] = serialize::uint128_t( 1 );
    in.keys[1] = serialize::uint128_t( 1 ) << 127;
    in.has_target = true;
    in.target_id = serialize::uint128_t( 42 );
    return in;
}

int main()
{
    using namespace ludicrous;

    // worst-case bounds, hand-derived (SPEC §6.1 item 4):
    //   FixedProbe    25 + 32 + 37 + 20 + 2*21               = 156
    //   WideProbe     128 + 34 + 102 + 11 + 128              = 403
    //   LudicrousState 2 + 156 + 403 + (3 + 4*128) + 1 + 128 = 1205
    //   Message       tag [0,1] = 1 bit + 1205               = 1206
    static_assert(FixedProbeMaxBits == 156, "FixedProbe worst case");
    static_assert(WideProbeMaxBits == 403, "WideProbe worst case");
    static_assert(LudicrousStateMaxBits == 1205, "LudicrousState worst case");
    static_assert(MessageMaxBits == 1206, "message-level bound");
    static_assert(ProtocolId != 0, "the unit has a protocol id");

    // zero initialization with specified defaults (SPEC §4.2), sentinel-zero
    // composition: a fresh state starts at DriveMode::None — the null rides
    // in-band — and the two defaulted 128-bit fields construct to their
    // declared values, one of which no int64 literal can spell
    {
        LudicrousState zero;
        check( zero.mode == DriveMode::None );
        check( zero.probe.reach == serialize::int128_t( 0 ) );
        check( zero.wide.entity_id == serialize::uint128_t( 0 ) );
        check( zero.wide.bias == serialize::int128_t( -250 ) );
        check( zero.wide.seed == serialize::uint128_t( 1 ) << 65 );
        check( zero.keys_count == 0 );
        check( zero.target_id == serialize::uint128_t( 0 ) );
    }

    alignas( 8 ) uint8_t buffer[256];

    // ---- the taken-branch wire: generated bytes == STANDARD.md-derived ----
    {
        LudicrousState in = make_state();
        serialize::WriteStream ws( buffer, sizeof( buffer ) );
        check( WriteLudicrousState( ws, in ) );
        ws.Flush();
        check( ws.GetBytesProcessed() == (int) sizeof( expected_ludicrous_state ) );
        check( std::memcmp( buffer, expected_ludicrous_state, sizeof( expected_ludicrous_state ) ) == 0 );
        check( golden_wire( "ludicrous_state", buffer, ws.GetBytesProcessed() ) );

        LudicrousState out;
        serialize::ReadStream rs( buffer, ws.GetBytesProcessed() );
        check( ReadLudicrousState( rs, out ) );
        check( out.mode == DriveMode::Ludicrous );
        check( out.probe.angle == in.probe.angle );
        check( out.probe.position == in.probe.position );
        check( out.probe.reach == in.probe.reach );
        check( out.probe.ticks == in.probe.ticks );
        check( out.probe.samples[0] == in.probe.samples[0] );
        check( out.probe.samples[1] == in.probe.samples[1] );
        check( out.wide.entity_id == in.wide.entity_id );
        check( out.wide.energy == in.wide.energy );
        check( out.wide.flux == in.wide.flux );
        check( out.wide.bias == serialize::int128_t( -250 ) );
        check( out.wide.seed == serialize::uint128_t( 1 ) << 65 );
        check( out.keys_count == 2 );
        check( out.keys[0] == in.keys[0] );
        check( out.keys[1] == in.keys[1] );
        check( out.has_target && out.target_id == serialize::uint128_t( 42 ) );
    }

    // ---- the untaken branch: identical prefix, and the 128-bit field under
    // it reads back ZERO into a dirty object (SPEC §5) ----
    {
        LudicrousState in = make_state();
        in.has_target = false;
        serialize::WriteStream ws( buffer, sizeof( buffer ) );
        check( WriteLudicrousState( ws, in ) );
        ws.Flush();
        check( ws.GetBytesProcessed() == (int) sizeof( expected_ludicrous_state_untargeted ) );
        check( std::memcmp( buffer, expected_ludicrous_state_untargeted, sizeof( expected_ludicrous_state_untargeted ) ) == 0 );
        check( golden_wire( "ludicrous_state_untargeted", buffer, ws.GetBytesProcessed() ) );

        LudicrousState out;
        out.target_id = serialize::uint128_t( 0xDEAD ); // dirty — the read must zero it
        serialize::ReadStream rs( buffer, ws.GetBytesProcessed() );
        check( ReadLudicrousState( rs, out ) );
        check( !out.has_target );
        check( out.target_id == serialize::uint128_t( 0 ) );
    }

    // ---- hostile reads REJECT, never clamp (STANDARD.md, SPEC §5) ----
    {
        // fixed: angle's 25 offset bits start at bit 2; all-ones = 33554431,
        // above the raw range 360 * 2^16 = 23592960
        uint8_t hostile[sizeof( expected_ludicrous_state )];
        std::memcpy( hostile, expected_ludicrous_state, sizeof( hostile ) );
        set_bits( hostile, 2, 25 );
        LudicrousState out;
        serialize::ReadStream rs( hostile, sizeof( hostile ) );
        check( !ReadLudicrousState( rs, out ) );
    }
    {
        // int128: energy's 34 offset bits start at bit 286 (2+156+128);
        // all-ones = 2^34 - 1 = 17179869183, above the range 10^10
        uint8_t hostile[sizeof( expected_ludicrous_state )];
        std::memcpy( hostile, expected_ludicrous_state, sizeof( hostile ) );
        set_bits( hostile, 286, 34 );
        LudicrousState out;
        serialize::ReadStream rs( hostile, sizeof( hostile ) );
        check( !ReadLudicrousState( rs, out ) );
    }
    {
        // truncation: running out of input mid-read is a read failure (SPEC §5)
        LudicrousState out;
        serialize::ReadStream rs( buffer, 4 );
        check( !ReadLudicrousState( rs, out ) );
    }

    // ---- the message dispatch surface over the new unit ----
    {
        Message m;
        check( m.type == MessageType::None );
        m.type = MessageType::LudicrousState;
        m.ludicrous_state = make_state();

        serialize::WriteStream ws( buffer, sizeof( buffer ) );
        check( WriteMessage( ws, m ) );
        ws.Flush();

        Message out;
        serialize::ReadStream rs( buffer, ws.GetBytesProcessed() );
        check( ReadMessage( rs, out ) );
        check( GetMessageType( out ) == MessageType::LudicrousState );
        check( out.ludicrous_state.wide.flux == m.ludicrous_state.wide.flux );
        check( out.ludicrous_state.probe.angle == 2981888 );
    }

    printf( "OK\n" );
    return 0;
}
