static ludicrous::LudicrousState make_state()
{
    using namespace ludicrous;
    LudicrousState in;
    in.mode = DriveMode::Ludicrous;
    in.probe.angle = 2981888;                                   // +45.5 * 2^16
    in.probe.position = -809119744ll;                           // -12346.1875 * 2^16
    in.probe.reach = serialize::int128_t( 65536000000ll - 1 );  // raw_max - 1
    in.probe.ticks = 777777;
    in.probe.samples[0] = -524288;                              // raw_min
    in.probe.samples[1] = 524288;                               // raw_max
    in.wide.entity_id = ( serialize::uint128_t( 0x0123456789ABCDEFull ) << 64 )
                      | serialize::uint128_t( 0xFEDCBA9876543210ull );
    in.wide.energy = serialize::int128_t( 4999999999ll );
    in.wide.flux = ( serialize::int128_t( 1 ) << 99 ) + serialize::int128_t( 7 );
    // wide.bias and wide.seed stay at their SPECIFIED DEFAULTS (-250 and
    // 2^65) — construction installs them, and they ride the wire as written
    in.keys_count = 2;
    in.keys[0] = serialize::uint128_t( 1 );
    in.keys[1] = serialize::uint128_t( 1 ) << 127;
    in.has_target = true;
    in.target_id = serialize::uint128_t( 42 );
    return in;
}

int main()
{
    using namespace ludicrous;

    // worst-case bounds, hand-derived (SPEC §6.1 item 4):
    //   FixedProbe    25 + 32 + 37 + 20 + 2*21               = 156
    //   WideProbe     128 + 34 + 102 + 11 + 128              = 403
    //   LudicrousState 2 + 156 + 403 + (3 + 4*128) + 1 + 128 = 1205
    static_assert(FixedProbeMaxBits == 156, "FixedProbe worst case");
    static_assert(WideProbeMaxBits == 403, "WideProbe worst case");
    static_assert(LudicrousStateMaxBits == 1205, "LudicrousState worst case");
    static_assert(ProtocolId != 0, "the unit has a protocol id");

    // zero initialization with specified defaults (SPEC §4.2), sentinel-zero
    // composition: a fresh state starts at DriveMode::None — the null rides
    // in-band — and the two defaulted 128-bit fields construct to their
    // declared values, one of which no int64 literal can spell
    {
        LudicrousState zero;
        check( zero.mode == DriveMode::None );
        check( zero.probe.reach == serialize::int128_t( 0 ) );
        check( zero.wide.entity_id == serialize::uint128_t( 0 ) );
        check( zero.wide.bias == serialize::int128_t( -250 ) );
        check( zero.wide.seed == serialize::uint128_t( 1 ) << 65 );
        check( zero.keys_count == 0 );
        check( zero.target_id == serialize::uint128_t( 0 ) );
    }

    alignas( 8 ) uint8_t buffer[256 + 8];  // + 8: read buffer allocations extend 8 bytes past the data (the reader loads 64-bit windows)

    // ---- the taken-branch wire: generated bytes == STANDARD.md-derived ----
    {
        LudicrousState in = make_state();
        serialize::WriteStream ws( buffer, sizeof( buffer ) );
        check( WriteLudicrousState( ws, in ) );
        ws.Flush();
        check( ws.GetBytesProcessed() == (int) sizeof( expected_ludicrous_state ) );
        check( std::memcmp( buffer, expected_ludicrous_state, sizeof( expected_ludicrous_state ) ) == 0 );
        check( golden_wire( "ludicrous_state", buffer, ws.GetBytesProcessed(), ws.GetBitsProcessed() ) );

        LudicrousState out;
        serialize::ReadStream rs( buffer, ws.GetBytesProcessed() );
        check( ReadLudicrousState( rs, out ) );
        check( out.mode == DriveMode::Ludicrous );
        check( out.probe.angle == in.probe.angle );
        check( out.probe.position == in.probe.position );
        check( out.probe.reach == in.probe.reach );
        check( out.probe.ticks == in.probe.ticks );
        check( out.probe.samples[0] == in.probe.samples[0] );
        check( out.probe.samples[1] == in.probe.samples[1] );
        check( out.wide.entity_id == in.wide.entity_id );
        check( out.wide.energy == in.wide.energy );
        check( out.wide.flux == in.wide.flux );
        check( out.wide.bias == serialize::int128_t( -250 ) );
        check( out.wide.seed == serialize::uint128_t( 1 ) << 65 );
        check( out.keys_count == 2 );
        check( out.keys[0] == in.keys[0] );
        check( out.keys[1] == in.keys[1] );
        check( out.has_target && out.target_id == serialize::uint128_t( 42 ) );
    }

    // ---- the untaken branch: identical prefix, and the 128-bit field under
    // it reads back ZERO into a dirty object (SPEC §5) ----
    {
        LudicrousState in = make_state();
        in.has_target = false;
        serialize::WriteStream ws( buffer, sizeof( buffer ) );
        check( WriteLudicrousState( ws, in ) );
        ws.Flush();
        check( ws.GetBytesProcessed() == (int) sizeof( expected_ludicrous_state_untargeted ) );
        check( std::memcmp( buffer, expected_ludicrous_state_untargeted, sizeof( expected_ludicrous_state_untargeted ) ) == 0 );
        check( golden_wire( "ludicrous_state_untargeted", buffer, ws.GetBytesProcessed(), ws.GetBitsProcessed() ) );

        LudicrousState out;
        out.target_id = serialize::uint128_t( 0xDEAD ); // dirty — the read must zero it
        serialize::ReadStream rs( buffer, ws.GetBytesProcessed() );
        check( ReadLudicrousState( rs, out ) );
        check( !out.has_target );
        check( out.target_id == serialize::uint128_t( 0 ) );
    }

    // ---- hostile reads REJECT, never clamp (STANDARD.md, SPEC §5) ----
    {
        // fixed: angle's 25 offset bits start at bit 2; all-ones = 33554431,
        // above the raw range 360 * 2^16 = 23592960
        uint8_t hostile[sizeof( expected_ludicrous_state ) + 8];  // + 8: read buffer allocations extend 8 bytes past the data
        std::memcpy( hostile, expected_ludicrous_state, sizeof( expected_ludicrous_state ) );
        set_bits( hostile, 2, 25 );
        LudicrousState out;
        serialize::ReadStream rs( hostile, sizeof( expected_ludicrous_state ) );
        check( !ReadLudicrousState( rs, out ) );
    }
    {
        // int128: energy's 34 offset bits start at bit 286 (2+156+128);
        // all-ones = 2^34 - 1 = 17179869183, above the range 10^10
        uint8_t hostile[sizeof( expected_ludicrous_state ) + 8];  // + 8: read buffer allocations extend 8 bytes past the data
        std::memcpy( hostile, expected_ludicrous_state, sizeof( expected_ludicrous_state ) );
        set_bits( hostile, 286, 34 );
        LudicrousState out;
        serialize::ReadStream rs( hostile, sizeof( expected_ludicrous_state ) );
        check( !ReadLudicrousState( rs, out ) );
    }
    {
        // truncation: running out of input mid-read is a read failure (SPEC §5)
        LudicrousState out;
        serialize::ReadStream rs( buffer, 4 );
        check( !ReadLudicrousState( rs, out ) );
    }

    // ---- DegenerateProbe: min == max costs ZERO bits (SPEC §4.6) ----
    // Three degenerate shapes ride in front of a tail byte: the whole wire
    // is that one byte, derived from the wire law by hand below. A port that
    // emits ANY bits for a degenerate range — the audit found F bits on the
    // wide path, an abort and a panic behind the old rejection — shifts the
    // tail and fails this compare and the golden.
    {
        static_assert( DegenerateProbeMaxBits == 8, "three degenerate fields cost zero bits" );

        DegenerateProbe in;
        in.locked_fixed = -196608;              // -3 * 2^16, the ONE legal raw
        in.locked_int = 7;
        in.locked_wide = -12345678901234ll;
        in.tail = 0xA5;

        uint8_t expected_probe[1] = { 0xA5 };   // the tail alone — nothing else reaches the wire
        serialize::WriteStream ws( buffer, sizeof( buffer ) );
        check( WriteDegenerateProbe( ws, in ) );
        ws.Flush();
        check( ws.GetBytesProcessed() == 1 );
        check( std::memcmp( buffer, expected_probe, 1 ) == 0 );
        check( golden_wire( "degenerate_probe", buffer, ws.GetBytesProcessed(), ws.GetBitsProcessed() ) );

        DegenerateProbe out; // members default to zero; memset is ill-formed on a non-trivial type (int128_t)
        serialize::ReadStream rs( buffer, ws.GetBytesProcessed() );
        check( ReadDegenerateProbe( rs, out ) );
        check( out.locked_fixed == -196608 );   // materialized from the range alone
        check( out.locked_int == 7 );
        check( out.locked_wide == -12345678901234ll );
        check( out.tail == 0xA5 );
    }

    // ---- UnsignedProbe: ufixed(I, F), the unsigned sibling (SPEC §4.3;
    //) ----
    // The width ladder mirrors FixedProbe's and adds the unsigned-only
    // hazard: span's raw values fill uint64's HIGH HALF (above 2^63) — any
    // sign-extending route corrupts them, and this byte-compare is the gate.
    // Derivation, in wire order (offset = raw − (min << F) in
    // bitlen(max − min) + F bits):
    //   angle    ufixed(16,16)  [0,360]    = 45.5 units  ->  2981888 in 25 bits
    //   span     ufixed(48,16)  [0,2^48-1] = raw_max     ->  0xFFFFFFFFFFFF0000 in 64 bits
    //   reach    ufixed(112,16) [0,2e6]    = raw_max - 1 ->  131071999999 in 37 bits
    //   ticks    ufixed(32,0)   [0,1e6]    = 777777      ->  777777 in 20 bits
    //   samples0 ufixed(16,16)  [0,16]     = raw_min     ->  0 in 21 bits
    //   samples1 ufixed(16,16)  [0,16]     = raw_max     ->  1048576 in 21 bits
    //   locked   ufixed(16,16)  [3,3]      = 3 * 2^16    ->  ZERO bits (degenerate)
    //   tail     uint8                     = 0xA5        ->  8 bits
    // Totals: 196 bits = 25 bytes.
    {
        static_assert( UnsignedProbeMaxBits == 196, "UnsignedProbe worst case" );

        UnsignedProbe in;
        in.angle = 2981888;                                 // +45.5 * 2^16
        in.span = 0xFFFFFFFFFFFF0000ull;                    // raw_max — the uint64 HIGH HALF
        in.reach = serialize::uint128_t( 131071999999ull ); // raw_max - 1
        in.ticks = 777777;
        in.samples[0] = 0;                                  // raw_min
        in.samples[1] = 1048576;                            // raw_max
        in.locked = 196608;                                 // 3 * 2^16, the ONE legal raw
        in.tail = 0xA5;

        uint8_t expected_unsigned[25] = { 0 };
        {
            int pos = 0;
            put_bits( expected_unsigned, pos, 25, 2981888ull ); pos += 25;
            put_bits( expected_unsigned, pos, 64, 0xFFFFFFFFFFFF0000ull ); pos += 64;
            put_bits( expected_unsigned, pos, 37, 131071999999ull ); pos += 37;
            put_bits( expected_unsigned, pos, 20, 777777ull ); pos += 20;
            put_bits( expected_unsigned, pos, 21, 0ull ); pos += 21;
            put_bits( expected_unsigned, pos, 21, 1048576ull ); pos += 21;
            // locked: a degenerate range reaches no wire (SPEC §4.6)
            put_bits( expected_unsigned, pos, 8, 0xA5ull ); pos += 8;
        }
        serialize::WriteStream ws( buffer, sizeof( buffer ) );
        check( WriteUnsignedProbe( ws, in ) );
        ws.Flush();
        check( ws.GetBytesProcessed() == (int) sizeof( expected_unsigned ) );
        check( std::memcmp( buffer, expected_unsigned, sizeof( expected_unsigned ) ) == 0 );
        check( golden_wire( "unsigned_probe", buffer, ws.GetBytesProcessed(), ws.GetBitsProcessed() ) );

        UnsignedProbe out;
        serialize::ReadStream rs( buffer, ws.GetBytesProcessed() );
        check( ReadUnsignedProbe( rs, out ) );
        check( out.angle == 2981888 );
        check( out.span == 0xFFFFFFFFFFFF0000ull );         // the high half round-trips bit-exact
        check( out.reach == serialize::uint128_t( 131071999999ull ) );
        check( out.ticks == 777777 );
        check( out.samples[0] == 0 && out.samples[1] == 1048576 );
        check( out.locked == 196608 );                      // materialized from the range alone
        check( out.tail == 0xA5 );

        // hostile: angle's 25 offset bits all-ones = 33554431, above the raw
        // range 360 * 2^16 = 23592960 — reject, never clamp
        {
            uint8_t hostile[sizeof( expected_unsigned ) + 8];  // + 8: read buffer allocations extend 8 bytes past the data
            std::memcpy( hostile, expected_unsigned, sizeof( expected_unsigned ) );
            set_bits( hostile, 0, 25 );
            UnsignedProbe hOut;
            serialize::ReadStream hrs( hostile, sizeof( expected_unsigned ) );
            check( !ReadUnsignedProbe( hrs, hOut ) );
        }
        // hostile: span's 64 offset bits all-ones = 2^64 - 1, above the raw
        // range 0xFFFFFFFFFFFF0000 — the headroom is exactly the low 16
        // bits, and the reject must fire in the UNSIGNED domain (a signed
        // compare would call the smuggled value negative and wave it through)
        {
            uint8_t hostile[sizeof( expected_unsigned ) + 8];  // + 8: read buffer allocations extend 8 bytes past the data
            std::memcpy( hostile, expected_unsigned, sizeof( expected_unsigned ) );
            set_bits( hostile, 25, 64 );
            UnsignedProbe hOut;
            serialize::ReadStream hrs( hostile, sizeof( expected_unsigned ) );
            check( !ReadUnsignedProbe( hrs, hOut ) );
        }
    }

    printf( "OK\n" );
    return 0;
}
