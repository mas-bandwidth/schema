// The fixed-point + 128-bit corpus unit's test binary (examples128/ ->
// generated/cpp/ludicrous). Round-trips the new wire families through the
// classic serialize runtime's fixed-point surface and byte-compares against
// EXPECTED ARRAYS DERIVED INDEPENDENTLY FROM STANDARD.md — the derivation
// implements the wire law by hand (bit i of the stream lives in byte i/8 at
// bit position i%8; ranged values are value - min in bit-length-of-range
// bits; fixed is the raw scaled offset in bitlen(max - min) + F bits;
// uint128 is 128 raw bits low qword first), never by calling serialize. The
// golden .bin files under testdata/wire/ were written FROM that derivation,
// so the C++ run asserts generated bytes == derived bytes both in-source and
// on disk. A mismatch is stop-the-line (SPEC §3.1, §7.2 gate 7).

#include <cstdio>
#include <cstdlib>
#include <cstring>

#include "LudicrousWire.h"
#include "LudicrousTable.h" // every type here is table-tainted (int128/fixed); the header must still compile

#define check( condition )                                                    \
    do                                                                        \
    {                                                                         \
        if ( !( condition ) )                                                 \
        {                                                                     \
            printf( "FAILED: %s (%s:%d)\n", #condition, __FILE__, __LINE__ ); \
            return 1;                                                         \
        }                                                                     \
    } while ( 0 )

// Golden wire bytes (SPEC §7.2 gate 7) — same contract as test/main.cpp.
static bool golden_wire( const char * name, const uint8_t * data, int64_t bytes )
{
    char path[256];
    snprintf( path, sizeof( path ), "testdata/wire/%s.bin", name );
    if ( std::getenv( "SCHEMA_UPDATE_WIRE_GOLDENS" ) )
    {
        FILE * f = fopen( path, "wb" );
        if ( !f )
        {
            printf( "cannot write %s\n", path );
            return false;
        }
        fwrite( data, 1, (size_t) bytes, f );
        fclose( f );
        return true;
    }
    FILE * f = fopen( path, "rb" );
    if ( !f )
    {
        printf( "missing wire golden %s (run: make update-goldens)\n", path );
        return false;
    }
    static uint8_t expected[4096];
    size_t n = fread( expected, 1, sizeof( expected ), f );
    fclose( f );
    if ( (int64_t) n != bytes || std::memcmp( expected, data, (size_t) bytes ) != 0 )
    {
        printf( "WIRE GOLDEN MISMATCH: %s (%lld golden vs %lld actual bytes) — stop-the-line (SPEC §3.1, §7.2 gate 7)\n",
                name, (long long) n, (long long) bytes );
        return false;
    }
    return true;
}

// set_bits forces bits [pos, pos + n) of the stream image to 1 — the hostile
// reader's tool: smuggling an offset into the range's bit headroom, which a
// read must REJECT, never clamp (STANDARD.md).
static void set_bits( uint8_t * data, int pos, int n )
{
    for ( int i = pos; i < pos + n; i++ )
    {
        data[i / 8] = (uint8_t) ( data[i / 8] | ( 1 << ( i % 8 ) ) );
    }
}

