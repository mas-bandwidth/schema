#!/bin/sh
# make/goose-wirefuzz-build.sh — builds the Goose wire-fuzz leg for one unit
# (make/goose-fuzz.mk; test/conformance/goose/wirefuzz.goose says why one
# executable per unit).
#
#   goose-wirefuzz-build.sh <goose> <generated unit dir> <out dir>
#
# Copies the unit's generated modules into <out dir>, writes the glue module
# naming the unit's registry, puts the leg and its C sidecar beside them, and
# builds <out dir>/wirefuzz with `goose build -O2` (the machine's C compiler).
set -u
goose=$1
src=$2
out=$3
rm -rf "$out" && mkdir -p "$out" || exit 1
cp "$src"/*.goose "$out"/ || exit 1
ns=$(sed -n 's/^namespace \(.*\);$/\1/p' "$out"/*Table.goose | head -1)
if [ -z "$ns" ]; then
	echo "goose-wirefuzz-build: $src has no table module" >&2
	exit 1
fi
{
	echo "// generated by make/goose-wirefuzz-build.sh: the unit under the fuzzer"
	for f in "$out"/*.goose; do
		echo "import .$(basename "$f" .goose);"
	done
	echo "fn conformance_unit() -> schema_rt::LoadUnit { return $ns::TableUnit; }"
} >"$out/conformance_unit.goose"
cp test/conformance/goose/wirefuzz.goose test/conformance/goose/wirefuzz.build \
	test/conformance/goose/wirefuzz_io.c "$out"/ || exit 1
(cd "$out" && "$goose" build -O2 wirefuzz.goose -o wirefuzz) >"$out/build.log" 2>&1 || {
	cat "$out/build.log" >&2
	exit 1
}
