// Command schema-c-nightly-fuzz-gen builds the C nightly fuzzing harness.
//
// It generates the C table code for each schema named in the corpus list (the
// same corpus the Makefile's table targets read) and writes one libFuzzer/
// AFL++ driver per schema and reader kind. The driver is produced from the
// generated header's own declarations, so a new table shape needs no edit
// here: the signature is read, not guessed.
package main

import (
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

var (
	loadGraph = regexp.MustCompile(`(?m)^static SCHEMA_UNUSED const ([A-Za-z_][A-Za-z0-9_]*) \* ([a-z0-9_]+)_load\(uint8_t \* region, int64_t region_bytes, const uint8_t \* wire, int64_t wire_bytes, TableReport \* report\)$`)
	loadValue = regexp.MustCompile(`(?m)^static SCHEMA_UNUSED int ([a-z0-9_]+)_load\( ([A-Za-z_][A-Za-z0-9_]*) \* value, const uint8_t \* buffer, int64_t bytes, TableReport \* report \)$`)
	fromJSON  = regexp.MustCompile(`(?m)^static SCHEMA_UNUSED int ([a-z0-9_]+)_from_json\( ([A-Za-z_][A-Za-z0-9_]*) \* (\w+), const char \* text, int64_t bytes, TableReport \* report \)`)
	builderInit = regexp.MustCompile(`(?m)^static SCHEMA_UNUSED int ([a-z0-9_]+)_builder_init\(`)
)

type table struct {
	name   string
	typ    string
	graph  bool
	builder bool
}

func main() {
	bin := flag.String("schema-bin", "bin/schema", "the schema compiler")
	out := flag.String("out", "build/schema-c-nightly-fuzz", "output root")
	corpus := flag.String("corpus", "make/schema-c-nightly-fuzz.corpus", "corpus list")
	flag.Parse()

	paths, err := corpusPaths(*corpus)
	if err != nil {
		fail(err)
	}
	if len(paths) == 0 {
		fail(fmt.Errorf("%s names no schema", *corpus))
	}
	for _, schema := range paths {
		if err := one(*bin, *out, schema); err != nil {
			fail(err)
		}
	}
	fmt.Printf("schema-c-nightly-fuzz-gen: %d schema units\n", len(paths))
}

func corpusPaths(path string) ([]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		out = append(out, line)
	}
	return out, nil
}

func slug(path string) string {
	s := strings.TrimSuffix(path, ".schema")
	s = strings.NewReplacer("/", "_", ".", "_").Replace(s)
	return s
}

func one(bin, out, entry string) error {
	dir := filepath.Join(out, slug(entry))
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	inputs := []string{entry}
	if info, err := os.Stat(entry); err == nil && info.IsDir() {
		inputs = nil
		files, err := filepath.Glob(filepath.Join(entry, "*.schema"))
		if err != nil {
			return err
		}
		inputs = files
	}
	if len(inputs) == 0 {
		return fmt.Errorf("%s: no schema", entry)
	}
	args := append([]string{"generate", "--lang", "c", "--out", dir}, inputs...)
	cmd := exec.Command(bin, args...)
	cmd.Stdout = os.Stderr
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("generate %s: %w", entry, err)
	}
	headers, err := filepath.Glob(filepath.Join(dir, "*Table.h"))
	if err != nil {
		return err
	}
	if len(headers) == 0 {
		return fmt.Errorf("%s: no Table.h emitted", entry)
	}
	for _, path := range headers {
		header := filepath.Base(path)
		base := strings.TrimSuffix(header, "Table.h")
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		tables := scan(string(data))
		if len(tables) == 0 {
			continue
		}
		for kind, name := range []string{"load", "strict", "json"} {
			driver := filepath.Join(dir, "fuzz_"+base+"_"+name+".c")
			if err := os.WriteFile(driver, []byte(render(header, tables, kind)), 0o644); err != nil {
				return err
			}
		}
	}
	return nil
}

func scan(header string) []table {
	byName := map[string]*table{}
	var order []string
	add := func(name string) *table {
		if t, ok := byName[name]; ok {
			return t
		}
		t := &table{name: name}
		byName[name] = t
		order = append(order, name)
		return t
	}
	for _, m := range loadGraph.FindAllStringSubmatch(header, -1) {
		t := add(m[2])
		t.typ, t.graph = m[1], true
	}
	for _, m := range loadValue.FindAllStringSubmatch(header, -1) {
		t := add(m[1])
		t.typ, t.graph = m[2], false
	}
	for _, m := range fromJSON.FindAllStringSubmatch(header, -1) {
		t := add(m[1])
		t.typ = m[2]
		t.builder = strings.HasSuffix(m[2], "Builder")
	}
	for _, m := range builderInit.FindAllStringSubmatch(header, -1) {
		if t, ok := byName[m[1]]; ok {
			t.builder = true
		}
	}
	result := make([]table, 0, len(order))
	for _, name := range order {
		result = append(result, *byName[name])
	}
	return result
}

func render(header string, tables []table, kind int) string {
	var b strings.Builder
	fmt.Fprintf(&b, `/* Code generated by schema-c-nightly-fuzz-gen. DO NOT EDIT.
   The C nightly fuzzer's generated driver. */
#define _POSIX_C_SOURCE 200112L
#include "%s"
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#define SCHEMA_C_FUZZ_KIND %d

static uint8_t * schema_c_fuzz_padded( const uint8_t * data, size_t size )
{
    uint8_t * buffer = (uint8_t *) malloc( size + 8 );
    if ( buffer == NULL ) { return NULL; }
    if ( size != 0 ) { memcpy( buffer, data, size ); }
    memset( buffer + size, 0, 8 );
    return buffer;
}

int LLVMFuzzerTestOneInput( const uint8_t * data, size_t size )
{
    uint8_t * buffer = schema_c_fuzz_padded( data, size );
    TableReport report;
    if ( buffer == NULL ) { return 0; }
    memset( &report, 0, sizeof( report ) );
`, header, kind)

	for i, t := range tables {
		switch kind {
		case 0:
			if t.graph {
				fmt.Fprintf(&b, `    { int64_t need = %s_load_measure( buffer, (int64_t) size ); int64_t bytes = need < 0 ? (int64_t) size * 8 + 256 : need; void * region = NULL;
      if ( bytes > 0 && bytes < (int64_t) (1u<<28) && posix_memalign( &region, 64, (size_t) bytes ) == 0 ) {
          const %s * value = %s_load( (uint8_t *) region, bytes, buffer, (int64_t) size, &report ); (void) value;
          free( region );
      } }
`, t.name, t.typ, t.name)
			} else {
				fmt.Fprintf(&b, `    { %s value_%d; memset( &value_%d, 0, sizeof( value_%d ) ); %s_reset( &value_%d ); %s_load( &value_%d, buffer, (int64_t) size, &report ); }
`, t.typ, i, i, i, t.name, i, t.name, i)
			}
		case 1:
			if t.graph {
				fmt.Fprintf(&b, `    { int64_t attribution = 0; TableRefuseReason reason; memset( &reason, 0, sizeof( reason ) );
      (void) %s_load_measure_ex( buffer, (int64_t) size, &attribution, &reason );
      attribution = %s_load_measure( buffer, (int64_t) size );
      if ( attribution >= 0 && attribution < (int64_t) (1u<<28) ) {
          void * region = NULL;
          if ( posix_memalign( &region, 64, (size_t) attribution + 8 ) == 0 ) {
              const %s * value = %s_load( (uint8_t *) region, attribution, buffer, (int64_t) size, &report ); (void) value;
              free( region );
          }
      } }
`, t.name, t.name, t.typ, t.name)
			} else {
				fmt.Fprintf(&b, `    { %s value_%d; memset( &value_%d, 0, sizeof( value_%d ) ); %s_reset( &value_%d ); %s_load( &value_%d, buffer, (int64_t) size, &report ); }
`, t.typ, i, i, i, t.name, i, t.name, i)
			}
		case 2:
			if t.builder {
				fmt.Fprintf(&b, `    { %s builder_%d; memset( &builder_%d, 0, sizeof( builder_%d ) ); if ( %s_builder_init( &builder_%d ) ) { %s_from_json( &builder_%d, (const char *) buffer, (int64_t) size, &report ); %s_builder_shutdown( &builder_%d ); } }
`, t.typ, i, i, i, t.name, i, t.name, i, t.name, i)
			} else {
				fmt.Fprintf(&b, `    { %s value_%d; memset( &value_%d, 0, sizeof( value_%d ) ); %s_reset( &value_%d ); %s_from_json( &value_%d, (const char *) buffer, (int64_t) size, &report ); }
`, t.typ, i, i, i, t.name, i, t.name, i)
			}
		}
	}
	b.WriteString("    free( buffer );\n    return 0;\n}\n")
	return b.String()
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "schema-c-nightly-fuzz-gen:", err)
	os.Exit(1)
}
