#!/bin/sh
set -u
goose=$1
src=$2
out=$3
rm -rf "$out" && mkdir -p "$out" || exit 1
cp "$src"/*.goose "$out"/ || exit 1
ns=$(sed -n 's/^namespace \(.*\);$/\1/p' "$out"/*Table.goose | head -1)
if [ -z "$ns" ]; then
	echo "goose-messagefuzz-build: $src has no table module" >&2
	exit 1
fi
{
	echo "// generated by make/goose-messagefuzz-build.sh"
	for f in "$out"/*.goose; do
		echo "import .$(basename "$f" .goose);"
	done
	echo "fn conformance_unit() -> schema_rt::LoadUnit { return $ns::TableUnit; }"
	msg_roots=$(cat "$out"/*Table.goose | sed -n 's/^fn \([A-Za-z0-9_]*\)LoadMessages(.*/\1/p')
	echo "fn conformance_message_root(root: const u8[:]) -> bool {"
	for r in $msg_roots; do echo "    if root == \"$r\" { return true; }"; done
	echo "    return false;"
	echo "}"
	echo "fn conformance_message_framed_fuzz(root: const u8[:], ann: const u8[:], has_ann: bool, batch: const u8[:], out: u8[>..]&, rep: schema_rt::MsgReport&) -> i64 {"
	for r in $msg_roots; do
		echo "    if root == \"$r\" {"
		echo "        var voc = schema_rt::MsgVocabulary { .. };"
		echo "        if has_ann {"
		echo "            if !schema_rt::announce_read(voc, ann, rep) || rep.damaged || rep.reason != 0 { return -2; }"
		echo "        } else {"
		echo "            var arep = schema_rt::MsgReport { .. };"
		echo "            if !schema_rt::announce_read(voc, $ns::${r}Announce, arep) { return -2; }"
		echo "        }"
		echo "        var values: $ns::$r[256] = [$ns::$r { .. }; 256];"
		echo "        let n = $ns::${r}LoadMessages(values[0..256], voc, batch, rep);"
		echo "        if n < 1 || rep.damaged || rep.reason != 0 { return -2; }"
		echo "        var srep = schema_rt::MsgReport { .. };"
		echo "        let sz = $ns::${r}SaveMessages(values[0..n], out, srep);"
		echo "        if sz < 0 { return -1; }"
		echo "        return sz;"
		echo "    }"
	done
	echo "    return -2;"
	echo "}"
} >"$out/conformance_unit.goose"
cp test/conformance/goose/messagefuzz.goose "$out/wirefuzz.goose" || exit 1
cp test/conformance/goose/wirefuzz.build test/conformance/goose/wirefuzz_io.c "$out"/ || exit 1
(cd "$out" && "$goose" build -O2 wirefuzz.goose -o wirefuzz) >"$out/build.log" 2>&1 || {
	cat "$out/build.log" >&2
	exit 1
}
