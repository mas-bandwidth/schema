// The CLI's WRITE POLICY, proven from outside the binary (issue #473).
//
// `schema fmt` is the only command that writes a schema file. Everything else
// reads the unit as it sits on disk and leaves it byte for byte alone, so a
// read-only checkout, a sandboxed build, a concurrent generation and an editor
// integration all work, and a command that answers a question never edits the
// source it answered about.
//
// Three legs, because the rule has three halves a reader would otherwise have
// to take on trust:
//
// TestOnlyFmtWritesTheSchemaFile runs the reading commands over a deliberately
// unformatted unit and watches the bytes and the mtime; then it runs `fmt` on
// the same file and watches it change, which is also what proves the fixture
// was unformatted in the first place.
//
// TestUnformattedAndFormattedUnitsAgree is the equivalence the removed
// in-place rewrite used to guarantee by force: check, id, projection and
// generate over an unformatted unit produce exactly what the same commands
// produce over its formatted twin, output for output and generated byte for
// generated byte, across every target.
//
// TestReadOnlyTreeRunsEveryReadingCommand is the reported defect: the unit's
// directory and file are made read-only and every reading command must still
// exit 0 and leave the file untouched. Restore the in-place rewrite and this
// one goes red with the compiler's own "permission denied".
package main

import (
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
	"testing"
	"time"
)

// unformattedUnit is a unit no formatter would leave alone: doubled spaces
// after `package`, two-space and seven-space indents, padded qualification
// columns and an unaligned const run. It parses, and every construct in it is
// one the C, C++, C#, Dart, Elixir, Go, Java, JavaScript and Rust backends all
// emit, so the generate leg can run the whole matrix over it.
const unformattedUnit = `package  probe

const  MaxHealth   =  100
const MaxArmor = 8

enum Team { red, blue, spectator }

type Thing
{
  health   int32   |   min = 0, max = MaxHealth
      name string(32)
   armor [4]uint8 | min = 0, max = MaxArmor
  team Team
}
`

// the commands that only READ. Each is run as `schema <verb> <dir>`; generate
// takes its output directory from the caller, because that is the one place it
// is allowed to write.
var readingCommands = [][]string{
	{"check"},
	{"check", "--verbose"},
	{"id"},
	{"projection"},
	{"build-version"},
}

// every registered target, so the generate leg measures the whole matrix
// rather than the two backends that happen to be convenient.
var targets = []string{"c", "cpp", "cs", "dart", "elixir", "go", "java", "js", "rust"}

// buildCLI builds this package into the test's temporary directory and returns
// the binary's path. The tests drive the CLI as a user does — a process, an
// argument list, an exit code — because the policy under test is the CLI's,
// not the library's.
func buildCLI(t *testing.T) string {
	t.Helper()
	bin := filepath.Join(t.TempDir(), "schema")
	cmd := exec.Command("go", "build", "-o", bin, ".")
	cmd.Dir = "."
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go build: %v\n%s", err, out)
	}
	return bin
}

// run executes the CLI and returns its combined output, failing on a nonzero
// exit with the output the user would have seen.
func run(t *testing.T, bin string, args ...string) string {
	t.Helper()
	out, err := exec.Command(bin, args...).CombinedOutput()
	if err != nil {
		t.Fatalf("schema %s: %v\n%s", strings.Join(args, " "), err, out)
	}
	return string(out)
}

// writeUnit puts the unformatted fixture in its own directory and returns the
// directory and the file inside it.
func writeUnit(t *testing.T, dir string) (string, string) {
	t.Helper()
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	// one basename across both twins: generated files are named by it, so the
	// emitted trees are comparable file for file.
	path := filepath.Join(dir, "Probe.schema")
	if err := os.WriteFile(path, []byte(unformattedUnit), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir, path
}

// fileState is the pair a caller compares before and after: the bytes, and the
// modification time a build system reads.
type fileState struct {
	data []byte
	mod  time.Time
}

func stat(t *testing.T, path string) fileState {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	return fileState{data: data, mod: info.ModTime()}
}

func (s fileState) unchanged(t *testing.T, path, what string) {
	t.Helper()
	now := stat(t, path)
	if string(now.data) != string(s.data) {
		t.Errorf("%s rewrote %s\nbefore:\n%s\nafter:\n%s", what, path, s.data, now.data)
	}
	if !now.mod.Equal(s.mod) {
		t.Errorf("%s moved the mtime of %s: %v -> %v", what, path, s.mod, now.mod)
	}
}

func TestOnlyFmtWritesTheSchemaFile(t *testing.T) {
	bin := buildCLI(t)
	work := t.TempDir()
	dir, path := writeUnit(t, filepath.Join(work, "unit"))

	before := stat(t, path)
	for _, verb := range readingCommands {
		args := append(append([]string{}, verb...), dir)
		run(t, bin, args...)
		before.unchanged(t, path, "schema "+strings.Join(verb, " "))
	}
	for _, target := range targets {
		out := filepath.Join(work, "generated", target)
		run(t, bin, "generate", "--lang", target, "--out", out, dir)
		before.unchanged(t, path, "schema generate --lang "+target)
	}

	// fmt is the writer, and this is also the fixture's own gate: a fixture
	// already in canonical form would make every assertion above vacuous.
	run(t, bin, "fmt", dir)
	after := stat(t, path)
	if string(after.data) == string(before.data) {
		t.Fatal("fmt left the fixture alone: the fixture is already canonical and the assertions above prove nothing")
	}
	// and fmt settles: a second run over a canonical tree writes nothing.
	settled := stat(t, path)
	run(t, bin, "fmt", dir)
	settled.unchanged(t, path, "schema fmt over an already canonical file")
}

func TestUnformattedAndFormattedUnitsAgree(t *testing.T) {
	bin := buildCLI(t)
	work := t.TempDir()
	rawDir, rawPath := writeUnit(t, filepath.Join(work, "raw"))
	canonDir, canonPath := writeUnit(t, filepath.Join(work, "canon"))
	run(t, bin, "fmt", canonDir)

	raw := stat(t, rawPath)
	canon := stat(t, canonPath)
	if string(raw.data) == string(canon.data) {
		t.Fatal("the twins are byte-identical: nothing here is being compared")
	}

	for _, verb := range readingCommands {
		want := run(t, bin, append(append([]string{}, verb...), canonDir)...)
		got := run(t, bin, append(append([]string{}, verb...), rawDir)...)
		if got != want {
			t.Errorf("schema %s diverged between the twins\nformatted:   %q\nunformatted: %q",
				strings.Join(verb, " "), want, got)
		}
	}

	for _, target := range targets {
		wantDir := filepath.Join(work, "want", target)
		gotDir := filepath.Join(work, "got", target)
		run(t, bin, "generate", "--lang", target, "--out", wantDir, canonDir)
		run(t, bin, "generate", "--lang", target, "--out", gotDir, rawDir)
		compareTrees(t, target, wantDir, gotDir)
	}

	// the loads left both twins as they were: the unformatted one is still
	// unformatted, and the formatted one is still formatted.
	raw.unchanged(t, rawPath, "the unformatted twin's commands")
	canon.unchanged(t, canonPath, "the formatted twin's commands")
}

// compareTrees fails unless two generated directories hold the same file names
// and the same bytes under each of them.
func compareTrees(t *testing.T, target, wantDir, gotDir string) {
	t.Helper()
	want := treeNames(t, wantDir)
	got := treeNames(t, gotDir)
	if strings.Join(want, " ") != strings.Join(got, " ") {
		t.Errorf("%s: different files emitted\nformatted:   %v\nunformatted: %v", target, want, got)
		return
	}
	for _, name := range want {
		a, err := os.ReadFile(filepath.Join(wantDir, name))
		if err != nil {
			t.Fatal(err)
		}
		b, err := os.ReadFile(filepath.Join(gotDir, name))
		if err != nil {
			t.Fatal(err)
		}
		if string(a) != string(b) {
			t.Errorf("%s: %s differs between the formatted and unformatted twins", target, name)
		}
	}
}

func treeNames(t *testing.T, dir string) []string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		names = append(names, e.Name())
	}
	sort.Strings(names)
	return names
}

func TestReadOnlyTreeRunsEveryReadingCommand(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("root writes through a read-only directory, so the mode proves nothing")
	}
	bin := buildCLI(t)
	work := t.TempDir()
	dir, path := writeUnit(t, filepath.Join(work, "unit"))

	// the whole tree read-only, file and directory alike: a rewrite cannot
	// land, and neither can a write through a temporary and a rename.
	if err := os.Chmod(path, 0o444); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(dir, 0o555); err != nil {
		t.Fatal(err)
	}
	// t.TempDir's own cleanup needs the mode back.
	t.Cleanup(func() {
		_ = os.Chmod(dir, 0o755)
		_ = os.Chmod(path, 0o644)
	})

	before := stat(t, path)
	for _, verb := range readingCommands {
		args := append(append([]string{}, verb...), dir)
		run(t, bin, args...)
		before.unchanged(t, path, "schema "+strings.Join(verb, " "))
	}
	// generate writes, but only where --out points, and that is not the tree
	// it read.
	for _, target := range targets {
		out := filepath.Join(work, "generated", target)
		run(t, bin, "generate", "--lang", target, "--out", out, dir)
		before.unchanged(t, path, "schema generate --lang "+target)
	}
}
