// The reproductions of review finding F-014 against the volume the test runs
// on: through the real writer where the volume folds names, and through the
// command itself on any volume. The rules themselves are held against both
// kinds of volume, on any machine, in generatedspelling_test.go.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"sort"
	"testing"
)

func goFile(base, body string) string {
	return fmt.Sprintf("// Code generated by the schema compiler from %s.schema. DO NOT EDIT.\n%s\n", base, body)
}

// playerRun is what generate writes for a unit of one file, <base>.schema:
// files named after the base, each carrying the header that names it.
func playerRun(base, body string) map[string][]byte {
	files := map[string][]byte{}
	for _, suffix := range []string{"", "Table", "TableJSON", "View", "Block"} {
		files[base+suffix+".go"] = []byte(goFile(base, body))
	}
	files["demo_schema.go"] = []byte("// Code generated by the schema compiler for package demo. DO NOT EDIT.\n" + body + "\n")
	return files
}

func sortedNames(files map[string][]byte) []string {
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

func dirNames(t *testing.T, dir string) []string {
	t.Helper()
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, e := range entries {
		names = append(names, e.Name())
	}
	sort.Strings(names)
	return names
}

// The same two reproductions on the volume itself, through the real writer.
// Runs where the volume takes two spellings of a name for one entry, and is
// skipped, named, where it keeps them apart (there the tree above that does
// not fold is the case that applies, and the end-to-end test below runs it).
func TestRegenerationOnAVolumeThatFoldsNames(t *testing.T) {
	probe := t.TempDir()
	writeTestFile(t, filepath.Join(probe, "Probe.go"), "probe")
	if _, err := os.Lstat(filepath.Join(probe, "probe.go")); err != nil {
		t.Skipf("this volume keeps Probe.go and probe.go apart, so a write to one never lands on the other here: %v", err)
	}
	t.Run("source renamed in case", func(t *testing.T) {
		out := t.TempDir()
		if err := writeGenerated(out, playerRun("Player", "first run"), "go", true, "demo", []string{"Player"}, false); err != nil {
			t.Fatal(err)
		}
		writeTestFile(t, filepath.Join(out, "hand.go"), "package demo\n")
		second := playerRun("player", "second run")
		if err := writeGenerated(out, second, "go", true, "demo", []string{"player"}, false); err != nil {
			t.Fatal(err)
		}
		want := append(sortedNames(second), "hand.go")
		sort.Strings(want)
		if got := dirNames(t, out); !slices.Equal(got, want) {
			t.Fatalf("after one run the directory holds\n%v\nwant\n%v", got, want)
		}
		for name, data := range second {
			wantGenerated(t, filepath.Join(out, name), string(data))
		}
	})
	t.Run("output renamed in case", func(t *testing.T) {
		out := t.TempDir()
		run := playerRun("Demo", "first run")
		if err := writeGenerated(out, run, "go", true, "demo", []string{"Demo"}, false); err != nil {
			t.Fatal(err)
		}
		// a case-only rename, through a third name so the volume takes it
		if err := os.Rename(filepath.Join(out, "DemoView.go"), filepath.Join(out, "tmp.go")); err != nil {
			t.Fatal(err)
		}
		if err := os.Rename(filepath.Join(out, "tmp.go"), filepath.Join(out, "demoview.go")); err != nil {
			t.Fatal(err)
		}
		if err := writeGenerated(out, run, "go", true, "demo", []string{"Demo"}, false); err != nil {
			t.Fatal(err)
		}
		if got, want := dirNames(t, out), sortedNames(run); !slices.Equal(got, want) {
			t.Fatalf("after one run the directory holds\n%v\nwant\n%v", got, want)
		}
	})
}

func wantGenerated(t *testing.T, path, want string) {
	t.Helper()
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%s: %v", path, err)
	}
	if string(got) != want {
		t.Fatalf("%s holds %q, want %q", path, got, want)
	}
}

const playerUnit = "package demo\n\nfixed table Player {\n  level int32\n}\n"

// The command itself, end to end, on whatever volume the test runs on: the
// reviewer's reproduction. Generate Go from Player.schema, rename only the
// source to player.schema, regenerate into the same directory. The directory
// then holds exactly what a first generation from player.schema writes into
// an empty one: the same names under the same spelling, the same bytes.
func TestGenerateGoAfterACaseOnlySourceRename(t *testing.T) {
	bin := buildCLI(t)
	work := t.TempDir()
	unit := filepath.Join(work, "unit")
	writeTestFile(t, filepath.Join(unit, "Player.schema"), playerUnit)
	out := filepath.Join(work, "out")
	run(t, bin, "generate", "--lang", "go", "--out", out, unit)
	firstRun := dirNames(t, out)

	// the control: regenerating with the source name unchanged keeps every file
	run(t, bin, "generate", "--lang", "go", "--out", out, unit)
	if got := dirNames(t, out); !slices.Equal(got, firstRun) {
		t.Fatalf("regenerating an unchanged unit moved the directory from\n%v\nto\n%v", firstRun, got)
	}

	// a case-only rename, through a third name so every volume takes it
	if err := os.Rename(filepath.Join(unit, "Player.schema"), filepath.Join(unit, "tmp.schema")); err != nil {
		t.Fatal(err)
	}
	if err := os.Rename(filepath.Join(unit, "tmp.schema"), filepath.Join(unit, "player.schema")); err != nil {
		t.Fatal(err)
	}
	fresh := filepath.Join(work, "fresh")
	run(t, bin, "generate", "--lang", "go", "--out", fresh, unit)
	want := dirNames(t, fresh)
	if len(want) != len(firstRun) {
		t.Fatalf("the renamed unit generates %d files and the original %d", len(want), len(firstRun))
	}

	run(t, bin, "generate", "--lang", "go", "--out", out, unit)
	got := dirNames(t, out)
	if !slices.Equal(got, want) {
		t.Fatalf("after one regeneration the directory holds %d files\n%v\nwant the %d a first generation writes\n%v", len(got), got, len(want), want)
	}
	for _, name := range want {
		data, err := os.ReadFile(filepath.Join(fresh, name))
		if err != nil {
			t.Fatal(err)
		}
		wantGenerated(t, filepath.Join(out, name), string(data))
	}
}
