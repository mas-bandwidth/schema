# runtime-paths.sh — the §3.5 provenance mechanics, shared by bench/run.sh,
# bench/tools/pass-driver.sh and bench/tools/inline-verdict.sh. Sourced,
# never executed; callers cd to the repo root first, then call
# runtime_paths_init.
#
# The defect this exists to prevent (found 2026-08-15): bench/rust/Cargo.toml,
# bench/go/go.mod and bench/cs/schemabench.csproj hardcoded their runtime
# paths while run.sh recorded $SERIALIZE_RS / $SERIALIZE_GO / $SERIALIZE_CS
# in the preamble. A pass run with SERIALIZE_RS pointing at a fix branch
# recorded that branch's sha while measuring whatever ../serialize.rs was
# checked out at — a CSV lying about its own provenance. Two mechanics
# close it:
#
#   1. the env vars now REACH the builds. When a var points away from the
#      checked-in default, the leg builds through a materialized override —
#      generated cargo manifests, a go -modfile, an msbuild property — under
#      build/bench/runtime-override (git-ignored). Checked-in files are never
#      edited, so the working tree stays clean, and with no override the
#      build commands are byte-identical to the defaults.
#
#   2. verify_runtime asks each TOOLCHAIN what it will actually build
#      against (cargo pkgid, go list -m, msbuild -getItem:Compile — never
#      this script's own intent) and compares that to the env var. run.sh
#      refuses to emit rows on mismatch; the preamble marks every runtime
#      line [build-verified: <resolved path>] or says out loud that the
#      line is unproven.
#
# Rust needs TWO override manifests because generated/rust/Cargo.toml (which
# the Makefile writes) carries its own serialize path: if only the bench
# manifest moved, cargo would see two distinct serialize crates and the
# types would not unify. cargo pkgid doubles as the guard for exactly that —
# it errors on an ambiguous package name, which verify_runtime turns into a
# refusal.

# realpath for directories, portable (macOS bash 3.2 has no realpath -m)
rp_dir() { (cd "$1" 2>/dev/null && pwd -P); }

# cargo, whether or not rustup's shims are on PATH (same fallback run.sh uses)
rt_cargo() { PATH="/opt/homebrew/opt/rustup/bin:$PATH" cargo "$@"; }

runtime_paths_init() {
    SERIALIZE="${SERIALIZE:-../serialize}"
    SERIALIZE_C="${SERIALIZE_C:-../serialize.c}"
    SERIALIZE_GO="${SERIALIZE_GO:-../serialize.go}"
    SERIALIZE_RS="${SERIALIZE_RS:-../serialize.rs}"
    SERIALIZE_CS="${SERIALIZE_CS:-../serialize.cs}"

    RT_OVR="build/bench/runtime-override"
    ABS_ROOT="$(pwd -P)"
    ABS_SERIALIZE="$(rp_dir "$SERIALIZE" || true)"
    ABS_SERIALIZE_C="$(rp_dir "$SERIALIZE_C" || true)"
    ABS_SERIALIZE_GO="$(rp_dir "$SERIALIZE_GO" || true)"
    ABS_SERIALIZE_RS="$(rp_dir "$SERIALIZE_RS" || true)"
    ABS_SERIALIZE_CS="$(rp_dir "$SERIALIZE_CS" || true)"

    # effective build arguments — empty means "the checked-in default,
    # byte-identical to a run with no env vars set"
    RS_MANIFEST="$ABS_ROOT/bench/rust/Cargo.toml"
    RS_CARGO_ARGS=""
    GO_MODFILE_ARG=""
    CS_PROP_ARGS=""      # for dotnet run
    CS_MSBUILD_ARGS=""   # for msbuild evaluation (verify_runtime)

    local def

    # ---- rust override: two generated manifests, absolute paths ----
    def="$(rp_dir ../serialize.rs || true)"
    if [ -n "$ABS_SERIALIZE_RS" ] && [ "$ABS_SERIALIZE_RS" != "$def" ]; then
        mkdir -p "$RT_OVR/rust/example" "$RT_OVR/rust/bench"
        cat > "$RT_OVR/rust/example/Cargo.toml" <<EOF
# GENERATED by bench/tools/runtime-paths.sh (§3.5 runtime override) — lives
# under build/ (git-ignored), never repo content. The example crate rebuilt
# against SERIALIZE_RS instead of the path generated/rust/Cargo.toml bakes in.
[package]
name = "example"
version = "0.0.0"
edition = "2024"

[lib]
name = "example"
path = "$ABS_ROOT/generated/rust/src/lib.rs"

[dependencies]
serialize = { path = "$ABS_SERIALIZE_RS" }

[workspace]
EOF
        cat > "$RT_OVR/rust/bench/Cargo.toml" <<EOF
# GENERATED by bench/tools/runtime-paths.sh (§3.5 runtime override) — lives
# under build/ (git-ignored), never repo content. bench/rust rebuilt against
# SERIALIZE_RS; both serialize path deps point at the same checkout so the
# graph unifies on ONE serialize crate (cargo pkgid verifies that).
[package]
name = "benchrust"
version = "0.0.0"
edition = "2024"

[[bin]]
name = "benchrust"
path = "$ABS_ROOT/bench/rust/src/main.rs"

[dependencies]
example = { path = "$ABS_ROOT/$RT_OVR/rust/example" }
serialize = { path = "$ABS_SERIALIZE_RS" }

[workspace]
EOF
        RS_MANIFEST="$ABS_ROOT/$RT_OVR/rust/bench/Cargo.toml"
        # --target-dir target keeps the binary at bench/rust/target/release/
        # benchrust (callers cd bench/rust), where inline-verdict.sh reads it
        RS_CARGO_ARGS="--manifest-path $RS_MANIFEST --target-dir target"
    fi

    # ---- go override: an alternate modfile (go mod edit -replace on a copy).
    # Only the MAIN module's replace directives apply in Go, so overriding
    # bench/go's modfile controls the whole graph — generated/go's own
    # replace line is ignored by construction.
    def="$(rp_dir ../serialize.go || true)"
    if [ -n "$ABS_SERIALIZE_GO" ] && [ "$ABS_SERIALIZE_GO" != "$def" ] \
        && [ -f bench/go/go.mod ] && command -v go >/dev/null 2>&1; then
        mkdir -p "$RT_OVR"
        cp bench/go/go.mod "$RT_OVR/go.bench.mod"
        go mod edit \
            -replace "example=$ABS_ROOT/generated/go" \
            -replace "github.com/mas-bandwidth/serialize.go=$ABS_SERIALIZE_GO" \
            "$RT_OVR/go.bench.mod"
        GO_MODFILE_ARG="-modfile=$ABS_ROOT/$RT_OVR/go.bench.mod"
    fi

    # ---- cs override: an msbuild property the csproj's Compile includes
    # consume (<SerializeCsRoot>, defaulting to the checked-in path) ----
    def="$(rp_dir ../serialize.cs || true)"
    if [ -n "$ABS_SERIALIZE_CS" ] && [ "$ABS_SERIALIZE_CS" != "$def" ]; then
        CS_PROP_ARGS="--property:SerializeCsRoot=$ABS_SERIALIZE_CS"
        CS_MSBUILD_ARGS="-p:SerializeCsRoot=$ABS_SERIALIZE_CS"
    fi
}

# verify_runtime <cpp|c|go|rust|cs> — the §3.5 fail-closed check.
#   stdout: the toolchain-resolved absolute runtime path (verified)
#   return: 0 verified; 2 leg cannot run this invocation (reason on stderr);
#           1 MISMATCH or unprovable — the caller must refuse to emit rows.
verify_runtime() {
    local want got id items
    case "$1" in

    cpp)
        # -I$SERIALIZE and the preamble line share ONE variable; existence of
        # the header is the remaining fact to prove.
        [ -f "$SERIALIZE/serialize.h" ] || {
            echo "cpp: serialize.h not found at $SERIALIZE" >&2; return 2; }
        rp_dir "$SERIALIZE"
        ;;

    c)
        [ -f "$SERIALIZE_C/serialize.c" ] || {
            echo "c: serialize.c not found at $SERIALIZE_C" >&2; return 2; }
        rp_dir "$SERIALIZE_C"
        ;;

    go)
        [ -f bench/go/main.go ] || { echo "go: runner not landed" >&2; return 2; }
        command -v go >/dev/null 2>&1 || { echo "go: no toolchain" >&2; return 2; }
        want="$ABS_SERIALIZE_GO"
        [ -n "$want" ] || {
            echo "go: SERIALIZE_GO=$SERIALIZE_GO does not exist — cannot prove the recorded path" >&2
            return 1; }
        got="$(cd bench/go && go list $GO_MODFILE_ARG -m \
            -f '{{if .Replace}}{{.Replace.Dir}}{{else}}{{.Dir}}{{end}}' \
            github.com/mas-bandwidth/serialize.go 2>/dev/null)"
        got="$(rp_dir "$got" || true)"
        if [ -z "$got" ] || [ "$got" != "$want" ]; then
            echo "go: the build resolves serialize.go to '${got:-<unresolvable>}' but the preamble would record SERIALIZE_GO=$SERIALIZE_GO ($want)" >&2
            return 1
        fi
        echo "$got"
        ;;

    rust)
        [ -f bench/rust/Cargo.toml ] || { echo "rust: runner not landed" >&2; return 2; }
        command -v cargo >/dev/null 2>&1 || [ -x /opt/homebrew/opt/rustup/bin/cargo ] || {
            echo "rust: no cargo" >&2; return 2; }
        want="$ABS_SERIALIZE_RS"
        [ -n "$want" ] || {
            echo "rust: SERIALIZE_RS=$SERIALIZE_RS does not exist — cannot prove the recorded path" >&2
            return 1; }
        # cargo pkgid resolves the graph the build will use, and ERRORS if
        # more than one package is named serialize (the split-graph case two
        # disagreeing path deps would produce) — both failure modes refuse.
        # pkgid needs a lockfile; generating one is exactly what the build
        # itself would do (path deps only, no network), so it proves nothing
        # the build would not.
        rt_cargo generate-lockfile --manifest-path "$RS_MANIFEST" >/dev/null 2>&1 || true
        if ! id="$(rt_cargo pkgid --manifest-path "$RS_MANIFEST" serialize 2>&1)"; then
            echo "rust: cargo cannot resolve a unique serialize crate from $RS_MANIFEST:" >&2
            echo "$id" | sed 's/^/    /' >&2
            return 1
        fi
        got="$(echo "$id" | sed -E 's|^(path\+)?file://||; s|#.*$||')"
        got="$(rp_dir "$got" || true)"
        if [ -z "$got" ] || [ "$got" != "$want" ]; then
            echo "rust: the build resolves serialize to '${got:-<unresolvable>}' but the preamble would record SERIALIZE_RS=$SERIALIZE_RS ($want)" >&2
            return 1
        fi
        echo "$got"
        ;;

    cs)
        ls bench/cs/*.csproj >/dev/null 2>&1 || { echo "cs: runner not landed" >&2; return 2; }
        command -v dotnet >/dev/null 2>&1 || { echo "cs: no dotnet" >&2; return 2; }
        want="$ABS_SERIALIZE_CS"
        [ -n "$want" ] || {
            echo "cs: SERIALIZE_CS=$SERIALIZE_CS does not exist — cannot prove the recorded path" >&2
            return 1; }
        # msbuild evaluates the ACTUAL Compile item list the build will use
        # (property defaults included); the serialize items must all live
        # under the recorded root. No Serialize.cs item at all is a refusal:
        # a csproj that stopped consuming the property cannot prove itself.
        items="$(dotnet msbuild bench/cs/schemabench.csproj -getItem:Compile $CS_MSBUILD_ARGS 2>/dev/null \
            | sed -n 's/.*"Identity": *"\([^"]*\)".*/\1/p' \
            | grep -E '(^|/)(Serialize|Int128Pair)\.cs$')"
        if [ -z "$items" ]; then
            echo "cs: msbuild reports no serialize Compile items — the build's runtime inputs cannot be proven" >&2
            return 1
        fi
        got=""
        local item dir root
        while IFS= read -r item; do
            case "$item" in
                /*) dir="$(rp_dir "$(dirname "$item")" || true)" ;;
                *)  dir="$(rp_dir "bench/cs/$(dirname "$item")" || true)" ;;
            esac
            root="${dir%/src}"
            if [ -z "$dir" ] || [ "$root" != "$want" ]; then
                echo "cs: Compile item '$item' resolves to '${dir:-<unresolvable>}' but the preamble would record SERIALIZE_CS=$SERIALIZE_CS ($want)" >&2
                return 1
            fi
            got="$root"
        done <<EOF
$items
EOF
        echo "$got"
        ;;

    *)
        echo "verify_runtime: unknown language $1" >&2
        return 1
        ;;
    esac
}
