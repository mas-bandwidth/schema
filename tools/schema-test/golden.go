// goldenAdapter runs goldens: a test whose inputs are {"writer":
// "pins-wire-tables", "files": ["testdata/wire/tables/examples/a.bin"]} holds
// that the committed files are exactly what their writer writes today. The
// writer is the make target that rewrites that family of pins from its
// generator; it runs once per run in a copy of the tracked tree beside the
// checkout, and each asked file is compared byte for byte with the copy's.
//
//   - A file the writer wrote differently is a FAIL: it is stale, or it was
//     edited by hand. A file the writer no longer writes at all is a FAIL:
//     nothing generates it, so it was written by hand.
//   - A file the writer wrote under the pin roots (testdata/ and
//     bench/corpus/variants/, what the old pins job diffed) that no golden
//     row of the writer names, and that is not committed or not what is
//     committed, fails every row of that writer: a new pin is committed with
//     its row, never left for a later run to find. So does a committed pin
//     under the roots, no row of the writer's, that the writer deleted.
//   - A row whose file is not committed (not tracked, or not in the
//     checkout) is MISSING (Answers is false): a missing golden is never
//     generated by a run.
//   - With --update, the run re-pins exactly the files of the rows it names,
//     copied from the writer's output, and nothing else; while the writer
//     also wrote a stray pin it re-pins nothing.
//
// The checkout is never written except by --update.
type goldenAdapter struct {
	// write runs the writer in a copy of the tree, with each file in fresh
	// (every file a golden row of the writer names) aged to goldenSeeded in the
	// copy first; the copy reports a golden the writer left untouched
	// (untouched), so one it no longer writes fails, never passing as the
	// committed file copied in. (Aged and not deleted or overwritten: some
	// writers re-pin only the goldens that are there, and some load them
	// first.) It returns the copy, the writer's log and a cleanup; a unit test
	// hands in its own, so no unit test copies a tree or runs make.
	write func(ctx context.Context, writer string, fresh []string) (fileTree, func(), string, error)
	// checkout is the tree the goldens are committed in.
	checkout fileTree
	// tracked reports whether a file is committed (git ls-files), or the
	// error that kept the index from being read; nil holds every file of the
	// checkout committed, as a unit test's tree is.
	tracked func(path string) (bool, error)
	// reg is the registry the run loaded: a file another golden row of the
	// writer names is that row's (MISSING when it is not committed), never a
	// stray pin.
	reg *testreg.Registry
}

// fileTree is a tree of files by repository path: the checkout, or the copy
// a writer wrote into.
type fileTree interface {
	Read(path string) ([]byte, error)
	Write(path string, data []byte) error
	// Walk is the path of every file under a root, or nothing when the
	// root does not exist.
	Walk(root string) ([]string, error)
}

// dirTree is a fileTree on disk, rooted at a directory.
type dirTree string

func (d dirTree) path(p string) string { return filepath.Join(string(d), filepath.FromSlash(p)) }

func (d dirTree) Read(p string) ([]byte, error) { return os.ReadFile(d.path(p)) }

func (d dirTree) Write(p string, data []byte) error { return os.WriteFile(d.path(p), data, 0o644) }

func (d dirTree) Walk(root string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(d.path(root), func(p string, e os.DirEntry, err error) error {
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) && p == d.path(root) {
				return filepath.SkipDir
			}
			return err
		}
		if e.IsDir() {
			return nil
		}
		rel, err := filepath.Rel(string(d), p)
		if err != nil {
			return err
		}
		out = append(out, filepath.ToSlash(rel))
		return nil
	})
	return out, err
}

// pinRoots are where pins live: what the pins job diffed before the golden
// rows held them.
var pinRoots = []string{"testdata", "bench/corpus/variants"}

type goldenInputs struct {
	Writer string   `json:"writer"`
	Files  []string `json:"files"`
}

type updateKey struct{}

// withUpdate marks a run as a re-pin (schema-test run --update).
func withUpdate(ctx context.Context) context.Context {
	return context.WithValue(ctx, updateKey{}, true)
}

func updating(ctx context.Context) bool { v, _ := ctx.Value(updateKey{}).(bool); return v }

// goldenSeeded is the time each golden of a writer is aged to in the copy
// before the writer runs: a golden that still has it was not written.
var goldenSeeded = time.Unix(1, 0)

// untouched is a tree that knows which of its goldens the writer left as
// they were seeded.
type untouched interface {
	Untouched(path string) bool
}

// seededTree is the writer's copy: a dirTree whose seeded goldens report
// whether the writer wrote them.
type seededTree struct {
	dirTree
	seeded map[string]bool
}

func (s seededTree) Untouched(p string) bool {
	if !s.seeded[p] {
		return false
	}
	info, err := os.Stat(s.path(p))
	return err == nil && info.ModTime().Equal(goldenSeeded)
}

func newGoldenAdapter() goldenAdapter {
	var once sync.Once
	var files map[string]bool
	var indexErr error
	tracked := func(p string) (bool, error) {
		once.Do(func() {
			files = map[string]bool{}
			var list []string
			if list, indexErr = trackedFiles(context.Background(), "."); indexErr == nil {
				for _, f := range list {
					files[f] = true
				}
			}
		})
		return files[p], indexErr
	}
	return goldenAdapter{write: writeInCopy, checkout: dirTree("."), tracked: tracked}
}

func decodeGolden(raw json.RawMessage) (goldenInputs, error) {
	var in goldenInputs
	d := json.NewDecoder(bytes.NewReader(raw))
	d.DisallowUnknownFields()
	if err := d.Decode(&in); err != nil {
		return in, err
	}
	if !strings.HasPrefix(in.Writer, "pins-") || strings.ContainsAny(in.Writer, " \t=") || len(in.Files) == 0 {
		return in, fmt.Errorf("want a pins- writer and its files, got %q %v", in.Writer, in.Files)
	}
	for _, f := range in.Files {
		if filepath.IsAbs(f) || strings.Contains(f, "..") || f != filepath.ToSlash(filepath.Clean(f)) {
			return in, fmt.Errorf("file %q is not a clean repository path", f)
		}
	}
	return in, nil
}

func (a goldenAdapter) Answers(t testreg.Test) bool {
	if t.Scope != testreg.LangFree || t.Type != "golden" {
		return false
	}
	in, err := decodeGolden(t.Inputs)
	if err != nil {
		return false
	}
	for _, f := range in.Files {
		if _, err := a.checkout.Read(f); err != nil {
			return false // MISSING: a golden is never generated by a run
		}
		if ok, err := a.isTracked(f); err == nil && !ok {
			return false // MISSING: not committed
		}
		// an index that cannot be read is answered, so Run names its error
		// on every row instead of calling each one MISSING
	}
	return true
}

func (a goldenAdapter) Run(ctx context.Context, _ string, instances []testreg.Instance) ([]testreg.Result, error) {
	if _, err := a.isTracked(""); err != nil {
		return nil, fmt.Errorf("git ls-files, which says which goldens are committed: %w", err)
	}
	byWriter := map[string][]testreg.Instance{}
	ins := map[string]goldenInputs{}
	var writers []string
	for _, inst := range instances {
		in, err := decodeGolden(inst.Test.Inputs)
		if err != nil {
			return nil, fmt.Errorf("%s: inputs: %w", inst.Full, err)
		}
		ins[inst.Full] = in
		if _, ok := byWriter[in.Writer]; !ok {
			writers = append(writers, in.Writer)
		}
		byWriter[in.Writer] = append(byWriter[in.Writer], inst)
	}
	var out []testreg.Result
	for _, w := range writers {
		registered := a.registered(w)
		for _, inst := range byWriter[w] {
			for _, f := range ins[inst.Full].Files {
				registered[f] = true
			}
		}
		fresh := slices.Sorted(maps.Keys(registered))
		written, cleanup, log, err := a.write(ctx, w, fresh)
		if err != nil && ctx.Err() != nil {
			return out, fmt.Errorf("writer %s: %w\n%s", w, err, tail(log, 40))
		}
		if err != nil {
			// this writer's rows fail with its error; the other writers'
			// rows are still judged on their own writers
			for _, inst := range byWriter[w] {
				out = append(out, testreg.Result{Instance: inst.Full, Verdict: testreg.Fail,
					Reason: fmt.Sprintf("writer %s: %v\n%s", w, err, tail(log, 40))})
			}
			continue
		}
		res, err := a.judge(ctx, written, registered, byWriter[w], ins)
		cleanup()
		out = append(out, res...)
		if err != nil {
			return out, err
		}
	}
	return out, nil
}

// judge compares each instance's files in the writer's copy with the
// checkout's, and re-pins them under --update.
func (a goldenAdapter) judge(ctx context.Context, written fileTree, registered map[string]bool, instances []testreg.Instance, ins map[string]goldenInputs) ([]testreg.Result, error) {
	// a pin no golden row of the writer names: new, or rewritten
	owned := map[string]bool{}
	for _, inst := range instances {
		for _, f := range ins[inst.Full].Files {
			owned[f] = true
		}
	}
	var stray []string
	for _, root := range pinRoots {
		paths, err := written.Walk(root)
		if err != nil {
			return nil, fmt.Errorf("reading the writer's %s: %w", root, err)
		}
		for _, f := range paths {
			if owned[f] || registered[f] {
				continue
			}
			got, err := written.Read(f)
			if err != nil {
				return nil, err
			}
			if want, err := a.checkout.Read(f); err != nil || !a.committed(f) || !bytes.Equal(got, want) {
				stray = append(stray, f)
			}
		}
		// a committed pin the writer deleted is as stray as one it added
		committed, err := a.checkout.Walk(root)
		if err != nil {
			return nil, fmt.Errorf("reading the checkout's %s: %w", root, err)
		}
		for _, f := range committed {
			if owned[f] || registered[f] || !a.committed(f) {
				continue
			}
			if _, err := written.Read(f); err != nil {
				stray = append(stray, f+" (deleted by the writer)")
			}
		}
	}
	sort.Strings(stray)
	var out []testreg.Result
	for _, inst := range instances {
		var bad []string
		for _, f := range ins[inst.Full].Files {
			got, err := written.Read(f)
			if u, ok := written.(untouched); err != nil || ok && u.Untouched(f) {
				bad = append(bad, fmt.Sprintf("%s: its writer no longer writes it, so nothing generates it: a golden nobody generates was written by hand", f))
				continue
			}
			want, err := a.checkout.Read(f)
			if err != nil {
				return out, err
			}
			if bytes.Equal(got, want) {
				continue
			}
			if updating(ctx) && len(stray) == 0 {
				if err := a.checkout.Write(f, got); err != nil {
					return out, err
				}
				continue
			}
			bad = append(bad, fmt.Sprintf("%s is not what its writer writes (%d bytes committed, %d written): it is stale or was edited by hand; re-pin it with schema-test run --update %s, and never by hand", f, len(want), len(got), inst.Full))
		}
		if len(stray) > 0 {
			bad = append(bad, fmt.Sprintf("the writer also wrote %s, which no golden row names and which is not committed as written: a pin is committed with its golden row", strings.Join(stray, ", ")))
		}
		if len(bad) > 0 {
			out = append(out, testreg.Result{Instance: inst.Full, Verdict: testreg.Fail, Reason: strings.Join(bad, "\n")})
			continue
		}
		out = append(out, testreg.Result{Instance: inst.Full, Verdict: testreg.Pass})
	}
	return out, nil
}

// committed reports whether a file of the checkout is committed.
// isTracked is tracked, with nil tracking every file.
func (a goldenAdapter) isTracked(f string) (bool, error) {
	if a.tracked == nil {
		return true, nil
	}
	return a.tracked(f)
}

// committed is whether f is committed; Run has already failed on an index
// it could not read.
func (a goldenAdapter) committed(f string) bool {
	ok, err := a.isTracked(f)
	return err == nil && ok
}

// registered is every file a golden row of the writer names in the
// registry, selected or not.
func (a goldenAdapter) registered(writer string) map[string]bool {
	out := map[string]bool{}
	if a.reg == nil {
		return out
	}
	for _, t := range a.reg.Tests {
		if t.Adapter != "golden" {
			continue
		}
		if in, err := decodeGolden(t.Inputs); err == nil && in.Writer == writer {
			for _, f := range in.Files {
				out[f] = true
			}
		}
	}
	return out
}

// writeInCopy copies the tracked tree beside the checkout (so ../serialize
// resolves as it does for the checkout), ages the files in fresh in the copy
// (seedGoldens), and runs the writer there.
func writeInCopy(ctx context.Context, writer string, fresh []string) (fileTree, func(), string, error) {
	root, err := os.Getwd()
	if err != nil {
		return nil, nil, "", err
	}
	files, err := trackedFiles(ctx, root)
	if err != nil {
		return nil, nil, "", err
	}
	if _, err := sweepStale(filepath.Dir(root), copyHost(), processAlive); err != nil {
		return nil, nil, "", err
	}
	work, err := os.MkdirTemp(filepath.Dir(root), copyPrefix("golden"))
	if err != nil {
		return nil, nil, "", err
	}
	cleanup := func() { _ = os.RemoveAll(work) }
	for _, f := range files {
		if err := copyFile(filepath.Join(root, filepath.FromSlash(f)), filepath.Join(work, filepath.FromSlash(f))); err != nil {
			cleanup()
			return nil, nil, "", err
		}
	}
	seeded, err := seedGoldens(work, fresh)
	if err != nil {
		cleanup()
		return nil, nil, "", err
	}
	cmd := exec.CommandContext(ctx, "make", "--no-print-directory", fmt.Sprintf("-j%d", runtime.NumCPU()), writer)
	bound(cmd)
	cmd.Dir = work
	var out bytes.Buffer
	cmd.Stdout = &out
	cmd.Stderr = &out
	if err := writerFailed(writer, out.String(), cmd.Run()); err != nil {
		cleanup()
		return nil, nil, out.String(), err
	}
	return seededTree{dirTree(work), seeded}, cleanup, out.String(), nil
}

// writerFailed is why a writer's run wrote nothing to judge: it exited
// non-zero (runErr), or its log reports a skip. nil when it wrote.
func writerFailed(writer, log string, runErr error) error {
	if runErr != nil {
		return fmt.Errorf("make %s: %w", writer, runErr)
	}
	if err := testreg.RefuseSkips(strings.Split(log, "\n")); err != nil {
		return fmt.Errorf("make %s: %w", writer, err)
	}
	return nil
}

// seedGoldens ages each file of fresh that is in the copy at work to
// goldenSeeded, and returns the ones it aged: a golden the writer then
// leaves untouched was not written. One not in the copy is not committed:
// its row is MISSING, and the writer may write it.
func seedGoldens(work string, fresh []string) (map[string]bool, error) {
	seeded := map[string]bool{}
	for _, f := range fresh {
		p := filepath.Join(work, filepath.FromSlash(f))
		if _, err := os.Stat(p); errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err := os.Chtimes(p, goldenSeeded, goldenSeeded); err != nil {
			return nil, err
		}
		seeded[f] = true
	}
	return seeded, nil
}

// goldenOnly refuses an --update run that selects anything but goldens: a
// re-pin names the goldens it rewrites, and nothing else runs under it.
func goldenOnly(instances []testreg.Instance) error {
	var other []string
	for _, inst := range instances {
		if inst.Test.Type != "golden" {
			other = append(other, inst.Full)
		}
	}
	if len(other) > 0 {
		return usageError{fmt.Sprintf("--update re-pins goldens, and the run selects %d tests that are not: %s", len(other), strings.Join(other[:min(len(other), 3)], ", "))}
	}
	if len(instances) == 0 || !slices.ContainsFunc(instances, func(i testreg.Instance) bool { return i.Test.Type == "golden" }) {
		return usageError{"--update names the goldens it re-pins"}
	}
	return nil
}

// Serial: a writer takes the checkout (testreg.Serial).
func (goldenAdapter) Serial() bool { return true }
