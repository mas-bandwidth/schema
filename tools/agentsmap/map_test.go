// TestStaleMapFailsUntilRegenerate is the red-first blade: edit a mapped
// directory, the guard goes red, regenerate, the guard goes green.
func TestStaleMapFailsUntilRegenerate(t *testing.T) {
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "Makefile"), []byte("# test tree\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.Mkdir(filepath.Join(dir, "alpha"), 0o755); err != nil {
		t.Fatal(err)
	}
	cat := []Entry{
		page("alpha", "the mapped tree", "go test", "go test"),
	}
	pages, issues := Render(dir, cat)
	if len(issues) != 0 {
		t.Fatalf("fresh tree: %s", strings.Join(issues, "; "))
	}
	if err := Write(dir, pages); err != nil {
		t.Fatal(err)
	}
	if issues := Check(dir, cat); len(issues) != 0 {
		t.Fatalf("committed map should be green: %s", strings.Join(issues, "; "))
	}

	if err := os.Mkdir(filepath.Join(dir, "alpha", "beta"), 0o755); err != nil {
		t.Fatal(err)
	}
	red := Check(dir, cat)
	if !hasIssue(red, "uncatalogued directory alpha/beta") {
		t.Fatalf("new child without a catalog row should be uncatalogued, got:\n%s", strings.Join(red, "\n"))
	}
	if !hasIssue(red, "stale; run: make map") {
		t.Fatalf("new child without regenerating should stale the page, got:\n%s", strings.Join(red, "\n"))
	}

	cat = append(cat, e("alpha/beta", "a child", "go test", "go test"))
	stale := Check(dir, cat)
	if hasIssue(stale, "uncatalogued") {
		t.Fatalf("catalogued child should not be uncatalogued, got:\n%s", strings.Join(stale, "\n"))
	}
	if !hasIssue(stale, "stale; run: make map") {
		t.Fatalf("catalogued child without regenerating should still be stale, got:\n%s", strings.Join(stale, "\n"))
	}

	pages, issues = Render(dir, cat)
	if len(issues) != 0 {
		t.Fatalf("after catalog row: %s", strings.Join(issues, "; "))
	}
	if err := Write(dir, pages); err != nil {
		t.Fatal(err)
	}
	if issues := Check(dir, cat); len(issues) != 0 {
		t.Fatalf("after make map the guard should be green, got:\n%s", strings.Join(issues, "\n"))
	}

	if err := os.WriteFile(filepath.Join(dir, "alpha", "beta", "AGENTS.md"), []byte("hand-written\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	hand := Check(dir, cat)
	if !hasIssue(hand, "not generated by tools/agentsmap") {
		t.Fatalf("a hand-written AGENTS.md should fail, got:\n%s", strings.Join(hand, "\n"))
	}
}

func TestNoPerHarnessFileStandsBesideAgents(t *testing.T) {
	root := testRoot(t)
	files := 0
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case ".git", "testdata", "node_modules":
				return filepath.SkipDir
			}
			return nil
		}
		files++
		if d.Name() == "CLAUDE.md" {
			rel, _ := filepath.Rel(root, path)
			t.Errorf("%s stands beside AGENTS.md; Glenn, 2026-09-18: AGENTS.md alone — no CLAUDE.md, no pointer file, no symlink", filepath.ToSlash(rel))
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if files == 0 {
		t.Fatal("the walk read no file: a search that looked at nothing found no CLAUDE.md")
	}
}

// TestIgnoredScratchDirsAreNeverMapped pins that an ignored directory can
// never be catalogued again. tmp/ is the gitignored scratch directory
// (.gitignore:4), so whether it exists depends on the machine: a catalog row
// for it turns the guard red on any machine without a local tmp/, and deleting
// the row alone turns the guard red on any machine that has one. The ignored
// name must be skipped by the tree walk and named by no row.
func TestIgnoredScratchDirsAreNeverMapped(t *testing.T) {
	t.Parallel()
	if !skipDir("tmp") {
		t.Errorf("skipDir(\"tmp\") = false; tmp/ is the gitignored scratch directory (.gitignore:4) and must be skipped on every machine")
	}
	for _, row := range catalog {
		last := filepath.Base(filepath.FromSlash(row.Path))
		if skipDir(last) {
			t.Errorf("catalog row %q names ignored directory %q; an ignored directory can never be catalogued", row.Path, last)
		}
	}
}

func hasIssue(issues []string, sub string) bool {
	for _, s := range issues {
		if strings.Contains(s, sub) {
			return true
		}
	}
	return false
}

func testRoot(t *testing.T) string {
	t.Helper()
	root, err := repoRoot()
	if err != nil {
		t.Fatal(err)
	}
	return root
}

// TestSkippedDirectoriesHoldNoTrackedFile holds the map's skip rule to git. The
// map leaves a directory out by NAME (skipNames, and every dot-directory but
// mappedDotDirs), on the claim that such a directory is build output or a
// machine's own. A directory the repository tracks is neither: skipped, it is a
// source tree no page lists and no row guards. .claude-plugin was one.
func TestSkippedDirectoriesHoldNoTrackedFile(t *testing.T) {
	root := testRoot(t)
	if _, err := os.Stat(filepath.Join(root, ".git")); err != nil {
		t.Skipf("%s is not a git checkout (%v): which directories are tracked is git's to say", root, err)
	}
	issues, err := trackedButSkipped(root, catalog, func(dir string) ([]string, error) {
		cmd := exec.Command("git", "-C", root, "ls-files", "--", dir)
		out, err := cmd.Output()
		if err != nil {
			return nil, err
		}
		return strings.Fields(string(out)), nil
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, s := range issues {
		t.Error(s)
	}
}

// TestTrackedButSkippedNegativeControl plants a tree whose skipped directories
// are one tracked and two not, and requires the tracked one alone to be named.
func TestTrackedButSkippedNegativeControl(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	for _, sub := range []string{"alpha/bin", "alpha/src", ".plugin", "build", ".editor"} {
		if err := os.MkdirAll(filepath.Join(dir, sub), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	cat := []Entry{page("alpha", "the mapped tree", "go test", "go test"), e("alpha/src", "source", "go test", "go test")}
	tracked := map[string][]string{"alpha/bin": {"alpha/bin/tool.dart"}, ".plugin": {".plugin/manifest.json"}}
	lookedAt := 0
	issues, err := trackedButSkipped(dir, cat, func(d string) ([]string, error) {
		lookedAt++
		return tracked[d], nil
	})
	if err != nil {
		t.Fatal(err)
	}
	if lookedAt != 4 {
		t.Errorf("asked about %d skipped directories, want 4 (.editor, .plugin, build, alpha/bin)", lookedAt)
	}
	if len(issues) != 2 || !strings.Contains(issues[0], ".plugin holds 1 tracked file") || !strings.Contains(issues[1], "alpha/bin holds 1 tracked file") {
		t.Errorf("issues = %q, want .plugin and alpha/bin, each named", issues)
	}
}

// trackedButSkipped names every directory the map skips by name that holds a
// file the repository tracks, as trackedFiles reports them.
func trackedButSkipped(root string, cat []Entry, trackedFiles func(dir string) ([]string, error)) ([]string, error) {
	skipped, err := SkippedDirs(root, cat)
	if err != nil {
		return nil, err
	}
	var issues []string
	for _, dir := range skipped {
		files, err := trackedFiles(dir)
		if err != nil {
			return nil, err
		}
		if len(files) > 0 {
			issues = append(issues, dir+" holds "+strconv.Itoa(len(files))+" tracked file(s) and the map skips it by name: a tracked directory is source, so catalog it (tools/agentsmap/catalog.go; a dot-directory also joins mappedDotDirs) or stop tracking it")
		}
	}
	return issues, nil
}
